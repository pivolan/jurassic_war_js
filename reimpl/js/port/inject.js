// Отдача приказов юнитам мимо интерфейса (наше). Одна точка на всех: ИИ (js/ai) и сетевая
// игра (js/net) кладут приказы сюда, а отсюда они уходят в настоящую очередь движка.
//
// Куда именно. Внутри шага 0x13f4c сначала сбрасывает указатель очереди (`[0x33c7c] = 0x33c88`),
// потом зовёт 0x1419e (разбор «ожидающего клика» игрока), и только потом применяет накопленные
// записи. Значит запись, положенная ДО тика, будет стёрта сбросом — на этом уже сгорел
// эксперимент с внешним управлением. Точка внедрения одна: обёртка над 0x1419e, сначала
// оригинал, потом наши записи. Так и игрок, и ИИ, и сетевой соперник пишут в одну очередь одним
// форматом (10 байт: маркер игрока, код, юнит, цель, X, Y).
import { F } from '../fn.js';
import { U, UNITS } from '../mem.js';

export const КОД = { ИДТИ: 0x0f, АТАКА: 0x1f, СТОП: 0x2f, ОХРАНА: 0x3f, ДОБЫЧА: 0x4c };   // 0x2f — он же «сон», кнопка zzz

const ждут = new WeakMap();               // eng → массив записей до ближайшего 0x1419e
/** Наши собственные коды приказов: код → (eng, запись). Они не уходят в очередь движка, а
 *  выполняются здесь же — в том же месте шага, что и штатные, поэтому в сети всё сходится. */
export const НАШИ = new Map();
/** Что позвать в конце каждого шага (планы стройки и прочая наша механика). */
export const наШаг = [];

/** Положить приказ юниту. Он уйдёт в очередь движка внутри ближайшего шага. */
export function приказ(eng, юнит, код, цель = 0, x = 0, y = 0) {
  установить();
  let q = ждут.get(eng);
  if (!q) ждут.set(eng, q = []);
  // JW_TRACE_ORDERS=1 — запомнить, ОТКУДА положен приказ. Нужно для разбора жалоб вида «юниты
  // топчутся и не бьют»: приказ уходит через общую очередь, и в месте отправки стека уже нет.
  const з = { юнит, код, цель, x, y };
  if (globalThis.process?.env?.JW_TRACE_ORDERS) з.откуда = new Error().stack;
  q.push(з); счёт.положено++;
}

/** Приказы, ещё не ушедшие в очередь движка (копия): нужны, чтобы повторить их на копии движка
 *  при просчёте вперёд (js/ai/ластхит.js). */
export const ожидающие = (eng) => (ждут.get(eng) || []).map(з => ({ ...з }));
/** Сколько приказов ждёт отправки (для отладки). */
export const вОчереди = (eng) => (ждут.get(eng) || []).length;
export const счёт = { положено: 0, отдано: 0 };
/** Пока идёт внедрение, `внедряем` = true: так обёртка 0x14895 в игре отличает приказы из сети
 *  (их надо пустить в очередь) от приказов своего игрока (их надо отправить в сеть, а не в очередь). */
export const состояние = { внедряем: false };

// Обёртка ставится при импорте, но если этот модуль оказался загружен РАНЬШЕ modules.js (порядок
// импортов в вызывающем файле), оригинал ещё не определён, а потом modules.js затрёт обёртку —
// и приказы молча перестанут доходить до очереди (так сгорел один тестовый скрипт). Поэтому
// `приказ()` перед каждой записью проверяет, что обёртка на месте, и ставит её заново.
let orig1419e;
/**
 * Поставить обёртку на 0x1419e. Зовётся при загрузке модуля, из `приказ()` и из включения любой
 * нашей механики. Отдельная точка входа нужна из-за порядка вычисления модулей: если файл
 * статически импортирует и modules.js, и что-нибудь, тянущее inject.js, то из-за верхнеуровневого
 * await внутри modules.js inject.js успевает выполниться РАНЬШЕ orders_ai.js — и тот затирает
 * обёртку. Приказы это переживали (там есть проверка), а вот хуки `наШаг` молча не звались.
 */
export function установить() {
  // Уже стоим — сами или под чужой обёрткой с пометкой «наш» (web/game.js оборачивает нас и
  // помечает). Иначе, обернув чужую обёртку, которая зовёт нас, получим бесконечную рекурсию.
  if (F[0x1419e] === обёртка || (F[0x1419e] && F[0x1419e].наш)) return;
  orig1419e = F[0x1419e];
  счёт.былОригинал = typeof orig1419e;
  F[0x1419e] = обёртка;
  F[0x1419e].наш = true;
}
/** Обёртка над раздачей приказов (0x1419e): сначала оригинал, потом наши записи и шаги механик.
 *  Точка одна на всех — только так приказы игрока, ИИ и сети попадают в очередь одинаково. */
const обёртка = (eng, r) => {
  const res = orig1419e(eng, r);
  const q = ждут.get(eng);
  if (q && q.length) {
    состояние.внедряем = true;
    try { for (const з of q) {
      const свой = НАШИ.get(з.код);
      if (свой) { свой(eng, з); счёт.отдано++; continue; }
      // Пометка цели ровно как в 0x145cd: без неё атакуемый не «замечает» удар так же, как при
      // приказе из интерфейса, и состояния расходятся.
      if (з.код === КОД.АТАКА && з.цель) eng.m.w8(UNITS + з.цель + U.FX43, eng.m.u8(UNITS + з.цель + U.FX43) | 2);
      F[0x14895](eng, { eax: з.код, esi: з.юнит, edi: з.цель, edx: з.x & 0xffff, ebx: з.y & 0xffff, откуда: з.откуда }); счёт.отдано++;
    } } finally { состояние.внедряем = false; }
    q.length = 0;
  }
  for (const f of наШаг) f(eng);
  return res;
};
установить();
