// Очередь приказов юнита (наше; в оригинале её нет).
//
// Зачем. В оригинале один щелчок — один приказ, и всё, что сложнее «иди сюда», приходится вести
// вручную. С зажатым Shift можно наметить сразу цепочку: обойти три точки, добить двух врагов
// по очереди, подобрать мясо и уйти домой. Цели при этом могут двигаться — в шаге «атака»
// хранится номер юнита, а не клетка, поэтому очередь гонится за целью, куда бы та ни ушла.
//
// Как. Каждый шаг очереди — наш собственный код приказа, он идёт через общую очередь 0x14895:
// значит доезжает по сети и попадает в запись партии. Здесь шаги только копятся; выполняет их
// шаг() — он выдаёт движку обычный приказ (0x0f / 0x1f / 0x4c) и ждёт, пока юнит освободится.
//
// Когда снимается: юнит погиб; очередь кончилась; игрок отдал любой приказ без Shift (это делает
// обвязка — см. setQueueHandler в js/port/input.js) — новый приказ всегда важнее старого плана.
import { G, U, UNITS } from '../mem.js';
import { F } from '../fn.js';
import { приказ, КОД, НАШИ, наШаг, установить } from './inject.js';

// 0xf8 занят камикадзе (js/port/kamikaze.js) — новый код берём следующим свободным.
export const ШАГ_ИДТИ = 0xf4, ШАГ_АТАКА = 0xf5, ШАГ_ВЗЯТЬ = 0xf6, ОЧИСТИТЬ = 0xf7, ШАГ_ОТНЕСТИ = 0xf9;
const КОД_ШАГА = { [ШАГ_ИДТИ]: КОД.ИДТИ, [ШАГ_АТАКА]: КОД.АТАКА, [ШАГ_ВЗЯТЬ]: КОД.ДОБЫЧА };
const МЯСО = 0x1e, СКЛАД = 0x1a + 4;        // предмет «мясо» (id 30) и тип здания «склад» (26 + вид 4)
export const ПРЕДЕЛ = 16;                // больше шагов в очереди не держим
const ШАГ_ПРОВЕРКИ = 4;                  // раз в столько шагов смотрим, не пора ли следующий
const РАЗГОН = 12;                       // столько шагов после выдачи не считаем юнита «стоящим»
const СРОК = 1800;                       // ~100 с на один шаг: не уложился — бросаем и идём дальше
const ПОПЫТОК = 3;                       // столько раз повторяем приказ, если юнит встал не дойдя
const ЖДАТЬ_МЯСО = 180;                  // ~10 с ждём, пока подобранное окажется в руках, потом бросаем шаг
const ЗАПАС_НОСИЛЬЩИКА = 50;             // столько склад носильщику оставляет (0x19229: FOOD > 50 → сдать FOOD − 50)

/** Очереди приказов этого движка: юнит → шаги. */
const карта = (eng) => (eng.очередьПриказов || (eng.очередьПриказов = new Map()));
/** Очередь юнита: массив шагов {вид, цель, x, y} (x,y — тайлы) или пустой массив. */
export const очередь = (eng, i) => eng.очередьПриказов?.get(i)?.шаги || [];
/** Все очереди (для отрисовки цепочек). */
export const все = (eng) => eng.очередьПриказов || new Map();
/** Забыть очередь юнита (он получил обычный приказ или погиб). */
export function снять(eng, юнит) { eng.очередьПриказов?.delete(юнит); }
/** Очереди в плоский массив — для снимка и записи. */
export function dump(eng) {
  return [...(eng.очередьПриказов || new Map())].map(([i, с]) => [i, с.шаги.flatMap(ш => [ш.вид, ш.цель, ш.x, ш.y])]);
}
/** Очереди из снимка. */
export function restore(eng, список) {
  const c = карта(eng); c.clear();
  for (const [i, плоско] of список || []) {
    const шаги = [];
    for (let k = 0; k + 3 < плоско.length; k += 4) шаги.push({ вид: плоско[k], цель: плоско[k + 1], x: плоско[k + 2], y: плоско[k + 3] });
    if (шаги.length) c.set(i, новая(шаги));
  }
}
/** Пустая запись очереди с этими шагами. */
const новая = (шаги) => ({ шаги, выдан: false, выданНа: 0, попыток: 0 });

/** Слот с мясом в руках (6..8) или −1. Носить умеет любой юнит, не только простолюдин. */
export function слотМяса(m, i) {
  for (let k = 6; k <= 8; k++) if (m.u8(UNITS + i + U.INV + k) === МЯСО) return k;
  return -1;
}
/** Ближайший к юниту свой склад (мясо принимает только он) или 0. */
export function ближайшийСклад(m, i) {
  const вл = m.u8(UNITS + i + U.OWNER), c = { x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 };
  let лучший = 0, d0 = 1e9;
  for (let з = m.u32(G.unitHead); з; з = m.u32(UNITS + з + U.NEXT)) {
    if (m.u8(UNITS + з + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + з + U.OWNER) !== вл || m.u8(UNITS + з + U.TYPE) !== СКЛАД) continue;
    const d = Math.abs((m.u16(UNITS + з + U.X) >> 5) - c.x) + Math.abs((m.u16(UNITS + з + U.Y) >> 5) - c.y);
    if (d < d0 || (d === d0 && з < лучший)) { d0 = d; лучший = з; }
  }
  return лучший;
}
/** Свободная клетка рядом со складом, ближайшая к юниту: сам склад непроходим. */
const ВОКРУГ_СКЛАДА = [[-1, 0], [2, 0], [0, -1], [0, 2], [-1, -1], [2, -1], [-1, 2], [2, 2], [1, -1], [1, 2], [-1, 1], [2, 1]];
export function подходКСкладу(m, склад, откуда) {
  const б = { x: m.u16(UNITS + склад + U.X) >> 5, y: m.u16(UNITS + склад + U.Y) >> 5 };
  let лучшая = б, d0 = 1e9;
  for (const [dx, dy] of ВОКРУГ_СКЛАДА) {
    const п = { x: б.x + dx, y: б.y + dy };
    const d = Math.abs(п.x - откуда.x) + Math.abs(п.y - откуда.y);
    if (d < d0) { d0 = d; лучшая = п; }
  }
  return лучшая;
}

/** Юнит жив и не труп. */
const жив = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.STATE) !== 0x60;
/** Клетка юнита. */
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });

/** Приказ игрока: добавить шаг в очередь. Через 0x14895 — чтобы он уехал в сеть и в запись.
 *  x,y — мировые координаты (как у обычного приказа), внутри переводим в тайлы. */
export const приказШаг = (eng, юнит, вид, цель, x, y) =>
  F[0x14895](eng, { eax: вид, esi: юнит, edi: цель, edx: x & ~0x1f, ebx: y & ~0x1f });
/** Приказ игрока: очистить очередь юнита. */
export const приказОчистить = (eng, юнит) =>
  F[0x14895](eng, { eax: ОЧИСТИТЬ, esi: юнит, edi: 0, edx: 0, ebx: 0 });

НАШИ.set(ОЧИСТИТЬ, (eng, з) => { eng.очередьПриказов?.delete(з.юнит); });
for (const вид of [ШАГ_ИДТИ, ШАГ_АТАКА, ШАГ_ВЗЯТЬ, ШАГ_ОТНЕСТИ]) НАШИ.set(вид, (eng, з) => {
  const m = eng.m, юнит = з.юнит;
  if (!жив(m, юнит) || m.u8(UNITS + юнит + U.TYPE) >= 0x1a) return;
  const c = карта(eng);
  let с = c.get(юнит);
  if (!с) c.set(юнит, с = новая([]));
  if (с.шаги.length >= ПРЕДЕЛ) return;
  с.шаги.push({ вид, цель: з.цель, x: з.x >> 5, y: з.y >> 5 });
});

/** Шаг очередей: выдать текущий приказ, снять выполненный. Зовётся из inject на каждом шаге. */
export function шаг(eng) {
  const c = eng.очередьПриказов; if (!c || !c.size) return;
  const m = eng.m; const сейчас = m.u32(G.step);
  if ((сейчас % ШАГ_ПРОВЕРКИ) !== 0) return;
  for (const [i, с] of [...c]) {
    if (!жив(m, i)) { c.delete(i); continue; }
    // Пропускаем шаги, которые уже нечего выполнять: цель погибла, пока до неё шли.
    while (с.шаги.length && с.шаги[0].вид === ШАГ_АТАКА && !жив(m, с.шаги[0].цель)) { с.шаги.shift(); с.выдан = false; с.попыток = 0; }
    if (!с.шаги.length) { c.delete(i); continue; }
    const ш = с.шаги[0];
    if (!с.выдан) {
      выдать(eng, i, ш);
      // «Отнести» с пустыми руками приказа не выдало: предмет движок кладёт в руки чуть позже,
      // чем засчитывает приход на клетку. Ждём его, не тратя попытку, но не вечно — если мясо
      // так и не досталось (успел другой, кусок исчез), шаг снимаем, иначе очередь висит навсегда.
      if (ш.вид === ШАГ_ОТНЕСТИ && !ш.несли) {
        ш.ждём ??= сейчас;
        if (сейчас - ш.ждём > ЖДАТЬ_МЯСО) дальше(c, i, с);
        continue;
      }
      с.выдан = true; с.выданНа = сейчас; с.попыток++;
      continue;
    }
    if (сейчас - с.выданНа > СРОК) { дальше(c, i, с); continue; }        // не уложился — следующий
    if (сейчас - с.выданНа < РАЗГОН) continue;                           // приказ ещё не подхватили
    const ст = m.u8(UNITS + i + U.STATE);
    if (m.u8(UNITS + i + U.ORDER) !== 0xff) continue;                    // приказ ещё в поле
    if ((ст & 0xf0) !== 0x30) continue;                                  // идёт или дерётся
    // Юнит освободился. Дошёл — берём следующий шаг; встал не дойдя — пробуем ещё раз.
    if (дошёл(m, i, ш) || с.попыток >= ПОПЫТОК) дальше(c, i, с);
    else { с.выдан = false; }
  }
}

/** Шаг выполнен: снять его и перейти к следующему. */
function дальше(c, i, с) {
  с.шаги.shift(); с.выдан = false; с.попыток = 0;
  if (!с.шаги.length) c.delete(i);
}

/** Отдать юниту очередной шаг очереди обычным приказом. */
function выдать(eng, i, ш) {
  const m = eng.m;
  // «Отнести на склад»: цель ищем в момент выдачи, а не когда шаг ставили — пока юнит собирал
  // мясо, ближайший склад мог смениться или погибнуть. Приказ тот же, что у кнопки B
  // (0x51 + слот руки): движок сам доводит юнита до рамки склада и засчитывает еду.
  if (ш.вид === ШАГ_ОТНЕСТИ) {
    // Руки могут быть ещё пусты: приказ «подобрать» считается выполненным, когда юнит дошёл до
    // клетки, а предмет движок кладёт ему в руки чуть позже. Поэтому шаг не снимаем, а просто
    // ничего не выдаём — на следующей проверке попробуем снова; совсем безнадёжный случай
    // отвалится по СРОК. Раньше здесь стоял сброс шага, и отряд оставался стоять с мясом в руках.
    const слот = слотМяса(m, i); if (слот < 0) return;
    const склад = ближайшийСклад(m, i); if (!склад) return;
    const п = подходКСкладу(m, склад, кл(m, i));
    F[0x14895](eng, { eax: (0x51 + слот) & 0xff, esi: i, edi: склад, edx: п.x << 5, ebx: п.y << 5 });
    ш.несли = 1;                                                       // приказ ушёл — теперь пустые руки значат «сдал»
    return;
  }
  if (ш.вид === ШАГ_АТАКА) {
    const п = кл(m, ш.цель);
    приказ(eng, i, КОД.АТАКА, ш.цель, п.x << 5, п.y << 5);
    return;
  }
  приказ(eng, i, КОД_ШАГА[ш.вид], 0, ш.x << 5, ш.y << 5);
}

/** Шаг считается выполненным: юнит на месте, цель мертва или предмет подобран. */
function дошёл(m, i, ш) {
  if (ш.вид === ШАГ_АТАКА) return !жив(m, ш.цель);
  // Ходка одна. Склад забирает всё сверх пятидесяти, и эти полсотни носильщику оставляют —
  // так в оригинале, и так хочет владелец: «не надо всё мясо отдавать, 50 должно оставаться».
  // Поэтому шаг закрыт, как только сдавать больше нечего: руки пусты (несли ≤ 50 и отдали всё)
  // или в руках остался неприкосновенный запас. Пустые руки ДО выдачи приказа значат «ещё не
  // подобрал», а не «уже отнёс», — отсюда проверка `несли`.
  if (ш.вид === ШАГ_ОТНЕСТИ) return !!ш.несли && (слотМяса(m, i) < 0 || m.u16(UNITS + i + U.FOOD) <= ЗАПАС_НОСИЛЬЩИКА);
  const я = кл(m, i);
  return Math.abs(я.x - ш.x) <= 1 && Math.abs(я.y - ш.y) <= 1;
}

наШаг.push(шаг);
установить();
