// Украшения-артефакты: пассивные прибавки (наше, по умолчанию выключено в оригинале).
//
// Что в оригинале. Подобранная вещь по флагам ложится в свою тройку слотов: оружие 0..2, щиты
// 3..5, еда 6..8, украшения 9..11. У украшений в таблице предметов (0x30954, поля HP/MAG/MANA/
// ATK/DEF/SPD) числа есть, но их не читает никто: бой смотрит только слоты оружия и щита, а
// процедуру начисления бонусов (0x1c5d6) зовут лишь для еды. То есть ряд украшений нарисован,
// подбор в него работает, проверка победы пятой миссии их ищет — а прибавки до юнита не доходят.
//
// Что делает этот модуль. Пока переключатель выключен, он не трогает ничего вообще. Когда
// включён — держит статы юнита равными «базовым плюс то, что надето»: раз в несколько шагов
// сверяет, что лежит в слотах 9..11, и доводит поля юнита до нужных значений. Никакой активации у
// украшений нет и не появляется: напиток не пьётся, кристалл не применяется, они просто носятся.
//
// Почему так, а не «начислить при подборе». Предмет можно отдать, потерять при смерти, подобрать
// заново — событий много, и часть из них внутри чужих процедур. Сверка состояния переживает все
// эти пути и, главное, одинаково считается на всех машинах: шаг сверки идёт внутри шага симуляции,
// а что надето — это память движка. Начисленное хранится отдельно (снимок везёт его вместе с
// маршрутами и планами), чтобы снятие украшения возвращало ровно столько же, сколько дало.
import { G, U, UNITS } from '../mem.js';
import { наШаг, установить } from './inject.js';

const ШАГ_СВЕРКИ = 4;                    // раз в столько шагов; смена экипировки не бывает чаще
const ПОЛЯ = [U.HPMAX, U.MAG, U.MANA, U.ATK, U.DEF, U.SPD];   // порядок как в таблице предметов
const СЛОТЫ = [9, 10, 11];
/** Кто носит вещи: люди и прирученные динозавры (типы 1-13). */
const ЖИВЫЕ_ТИПЫ = (t) => t >= 1 && t <= 13;     // люди и ручные динозавры: только они носят вещи

export const настройка = { вкл: false };
const начислено = new WeakMap();         // eng → Map(юнит → [hp, mag, mana, atk, def, spd])
/** Кому и сколько уже начислено от украшений: юнит → шесть прибавок. */
const карта = (eng) => { let c = начислено.get(eng); if (!c) начислено.set(eng, c = new Map()); return c; };

/** Включить или выключить прибавки. Выключение сразу снимает уже начисленное. */
export function задать(eng, вкл) {
  установить();                            // без обёртки 0x1419e хук шага не позовётся (см. inject.js)
  настройка.вкл = !!вкл;
  if (eng && !настройка.вкл) снятьВсё(eng);
}
/** Включено ли правило прибавок от артефактов. */
export const включено = () => настройка.вкл;
/** Начисленные прибавки в снимок и в запись партии. */
export function dump(eng) { return [...карта(eng)].map(([ю, в]) => [ю, ...в]); }
/** Начисленные прибавки из снимка. */
export function restore(eng, с) {
  const c = карта(eng); c.clear();
  for (const [ю, ...в] of с || []) c.set(ю, в);
}

/** Сумма прибавок от того, что надето (слоты 9..11). */
function надето(m, i) {
  const сумма = [0, 0, 0, 0, 0, 0];
  for (const s of СЛОТЫ) {
    const id = m.u8(UNITS + i + U.INV + s); if (!id) continue;
    const строка = m.u32(0x30a9e + id * 4);
    for (let k = 0; k < 6; k++) сумма[k] += m.u8(строка + 0x30954 + k);
  }
  return сумма;
}
/** Прибавить дельту к полю юнита с насыщением в границах байта. */
function довести(m, i, поле, d) {
  if (!d) return;
  const v = m.u8(UNITS + i + поле) + d;
  m.w8(UNITS + i + поле, v < 0 ? 0 : v > 0xff ? 0xff : v);
}
/** Довести характеристики юнита до новой суммы прибавок (разницей, а не пересчётом). */
function применить(m, i, было, стало) {
  for (let k = 0; k < 6; k++) довести(m, i, ПОЛЯ[k], стало[k] - было[k]);
  // Текущая мана не должна превышать предел, а при росте предела она не поднимается сама.
  const mx = m.u8(UNITS + i + U.MAG); if (m.u8(UNITS + i + U.MANA) > mx) m.w8(UNITS + i + U.MANA, mx);
}
/** Снять все прибавки: правило выключили или партия кончилась. */
function снятьВсё(eng) {
  const m = eng.m, c = карта(eng);
  for (const [i, было] of c) if (i && !(m.u8(UNITS + i + U.FLAGS5B) & 1)) применить(m, i, было, [0, 0, 0, 0, 0, 0]);
  c.clear();
}

/** Шаг сверки: держим статы равными «базовые + надетое». Зовётся из inject на каждом шаге. */
export function шаг(eng) {
  const m = eng.m;
  if (!настройка.вкл) return;
  if ((m.u32(G.step) % ШАГ_СВЕРКИ) !== 0) return;
  const c = карта(eng);
  const живы = new Set();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (!ЖИВЫЕ_ТИПЫ(m.u8(UNITS + i + U.TYPE))) continue;
    живы.add(i);
    const стало = надето(m, i);
    const было = c.get(i) || [0, 0, 0, 0, 0, 0];
    let разница = false; for (let k = 0; k < 6; k++) if (было[k] !== стало[k]) { разница = true; break; }
    if (!разница) continue;
    применить(m, i, было, стало);
    if (стало.some(v => v)) c.set(i, стало); else c.delete(i);
  }
  // Юнит погиб или перестал быть носителем — запись больше не нужна (его статы уже не наши).
  for (const i of [...c.keys()]) if (!живы.has(i)) c.delete(i);
}

наШаг.push(шаг);
