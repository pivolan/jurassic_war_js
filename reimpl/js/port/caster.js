// Маг после вспомогательного заклинания возвращается к бою.
//
// Как в оригинале. Состояние «заклинание отработало» разводится таблицей 0x182c8 на два
// обработчика: боевые заклинания (состояния 0xc6..0xc8 — Framing-Ball и прочие) идут в
// 0x19b8c, который берёт цель из [+0x33] и заново выдаёт приказ атаки 0x19f63; все остальные,
// включая лечение, регенерацию, полное лечение и воскрешение (0xc0..0xc4), идут в 0x19b78,
// а он просто ставит приказ 0x3f — «свободен». Приказ 0x3f переводит юнита в состояние 0x38,
// где раз в несколько тиков вызывается 0x1a526 — поиск врага по спирали радиусом
// (скорость >> 5) + 1, то есть у медленной целительницы всего два кольца клеток. Врага дальше
// двух клеток она не увидит и будет стоять, хотя до заклинания дралась.
//
// Что делаем. Перед тем как приказ заклинания затрёт [+0x33] целью заклинания, запоминаем,
// кого маг бил, и после 0x19b78 возвращаем ему этот приказ атаки — ровно так же, как оригинал
// уже делает для боевых заклинаний в 0x19b8c. Это единственное отличие от оригинала в этом
// файле; выключается через eng.resumeAttack = false.
//
// Цель проверяем при восстановлении, а не при запоминании: записи юнитов переиспользуются
// после смерти, поэтому запомненный номер годится, только если по нему до сих пор живой чужой
// юнит (та же грабля, что была с кэшем маршрутов в path.js).
import { F } from '../fn.js';
import { U, UNITS } from '../mem.js';

const SPELL_ORDER_LO = 0xa0, SPELL_ORDER_HI = 0xd7;    // коды приказов-заклинаний
// Поводок. Приказ атаки движок не отменяет по расстоянию: в 0x18bb3 юнит, не достающий до цели,
// просто снова идёт к ней (сдаться может только дикий зверь — 1 шанс из 200 за тик), и бросает
// погоню лишь когда цель умерла. Значит, вернуть бой можно только если противник рядом, иначе
// целительница, слетавшая лечить кого-то на другой конец карты, побежит обратно через всю карту.
// Берём порог самого движка: 0x180 пикселей (12 клеток) по большей из осей — так 0x1df84
// отделяет «далеко» от «рядом» (0x1e058: cmp bx, 0xe0 и дальше 0x180, bx = max(|dx|,|dy|)).
const LEASH = 0x180;
const memo = new WeakMap();                            // eng → Map(номер записи мага → цель)
/** Запомненные цели магов этого движка. */
const map = (eng) => { let m = memo.get(eng); if (!m) memo.set(eng, m = new Map()); return m; };
/** Запомненные цели магов — состояние симуляции вне памяти движка; в сетевой игре едут со снимком. */
export function dumpTargets(eng) { return [...map(eng)]; }
/** Цели магов из снимка. */
export function restoreTargets(eng, список) { const m = map(eng); m.clear(); for (const [k, v] of список || []) m.set(k, v); }

/** Юнит жив и не труп. */
const alive = (m, i) => i !== 0 && m.u8(UNITS + i + U.STATE) !== 0x60 && (m.u8(UNITS + i + U.FLAGS5B) & 1) === 0;

// ---- 0x18154: обработчик людей. Приказ применяется (и затирает [+0x33]) только когда юнит
// стоит ровно на тайле — то же условие, что в оригинале, иначе запомним цель раньше времени.
const orig18154 = F[0x18154];
F[0x18154] = (eng, r) => {
  const m = eng.m, esi = r.esi;
  if (eng.resumeAttack !== false) {
    const ord = m.u8(UNITS + esi + U.ORDER);
    if (ord >= SPELL_ORDER_LO && ord <= SPELL_ORDER_HI &&
        (m.u16(UNITS + esi + U.X) & 0x1f) === 0 && (m.u16(UNITS + esi + U.Y) & 0x1f) === 0) {
      const tgt = m.u32(UNITS + esi + U.TARGET);
      if (alive(m, tgt) && m.u8(UNITS + tgt + U.OWNER) !== m.u8(UNITS + esi + U.OWNER)) map(eng).set(esi, tgt);
      else map(eng).delete(esi);
    }
  }
  return orig18154(eng, r);
};

// ---- 0x19b78: заклинание отработало. Оригинал ставит приказ 0x3f; если у мага была цель
// до заклинания и она ещё жива и всё ещё чужая — возвращаем приказ атаки по ней.
const orig19b78 = F[0x19b78];
F[0x19b78] = (eng, r) => {
  const m = eng.m, esi = r.esi;
  const res = orig19b78(eng, r);
  if (eng.resumeAttack === false || m.u8(UNITS + esi + U.ORDER) !== 0x3f) return res;
  const tgt = map(eng).get(esi); map(eng).delete(esi);
  if (tgt === undefined || !alive(m, tgt)) return res;
  if (m.u8(UNITS + tgt + U.OWNER) === m.u8(UNITS + esi + U.OWNER)) return res;
  const dx = Math.abs(m.u16(UNITS + tgt + U.X) - m.u16(UNITS + esi + U.X));
  const dy = Math.abs(m.u16(UNITS + tgt + U.Y) - m.u16(UNITS + esi + U.Y));
  if ((dx > dy ? dx : dy) > LEASH) return res;         // цель уже далеко — не гонимся
  F[0x19f63](eng, { esi, edi: tgt });                  // тот же вызов, что у боевых заклинаний
  return res;
};
