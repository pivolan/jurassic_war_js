// Кто в партии человек (наше). Нужно для сетевой игры: людей может быть несколько, и симуляция
// на всех машинах обязана считать их одинаково — иначе на моей машине ИИ водит юнитов соперника,
// а на его машине нет, и состояния разъезжаются на первом же шаге.
//
// [0x31b64] (G.humanOwner) остаётся «моим племенем» и дальше отвечает только за зрительское:
// туман, голоса, сообщения, что показывать в панели. А всё, что влияет на симуляцию —
// пропуск слота в ИИ, автоматический выбор оружия, реакции построек — спрашивает здесь.
//
// В одиночной игре набор пуст и человек один — [0x31b64], как в оригинале.
import { G } from '../mem.js';

let набор = null;                       // Set владельцев-людей или null (одиночная игра)
const поПамяти = new WeakMap();         // Mem → Set: свой набор у каждого движка (несколько партий в одном процессе — проверки)

/** Задать людей на партию (сетевая игра). null — обратно к одиночной. С `m` — только для этого движка. */
export function задатьЛюдей(владельцы, m = null) {
  const s = владельцы ? new Set(владельцы) : null;
  if (m) { if (s) поПамяти.set(m, s); else поПамяти.delete(m); } else набор = s;
}
export const люди = (m = null) => (m && поПамяти.get(m)) || набор;

/** Человек ли владелец `вл` — одинаково на всех машинах партии. */
export function человек(m, вл) { const s = поПамяти.get(m) || набор; return s ? s.has(вл) : вл === m.u8(G.humanOwner); }
