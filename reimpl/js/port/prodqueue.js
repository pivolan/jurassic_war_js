// Очередь производства в здании (наше). В оригинале здание учит одного юнита за раз, и клик по
// портрету при занятом здании просто глотался. Здесь клик при занятом здании ставит юнита в очередь
// (счётчик у иконки), правая кнопка снимает одного из очереди, а когда очереди по этому портрету
// нет — отменяет текущее производство с возвратом еды.
//
// Очередь — состояние симуляции вне памяти движка (как маршруты патрулей): меняется только
// приказами 0x7f/0x7e, которые проходят через общую очередь приказов, поэтому в сетевой игре у всех
// одинакова; едет со снимком (lockstep.состояниеJS) и в сейв/реплей.
export const ПРЕДЕЛ = 9;                 // больше девяти одного вида в очередь не ставим

const очереди = new WeakMap();           // eng → Map(здание → [номер портрета, ...])
/** Очереди производства этого движка: здание → список номеров портретов. */
const карта = (eng) => { let q = очереди.get(eng); if (!q) очереди.set(eng, q = new Map()); return q; };

/** Что стоит в очереди у здания (пустой массив, если ничего). */
export function очередь(eng, здание) { return карта(eng).get(здание) || []; }
/** Поставить в очередь ещё одного юнита вида k; false — упёрлись в предел. */
export function добавить(eng, здание, k) {
  const q = карта(eng); const с = q.get(здание) || [];
  if (с.filter(x => x === k).length >= ПРЕДЕЛ) return false;
  с.push(k); q.set(здание, с); return true;
}
/** Снять последнего юнита вида k из очереди; true — снят. */
export function убрать(eng, здание, k) {
  const с = карта(eng).get(здание); if (!с) return false;
  const i = с.lastIndexOf(k); if (i < 0) return false;
  с.splice(i, 1); if (!с.length) карта(eng).delete(здание); return true;
}
/** Снять первого из очереди и вернуть его вид: здание освободилось. */
export function следующий(eng, здание) {
  const с = карта(eng).get(здание); if (!с || !с.length) return undefined;
  const k = с.shift(); if (!с.length) карта(eng).delete(здание); return k;
}
/** Забыть очередь здания (его снесли). */
export function очистить(eng, здание) { карта(eng).delete(здание); }
/** Сколько юнитов вида k стоит в очереди (число рисуется у портрета). */
export function сколько(eng, здание, k) { return очередь(eng, здание).filter(x => x === k).length; }
/** Очереди в снимок и в запись партии. */
export function dump(eng) { return [...карта(eng)].map(([з, с]) => [з, ...с]); }
/** Очереди из снимка. */
export function restore(eng, список) { const q = карта(eng); q.clear(); for (const [з, ...с] of список || []) if (с.length) q.set(з, с.slice()); }
