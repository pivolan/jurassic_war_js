// Автоприрост еды (наше, в оригинале такого нет; по умолчанию выключено).
//
// Зачем. Вся экономика игры — охота: зверя убили, мясо принесли. На бедной зверьём карте это
// упирается в потолок, партия вязнет, и до дорогих юнитов и заклинаний никто не доживает.
// Правило «каждой живой базе капает еда» превращает партию в нормальную стратегию: строить есть
// на что, а разница решается тем, кто лучше воюет, а не тем, кому досталось пастбище.
//
// Кому капает: каждому цвету, у которого стоит Святилище (главный дом). Нет Святилища — нет и
// прироста: базу снесли, племя живёт тем, что успело добыть.
//
// Как считается. Тик игры — 55 мс, значит минута это 1091 шаг. Чтобы не сыпать раз в минуту
// мешком, начисляем понемногу: ПОРЦИЯ еды каждые ПЕРИОД шагов. 200 × (1091 / 109) ≈ 2002 в
// минуту — то, что и просили, с точностью до двух единиц.
//
// Детерминизм. Считается внутри шага симуляции по номеру шага, из памяти движка, без часов и
// случайностей: у всех машин выходит одно и то же. Флаг правила приезжает в параметрах старта и
// едет в снимке (lockstep.состояниеJS), как и «украшения».
import { G, U, UNITS } from '../mem.js';
import { наШаг, установить } from './inject.js';

export const ПЕРИОД = 109;               // шагов между начислениями
export const ПОРЦИЯ = 200;               // еды за начисление — это ~2000 в минуту
const СВЯТИЛИЩЕ = 0x1a;

let вкл = false;
/** Включить или выключить правило (одинаково у всех: приходит в параметрах старта). */
export function задать(_eng, значение) { вкл = !!значение; }
/** Включено ли правило автоприроста еды. */
export const включено = () => вкл;

/** Начисление: раз в ПЕРИОД шагов каждой базе со Святилищем капает ПОРЦИЯ еды. */
export function шаг(eng) {
  if (!вкл) return;
  const m = eng.m;
  if ((m.u32(G.step) % ПЕРИОД) !== 0) return;
  const есть = new Set();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.TYPE) !== СВЯТИЛИЩЕ) continue;
    const вл = m.u8(UNITS + i + U.OWNER); if (вл < 8) есть.add(вл);
  }
  for (const вл of есть) m.w32(G.food + вл * 4, (m.u32(G.food + вл * 4) + ПОРЦИЯ) >>> 0);
}

наШаг.push(шаг);
установить();
