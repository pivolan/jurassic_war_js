// Планы стройки (наше). Очередь построек в оригинале уже есть: Святилище выпускает строителя,
// заранее «настроенного» на здание (портрет в панели = вид постройки, он же +0x59 у строителя), и
// такую очередь мы уже умеем копить (prodqueue.js). Чего нет — места: вышедшего строителя надо
// вести за руку и жать «строить». План закрывает именно это: игрок отмечает точку, а вышедший
// строитель сам идёт туда и ставит здание.
//
// Детерминизм. План меняется только приказами ПЛАН_ДОБАВИТЬ/ПЛАН_УБРАТЬ, которые идут через ту же
// очередь приказов, что и всё остальное (inject.js), поэтому в сетевой игре планы одинаковы у
// всех. Шаг плана (кому идти и когда строить) считается внутри шага симуляции, на тех же данных,
// и едет со снимком (lockstep.состояниеJS).
import { G, U, UNITS } from '../mem.js';
import { F } from '../fn.js';
import { приказ, КОД, НАШИ, наШаг } from './inject.js';

export const ПЛАН_ДОБАВИТЬ = 0xf1, ПЛАН_УБРАТЬ = 0xf2;
const ШАГ_ПРОВЕРКИ = 8;                  // раз в столько шагов раздаём планы строителям
const БЛИЗКО = 40;                       // точек до точки стройки, ближе — можно ставить
const СТРОИТЕЛЬ = 4;

const планы = new WeakMap();             // eng → [{ вл, вид, x, y, кому }]
/** Все планы стройки этого движка. */
const списокПланов = (eng) => { let п = планы.get(eng); if (!п) планы.set(eng, п = []); return п; };

/** Планы владельца вл (или все, если владелец не указан). */
export function список(eng, вл) { return списокПланов(eng).filter(п => вл === undefined || п.вл === вл); }
/** Отметить место под здание: строитель придёт сюда сам. */
export function добавить(eng, вл, вид, x, y) {
  const п = списокПланов(eng);
  if (п.length >= 32) return false;
  п.push({ вл, вид: вид & 0xff, x: x & ~0x1f, y: y & ~0x1f, кому: 0 });
  return true;
}
/** Снять план, ближайший к точке (в пределах клетки); true — сняли. */
export function убрать(eng, вл, x, y) {
  const п = списокПланов(eng);
  const i = п.findIndex(z => z.вл === вл && Math.abs(z.x - (x & ~0x1f)) < 32 && Math.abs(z.y - (y & ~0x1f)) < 32);
  if (i < 0) return false;
  п.splice(i, 1); return true;
}
/** Снять все планы владельца. */
export function очистить(eng, вл) { const п = списокПланов(eng); for (let i = п.length - 1; i >= 0; i--) if (п[i].вл === вл) п.splice(i, 1); }
/** Планы в простой массив — для снимка и записи партии. */
export function dump(eng) { return списокПланов(eng).map(п => [п.вл, п.вид, п.x, п.y, п.кому]); }
/** Поднять планы из снимка. */
export function restore(eng, с) { планы.set(eng, (с || []).map(([вл, вид, x, y, кому]) => ({ вл, вид, x, y, кому: кому || 0 }))); }

/** Юнит существует и не мёртв. */
const живой = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1);
/** Строитель этого владельца, который сейчас ничем не занят. */
const свободныйСтроитель = (m, i, вл, вид) =>
  живой(m, i) && m.u8(UNITS + i + U.TYPE) === СТРОИТЕЛЬ && m.u8(UNITS + i + U.OWNER) === вл &&
  m.u8(UNITS + i + 0x59) === вид && m.u8(UNITS + i + U.ORDER) === 0xff;

/** Шаг планов: кому идти, кому уже ставить здание. Зовётся из inject на каждом шаге. */
export function шаг(eng) {
  const m = eng.m; const п = списокПланов(eng);
  if (!п.length || (m.u32(G.step) % ШАГ_ПРОВЕРКИ) !== 0) return;
  for (let k = п.length - 1; k >= 0; k--) {
    const пл = п[k];
    // Назначенный строитель мог стать зданием (план выполнен) или погибнуть — тогда ищем нового.
    if (пл.кому && (!живой(m, пл.кому) || m.u8(UNITS + пл.кому + U.TYPE) !== СТРОИТЕЛЬ)) {
      const стал = живой(m, пл.кому) && m.u8(UNITS + пл.кому + U.TYPE) >= 0x1a;
      пл.кому = 0;
      if (стал) { п.splice(k, 1); continue; }                    // здание поставлено — план закрыт
    }
    if (!пл.кому) {
      let лучший = 0, dist = Infinity;
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (!свободныйСтроитель(m, i, пл.вл, пл.вид)) continue;
        if (п.some(z => z !== пл && z.кому === i)) continue;
        const d = Math.abs(m.u16(UNITS + i + U.X) - пл.x) + Math.abs(m.u16(UNITS + i + U.Y) - пл.y);
        if (d < dist) { dist = d; лучший = i; }
      }
      if (!лучший) continue;
      пл.кому = лучший;
    }
    const с = пл.кому;
    if (m.u8(UNITS + с + U.ORDER) !== 0xff) continue;            // уже чем-то занят, подождём
    const dx = Math.abs(m.u16(UNITS + с + U.X) - пл.x), dy = Math.abs(m.u16(UNITS + с + U.Y) - пл.y);
    if (dx > БЛИЗКО || dy > БЛИЗКО) приказ(eng, с, КОД.ИДТИ, 0, пл.x, пл.y);
    else приказ(eng, с, 0xe0, с, 0, 0);                          // 0xe0 — «строить здесь», как кнопка в панели
  }
}

// Приказы планов идут через общую очередь: у всех машин они применяются в одном и том же месте шага.
НАШИ.set(ПЛАН_ДОБАВИТЬ, (eng, з) => добавить(eng, з.цель & 0xff, (з.цель >> 8) & 0xff, з.x, з.y));
НАШИ.set(ПЛАН_УБРАТЬ, (eng, з) => убрать(eng, з.цель & 0xff, з.x, з.y));
наШаг.push(шаг);

// Приказ от игрока идёт через ту же точку, что и любой другой (0x14895): в сетевой партии обвязка
// перехватит его и отправит пакетом хода, в одиночной — положит в нашу очередь (обвязка знает наши
// коды). Звать приказ() напрямую нельзя: тогда план появился бы только на своей машине.
export const приказПлана = (eng, юнит, вл, вид, x, y) =>
  F[0x14895](eng, { eax: ПЛАН_ДОБАВИТЬ, esi: юнит, edi: (вл & 0xff) | ((вид & 0xff) << 8), edx: x & 0xffff, ebx: y & 0xffff });
/** Приказ «снять план в этой точке» — через общую очередь, чтобы дошёл до всех. */
export const приказСнятия = (eng, юнит, вл, x, y) =>
  F[0x14895](eng, { eax: ПЛАН_УБРАТЬ, esi: юнит, edi: вл & 0xff, edx: x & 0xffff, ebx: y & 0xffff });

// ---------------------------------------------------------------- доведение приказа «строить»
// Приказ 0xe0 в оригинале одноразовый: 0x1d1cf ищет площадку, и если она не там, где стоит
// строитель, отправляет его туда обычным «идти» — и на этом всё. Дошёл и стоит, здания нет.
// В оригинале это лечилось тем, что игрок жал «строить» ещё раз; выглядит как «команда не
// сработала». Здесь запоминаем намерение и повторяем приказ, когда строитель дошёл.
const хотят = new WeakMap();             // eng → Map(строитель → {вид, попыток})
/** Кто из строителей какой дом собирается ставить (и сколько раз уже пробовал). */
const хочу = (eng) => { let c = хотят.get(eng); if (!c) хотят.set(eng, c = new Map()); return c; };
const ПОПЫТОК = 6;                       // больше — значит места и правда нет, перестаём дёргать

/** Намерения строителей в снимок. */
export function dumpСтройки(eng) { return [...хочу(eng)].map(([i, з]) => [i, з.вид, з.попыток]); }
/** Намерения строителей из снимка. */
export function restoreСтройки(eng, с) {
  const c = хочу(eng); c.clear();
  for (const [i, вид, попыток] of с || []) c.set(i, { вид, попыток: попыток | 0 });
}

const ориг1d1cf = F[0x1d1cf];
F[0x1d1cf] = (eng, r) => {
  const m = eng.m, esi = r.esi;
  const вид = m.u8(UNITS + esi + 0x59);
  const res = ориг1d1cf(eng, r);
  // Строитель остался строителем и получил приказ «идти» — значит ушёл к площадке, надо вернуться
  // к стройке, когда дойдёт.
  if (m.u8(UNITS + esi + U.TYPE) === СТРОИТЕЛЬ && m.u8(UNITS + esi + U.ORDER) === КОД.ИДТИ) {
    const было = хочу(eng).get(esi);
    хочу(eng).set(esi, { вид, попыток: (было?.вид === вид ? было.попыток : 0) + 1 });
  } else хочу(eng).delete(esi);
  return res;
};

/** Шаг доведения: строитель дошёл и стоит — повторяем «строить». Зовётся из inject каждый шаг. */
export function шагСтройки(eng) {
  const m = eng.m; const c = eng && хотят.get(eng); if (!c || !c.size) return;
  if ((m.u32(G.step) % 8) !== 0) return;
  for (const [i, з] of [...c]) {
    if (!живой(m, i) || m.u8(UNITS + i + U.TYPE) !== СТРОИТЕЛЬ) { c.delete(i); continue; }
    if (з.попыток > ПОПЫТОК) { c.delete(i); continue; }
    if (m.u8(UNITS + i + U.ORDER) !== 0xff) continue;                 // приказ ещё в пути
    const ст = m.u8(UNITS + i + U.STATE);
    if ((ст & 0xf0) !== 0x30) continue;                               // ещё идёт или занят
    if ((m.u16(UNITS + i + U.X) & 0x1f) || (m.u16(UNITS + i + U.Y) & 0x1f)) continue;
    m.w8(UNITS + i + 0x59, з.вид);
    m.w8(UNITS + i + U.ORDER, 0xe0); m.w32(UNITS + i + 0x47, i);      // «строить здесь» ещё раз
  }
}
наШаг.push(шагСтройки);
