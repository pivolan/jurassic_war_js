// Не слышно и не видно того, что происходит в неразведанной темноте.
//
// Как в оригинале. Проверок видимости в звуке нет вообще: 0x1ffb6, 0x1feb7 и остальные обёртки
// смотрят только на флаг «звук включён» [0x30c4c], а сам проигрыватель 0x2000d считает лишь
// громкость по расстоянию от центра экрана — таблицы 0x39060 (ближний канал) и 0x39161
// (дальний) по горизонтали и штраф 0x39262 по вертикали; если после вычитания оба канала
// вышли в ноль, звук просто не ставится в очередь. Замер на 10-й миссии: из 1049 заявок за
// 45 с 189 гасились расстоянием, но 138 приходили от юнитов на неразведанных клетках — их
// было слышно.
//
// Всплывающие «HP+1 / OP+1 / DP+1 / MP+1 / VP+1» (эффект 0x3a, рисуется 0x25f94 строкой из
// таблицы 0x42410) тоже рисуются кому угодно: в цикле эффектов 0x25cbc проверки нет. Поверх
// них потом ложится туман 0x2438e, но он накладывается операцией OR, а текст цвета 0xf8 от
// такого не темнеет — надпись видно сквозь темноту. За те же 45 с из 71434 отрисовок 14274
// пришлись на юнитов в неразведанных клетках.
//
// Что делаем. Гасим и звук, и надпись, если клетка юнита ещё не разведана (бит 0 в BI —
// его выставляет разведка, при загрузке миссии 0x244c3 обнуляет его по всей карте).
// Выключается через eng.fogQuiet = false — тогда всё как в оригинале.
import { F } from '../fn.js';
import { U, UNITS, BI } from '../mem.js';

const PROJ = 0xf2504;

/** Разведана ли клетка, на которой стоит юнит. */
function seen(m, u) {
  if (!u) return true;
  const gx = m.u16(UNITS + u + U.X) >>> 5, gy = m.u16(UNITS + u + U.Y) >>> 5;
  return (m.u8(BI + gx + (gy << 8)) & 1) !== 0;
}

// ---- 0x2000d: заявка на звук от юнита esi
const orig2000d = F[0x2000d];
F[0x2000d] = (eng, r) => {
  if (eng.fogQuiet !== false && !seen(eng.m, r.esi >>> 0)) return { eax: r.eax, ebx: 0, edx: 0, ecx: 0 };
  return orig2000d(eng, r);
};

// ---- 0x25f94: надпись над юнитом (эффект esi — запись в пуле 0xf2504)
const orig25f94 = F[0x25f94];
F[0x25f94] = (eng, r) => {
  if (eng.fogQuiet !== false && !seen(eng.m, eng.m.u32(PROJ + r.esi + 4))) return;
  return orig25f94(eng, r);
};
