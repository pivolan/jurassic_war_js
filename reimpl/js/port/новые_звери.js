// НОВЫЕ ЗВЕРИ: брахиозавр (тип 15) и демон (18). В паке игры у них спрайты-заглушки 1×1 — авторы
// их задумали (статы, мясо, имена есть), но не нарисовали. Кадры рисуем сами (tools/пак_зверей.py →
// data/beasts.bin) и после загрузки миссии подставляем в таблицу слотов движка (0x16e5f4, 16 байт:
// u32 адрес пикселей, u16 w, u16 h, 4 × i16 привязка). Номер слота = номер спрайта в паке 04.
//
// Пиксели кладём в свой хвост памяти (за ХВОСТ + прежний запас), а не в кучу спрайтов [0x48874]:
// при смене племени движок откатывает кучу (0x2bbbd) и затёр бы наши кадры. Хвост не входит ни в
// снимок партии, ни в сверку локстепа — поэтому после каждой загрузки миссии и сохранения вставляем
// заново (loader.js). Код движка не меняется: он просто находит в слотах настоящие кадры.
import { ЗВЕРИ_АДРЕС, ЗВЕРИ_РАЗМЕР } from '../mem.js';

const SLOTS = 0x16e5f4;
let пак = null;                       // Uint8Array содержимого beasts.bin

/** Задать пак (браузер — после fetch, node — после readFileSync). */
export function задать(буф) { пак = буф && буф.length > 6 ? буф : null; }
export const есть = () => !!пак;

/** Подставить кадры в слоты. Возвращает число записей (0 — пака нет). */
export function вставить(m) {
  if (!пак || m.b.length < ЗВЕРИ_АДРЕС + ЗВЕРИ_РАЗМЕР) return 0;
  const dv = new DataView(пак.buffer, пак.byteOffset, пак.byteLength);
  if (dv.getUint32(0, false) !== 0x4a574e5a) return 0;            // 'JWNZ'
  const n = dv.getUint16(4, true);
  let p = 6, куда = ЗВЕРИ_АДРЕС;
  for (let k = 0; k < n; k++) {
    const слот = dv.getUint16(p, true), w = dv.getUint16(p + 2, true), h = dv.getUint16(p + 4, true);
    const x = [0, 1, 2, 3].map(j => dv.getInt16(p + 6 + j * 2, true));
    p += 14;
    if (куда + w * h > ЗВЕРИ_АДРЕС + ЗВЕРИ_РАЗМЕР) break;
    m.b.set(пак.subarray(p, p + w * h), куда);
    const о = SLOTS + слот * 16;
    m.w32(о, куда); m.w16(о + 4, w); m.w16(о + 6, h);
    for (let j = 0; j < 4; j++) m.w16(о + 8 + j * 2, x[j]);
    p += w * h; куда += w * h;
  }
  return n;
}
