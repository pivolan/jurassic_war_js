// [главный юнит, второстепенный, дом главного (вид 0..13 для Sanctuary: 0 Sanctuary, 1 Barracks, 2/3 Armory, 4 Storage, 5..8 Elf/Wizard/Warlock/Ranger, 9..13 динозавры)]
// `правка` — поправка на баланс скирмиша (см. БАЛАНС ниже): −1 один главный боец вместо двух,
// +1 — три. Числа из прогона по трём картам (168 партий, зверский уровень): Ka-noo-se 55 %,
// Tyrano и Romack по 45 %, Moospell 38 %, RaDumBa 36 %, Koomba и Masai по 29 %, Koaka 10 %.
// Фирменная снаряга племени: что главный боец носит с самого начала. Даётся ровно одному юниту
// и только тем племенам, чьи бойцы вообще умеют носить вещи (люди, типы 1..3 — у динозавров,
// эльфов, рейнджеров и магов рук под оружие нет). Вещи взяты не с потолка, а из ассортимента
// СОБСТВЕННОЙ оружейной племени — то есть это и правда его снаряжение, а не чужое:
//   id 1..7  — оружие (атака 28/24/20/15/9/7/5), из них 5..7 двуручные и щит с ними нельзя;
//   id 10    — щит (+15 защиты), умеет только вторая оружейная (Koomba);
