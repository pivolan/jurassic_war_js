// Зачем. Замер поведений (tools/ai_поведение.mjs, 8960 партий) показал, что у Koomba ВСЕ восемь
// манер игры в минусе — набор просто слабее прочих, и никакой тактикой это не вытягивается.
// Владелец: «Кумбе добавь стартовый набор, пусть юниты будут одеты в щит и топор».
