// Сетевая партия по местам (наше). Карта оригинала даёт восемь готовых армий; вместо них хост
// расставляет стартовые наборы по местам-цветам, которые заняли игроки или компьютер, а
// закрытые места остаются пустыми. Место — это владелец (цвет) 0..7, стартовая точка — Sanctuary
// этого владельца на карте (на всех картах пака 13 она есть у каждого). Племя игрока задаёт
// только состав набора и спрайты; сторона в симуляции — цвет.
//
// Набор племени взят из того, чем племена вооружены на сетевых картах оригинала (tools: разбор
// пака 13): Tyrano — динозавры, Ka-noo-se — эльфы, Romack — рейнджеры, Masai — воины,
// Moospell — маги, Koomba — силачи, RaDumBa — силачи и воины, Koaka — карнотавры и рамфоринхи.
