/**
 * Правка стартового набора под баланс (наше). Сами наборы взяты из оригинала, но в скирмише
 * восемь племён играют друг против друга напрямую, и разброс получается большой: стрелковые
 * племена бьют ближние просто потому, что стрелок стреляет и отходит. Правка меняет только
 * число главных бойцов в наборе: −1 — один вместо двух, +1 — три. Ничего в статах и в
 * технологиях не трогаем, поэтому «оригинальность» партии не страдает: это настройка скирмиша.
 * Числа подобраны прогоном tools/ai_tourney.mjs племена по трём картам, см. AI-STRATEGY.md §9.
 * Выключается через БАЛАНС.вкл = false (для сверки).
 */
export const БАЛАНС = { вкл: true };

/** Включить встроенный ИИ слота `s` посреди партии — то, что 0x15da1 делает при загрузке миссии для
 *  слотов с ИИ, только без второго ГСЧ (он у каждой машины свой): строка таблицы целей — первая. */
export function включитьИИ(m, s) {
  if (m.u8(0x32aec + s) !== 0) return;
  m.w8(0x32aec + s, 1);
  m.w8(0x32afc + s, 1); m.w8(0x32af4 + s, 0);
  m.w8(0x32b04 + s, m.u8(0x32d2c + (s << 5) + 1));
  const e = s * 10; m.w8(0x32bcc + e, 8); m.w8(0x32bcd + e, 0); m.w8(0x32c1c + e, 8); m.w8(0x32c1d + e, 0);
  let v = m.u16(0x32c7c + s * 2) + 0xc8; const d = m.u8(G.difficulty); if (d !== 2) { v += 0x50; if (d !== 1) v += 0x50; } m.w16(0x32c7c + s * 2, v);
}

/** Стартовые точки карты: владелец → {x, y} его Sanctuary (или середина его юнитов). */
export function стартовыеПозиции(m) {
  const из = {}, сумма = {};
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const o = m.u8(UNITS + i + U.OWNER), t = m.u8(UNITS + i + U.TYPE); if (o > 7) continue;
    const x = m.u16(UNITS + i + U.X), y = m.u16(UNITS + i + U.Y);
    if (t === 26 && !из[o]) из[o] = { x, y };
    const с = сумма[o] ??= { x: 0, y: 0, n: 0 }; с.x += x; с.y += y; с.n++;
  }
  for (const o of Object.keys(сумма)) if (!из[o]) из[o] = { x: Math.round(сумма[o].x / сумма[o].n) & ~31, y: Math.round(сумма[o].y / сумма[o].n) & ~31 };
  return из;
}

/**
 * Убрать с карты армии владельцев 0..7 (звери и растения владельца 8 остаются) и очистить сетки.
 * `родные` — цвета, чьи войска с карты НЕ убираются: они играют тем, что им дала сама карта.
 * Нужно для смешанных прогонов вида «двое со стартовыми наборами против родного компьютера».
 */
function снестиАрмии(eng, родные = []) {
  const m = eng.m; const список = [];
  const беречь = new Set(родные);
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const вл = m.u8(UNITS + i + U.OWNER);
    if (вл < 8 && !беречь.has(вл)) список.push(i);
  }
  for (const i of список) call(eng, 0x1aaf7, { esi: i });      // из списка живых — в свободный список
  for (let s = 0; s < 8; s++) { if (беречь.has(s)) continue; m.w32(G.food + s * 4, 0); m.w32(0x31c48 + s * 4, 0); }
  F[0x15070](eng);                                              // сетки BI/MO заново по оставшимся
}

/** Создать юнита заданного вида в точке (расстановка скирмиша). */
function юнит(eng, тип, слот, владелец, x, y) {
  const r = call(eng, 0x1caf0, { eax: тип | (слот << 8), ecx: владелец, edx: x, ebx: y });
  return r && r.cf ? null : (r.esi >>> 0);
}
/** Готовое здание вида `вид` рядом с (x, y): ставится конструктором и сразу достраивается. */
function здание(eng, вид, слот, владелец, x, y) {
  const m = eng.m, esi = юнит(eng, 4, слот, владелец, x, y); if (esi === null) return null;
  const s = UNITS + esi; m.w8(s + 0x59, вид);
  call(eng, 0x1a42c, { esi, edx: m.u16(s + U.X), ebx: m.u16(s + U.Y) });
  const site = F[0x1cd2d](eng, { eax: вид, esi });
  m.w16(s + U.X, site.edx); m.w16(s + U.Y, site.ebx);
  const type = (вид + 0x1a) & 0xff, st = m.u32(0x30a9e + type * 4);
  m.w8(s + U.TYPE, type); m.w8(s + U.STATE, 0); m.w8(s + U.FLAGS50, 0); m.w8(s + U.ORDER, 0xff);
  m.w8(s + U.HPMAX, m.u8(st + 0x37654)); m.w8(s + U.HP, m.u8(st + 0x37654)); m.w8(s + 0x51, m.u8(st + 0x37654));
  const mag = m.u8(st + 0x37656); m.w8(s + U.MAG, mag); m.w8(s + U.MANA, mag);
  m.w8(s + U.ATK, m.u8(st + 0x37657)); m.w8(s + U.DEF, m.u8(st + 0x37658)); m.w8(s + U.SPD, m.u8(st + 0x37659));
  for (let k = 0; k < 12; k++) m.w8(s + U.INV + k, 0);
  call(eng, 0x1dac2, { esi });                                   // отпечаток в сетке
  if (type === 0x1e) m.w32(0x31c48 + владелец * 4, m.u32(0x31c48 + владелец * 4) + 1);
  return esi;
}
/** Первый вид дома, который племя слота действительно умеет строить (маска Святилища 0x30e88). */
function первыйДом(m, слот) {
  const маска = m.u32(m.u32(0x30e88 + слот * 4)) >>> 0;             // вид 0 — список Святилища
  if ((маска >>> 1) & 1) return 1;                                  // казарма есть почти у всех
  for (let k = 1; k < 14; k++) if ((маска >>> k) & 1) return k;
  return 1;
}
/**
 * Надеть на бойца фирменную снарягу племени. Ничего не делает, если у племени её нет, боец не
 * создался или он не человек: вещи носят только типы 1..3, остальным их просто некуда деть.
 * Вещь кладём в инвентарь и сразу помечаем надетой — в оригинале подобранное надевают кнопкой,
 * но здесь это стартовый комплект, а не находка.
 */
function одеть(m, esi, племя) {
  if (esi === null || esi === undefined || БЕЗ_СНАРЯГИ) return;
  const н = СНАРЯГА[(племя | 0) & 7]; if (!н) return;
  const s = UNITS + esi, т = m.u8(s + U.TYPE);
  if (т < 1 || т > 3) return;
  if (н.оружие) { m.w8(s + U.INV + СЛОТ_ОРУЖИЯ, н.оружие); m.w8(s + U.WEAPON, СЛОТ_ОРУЖИЯ); }
  const вторая = н.щит || н.оберег;
  if (вторая) { m.w8(s + U.INV + СЛОТ_ЩИТА, вторая); m.w8(s + U.SHIELD, СЛОТ_ЩИТА); }
}

/** Урезать характеристики вдвое: так ставится слабый стартовый состав. */
function половина(m, esi) { const s = UNITS + esi; for (const f of [U.HPMAX, U.HP, U.MAG, U.MANA, U.ATK, U.DEF, U.SPD]) m.w8(s + f, Math.max(1, m.u8(s + f) >> 1)); }
/** Подрезать стартовому бойцу все параметры на `проц` процентов (правка баланса, см. БАЛАНС). */
function ослабить(m, esi, проц) {
  const s = UNITS + esi;
  for (const f of [U.HPMAX, U.HP, U.MAG, U.MANA, U.ATK, U.DEF, U.SPD]) {
    const было = m.u8(s + f); if (!было) continue;                   // нулевую магию в единицу не превращаем
    m.w8(s + f, Math.max(1, Math.round(было * (100 - проц) / 100)));
  }
}

/**
 * Расставить партию по местам. места: [{ цвет: 0..7, кто: 'игрок'|'компьютер', племя: 0..7 }] —
 * закрытые места не передаются. Возвращает список созданного по цветам (для проверок).
 */
export function расставить(eng, места, { быстрый = false, родные = [] } = {}) {
  const m = eng.m;
  const точки = стартовыеПозиции(m);
  снестиАрмии(eng, родные);
  for (let s = 0; s < 8; s++) { m.w8(0x32ae4 + s, s); if (!родные.includes(s)) m.w8(0x32aec + s, 0); }   // слот = цвет, ИИ пока никому
  // Слот юнита (+5) в оригинале равен племени: по нему берутся маска доступных построек
  // (0x30e88 → таблица по видам зданий), облик зданий (0x416d4) и предпочтения ИИ (0x32d2c).
  // У нас слот = цвет места, чтобы учёт ИИ по слотам не путался при двух одинаковых племенах,
  // а таблицы для слота-цвета подменяем на таблицы племени набора — иначе Муспел на первом месте
  // жил по технологиям Tyrano: дом магов ничего не производил, а Sanctuary его не предлагал.
  // Эталон берём тот, что запомнил загрузчик сразу после чтения пака. Снимать его здесь нельзя:
  // расстановка эти же таблицы и переписывает, и на второй расстановке (рестарт, смена племени в
  // лобби) «исходником» оказалась бы уже переставленная таблица — игрок получал чужие дома.
  const эталон = m.племенныеТаблицы;
  const тех = эталон?.тех || [...Array(8)].map((_, s) => m.u32(0x30e88 + s * 4));
  const облик = эталон?.облик || m.b.slice(0x416d4, 0x416d4 + 14 * 8 * 4);
  const ии = эталон?.ии || m.b.slice(0x32d2c, 0x32d2c + 8 * 32);
  // Сначала вернуть все восемь столбцов к эталону, и только потом класть строки племён по местам.
  // Расстановка идёт заново на каждое изменение в лобби, и без сброса столбец закрытого (или
  // просто не переданного) места сохранял бы племя из прошлой раскладки.
  for (let s = 0; s < 8; s++) m.w32(0x30e88 + s * 4, тех[s]);
  m.b.set(облик, 0x416d4);
  m.b.set(ии, 0x32d2c);
  for (const место of места) {
    const ц = место.цвет, т = (место.племя | 0) & 7;
    m.w32(0x30e88 + ц * 4, тех[т]);
    for (let k = 0; k < 14; k++) for (let b = 0; b < 4; b++) m.w8(0x416d4 + (k * 8 + ц) * 4 + b, облик[(k * 8 + т) * 4 + b]);
    for (let b = 0; b < 32; b++) m.w8(0x32d2c + ц * 32 + b, ии[т * 32 + b]);
  }
  const итог = {};
  for (const место of [...места].sort((a, b) => a.цвет - b.цвет)) {
    const ц = место.цвет, н = ПЛЕМЯ_НАБОР[место.племя] || ПЛЕМЯ_НАБОР[0];
    const т = точки[ц] || точки[Object.keys(точки)[0]]; if (!т) continue;
    const созд = [];
    const дом = (вид, dx, dy) => { const e = здание(eng, вид, ц, ц, (т.x + dx) & 0xffff, (т.y + dy) & 0xffff); if (e !== null) созд.push(e); return e; };
    const боец = (тип, dx, dy) => {
      const e = юнит(eng, тип, ц, ц, (т.x + dx) & 0xffff, (т.y + dy) & 0xffff);
      if (e === null) return e;
      созд.push(e);
      // Тонкая правка баланса: подрезать конкретному стартовому бойцу параметры. Нужна потому,
      // что убрать юнита из набора — слишком грубо: у Tyrano разница между одним динозавром и
      // двумя это 25 процентных пунктов побед, промежуточной ступеньки между ними нет.
      const проц = БАЛАНС.вкл ? (н.подрезать?.[тип] || 0) : 0;
      if (проц) ослабить(m, e, проц);
      return e;
    };
    дом(0, 0, 0);                                                 // Sanctuary — главная база
    дом(4, 128, 0);                                               // склад еды
    дом(н.дом, -128, 64);                                         // дом главного юнита
    const стр = боец(4, 64, 96);                                  // строитель
    // Строителю обязательно назначить, что он строит (+0x59). В оригинале конструктор всегда
    // выходит из Святилища уже настроенным на выбранный дом, а наш стартовый набор делал его
    // «пустым»: в поле оставался мусор, и Tyrano получал строителя, настроенного на Оружейную —
    // дом, которого у этого племени вообще нет, и в котором потом ничего нельзя заказать.
    // Ставим первый дом, который племя и правда умеет строить: казарму, если она ему доступна.
    if (стр !== null) m.w8(UNITS + стр + 0x59, первыйДом(m, ц));
    if (быстрый) {
      const a = боец(н.главный, 96, 96), b = боец(1, 128, 96);    // главный + человек, половина статов
      одеть(m, a, место.племя);
      if (a !== null) половина(m, a); if (b !== null) половина(m, b);
    } else {
      const правка = БАЛАНС.вкл ? (н.правка || 0) : 0;
      // `вместо` — чем заменить подаренных главных бойцов. У племени с динозаврами набор даёт
      // с порога тело, до которого другим не дорасти никакой охотой: трицератопс это 310 очков
      // статов, а прокачать до них простолюдина стоит 64 леопарда, то есть больше, чем на всей
      // карте есть опыта (tools/ai_prices.mjs). Динозавров теперь надо строить, как всем.
      const главный = (БАЛАНС.вкл && н.вместо) ? н.вместо : н.главный;
      const второй = (БАЛАНС.вкл && н.вместо) ? н.вместо : н.второй;
      одеть(m, боец(главный, 96, 96), место.племя);
      if (правка >= 0) боец(второй, 128, 96);
      if (правка > 0) боец(главный, 160, 96);
      // Простолюдины: обычно трое. Тонкая правка — на одного меньше: у Tyrano в наборе и так
      // велоцираптор с трицератопсом, а снятие второго динозавра оказалось слишком грубым
      // (45 % побед → 21 %, замер по трём картам).
      const простых = 3 + (БАЛАНС.вкл ? (н.простых || 0) : 0);
      for (let k = 0; k < простых; k++) боец(1, 64 + k * 32, 128);
    }
    m.w32(G.food + ц * 4, быстрый ? ЕДА_БЫСТРО : ЕДА_ОБЫЧНО);
    // Встроенный ИИ на сетевых картах не играет (точку сбора и группы он берёт из данных карты,
    // а в паке 13 там нули) — поэтому по умолчанию на месте компьютера сидит наш скриптовый,
    // а включитьИИ зовём только если хост выбрал именно оригинальный.
    if (место.кто === 'компьютер' && место.ии === 'встроенный') включитьИИ(m, ц);
    итог[ц] = созд;
  }
  return итог;
}
