// Патрулирование отряда (наше; в оригинале такого приказа нет).
//
// Опора — «охрана поста» оригинала. Состояния 0x3x: 0x3f встать на пост (тайл поста уходит в
// +0x44/+0x45), 0x38 стоять и раз в несколько тиков искать врага рядом (0x1a526) и кидаться на
// него (0x19fdf), 0x30..0x33 гнать и бить, 0x37 вернуться на пост, 0x36 идти на пост, по дороге
// осматриваясь. Патруль — это маршрут из нескольких точек, по которому юнит ходит по кругу теми
// же состояниями.
//
// ВАЖНО про поиск врага. Спиральный поиск 0x1a526/0x1a531 (findTarget) считает клетки **от поста
// +0x44/+0x45**, а не от самого юнита. Поэтому пост нельзя занимать конечной точкой маршрута: юнит
// уходил бы от неё и осматривал место, где его нет, — ровно поэтому первая версия патруля никого
// не трогала. Теперь пост на каждой пройденной клетке переставляется под ноги юниту, а цель
// движения живёт в DSTX/DSTY, как у обычного приказа.
//
// Приказы (коды в оригинале свободны, разбираются штатной 0x1419e через 0x14621 «всем выделенным»):
//   0x34 — добавить точку маршрута (юнит при этом встаёт и ждёт остальных точек);
//   0x35 — маршрут задан, пошёл по кругу.
//
// Маршрут (до 5 точек и номер текущей) лежит в eng.patrols: в записи юнита свободных байт нет —
// +0x55..+0x58 занимает прямоугольник выпаса, который загрузчик заполняет всем юнитам, а значения
// доходят до 255. В памяти оригинала мы меняем только пост и цель движения. Детерминизм цел:
// маршрут собирается только из хода симуляции, а сами приказы идут через очередь 0x14895, то есть
// попадают в реплей; для сейвов есть dump()/restore().
//
// Выключается через eng.patrol = false.
import { F, call } from '../fn.js';
import { U, UNITS, ITEMS } from '../mem.js';

export const ORDER_POINT = 0x34;   // добавить точку маршрута
export const ORDER_GO = 0x35;      // пойти по маршруту
export const MAX_POINTS = 10;
// Сколько клеток вокруг осматриваем после боя: добыча падает под ноги убитому, дальше не ищем.
const СБОР_РАДИУС = 4;
const ГОЛОВА_ПРЕДМЕТОВ = 0x31b7c;
const ДОБЫЧА = 0x4c;
// Сколько шагов не возвращаться к клетке, откуда добычу взять не вышло. 600 шагов — это полминуты
// игры: за это время либо руки освободятся, либо кучку подберёт кто-то другой.
const ЗАБЫТЬ_ДОБЫЧУ = 600;
// Сторож: сколько шагов патрульный вправе простоять на месте, не будучи в бою. Дальше считаем,
// что он застрял (точку заняли, дорогу перекрыли, маршрут упёрся в чужое здание), и подталкиваем
// его к следующей точке. Жалоба была ровно такая: «зависают на середине пути и не реагируют ни на
// что внешнее, их бьют, а они стоят». Причину в одиночку воспроизвести не удалось, поэтому лечим
// симптом там, где это ничего не стоит: 150 шагов — это восемь секунд игры, нормальный патрульный
// столько на месте не стоит никогда.
const СТОЯЛ_ХВАТИТ = 150;
const ШАГ = 0x31ab4;                     // номер шага симуляции (G.step)
// Радиус поиска врага в патруле — индекс в таблице длин спирали 0x3058c (4 → 49 клеток, примерно
// три с половиной клетки в стороны). У охраны он свой, (СКОР>>5)+1, и часто равен одной клетке:
// патруль с таким проходил бы мимо противника в двух шагах.
const SCAN = 4;
// Поводок: на сколько клеток от ближайшей точки маршрута патрульный вправе отойти за противником.
// Зверь или чужой боец убегает, охрана гонится без конца — и «патруль охотничьих угодий»
// превращается в погоню через полкарты. Дошли до предела — бросаем цель и возвращаемся на маршрут.
const ПОВОДОК = +(globalThis.process?.env?.JW_LEASH || 8);

/** Маршруты патруля этого движка: юнит → точки и номер текущей. */
const карта = (eng) => (eng.patrols || (eng.patrols = new Map()));
/** Юнит стоит ровно на клетке, а не между ними: решения принимаем только тогда. */
const наТайле = (m, b) => (m.u16(b + U.X) & 0x1f) === 0 && (m.u16(b + U.Y) & 0x1f) === 0;

/** Маршрут юнита: { pts: [{x,y} в тайлах], i: номер текущей точки } или null. */
export function route(eng, i) { return eng.patrols?.get(i) || null; }
/**
 * Маршруты для сохранения: [[юнит, номер точки, счётчик простоя, [x, y, …], [клетка, шаг, …]], …].
 * Счётчик простоя и список «оттуда не берётся» тоже едут: они решают, когда патрульный перескочит
 * точку и пойдёт ли он за кучкой, — а значит влияют на симуляцию. Если их не сохранять, игрок,
 * подключившийся к партии по снимку, начнёт считать заново и разойдётся с остальными.
 */
export function dump(eng) {
  return [...(eng.patrols || new Map())].map(([i, p]) => [i, p.i, p.стоял | 0, p.былXY | 0,
    p.pts.flatMap(t => [t.x, t.y]), [...(p.неберётся || new Map())].flat()]);
}
/** Восстановить маршруты из сейва или из шапки реплея. */
export function restore(eng, список) {
  const c = карта(eng); c.clear();
  for (const запись of список || []) {
    // Старые записи (сейвы и реплеи до сторожа простоя) — плоский список координат после номера
    // точки; новые — с отдельными полями. Читаем оба вида.
    const [i, idx, ...хвост] = запись;
    let стоял = 0, былXY = 0, плоско, забыто = [];
    if (Array.isArray(хвост[2])) { [стоял, былXY, плоско, забыто] = хвост; }
    else плоско = хвост;
    const pts = []; for (let k = 0; k + 1 < плоско.length; k += 2) pts.push({ x: плоско[k], y: плоско[k + 1] });
    if (!pts.length) continue;
    const неберётся = new Map();
    for (let k = 0; k + 1 < (забыто || []).length; k += 2) неберётся.set(забыто[k], забыто[k + 1]);
    c.set(i, { pts, i: idx % pts.length, готов: true, стоял: стоял | 0, былXY: былXY | 0, неберётся });
  }
}

/**
 * Свой приказ юниту в патруле: пишем поля напрямую (так же делает сам движок в 0x1a34c/0x1a354) и
 * помечаем приказ «нашим», чтобы сторож ниже не принял его за приказ игрока и не снял патруль.
 */
function приказСебе(eng, esi, ord, x = 0, y = 0, цель = 0) {
  const m = eng.m, b = UNITS + esi;
  m.w8(b + U.ORDER, ord); m.w32(b + 0x47, цель); m.w16(b + 0x4b, x & 0xffff); m.w16(b + 0x4d, y & 0xffff);
  const p = eng.patrols?.get(esi); if (p) p.пропустить = ord;
}

/**
 * Подобрать добычу рядом. После боя на земле остаётся мясо (а с людей — их вещи), и уходить от
 * него по маршруту глупо: патрульный сам сходит за ближайшей кучкой.
 *
 * Клетки, откуда взять не вышло (руки заняты, вещь не лезет в инвентарь), помним по номеру шага и
 * какое-то время обходим стороной. Раньше помнилась ровно ОДНА клетка, и она же сбрасывалась,
 * если другой добычи рядом не нашлось. Получался вечный круг: сходил к куче — не взял — забыл —
 * пошёл к ней же. Юнит топтался около кучи, по маршруту не шёл и на удары не отвлекался — ровно
 * та жалоба, что «зависают на середине пути и ничего не делают».
 * @returns true — приказ на сбор отдан.
 */
function собратьРядом(eng, esi) {
  const m = eng.m, b = UNITS + esi, p = eng.patrols?.get(esi);
  if (!p) return false;
  const шаг = m.u32(ШАГ);
  if (!p.неберётся) p.неберётся = new Map();
  const cx = m.u16(b + U.X) >>> 5, cy = m.u16(b + U.Y) >>> 5;
  let лучшая = null, d0 = 1e9;
  for (let it = m.u32(ГОЛОВА_ПРЕДМЕТОВ); it; it = m.u32(ITEMS + it + 0xc)) {
    const x = m.u8(ITEMS + it + 1), y = m.u8(ITEMS + it + 2);
    const dx = x > cx ? x - cx : cx - x, dy = y > cy ? y - cy : cy - y;
    const d = dx > dy ? dx : dy;
    if (d > СБОР_РАДИУС) continue;
    const когда = p.неберётся.get((y << 8) | x);
    if (когда !== undefined && шаг - когда < ЗАБЫТЬ_ДОБЫЧУ) continue;       // недавно ходили без толку
    if (d < d0 || (d === d0 && лучшая && (y < лучшая.y || (y === лучшая.y && x < лучшая.x)))) { d0 = d; лучшая = { x, y }; }
  }
  if (!лучшая) return false;
  // Список забытых клеток не растим бесконечно: он живёт столько же, сколько сам патруль.
  if (p.неберётся.size > 32) for (const [к, когда] of p.неберётся) if (шаг - когда >= ЗАБЫТЬ_ДОБЫЧУ) p.неберётся.delete(к);
  p.неберётся.set((лучшая.y << 8) | лучшая.x, шаг);
  приказСебе(eng, esi, ДОБЫЧА, лучшая.x << 5, лучшая.y << 5);
  return true;
}

/** Пойти к текущей точке маршрута: цель в DST, движение — состоянием 0x36, как у возврата на пост. */
function кТочке(eng, esi) {
  const m = eng.m, b = UNITS + esi, p = eng.patrols.get(esi);
  const t = p.pts[p.i % p.pts.length];
  m.w16(b + U.DSTX, (t.x << 5) & 0xffff); m.w16(b + U.DSTY, (t.y << 5) & 0xffff);
  m.w8(b + U.STATE, 0x36);
  call(eng, 0x1db94, { esi });
}

// ---- состояния 0x3x: приказы патруля, ход по маршруту и поиск врага под ногами
const orig18e89 = F[0x18e89];
F[0x18e89] = (eng, r) => {
  const m = eng.m, esi = r.esi, b = UNITS + esi;
  if (eng.patrol === false || m.u8(b + U.TYPE) >= 0xe) return orig18e89(eng, r);
  const st = m.u8(b + U.STATE);

  if (st === ORDER_POINT) {                       // «добавить точку»: копим маршрут и ждём
    const p = карта(eng).get(esi) || { pts: [], i: 0 };
    if (p.готов) { p.pts = []; p.готов = false; }  // первая точка после прошлого маршрута — начинаем заново
    if (p.pts.length < MAX_POINTS)
      p.pts.push({ x: (m.u16(b + U.DSTX) >>> 5) & 0xff, y: (m.u16(b + U.DSTY) >>> 5) & 0xff });
    p.i = 0; карта(eng).set(esi, p);
    m.w8(b + U.STATE, 0x3f);                       // стоим на месте, пока игрок расставляет точки
    return orig18e89(eng, r);
  }
  const p = eng.patrols?.get(esi);
  if (st === ORDER_GO) {                           // «пошёл»
    if (!p || !p.pts.length) { m.w8(b + U.STATE, 0x3f); return orig18e89(eng, r); }
    p.готов = true; p.i = 0;
    кТочке(eng, esi);
    return;
  }
  if (!p || !p.готов) return orig18e89(eng, r);

  if (st === 0x37) { if (!наТайле(m, b)) return; if (собратьРядом(eng, esi)) return; кТочке(eng, esi); return; }   // из боя: сначала добыча, потом дальше
  // Погоня (0x30..0x33): проверяем поводок. Считаем по ближайшей точке маршрута, а не по посту:
  // пост в патруле переставляется под ноги на каждой клетке и сам по себе ничего не ограничивает.
  if (st >= 0x30 && st <= 0x33 && наТайле(m, b)) {
    const cx = m.u16(b + U.X) >>> 5, cy = m.u16(b + U.Y) >>> 5;
    let d0 = 1e9;
    for (const т of p.pts) { const d = Math.max(Math.abs(т.x - cx), Math.abs(т.y - cy)); if (d < d0) d0 = d; }
    // Из рукопашной не уходим, даже если поводок кончился: развернуться перед зверем — значит
    // получить несколько ударов в спину бесплатно. На замере (tools/patrol_test.mjs) поводок без
    // этой оговорки просто убивал бойца: он бросал бой в упор и умирал по дороге назад.
    const цель = m.u32(b + 0x47) >>> 0;
    const рядомВраг = цель && !(m.u8(UNITS + цель + U.FLAGS5B) & 1)
      && Math.max(Math.abs((m.u16(UNITS + цель + U.X) >>> 5) - cx), Math.abs((m.u16(UNITS + цель + U.Y) >>> 5) - cy)) <= 1;
    if (d0 > ПОВОДОК && !рядомВраг) { приказСебе(eng, esi, 0x37); return; }
  }
  if (st === 0x38) { p.i = (p.i + 1) % p.pts.length; p.стоял = 0; кТочке(eng, esi); return; }   // дошёл — следующая точка
  // Сторож застревания. Считаем только вне боя: в схватке юнит и должен стоять на месте.
  if (st < 0x30 || st > 0x33) {
    const xy = (m.u16(b + U.X) << 16) | m.u16(b + U.Y);
    if (xy === p.былXY) {
      if ((p.стоял = (p.стоял || 0) + 1) > СТОЯЛ_ХВАТИТ) {
        p.стоял = 0; p.i = (p.i + 1) % p.pts.length;   // эта точка не даётся — пробуем следующую
        кТочке(eng, esi); return;
      }
    } else { p.былXY = xy; p.стоял = 0; }
  }
  if (st === 0x36 && наТайле(m, b)) {
    // Пост — под ноги: от него считается спиральный поиск, иначе патруль осматривает пустое место.
    m.w8(b + 0x44, (m.u16(b + U.X) >>> 5) & 0xff); m.w8(b + 0x45, (m.u16(b + U.Y) >>> 5) & 0xff);
    const f = call(eng, 0x1a531, { esi, ebx: SCAN });
    if ((f.edi >>> 0) !== 0) return call(eng, 0x19fdf, { esi, edi: f.edi >>> 0 });
  }
  return orig18e89(eng, r);
};

// ---- патруль снимает только настоящий приказ игрока; со смертью юнита он снимается тоже
//
// Раньше сторож стоял в 0x18154 и смотрел на БАЙТ приказа: всё, чего нет в белом списке, считалось
// приказом человека. Список угадать нельзя — движок в схватке сам пишет юниту 0x30..0x33, и стоило
// охране погнаться за целью «не тем» кодом, как маршрут молча стирался. Именно на это жаловался
// тестер: «после стычки юнит должен возвращаться в патруль».
//
// Теперь точка одна и честная: все приказы извне (клик игрока, сеть, скриптовый ИИ) проходят через
// 0x14895 — там и снимаем маршрут, если приказ не патрульный. Внутренние решения самого патруля
// (приказСебе) идут мимо 0x14895 и маршруту не вредят.
const origПриказ = F[0x14895];
F[0x14895] = (eng, r) => {
  const код = r.eax & 0xff, esi = r.esi;
  if (eng.patrols?.has(esi) && код !== ORDER_POINT && код !== ORDER_GO) eng.patrols.delete(esi);
  return origПриказ(eng, r);
};

const orig18154 = F[0x18154];
F[0x18154] = (eng, r) => {
  const m = eng.m, esi = r.esi, b = UNITS + esi;
  const st = m.u8(b + U.STATE);
  if (eng.patrols?.has(esi) && (st === 0x60 || st === 0x6f)) eng.patrols.delete(esi);   // юнит погиб
  return orig18154(eng, r);
};

// ---- 0x1a34c «дело сделано, стоять на посту». Для патрульного это конец схватки: сам приказ
// (0x3f) означал бы «игрок приказал охранять» и снимал маршрут — а человек ничего не приказывал.
// Поэтому подменяем: сначала подобрать выпавшее рядом, потом дальше по маршруту.
const orig1a34c = F[0x1a34c];
F[0x1a34c] = (eng, r) => {
  const esi = r.esi, p = eng.patrols?.get(esi);
  if (eng.patrol === false || !p || !p.готов) return orig1a34c(eng, r);
  if (собратьРядом(eng, esi)) return;
  приказСебе(eng, esi, 0x37);
};
