// Режим «камикадзе» (наше; в оригинале его нет).
//
// Что делает. Юнит перестаёт ждать приказов и идёт убивать всё подряд: берёт ближайшую живую
// цель, бьёт её, а как только она мертва — тут же следующую ближайшую, и так пока сам жив. Это
// не «охрана» (та ждёт врага у себя под носом) и не «атака цели» (та кончается вместе с целью).
//
// Кого считает целью. Всё живое, что не своё: чужие племена и дикое зверьё. Здания трогаем
// только когда живых существ рядом не осталось вовсе — иначе камикадзе застревает у стены, пока
// его расстреливают. Ищем в пределах ДАЛЬНОСТЬ клеток, чтобы не гнать через всю карту.
//
// Как это уживается с сетью. Режим включается нашим приказом через общую очередь (inject.НАШИ),
// то есть приходит всем машинам одинаково; сам список камикадзе едет в снимке
// (lockstep.состояниеJS) и в записи партии. Выбор цели детерминирован: ближайшая по расстоянию,
// при равенстве — с меньшим номером в списке юнитов, никакой случайности.
//
// Когда снимается: юнит погиб, игрок отдал любой свой приказ, или нажал клавишу ещё раз.
import { G, U, UNITS } from '../mem.js';
import { F } from '../fn.js';
import { приказ, КОД, НАШИ, наШаг, установить } from './inject.js';

// Код нашего приказа. Заняты: 0xf1/0xf2 планы стройки, 0xf3 «следовать», 0xf4..0xf7 очередь
// приказов по Shift. Взял 0xf8 — и проверяю занятость при регистрации: сначала я поставил 0xf4,
// его молча перекрыл orderqueue.js, камикадзе не работал, а шаг «идти» из очереди Shift ушёл бы
// в никуда. Тихо такое ловится только отладкой, поэтому пусть падает сразу.
export const КАМИКАДЗЕ = 0xf8;
const ШАГ_ПРОВЕРКИ = 8;                  // раз в столько шагов смотрим, жива ли цель
const ДАЛЬНОСТЬ = 40;                    // клеток: дальше не ищем, чтобы не бежать через всю карту

/** Кто сейчас в режиме камикадзе: юнит → его текущая цель. */
const карта = (eng) => (eng.kamikaze || (eng.kamikaze = new Map()));
/** Все камикадзе (обвязка рисует над ними пометку). */
export const бешеные = (eng) => eng.kamikaze || new Map();
/** Юнит сейчас в режиме камикадзе. */
export const включён = (eng, юнит) => !!eng.kamikaze?.has(юнит);
/** Список камикадзе в снимок локстепа и в запись партии. */
export function dump(eng) { return [...(eng.kamikaze || new Map())].map(([i, с]) => [i, с.цель]); }
/** Список камикадзе из снимка. */
export function restore(eng, список) {
  const c = карта(eng); c.clear();
  for (const [i, цель] of список || []) c.set(i, { цель: цель | 0 });
}
/** Выключить режим у юнита. */
export function снять(eng, юнит) { eng.kamikaze?.delete(юнит); }

/** Юнит жив и не труп. */
const жив = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.STATE) !== 0x60;
/** Клетка юнита. */
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });

/** Ближайшая живая цель для юнита: сперва существа, здания — только если существ нет. */
function ближайшая(eng, m, i) {
  const мой = m.u8(UNITS + i + U.OWNER); const я = кл(m, i);
  let лучший = 0, лучшееD = 1e9, дом = 0, домD = 1e9;
  for (let c = m.u32(G.unitHead); c; c = m.u32(UNITS + c + U.NEXT)) {
    if (c === i || !жив(m, c)) continue;
    const вл = m.u8(UNITS + c + U.OWNER); if (вл === мой) continue;
    const т = m.u8(UNITS + c + U.TYPE); if (т >= 24 && т <= 25) continue;        // растения не враги
    const п = кл(m, c); const d = Math.max(Math.abs(п.x - я.x), Math.abs(п.y - я.y));
    if (d > ДАЛЬНОСТЬ) continue;
    if (т >= 0x1a) { if (d < домD) { домD = d; дом = c; } continue; }
    if (d < лучшееD) { лучшееD = d; лучший = c; }
  }
  return лучший || дом;
}

/** Приказ игрока: включить или выключить режим. Через 0x14895 — чтобы уйти в сеть и в запись. */
export const приказКамикадзе = (eng, юнит) =>
  F[0x14895](eng, { eax: КАМИКАДЗЕ, esi: юнит, edi: 0, edx: 0, ebx: 0 });

if (НАШИ.has(КАМИКАДЗЕ)) throw new Error('код приказа 0x' + КАМИКАДЗЕ.toString(16) + ' уже занят другим модулем');
НАШИ.set(КАМИКАДЗЕ, (eng, з) => {
  const m = eng.m, юнит = з.юнит;
  if (!жив(m, юнит)) return;
  const т = m.u8(UNITS + юнит + U.TYPE); if (т < 1 || т > 13) return;            // только свои бойцы
  const c = карта(eng);
  if (c.has(юнит)) { c.delete(юнит); return; }                                   // второе нажатие — отбой
  c.set(юнит, { цель: 0 });
});

/** Шаг режима: цель мертва или её нет — берём следующую ближайшую. */
export function шаг(eng) {
  const c = eng.kamikaze; if (!c || !c.size) return;
  const m = eng.m;
  if ((m.u32(G.step) % ШАГ_ПРОВЕРКИ) !== 0) return;
  for (const [i, с] of [...c]) {
    if (!жив(m, i)) { c.delete(i); continue; }
    if (жив(m, с.цель)) {
      const ст = m.u8(UNITS + i + U.STATE);
      if (ст >= 0x10 && ст <= 0x1f) continue;                                    // уже дерётся с ней
      const п = кл(m, с.цель);
      приказ(eng, i, КОД.АТАКА, с.цель, п.x << 5, п.y << 5);                     // догоняем, если отстал
      continue;
    }
    const цель = ближайшая(eng, m, i);
    if (!цель) { с.цель = 0; continue; }                                         // рядом никого — ждём
    с.цель = цель; const п = кл(m, цель);
    приказ(eng, i, КОД.АТАКА, цель, п.x << 5, п.y << 5);
  }
}

наШаг.push(шаг);
установить();
