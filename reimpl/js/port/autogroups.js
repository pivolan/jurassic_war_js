// Автоматическая привязка новых юнитов к цифрам 1..9 и 0 (наше, в оригинале такого нет).
//
// Зачем. В оригинале группы назначаются только руками, Ctrl+цифрой, и до первой такой привязки
// клавиши 1..0 не делают ничего. На деле игрок почти всегда хочет ровно одного: чтобы каждый
// свежий боец сразу оказался под своей цифрой, а сбоку висела его иконка со здоровьем — как в
// современных стратегиях. Правило делает именно это и ничего больше.
//
// Правило. У каждого цвета не больше ДЕСЯТИ занятых цифр. Пока свободные цифры есть, очередной
// живой юнит без группы получает наименьшую свободную. Умер юнит — его цифра освобождается и
// достанется следующему. Больше десяти юнитов — остальные остаются без цифры, их в колонке нет.
// Ручную привязку правило не трогает: занятая цифра считается занятой, кем бы её ни заняли.
//
// Только своим. Сначала цифры раздавались всем цветам подряд — компьютеру они не мешают, а код
// короче. Оказалось, мешают: штатный выбор группы (0x11093) владельца НЕ проверяет и берёт первый
// же юнит с этой цифрой в списке. Если раньше по списку шёл чужой боец с той же цифрой, нажатие
// выделяло врага, и юнит «не выделялся нормально» — жалоба на телепортёров-скаутов. В оригинале
// такого быть не могло: группы там ставил только человек, у чужих байт всегда нулевой.
//
// Сетевая игра от этого не страдает: байт +0x07 целиком исключён из хеша сверки локстепа
// (lockstep.хеш: «интерфейсный»), поэтому у каждого игрока свои цифры — и это нормально.
import { G, U, UNITS } from '../mem.js';
import { F } from '../fn.js';
import { наШаг, установить } from './inject.js';

const SEL = 0x31adc;                     // кого панель считает выбранным (UI.sel в port/input.js)

// Второе нажатие той же цифры наводит камеру на отряд. В оригинале для этого была отдельная
// комбинация (Alt+цифра, 0x1107b), но привычка из современных стратегий другая: жмёшь цифру —
// выбрал, жмёшь ещё раз — смотришь. Оборачиваем штатный выбор группы, чтобы это работало и с
// клавиатуры, и с колонки отрядов (она зовёт ту же функцию).
// Камера (0x31ae8/0x31aec) в хеш локстепа не входит — соседний по адресу диапазон начинается с
// 0x31af0, — так что на сетевую партию это не влияет.
const ориг11093 = F[0x11093];
F[0x11093] = (eng, r) => {
  const m = eng.m, al = r.eax & 0xff;
  const было = m.u32(SEL);
  const таЖе = было && (m.u8(UNITS + было + U.F07) & 0x80) && (m.u8(UNITS + было + U.F07) & 0x7f) === al;
  const из = ориг11093(eng, r);
  const стало = m.u32(SEL);
  if (таЖе && стало) F[0x1113c](eng, { esi: стало });
  return из;
};

export const ПЕРИОД = 8;                 // шагов между проверками: чаще незачем, реже — заметно
export const ЦИФР = 10;                  // 1..9 и 0 (в памяти это 1..10)

let вкл = true;
/** Включить или выключить правило (одинаково у всех: приходит в параметрах старта). */
export function задать(_eng, значение) { вкл = !!значение; }
/** Включена ли автопривязка цифр к новым юнитам. */
export const включено = () => вкл;

/** Раздача цифр: свободные номера 1..9 и 0 достаются своим бойцам без группы. */
export function шаг(eng) {
  if (!вкл) return;
  const m = eng.m;
  if ((m.u32(G.step) % ПЕРИОД) !== 0) return;
  const я = m.u8(G.humanOwner);
  let маска = 0;                         // какие цифры уже заняты у человека
  const ничьи = [];                      // его же юниты без цифры, в порядке списка
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== я) continue;
    const тип = m.u8(UNITS + i + U.TYPE);
    // ЗДАНИЮ ЦИФРА НЕ ПОЛОЖЕНА, И СТАРУЮ НАДО СНЯТЬ. Конструктор — обычный юнит (тип 4), цифру он
    // получает наравне со всеми, а потом ПРЕВРАЩАЕТСЯ в дом (js/port/economy.js, 0x1d1cf): тип
    // меняется, а байт +0x07 остаётся прежним. В итоге дом сидит под цифрой: занимает номер,
    // светится в колонке отрядов слева и выделяется нажатием этой цифры. В кампании это было
    // незаметно, потому что строить до второй стадии не приходилось; на стенде вылезло сразу.
    if (тип < 1 || тип > 13) {
      if (тип >= 0x1a && (m.u8(UNITS + i + U.F07) & 0x7f)) m.w8(UNITS + i + U.F07, m.u8(UNITS + i + U.F07) & 0x80);
      continue;                                                        // звери и здания в раздаче не участвуют
    }
    const г = m.u8(UNITS + i + U.F07) & 0x7f;
    if (г >= 1 && г <= ЦИФР) маска |= 1 << г;
    else if (!г) ничьи.push(i);
  }
  for (const i of ничьи) {
    let г = 0;
    for (let k = 1; k <= ЦИФР; k++) if (!(маска & (1 << k))) { г = k; break; }
    if (!г) break;                       // все десять цифр заняты — остальные остаются без номера
    маска |= 1 << г;
    m.w8(UNITS + i + U.F07, (m.u8(UNITS + i + U.F07) & 0x80) | г);
  }
}

наШаг.push(шаг);
установить();
