import { F } from './fn.js'; import { G, U, UNITS } from './mem.js';
F[0x15f86] = (eng) => { eng.f_15f86(); };
F[0x20469] = (eng) => ({ edx: eng.rand_raw() });

// FUN_000204a6: rand(n) с n=[393a8], состояние [393a4], подмешивает таймер BIOS [0x46c]
F[0x204a6] = (eng) => {
  const m = eng.m; const n = m.u32(0x393a8); if (n === 0) return { edx: 0 };
  const eax = (m.u32(0x393a4) + m.u32(0x46c)) >>> 0; const q = Math.floor(eax / n) >>> 0, r = eax % n;
  m.w32(0x393a4, (m.u32(0x393a4) + q) >>> 0); m.w32(0x393a4, (m.u32(0x393a4) ^ m.u32(0x393ac + (q >>> 28))) >>> 0);
  return { edx: r };
};
