// Широкое окно карты (наше): вывод игры переезжает в отдельный большой кадр.
//
// Зачем. У оригинала кадр 640×480, и окно карты в нём — 512×480 (16×15 клеток) при показанной
// панели. На сегодняшнем экране это крошечный кусок мира. Прежний «зум» проблему не решал: он
// не увеличивает обзор, а ПРОРЕЖИВАЕТ пиксели уже отрисованной сцены (каждый z-й), поэтому
// картинка мылится, стоит дорого (до 192 проходов сцены) и включена только зрителю.
//
// Как. Ничего не масштабируем — просто делаем окно карты больше и рисуем 1:1. Это возможно
// потому, что движок нигде не зашивает размер: и «база вывода» (0x488c0 для спрайтов, 0x46f00
// для тайлов), и размер окна (0x488c4/0x488c8), и число клеток (0x31af0/0x31af4), и таблица
// смещений строк — обычные переменные памяти, которые он честно читает. Панель рисуется по
// 0x488c4, то есть сразу за окном карты, и уезжает вправо сама.
//
// Что НЕ трогаем. Кадр меню, заставок и окон (FB = 0x1235f4, 640×480) остаётся на месте и живёт
// своей жизнью: `ui/shell.js` и `ui/screen.js` пишут в него напрямую и целыми блоками. Поэтому
// сломать меню эта правка не может — оно работает с другим буфером.
//
// Где лежит широкий кадр. За концом исходной памяти (`Mem.ХВОСТ`), то есть вне области
// симуляции 0x30000..0x123000: в хеш локстепа не входит, в снимок не едет. Диапазон
// 0x488c0..0x488f0 в `js/net/lockstep.js` и так помечен зрительским, так что у игроков одной
// сетевой партии могут быть разные размеры окна — партия не разъедется.
import { FB, ROWS, VW, VH, XBASE, сПанельнойБазой, сеткаЮнитов } from './scene.js';
import { ХВОСТ } from '../mem.js';

// Раскладка хвоста памяти: сперва наши указатели, потом таблица строк, потом сам кадр.
export const УК_РЯДЫ = ХВОСТ;                 // u32: адрес действующей таблицы смещений строк
export const УК_ШИРИНА = ХВОСТ + 4;           // u32: ширина кадра в байтах (он же шаг строки)
export const УК_ВЫСОТА = ХВОСТ + 8;           // u32: высота кадра в строках
const РЯДЫ_ШИРОКИЕ = ХВОСТ + 0x40;            // таблица строк широкого кадра
export const МАКС_В = 1600;                   // строк максимум: столько мест под таблицу
const КАДР = РЯДЫ_ШИРОКИЕ + МАКС_В * 4;       // сам широкий кадр
export const МАКС_Ш = 2560;
// Сетка «кто в какой клетке» для слоя юнитов (0x24d70). В оригинале она фиксированная: 24×23
// клетки и четыре массива по 552 записи — этого хватало на окно 512×480 с запасом. Для широкого
// окна клеток нужно вчетверо больше, поэтому массивы свои, сразу за кадром.


const ТАЙЛ = 32;
const ПАНЕЛЬ = 128;                           // ширина боковой панели оригинала, 640 − 512
const БУФЕР_ТЕКСТА = 0x46f10;                 // куда пишет шрифт игры (js/render/text.js)
const БАЗА_МИНИКАРТЫ = 0x3e6e8;               // у мини-карты своя база вывода (js/render/hud.js)
const КАРТА_Ш = 0x31af8, КАРТА_В = 0x31afc;   // размер карты в клетках
const КАМ_X = 0x31ae8, КАМ_Y = 0x31aec, КАМ_МАКС_X = 0x31b00, КАМ_МАКС_Y = 0x31b04;

/**
 * Пересчитать предел камеры под новый размер окна и подтянуть её саму, если она оказалась за ним.
 * Предел считает загрузчик миссии (js/port/loader.js) по числу клеток в окне, а окно у нас
 * меняется уже после загрузки — без пересчёта прыжок по мини-карте уводил камеру за нижний край
 * карты, и под ней оставалась чёрная полоса.
 */
function пределыКамеры(m) {
  if (!m.u32(КАРТА_Ш)) return;                                        // миссия ещё не загружена
  const мx = Math.max(0, (m.u32(КАРТА_Ш) - m.u32(0x31af0))) << 5;
  const мy = Math.max(0, (m.u32(КАРТА_В) - m.u32(0x31af4))) << 5;
  m.w32(КАМ_МАКС_X, мx); m.w32(КАМ_МАКС_Y, мy);
  if (m.u32(КАМ_X) > мx) m.w32(КАМ_X, мx);
  if (m.u32(КАМ_Y) > мy) m.w32(КАМ_Y, мy);
}

/** Действующая таблица смещений строк: широкая, если включено, иначе родная. */
export const ряды = (m) => m.u32(УК_РЯДЫ) || ROWS;
/** Действующая база вывода игрового кадра. */
export const кадр = (m) => m.u32(XBASE);
/** Включено ли широкое окно. */
export const широко = (m) => m.u32(УК_РЯДЫ) !== 0;

/** Размер игрового кадра целиком (с панелью). */
export const размер = (m) => широко(m) ? { ш: m.u32(УК_ШИРИНА), в: m.u32(УК_ВЫСОТА) } : { ш: 640, в: 480 };

// Что было до нас — чтобы вернуть в точности, а не «как мы думаем, было».
let было = null;
function запомнить(m) {
  if (было) return;
  было = { xbase: m.u32(XBASE), тайлбаза: m.u32(0x46f00), текст: m.u32(БУФЕР_ТЕКСТА), мини: m.u32(БАЗА_МИНИКАРТЫ), vw: m.u32(VW), vh: m.u32(VH),
           клетокX: m.u32(0x31af0), клетокY: m.u32(0x31af4), краяX: m.u32(0x46ffc) };
}

/**
 * Включить широкое окно: кадр `ш`×`в` пикселей целиком (панель входит в ширину).
 * Размеры округляются вниз до целых клеток по 32 пикселя — иначе движок рисует полтайла и
 * оставляет мусорную полосу справа и снизу.
 */
export function включить(m, ш, в) {
  запомнить(m);
  ш = Math.max(640, Math.min(МАКС_Ш, ш | 0)); в = Math.max(480, Math.min(МАКС_В, в | 0));
  const окноШ = Math.floor((ш - ПАНЕЛЬ) / ТАЙЛ) * ТАЙЛ;               // ширина карты, кратная клетке
  const окноВ = Math.floor(в / ТАЙЛ) * ТАЙЛ;
  ш = окноШ + ПАНЕЛЬ; в = окноВ;
  for (let y = 0; y < в; y++) m.w32(РЯДЫ_ШИРОКИЕ + y * 4, y * ш);     // своя таблица строк
  m.w32(УК_РЯДЫ, РЯДЫ_ШИРОКИЕ); m.w32(УК_ШИРИНА, ш); m.w32(УК_ВЫСОТА, в);
  m.w32(XBASE, КАДР); m.w32(0x46f00, КАДР); m.w32(БУФЕР_ТЕКСТА, КАДР);  // спрайты, тайлы и шрифт — в новый кадр
  // Мини-карта живёт в панели и пишет по своей базе, минуя 0x488c0. Её координаты тоже отсчитаны
  // от кадра 640, поэтому базу сразу сдвигаем к правому краю — отдельной обёртки не нужно.
  m.w32(БАЗА_МИНИКАРТЫ, КАДР + (ш - 640));
  m.w32(VW, окноШ); m.w32(VH, окноВ);
  m.w32(0x31af0, окноШ / ТАЙЛ); m.w32(0x31af4, окноВ / ТАЙЛ);
  m.w32(0x46ffc, окноШ - 1);                                           // правый край прокрутки
  пределыКамеры(m);
  m.b.fill(0, КАДР, КАДР + ш * в);
  return { ш, в, окноШ, окноВ };
}

// Сдвиг базы для панели живёт в scene.js (иначе получился бы круговой импорт), здесь только
// пробрасываем наружу — звать его удобнее отсюда, вместе с остальным про широкое окно.
export { сПанельнойБазой, сеткаЮнитов };

/**
 * Перенести середину широкого кадра в родной кадр меню (FB, 640×480). Нужно для внутриигрового
 * меню: оболочка замораживает именно FB и рисует колесо поверх него, а в широком режиме игра туда
 * ничего не пишет — без этого за меню оставался бы чёрный экран. Берём ЛЕВЫЙ ВЕРХНИЙ угол окна:
 * камера отсчитывается именно от него, поэтому там всегда то, на что игрок смотрел, а в середине
 * широкого окна на большой карте обычно ещё туман.
 */
export function вКадрМеню(m) {
  if (!широко(m)) return;
  const ш = m.u32(УК_ШИРИНА), кадр = m.u32(XBASE);
  const x0 = 0, y0 = 0;
  for (let y = 0; y < 480; y++) {
    const из = кадр + (y0 + y) * ш + x0;
    m.b.copyWithin(FB + m.u32(ROWS + y * 4), из, из + 640);
  }
}

/** Вернуть всё как было: игра снова рисует в родной кадр 640×480. */
export function выключить(m) {
  if (!было) { m.w32(УК_РЯДЫ, 0); return; }
  m.w32(УК_РЯДЫ, 0); m.w32(УК_ШИРИНА, 0); m.w32(УК_ВЫСОТА, 0);
  m.w32(XBASE, было.xbase); m.w32(0x46f00, было.тайлбаза); m.w32(БУФЕР_ТЕКСТА, было.текст);
  m.w32(БАЗА_МИНИКАРТЫ, было.мини);
  m.w32(VW, было.vw); m.w32(VH, было.vh);
  m.w32(0x31af0, было.клетокX); m.w32(0x31af4, было.клетокY);
  m.w32(0x46ffc, было.краяX);
  пределыКамеры(m);
}
