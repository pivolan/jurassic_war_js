// Сборка своих сцен прямо в памяти движка (наше; в игре таких карт нет).
//
// Общая часть стенда поиска пути (js/ui/pathscenes.js) и тренировочных арен ИИ (js/ai/arena.js):
// карта нужного размера, чистое поле, деревья, скалы, вода, метка цели, расстановка юнитов.
// От загруженной миссии берутся набор тайлов, спрайты и палитра — всё остальное переписывается.
//
// Деревья — не юниты, а украшения карты: в слове BG старшие пять бит хранят номер украшения,
// 0x24d70 рисует его спрайтом 0xaf7+n вместе с юнитами, сортируя по ряду. Номера 1..3 —
// лиственные деревья, 4..6 — пальмы, 7 — каменная арка, 8..9 — кактусы. Проходимость от
// украшения не зависит, поэтому клетка отдельно помечается занятой в BI — так же, как её
// занимает растение оригинала (владелец 8, то есть 9<<2 в BI, нулевой ниббл MO).
//
// Растение оригинала живёт с состоянием 0x10/0x20 и приказом 0x3f, кадр ему крутит своя ветка
// автомата. Заводить препятствие как бойца (состояние 0x3f) нельзя: на первом же шаге его
// прогонит человеческий автомат и подменит спрайт — на карте появятся обломки чужих спрайтов.
import { call } from '../fn.js';
import { G, U, UNITS, BI, MO, BG } from '../mem.js';
import { FB, ROWS, ряды } from '../render/scene.js';

// Тайлы набора третьей миссии
export const ГРУНТ = 394;      // сухая трава, проходимо
export const КАМЕНЬ = 567;     // бурая скала, стена
export const ВОДА = 331;       // чистая вода, стена
export const ПЕСОК = 325;      // светлый песок, проходимо — из него крест метки
export const КРАСНЫЙ = 216;    // растрескавшаяся красная земля, проходимо — центр метки
export const ДЕРЕВЬЯ = [3, 1, 2];   // номера украшений-деревьев, вперемежку для живости

/** Номер клетки из координат, с заворотом на 256 — как адресует сетку сам движок. */
export const клетка = (x, y) => ((x + 256) & 0xff) + (((y + 256) & 0xff) << 8);

/** Занять клетку так, как её занимает дерево: владелец 8 (ничей) в BI, ниббл MO пустой. */
export function занять(m, x, y) {
  const c = клетка(x, y);
  m.w8(BI + c, (m.u8(BI + c) & 3) | (9 << 2));
}

/** Поставить юнита в клетку и завести его «на посту»: приказов нет, цель под ногами. */
export function поставить(eng, i, x, y) {
  const m = eng.m;
  m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) & 0xfe);   // показать
  m.w16(UNITS + i + U.X, x << 5); m.w16(UNITS + i + U.Y, y << 5);
  m.w16(UNITS + i + U.DSTX, x << 5); m.w16(UNITS + i + U.DSTY, y << 5);
  m.w8(UNITS + i + U.STATE, 0x3f); m.w8(UNITS + i + U.ORDER, 0xff); m.w8(UNITS + i + U.ATKCTR, 0);
  m.w32(UNITS + i + U.TARGET, 0);
  m.w8(UNITS + i + U.FLAGS50, 0); m.w8(UNITS + i + 0x40, 0); m.w8(UNITS + i + U.FX43, 0);
  m.w8(UNITS + i + 0x44, x); m.w8(UNITS + i + 0x45, y);
  m.w8(UNITS + i + 0x53, x); m.w8(UNITS + i + 0x54, y);
  call(eng, 0x1e56d, { esi: i, edx: x << 5, ebx: y << 5 });          // отметить клетку в BI/MO
}

/**
 * Пустая сцена размером W×H: карта, чистое поле, камера в нуле, всё разведано, юниты спрятаны.
 * Возвращает списки живых записей юнитов по типам — из них сцена набирает бойцов.
 * @param {boolean} чисто — убрать панель, мини-карту и полосы статов (для стенда и арены).
 */
export function основа(eng, W, H, чисто = true) {
  const m = eng.m;
  m.w32(G.mapW, W); m.w32(G.mapH, H);
  m.w32(0x31af0, W); m.w32(0x31af4, H);            // окно карты в клетках
  m.w32(0x488c4, W * 32); m.w32(0x488c8, H * 32);  // и в точках
  m.w32(0x46ffc, W * 32 - 1);                      // правый край отсечения текста
  if (чисто) {
    // Ничего лишнего поверх карты: ни панели, ни мини-карты, ни счётчиков еды.
    m.w8(0x31ae0, m.u8(0x31ae0) & ~0x0f);          // панель, мини-карта и её режимы — прочь
    m.w8(0x31ac7, 0);                              // полосы статов не рисуем
    m.w32(0x41910, 0x41938);                       // всплывающее сообщение снять
    for (let y = 0; y < 480; y++) m.b.fill(0, FB + m.u32(ряды(m) + y * 4), FB + m.u32(ряды(m) + y * 4) + 640);
  }
  m.w32(0x31b7c, 0);                               // предметы на земле убрать из списка
  for (let p = 0; p < 8; p++) m.w32(0x31c48 + p * 4, 0);   // складов нет — строка FOODS не рисуется
  // Счётчики «сколько дикого зверья доразвести» (0x33358 + тип*4): иначе движок исправно
  // подселяет зверей по краю карты, и через полминуты по краю сцены идёт стадо.
  for (let a = 0x33358; a < 0x333c8; a += 4) m.w32(a, 0);
  m.w32(0x31ae8, 0); m.w32(0x31aec, 0);            // камера в нуле
  m.w32(0x31b00, 0); m.w32(0x31b04, 0);            // и двигать её некуда
  // Кроме самой сцены чистим поля вокруг неё: старшие пять бит слова карты — украшение, и
  // рисуется оно на две-три клетки дальше видимого края (деревья старой карты свешивались внутрь).
  for (let y = -2; y <= H + 5; y++) for (let x = -2; x <= W + 5; x++) {
    m.w16(BG + (((y + 256) & 0xff) << 9) + (((x + 256) & 0xff) * 2), ГРУНТ);
    const c = клетка(x, y); m.w8(BI + c, 1); m.w8(MO + c, 0);
  }
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    m.w16(BG + (y << 9) + x * 2, ГРУНТ);
    const c = клетка(x, y);
    m.w8(BI + c, 1);                               // клетка свободна и разведана
    m.w8(MO + c, 0);
  }
  // Кайма разведанного вокруг карты: код тумана складывается из клетки и четырёх соседей, и без
  // каймы по краю рисовался бы туман — а тайлы тумана в этом наборе выглядят как пальмы.
  for (let x = -1; x <= W; x++) { m.w8(BI + клетка(x, -1), 1); m.w8(BI + клетка(x, H), 1); }
  for (let y = -1; y <= H; y++) { m.w8(BI + клетка(-1, y), 1); m.w8(BI + клетка(W, y), 1); }

  const поТипам = new Map();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) | 1);    // спрятать всех
    m.w8(UNITS + i + U.F07, m.u8(UNITS + i + U.F07) & 0x7f);
    m.w16(UNITS + i + U.FOOD, 0);                  // и «Foods=» внизу тоже не нужен
    const t = m.u8(UNITS + i + U.TYPE);
    if (!поТипам.has(t)) поТипам.set(t, []);
    поТипам.get(t).push(i);
  }
  return { W, H, поТипам, дерево: 0 };
}

/** Свободные записи юнитов нужного типа (первый попавшийся из списка предпочтений). */
export function запас(сц, типы) {
  for (const t of типы) { const a = сц.поТипам.get(t); if (a && a.length) return a; }
  return [];
}

/** Положить тайл t, если точка внутри сцены. */
export const тайл = (сц, m, x, y, t) => {
  if (x >= 0 && y >= 0 && x < сц.W && y < сц.H) m.w16(BG + (y << 9) + x * 2, t);
};
/** Залить прямоугольник непроходимым камнем (стенка сцены). */
export const камень = (eng, сц, x0, y0, x1, y1) => {
  const m = eng.m;
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) { тайл(сц, m, x, y, КАМЕНЬ); m.w8(BI + клетка(x, y), 1); }
};
/** Залить прямоугольник водой: тоже непроходима, но выглядит иначе. */
export const вода = (eng, сц, x0, y0, x1, y1) => {
  const m = eng.m;
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) { тайл(сц, m, x, y, ВОДА); m.w8(BI + клетка(x, y), 1); }
};

/** Дерево в клетке: украшение поверх тайла плюс занятая клетка. */
export function дерево(eng, сц, x, y) {
  const m = eng.m;
  if (x < 0 || y < 0 || x >= сц.W || y >= сц.H) return false;
  const n = ДЕРЕВЬЯ[(сц.дерево++) % ДЕРЕВЬЯ.length];
  m.w16(BG + (y << 9) + x * 2, (m.u16(BG + (y << 9) + x * 2) & 0x7ff) | (n << 11));
  занять(m, x, y);
  return true;
}

/** Метка цели: крест из песка и красный центр. Возвращает саму точку. */
export function метка(eng, сц, x, y) {
  const m = eng.m;
  for (const [dx, dy] of [[0, 0], [1, 0], [-1, 0], [0, 1], [0, -1], [2, 0], [-2, 0], [0, 2], [0, -2]])
    тайл(сц, m, x + dx, y + dy, ПЕСОК);
  тайл(сц, m, x, y, КРАСНЫЙ);
  return { x, y };
}

/** Свободна ли клетка (нет ни юнита, ни здания, ни дерева). */
export const свободна = (m, x, y) => (m.u8(BI + клетка(x, y)) >> 2) === 0;
