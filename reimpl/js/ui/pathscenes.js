// Испытательные сцены для поиска пути (наше; в игре таких карт нет).
//
// Общая механика сборки сцен — js/ui/scenebuild.js (карта, деревья, скалы, вода, метка,
// расстановка юнитов). Здесь только сами пять сцен и отряд под них.
//
// Размер карты равен окну без боковой панели: 20×15 клеток = 640×480 точек, камера в нуле.
// Так вся сцена целиком видна на экране и ничего не надо прокручивать.
import { G, U, UNITS } from '../mem.js';
import { основа, запас, поставить, дерево, камень, вода, метка, свободна, клетка } from './scenebuild.js';

export const МИССИЯ = 2, ПЛЕМЯ = 0;      // на чём собираем: сухие степи и много живности
const БОЕЦ = [5, 1];                     // тип 5 — маг в красном, он виднее простого воина типа 1

const W = 20, H = 15;
export const РАЗМЕР = { w: W, h: H };

/** Отряд игрока: ставим и сразу выделяем — чтобы можно было просто ткнуть в цель. */
function отряд(eng, сц, точки) {
  const m = eng.m;
  const свои = запас(сц, БОЕЦ);
  точки.forEach(([x, y], k) => {
    const i = свои[k];
    if (i === undefined) return;
    m.w8(UNITS + i + U.OWNER, m.u8(G.humanOwner));
    поставить(eng, i, x, y);
    m.w8(UNITS + i + U.F07, m.u8(UNITS + i + U.F07) | 0x80);
  });
  // Вожака не назначаем: с ним движок печатает внизу «Foods=», а приказы и так идут всем
  // выделенным (0x14398 смотрит бит выделения, а не вожака).
  m.w32(0x31adc, 0);
}

