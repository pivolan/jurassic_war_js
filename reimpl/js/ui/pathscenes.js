      const cx = 10, cy = 7, r = 4.2;
      for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
        const d = Math.hypot(x - cx, (y - cy) * 1.15);
        if (d <= r) вода(eng, сц, x, y, x, y);
      }
      for (const x of [7, 9, 11, 13]) { дерево(eng, сц, x, 0); дерево(eng, сц, x, 14); }
