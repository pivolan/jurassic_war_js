/** Собрать сцену по номеру. Возвращает { x, y } цели в клетках. */
export function собрать(eng, номер) {
  const с = СЦЕНЫ[номер] || СЦЕНЫ[0];
  const цель = с.собрать(eng);
  eng.m.w32(0x33c7c, 0x33c88);            // очередь приказов — пустая
  eng.m.w8(0x31acc, 0xff);
  return цель;
}
