// Тренировочные арены для сети, ведущей одного юнита (наше).
//
// Арена — это маленькая сцена, собранная в памяти движка (общая механика — js/ui/scenebuild.js):
// карта, препятствия, наш боец, противник, звери, предметы, охраняемый объект и задание (роль,
// вес важности, цель). Каждая арена умеет разыгрываться в вариациях по номеру: меняются число
// врагов, направления, дистанции и здоровье. Это и есть «процедурная генерация сценариев» из плана.
//
// Здесь — строительные блоки и сборка эпизода. Сами сцены (их полсотни) лежат в js/ai/scenes.js
// и при импорте добавляют себя в список АРЕНЫ. Отдельный набор помечен `проверочная: true` —
// на них НЕ обучаем, только смотрим. Иначе легко обмануться: сеть охотно зазубривает набор.
import { call } from '../fn.js';
import { G, U, UNITS, BI, ITEMS } from '../mem.js';
import { основа, запас, поставить, клетка } from '../ui/scenebuild.js';

// Миссия 11 — единственная, где в записях есть все нужные типы разом: строитель (4, одна запись),
// воины (2, 3), маги всех четырёх видов (5–8), ручной динозавр (9), дилофозавр (13), тигр (21),
// тираннозавры (14), мамонты (19). В девятой нет строителя, во второй — магов, тигров и
// дилофозавра. Набор тайлов по проходимости совпадает со второй (394 трава, 567 скала, 331 вода).
export const МИССИЯ = 11, ПЛЕМЯ = 0;
const W = 20, H = 15;
export const РАЗМЕР = { w: W, h: H };
export const НАШ = [5, 1];        // маг в красном, запасной — воин
export const ВРАГ = [1, 5];       // враг другого вида, чтобы на глаз различались
const ДОМ = [30, 27, 31];  // здания миссии 3: тип 30 — хижина, годится как «охраняемый объект»

// Типы юнитов, которые есть в записях второй миссии и годятся в бойцы:
//   1 — общинник (hp 64, atk 84), 4 — строитель (hp 30, слабый и медленный), 5 — маг (hp 62),
//   9 — ручной динозавр (hp 80, def 80). Дикие: 14 — тираннозавр (hp 200, atk 150, убивает
//   любого), 19 — мамонт (hp 80, atk 55, равный противник), 22 — леопард (hp 22), 23 — пёс (hp 18).
export const ЗВЕРИ = { ТИРАННОЗАВР: 14, МАМОНТ: 19, ТИГР: 21, ЛЕОПАРД: 22, ПЁС: 23 };
export const ЛЮДИ = { ОБЩИННИК: 1, СИЛАЧ: 2, ВОИН: 3, СТРОИТЕЛЬ: 4, ЭЛЬФ: 5, ВОЛШЕБНИК: 6, ВАРЛОК: 7, РЕЙНДЖЕР: 8, ДИНОЗАВР: 9, ДИЛОФОЗАВР: 13 };

// Записи юнитов в миссиях прокачаны вразнобой (один общинник hp 30, другой hp 158). Чтобы сцена не
// зависела от того, какая запись досталась, каждому поставленному юниту пишутся канонические
// статы своего типа: [HPMAX, ATK, DEF, SPD, MAG]. Люди и маги — как у первых записей второй
// миссии (на них настроены все прежние сцены), остальные — типовые записи девятой.
export const СТАТЫ = {
  1: [64, 84, 34, 54, 34], 2: [70, 35, 70, 30, 0], 3: [100, 170, 35, 90, 50], 4: [30, 20, 20, 30, 0],
  5: [62, 66, 38, 57, 57], 6: [55, 100, 20, 75, 75], 7: [80, 110, 25, 100, 100], 8: [74, 93, 25, 104, 64],   // волшебник хрупкий и злой: фокус на нём решает стычку
  9: [80, 50, 80, 90, 0], 13: [73, 96, 40, 73, 23],
  14: [200, 150, 150, 200, 0], 19: [80, 55, 45, 120, 0], 21: [50, 50, 40, 120, 0], 22: [22, 24, 24, 100, 0], 23: [18, 20, 20, 80, 0],
};
/** Характеристики юнита одной строкой — для подписи в сцене. */
function статы(m, i) {
  const с = СТАТЫ[m.u8(UNITS + i + U.TYPE)];
  if (!с) return;
  m.w8(UNITS + i + U.HPMAX, с[0]); m.w8(UNITS + i + U.HP, с[0]); m.w8(UNITS + i + U.ATK, с[1]); m.w8(UNITS + i + U.DEF, с[2]);
  m.w8(UNITS + i + U.SPD, с[3]); m.w8(UNITS + i + U.MAG, с[4]); m.w8(UNITS + i + U.MANA, с[4]);
  m.w8(UNITS + i + U.XP, 0); m.w8(UNITS + i + U.WEAPON, 0xff); m.w8(UNITS + i + U.SHIELD, 0xff);
}

/** Простой воспроизводимый генератор: одинаковый номер — одинаковая арена. */
export function случай(seed) {
  let s = (seed | 0) * 1103515245 + 12345;
  return (n) => { s = (s * 1103515245 + 12345) & 0x7fffffff; return n ? s % n : s; };
}

/** Расставить отряд заданных типов по точкам сцены. */
function поставитьОтряд(eng, сц, типы, владелец, точки) {
  const m = eng.m, свободные = запас(сц, типы);
  const поставленные = [];
  for (const [x, y] of точки) {
    const i = свободные.shift();
    if (i === undefined) break;
    m.w8(UNITS + i + U.OWNER, владелец);
    статы(m, i);
    поставить(eng, i, x, y);
    поставленные.push(i);
  }
  return поставленные;
}

/** Наш отряд: ставим и выделяем — чтобы в просмотрщике было видно рамку. */
export function наши(eng, сц, точки, типы = НАШ) {
  const m = eng.m;
  const список = поставитьОтряд(eng, сц, типы, m.u8(G.humanOwner), точки);
  for (const i of список) m.w8(UNITS + i + U.F07, m.u8(UNITS + i + U.F07) | 0x80);
  m.w32(0x31adc, 0);        // вожака не назначаем: с ним движок печатает «Foods=»
  return список;
}
/** Союзники: наши по владельцу, но НЕ управляемые и не выделенные — часть обстановки. Типы — по
 *  одному на точку (первый — запасной для остальных). Стоя на посту, союзник сам выходит на врага,
 *  попавшего в его обзор (проверено движком): к нему и имеет смысл отступать. */
export function союзники(eng, сц, точки, типы = [1]) {
  const список = [];
  точки.forEach((p, k) => список.push(...поставитьОтряд(eng, сц, [типы[k] ?? типы[0], 1, 5], eng.m.u8(G.humanOwner), [p])));
  return список;
}
export const чужие = (eng, сц, точки, типы = ВРАГ) =>
  поставитьОтряд(eng, сц, типы, (eng.m.u8(G.humanOwner) + 1) & 7, точки);

/**
 * Дикие звери: владелец 8 («природа»), исполняются своим обработчиком 0x184c8. Без приказа зверь
 * стоит и раз в ~200 шагов идёт пастись; с приказом атаки (`нападать`) идёт на цель и дерётся,
 * как и враг-человек. Инстинкт может перебить приказ, но проверено: до цели зверь доходит.
 */
export function звери(eng, сц, тип, точки, нападать = 0, мясо = 0) {
  const список = поставитьОтряд(eng, сц, [тип], 8, точки);
  for (const i of список) {
    if (нападать) приказАтаковать(eng, i, нападать);
    eng.m.w16(UNITS + i + U.FOOD, мясо);      // убивший зверя получает его еду себе — это и есть охота
  }
  return список;
}

/**
 * Предмет на земле: запись из пула OI (economy-spec §12), еда (тип 0x1e) с количеством.
 * Бит 1 в BI — «здесь что-то лежит»; фаза 0x1c340 его и так поднимает, но пусть будет сразу.
 */
export function предмет(eng, сц, x, y, кол = 20, тип = 0x1e) {
  const m = eng.m, i = m.u32(0x31b80);
  if (!i) return 0;
  m.w32(0x31b80, m.u32(ITEMS + i + 0xc));
  m.w8(ITEMS + i, тип); m.w8(ITEMS + i + 1, x); m.w8(ITEMS + i + 2, y);
  m.w16(ITEMS + i + 4, 0x19); m.w16(ITEMS + i + 6, кол);
  const голова = m.u32(0x31b7c);
  m.w32(ITEMS + i + 8, 0); m.w32(ITEMS + i + 0xc, голова);
  if (голова) m.w32(ITEMS + голова + 8, i);
  m.w32(0x31b7c, i);
  m.w8(BI + клетка(x, y), m.u8(BI + клетка(x, y)) | 2);
  return i;
}

/**
 * Охраняемый объект — здание с карты миссии, переставленное в нужную клетку.
 *
 * Состояние здания трогать НЕЛЬЗЯ. 0x60 у здания это не «стоит», а обвал: обработчик 0x1886e
 * при состоянии не 0x6f крутит счётчик и через восемь тиков убирает здание из живых. Первый
 * вариант арены ставил 0x60 — дом исчезал на третьем тике, враги теряли цель и вставали
 * столбом, а эпизод заканчивался «объект разрушен» ещё до первого решения сети. Живое здание
 * приходит из миссии в состоянии 0x3f, его и оставляем.
 */
export function дом(eng, сц, x, y, владелец = eng.m.u8(G.humanOwner)) {
  const m = eng.m, свободные = запас(сц, ДОМ);
  const i = свободные[0];
  if (i === undefined) return 0;
  свободные.shift();
  call(eng, 0x1a42c, { esi: i, edx: m.u16(UNITS + i + U.X), ebx: m.u16(UNITS + i + U.Y) });  // снять со старой клетки
  m.w8(UNITS + i + U.OWNER, владелец);
  m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) & 0xfe);
  m.w16(UNITS + i + U.X, x << 5); m.w16(UNITS + i + U.Y, y << 5);
  m.w16(UNITS + i + U.DSTX, x << 5); m.w16(UNITS + i + U.DSTY, y << 5);
  m.w8(UNITS + i + U.ORDER, 0xff); m.w8(UNITS + i + U.ATKCTR, 0);
  m.w8(UNITS + i + U.FLAGS50, 0); m.w8(UNITS + i + U.FX43, 0);
  m.w8(UNITS + i + 0x53, x); m.w8(UNITS + i + 0x54, y);
  m.w8(UNITS + i + U.HP, m.u8(UNITS + i + U.HPMAX));
  for (let dy = 0; dy <= 1; dy++) for (let dx = 0; dx <= 1; dx++)
    m.w8(BI + клетка(x + dx, y + dy), (m.u8(BI + клетка(x + dx, y + dy)) & 3) | (((владелец + 1) << 2) & 0xff));
  return i;
}

/** Врагу — приказ атаковать объект: он приходит в поле ORDER, как обычный приказ. */
export function приказАтаковать(eng, кто, цель) {
  const m = eng.m;
  if (!цель) return;
  m.w8(UNITS + кто + U.ORDER, 0x1f);
  m.w32(UNITS + кто + 0x47, цель);
  m.w16(UNITS + кто + 0x4b, m.u16(UNITS + цель + U.X));
  m.w16(UNITS + кто + 0x4d, m.u16(UNITS + цель + U.Y));
}

/** Убавить здоровье (доля от максимума): раненые бойцы — тоже часть вариаций. */
export function ранить(eng, i, доля) {
  const m = eng.m, макс = m.u8(UNITS + i + U.HPMAX);
  m.w8(UNITS + i + U.HP, Math.max(1, Math.round(макс * доля)));
}

/** Обнулить ману (маг без маны — цель попроще; на обычную атаку магов мана не влияет, но признак в окне есть). */
export function безМаны(eng, i) { eng.m.w8(UNITS + i + U.MANA, 0); }

/** Усилить (или ослабить) юнита: множитель к HPMAX/HP, ATK и DEF — для подбора баланса сцены. */
export function усилить(eng, i, k) {
  const m = eng.m, b = UNITS + i, кл = (v) => Math.max(1, Math.min(255, Math.round(v * k)));
  m.w8(b + U.HPMAX, кл(m.u8(b + U.HPMAX))); m.w8(b + U.HP, m.u8(b + U.HPMAX));
  m.w8(b + U.ATK, кл(m.u8(b + U.ATK))); m.w8(b + U.DEF, кл(m.u8(b + U.DEF)));
}

/** Уложить спать сразу при сборке сцены: родное состояние отдыха 0x2f, дальше его ведёт 0x18e0b. */
export function уснуть(eng, i) { eng.m.w8(UNITS + i + U.STATE, 0x2f); }

/** Пустая арена стандартного размера. */
export const поле = (eng) => основа(eng, W, H);

// Список арен заполняет js/ai/scenes.js при импорте (там и лежат все сцены).
export const АРЕНЫ = [];

/** Собрать арену (номер в списке или само описание): возвращает описание эпизода. */
export function собрать(eng, что, вариация = 0) {
  const а = typeof что === 'object' ? что : (АРЕНЫ[что] || АРЕНЫ[0]);
  const номер = typeof что === 'object' ? АРЕНЫ.indexOf(что) : что;
  const с = а.собрать(eng, вариация);
  eng.m.w32(0x33c7c, 0x33c88);
  eng.m.w8(0x31acc, 0xff);
  const эп = {
    арена: номер, вариация, имя: а.имя, подпись: а.подпись, роль: а.роль,
    шагов: 0, шаговВсего: а.шагов, шаговОбъект: 0,
    наши: с.наши, враги: с.враги || [], враговВсего: (с.враги || []).length,
    охраняемый: с.охраняемый || 0, точка: с.точка || null, вес: с.вес ?? 1,
    предметы: с.предметы || [], едыВсего: с.едыВсего || 0, скриптВрага: !!с.скриптВрага,
    дистанция: 16, награда: 0,
  };
  эп.охраняемыйHPмакс = эп.охраняемый ? eng.m.u8(UNITS + эп.охраняемый + U.HPMAX) : 0;
  // Строитель (тип 4) не дерётся: боевые роли для него в сценах недопустимы.
  эп.строитель = эп.наши.length > 0 && эп.наши.every(i => eng.m.u8(UNITS + i + U.TYPE) === 4);
  if (эп.наши.some(i => eng.m.u8(UNITS + i + U.TYPE) === 4) && ['ATTACK_TO_DEATH', 'DEFEND_POINT', 'DISTRACT'].includes(а.роль))
    throw new Error(`сцена «${а.имя}»: строителю нельзя роль ${а.роль}`);
  эп.задание = { роль: эп.роль, вес: эп.вес, точка: эп.точка, цель: 0 };
  return эп;
}
