// Скриптовый учитель: простая эвристика, с которой начинается обучение (наше).
//
// Он нарочно топорный. Его дело — дать сети разумную отправную точку вместо случайного
// блуждания и остаться эталоном для сравнения. Полировать его не надо: хороший скрипт — это
// потерянные недели, а сеть всё равно должна его перерасти.
import { U, UNITS } from '../mem.js';
import { ПАРАМЕТРЫ as П } from './params.js';
import { враги, дома, предметы, клетка, строитель, спит, дальность, обмен, союзники, К_ЦЕЛИ, БЛИЖНИЙ, СЛАБЕЙШИЙ, ОТОЙТИ, ДЕРЖАТЬ, ПОДОБРАТЬ, УСНУТЬ, СТРЕЛЯТЬ, НИЧЕГО, РАНЕНЫЙ, МАГ, ЗАЩИТИТЬ, ДОМ, ЦЕЛЬ } from './act.js';

/**
 * Направление из восьми, ближайшее к вектору (dx,dy). Только целые числа: `Math.atan2` в
 * стандарте языка не задан точно, и два браузера имели право вернуть разные последние биты —
 * для приказа, который считается на всех машинах одинаково, это недопустимо.
 *
 * Считаем так же, как таблица: октант задаётся знаками dx,dy, а внутри октанта граница между
 * «по оси» и «по диагонали» лежит на 22.5°, где tg = 0.414213…  Сравнение
 * `мин * 1000 > макс * 414` — та же граница, выраженная целыми (0.414 против 0.41421:
 * расхождение только на волосок от самой границы, где оба направления равнозначны).
 */
const ОСЬ = [0, 2, 4, 6];                              // вверх, вправо, вниз, влево
/** Направление «прочь отсюда» в номер действия «идти ↑…↖» по вектору смещения. */
export function сторона(dx, dy) {
  if (!dx && !dy) return 0;
  const ax = dx < 0 ? -dx : dx, ay = dy < 0 ? -dy : dy;
  const мин = ax < ay ? ax : ay, макс = ax < ay ? ay : ax;
  if (мин * 1000 > макс * 414) {                       // диагональ: 1,3,5,7
    if (dx > 0) return dy < 0 ? 1 : 3;
    return dy < 0 ? 7 : 5;
  }
  if (ax > ay) return dx > 0 ? ОСЬ[1] : ОСЬ[3];
  return dy < 0 ? ОСЬ[0] : ОСЬ[2];
}

/**
 * Решение учителя для бойца. Возвращает номер действия.
 * Логика в четырёх строках:
 *   1. здоровье низкое и приказ не «любой ценой» — отходить;
 *   2. роль «отвлечь» — бить того, кто ближе всех к охраняемому объекту, и не добивать;
 *   3. враг в пределах видимости — бить (слабейшего, если он рядом, иначе ближайшего);
 *      в ролях «собрать» и «держать» — только если он подошёл вплотную;
 *   4. иначе идти к цели задания (в роли «собрать» — к ближайшему предмету), а если цели нет —
 *      держать позицию.
 */
export function решение(eng, боец, эп) {
  const m = eng.m;
  const макс = m.u8(UNITS + боец + U.HPMAX) || 1;
  const доля = m.u8(UNITS + боец + U.HP) / макс;
  const вес = эп.задание.вес;
  // Пасущийся зверь — не враг, пока не вцепился: с тираннозавром лучше не связываться, а мимо
  // мамонтов надо просто пройти. Исключение — роль «уничтожить», там зверь и есть цель.
  // Зверь с целью (грызёт дом, гонит своих) — уже враг, как и в ролях уничтожения/обороны/отвлечения.
  const в = враги(eng, боец).filter(е => m.u8(UNITS + е.i + U.OWNER) !== 8
                                       || m.u32(UNITS + е.i + U.TARGET) !== 0
                                       || ['ATTACK_TO_DEATH', 'DISTRACT', 'DEFEND_POINT'].includes(эп.роль)
                                       || (эп.роль === 'GATHER' && !эп.предметы.length));

  // Разведчик. Он не воюет вообще: его дело — раскрыть карту и вернуться живым. Враг в окне —
  // уходим к своим (если до них далеко) или просто прочь; чисто — идём к точке осмотра. Спать
  // посреди чужой земли тоже не будем: раненого разведчика штаб сам отзывает домой.
  if (эп.роль === 'SCOUT') {
    const c = клетка(m, боец);
    const далеко = эп.точка && Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y)) > П.к_своим_дистанция;
    if (в.length) return далеко ? К_ЦЕЛИ : ОТОЙТИ;
    if (!эп.точка) return ДЕРЖАТЬ;
    return Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y)) <= 1 ? ДЕРЖАТЬ : К_ЦЕЛИ;
  }

  // Отступать: если есть куда (свои на посту) — туда, иначе просто прочь от врагов.
  // Сон: угрозы в окне нет, здоровье ниже порога — спать (в ролях отхода и поста — с 70 %,
  // в остальных только совсем битым, чтобы не тянуть с задачей). Спящему — «ничего»: любой
  // приказ его будит. Появился враг — ниже сработает обычная логика роли и разбудит его приказом.
  const порогСна = эп.роль === 'RETREAT' || эп.роль === 'HOLD' || эп.роль === 'DEFEND_POINT' ? П.сон_порог_отход : П.сон_порог_иначе;
  // Спать — только когда делать нечего. Если отряду НАЗНАЧЕНА живая цель, боец идёт к ней, даже
  // будучи побитым: цель может стоять в десяти клетках, то есть за окном обзора, и старое правило
  // «врага в окне нет и здоровья меньше 40 % — спи» укладывало спать всех, кто на секунду вышел
  // из драки. Владелец про это и сказал: «мешает механика, встроенная в каждого юнита, которая не
  // даёт начать атаку». Отойти и отлежаться по-прежнему можно — это делает роль RETREAT, куда
  // раненых отправляет штаб, и там порог свой (0.7).
  const цельОтряда = эп.задание && эп.задание.цель;
  const цельЖива = цельОтряда && !(m.u8(UNITS + цельОтряда + U.FLAGS5B) & 1);
  if (!в.length && !цельЖива && доля < порогСна) return спит(eng, боец) ? НИЧЕГО : УСНУТЬ;

  const стрелок = дальность(m, боец) > 0;
  // Оценка силы: обмен заведомо проигрышный (больше 2:1 против нас со всеми врагами в окне) и роль
  // не требует умереть на месте — не драться. Стрелок дёргает и уходит (макро «стрелять» само
  // отскакивает), ближник в DISTRACT агрит и уводит (ниже), в остальных ролях — к своим или прочь.
  if (в.length && вес < 2 && эп.роль !== 'RETREAT' && эп.роль !== 'DISTRACT' && обмен(m, боец, в, союзники(eng, боец)).общий > П.обмен_безнадёжный) {
    if (стрелок) return СТРЕЛЯТЬ;
    if (эп.точка && эп.роль !== 'MOVE_TO') {
      const c = клетка(m, боец);
      if (Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y)) > П.к_своим_дистанция) return К_ЦЕЛИ;
    }
    return ОТОЙТИ;
  }
  // Строитель не дерётся никогда: любая угроза в окне — отходить (к своим, если они далеко).
  if (строитель(m, боец) && в.length) {
    if (эп.точка && эп.роль === 'RETREAT') {
      const c = клетка(m, боец);
      if (Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y)) > П.к_своим_дистанция) return К_ЦЕЛИ;
    }
    return ОТОЙТИ;
  }
  // Отступать: если есть куда (свои на посту) и до них далеко — туда; рядом со своими или
  // без цели — уходить от врагов (веер направлений с обходом стен, см. act.js). Стоять на месте
  // под ударами нельзя ни там, ни там: все ходят с одной скоростью, движущегося не догнать.
  if (эп.роль === 'RETREAT') {
    if (!в.length) return ДЕРЖАТЬ;
    if (эп.точка) {
      const c = клетка(m, боец);
      if (Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y)) > П.к_своим_дистанция) return К_ЦЕЛИ;
    }
    return ОТОЙТИ;
  }
  if (доля < П.отход_hp && вес < 2 && в.length) return ОТОЙТИ;
  // Герой (тот, в кого племя слило весь опыт) размениваться не должен: он отходит заметно
  // раньше остальных. Один такой боец стоит половины отряда — опыт за убийство растёт квадратом
  // статов жертвы, и подарить его врагу дороже, чем проиграть эту стычку.
  if (эп.беречь && в.length && доля < П.беречь_hp) return стрелок ? СТРЕЛЯТЬ : ОТОЙТИ;

  if (эп.роль === 'DISTRACT' && эп.охраняемый) {
    // «Дёргать»: подойти и ударить того, кто ещё не на нас (звери и люди переключаются на
    // ударившего, если их цель — здание; проверено движком), потом отойти на пару клеток,
    // чтобы за бойцом пошли, а не вернулись к дому; когда все на нас — уводить от дома.
    const дх = m.u16(UNITS + эп.охраняемый + U.X) >> 5, ду = m.u16(UNITS + эп.охраняемый + U.Y) >> 5;
    const свои = в.filter(е => m.u32(UNITS + е.i + U.TARGET) !== боец);
    const c = клетка(m, боец);
    if (свои.length) {
      if (стрелок) return СТРЕЛЯТЬ;                     // стрелок агрит выстрелом и сам отскакивает
      // Квадрат расстояния вместо Math.hypot: порядок тот же, а точность у hypot стандартом не
      // задана — по сети два браузера могли бы отсортировать список по-разному.
      const кв = (е) => (е.x - дх) * (е.x - дх) + (е.y - ду) * (е.y - ду);
      свои.sort((a, b) => кв(a) - кв(b) || a.i - b.i);
      const пам = эп.память && эп.память.get(боец);
      if (свои[0].d <= П.дёргать_дистанция && пам && пам.действие === БЛИЖНИЙ) return ОТОЙТИ;   // ударил — отскочить
      return БЛИЖНИЙ;
    }
    if (стрелок) return СТРЕЛЯТЬ;
    return сторона(c.x - дх, c.y - ду);                 // все уже за нами — уводим подальше
  }

  const близко = в.filter(е => е.d <= П.близко);
  if (эп.роль === 'GATHER') {
    // За едой, а не за дракой: бьём только того, кто уже вцепился, иначе — к предмету.
    if (близко.length) return стрелок ? СТРЕЛЯТЬ : близко.length > 1 ? СЛАБЕЙШИЙ : БЛИЖНИЙ;
    if (предметы(eng, боец).length) return ПОДОБРАТЬ;
    return в.length ? БЛИЖНИЙ : (эп.точка ? К_ЦЕЛИ : ДЕРЖАТЬ);
  }
  if (эп.роль === 'HOLD' && эп.точка) {
    // Пост не бросать: драться только с теми, кто подошёл, остальных ждать на месте.
    const c = клетка(m, боец);
    const d = Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y));
    if (близко.length) return стрелок ? СТРЕЛЯТЬ : близко.length > 1 ? СЛАБЕЙШИЙ : БЛИЖНИЙ;
    return d > П.держать_дистанция ? К_ЦЕЛИ : ДЕРЖАТЬ;
  }
  if (в.length) {
    // Стрелок в ATTACK / DEFEND (и вообще при враге в окне) — «выстрелил, отошёл, выстрелил»;
    // при явном перевесе макро само не отскакивает, а просто бьёт (уточнение владельца).
    // Назначенную цель макро учитывает само (act.js): стреляет в неё, а не в того, кто ближе.
    // Отбирать у стрелка это макро нельзя — без него он идёт в упор и размен проигрывает.
    if (стрелок) return СТРЕЛЯТЬ;
    // Назначенная цель важнее приоритетов свалки: её ставит либо отряд (охота — весь отряд валит
    // одного зверя), либо «липкость» — боец уже подранил кого-то и бросать его нельзя. Раньше
    // цель выбиралась заново каждые восемь шагов, и начатая добыча не добивалась никогда:
    // двое почти убили тигра, один отвлёкся, второй в одиночку не перебивает регенерацию.
    // Проверяем, что цель ещё в окне: гнаться за ней через полкарты — не дело бойца.
    const назначена = эп.задание && эп.задание.цель;
    if (назначена && в.some(е => е.i === назначена)) return ЦЕЛЬ;
    // Приоритет цели в свалке: маг с маной — первым (он опаснее всех и хрупкий), потом тот, кто
    // добивает союзника, потом раненый враг рядом (добить — минус одна пара рук), иначе ближний.
    if (П.приоритет_маг >= 0.5 && в.some(е => е.маг && е.мана > 0)) return МАГ;
    if (П.приоритет_защитить >= 0.5 && в.some(е => е.бьётСвоего && е.d <= П.защитить_дистанция)) return ЗАЩИТИТЬ;
    if (П.приоритет_раненый >= 0.5 && близко.length > 1 && близко.some(е => е.доля < П.раненый_доля)) return РАНЕНЫЙ;
    if (близко.length) return близко.length > 1 ? СЛАБЕЙШИЙ : БЛИЖНИЙ;
    return БЛИЖНИЙ;
  }

  // Врагов в окне нет, а вражеский дом есть — ломать его. В этой игре постройки и есть партия:
  // склад держит еду (единственный ресурс), Святилище делает строителей, казармы и школы — поток
  // бойцов. Учитель обязан это показывать, иначе сеть про новое действие просто не узнает.
  // Строитель не дерётся вовсе, отход и сбор еды тоже не отвлекаем.
  if (!строитель(m, боец) && эп.роль !== 'RETREAT' && эп.роль !== 'GATHER' && дома(eng, боец).length) return ДОМ;

  // Роль «уничтожить», врагов в окне нет — идти к ближайшему врагу на карте (в стычках отряды
  // начинают дальше окна, и без этого обе стороны стояли бы столбом).
  if (эп.роль === 'ATTACK_TO_DEATH' && !в.length && !эп.точка) {
    const далеко = враги(eng, боец, 64);
    if (далеко.length) { const ц = далеко.reduce((a, b) => a.d < b.d ? a : b); return сторона(ц.dx, ц.dy); }
  }
  if (эп.роль === 'DEFEND_POINT' && эп.точка) {
    const c = клетка(m, боец);
    const d = Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y));
    return d > П.пост_дистанция ? К_ЦЕЛИ : ДЕРЖАТЬ;
  }
  if (эп.точка) {
    const c = клетка(m, боец);
    const d = Math.max(Math.abs(c.x - эп.точка.x), Math.abs(c.y - эп.точка.y));
    return d <= 1 ? ДЕРЖАТЬ : К_ЦЕЛИ;
  }
  return ДЕРЖАТЬ;
}
