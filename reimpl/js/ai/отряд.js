// Сеть ОТРЯДА: одна сеть смотрит на всю сцену и выдаёт приказ сразу всем бойцам (наше).
//
// Замысел владельца: «нейронка должна на выходе отдавать команду для четырёх этих юнитов; прям на
// выходе у неё столько параметров, сколько надо для этих четырёх… не четыре отдельных, а одна, но
// которая сразу всем управляет».
//
// Чем это отличается от сети бойца (js/ai/net.js). Та решает за ОДНОГО и видит мир из его глаз:
// каждый сам по себе, и согласовать их может только внешнее правило (штаб). Здесь наоборот: вход
// один на весь отряд — общая картина местности и состояние каждого бойца, — а выход это МЕСТА:
// столько голов, сколько бойцов, и каждая выдаёт действие своему. Сеть сразу видит, что делают
// остальные, поэтому «двое держат зверя, третий заходит сбоку, четвёртый отходит» для неё одно
// решение, а не четыре независимых.
//
// Наблюдение (должно совпадать байт в байт с tools/ai_net.py, класс Отряд):
//   окно 24×24 клетки вокруг середины отряда, 6 слоёв:
//     0 проходимо, 1 разведано, 2 свои, 3 зверьё (доля здоровья), 4 чужие племена, 5 мясо и вещи;
//   вектор на 48 чисел: по 10 на каждое место (жив, здоровье, где стоит относительно середины,
//   бьют ли его, дерётся ли, чем бьёт, сколько ударов держит) и 8 общих (сколько зверья рядом,
//   до ближайшего, суммарное здоровье отряда, доля времени).
import { G, U, UNITS, BG, BI } from '../mem.js';
import { ЧИСЛО_ДЕЙСТВИЙ } from './act.js';

export const ОКНО = 24;                  // клеток в стороне окна (чётное: делится пулингом дважды)
export const СЛОЁВ = 6;
export const МЕСТ = 4;                   // столько бойцов ведёт сеть — столько у неё голов
export const НА_МЕСТО = 10;              // чисел в векторе на одно место
export const ОБЩИХ = 8;
export const ВЕКТОР = МЕСТ * НА_МЕСТО + ОБЩИХ;
export const ДЕЙСТВИЙ = ЧИСЛО_ДЕЙСТВИЙ;

const П = ОКНО * ОКНО;
const R = ОКНО >> 1;
const TILE_INF = 0x3183c;
const ЗВЕРЬ = (t) => t >= 14 && t <= 23;
const урон = (a, d) => Math.max(1, (Math.max(a - d, 0) >> 4) + (a >> 5) + 1);

/** Пустые буферы наблюдения — их переиспользуют, чтобы не сорить памятью на каждом решении. */
export const пустое = () => ({ окно: new Float32Array(СЛОЁВ * П), вектор: new Float32Array(ВЕКТОР) });

/**
 * Наблюдение отряда. `места` — массив из МЕСТ номеров юнитов (0 на пустом месте: боец погиб).
 * Порядок мест ПОСТОЯНЕН в пределах эпизода: голова номер k всегда управляет местом k, иначе
 * сеть не сможет ничего выучить про «своего» бойца.
 */
export function наблюдать(eng, места, доляВремени = 0, вых = пустое()) {
  const m = eng.m, b = m.b;
  const окно = вых.окно, вектор = вых.вектор;
  окно.fill(0); вектор.fill(0);
  const живые = места.filter(i => i && !(b[UNITS + i + U.FLAGS5B] & 1) && b[UNITS + i + U.HP] > 0);
  if (!живые.length) return вых;
  const мой = b[UNITS + живые[0] + U.OWNER];
  let cx = 0, cy = 0;
  for (const i of живые) { cx += (m.u16(UNITS + i + U.X) >> 5) / живые.length; cy += (m.u16(UNITS + i + U.Y) >> 5) / живые.length; }
  cx = Math.round(cx); cy = Math.round(cy);
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const x0 = cx - R, y0 = cy - R;

  // ---- местность и туман
  for (let dy = 0; dy < ОКНО; dy++) {
    const y = y0 + dy; if (y < 0 || y >= H) continue;
    for (let dx = 0; dx < ОКНО; dx++) {
      const x = x0 + dx; if (x < 0 || x >= W) continue;
      const k = dy * ОКНО + dx, c = x + (y << 8);
      const разведано = b[BI + c] & 1;
      окно[1 * П + k] = разведано;
      if (!разведано) continue;
      const слово = m.u16(BG + (y << 9) + x * 2);
      окно[0 * П + k] = (слово & 0xf800) ? 0 : (b[TILE_INF + (слово & 0x7ff)] & 1);
    }
  }
  // ---- живое: свои, зверьё, чужие племена
  let зверейРядом = 0, доБлижнего = 99, ближний = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (b[UNITS + i + U.FLAGS5B] & 1) continue;
    const т = b[UNITS + i + U.TYPE];
    const x = (m.u16(UNITS + i + U.X) >> 5) - x0, y = (m.u16(UNITS + i + U.Y) >> 5) - y0;
    if (x < 0 || y < 0 || x >= ОКНО || y >= ОКНО) continue;
    const k = y * ОКНО + x;
    const доля = b[UNITS + i + U.HP] / (b[UNITS + i + U.HPMAX] || 1);
    if (b[UNITS + i + U.OWNER] === мой && т < 0x1a) { окно[2 * П + k] = доля; continue; }
    if (ЗВЕРЬ(т)) {
      окно[3 * П + k] = доля;
      const d = Math.abs(x - R) + Math.abs(y - R);
      if (d <= 12) зверейРядом++;
      if (d < доБлижнего) { доБлижнего = d; ближний = i; }
      continue;
    }
    if (т < 0x1a) окно[4 * П + k] = доля;
  }
  // ---- мясо и вещи на земле
  const ITEMS = 0xf4f34, ГОЛОВА = 0x31b7c;
  for (let it = m.u32(ГОЛОВА); it; it = m.u32(ITEMS + it + 0xc)) {
    const x = b[ITEMS + it + 1] - x0, y = b[ITEMS + it + 2] - y0;
    if (x < 0 || y < 0 || x >= ОКНО || y >= ОКНО) continue;
    окно[5 * П + y * ОКНО + x] = b[ITEMS + it] === 0x1e ? 1 : 0.5;
  }
  // ---- вектор: по десять чисел на место
  for (let s = 0; s < МЕСТ; s++) {
    const i = места[s]; const б = s * НА_МЕСТО;
    if (!i || (b[UNITS + i + U.FLAGS5B] & 1) || b[UNITS + i + U.HP] === 0) continue;
    const hp = b[UNITS + i + U.HP], макс = b[UNITS + i + U.HPMAX] || 1;
    const x = (m.u16(UNITS + i + U.X) >> 5) - cx, y = (m.u16(UNITS + i + U.Y) >> 5) - cy;
    const цель = m.u32(UNITS + i + U.TARGET);
    let бьютМеня = 0, худший = 0;
    for (let j = m.u32(G.unitHead); j; j = m.u32(UNITS + j + U.NEXT)) {
      if (b[UNITS + j + U.FLAGS5B] & 1 || b[UNITS + j + U.OWNER] === мой) continue;
      if (m.u32(UNITS + j + U.TARGET) === i) бьютМеня = 1;
      const dx2 = (m.u16(UNITS + j + U.X) >> 5) - (m.u16(UNITS + i + U.X) >> 5);
      const dy2 = (m.u16(UNITS + j + U.Y) >> 5) - (m.u16(UNITS + i + U.Y) >> 5);
      if (Math.abs(dx2) + Math.abs(dy2) > 6) continue;
      const у = урон(b[UNITS + j + U.ATK], b[UNITS + i + U.DEF]); if (у > худший) худший = у;
    }
    вектор[б + 0] = 1;                                   // место занято
    вектор[б + 1] = hp / макс;                           // доля здоровья
    вектор[б + 2] = Math.max(-1, Math.min(1, x / R));    // где стоит относительно середины
    вектор[б + 3] = Math.max(-1, Math.min(1, y / R));
    вектор[б + 4] = бьютМеня;
    вектор[б + 5] = цель && !(b[UNITS + цель + U.FLAGS5B] & 1) ? 1 : 0;
    вектор[б + 6] = b[UNITS + i + U.ATK] / 128;
    вектор[б + 7] = b[UNITS + i + U.DEF] / 128;
    вектор[б + 8] = худший ? Math.min(1, hp / (худший * 8)) : 1;   // на сколько ударов его хватит
    вектор[б + 9] = (b[UNITS + i + U.STATE] >> 4) === 1 ? 1 : 0;   // уже дерётся
  }
  const б = МЕСТ * НА_МЕСТО;
  вектор[б + 0] = Math.min(1, зверейРядом / 8);
  вектор[б + 1] = Math.min(1, доБлижнего / 16);
  вектор[б + 2] = ближний ? b[UNITS + ближний + U.HP] / (b[UNITS + ближний + U.HPMAX] || 1) : 0;
  вектор[б + 3] = ближний ? Math.min(1, урон(b[UNITS + ближний + U.ATK], b[UNITS + живые[0] + U.DEF]) / 8) : 0;
  let сум = 0, максСум = 0;
  for (const i of места) { if (!i) continue; сум += b[UNITS + i + U.HP]; максСум += b[UNITS + i + U.HPMAX] || 1; }
  вектор[б + 4] = максСум ? сум / максСум : 0;
  вектор[б + 5] = живые.length / МЕСТ;
  вектор[б + 6] = Math.max(0, Math.min(1, доляВремени));
  вектор[б + 7] = 1;                                     // свободный вход под будущее
  return вых;
}

// ---------------------------------------------------------------- сеть
/** Разобрать веса отряда из JSON. */
export function загрузить(json) {
  const w = typeof json === 'string' ? JSON.parse(json) : json;
  if (w.вид !== 'отряд') throw new Error('это не веса отряда: вид ' + w.вид);
  if (w.окно !== ОКНО || w.слоёв !== СЛОЁВ || w.вектор !== ВЕКТОР || w.действий !== ДЕЙСТВИЙ || w.мест !== МЕСТ)
    throw new Error(`веса не под эту сеть: окно ${w.окно}/${ОКНО}, слоёв ${w.слоёв}/${СЛОЁВ}, вектор ${w.вектор}/${ВЕКТОР}, действий ${w.действий}/${ДЕЙСТВИЙ}, мест ${w.мест}/${МЕСТ}`);
  const f = (a) => Float32Array.from(a); const с = w.слои;
  return { имя: w.имя || '', описание: w.описание || '',
    c1w: f(с.c1w), c1b: f(с.c1b), c2w: f(с.c2w), c2b: f(с.c2b), c3w: f(с.c3w), c3b: f(с.c3b),
    f1w: f(с.f1w), f1b: f(с.f1b), f2w: f(с.f2w), f2b: f(с.f2b), pw: f(с.pw), pb: f(с.pb), vw: f(с.vw), vb: f(с.vb),
    К1: с.c1b.length, К2: с.c2b.length, К3: с.c3b.length, С: с.f1b.length, С2: с.f2b.length, буф: null };
}

function буферы(с) {
  if (с.буф) return с.буф;
  const П2 = (ОКНО / 2) ** 2, П4 = (ОКНО / 4) ** 2;
  return с.буф = { a1: new Float32Array(с.К1 * П), p1: new Float32Array(с.К1 * П2),
    a2: new Float32Array(с.К2 * П2), p2: new Float32Array(с.К2 * П4), a3: new Float32Array(с.К3 * П4),
    сжат: new Float32Array(с.К3 * 2), h: new Float32Array(с.С), h2: new Float32Array(с.С2),
    логиты: new Float32Array(МЕСТ * ДЕЙСТВИЙ), вер: new Float32Array(МЕСТ * ДЕЙСТВИЙ) };
}

/** Свёртка 3×3 с нулевой рамкой и ReLU. */
function свёртка(вх, Cin, H, w, b, Cout, вых) {
  const P = H * H;
  for (let o = 0; o < Cout; o++) {
    const бо = o * P, смещ = b[o];
    for (let i = 0; i < P; i++) вых[бо + i] = смещ;
    for (let c = 0; c < Cin; c++) {
      const бв = c * P, бw = (o * Cin + c) * 9;
      for (let ky = -1; ky <= 1; ky++) for (let kx = -1; kx <= 1; kx++) {
        const k = w[бw + (ky + 1) * 3 + (kx + 1)]; if (k === 0) continue;
        const y0 = Math.max(0, -ky), y1 = Math.min(H, H - ky), x0 = Math.max(0, -kx), x1 = Math.min(H, H - kx);
        for (let y = y0; y < y1; y++) {
          const ряд = бо + y * H, вряд = бв + (y + ky) * H + kx;
          for (let x = x0; x < x1; x++) вых[ряд + x] += k * вх[вряд + x];
        }
      }
    }
    for (let i = бо; i < бо + P; i++) if (вых[i] < 0) вых[i] = 0;
  }
}
/** Макс-пул 2×2. */
function пул(вх, C, H, вых) {
  const h = H >> 1;
  for (let c = 0; c < C; c++) for (let y = 0; y < h; y++) for (let x = 0; x < h; x++) {
    const i = c * H * H + 2 * y * H + 2 * x;
    let mx = вх[i]; if (вх[i + 1] > mx) mx = вх[i + 1]; if (вх[i + H] > mx) mx = вх[i + H]; if (вх[i + H + 1] > mx) mx = вх[i + H + 1];
    вых[c * h * h + y * h + x] = mx;
  }
}

/** Прямой проход: наблюдение отряда → {логиты[МЕСТ][ДЕЙСТВИЙ], вер, ценность}. */
export function вперёд(сеть, наб) {
  const б = буферы(сеть); const П4 = (ОКНО / 4) ** 2;
  свёртка(наб.окно, СЛОЁВ, ОКНО, сеть.c1w, сеть.c1b, сеть.К1, б.a1);
  пул(б.a1, сеть.К1, ОКНО, б.p1);
  свёртка(б.p1, сеть.К1, ОКНО / 2, сеть.c2w, сеть.c2b, сеть.К2, б.a2);
  пул(б.a2, сеть.К2, ОКНО / 2, б.p2);
  свёртка(б.p2, сеть.К2, ОКНО / 4, сеть.c3w, сеть.c3b, сеть.К3, б.a3);
  for (let c = 0; c < сеть.К3; c++) {
    let mx = -Infinity, сум = 0; const база = c * П4;
    for (let i = 0; i < П4; i++) { const v = б.a3[база + i]; if (v > mx) mx = v; сум += v; }
    б.сжат[c] = mx; б.сжат[сеть.К3 + c] = сум / П4;
  }
  const вх1 = сеть.К3 * 2, вх = вх1 + ВЕКТОР;
  for (let j = 0; j < сеть.С; j++) {
    let s = сеть.f1b[j]; const бw = j * вх;
    for (let i = 0; i < вх1; i++) s += сеть.f1w[бw + i] * б.сжат[i];
    for (let i = 0; i < ВЕКТОР; i++) s += сеть.f1w[бw + вх1 + i] * наб.вектор[i];
    б.h[j] = s > 0 ? s : 0;
  }
  for (let j = 0; j < сеть.С2; j++) {
    let s = сеть.f2b[j]; const бw = j * сеть.С;
    for (let i = 0; i < сеть.С; i++) s += сеть.f2w[бw + i] * б.h[i];
    б.h2[j] = s > 0 ? s : 0;
  }
  // Голова на каждое место: МЕСТ×ДЕЙСТВИЙ логитов из одного и того же скрытого слоя.
  for (let s = 0; s < МЕСТ * ДЕЙСТВИЙ; s++) {
    let v = сеть.pb[s]; const бw = s * сеть.С2;
    for (let j = 0; j < сеть.С2; j++) v += сеть.pw[бw + j] * б.h2[j];
    б.логиты[s] = v;
  }
  for (let s = 0; s < МЕСТ; s++) {
    let макс = -Infinity; const б0 = s * ДЕЙСТВИЙ;
    for (let a = 0; a < ДЕЙСТВИЙ; a++) if (б.логиты[б0 + a] > макс) макс = б.логиты[б0 + a];
    let сумма = 0;
    for (let a = 0; a < ДЕЙСТВИЙ; a++) { б.вер[б0 + a] = Math.exp(б.логиты[б0 + a] - макс); сумма += б.вер[б0 + a]; }
    for (let a = 0; a < ДЕЙСТВИЙ; a++) б.вер[б0 + a] /= сумма;
  }
  let v = сеть.vb[0];
  for (let j = 0; j < сеть.С2; j++) v += сеть.vw[j] * б.h2[j];
  return { логиты: б.логиты, вер: б.вер, ценность: v };
}

/** Политика отряда: наблюдение → массив из МЕСТ действий. Температура 0 — argmax (для партии). */
export function политика(json, { температура = 0, seed = 1 } = {}) {
  const сеть = загрузить(json);
  let сост = seed >>> 0 || 1;
  const бросок = () => { сост ^= сост << 13; сост ^= сост >>> 17; сост ^= сост << 5; return ((сост >>> 0) % 1e6) / 1e6; };
  const из = { действия: new Int32Array(МЕСТ), вер: null, ценность: 0 };
  return Object.assign((наб) => {
    const р = вперёд(сеть, наб);
    for (let s = 0; s < МЕСТ; s++) {
      const б0 = s * ДЕЙСТВИЙ;
      let a = 0;
      if (температура <= 0) { let м = -Infinity; for (let k = 0; k < ДЕЙСТВИЙ; k++) if (р.логиты[б0 + k] > м) { м = р.логиты[б0 + k]; a = k; } }
      else { let x = бросок(), сум = 0; a = ДЕЙСТВИЙ - 1; for (let k = 0; k < ДЕЙСТВИЙ; k++) { сум += р.вер[б0 + k]; if (x <= сум) { a = k; break; } } }
      из.действия[s] = a;
    }
    из.вер = р.вер; из.ценность = р.ценность;
    return из;
  }, { сеть });
}
