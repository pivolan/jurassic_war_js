// Прямой проход сети одного юнита на чистом JS (наше). Веса — из JSON, который выгружает
// tools/ai_train_bc.py / tools/ai_ppo.py. Отдельной библиотеки не берём: модель на ~80 тысяч
// параметров, проход — сотня строк и доли миллисекунды, а лишняя зависимость в браузере не нужна.
//
// Архитектура (должна побайтно совпадать с классом Сеть в tools/ai_net.py):
//   окно 8×16×16 → свёртка 3×3 8→16, ReLU, макс-пул 2 → свёртка 3×3 16→32, ReLU, макс-пул 2
//   → 32×4×4 = 512 → конкат с вектором признаков → полносвязный 128, ReLU
//   → голова политики (15 логитов) и голова ценности (1 число).
// Пулинг вместо усреднения: направление к цели — это положение в окне, усреднение его стирает.
import { ОКНО, СЛОЁВ, ВЕКТОР } from './obs.js';
import { ЧИСЛО_ДЕЙСТВИЙ } from './act.js';

/** Разобрать JSON весов в типизированные массивы. */
export function загрузить(json) {
  const w = typeof json === 'string' ? JSON.parse(json) : json;
  if (w.окно !== ОКНО || w.слоёв !== СЛОЁВ || w.вектор !== ВЕКТОР || w.действий !== ЧИСЛО_ДЕЙСТВИЙ)
    throw new Error(`веса не под эту сеть: окно ${w.окно}/${ОКНО}, слоёв ${w.слоёв}/${СЛОЁВ}, вектор ${w.вектор}/${ВЕКТОР}, действий ${w.действий}/${ЧИСЛО_ДЕЙСТВИЙ}`);
  const f = (a) => Float32Array.from(a);
  const с = w.слои;
  // Две формы сети. Старая (две свёртки, одна полносвязная) осталась ради уже обученных весов;
  // новая — глубже и шире, её признак в записи это третья свёртка c3. Просьба владельца:
  // «дай нейронке интереснее структуру, чтобы она умнее была».
  const глубокая = !!с.c3w;
  return {
    имя: w.имя || '', описание: w.описание || '', глубокая,
    c1w: f(с.c1w), c1b: f(с.c1b), c2w: f(с.c2w), c2b: f(с.c2b),
    c3w: глубокая ? f(с.c3w) : null, c3b: глубокая ? f(с.c3b) : null,
    f1w: f(с.f1w), f1b: f(с.f1b),
    f2w: глубокая ? f(с.f2w) : null, f2b: глубокая ? f(с.f2b) : null,
    pw: f(с.pw), pb: f(с.pb), vw: f(с.vw), vb: f(с.vb),
    К1: с.c1b.length, К2: с.c2b.length, К3: глубокая ? с.c3b.length : 0,
    С: с.f1b.length, С2: глубокая ? с.f2b.length : 0,
    буф: null,
  };
}

const П = ОКНО * ОКНО, П2 = (ОКНО / 2) * (ОКНО / 2), П4 = (ОКНО / 4) * (ОКНО / 4);

/** Рабочие массивы сети, выделенные один раз: на каждом решении их переиспользуем. */
function буферы(сеть) {
  if (сеть.буф) return сеть.буф;
  return сеть.буф = {
    a1: new Float32Array(сеть.К1 * П), p1: new Float32Array(сеть.К1 * П2),
    a2: new Float32Array(сеть.К2 * П2), p2: new Float32Array(сеть.К2 * П4),
    a3: new Float32Array((сеть.К3 || 1) * П4), сжат: new Float32Array((сеть.К3 || 1) * 2),
    h: new Float32Array(сеть.С), h2: new Float32Array(сеть.С2 || 1),
    логиты: new Float32Array(ЧИСЛО_ДЕЙСТВИЙ), вер: new Float32Array(ЧИСЛО_ДЕЙСТВИЙ),
  };
}

/** Свёртка 3×3 с нулевой рамкой и ReLU: вх [Cin,H,H] → вых [Cout,H,H]; веса [Cout,Cin,3,3]. */
function свёртка(вх, Cin, H, w, b, Cout, вых) {
  const P = H * H;
  for (let o = 0; o < Cout; o++) {
    const бо = o * P, смещ = b[o];
    вых.fill(смещ, бо, бо + P);
    for (let c = 0; c < Cin; c++) {
      const бв = c * P, бw = (o * Cin + c) * 9;
      for (let ky = -1; ky <= 1; ky++) {
        const y0 = ky < 0 ? 1 : 0, y1 = ky > 0 ? H - 1 : H;
        for (let kx = -1; kx <= 1; kx++) {
          const k = w[бw + (ky + 1) * 3 + (kx + 1)];
          const x0 = kx < 0 ? 1 : 0, x1 = kx > 0 ? H - 1 : H;
          for (let y = y0; y < y1; y++) {
            const ряд = бо + y * H, вряд = бв + (y + ky) * H + kx;
            for (let x = x0; x < x1; x++) вых[ряд + x] += k * вх[вряд + x];
          }
        }
      }
    }
    for (let i = бо; i < бо + P; i++) if (вых[i] < 0) вых[i] = 0;
  }
}
/** Макс-пул 2×2. */
function пул(вх, C, H, вых) {
  const h = H >> 1;
  for (let c = 0; c < C; c++) for (let y = 0; y < h; y++) for (let x = 0; x < h; x++) {
    const i = c * H * H + 2 * y * H + 2 * x;
    let m = вх[i]; if (вх[i + 1] > m) m = вх[i + 1]; if (вх[i + H] > m) m = вх[i + H]; if (вх[i + H + 1] > m) m = вх[i + H + 1];
    вых[c * h * h + y * h + x] = m;
  }
}

/**
 * Прямой проход: наблюдение {окно, вектор} → {логиты, вер (softmax), ценность}.
 *
 * Две формы, обе байт в байт совпадают с классами в tools/ai_net.py:
 *   старая:   16×16×11 → св.3×3 →16, пул → св.3×3 →32, пул → 512 ⊕ вектор → 128 → головы;
 *   глубокая: 16×16×11 → св.3×3 →24, пул → св.3×3 →48, пул → св.3×3 →64 (без пула)
 *             → сжатие по каналам (макс и среднее сразу) → 128 ⊕ вектор → 256 → 128 → головы.
 * Сжатие вместо развёртки всей карты 64×4×4 делает вход полносвязного втрое меньше при большем
 * числе каналов: сеть получает «что есть в окне» (макс) и «сколько этого» (среднее), а не
 * привязку признака к клетке — привязку и так дают свёртки.
 */
export function вперёд(сеть, наб) {
  const б = буферы(сеть);
  свёртка(наб.окно, СЛОЁВ, ОКНО, сеть.c1w, сеть.c1b, сеть.К1, б.a1);
  пул(б.a1, сеть.К1, ОКНО, б.p1);
  свёртка(б.p1, сеть.К1, ОКНО / 2, сеть.c2w, сеть.c2b, сеть.К2, б.a2);
  пул(б.a2, сеть.К2, ОКНО / 2, б.p2);
  let вх1, вхБуф;
  if (сеть.глубокая) {
    свёртка(б.p2, сеть.К2, ОКНО / 4, сеть.c3w, сеть.c3b, сеть.К3, б.a3);
    for (let c = 0; c < сеть.К3; c++) {
      let м = -Infinity, сум = 0; const база = c * П4;
      for (let i = 0; i < П4; i++) { const v = б.a3[база + i]; if (v > м) м = v; сум += v; }
      б.сжат[c] = м; б.сжат[сеть.К3 + c] = сум / П4;
    }
    вх1 = сеть.К3 * 2; вхБуф = б.сжат;
  } else { вх1 = сеть.К2 * П4; вхБуф = б.p2; }
  const вх = вх1 + ВЕКТОР;                          // вход полносвязного: [сжатое окно, вектор]
  const h = б.h;
  for (let j = 0; j < сеть.С; j++) {
    let s = сеть.f1b[j]; const бw = j * вх;
    for (let i = 0; i < вх1; i++) s += сеть.f1w[бw + i] * вхБуф[i];
    for (let i = 0; i < ВЕКТОР; i++) s += сеть.f1w[бw + вх1 + i] * наб.вектор[i];
    h[j] = s > 0 ? s : 0;
  }
  // Глубокая форма: ещё один полносвязный слой перед головами.
  let голова = h, ширина = сеть.С;
  if (сеть.глубокая) {
    for (let j = 0; j < сеть.С2; j++) {
      let s = сеть.f2b[j]; const бw = j * сеть.С;
      for (let i = 0; i < сеть.С; i++) s += сеть.f2w[бw + i] * h[i];
      б.h2[j] = s > 0 ? s : 0;
    }
    голова = б.h2; ширина = сеть.С2;
  }
  let макс = -Infinity;
  for (let a = 0; a < ЧИСЛО_ДЕЙСТВИЙ; a++) {
    let s = сеть.pb[a]; const бw = a * ширина;
    for (let j = 0; j < ширина; j++) s += сеть.pw[бw + j] * голова[j];
    б.логиты[a] = s; if (s > макс) макс = s;
  }
  let сумма = 0;
  for (let a = 0; a < ЧИСЛО_ДЕЙСТВИЙ; a++) { б.вер[a] = Math.exp(б.логиты[a] - макс); сумма += б.вер[a]; }
  for (let a = 0; a < ЧИСЛО_ДЕЙСТВИЙ; a++) б.вер[a] /= сумма;
  let v = сеть.vb[0];
  { const г = сеть.глубокая ? б.h2 : h, ш = сеть.глубокая ? сеть.С2 : сеть.С;
    for (let j = 0; j < ш; j++) v += сеть.vw[j] * г[j]; }
  return { логиты: б.логиты, вер: б.вер, ценность: v };
}

/** Выбрать действие из распределения (сэмплирование, не argmax — иначе одна сцена всегда
 *  разыгрывается одинаково). `сл` — генератор в [0,1); температура 0 даёт argmax. */
export function выбрать(вер, сл = Math.random, температура = 1) {
  if (температура <= 0) { let k = 0; for (let a = 1; a < вер.length; a++) if (вер[a] > вер[k]) k = a; return k; }
  let r = сл(), сумма = 0;
  if (температура !== 1) {
    const t = new Float64Array(вер.length); let z = 0;
    for (let a = 0; a < вер.length; a++) { t[a] = Math.pow(вер[a], 1 / температура); z += t[a]; }
    for (let a = 0; a < вер.length; a++) { сумма += t[a] / z; if (r < сумма) return a; }
    return вер.length - 1;
  }
  for (let a = 0; a < вер.length; a++) { сумма += вер[a]; if (r < сумма) return a; }
  return вер.length - 1;
}
