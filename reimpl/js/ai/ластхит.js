// ЛАСТХИТ ПО ФОРМУЛАМ: последний удар по зверю — назначенному бойцу, чтобы опыт за убийство шёл
// тому, кого качаем. Владелец: «должно быть значительно проще, тупо по формулам, у нас же есть все
// данные» — и правда, ближний бой в движке детерминирован целиком:
//
//   • удар человека (типы 1–8) — в шаг, когда счётчик анимации (+ATKCTR) переходит с 7 на 8, дальше
//     раз в 8 шагов; ящера и зверя (тип 9+) — на счётчике 6, дальше раз в 6 (0x1a7cb);
//   • урон — формула 0x1e934 с таблицами оружия и щита (уронПо), без случайности;
//   • регенерация +1 — в шаг, где младший счётчик шагов (G.stepLow) обнулился (0x18ab2), в очередь
//     самого зверя;
//   • внутри шага юниты ходят в порядке списка движка — кто раньше в списке, тот раньше бьёт;
//   • приказ «стоп», отданный сейчас, срабатывает в начале следующего шага, раньше удара; если на
//     следующем шаге снова дать «атаку», пропущенный удар человека переедет на +7 шагов, ящера — на
//     +6 (замер: стоп на 65, атака на 66, удар на 72; у раптора 62 → 68).
//
// Поэтому план считается перебором по этим формулам: на каждом чужом ударе ветвимся «бей» или
// «пропусти» (смертельный чужой — только «пропусти») и ищем самый ранний шаг, когда добивает
// назначенный. Из лучшего плана берём действие на ближайший шаг: кому сейчас «стоп».
import { G, U, UNITS, BI } from '../mem.js';
import { проходима } from './act.js';
import { приказ, КОД } from '../port/inject.js';

const жив = (m, i) => !!i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.HP) > 0
                      && (m.u8(UNITS + i + U.STATE) & 0xf0) !== 0x60;
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
const ПЕРИОД = (тип) => (тип < 9 ? 8 : 6);
const ПЕРЕНОС = (тип) => (тип < 9 ? 7 : 6);                  // куда уезжает пропущенный удар

/** Через сколько шагов боец ударит цель (1 — в ближайший), или 0, если сейчас он её не бьёт. */
export function доУдара(m, i, цель) {
  if (m.u8(UNITS + i + U.STATE) !== 0x10 || m.u32(UNITS + i + U.TARGET) !== цель) return 0;
  const a = кл(m, i), b = кл(m, цель);
  if (Math.max(Math.abs(a.x - b.x), Math.abs(a.y - b.y)) > 1) return 0;
  const c = m.u8(UNITS + i + U.ATKCTR);
  if (m.u8(UNITS + i + U.TYPE) < 9) return c <= 7 ? 8 - c : 0;
  return c <= 6 ? 7 - c : 6;
}

/** Опыт и статы бойца — по ним видно, кто добил (для сцен и замеров). */
export const отпечатокОпыта = (m, i) => ({ xp: m.u32(UNITS + i + U.XP),
  статы: m.u8(UNITS + i + U.HPMAX) + m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.SPD) + m.u8(UNITS + i + U.MAG) });
export const добил = (m, i, было) => { const с = отпечатокОпыта(m, i); return с.статы > было.статы || с.xp - было.xp > 10; };

export const новое = () => ({ цель: 0, держим: new Map(), уступили: new Map(), стопов: 0, отказ: false, уступок: 0, решений: 0 });
export const неТрогать = (лх) => new Set([...лх.держим.keys(), ...лх.уступили.keys()]);

/**
 * План боя по формулам. бойцы: [{ i, тип, урон, след, порядок }], где след — шаг ближайшего удара
 * (0 — не бьёт). Возвращает { шаг, кто, стопСейчас:Set } — самый ранний шаг, когда добивает
 * назначенный (или Infinity), и кого из бьющих в ближайший шаг надо остановить.
 */
function план(hp, max, реген0, порядокЗверя, бойцы, назначен, ГОРИЗОНТ, ПРОПУСКОВ) {
  let лучший = { шаг: Infinity, стопСейчас: null };
  const n = бойцы.length;
  // Рекурсивно по шагам: состояние — жизни, шаги ближайших ударов, сколько ещё можно пропускать.
  // Уже разобранное состояние второй раз ничего не даст: лучший шаг только уменьшается и заменяется
  // лишь строго меньшим, а всё, что достижимо отсюда, первый заход уже нашёл.
  const было = new Set();
  const идти = (k, hp, след, пропусков, стопы1) => {
    if (k > ГОРИЗОНТ || k >= лучший.шаг) return;
    const ключ = k + ':' + hp + ':' + пропусков + ':' + след.join(',');
    if (было.has(ключ)) return;
    было.add(ключ);
    // события шага k по порядку списка: реген зверя и удары
    const событ = [];
    if (((реген0 + k) & 15) === 0) событ.push({ порядок: порядокЗверя, реген: true });
    for (let j = 0; j < n; j++) if (след[j] === k) событ.push({ порядок: бойцы[j].порядок, j });
    if (!событ.length) { // до ближайшего события — прыжком
      let nk = ГОРИЗОНТ + 1; for (let j = 0; j < n; j++) if (след[j] > k && след[j] < nk) nk = след[j];
      const r = 16 - ((реген0 + k) & 15); if (k + r < nk) nk = k + r;
      return идти(nk, hp, след, пропусков, стопы1);
    }
    событ.sort((a, b) => a.порядок - b.порядок);
    // перебор по событиям шага: для каждого чужого удара — «бей»/«пропусти»
    const поСобытиям = (e, hp, след, пропусков, стопы1) => {
      if (e === событ.length) return идти(k + 1, hp, след, пропусков, стопы1);
      const с = событ[e];
      if (с.реген) return поСобытиям(e + 1, Math.min(max, hp + 1), след, пропусков, стопы1);
      const б = бойцы[с.j], дальше = след.slice(); дальше[с.j] = k + ПЕРИОД(б.тип);
      if (б.i === назначен) {
        if (hp - б.урон <= 0) { if (k < лучший.шаг) лучший = { шаг: k, стопСейчас: стопы1 }; return; }
        return поСобытиям(e + 1, hp - б.урон, дальше, пропусков, стопы1);
      }
      const смертелен = hp - б.урон <= 0;
      // пропустить
      if (смертелен || пропусков > 0) {
        const пр = след.slice(); пр[с.j] = k + ПЕРЕНОС(б.тип);
        const с1 = k === 1 ? new Set([...(стопы1 || []), б.i]) : стопы1;
        поСобытиям(e + 1, hp, пр, смертелен ? пропусков : пропусков - 1, с1);
      }
      if (!смертелен) поСобытиям(e + 1, hp - б.урон, дальше, пропусков, стопы1);
    };
    поСобытиям(0, hp, след, пропусков, стопы1);
  };
  идти(1, hp, бойцы.map(б => б.след), ПРОПУСКОВ, new Set());
  return лучший;
}

/** Без ластхита: на каком шаге зверь умрёт (для допуска). */
function естественно(hp, max, реген0, порядокЗверя, бойцы, ГОРИЗОНТ) {
  const след = бойцы.map(б => б.след);
  for (let k = 1; k <= ГОРИЗОНТ; k++) {
    const событ = [];
    if (((реген0 + k) & 15) === 0) событ.push({ порядок: порядокЗверя, реген: true });
    for (let j = 0; j < бойцы.length; j++) if (след[j] === k) событ.push({ порядок: бойцы[j].порядок, j });
    событ.sort((a, b) => a.порядок - b.порядок);
    for (const с of событ) {
      if (с.реген) { hp = Math.min(max, hp + 1); continue; }
      hp -= бойцы[с.j].урон; след[с.j] = k + ПЕРИОД(бойцы[с.j].тип);
      if (hp <= 0) return k;
    }
  }
  return Infinity;
}

/**
 * Шаг ластхита. Зовётся после того, как отряд отдал приказы на этот шаг.
 * @param уронПо (m, кто, кого) → урон за удар (с оружием и щитом)
 * @param опции { ДОПУСК: на сколько шагов можно затянуть бой ради назначенного, ПРОПУСКОВ: глубина }
 */
export function шаг(eng, лх, цель, назначен, бойцы, уронПо, опции = {}) {
  const m = eng.m, ДОПУСК = опции.ДОПУСК ?? 24, ГОРИЗОНТ = опции.ГОРИЗОНТ ?? 160, ПРОПУСКОВ = опции.ПРОПУСКОВ ?? 6;
  if (лх.цель !== цель) { лх.цель = цель; лх.держим.clear(); лх.уступили.clear(); лх.отказ = false; лх.ждёмС = null; }
  // Остановленных на прошлом шаге — снова в бой (пропуск рассчитан как «стоп, потом сразу атака»).
  for (const [i] of лх.держим) if (жив(m, i)) приказ(eng, i, КОД.АТАКА, цель, m.u16(UNITS + цель + U.X), m.u16(UNITS + цель + U.Y));
  лх.держим.clear();
  if (лх.отказ) for (const [i] of лх.уступили) { приказ(eng, i, КОД.АТАКА, цель, m.u16(UNITS + цель + U.X), m.u16(UNITS + цель + U.Y)); лх.уступили.delete(i); }
  if (!жив(m, цель) || !назначен || лх.отказ || !бойцы.includes(назначен)) return { стоп: 0 };
  // Порядок в списке движка — кто раньше ходит в шаге.
  const порядок = new Map(); let n = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) порядок.set(i, n++);
  const б = бойцы.filter(i => жив(m, i)).map(i => ({ i, тип: m.u8(UNITS + i + U.TYPE), урон: уронПо(m, i, цель),
                                                   след: доУдара(m, i, цель), порядок: порядок.get(i) ?? 0 }));
  // Следим, только когда до смерти зверя недалеко: три круга ударов всех, кто при нём.
  {
    const hp0 = m.u8(UNITS + цель + U.HP), заКруг0 = б.reduce((a, x) => a + x.урон, 0);
    if (hp0 > заКруг0 * 3 + 2) return { стоп: 0 };
  }
  const цк = кл(m, цель), нк = кл(m, назначен);
  const далеко = (a, c) => Math.max(Math.abs(a.x - c.x), Math.abs(a.y - c.y));
  // МЕСТО НАЗНАЧЕННОМУ. У зверя в тупике два-три свободных бока, и их могут занять другие — тогда
  // назначенный не ударит вовсе. Если свободного бока нет, а назначенный рядом и ждёт, ближайший к
  // нему из стоящих вплотную отходит на клетку и ждёт, пока назначенный не встанет к зверю.
  if (далеко(нк, цк) <= 1) for (const [i] of лх.уступили) { приказ(eng, i, КОД.АТАКА, цель, m.u16(UNITS + цель + U.X), m.u16(UNITS + цель + U.Y)); лх.уступили.delete(i); }
  let свободных = 0;
  for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++)
    if ((dx || dy) && проходима(m, цк.x + dx, цк.y + dy) && !(m.u8(BI + цк.x + dx + ((цк.y + dy) << 8)) & 0xfc)) свободных++;
  if (далеко(нк, цк) > 1 && далеко(нк, цк) <= 3 && !свободных && !лх.уступили.size) {
    const кто = бойцы.filter(i => i !== назначен && жив(m, i) && далеко(кл(m, i), цк) <= 1)
                     .sort((a, b) => далеко(кл(m, a), нк) - далеко(кл(m, b), нк))[0];
    if (кто) {
      const ck = кл(m, кто); let куда = null, оц = -1e9;
      for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dy)) !== 2) continue;
        const x = цк.x + dx, y = цк.y + dy;
        if (!проходима(m, x, y) || (m.u8(BI + x + (y << 8)) & 0xfc)) continue;
        const о = далеко({ x, y }, нк) - далеко({ x, y }, ck) * 0.5;
        if (о > оц) { оц = о; куда = { x, y }; }
      }
      if (куда) {
        приказ(eng, кто, КОД.ИДТИ, 0, куда.x << 5, куда.y << 5);
        приказ(eng, назначен, КОД.АТАКА, цель, m.u16(UNITS + цель + U.X), m.u16(UNITS + цель + U.Y));
        лх.уступили.set(кто, куда); лх.уступок++;
      }
    }
  }
  // Назначенный ещё идёт к зверю (рядом, в пределах трёх клеток) — считаем, что ударит не раньше
  // чем через 9 шагов (подход и замах), и всё равно не даём добить чужим.
  if (!б.some(x => x.i === назначен && x.след > 0)) {
    const н = б.find(x => x.i === назначен);
    if (!н || далеко(нк, цк) > 3) return { стоп: 0 };
    // Ждём назначенного не дольше ЖДАТЬ шагов: не дошёл — отступаемся, пусть добивает кто придётся.
    if (далеко(нк, цк) > 1) {
      лх.ждёмС ??= m.u32(G.step);
      if (m.u32(G.step) - лх.ждёмС > (опции.ЖДАТЬ ?? 100)) { лх.отказ = true; return { стоп: 0 }; }
      н.след = 9;
    } else {
      // Уже вплотную, но между ударами: после подхода он стоит в паузе 0x12 (счётчик идёт вниз),
      // потом входит в 0x10 со счётчиком 2 и бьёт через 6 шагов.
      лх.ждёмС = null;
      const ст = m.u8(UNITS + назначен + U.STATE), c = m.u8(UNITS + назначен + U.ATKCTR);
      н.след = ст === 0x12 ? c + 7 : 8;
    }
  } else лх.ждёмС = null;
  const бьют = б.filter(x => x.след > 0);
  const hp = m.u8(UNITS + цель + U.HP), max = m.u8(UNITS + цель + U.HPMAX);
  const реген0 = m.u16(G.stepLow), пз = порядок.get(цель) ?? 0;
  лх.решений++;
  const сам = естественно(hp, max, реген0, пз, бьют, ГОРИЗОНТ);
  const п = план(hp, max, реген0, пз, бьют, назначен, ГОРИЗОНТ, ПРОПУСКОВ);
  if (п.шаг === Infinity && сам === Infinity) return { стоп: 0 };     // зверь пока вне досягаемости — решать рано
  if (п.шаг === Infinity || п.шаг - сам > ДОПУСК) { if (globalThis.process?.env?.ЛХ_ОТЛАДКА) console.error('отказ', m.u32(G.step), 'hp', hp, 'сам', сам, 'план', п.шаг, JSON.stringify(бьют)); лх.отказ = true; return { стоп: 0, сам, план: п.шаг }; }
  for (const i of п.стопСейчас || []) { приказ(eng, i, КОД.СТОП); лх.держим.set(i, true); лх.стопов++; }
  return { стоп: п.стопСейчас?.size || 0, сам, план: п.шаг };
}
