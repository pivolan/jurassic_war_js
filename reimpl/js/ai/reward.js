// Награды по ролям (наше).
//
// Итог эпизода считается градуированно, а не «победил / не победил»: сумма долей — сколько
// здоровья осталось у охраняемого объекта, сколько врагов отвлечено или убито, сколько шагов
// объект продержался, выжил ли сам боец. Тогда «база умерла, но медленнее» само по себе
// приносит очки, и сети не нужно объяснять словами, что отвлечь восьмерых и выжить лучше,
// чем героически погибнуть после одного удара.
//
// Подсказки (shaping) держим В РАЗЫ меньше итоговой части. Это главная и самая незаметная
// ошибка в такой задаче: если платить за нанесённый урон наравне с исходом, получится берсерк,
// который бьёт что попало и никогда не отвлекает и не отступает.
import { G, U, UNITS } from '../mem.js';
import { жив } from './act.js';

// Веса подсказок. Урон считается ДОЛЕЙ от начального запаса здоровья соответствующей стороны,
// а не в единицах HP: иначе вес подсказки зависит от того, сколько народу в сцене, и на большой
// свалке подсказки перевешивают исход. Замер на скриптовом учителе до этой правки: в «обороне
// дома» исход +0.81, а подсказки +1.25 — ровно тот случай, от которого предупреждает план.
// Сейчас потолок подсказок за эпизод примерно от -0.6 до +0.25 при исходе порядка единицы.
export const ПОДСКАЗКИ = {
  урон_нанесён: 0.25,       // за весь запас здоровья врагов, снятый целиком
  урон_получен: -0.20,      // за весь наш запас, потерянный целиком
  урон_объекта: -0.25,      // за весь запас охраняемого объекта
  шаг: -0.0008,             // лёгкий штраф за время — чтобы не тянул
  осцилляция: -0.03,        // вернулся туда, где был два решения назад
  лечение: 0.15,            // за весь наш запас, восстановленный (сном или едой) — не за сам сон
  темп: -0.01,              // отход при явном перевесе (обмен ≤ ПЕРЕВЕС): потеря темпа, надо добивать
};

/** Снимок величин, из которых считаются награды. */
export function замер(eng, эп) {
  const m = eng.m;
  const с = { hp: 0, hpмакс: 0, врагиHP: 0, враговЖивых: 0, охраняемыйHP: 0, наНас: 0, позиции: [] };
  for (const i of эп.наши) if (жив(m, i)) { с.hp += m.u8(UNITS + i + U.HP); с.hpмакс += m.u8(UNITS + i + U.HPMAX); }
  for (const i of эп.враги) {
    if (!жив(m, i)) continue;
    с.враговЖивых++;
    с.врагиHP += m.u8(UNITS + i + U.HP);
    const ц = m.u32(UNITS + i + U.TARGET);
    if (ц && эп.наши.includes(ц)) с.наНас++;          // отвлёкся на нас, а не на объект
  }
  if (эп.охраняемый) с.охраняемыйHP = жив(m, эп.охраняемый) ? m.u8(UNITS + эп.охраняемый + U.HP) : 0;
  for (const i of эп.наши) с.позиции.push(жив(m, i) ? (m.u16(UNITS + i + U.X) >> 5) + ((m.u16(UNITS + i + U.Y) >> 5) << 8) : -1);
  return с;
}

/** Награда за одно решение: только подсказки, итог считается отдельно. */
export function заШаг(eng, эп, было, стало, история) {
  let r = ПОДСКАЗКИ.шаг;
  // Строителю за нанесённый урон не платим: он не должен драться (правило владельца).
  if (!эп.строитель) r += ПОДСКАЗКИ.урон_нанесён * Math.max(0, было.врагиHP - стало.врагиHP) / (эп.врагиHP0 || 1);
  r += ПОДСКАЗКИ.урон_получен * Math.max(0, было.hp - стало.hp) / (эп.нашиHP0 || 1);
  r += ПОДСКАЗКИ.лечение * Math.max(0, стало.hp - было.hp) / (эп.нашиHPмакс || эп.нашиHP0 || 1);
  if (эп.охраняемый)
    r += ПОДСКАЗКИ.урон_объекта * Math.max(0, было.охраняемыйHP - стало.охраняемыйHP) / (эп.охраняемыйHPмакс || 1);
  // Несколько бойцов под сетью: подсказка за шаг и осцилляция считались бы по каждому и росли с
  // числом бойцов (в «три на три» −1.98 против исхода +0.32 — грабля №4). Делим на живых.
  const живых = эп.наши.filter(i => жив(eng.m, i)).length || 1;
  r = r / живых;
  // Осцилляция: вернулся в клетку, где стоял два решения назад, и при этом никуда не воюет.
  if (история.length >= 2) {
    const позапрошлые = история[история.length - 2];
    for (let k = 0; k < стало.позиции.length; k++)
      if (стало.позиции[k] >= 0 && позапрошлые[k] === стало.позиции[k] && было.позиции[k] !== стало.позиции[k])
        r += ПОДСКАЗКИ.осцилляция / живых;
  }
  return r;
}

/**
 * Итог эпизода по роли. Все составляющие — доли от 0 до 1, сумма весов равна 1,
 * так что итог лежит примерно в [-1, +1] и подсказки его не перевешивают.
 */
export function итог(eng, эп) {
  const m = eng.m;
  const с = замер(eng, эп);
  const выжило = эп.наши.filter(i => жив(m, i)).length / (эп.наши.length || 1);
  // Градуированный результат: «погиб позже» лучше, чем «погиб сразу». Без этого в сценах, где
  // выжить почти нельзя, у сети нет градиента — все исходы одинаково нулевые.
  // Если боец (объект) жив в конце — доля прожитого равна единице, сколько бы эпизод ни длился:
  // иначе быстрая победа наказывалась бы за то, что эпизод кончился рано.
  const прожил = выжило > 0 ? 1 : (эп.шаговВсего ? Math.min(1, эп.шаговЖив / эп.шаговВсего) : 0);
  // Убито — с учётом опасности (здоровье × атака на старте): маг весит больше пса.
  let опВсего = 0, опУбито = 0;
  for (const i of эп.враги) { const w = эп.опасность ? (эп.опасность.get(i) || 1) : 1; опВсего += w; if (!жив(m, i)) опУбито += w; }
  const убито = опВсего ? опУбито / опВсего : 0;
  const отвлечено = с.враговЖивых ? с.наНас / с.враговЖивых : (эп.враговВсего ? 1 : 0);
  const объект = эп.охраняемый ? с.охраняемыйHP / (эп.охраняемыйHPмакс || 1) : 0;
  const продержался = эп.охраняемый ? (с.охраняемыйHP > 0 ? 1 : эп.шаговОбъект / эп.шаговВсего) : 0;
  const дошёл = эп.точка ? доля_дошёл(m, эп) : 0;
  const здоров = с.hpмакс ? с.hp / с.hpмакс : 0;                   // доля здоровья живых в конце
  // Отвлечено — не только в конце, а в среднем за эпизод: сколько врагов держались на бойце.
  const отвлекал = эп.отвлечённостьЧисло ? эп.отвлечённостьСумма / эп.отвлечённостьЧисло : 0;
  const разрушен = эп.охраняемый && !жив(m, эп.охраняемый) ? 1 : 0;
  // Бессмысленная смерть: роль не требовала умереть на месте (вес < «любой ценой»), обмен на старте
  // был заведомо проигрышный (больше 2:1), а боец всё-таки погиб — штраф поверх исхода.
  const зря = выжило === 0 && эп.вес < 2 && (эп.обменСтарт || 0) > 2 && эп.роль !== 'RETREAT' ? 0.3 : 0;
  const собрано = эп.едыВсего ? Math.min(1, еда(m, эп) / эп.едыВсего) : 0;

  switch (эп.роль) {
    case 'ATTACK_TO_DEATH':
      return 0.60 * убито + 0.25 * выжило + 0.15 * прожил - зря;
    case 'DEFEND_POINT':
      // Выживание весит больше, чем раньше: с сильными врагами «бить до последнего» иначе
      // выигрывало — звери, убив защитника, уходят пастись и дом стоит.
      return 0.35 * объект + 0.15 * продержался + 0.30 * выжило + 0.10 * убито + 0.10 * прожил - зря;
    case 'DISTRACT':
      // За убийство тут НЕ платим: цель не в том, чтобы убить, а в том, чтобы увести на себя.
      // Главное — сколько врагов и как долго держались на бойце (среднее за эпизод), затем
      // здоровье дома; его гибель — большой штраф, чтобы «ушёл и выжил» не считалось успехом.
      return 0.30 * отвлекал + 0.25 * объект + 0.10 * продержался + 0.10 * прожил + 0.25 * выжило - 0.5 * разрушен - зря;
    case 'RETREAT':
      // Здоровье в конце — тоже часть исхода: отступивший и подлечившийся лучше просто уцелевшего.
      return 0.35 * выжило + 0.30 * прожил + 0.15 * (1 - Math.min(1, с.наНас / (эп.враговВсего || 1))) + 0.20 * здоров;
    case 'HOLD':
      return 0.45 * выжило + 0.30 * держит(m, эп) + 0.15 * убито + 0.10 * прожил - зря;
    case 'GATHER':
      // Еда в руках — главное; выжить — тоже, чтобы не лез за мясом под нос хищнику.
      return 0.60 * собрано + 0.30 * выжило + 0.10 * прожил;
    case 'MOVE_TO':
    default:
      return 0.70 * дошёл + 0.30 * выжило;
  }
}

/** Сколько еды набрал отряд за эпизод (поле FOOD, разница с началом). */
export function еда(m, эп) {
  // FOOD — знаковое: люди платят едой за лечение, и у бойца без еды поле уходит в минус.
  let s = 0;
  for (const i of эп.наши) if (жив(m, i)) s += (m.u16(UNITS + i + U.FOOD) << 16) >> 16;
  return Math.max(0, s - (эп.еда0 || 0));
}

/** Насколько отряд дошёл до точки задания: 0 — стоит на старте, 1 — на месте. */
function доля_дошёл(m, эп) {
  let лучшее = 0;
  for (const i of эп.наши) {
    if (!жив(m, i)) continue;
    const d = Math.max(Math.abs((m.u16(UNITS + i + U.X) >> 5) - эп.точка.x),
                       Math.abs((m.u16(UNITS + i + U.Y) >> 5) - эп.точка.y));
    лучшее = Math.max(лучшее, Math.max(0, 1 - d / (эп.дистанция || 16)));
  }
  return лучшее;
}
/** Держит ли отряд свою точку: доля живых, стоящих рядом с ней. */
function держит(m, эп) {
  if (!эп.точка) return 0;
  let вместе = 0;
  for (const i of эп.наши) {
    if (!жив(m, i)) continue;
    const d = Math.max(Math.abs((m.u16(UNITS + i + U.X) >> 5) - эп.точка.x),
                       Math.abs((m.u16(UNITS + i + U.Y) >> 5) - эп.точка.y));
    if (d <= 2) вместе++;
  }
  return вместе / (эп.наши.length || 1);
}
