// Политика «нейронка»: наблюдение → прямой проход сети → сэмплированное действие (наше).
// Подключается так же, как скриптовый учитель: политика(eng, боец, эп, наб) → номер действия.
import { загрузить, вперёд, выбрать } from './net.js';

/** Воспроизводимый генератор для сэмплирования (общий на политику). */
export function генератор(seed = 1) {
  let s = (seed >>> 0) || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
}

/**
 * Сделать политику из JSON весов.
 * @param температура 1 — как учили; 0 — argmax (для показа «что сеть считает лучшим»).
 * Возвращаемая функция хранит в .последнее распределение и ценность последнего решения — для стенда.
 */
export function политикаСети(json, { температура = 1, seed = 1 } = {}) {
  const сеть = загрузить(json), сл = генератор(seed);
  const п = (eng, боец, эп, наб) => {
    const { логиты, вер, ценность } = вперёд(сеть, наб);
    // При нулевой температуре берём argmax по логитам, а не по вероятностям: softmax считает
    // Math.exp, а он в стандарте языка не задан точно — на другой машине последние биты могут
    // разойтись и на почти равных действиях выбор перевернётся. В партии это разъехавшийся
    // локстеп; по логитам сравнение точное.
    const действие = выбрать(температура <= 0 ? логиты : вер, сл, температура);
    п.последнее = { вер: Float32Array.from(вер), ценность, действие };
    return действие;
  };
  п.сеть = сеть;
  return п;
}
