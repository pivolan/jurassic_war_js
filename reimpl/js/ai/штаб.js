/**
 * СПРОСИТЬ ВНЕШНИЙ МОЗГ. Если в состоянии лежит `с.спросить(сводка, ВАРИАНТЫ) → Promise<вид>`,
 * штаб раз в такт отправляет ему сводку и, когда придёт ответ, кладёт его в с.приказ. Ждать ответа
 * никто не будет: пока его нет, работает скриптовое решение. Так сюда встаёт ДЖЕВ (через наш
 * прокси /jw/jev, tools/jev_прокси.mjs) и так же встанет сеть штаба.
 * Один вопрос в полёте за раз — иначе очередь запросов растёт быстрее, чем приходят ответы.
 */
function мозгом(с, св, угодья, заказы) {
  с.последняяСводка = св;                    // её же читают стенд и строка состояния
  if (typeof с.спросить !== 'function' || с.вПолёте) return;
  с.вПолёте = true;
  Promise.resolve(с.спросить(св, ВАРИАНТЫ, угодья, заказы)).then(о => {
    // Ответ либо одним словом (что делать), либо решением целиком: {вид, угодье}.
    const вид = typeof о === 'string' ? о : о?.вид;
    if (вид && ВАРИАНТЫ[вид]) {
      с.приказ = вид; с.мозг = вид; с.мозгКогда = Date.now();
      // НОВЫЙ ОТВЕТ ОТМЕНЯЕТ ПРЕЖНИЙ ПРИКАЗ СРАЗУ. Владелец: «а потом может ли ДЖЕВ снимать этот
      // приказ, чтобы назначить что-то другое — к примеру, надо отрядам начать нападение куда-то».
      // Поэтому решение пересматривается в тот же тик, а не через оставшиеся секунды такта.
      с.решено = -1e9;
      // Уходя с охоты, отпускаем закреплённое угодье: вернёмся — выберем заново по обстановке.
      if (вид !== 'охота' && вид !== 'зачистка' && вид !== 'марш') с.угодьеМозга = null;
    }
    if (о && typeof о === 'object' && о.угодье !== undefined && о.угодье !== null) с.мозгУгодье = о.угодье;
    // Что заказать — решение мозга: дом в Святилище или бойца в готовом доме. ПРОРАБ выполняет,
    // место под дом выбирает сам.
    if (о && typeof о === 'object' && о.дом !== undefined && о.дом !== null) с.мозгДом = о.дом;
    if (о && typeof о === 'object' && о.боец) с.мозгБоец = о.боец;
  }).catch(e => { с.мозгОшибка = String(e && e.message || e); })
    .finally(() => { с.вПолёте = false; });
}

/** Кучки логова: где зверьё РОЖДАЕТСЯ. Считаются один раз на карту — точки не меняются. */
function кучки(m, с) {
  if (с.кучкиКарты && с.кучкиДля === m.u32(G.mapW) * 1000 + m.u8(G.mission)) return с.кучкиКарты;
  const точки = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (!ЗВЕРЬ(m.u8(UNITS + i + U.TYPE))) continue;
    точки.push({ н: i, x: m.u8(UNITS + i + 0x59), y: m.u8(UNITS + i + 0x5a) });
  }
  const к = [];
  for (const т of точки) {
    const своя = к.find(g => далеко(g, т) <= КУЧКА);
    if (своя) { своя.звери.push(т.н); своя.x = Math.round((своя.x * (своя.звери.length - 1) + т.x) / своя.звери.length);
                своя.y = Math.round((своя.y * (своя.звери.length - 1) + т.y) / своя.звери.length); }
    else к.push({ x: т.x, y: т.y, звери: [т.н] });
  }
  с.кучкиКарты = к; с.кучкиДля = m.u32(G.mapW) * 1000 + m.u8(G.mission);
  return к;
}

