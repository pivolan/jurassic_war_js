/**
 * Кто такой этот зверь В НАШИХ ЦИФРАХ: сколько мы снимаем с него за удар, сколько он с нас, и
 * проходит ли размен по расчёту ВОЖАКА. Без этого ДЖЕВ видел «4 зверя, 24 клетки» и отправлял
 * отряд в угол к тигру — владелец: «надо больше данных, чтобы он понимал, какие звери не по зубам».
 */
function оЗвере(m, свои, з) {
  const т = m.u8(UNITS + з + U.TYPE);
  // Характеристики зверя нужны не только для «по зубам», но и для расчёта, чего стоит боец,
  // которого мы собираемся заказать: против кого-то же он будет драться.
  const хар = { атака: m.u8(UNITS + з + U.ATK), защита: m.u8(UNITS + з + U.DEF), скорость: m.u8(UNITS + з + U.SPD) };
  if (!свои.length) return { кто: ИМЯ_ЗВЕРЯ[т] || ('тип ' + т), жизни: m.u8(UNITS + з + U.HP), ...хар,
                             наш_удар: 0, его_удар: 0, по_зубам: false };
  return {
    кто: ИМЯ_ЗВЕРЯ[т] || ('тип ' + т),
    жизни: m.u8(UNITS + з + U.HP), ...хар,
    наш_удар: свои.length ? уронПо(m, свои[0], з) : 0,     // сколько снимаем мы за удар
    его_удар: свои.length ? уронПо(m, з, свои[0]) : 0,     // сколько снимает он
    по_зубам: поЗубам(m, свои, [з]),
  };
}

/**
 * НАШИ ВОЙСКА поимённо: кого сколько и что каждый собой представляет. Владелец: «ДЖЕВ знает,
 * какие у нас войска уже есть, какие войска есть у противника и что они умеют — и пусть строит
 * как лучше». Цифры те же, что у движка при создании юнита (справочник.статы).
 */
function составВойск(m, кого) {
  const по = new Map();
  for (const i of кого) {
    const т = m.u8(UNITS + i + U.TYPE);
    let з = по.get(т);
    if (!з) { з = { кто: ИМЯ_ТИПА[т] || ('тип ' + т), сколько: 0, ...статы(m, т) }; delete з.мясо; по.set(т, з); }
    з.сколько++;
  }
  return [...по.values()].sort((a, b) => b.сколько - a.сколько);
}

/**
 * ОРУЖИЕ: что надето, что лежит по карманам и что валяется бесхозным на земле. Владелец: «надо
 * приготовить все описания для оружия, чтобы он понимал, у кого какое оружие есть; может, валяется
 * где-то бесхозное оружие или у кого-то лежит в карманах, — и исходя из этого принимал решение,
 * стоит ли оружие новое строить».
 *
 * Карманы — это слоты инвентаря (U.INV): 0–2 оружие, 3–5 щиты. Надето то, на что указывают
 * U.WEAPON и U.SHIELD. Бесхозное на земле лежит в списке предметов (0x31b7c), где тип записи и
 * есть номер вещи.
 */
function оружиеУНас(m, свои) {
  if (!свои.length) return { людей: 0, безОружия: 0, безЩита: 0, надето: {}, вКарманах: {} };
  const надето = {}, вКарманах = {};
  let безОружия = 0, безЩита = 0, людей = 0;
  const плюс = (куда, id) => { куда[id] = (куда[id] || 0) + 1; };
  for (const i of свои) {
    const т = m.u8(UNITS + i + U.TYPE);
    if (т < 1 || т > 3) continue;                      // вещи носят только люди
    людей++;
    const ор = m.u8(UNITS + i + U.WEAPON), щ = m.u8(UNITS + i + U.SHIELD);
    if (ор !== 0xff) плюс(надето, m.u8(UNITS + i + U.INV + ор)); else безОружия++;
    if (щ !== 0xff) плюс(надето, m.u8(UNITS + i + U.INV + щ)); else безЩита++;
    for (let k = 0; k < 6; k++) {
      const id = m.u8(UNITS + i + U.INV + k);
      if (!id || k === ор || k === щ) continue;
      плюс(вКарманах, id);
    }
  }
  return { людей, безОружия, безЩита, надето, вКарманах };
}

/** Бесхозные вещи на земле: что это и далеко ли до них. */
function вещиНаЗемле(m, серед) {
  const по = {};
  for (let i = m.u32(0x31b7c), шагов = 0; i && шагов < 4096; i = m.u32(ITEMS + i + 0xc), шагов++) {
    const тип = m.u8(ITEMS + i);
    if (!тип || тип === 0x1e) continue;                // 0x1e — мясо, оно считается отдельно
    const в = вещьСправка(m, тип);
    if (!в.оружие && !в.щит) continue;
    const д = далеко({ x: m.u8(ITEMS + i + 1), y: m.u8(ITEMS + i + 2) }, серед);
    const к = по[тип] || (по[тип] = { id: тип, сколько: 0, ближайшее: 99, оружие: в.оружие, щит: в.щит,
                                      атака: в.атака, защита: в.защита });
    к.сколько++; к.ближайшее = Math.min(к.ближайшее, д);
  }
  return Object.values(по).sort((a, b) => a.ближайшее - b.ближайшее).slice(0, 8);
}

/**
 * ЧУЖИЕ ПЛЕМЕНА В НАШИХ ЦИФРАХ. Владелец: «надо передавать информацию про противников, которые
 * тоже могут там находиться: враги опасные, и не стоит с ними ссориться; плюс надо знать нашу
 * силу — может, имеет смысл там всех убить и занять место самим». Поэтому по каждому чужому
 * племени считаем то же, что по зверью: сколько бойцов и домов, наш удар по их сильнейшему и его
 * удар по нам, проходит ли размен, и далеко ли до них.
 *
 * Размен по чужим меряем ПО СИЛЬНЕЙШЕМУ их бойцу, а не по сумме: чужой воин с оружием убивает
 * конкретного человека за пару секунд, и «в сумме нас больше» тут ничего не значит.
 */
function чужиеПлемена(m, свои, серед) {
  const мой = свои.length ? m.u8(UNITS + свои[0] + U.OWNER) : m.u8(G.humanOwner);
  const по = new Map();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!жив(m, i)) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (ЗВЕРЬ(т) || т === 24 || т === 25) continue;
    const хозяин = m.u8(UNITS + i + U.OWNER);
    if (хозяин === мой || хозяин > 7) continue;      // 8 — это дикая живность, а не племя
    let п = по.get(хозяин);
    if (!п) { п = { племя: хозяин, бойцов: 0, домов: 0, сила: 0, далеко: 99, сильнейший: 0, кто: [] }; по.set(хозяин, п); }
    const д = далеко(кл(m, i), серед);
    п.далеко = Math.min(п.далеко, д);
    if (ДОМ_ЛИ(т)) { п.домов++; continue; }
    п.бойцов++;
    п.кто.push(i);
    п.сила += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.HP);
    if (!п.сильнейший || m.u8(UNITS + i + U.ATK) > m.u8(UNITS + п.сильнейший + U.ATK)) п.сильнейший = i;
  }
  let наша = 0;
  for (const i of свои) наша += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.HP);
  return [...по.values()].map(п => ({
    племя: п.племя, бойцов: п.бойцов, домов: п.домов, далеко: п.далеко,
    состав: составВойск(m, п.кто).slice(0, 5),
    их_сила: п.сила, наша_сила: наша, перевес_наш: +(п.сила ? наша / п.сила : 9).toFixed(2),
    наш_удар: (п.сильнейший && свои.length) ? уронПо(m, свои[0], п.сильнейший) : 0,
    его_удар: (п.сильнейший && свои.length) ? уронПо(m, п.сильнейший, свои[0]) : 0,
    по_зубам: (п.сильнейший && свои.length) ? поЗубам(m, свои, [п.сильнейший]) : true,
  })).sort((a, b) => a.далеко - b.далеко);
}

/** Сколько чужих бойцов пасётся у этой точки (и чьих). */
function чужиеУ(m, свои, точка, r) {
  const мой = свои.length ? m.u8(UNITS + свои[0] + U.OWNER) : m.u8(G.humanOwner);
  let n = 0; const племена = new Set();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!жив(m, i)) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    // Цветы и грибы (24, 25) тоже числятся за хозяином 8 — это живность, а не племя.
    if (ЗВЕРЬ(т) || т === 24 || т === 25 || т >= 0x1a) continue;
    const хозяин = m.u8(UNITS + i + U.OWNER);
    if (хозяин === мой || хозяин > 7) continue;
    if (далеко(кл(m, i), точка) > r) continue;
    n++; племена.add(хозяин);
  }
  return { сколько: n, племена: [...племена] };
}

/** Разбор кучки для мозга: сколько там зверья, сколько по зубам и кто в ней самый злой. */
function оКучке(m, свои, к, серед) {
  const живые = к.звери.filter(з => жив(m, з));
  const разбор = живые.map((з, н) => ({ ...оЗвере(m, свои, з), мясо: m.u16(UNITS + з + U.FOOD) }));
  let самый = null;
  for (const р of разбор) if (!самый || р.его_удар > самый.его_удар) самый = р;
  // Мясо туши лежит в поле FOOD самой записи (combat.js: при смерти оно переносится в кусок 0x1e).
  // Считаем отдельно то, что реально возьмём, — с тех, кто нам по зубам.
  const мясо = разбор.reduce((a, р) => a + р.мясо, 0);
  const мясоПоЗубам = разбор.filter(р => р.по_зубам).reduce((a, р) => a + р.мясо, 0);
  const чужие = чужиеУ(m, свои, к, УГОДЬЕ_РАДИУС);
  return {
    зверей: живые.length,
    по_зубам: разбор.filter(р => р.по_зубам).length,
    не_по_зубам: разбор.filter(р => !р.по_зубам).length,
    мясо, мясо_по_зубам: мясоПоЗубам,
    самый_злой: самый,
    чужих_рядом: чужие.сколько, чьих: чужие.племена,
    далеко: далеко(к, серед),
    кучка: к,
  };
}

/** Середина отряда. */
function серединаОтряда(m, свои) {
  let x = 0, y = 0;
  for (const i of свои) { const c = кл(m, i); x += c.x; y += c.y; }
  return { x: Math.round(x / свои.length), y: Math.round(y / свои.length) };
}

/**
 * Сводка обстановки для внешнего мозга (jev и прочие): ровно то, по чему принимается решение.
 * Держим её мелкой — её же можно слать по сети раз в пять секунд.
 */
export function сводка(m, свои, стр, кучкиСписок, серед) {
  const з = здоровьеОтряда(m, свои);
  const ок = округа(m, свои, серед);
  return {
    шаг: m.u32(G.step), миссия: m.u8(G.mission),
    отряд: свои.length, середина: серед,
    еда: m.u32(0x31c28 + m.u8(G.humanOwner) * 4),
    домов: стр?.домов || 0, тревога: !!стр?.тревога,
    // Здоровье отряда и сила округи — это и есть вход для решения «отойти отдохнуть»:
    // «нейронка штаба должна уметь это решение принимать, то есть звери вокруг, их сила и всё такое».
    жизни: з.жизни, жизниМакс: з.макс, жизниДоля: +(з.доля).toFixed(2), битых: з.битых,
    зверейРядом: ок.зверей, силаЗверей: ок.сила, силаНаша: ок.наша,
    // Поимённо — кто рядом и справимся ли мы с ним. Это главный вход для решения «отдых» и
    // «не ходить туда»: одно дело пять собак, другое — тигр.
    ктоРядом: ок.разбор, непосильныхРядом: ок.разбор.filter(р => !р.по_зубам).length,
    // Чужие племена: с кем не стоит ссориться, а кого можно добить и занять место.
    чужие: чужиеПлемена(m, свои, серед),
    // Кто у нас уже есть — по этому мозг и решает, кого заказывать дальше.
    наши_войска: составВойск(m, свои),
    // Экономика: сколько приносим, сколько дома способны переварить и нужен ли ещё дом.
    экономика: стр?.экономика || null,
    // Как устроена игра — общая механика: что для чего и как используется.
    механика: МЕХАНИКА,
    // Оружие: надето, лежит в карманах, валяется бесхозным. Отсюда видно, нужна ли ковка.
    оружие_у_нас: оружиеУНас(m, свои),
    оружие_на_земле: вещиНаЗемле(m, серед),
    перевесЗверья: +(ок.наша ? ок.сила / ок.наша : 0).toFixed(2),
    доБлижайшегоЗверя: ок.ближайший,
    отдыхаем: !!ок.отдыхаем,
    кучки: кучкиСписок.map(к => ({ x: к.x, y: к.y, живых: к.звери.filter(з2 => жив(m, з2)).length,
                                   далеко: далеко(к, серед) })),
  };
}

/** Сумма жизней отряда, её доля от полной и сколько бойцов ниже половины. */
function здоровьеОтряда(m, свои) {
  let жизни = 0, макс = 0, битых = 0;
  for (const i of свои) {
    const hp = m.u8(UNITS + i + U.HP), hm = m.u8(UNITS + i + U.HPMAX);
    жизни += hp; макс += hm; if (hp * 2 < hm) битых++;
  }
  return { жизни, макс, доля: макс ? жизни / макс : 1, битых };
}

/**
 * Что вокруг отряда: сколько зверья в радиусе УГОДЬЕ_РАДИУС, какая у него сила и какая у нас.
 * Сила считается грубо — сумма атаки и жизней: точный размен считает ВОЖАК (он знает таблицы
 * оружия), а штабу нужен лишь порядок величины, чтобы решать «пора уходить» и чтобы это же число
 * можно было скормить сети.
 */
function округа(m, свои, серед) {
  let зверей = 0, сила = 0, ближайший = 99;
  const разбор = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!жив(m, i) || !ЗВЕРЬ(m.u8(UNITS + i + U.TYPE))) continue;
    const д = далеко(кл(m, i), серед);
    if (д > УГОДЬЕ_РАДИУС) continue;
    зверей++; ближайший = Math.min(ближайший, д);
    сила += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.HP);
    if (разбор.length < 6) разбор.push({ ...оЗвере(m, свои, i), далеко: д });
  }
  let наша = 0;
  for (const i of свои) наша += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.HP);
  return { зверей, сила, наша, ближайший, разбор };
}

/**
 * БЛИЖАЙШЕЕ ПУСТОЕ БЕЗОПАСНОЕ МЕСТО. Кольцами от отряда; клетка годится, если по ней можно
 * пройти, из неё есть куда бежать (не тупик — та же мерка, что у отхода ВОЖАКА) и рядом нет ни
 * живого зверья, ни ЛОГОВ: зверь возрождается на своей домашней клетке, и лечь спать на чужом
 * логове значит проснуться от укуса. Требование к пустоте ослабляем по очереди — иначе на тесных
 * картах места не найдётся вовсе и команда «отойти» ничего не сделает.
 */
export function безопасноеМесто(m, серед, свои) {
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const звери = [], лог = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (ЗВЕРЬ(т)) {
      лог.push({ x: m.u8(UNITS + i + 0x59), y: m.u8(UNITS + i + 0x5a) });
      if (жив(m, i)) звери.push(кл(m, i));
    } else if (т < 0x1a && m.u8(UNITS + i + U.OWNER) !== m.u8(UNITS + свои[0] + U.OWNER) && жив(m, i)) звери.push(кл(m, i));
  }
  const выходы = (x, y) => {
    let n = 0;
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++)
      if ((dx || dy) && проходима(m, x + dx, y + dy)) n++;
    return n;
  };
  for (const порог of [БЕЗОПАСНО_ОТ, Math.round(БЕЗОПАСНО_ОТ / 2), 3]) {
    let лучшее = null, лучшая = -1e9;
    for (let r = 2; r <= ИСКАТЬ_ДО; r++) {
      for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue;
        const x = серед.x + dx, y = серед.y + dy;
        if (x < 2 || y < 2 || x > W - 3 || y > H - 3) continue;
        if (!проходима(m, x, y) || выходы(x, y) < ВЫХОДОВ_НАДО) continue;
        let доЗверя = 99, доЛогова = 99;
        for (const з of звери) доЗверя = Math.min(доЗверя, далеко(з, { x, y }));
        for (const л of лог) доЛогова = Math.min(доЛогова, далеко(л, { x, y }));
        if (доЗверя < порог || доЛогова < порог) continue;
        // Ближе — лучше (идти под ударом дольше некуда), но пустота важнее пары клеток пути.
        const оценка = Math.min(доЗверя, 20) * 3 + Math.min(доЛогова, 20) - r * 2;
        if (оценка > лучшая) { лучшая = оценка; лучшее = { x, y }; }
      }
      // Нашли на этом кольце — дальше не ищем: место должно быть БЛИЖАЙШИМ.
      if (лучшее && r >= 6) break;
    }
    if (лучшее) return лучшее;
  }
  return null;
}

/**
 * Шаг штаба. Зовётся каждый тик, но РЕШАЕТ раз в ПЕРЕСМОТР: между пересмотрами держится прежняя
 * директива — иначе отряд метался бы между областями, не доходя ни до одной.
 * @param свои  живые бойцы отряда (без конструкторов)
 * @param стр   разбор слоя стройки (дома, тревога, база)
 */
export function шаг(eng, свои, с, стр) {
  const m = eng.m;
  const шг = m.u32(G.step);
  // Без бойцов штаб всё равно нужен: он решает заказы. Серединой тогда считаем базу.
  const серед = свои.length ? серединаОтряда(m, свои) : (стр?.база || { x: 0, y: 0 });
  if (!свои.length) {
    if (шг - (с.спрошено ?? -1e9) >= ПЕРЕСМОТР) {
      с.спрошено = шг;
      мозгом(с, сводка(m, свои, стр, [], серед), [], { дома: стр?.меню || [], бойцы: стр?.менюБойцов || [],
                                                       экономика: стр?.экономика || null, зверь: стр?.эталонЗверя || null });
    }
    return с.директива;
  }

  // СПРАШИВАЕМ МОЗГ ВСЕГДА И ПЕРВЫМ ДЕЛОМ — раз в такт, что бы отряд сейчас ни делал. Сперва
  // вопрос стоял ниже отдыха, и во время отдыха ДЖЕВ не видел ничего: он не мог ни поднять отряд
  // раньше, ни увести с плохого места. Ответ приходит через полсекунды и ложится в с.приказ,
  // поэтому опоздание на один такт роли не играет.
  if (шг - (с.спрошено ?? -1e9) >= ПЕРЕСМОТР) {
    с.спрошено = шг;
    const всеКучки = кучки(m, с);
    const живыеК = всеКучки.filter(к => к.звери.filter(з => жив(m, з)).length >= ВЫБИТО);
    // ПРЕДЛАГАЕМ ТОЛЬКО ТО, ГДЕ ЕСТЬ КОГО БИТЬ. Владелец: «ДЖЕВ отводит игроков в дальний угол и
    // сталкивает с тигром, который их сильнее». Кучку, где ни один зверь не по зубам, мозгу не
    // показываем совсем — выбрать её он не сможет. Если таких не осталось ни одной, показываем
    // все: пусть решает по цифрам, а не вслепую.
    const разбор = живыеК.map(к => оКучке(m, свои, к, серед));
    const годные = разбор.filter(р => р.по_зубам > 0);
    // Показываем шесть БЛИЖАЙШИХ: дальний угол карты — это минута бега, за которую отряд ничего
    // не добудет, а список из дюжины вариантов только размывает выбор (и стоит лишних токенов).
    const показ = (годные.length ? годные : разбор).sort((a, b) => a.далеко - b.далеко).slice(0, 6);
    с.кучкиМозгу = показ.map(({ кучка, ...остальное }) => остальное);
    с.кучкиМозгуСписок = показ.map(р => р.кучка);
    мозгом(с, сводка(m, свои, стр, всеКучки, серед), с.кучкиМозгу,
           { дома: стр?.меню || [], бойцы: стр?.менюБойцов || [],
             экономика: стр?.экономика || null, зверь: стр?.эталонЗверя || null,
             бойцовЕсть: стр?.бойцов, хватитНарода: стр?.хватитНарода, домаЖдут: стр?.домаЖдут,
             безоружных: стр?.безоружных, безЩита: стр?.безЩита, нашаСила: стр?.нашаСила,
             сильнейшийЧужой: стр?.сильнейшийЧужой, надоСилы: стр?.надоСилы });
  }

  // 0. ОТДЫХ — ЖЁСТКАЯ КОМАНДА. Раз начали, держим до полного лечения: ни угодья, ни кучки, ни
  // такт пересмотра его не перебивают. Снимает отдых только полное здоровье или тревога по дому.
  // Решение принять может кто угодно: скрипт (по доле жизней), внешний мозг (с.приказ = 'отдых')
  // или человек кнопкой — дальше всё одинаково.
  const зд = здоровьеОтряда(m, свои);
  const вылечились = свои.every(i => m.u8(UNITS + i + U.HP) >= Math.ceil(m.u8(UNITS + i + U.HPMAX) * ВЫЛЕЧИЛИСЬ));
  if (с.приказ === 'отдых') { с.отдыхает = true; с.местоОтдыха = null; с.приказ = null; с.отменилОтдых = null; }
  else if (с.приказ) { с.отдыхает = false; с.местоОтдыха = null; с.отменилОтдых = шг; с.приказ = null; }
  // Скриптовый порог не спорит со свежей отменой мозга — до самого дна.
  const порогОтдыха = (с.отменилОтдых && шг - с.отменилОтдых < ОТМЕНА_ДЕРЖИТСЯ) ? ОТДЫХ_ДНО : ОТДЫХ_ПОРОГ;
  if (ОТДЫХ && !с.отдыхает && зд.доля < порогОтдыха) с.отдыхает = true;
  if (с.отдыхает) {
    if (вылечились || (стр?.тревога && жив(m, стр.тревога))) { с.отдыхает = false; с.местоОтдыха = null; }
    else {
      // Место ищем один раз и держим. Пересчитываем, только если оно перестало быть пустым
      // (зверь подошёл вплотную) — тогда отряд не просыпается зря, а уходит на новое.
      const надоНовое = !с.местоОтдыха
        || (с.местоОтдыха.проверено !== undefined && шг - с.местоОтдыха.проверено > ПЕРЕСМОТР && близкоЗверьё(m, с.местоОтдыха, свои));
      if (надоНовое) {
        const т = безопасноеМесто(m, серед, свои);
        if (т) с.местоОтдыха = { x: т.x, y: т.y, проверено: шг };
      } else с.местоОтдыха.проверено = шг;
      if (с.местоОтдыха) {
        const т = с.местоОтдыха;
        return (с.директива = { вид: 'отдых', область: область(т, 4), точка: { x: т.x, y: т.y }, цель: 0,
                                почему: `лечимся ${Math.round(зд.доля * 100)}% → ${Math.round(ВЫЛЕЧИЛИСЬ * 100)}%` });
      }
      // Места не нашлось вовсе — отдых отменяем, пусть работает обычная логика сна ВОЖАКА.
      с.отдыхает = false;
    }
  }

  // 0а. СВЯТИЛИЩЕ НЕ У СТАРТА (опыт JW_СТР_СВЯТ_ТОЧКА): пока его нет, отряд ведёт строителя к точке.
  if (Стройка.СВЯТ_ТОЧКА) {
    const мой = m.u8(G.humanOwner);
    let есть = false;
    for (let i = m.u32(G.unitHead); i && !есть; i = m.u32(UNITS + i + U.NEXT))
      есть = !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.OWNER) === мой && m.u8(UNITS + i + U.TYPE) === 26;
    if (!есть) { const т = Стройка.СВЯТ_ТОЧКА;
      return (с.директива = { вид: 'охота', область: область(т, 3), точка: т, цель: 0, почему: 'ведём строителя к месту Святилища' }); }
  }
  // 0б. ПЛАН ВТОРОЙ МИССИИ ТИРАНО (JW_ШТАБ_ПЛАН=1). Фазы: «карман» — добить стартовых леопарда и
  // пса у базы (ротацией, см. ВОЖАК); «ждать» — стоять у 34,38, бить возрождённых в кармане и ждать
  // окна мимо мамонта (Т2.можноВыходить); «выход» — маршем за горло; «фарм» — логова запада.
  if (ПЛАН && Т2.этаКарта(m) && свои.length) {
    с.план ??= 'карман';
    const дикие = [];
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT))
      if (ЗВЕРЬ(m.u8(UNITS + i + U.TYPE)) && жив(m, i)) дикие.push(i);
    const вКармане = дикие.filter(i => Т2.вКармане(кл(m, i)));
    const целы = свои.every(i => m.u8(UNITS + i + U.HP) * 100 >= m.u8(UNITS + i + U.HPMAX) * ПЛАН_ЗДОРОВЬЕ);
    if (с.план === 'фарм' && Т2.вКармане(серед)) с.план = 'ждать';          // вернулись в карман — снова ждать окна
    if (с.план === 'карман' && !вКармане.length) с.план = 'ждать';
    // Выходим прокачанными: снаружи тигры (65/65/55), новичкам они не по силам — сначала набираем атаку
    // на возрождённых в кармане (они слабые: табличные статы).
    const сильны = свои.every(i => m.u8(UNITS + i + U.ATK) >= ПЛАН_АТАКА);
    // Мамонт над горлом: прокачались до ПРОТИВ_МАМОНТА — идём бить его сами (ВОЖАК ведёт ротацию),
    // после смерти он возрождается только через 8100 тиков (~7,5 мин), и выход свободен.
    const мам = ПЛАН_МАМОНТ ? Т2.северныйМамонт(m) : 0;
    const П = Т2.ПРОТИВ_МАМОНТА;
    const противМамонта = свои.length >= 4 && свои.every(i => m.u8(UNITS + i + U.HPMAX) >= П.hp
      && m.u8(UNITS + i + U.ATK) >= П.atk && m.u8(UNITS + i + U.DEF) >= П.def);
    // Бьём только на его выпасе и без свидетелей: мамонт бродит (замер: ушёл к 15,22), и отряд,
    // пошедший за ним, погиб от тамошних леопардов.
    const мамК = мам ? кл(m, мам) : null;
    const мамДома = мамК && далеко(мамК, Т2.ЛОГОВО_МАМОНТА) <= 5;
    const свидетели = мамК ? дикие.filter(i => i !== мам && далеко(кл(m, i), мамК) <= 8).length : 0;
    if (с.план === 'ждать' && мам && мамДома && !свидетели && целы && противМамонта && !вКармане.length) с.план = 'мамонт';
    if (с.план === 'мамонт' && (!мам || свои.length < 3 || далеко(мамК, Т2.ЛОГОВО_МАМОНТА) > 8)) с.план = 'ждать';
    if (с.план === 'ждать' && целы && сильны && Т2.складЗаГорломИдёт(m) && Т2.можноВыходить(m)
        && !(мам && противМамонта)) с.план = 'выход';
    if (с.план === 'мамонт') {
      const т = кл(m, мам);
      return (с.директива = { вид: 'охота', область: область(т, 4), точка: т, цель: мам, принудительно: true, сценарий: 'мамонт',
                              почему: 'план: бьём северного мамонта' });
    }
    if (с.план === 'выход' && далеко(серед, Т2.ЗА_ГОРЛОМ) <= 2) с.план = 'фарм';
    if (с.план === 'карман')
      return (с.директива = { вид: 'охота', область: { x0: Т2.КАРМАН.x0, y0: 38, x1: Т2.КАРМАН.x1, y1: Т2.КАРМАН.y1 }, точка: { x: 34, y: 40 }, цель: 0, почему: 'план: зачищаем карман', строго: true });
    if (с.план === 'ждать')
      return (с.директива = { вид: 'охота', область: { x0: Т2.КАРМАН.x0, y0: 38, x1: Т2.КАРМАН.x1, y1: Т2.КАРМАН.y1 }, точка: { x: 34, y: 40 }, цель: 0,
                              почему: вКармане.length ? 'план: бьём возрождённых в кармане' : 'план: ждём окна мимо мамонта', строго: true });
    if (с.план === 'выход')
      return (с.директива = { вид: 'марш', область: область(Т2.ЗА_ГОРЛОМ, 2), точка: Т2.ЗА_ГОРЛОМ, цель: 0, почему: 'план: выходим за горло' });
    // фарм: логова запада; тревогу по дому в кармане берёт охрана, а не весь отряд через мамонта
    const лог = выбратьЛогово(m, свои, серед, с, (т) => т.x >= Т2.ФАРМ.x0 && т.x <= Т2.ФАРМ.x1 && т.y >= Т2.ФАРМ.y0 && т.y <= Т2.ФАРМ.y1 && !Т2.вКармане(т));
    if (лог) return (с.директива = { вид: 'охота', область: область(лог.точка, МАРШРУТ_КРУГ), точка: лог.точка, цель: 0,
                                    почему: `план: логово ${лог.имя}${лог.ждать ? ', ждём ' + лог.ждать + ' с' : ''}` });
    return (с.директива = { вид: 'охота', область: область(Т2.ЗА_ГОРЛОМ, 4), точка: Т2.ЗА_ГОРЛОМ, цель: 0, почему: 'план: ждём зверя за горлом' });
  }

  // 1. ТРЕВОГА ПЕРЕБИВАЕТ ВСЁ И СРАЗУ, без ожидания пересмотра: дом ломают сейчас, а не через
  // пять секунд. Само наведение делает отряд (он уже умеет по стр.тревога), штаб лишь меняет вид
  // директивы, чтобы область не тянула бойцов обратно на угодье.
  if (стр?.тревога && жив(m, стр.тревога) && !с.охотаБезДомов && (!с.участокГруппы || с.ближеКТревоге)) {
    const т = кл(m, стр.тревога);
    return (с.директива = { вид: 'оборона', область: область(т, ДОМ_КРУГ), точка: т,
                            цель: стр.тревога, почему: 'ломают дом' });
  }

  // ГРУППА СО СВОИМ УЧАСТКОМ (режим двух групп ВОЖАКА): охотимся в своей половине карты; дальнюю
  // стройку прикрывает та группа, в чьей половине площадка. Остальные правила штаба — для одного
  // отряда на всю карту — здесь не нужны.
  // МАРШРУТ ПО ЛОГОВАМ (опыт, JW_ШТАБ_МАРШРУТ=1). Расчёт предела второй миссии Тирано показал:
  // быстрее всего не гоняться за кем попало, а ходить по логовам и бить тех, кто возродился, —
  // возрождённый зверь слабее стартового (табличные статы, 0x1cfcb). Выбираем логово по
  // (дойти + дождаться возрождения + убить) на единицу мяса; время до возрождения читаем из самого
  // движка — счётчик мёртвого зверя (+ANIM) идёт до его срока (0x18058).
  if (МАРШРУТ && !(стр?.площадка && КОНВОЙ)) {
    const цельМаршрута = выбратьЛогово(m, свои, серед, с);
    if (цельМаршрута) {
      const т = цельМаршрута.точка, дошли = далеко(серед, т) <= 2;
      return (с.директива = { вид: 'охота', область: область(т, МАРШРУТ_КРУГ), точка: т, цель: 0,
                              почему: `логово: ${цельМаршрута.имя}${цельМаршрута.ждать ? ', возродится через ' + цельМаршрута.ждать + ' с' : ''}` });
    }
  }
  if (с.участокГруппы) {
    if (с.конвой && КОНВОЙ && стр?.задание?.вид === 'дома' && стр?.площадка) {
      const п = стр.площадка;
      const дошли = далеко(серед, п) <= КОНВОЙ_КРУГ;
      return (с.директива = { вид: дошли ? 'охота' : 'марш', область: область(п, КОНВОЙ_КРУГ),
                              точка: { x: п.x, y: п.y }, цель: 0, почему: 'группа прикрывает стройку' });
    }
    const у = с.участокГруппы;
    return (с.директива = { вид: 'охота', область: у, точка: { x: (у.x0 + у.x1) >> 1, y: (у.y0 + у.y1) >> 1 },
                            цель: 0, почему: 'группа: свой участок' });
  }
  if (с.директива && шг - с.решено < ПЕРЕСМОТР) {
    // Между пересмотрами всё же следим за одним: дошли ли. «Марш» кончается сам, как только
    // отряд оказался у цели, — ждать до конца такта незачем.
    const д = с.директива;
    if (д.вид === 'марш' && д.точка && далеко(серед, д.точка) <= ПРИШЛИ)
      { д.вид = 'зачистка'; д.почему = 'дошли'; }
    return д;
  }
  с.решено = шг;

  const список = кучки(m, с);
  const живыхВ = (к) => к.звери.filter(з => жив(m, з)).length;

  // 2. МИССИЯ ПРО ДОМА — РАБОТАЕМ У БАЗЫ. Пока отряд гоняется за гиеной на другом конце карты,
  // зверьё разбирает недостроенное Святилище. Это прежнее правило образца, поднятое на уровень
  // выше: теперь оно видно в директиве и его можно перебить руками.
  // 2а. ДАЛЬНЯЯ СТРОЙКА. Площадку вдали от базы выбрал ПРОРАБ, строителя ведёт туда он же, а
  // прикрыть её, пока дом не встал, некому, кроме отряда: идём туда же и охотимся вокруг.
  if (КОНВОЙ && стр?.задание?.вид === 'дома' && стр?.площадка) {
    const п = стр.площадка;
    const дошли = далеко(серед, п) <= КОНВОЙ_КРУГ;
    return (с.директива = { вид: дошли ? 'охота' : 'марш', область: область(п, КОНВОЙ_КРУГ),
                            точка: { x: п.x, y: п.y }, цель: 0, почему: 'прикрываем дальнюю стройку' });
  }
  // 2б. СТРАЖА, ПОКА ВОЙСКО СЛАБОЕ. Опыт на Тирано/2: простолюдин проигрывает леопарду один на
  // один, четверо валят его ценой одного своего (500 еды за 200 мяса), а у дома, который зверь
  // ломает, — ценой трети бойца: удар держит стена. Поэтому, пока нет ни одного бойца, бьющего
  // эталонного зверя, на охоту не ходим: стоим у базы и бьём тех, кто пришёл сам.
  if (СТРАЖА && стр?.задание?.вид === 'дома' && стр?.база && стр.сильных === 0) {
    return (с.директива = { вид: 'стража', область: область(стр.база, СТРАЖА_КРУГ),
                            точка: стр.база, цель: 0, почему: 'войско слабое — ждём у базы' });
  }
  // ДОМА_ОХОТА: базу держит охрана (ОХРАНА_ДОМА ВОЖАКА), отряд у дома не сидит, а охотится как
  // на первой карте. Владелец: «если там оставить одного юнита на охрану, а остальных вывести, это
  // сильно ускорит общую охоту — остальным не надо будет возвращаться постоянно».
  if (стр?.задание?.вид === 'дома' && стр?.база && !ДОМА_ОХОТА && !с.охотаБезДомов) {
    const дошли = далеко(серед, стр.база) <= ДОМ_КРУГ;
    // Опыт ДОМА_ВСЕ: участок охватывает ВСЕ наши дома, а не только круг у Святилища, — казармы на
    // дальней площадке Тирано/2 мамонты разбирали, пока отряд ходил вокруг базы.
    if (ДОМА_ВСЕ && стр.домаГде?.length) {
      const о = область(стр.база, ДОМ_КРУГ);
      for (const д of стр.домаГде) {
        о.x0 = Math.min(о.x0, д.x - ДОМА_ВСЕ_ЗАПАС); о.y0 = Math.min(о.y0, д.y - ДОМА_ВСЕ_ЗАПАС);
        о.x1 = Math.max(о.x1, д.x + ДОМА_ВСЕ_ЗАПАС); о.y1 = Math.max(о.y1, д.y + ДОМА_ВСЕ_ЗАПАС);
      }
      return (с.директива = { вид: дошли ? 'охота' : 'марш', область: о, точка: стр.база, цель: 0, почему: 'охраняем все дома' });
    }
    return (с.директива = { вид: дошли ? 'охота' : 'марш', область: область(стр.база, ДОМ_КРУГ),
                            точка: стр.база, цель: 0, почему: 'охраняем стройку' });
  }

  // 3. ШТУРМ ЧУЖОГО ПЛЕМЕНИ (опыт, по умолчанию выключен). Условие простое и считаемое: задание
  // требует добить племя и нас набралось не меньше ШТУРМ_НАДО. Размен с конкретным бойцом отряд
  // всё равно посчитает сам — штаб лишь ведёт его к чужой базе.
  // ШТУРМ. По ручке — только против тех, кого требует задание; по слову мозга — против любого
  // чужого племени: «надо отрядам начать нападение куда-то» это его решение, а не наше.
  const штурмПоПриказу = с.мозг === 'штурм';
  if ((ШТУРМ || штурмПоПриказу) && свои.length >= (штурмПоПриказу ? 1 : ШТУРМ_НАДО)) {
    const обязаны = обязательные(m, с);
    if (обязаны.size || штурмПоПриказу) {
      const мой = m.u8(UNITS + свои[0] + U.OWNER);
      let цель = 0, ближе = 1e9;
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (!жив(m, i)) continue;
        const хозяин = m.u8(UNITS + i + U.OWNER);
        const чужой = штурмПоПриказу ? (хозяин !== мой) : обязаны.has(хозяин);
        if (!чужой) continue;
        const т = m.u8(UNITS + i + U.TYPE);
        if (ЗВЕРЬ(т)) continue;                       // штурм — это про племена, не про зверьё
        if (т >= 0x1a && !ДОМ_ЛИ(т)) continue;
        const д = далеко(кл(m, i), серед);
        if (д < ближе) { ближе = д; цель = i; }
      }
      if (цель) {
        const т = кл(m, цель);
        return (с.директива = { вид: ближе <= ПРИШЛИ ? 'зачистка' : 'марш', область: область(т, УГОДЬЕ_РАДИУС),
                                точка: т, цель, почему: 'добиваем племя' });
      }
    }
  }

  // 3б. ОБОРОНА ПО СЛОВУ МОЗГА, когда дом ещё никто не ломает: стоим у базы и бьём всё, что
  // подойдёт. Без базы обороняться негде — тогда это обычная охота.
  if (с.мозг === 'оборона' && стр?.база) {
    const дошли = далеко(серед, стр.база) <= ДОМ_КРУГ;
    return (с.директива = { вид: дошли ? 'зачистка' : 'марш', область: область(стр.база, ДОМ_КРУГ),
                            точка: стр.база, цель: 0, почему: 'держим базу' });
  }

  // 4а. ОХОТА ГЛАВНОГО (после разделения): участок не назначаем — добычу по всей карте выбирает отряд сам,
  // по силам и по опасности вокруг зверя. Разбор сцены: штаб назначил кучку справа (43,35) у мамонтов, и
  // отряд бежал туда, хотя слева был слабый зверь и щит.
  if (с.охотаБезДомов || !УГОДЬЯ) return (с.директива = { вид: 'охота', область: null, точка: null, цель: 0, почему: 'охота: добычу выбирает отряд' });
  // 4. ОХОТА ПО КУЧКАМ. Берём ближайшую непустую; если в текущей уже некого бить — идём в
  // следующую. Это и есть «форсировать идти в область»: пока отряд не дошёл, директива 'марш'.
  const живые = список.filter(к => живыхВ(к) >= ВЫБИТО);
  // КАКОЕ УГОДЬЕ — ТОЖЕ РЕШЕНИЕ МОЗГА. Координаты ДЖЕВ выдать не может, но выбрать из
  // пронумерованных кучек — ровно его работа. Мы отдаём ему список (сколько зверья, как далеко),
  // он называет номер. Скриптовая оценка остаётся запасной: пока ответа нет и когда мозга нет.
  let лучшая = null, лучшаяОценка = -1e9;
  // ВЫБОР МОЗГА ДЕРЖИТСЯ, А НЕ ЖИВЁТ ОДИН ТАКТ. Владелец: «может ли ДЖЕВ установить места или
  // угодья для отряда, чтобы фармить опыт и добывать мясо, и будет ли это работать как приоритет
  // над основным скриптом?» — да: названное им угодье становится рабочим и держится, пока там
  // есть кого бить. Иначе выходила чехарда: ответ приходит через полсекунды, а скрипт за это
  // время уже увёл отряд в свою кучку, и на следующем такте всё менялось обратно.
  if (с.мозгУгодье !== undefined && с.мозгУгодье !== null) {
    // Номер — из того списка, который мы показывали мозгу (с.кучкиМозгуСписок), а не из всех живых.
    const выбранная = (с.кучкиМозгуСписок || живые)[с.мозгУгодье];
    if (выбранная) с.угодьеМозга = выбранная;
    с.мозгУгодье = null;
  }
  if (с.угодьеМозга) {
    // Держим, пока в нём осталась добыча ПО ЗУБАМ: выбитое угодье — уже не угодье.
    const разбор = оКучке(m, свои, с.угодьеМозга, серед);
    if (разбор.по_зубам > 0) лучшая = с.угодьеМозга;
    else с.угодьеМозга = null;
  }
  if (!лучшая) {
    // Скриптовый запасной выбор — по тем же цифрам, что видит мозг: сколько там добычи ПО ЗУБАМ,
    // сколько непосильных и как далеко идти. Кучку, где по зубам никого, не берём вовсе: это ровно
    // тот случай, когда отряд уводили в угол к тигру.
    const разбор = живые.map(к => оКучке(m, свои, к, серед));
    const годные = разбор.filter(р => р.по_зубам > 0);
    for (const р of (годные.length ? годные : разбор)) {
      const оценка = р.по_зубам * 3 - р.не_по_зубам * 4 - р.далеко;
      if (оценка > лучшаяОценка) { лучшаяОценка = оценка; лучшая = р.кучка; }
    }
  }
  if (!лучшая) return (с.директива = { вид: 'охота', область: null, точка: null, цель: 0, почему: 'зверья нет' });
  const дошли = далеко(серед, лучшая) <= УГОДЬЕ_РАДИУС;
  return (с.директива = { вид: дошли ? 'охота' : 'марш', область: область(лучшая, УГОДЬЕ_РАДИУС),
                          точка: { x: лучшая.x, y: лучшая.y }, цель: 0,
                          почему: `угодье ${живыхВ(лучшая)} зверей` });
}

/** Не подобралось ли зверьё к месту отдыха ближе, чем на треть безопасного круга. */
function близкоЗверьё(m, точка, свои) {
  const мой = m.u8(UNITS + свои[0] + U.OWNER);
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!жив(m, i)) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (!ЗВЕРЬ(т) && (т >= 0x1a || m.u8(UNITS + i + U.OWNER) === мой)) continue;
    if (далеко(кл(m, i), точка) <= Math.max(3, БЕЗОПАСНО_ОТ / 3)) return true;
  }
  return false;
}

/**
 * Логово для маршрута: у каждого дикого зверя есть точка рождения (+0x59/+0x5a). Живого берём, если
 * он по зубам; мёртвого — если по зубам будет возрождённый (табличные статы), и ждём его. Логово в
 * радиусе нападения живого зверя-убийцы (не по зубам) пропускаем.
 */
function выбратьЛогово(m, свои, серед, с, годится = null) {
  if (!свои.length) return null;
  const ТИК = 0.055, ХОД = 2.4;
  const убийцы = [];
  const все = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    const т = m.u8(UNITS + i + U.TYPE);
    if (!ЗВЕРЬ(т) || m.u8(UNITS + i + U.OWNER) !== 8) continue;
    все.push(i);
    if (жив(m, i) && !поЗубам(m, свои, [i], 1.2, false)) убийцы.push({ к: кл(m, i), р: (m.u8(UNITS + i + U.SPD) >> 5) + 3 });
  }
  // Сила отряда против табличного зверя этого типа — по формулам ударов (человек раз в 8 шагов).
  const наш = свои.map(i => ({ atk: m.u8(UNITS + i + U.ATK), def: m.u8(UNITS + i + U.DEF), hp: m.u8(UNITS + i + U.HP) }));
  const урон = (а, д) => Math.max(1, (Math.max(а - д, 0) >> 4) + (а >> 5) + 1);
  const посильноТабличный = (т) => {
    const t = статы(m, т);
    const dps = наш.reduce((a, б) => a + урон(б.atk, t.защита) / 8, 0) - 1 / 16;   // за шаг
    if (dps <= 0) return null;
    const шагов = t.жизни / dps;
    const поНам = урон(t.атака, Math.min(...наш.map(б => б.def))) / 6 * шагов;       // по одному, без ротации
    return поНам <= Math.min(...наш.map(б => б.hp)) * МАРШРУТ_РИСК ? шагов * ТИК : null;
  };
  let лучший = null;
  for (const i of все) {
    const т = m.u8(UNITS + i + U.TYPE);
    const логово = { x: m.u8(UNITS + i + 0x59), y: m.u8(UNITS + i + 0x5a) };
    const живой = жив(m, i);
    const где = живой ? кл(m, i) : логово;
    if (годится && !годится(где)) continue;
    if (убийцы.some(у => далеко(у.к, где) <= у.р)) continue;
    let бой, ждать = 0;
    if (живой) {
      if (!поЗубам(m, свои, [i], МАРШРУТ_ЗАПАС, false)) continue;
      бой = 10;
    } else {
      if (m.u16(UNITS + i + U.ANIM) === 0xffff) continue;                 // не возродится никогда
      бой = посильноТабличный(т); if (бой === null) continue;
      const срок = ((m.u32(0x33358 + т * 4) + m.u16(0x36d82 + т * 2)) & 0xffff);
      ждать = Math.max(0, срок - m.u16(UNITS + i + U.ANIM)) * ТИК;
    }
    const дорога = далеко(серед, где) / ХОД;
    const мясо = Math.max(1, m.u16(UNITS + i + U.FOOD) || статы(m, т).мясо);
    const оц = (дорога + Math.max(0, ждать - дорога) + бой) / мясо;
    if (!лучший || оц < лучший.оц) лучший = { оц, точка: где, имя: ИМЯ_ЗВЕРЯ[т] || ('зверь ' + т), ждать: Math.round(Math.max(0, ждать - дорога)) };
  }
  return лучший;
}

/** Чьё племя требует добить задание миссии. */
function обязательные(m, с) {
  const миссия = m.u8(G.mission);
  if (с.заданиеДля !== миссия) {
    с.заданиеДля = миссия; с.обязаны = new Set();
    try {
      const з = Кампания.задание(m);
      if (з?.вид === 'владелец') с.обязаны.add(з.кого & 7);
      if (з?.плюсВладелец !== undefined) с.обязаны.add(з.плюсВладелец & 7);
    } catch {}
  }
  return с.обязаны;
}
