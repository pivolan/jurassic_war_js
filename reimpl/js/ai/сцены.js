// Учебные сцены: подготовленные положения, в которых видно, ЧТО делает компьютер.
//
// Раньше сцены жили только в стенде (tools/ai_сцены.mjs) и попадали в игру записями .jwr. Владелец
// сказал прямо: «ты сцены мне дай, а не репки записанные» — и он прав. Запись показывает, как ИИ
// вёл себя в тот час, когда её сняли: правила с тех пор поменялись десять раз, а плёнка всё та же.
// Сцену надо СТАВИТЬ и запускать живьём — тогда видно нынешнее поведение, можно поставить на паузу,
// потыкать юнитов, переключить мозги и посмотреть ещё раз.
//
// Поэтому расстановки переехали сюда: модуль чистый (только движок, никакого node), его берут и
// стенд, и браузер. Стенд по ним пишет реплеи для замеров, игра — запускает их вживую.
import { G, U, UNITS, BI, ITEMS } from '../mem.js';
import { F } from '../fn.js';
import { поставить } from '../ui/scenebuild.js';

const ЗДАНИЕ = 0x1a, ЕДА = 0x1e;

/** Все живые юниты цвета (без зданий). */
export function бойцы(m, цвет) {
  const сп = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== цвет) continue;
    const t = m.u8(UNITS + i + U.TYPE);
    if (t >= 1 && t <= 13) сп.push(i);
  }
  return сп;
}
/** Дома цвета. */
export function дома(m, цвет) {
  const сп = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) === цвет && m.u8(UNITS + i + U.TYPE) >= ЗДАНИЕ) сп.push(i);
  }
  return сп;
}
/** Убрать юнита со сцены: помечаем «нет его» тем же битом, которым движок помечает убитых. */
export const убрать = (m, i) => m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) | 1);
/** Клетка юнита. */
export const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
/** Свободная запись в пуле юнитов — из неё делаем нового. */
function свободная(m) {
  for (let i = 96; i < 0xe000; i += 96) {
    const a = UNITS + i;
    if ((m.u8(a + U.FLAGS5B) & 1) && m.u8(a + U.TYPE) === 0) return i;
  }
  for (let i = 96; i < 0xe000; i += 96) if (m.u8(UNITS + i + U.FLAGS5B) & 1) return i;
  return 0;
}
/** Поставить нового юнита нужного типа: статы берём из таблицы видов движка. */
export function родить(eng, тип, владелец, x, y) {
  const m = eng.m, i = свободная(m); if (!i) return 0;
  const ст = m.u32(0x30a9e + тип * 4);                                // строка вида (та же, что у осилитТигра)
  m.w8(UNITS + i + U.TYPE, тип); m.w8(UNITS + i + U.OWNER, владелец);
  m.w8(UNITS + i + U.HPMAX, m.u8(ст + 0x37654)); m.w8(UNITS + i + U.HP, m.u8(ст + 0x37654));
  m.w8(UNITS + i + U.ATK, m.u8(ст + 0x37657)); m.w8(UNITS + i + U.DEF, m.u8(ст + 0x37658));
  m.w8(UNITS + i + U.SPD, m.u8(ст + 0x37659));
  m.w8(UNITS + i + U.XP, 0); m.w8(UNITS + i + U.WEAPON, 0xff); m.w8(UNITS + i + U.SHIELD, 0xff);
  m.w16(UNITS + i + U.FOOD, 0); m.w8(UNITS + i + U.ORDER, 0xff);
  for (let k = 0; k < 9; k++) m.w8(UNITS + i + U.INV + k, 0);
  поставить(eng, i, x, y);
  return i;
}
/** Переставить существующего юнита. */
export const переставить = (eng, i, x, y) => поставить(eng, i, x, y);
/** Кусок мяса на землю. */
export function мясо(eng, x, y, кол) {
  const c = F[0x1cdf3](eng, { eax: ЕДА, edx: x << 5, ebx: y << 5, esi: 0 });
  if (c && c.esi) eng.m.w16(ITEMS + c.esi + 6, кол);
}
/** Открыть туман вокруг точки — иначе половина экрана чёрная и смотреть нечего. */
export function открыть(m, x0, y0, r) {
  for (let y = Math.max(0, y0 - r); y < y0 + r; y++)
    for (let x = Math.max(0, x0 - r); x < x0 + r; x++)
      m.w8(BI + ((y & 0xff) << 8) + (x & 0xff), m.u8(BI + ((y & 0xff) << 8) + (x & 0xff)) | 1);
}
/** Сколько мяса лежит на земле: по нему видно, успевают ли его подбирать. */
export function мясоНаЗемле(m) {
  let всего = 0;
  for (let it = m.u32(0x31b7c); it; it = m.u32(ITEMS + it + 0xc))
    if (m.u8(ITEMS + it) === ЕДА) всего += m.u16(ITEMS + it + 6);
  return всего;
}

