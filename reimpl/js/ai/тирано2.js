// ПЛАН ВТОРОЙ МИССИИ ТИРАНО (высшая сложность) — данные карты, найденные опытом (агенты-исследователи,
// 23.09.2026). База в кармане с логовами леопарда (33,43) и пса (31,41); единственный выход — узкий
// проход на север к горлу 34,33, а над ним выпас северного мамонта. Дома задания в кармане не
// держатся (под ударом 70–80% времени), зато северо-западная полоса за горлом за 39 минут игры на
// 10 зёрнах не видела зверя ближе радиуса нападения ни разу.
//
// Правило выхода (замер: 118 из 120 дошли чисто, 2 погибли; начиная ждать с 60-й секунды — 120/120):
// ждать на 34,38 (туда мамонт не дотягивается), не выходить, пока на горле лежит щит (мамонт идёт за
// ним сам), и выходить, когда у каждого из трёх мамонтов у выхода и позиция, и точка, куда он идёт
// (DSTX/DSTY), дальше 5 клеток от любой клетки пути, а стоящий (0x38) не собирается вот-вот сорваться
// (счётчик простоя +0x50 ≤ 6). Радиус нападения — круг (r² ≤ 18 у мамонта), отсюда евклидово расстояние.
import { G, U, UNITS, ITEMS, BI } from '../mem.js';
import { приказ } from '../port/inject.js';
import { проходима } from './act.js';

export const ПУТЬ_ВЫХОДА = [[34,37],[34,36],[34,35],[34,34],[34,33],[34,32],[33,31],[32,30],[31,29],[30,28],[29,27],[28,26],[27,25],[26,24],[25,23],[25,22]];
export const СТОЯНКА = { x: 34, y: 38 };          // где ждать окна
export const СВЯТИЛИЩЕ = { x: 34, y: 42 };      // угол кармана: Святилище 3×2 не заслоняет мост
/** Логова в кармане базы: пёс и леопард — на них дом не ставим. */
export const ЛОГОВА_КАРМАНА = [{ x: 31, y: 41 }, { x: 33, y: 43 }];
export const ЗА_ГОРЛОМ = { x: 25, y: 22 };        // куда выходить
export const КАРМАН = { x0: 29, y0: 37, x1: 37, y1: 46 };
/** Площадки 2×2 (левый верхний угол): сначала второй склад, потом шесть домов задания. */
export const ПЛОЩАДКИ = [{ x: 25, y: 23 }, { x: 26, y: 20 }, { x: 23, y: 19 }, { x: 26, y: 17 }, { x: 24, y: 22 }, { x: 25, y: 21 }, { x: 27, y: 19 }, { x: 24, y: 18 }, { x: 23, y: 17 }];
/** Где фармить после выхода: запад и северо-запад, подальше от выпасов мамонтов. */
export const ФАРМ = { x0: 0, y0: 0, x1: 27, y1: 47 };   // x ≤ 27: погоня мамонта достаёт до ~28
const МАМОНТ = 19, СТОИТ = 0x38;

/** Наша ли это карта: вторая миссия (индекс 1), человек — Тирано (слот 0). */
export const этаКарта = (m) => m.u8(G.mission) === 1 && m.u8(G.humanOwner) === 0;
/** Клетка в кармане базы. */
export const вКармане = (т) => т.x >= КАРМАН.x0 && т.x <= КАРМАН.x1 && т.y >= 34 && т.y <= КАРМАН.y1;

/** Щит (предмет 9) ещё лежит на 33,32 — приманка для северного мамонта. */
export function щитНаГорле(m) {
  for (let it = m.u32(0x31b7c), n = 0; it && n < 4096; it = m.u32(ITEMS + it + 0xc), n++)
    if (m.u8(ITEMS + it) === 9 && m.u8(ITEMS + it + 1) === 33 && m.u8(ITEMS + it + 2) === 32) return true;
  return false;
}

/** Можно ли сейчас пройти путём выхода (в любую сторону). */
const срдОкно = globalThis.process?.env?.JW_ШТАБ_ПЛАН_ОКНО ?? (typeof location !== 'undefined' ? new URLSearchParams(location.search).get('JW_ШТАБ_ПЛАН_ОКНО') : null);
/** Ждать ли окна вообще. Владелец: «через мамонта вполне можно выйти, даже вплотную; он отстанет,
 *  главное — не привести погоню на базу». JW_ШТАБ_ПЛАН_ОКНО=0 — выходить сразу. */
const ОКНО = (срдОкно ?? '1') === '1';
export function можноВыходить(m, { порог = 5, f50 = 6, щит = true } = {}) {
  if (!ОКНО) return true;
  if (щит && щитНаГорле(m)) return false;
  const мин = (x, y) => Math.min(...ПУТЬ_ВЫХОДА.map(([px, py]) => Math.hypot(x - px, y - py)));
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    const b = UNITS + i;
    if (m.u8(b + U.TYPE) !== МАМОНТ || (m.u8(b + U.FLAGS5B) & 1)) continue;
    if (Math.hypot(m.u8(b + 0x59) - 34, m.u8(b + 0x5a) - 33) > 13) continue;   // далёкие мамонты не в счёт
    if (m.u8(b + U.STATE) === СТОИТ && m.u8(b + U.FLAGS50) > f50) return false;
    if (мин(m.u16(b + U.X) >> 5, m.u16(b + U.Y) >> 5) <= порог) return false;
    if (мин(m.u16(b + U.DSTX) >> 5, m.u16(b + U.DSTY) >> 5) <= порог) return false;
  }
  return true;
}

/** Есть ли у нас достроенный склад за горлом (вне кармана). */
export function складЗаГорлом(m) {
  const мой = m.u8(G.humanOwner);
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || m.u8(UNITS + i + U.OWNER) !== мой || m.u8(UNITS + i + U.TYPE) !== 30) continue;
    if (m.u8(UNITS + i + U.FLAGS50) & 2) continue;                        // ещё строится
    if (!вКармане({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 })) return true;
  }
  return false;
}

/** Идёт ли (или уже стоит) второй склад за горлом: наш строитель склада вне Святилища. */
export function складЗаГорломИдёт(m) {
  if (складЗаГорлом(m)) return true;
  const мой = m.u8(G.humanOwner);
  let складов = 0, строителейСклада = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || m.u8(UNITS + i + U.OWNER) !== мой) continue;
    if (m.u8(UNITS + i + U.TYPE) === 30) складов++;
    if (m.u8(UNITS + i + U.TYPE) === 4 && m.u8(UNITS + i + 0x59) === 4) строителейСклада++;
  }
  return складов >= 1 && строителейСклада >= 1;
}

/** Северный мамонт — хозяин выпаса над горлом (логово 35,26). 0, если мёртв. */
export function северныйМамонт(m) {
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    const b = UNITS + i;
    if (m.u8(b + U.TYPE) !== МАМОНТ || (m.u8(b + U.FLAGS5B) & 1) || !m.u8(b + U.HP)) continue;
    if (Math.abs(m.u8(b + 0x59) - 35) <= 2 && Math.abs(m.u8(b + 0x5a) - 26) <= 2) return i;
  }
  return 0;
}
/** Статы, с которыми четверо ротацией бьют мамонта без потерь (замер агента: 0 смертей из 160). */
export const ЛОГОВО_МАМОНТА = { x: 35, y: 26 };
export const ПРОТИВ_МАМОНТА = { hp: 35, atk: 32, def: 39 };

// БОЙ С СЕВЕРНЫМ МАМОНТОМ — отдельный сценарий (JW_ШТАБ_ПЛАН_МАМОНТ=1, сцена агента-исследователя:
// 0 смертей на 160 боёв при 35/32/39). Общий бой ВОЖАКА здесь не годится: он уходит в отрыв и на
// тревогу к базе, и мамонт идёт за ним в карман. Здесь всё просто: все бьют мамонта; тот, кого он
// бьёт, при жизнях ≤ ОТХОД уходит на ≤3 клетки прочь от него, остальные продолжают бить (мамонт,
// потеряв цель, стоит и переключается на ударившего — ротация). Вернуться: жизни ≥ НАЗАД, или ≥ ОТХОД,
// если мамонт бьёт уже не его.
const ОТХОД = 14, НАЗАД = 26;
const стоит = (m, i) => (m.u16(UNITS + i + U.X) & 31) === 0 && (m.u16(UNITS + i + U.Y) & 31) === 0 && m.u8(UNITS + i + U.STATE) !== 0;
function отходМамонта(m, h, мам, бойцы) {
  const x0 = m.u16(UNITS + h + U.X) >> 5, y0 = m.u16(UNITS + h + U.Y) >> 5;
  const zx = m.u16(UNITS + мам + U.X) / 32, zy = m.u16(UNITS + мам + U.Y) / 32;
  let луч = null, лО = -1e9;
  for (let dy = -3; dy <= 3; dy++) for (let dx = -3; dx <= 3; dx++) {
    const x = x0 + dx, y = y0 + dy;
    if (y >= 34 || !проходима(m, x, y) || (m.u8(BI + x + (y << 8)) & 0xfc)) continue;   // не к базе
    if (бойцы.some(i => i !== h && Math.abs(m.u16(UNITS + i + U.X) / 32 - x) < 1 && Math.abs(m.u16(UNITS + i + U.Y) / 32 - y) < 1)) continue;
    const д = Math.max(Math.abs(zx - x), Math.abs(zy - y));
    const о = Math.min(д, 3) * 10 - Math.max(Math.abs(dx), Math.abs(dy)) * 3;
    if (о > лО) { лО = о; луч = [x, y]; }
  }
  return луч;
}
/** Один шаг боя. пам — состояние ВОЖАКА (там храним режимы бойцов). Возврат: сколько бьют / отходят. */
export function бойСМамонтом(eng, бойцы, мам, пам) {
  const m = eng.m, реж = (пам.режМамонта ??= new Map());
  const мЦ = m.u32(UNITS + мам + U.TARGET), наМамонте = (m.u8(UNITS + мам + U.STATE) & 0xf0) === 0x30;
  // Вмешавшиеся: дикий (не мамонт), который держит целью кого-то из наших. Их сбиваем первыми —
  // леопарды с логов 37,21 и 40,18 приходят на шум боя, а мамонт всё равно ждёт ротацию.
  const жив = (i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.HP) > 0 && (m.u8(UNITS + i + U.STATE) & 0xf0) !== 0x60;
  let помеха = 0, помехаЖ = 1e9;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (i === мам || !жив(i) || m.u8(UNITS + i + U.OWNER) !== 8 || m.u8(UNITS + i + U.TYPE) < 14) continue;
    if (!бойцы.includes(m.u32(UNITS + i + U.TARGET))) continue;
    const ж = m.u8(UNITS + i + U.HP); if (ж < помехаЖ) { помехаЖ = ж; помеха = i; }
  }
  const ц = помеха || мам;
  const бить = (i) => приказ(eng, i, 0x1f, ц, m.u16(UNITS + ц + U.X), m.u16(UNITS + ц + U.Y));
  let бьют = 0, отходят = 0;
  for (const h of бойцы) {
    const hp = m.u8(UNITS + h + U.HP), наМне = наМамонте && мЦ === h;
    if ((реж.get(h) || 'бой') === 'бой') {
      if (наМне && hp <= ОТХОД) {
        const к = отходМамонта(m, h, мам, бойцы);
        if (к) { приказ(eng, h, 0x0f, 0, к[0] << 5, к[1] << 5); реж.set(h, 'отход'); отходят++; continue; }
      }
      if (m.u32(UNITS + h + U.TARGET) !== ц || (m.u8(UNITS + h + U.STATE) & 0xf0) !== 0x10) бить(h);
      бьют++;
    } else {
      отходят++;
      if (!стоит(m, h)) continue;
      if (hp >= НАЗАД || (!наМне && hp >= ОТХОД)) { реж.set(h, 'бой'); бить(h); }
      else if (наМне) { const к = отходМамонта(m, h, мам, бойцы); if (к) приказ(eng, h, 0x0f, 0, к[0] << 5, к[1] << 5); }
    }
  }
  return { бьют, отходят, цель: ц };
}
