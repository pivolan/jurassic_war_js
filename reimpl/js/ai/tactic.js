// Слой тактика (наше): что делает главный отряд прямо сейчас.
//
// Место в схеме (notes/AI-PLAN.md, часть 1): стратег решает, куда племя развивается и что строит;
// тактик — что делает отряд в своей зоне; боец — как он это исполняет. Стратег у нас скриптовый
// штаб (`js/port/ai_script.js`), боец — обученная сеть или учитель. Дырка была ровно посередине:
// роль отряду выбирала одна строчка «осанка атака → штурм, оборона → стоять у дома, иначе охота».
// Её и заменяет эта сеть.
//
// Почему выход — макро-действия, а не приказы. Отряд уже умеет штурмовать (с фокусом огня),
// охотиться (с выбором добычи и придержкой для героя), обороняться и отходить: это написано и
// проверено. Тактику остаётся выбрать одно из этого и указать, на что нацелиться. Так сеть учит
// решение «драться или кормиться», а не переизобретает поиск цели, и её выход остаётся коротким
// (6 ролей × 5 целей × 3 веса), а значит его можно искать эволюцией на исходах партий.
//
// Честность. Всё, что видит тактик, берётся из `осмотр()` — того же среза, по которому играет
// скриптовый штаб, где чужие юниты и дома уже отфильтрованы по разведанному. Никаких данных
// из-под тумана здесь не появляется.
import { G, U, UNITS } from '../mem.js';

export const ВХОД = 24;
export const РОЛИ = ['ATTACK_TO_DEATH', 'DEFEND_POINT', 'HOLD', 'RETREAT', 'GATHER', 'DISTRACT'];
export const ЦЕЛИ = ['вражбаза', 'ближний', 'свойдом', 'добыча', 'середина'];
export const ВЕСА = [1, 2, 3];
export const ВЫХОД = РОЛИ.length + ЦЕЛИ.length + ВЕСА.length;   // 6 + 5 + 3 = 14
export const СКРЫТЫХ = 16;

/** Клетка юнита. */
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
/** Манхэттенское расстояние между клетками. */
const рядом = (a, b) => { const dx = a.x - b.x, dy = a.y - b.y; return (dx < 0 ? -dx : dx) + (dy < 0 ? -dy : dy); };
/** Сумма характеристик: грубая мера силы юнита. */
const сила = (m, i) => m.u8(UNITS + i + U.HPMAX) + m.u8(UNITS + i + U.MAG) + m.u8(UNITS + i + U.ATK)
                     + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.SPD);
/** Зажать значение в 0..1 (признаки сети должны быть нормированы). */
const зажать = (x) => x < 0 ? 0 : x > 1 ? 1 : x;
const ЗОНА = 15;                    // клеток вокруг отряда: это и есть «своя зона» тактика

/**
 * Наблюдение тактика для отряда. Все числа приведены к 0..1: сеть маленькая, и разнобой
 * масштабов ей вреден больше, чем потеря точности.
 */
export function наблюдать(eng, с, о, отряд, вых = new Float32Array(ВХОД)) {
  const m = eng.m; вых.fill(0);
  const живые = отряд.filter(i => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1));
  if (!живые.length) return вых;
  let cx = 0, cy = 0, hp = 0, сил = 0, стрелков = 0, герой = 0;
  for (const i of живые) {
    const c = кл(m, i); cx += c.x; cy += c.y;
    hp += m.u8(UNITS + i + U.HP) / Math.max(1, m.u8(UNITS + i + U.HPMAX));
    сил += сила(m, i);
    const т = m.u8(UNITS + i + U.TYPE); if (т >= 5 && т <= 8 || т === 13) стрелков++;
    if (с.герои && с.герои.includes(i)) герой = 1;
  }
  const центр = { x: (cx / живые.length) | 0, y: (cy / живые.length) | 0 };
  вых[0] = зажать(живые.length / 10);
  вых[1] = зажать(hp / живые.length);
  вых[2] = зажать(стрелков / живые.length);
  вых[3] = зажать(сил / живые.length / 400);
  вых[4] = герой;

  // Чужие в зоне отряда: сколько их, какие они и далеко ли ближайший.
  let вблизи = 0, ихHP = 0, ихСил = 0, ихСтрелков = 0, d0 = 99;
  for (const е of о.врагиВидимые) {
    const d = рядом(кл(m, е), центр); if (d < d0) d0 = d;
    if (d > ЗОНА) continue;
    вблизи++; ихHP += m.u8(UNITS + е + U.HP) / Math.max(1, m.u8(UNITS + е + U.HPMAX)); ихСил += сила(m, е);
    const т = m.u8(UNITS + е + U.TYPE); if (т >= 5 && т <= 8 || т === 13) ихСтрелков++;
  }
  вых[5] = зажать(вблизи / 10);
  вых[6] = вблизи ? зажать(ихHP / вблизи) : 0;
  вых[7] = вблизи ? зажать(ихСтрелков / вблизи) : 0;
  вых[8] = вблизи ? зажать(ихСил / вблизи / 400) : 0;
  вых[9] = зажать(d0 / 40);
  // Перевес в зоне: своя сила против чужой, приведённая к 0..1 (0.5 — поровну).
  const своя = живые.reduce((s, i) => s + сила(m, i) * m.u8(UNITS + i + U.HP) / Math.max(1, m.u8(UNITS + i + U.HPMAX)), 0);
  const чужая = ихСил * (вблизи ? ихHP / вблизи : 0);
  вых[10] = зажать(своя / Math.max(1, своя + чужая));
  вых[11] = зажать(о.врагиВидимые.length / 15);
  вых[12] = зажать(о.бойцы.length / 15);
  вых[13] = зажать(о.дома.size / 6);
  вых[14] = зажать(о.вражДомаВидимые.length / 6);
  вых[15] = с.вражБаза ? 1 : 0;
  вых[16] = с.вражБаза ? зажать(рядом(центр, с.вражБаза) / 80) : 1;
  вых[17] = о.база ? зажать(рядом(центр, о.база) / 80) : 1;
  вых[18] = зажать(о.еда / 1500);
  const шаг = m.u32(G.step);
  вых[19] = с.битС >= 0 ? зажать(1 - (шаг - с.битС) / 1200) : 0;          // насколько свежий удар по дому
  вых[20] = о.святилище ? зажать(m.u8(UNITS + о.святилище + U.HP) / Math.max(1, m.u8(UNITS + о.святилище + U.HPMAX))) : 0;
  вых[21] = зажать(шаг / 20000);
  // Ближайшая добыча: зверь, до которого недалеко и рядом с которым нет чужих бойцов.
  let dз = 99;
  for (const з of о.звери) {
    const п = кл(m, з); const d = рядом(п, центр); if (d >= dз) continue;
    let подВрагом = false;
    for (const е of о.врагиВидимые) if (рядом(кл(m, е), п) <= 12) { подВрагом = true; break; }
    if (!подВрагом) dз = d;
  }
  вых[22] = зажать(dз / 50);
  вых[23] = с.осанка === 'копим' ? 1 : с.осанка === 'оборона' ? 0.66 : с.осанка === 'атака' ? 0.33 : 0;
  return вых;
}

// ---------------------------------------------------------------- сеть
// Один скрытый слой на 16 нейронов: около 650 весов. Столько ищется эволюцией за разумное время,
// а больше на таком коротком входе и не нужно.
export function случайная(seed = 1) {
  let s = seed >>> 0 || 1;
  const сл = () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296 * 2 - 1; };
  const мас = Math.sqrt(1 / ВХОД);
  return { w1: Float32Array.from({ length: ВХОД * СКРЫТЫХ }, () => сл() * мас), b1: new Float32Array(СКРЫТЫХ),
           w2: Float32Array.from({ length: СКРЫТЫХ * ВЫХОД }, () => сл() * Math.sqrt(1 / СКРЫТЫХ)), b2: new Float32Array(ВЫХОД) };
}
/** Веса сети одним плоским вектором — так их правит эволюция. */
export const вВектор = (сеть) => Float32Array.from([...сеть.w1, ...сеть.b1, ...сеть.w2, ...сеть.b2]);
/** Обратно: плоский вектор в матрицы сети. */
export function изВектора(v) {
  let k = 0; const взять = (n) => Float32Array.from(v.slice(k, k += n));
  return { w1: взять(ВХОД * СКРЫТЫХ), b1: взять(СКРЫТЫХ), w2: взять(СКРЫТЫХ * ВЫХОД), b2: взять(ВЫХОД) };
}
export const ЧИСЛО_ВЕСОВ = ВХОД * СКРЫТЫХ + СКРЫТЫХ + СКРЫТЫХ * ВЫХОД + ВЫХОД;

/** Прямой проход: вход → три группы логитов. Argmax по логитам, без softmax: решение в партии
 *  должно быть однозначным на любой машине, а Math.exp в стандарте языка не задан точно. */
export function вперёд(сеть, вх, буф = new Float32Array(СКРЫТЫХ), вых = new Float32Array(ВЫХОД)) {
  for (let j = 0; j < СКРЫТЫХ; j++) {
    let s = сеть.b1[j]; const б = j * ВХОД;
    for (let i = 0; i < ВХОД; i++) s += сеть.w1[б + i] * вх[i];
    буф[j] = s > 0 ? s : 0;                                  // ReLU
  }
  for (let a = 0; a < ВЫХОД; a++) {
    let s = сеть.b2[a]; const б = a * СКРЫТЫХ;
    for (let j = 0; j < СКРЫТЫХ; j++) s += сеть.w2[б + j] * буф[j];
    вых[a] = s;
  }
  return вых;
}
/** Номер наибольшего значения в куске вектора (выбор роли и цели). */
const argmax = (v, от, до) => { let k = от; for (let i = от + 1; i < до; i++) if (v[i] > v[k]) k = i; return k - от; };

/** Решение тактика: {роль, цель, вес}. */
export function решение(сеть, вх, буф, вых) {
  const л = вперёд(сеть, вх, буф, вых);
  const р = argmax(л, 0, РОЛИ.length);
  const ц = argmax(л, РОЛИ.length, РОЛИ.length + ЦЕЛИ.length);
  const в = argmax(л, РОЛИ.length + ЦЕЛИ.length, ВЫХОД);
  return { роль: РОЛИ[р], цель: ЦЕЛИ[ц], вес: ВЕСА[в], логиты: л };
}
