// Грубая модель партии (наше): считаем не каждый шаг движка, а сразу пятисекундными отрезками.
//
// Замысел владельца: «стратег принимает решение раз в несколько секунд, промежуточные кадры ему
// не нужны; если найти упрощённый метод и сократить число шагов в сто-тысячу раз, обучение
// пойдёт куда быстрее, и можно будет гонять не только пятнадцатиминутные партии, но и получасовые».
//
// Счёт простой: шаг движка это 55 мс, в пяти игровых секундах их 91, а в партии на 15 минут —
// 16 364. Модель делает 180 обновлений вместо 16 364 шагов, то есть примерно в девяносто раз
// меньше работы, и каждое обновление само по себе в разы дешевле шага. Получасовая партия в
// модели стоит дешевле, чем полминуты настоящей.
//
// ЧЕСТНОСТЬ. Это приближение, и оно врёт. Здесь нет поиска пути, тумана, микроконтроля, цветов,
// подобранных вещей и половины мелочей. Поэтому правило работы такое:
//   • учим стратега в модели — быстро и много;
//   • ПРОВЕРЯЕМ в настоящем движке, и только по нему судим;
//   • коэффициенты модели подбираем по настоящим партиям (tools/ai_модель.mjs), а не на глаз.
// Если сеть начнёт «выигрывать» в модели и проваливаться в игре — значит она нашла дырку в
// модели, а не стратегию; это нормальный рабочий режим, а не катастрофа.
//
// Формулы боя, опыта и цен берём ровно те, по которым живёт игра (см. notes/combat-spec.md и
// js/port/ai_script.js): урон за удар = ((АТК−ДЕФ)>>4) + (АТК>>5) + 1, перезарядка = 16 − СПД>>4,
// опыт за убийство = (сумма статов жертвы)² >> 2, цена +1 к стату = (текущий² >> 1) + 10.

export const ШАГ_С = 5;                                  // столько игровых секунд в одном обновлении

/** Урон за удар по формуле движка. */
export const урон = (атк, деф) => (((атк - деф) >> 4) + (атк >> 5) + 1) | 0;
/** Ударов в секунду: перезарядка в шагах = 16 − СПД>>4, шаг = 55 мс. */
export const темп = (спд) => 1 / (Math.max(1, 16 - (спд >> 4)) * 0.055);
/** Цена следующего очка стата. */
export const ценаОчка = (текущий) => ((текущий * текущий) >> 1) + 10;

/**
 * Отряд в модели: сколько бойцов и какие они в среднем. Держим средние, а не каждого: стратегу
 * всё равно, кто именно из шестерых упал, ему важно, что отряд ослаб.
 */
export const отряд = (n = 0, атк = 30, деф = 10, hp = 60, спд = 32, опыт = 0) => ({ n, атк, деф, hp, спд, опыт });

/** Суммарная «сила» отряда — та же мерка, что в скрипте: чем бить и сколько держит. */
export const силаОтряда = (о) => о.n * (о.атк + о.деф + о.hp);

/**
 * Бой двух отрядов за отрезок. Считаем взаимный урон по формуле движка и переводим его в потери:
 * пока суммарный урон не съел здоровье одного бойца — падает доля бойца, дальше целый.
 * Это и есть основное упрощение: строй, фокус огня и отход раненых сюда не входят.
 */
export function бой(a, b, секунд = ШАГ_С) {
  if (!a.n || !b.n) return;
  const уронAB = урон(a.атк, b.деф) * темп(a.спд) * a.n * секунд;
  const уронBA = урон(b.атк, a.деф) * темп(b.спд) * b.n * секунд;
  const палоB = Math.min(b.n, уронAB / Math.max(1, b.hp));
  const палоA = Math.min(a.n, уронBA / Math.max(1, a.hp));
  // Опыт достаётся победителю пропорционально убитым — ровно как в игре, где его получает добивший.
  a.опыт += палоB * ((b.атк + b.деф + b.hp) ** 2) / 4;
  b.опыт += палоA * ((a.атк + a.деф + a.hp) ** 2) / 4;
  a.n -= палоA; b.n -= палоB;
  if (a.n < 0.01) a.n = 0; if (b.n < 0.01) b.n = 0;
}

/** Вложить накопленный опыт в статы: пока хватает — покупаем очки, как это делает движок. */
export function подрасти(о) {
  let сделано = 0;
  while (сделано < 50) {                                 // предел на отрезок, чтобы не уйти в цикл
    const ц = ценаОчка(Math.round((о.атк + о.деф) / 2));
    if (о.опыт < ц) break;
    о.опыт -= ц; сделано++;
    // Движок раскидывает по статам; у нас — поочерёдно, чтобы отряд рос равномерно.
    if (сделано % 3 === 0) о.hp += 1; else if (сделано % 3 === 1) о.атк += 1; else о.деф += 1;
  }
}

/**
 * Охота за отрезок: отряд бьёт зверей, получает мясо и опыт. `стадо` — сколько зверей рядом и
 * какие они; возвращает, сколько мяса добыто.
 */
export function охота(о, стадо, секунд = ШАГ_С) {
  if (!о.n || !стадо.n) return 0;
  const зверь = отряд(стадо.n, стадо.атк, стадо.деф, стадо.hp, стадо.спд);
  const было = зверь.n;
  бой(о, зверь, секунд);
  стадо.n = зверь.n;
  const убито = было - зверь.n;
  return убито * стадо.мясо;
}

/**
 * Одна сторона в модели. Держим ровно то, чем ворочает стратег: еду, отряды, дома, рабочих и
 * расстояния. Всё остальное — подробности, которые на этом уровне не нужны.
 */
export function сторона({ еда = 2000, бойцы = отряд(4), рабочие = 2, дома = { склад: 1, святилище: 1 },
                          доБазы = 0, доПастбища = 12, доВрага = 60 } = {}) {
  return { еда, бойцы, рабочие, дома, доБазы, доПастбища, доВрага, мясоНаЗемле: 0, принесено: 0, построено: 0 };
}

// Сколько мяса один носильщик доносит в секунду: зависит от расстояния до пастбища. Коэффициент
// подбирается по настоящим партиям (tools/ai_модель.mjs), здесь — стартовое значение.
export const НОСКА = { скорость: 1.6, груз: 1000 };       // клеток в секунду и сколько несёт за ходку

/** Сколько мяса донесут носильщики за отрезок. */
export function доставка(с, секунд = ШАГ_С) {
  if (!с.мясоНаЗемле || !с.рабочие) return 0;
  const ходка = (2 * с.доПастбища) / НОСКА.скорость;      // туда и обратно
  const заОтрезок = с.рабочие * НОСКА.груз * (секунд / Math.max(1, ходка));
  const донесли = Math.min(с.мясоНаЗемле, заОтрезок);
  с.мясоНаЗемле -= донесли; с.еда += донесли; с.принесено += донесли;
  return донесли;
}
