/** Расставить n бойцов строем в прямоугольнике: одинаково у всех машин, генератор один. */
function построение(сл, n, x0, x1, y0, y1, вид) {
  const cy = (y0 + y1) >> 1;
  if (вид === 'линия') return Array.from({ length: n }, (_, k) => [x0 + сл(2), Math.max(y0, Math.min(y1, cy - n + 1 + k * 2))]);
  if (вид === 'клин') return Array.from({ length: n }, (_, k) => [x0 + Math.ceil(k / 2) * (x0 < 10 ? -1 : 1) + (x0 < 10 ? 2 : 0), Math.max(y0, Math.min(y1, cy + (k % 2 ? 1 : -1) * Math.ceil(k / 2)))]);
  return точки(сл, n, x0, x1, y0, y1);
}
