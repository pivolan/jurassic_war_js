/** Случайный тип нашего бойца: чаще маг (стрелок), иногда общинник, ручной динозавр или дилофозавр (стрелок). */
const боец = (сл) => [[5], [5], [1], [9], [13]][сл(5)];
/** Дерево, только если клетка свободна и не запрещена. */
function лес(eng, сц, сл, n, x0, x1, y0, y1, кроме = []) {
  for (let k = 0; k < n * 3 && n > 0; k++) {
    const x = x0 + сл(x1 - x0 + 1), y = y0 + сл(y1 - y0 + 1);
    if (!свободна(eng.m, x, y) || кроме.some(([kx, ky]) => Math.abs(kx - x) <= 1 && Math.abs(ky - y) <= 1)) continue;
    дерево(eng, сц, x, y); n--;
  }
}
/** Несколько точек в прямоугольнике, не совпадающих друг с другом. */
function точки(сл, n, x0, x1, y0, y1) {
  const из = [];
  while (из.length < n) {
    const p = [x0 + сл(x1 - x0 + 1), y0 + сл(y1 - y0 + 1)];
    if (!из.some(([x, y]) => x === p[0] && y === p[1])) из.push(p);
  }
  return из;
}
/** Натравить всех перечисленных на одну цель (сборка сцены, не решение ИИ). */
const всем = (eng, кто, цель) => { for (const i of кто) приказАтаковать(eng, i, цель); };

/** Общий каркас: генератор, поле, боец; возвращает всё, что нужно сценам. */
function старт(соль, вар, x, y, типы) {
  return (eng) => {
    const сл = случай(вар * 7919 + соль * 104729 + 17);
    const сц = поле(eng);
    const наш = наши(eng, сц, [[typeof x === 'function' ? x(сл) : x, typeof y === 'function' ? y(сл) : y]], типы ? типы(сл) : undefined);
    return { сл, сц, наш, я: наш[0] };
  };
}

