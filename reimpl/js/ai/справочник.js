const ТИК_С = 0.055;                            // один шаг движка
const РЕГЕН_В_СЕК = 1 / (16 * ТИК_С);          // движок лечит всех на +1 жизнь каждые 16 тиков

export const доступно = (m, слот, вид, k) => (m.u32(m.u32(0x30e88 + слот * 4) + вид * 4) >>> k) & 1;
export const СТОИМОСТЬ = (m, вид, k) => m.u8(0x315ac + (вид << 5) + k) * m.u32(0x30eac + ((вид << 5) + k) * 4);

/**
 * ТЕМП ПРОИЗВОДСТВА. Заказ идёт шагами: на каждом шаге здание списывает `цена шага` еды
 * (0x30eac) и продвигает счётчик, всего шагов — 0x315ac (economy.js, 0x1879b). Шаг делается раз
 * в тик, тик — 55 мс. Отсюда и время заказа, и пропускная способность дома: сколько еды он
 * физически способен потратить в секунду. Это ответ на «сколько зданий имеет смысл держать»:
 * один дом перерабатывает запас с постоянной скоростью, второй такой же — вдвое быстрее.
 */
export function темпПроизводства(m, вид, k) {
  const шагов = m.u8(0x315ac + (вид << 5) + k), заШаг = m.u32(0x30eac + ((вид << 5) + k) * 4);
  if (!шагов || !заШаг) return null;
  return { шагов, заШаг, цена: шагов * заШаг, секунд: +(шагов * ТИК_С).toFixed(1),
           едыВСек: Math.round(заШаг / ТИК_С) };
}

/** Характеристики бойца по его типу — из того же блока, которым движок создаёт юнита. */
export function статы(m, тип) {
  const s = 0x37654 + m.u32(0x30a9e + тип * 4);
  return { тип, жизни: m.u8(s), мана: m.u8(s + 2), атака: m.u8(s + 3), защита: m.u8(s + 4),
           скорость: m.u8(s + 5), мясо: m.u16(s + 6) };
}

/**
 * ОРУЖИЕ И ЩИТЫ: что даёт вещь и против кого она хороша. Владелец: «надо ДЖЕВА научить строить
 * оружие — типа, кому какое оружие, и для чего, и почему».
 *
 * В движке у каждого оружия своя таблица прибавок ПО ТИПУ ЦЕЛИ (0x37af4 + id·4): копьё может
 * давать плюс по зверю и ничего по человеку. Та же таблица со смещением 0x28 — то, сколько
 * СНИМАЕТ чужой щит. Поэтому «для чего» считается прямо здесь: прибавка к удару по человеку, по
 * собаке, по тигру и по мамонту. Носят вещи только люди (типы 1–3): динозавр или маг их не берёт.
 */
/**
 * ГРУППА ВЕЩИ. Определять щит по полю «защита» нельзя: у деревянного щита там стоит НОЛЬ, а
 * защищает он через таблицу оружия нападающего (уронПо: `таблица + 0x28 + номер щита`). Из-за
 * этого щиты числились оружием, и кузнице казалось, что щитов в меню нет вовсе. Владелец показал
 * панель Koomba: «вот у Koomba щит есть… синий щит» — и правда, предмет 8 это «Деревянный щит».
 * Таблица взята из наших же текстов предметов (reimpl/data/items_text.json, поле «группа»).
 */
const ГРУППЫ = { оружие: [1, 2, 3, 4, 5, 6, 7, 15, 16, 18, 22, 23],
                 щит: [8, 9, 10, 21, 24],
                 расходник: [11, 12, 13, 14, 30],
                 артефакт: [17, 19, 20, 25, 26, 27, 28, 29] };
export function группаВещи(id) {
  for (const [имя, список] of Object.entries(ГРУППЫ)) if (список.includes(id)) return имя;
  return 'иное';
}

export function вещьСправка(m, id) {
  const строка = 0x30954 + m.u32(0x30a9e + id * 4);
  const атака = m.u8(строка + 3), защита = m.u8(строка + 4);
  const таблица = m.u32(0x37af4 + id * 4);
  const цель = { человек: 3, пёс: 23, тигр: 21, мамонт: 19 };
  const прибавка = {};
  if (атака > 0 && таблица) for (const [имя, т] of Object.entries(цель)) прибавка[имя] = m.u8(т + таблица);
  const группа = группаВещи(id);
  // Сколько щит снимет — зависит от оружия бьющего; для показа берём меч (предмет 1) как образец.
  const снимает = группа === 'щит' ? m.u8(id + m.u32(0x37af4 + 1 * 4) + 0x28) : 0;
  return { id, атака, защита, жизни: m.u8(строка), скорость: m.u8(строка + 5), цена: m.u16(строка + 6),
           группа, оружие: группа === 'оружие', щит: группа === 'щит', снимает, прибавка };
}

/**
 * Кого делает дом этого вида и по какой кнопке. Казарма: кнопка 0 — простолюдин, 1 — силач,
 * 2 — воин (0x1d4df: тип = кнопка+1). Военные дома: одна и та же порода, кнопка — ступень выучки.
 */
function ктоИзДома(вид) {
  if (вид === 1) return [[1, 0], [2, 1], [3, 2]];
  if (вид >= 5 && вид <= 13) return [[вид, 0]];
  return [];
}

/**
 * Всё, что племя может заказать в Святилище, с ценой, ролью дома и силой его бойцов.
 * @param счёт функция «сколько таких домов уже есть» (из слоя стройки)
 */
export function домаПлемени(m, слот, еда, счёт = () => 0) {
  const список = [];
  for (let k = 0; k < 14; k++) {
    if (!доступно(m, слот, 0, k)) continue;
    const цена = СТОИМОСТЬ(m, 0, k);
    // Только те кнопки, что РЕАЛЬНО открыты этому племени на этой миссии. Иначе выходит обман:
    // в казарме на вторых миссиях открыт один простолюдин, а силач и воин — это его же выучка,
    // они вырастают из него в бою, а не заказываются.
    const даёт = ктоИзДома(k).filter(([, кн]) => доступно(m, слот, k, кн))
      .map(([т, кн]) => ({ кто: ИМЯ_ТИПА[т] || ('тип ' + т), ...статы(m, т),
                           цена: СТОИМОСТЬ(m, k, кн) || null }));
    список.push({ вид: k, имя: ИМЯ_ДОМА[k] || ('вид ' + k), цена, есть: счёт(k),
                  роль: РОЛЬ_ДОМА[k] || '', даёт, хватает: еда >= цена });
  }
  return список;
}

/**
 * Кого можно заказать ПРЯМО СЕЙЧАС в уже построенных домах. Владелец: «не всегда нам нужны все
 * здания, часто нам нужны новые юниты для атаки, охоты… пусть это ДЖЕВ решает, а ты ему просто
 * контекста наваливай». Поэтому здесь — полный список кнопок каждого нашего дома с ценой и силой
 * того, кто из этой кнопки выйдет.
 *
 * Выучка (k) у военных домов — это ступень: чем выше, тем дороже и сильнее боец. Оружейная делает
 * не бойцов, а вещи: их кладут на землю, и люди их надевают.
 */
export function бойцыВДомах(m, слот, дома, еда) {
  const список = [];
  for (const д of дома) {
    const вид = д.т - 0x1a;
    if (вид === 0 || д.стро) continue;                 // Святилище делает дома, недострой — ничего
    for (let k = 0; k < 8; k++) {
      if (!доступно(m, слот, вид, k)) continue;
      const цена = СТОИМОСТЬ(m, вид, k);
      if (!цена) continue;
      const темп = темпПроизводства(m, вид, k);
      const запись = { дом: д.н, вид, k, цена, хватает: еда >= цена, занят: д.занят, темп,
                       домИмя: ИМЯ_ДОМА[вид] || ('вид ' + вид) };
      if (вид === 1) { запись.кто = ['простолюдин', 'силач', 'воин'][k] || ('человек ' + k);
                       Object.assign(запись, статы(m, k + 1)); }
      else if (вид === 2 || вид === 3) {
        // Оружейная кладёт на землю предмет с номером k+1 (economy.js, 0x1d673).
        const в = вещьСправка(m, k + 1);
        запись.кто = в.оружие ? `оружие #${в.id}` : в.щит ? `щит #${в.id}` : `вещь #${в.id}`;
        Object.assign(запись, в, { вещь: true });
      }
      else { запись.кто = `${ИМЯ_ТИПА[вид] || 'боец'} (выучка ${k + 1})`; Object.assign(запись, статы(m, вид)); }
      список.push(запись);
    }
  }
  return список;
}

/**
 * ЧТО ХАРАКТЕРИСТИКИ ЗНАЧАТ В БОЮ. Владелец: «мы же ему не рассказали, насколько важны
 * характеристики юнита». Голые «атака 70, жизни 50» мозгу ничего не говорят — он сравнивает цены.
 * Поэтому переводим их в то, ради чего бойца покупают, по формулам самого движка:
 *
 *   урон за удар   = max(1, ((атака − защита цели) >> 4) + (атака >> 5) + 1)   (0x1e934)
 *   удар раз в     = 8 шагов у человека, 6 у ящера и зверя, шаг = 55 мс       (0x1a7cb)
 *   регенерация    = +1 жизнь каждые 16 тиков у всех живых                     (0x18ab2)
 *
 * Отсюда «урон в секунду», «сколько продержится» и «сколько успеет нанести за жизнь» — по этим
 * числам и видно, дорогой боец или двое дешёвых.
 */
export const уронЗаУдар = (атака, защита) => Math.max(1, (Math.max(атака - защита, 0) >> 4) + (атака >> 5) + 1);
// ТЕМП УДАРОВ — ПО ЗАМЕРУ. Человек (типы 1–8) в ближнем бою бьёт раз в 8 шагов: удар на 8-м кадре
// анимации (0x1a7cb, счётчик 2→8); ящер и зверь (тип 9 и выше) — раз в 6 (удар на 6-м кадре, счётчик
// снова с 2); растение — каждый шаг. От скорости темп НЕ зависит: проверено на скоростях 20, 100 и
// 200 (tools: удары.mjs, удары_зверя.mjs). Прежняя формула 16 − (скорость >> 4) — это пауза после
// подхода к цели (состояние 0x12), а не темп: с ней простолюдин бил вдвое реже, чем на деле.
export const тиковНаУдар = (тип) => (тип === 24 || тип === 25) ? 1 : ((тип ?? 1) < 9 ? 8 : 6);   // тип не знаем — считаем человеком
export const ударовВСекунду = (скорость, тип) => 1 / (тиковНаУдар(тип) * ТИК_С);

export function боевыеЦифры(боец, зверь) {
  if (!зверь || !зверь.атака) return null;
  const нашУдар = уронЗаУдар(боец.атака, зверь.защита);
  const егоУдар = уронЗаУдар(зверь.атака, боец.защита);
  const уронВСек = нашУдар * ударовВСекунду(боец.скорость, боец.тип);
  const поНам = Math.max(0.01, егоУдар * ударовВСекунду(зверь.скорость, зверь.тип ?? 22) - РЕГЕН_В_СЕК);
  const живёт = боец.жизни / поНам;
  const всего = уронВСек * живёт;
  return { нашУдар, егоУдар, уронВСек: +уронВСек.toFixed(1), живёт: +живёт.toFixed(1),
           всего: Math.round(всего), заЕду: боец.цена ? Math.round(всего / боец.цена * 1000) : null };
}

/**
 * ОТРЯД ПРОТИВ ЗВЕРЯ: бьёт ли отряд его вместе. Урон отряда в секунду — сумма; зверь бьёт одного за
 * другим (по средней защите). Годится, если за время убийства зверь снимет не больше половины общих
 * жизней отряда — ротацией раненых это без потерь (так четверо простолюдинов Тирано валят пса).
 */
export function отрядБьёт(отряд, зверь, доля = 0.5) {
  if (!отряд.length || !зверь) return false;
  let урон = 0, жизни = 0, защита = 0;
  for (const б of отряд) { урон += уронЗаУдар(б.атака, зверь.защита) * ударовВСекунду(б.скорость, б.тип); жизни += б.жизни; защита += б.защита; }
  const чистый = урон - РЕГЕН_В_СЕК; if (чистый <= 0) return false;
  const секунд = зверь.жизни / чистый;
  const поНам = уронЗаУдар(зверь.атака, защита / отряд.length) * ударовВСекунду(зверь.скорость, зверь.тип ?? 22);
  return поНам * секунд <= жизни * доля;
}

/**
 * ОДИН ПРОТИВ ТОЛПЫ. Владелец: «допустим, по очереди; если бить будет одновременно — коэффициенты
 * разные». Верно: когда n врагов бьют разом, входящий урон умножается на n, а наш остаётся
 * прежним — мы всё равно бьём по одному. Поэтому считаем оба случая.
 */
export function противТолпы(a, b, n) {
  const уронНаш = уронЗаУдар(a.атака, b.защита) * ударовВСекунду(a.скорость, a.тип);
  const уронИх = уронЗаУдар(b.атака, a.защита) * ударовВСекунду(b.скорость, b.тип ?? 22);
  let жизни = a.жизни, врагов = n, секунд = 0;
  while (врагов > 0) {
    const поНам = Math.max(0, уронИх * врагов - РЕГЕН_В_СЕК);
    const наУбийство = b.жизни / Math.max(0.01, уронНаш - РЕГЕН_В_СЕК);
    жизни -= поНам * наУбийство; секунд += наУбийство;
    if (жизни <= 0) return { победит: false, убил: n - врагов, секунд: +секунд.toFixed(1) };
    врагов--;
  }
  return { победит: true, убил: n, осталось: Math.round(жизни), секунд: +секунд.toFixed(1) };
}

/**
 * ДУЭЛЬ ПО КАЛЬКУЛЯТОРУ: кто кого и какой ценой. Владелец: «типа один силач может убить 5
 * слабаков, или как там — у тебя ведь есть данные калькулятора». Считаем ровно по движку: урон за
 * удар и темп ударов с обеих сторон; регенерацию (+1 жизнь за 16 тиков, 0x18ab2) тоже учитываем,
 * потому что на длинных разменах она решает.
 */
export function дуэль(a, b) {
  const уронA = уронЗаУдар(a.атака, b.защита) * ударовВСекунду(a.скорость, a.тип) - РЕГЕН_В_СЕК;
  const уронB = уронЗаУдар(b.атака, a.защита) * ударовВСекунду(b.скорость, b.тип ?? 22) - РЕГЕН_В_СЕК;
  if (уронA <= 0) return { победит: false, секунд: Infinity, потерял: a.жизни };
  const секунд = b.жизни / уронA;
  const потерял = Math.max(0, уронB) * секунд;
  return { победит: потерял < a.жизни, секунд: +секунд.toFixed(1), потерял: Math.round(потерял) };
}

/** Скольких таких он положит подряд, не отдыхая между схватками. */
export function скольких(a, b) {
  const д = дуэль(a, b);
  if (!isFinite(д.секунд)) return 0;
  if (д.потерял <= 0) return 99;                       // не пробивают вовсе
  return Math.max(0, Math.ceil(a.жизни / д.потерял) - 1);
}

/** Боевые цифры строкой: что боец сделает против вот этого зверя. */
export function строкаБоя(ц, зверь) {
  if (!ц) return '';
  return `; против «${зверь.кто}» бьёт на ${ц.нашУдар} (${ц.уронВСек} урона в секунду),`
       + ` тот бьёт его на ${ц.егоУдар} — продержится ${ц.живёт} с и успеет нанести ${ц.всего} урона`
       + (ц.заЕду ? `, то есть ${ц.заЕду} урона на 1000 еды` : '');
}

/**
 * Сравнение с самым дешёвым бойцом — то, ради чего всё это и считается: «типа один силач может
 * убить 5 слабаков». Даём оба случая: по очереди и когда наваливаются разом.
 */
export function сравнениеСДешёвым(б, дешёвый) {
  if (!дешёвый || !б.атака || б.кто === дешёвый.кто) return '';
  const подряд = скольких(б, дешёвый);
  const заЦену = Math.max(1, Math.round(б.цена / (дешёвый.цена || 1)));
  const толпа = противТолпы(б, дешёвый, заЦену);
  return `; в дуэли кладёт подряд ${подряд >= 99 ? 'сколько угодно' : подряд} таких, как ${дешёвый.кто};`
       + ` против ${заЦену} сразу (столько же по деньгам) — ${толпа.победит
           ? `побеждает, оставшись с ${толпа.осталось} жизнями` : `проигрывает, успев убить ${толпа.убил}`}`;
}

/** Одна строка про бойца для мозга: где заказать, почём и что он собой представляет. */
export function описаниеБойца(б, зверь = null, дешёвый = null) {
  if (б.вещь) {
    const п = Object.entries(б.прибавка || {}).map(([к, v]) => `по ${к} +${v}`).join(', ');
    return `${б.кто} в «${б.домИмя}», цена ${б.цена}`
      + (б.атака ? `: прибавка к атаке ${б.атака}` + (п ? ` (${п})` : '') : '')
      + (б.щит ? `: защита ${б.защита}` : '')
      + ' — вещь кладут на землю, её подбирают и надевают ЛЮДИ (простолюдин, силач, воин);'
      + ' динозавры и маги вещей не носят';
  }
  return `${б.кто} в «${б.домИмя}», цена ${б.цена}`
         + (б.темп ? ` (делается ${б.темп.секунд} с, дом при этом тратит ${б.темп.едыВСек} еды в секунду)` : '')
         + `: ${б.жизни} жизней, атака ${б.атака},`
         + ` защита ${б.защита}, скорость ${б.скорость}`
         + строкаБоя(боевыеЦифры(б, зверь), зверь || {})
         + сравнениеСДешёвым(б, дешёвый);
}

/** Одна строка про дом для мозга: цена, роль и кого он даёт с цифрами. */
export function описаниеДома(д, зверь = null) {
  // Дома работают по одному заказу за раз: второй такой же дом удваивает скорость производства.
  // Владелец: «если прям большой избыток мяса, имеет смысл построить ещё здания, чтобы быстрее
  // строить воинов для атаки».
  const кто = д.даёт.map(б => `${б.кто} (${б.жизни} жизней, атака ${б.атака}, защита ${б.защита}, скорость ${б.скорость}`
                              + (б.цена ? `, цена ${б.цена}` : '') + ')'
                              + (зверь && б.цена ? строкаБоя(боевыеЦифры(б, зверь), зверь).replace(/^; /, ', ') : '')).join('; ');
  // Про дубликат говорим честно: второй такой же дом нужен ТОЛЬКО когда первый не успевает
  // тратить доход. Прежняя формулировка («второй удваивает скорость») звучала как приглашение, и
  // ДЖЕВ ставил вторую оружейную при живой первой.
  return `${д.имя}, цена ${д.цена}`
         + (д.есть ? `. У НАС УЖЕ ЕСТЬ ТАКОЙ (${д.есть}); второй нужен только если первый не`
                     + ' успевает тратить доход, иначе это выброшенная еда' : '')
         + (д.роль ? ` — ${д.роль}` : '') + (кто ? `: ${кто}` : '');
}
