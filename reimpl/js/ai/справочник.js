/**
 * СПРАВОЧНИК ПЛЕМЕНИ: что оно умеет строить, кого эти дома делают и чего те бойцы стоят.
 *
 * Зачем. Владелец: «надо дать ему контекст — у нас есть информация по каждой расе, по доступным
 * юнитам, их силе и т.д., и что они делают, для чего полезны… надо приготовить всю эту информацию,
 * чтобы скармливать сети, и она понимала, что делать и что строить; сейчас за Moospell, например,
 * ничего не строится». Мозгу штаба (ДЖЕВУ или сети) нельзя предлагать голые номера кнопок: «вид 9»
 * ему ничего не говорит, а «загон велоцирапторов за 2500, даёт велоцираптора: 55 жизней, атака 45,
 * скорость 40» — говорит.
 *
 * Откуда берутся цифры. Всё читается у самого движка, ничего не выдумано:
 *   • какие кнопки есть у племени — таблица меню 0x30e88: `доступно(слот, вид, k)`;
 *   • сколько стоит кнопка — 0x315ac (счётчик) × 0x30eac (цена шага);
 *   • характеристики бойца — блок 0x37654 + 0x30a9e[тип]: жизни, мана, атака, защита, скорость,
 *     мясо (combat.js, 0x1cfcb — тем же блоком движок оживляет зверя).
 *
 * Соответствие «кнопка Святилища → тип бойца» тоже из игры: тип дома = вид + 0x1a, казарма (вид 1)
 * делает людей типов 1–3, а военные дома (вид ≥ 5) делают бойца, у которого ТИП РАВЕН ВИДУ дома —
 * загон велоцирапторов (9) делает велоцираптора (9).
 */
