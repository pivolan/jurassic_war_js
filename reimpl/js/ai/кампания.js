/**
 * Что от нас хочет миссия кампании — прочитанное из самой игры, а не выписанное под каждую карту.
 *
 * У кампании двенадцать миссий и восемь племён, и у каждой пары свой обработчик цели: игра держит
 * их в таблице 0x36a60[миссия*8 + племя] и вызывает раз в 32 шага (js/port/orders_ai.js, 0x17861).
 * Разбор ниже переводит адрес обработчика в понятное задание. Смысл именно в этом: один и тот же
 * скрипт спрашивает у движка «что считается победой здесь» и играет на это, вместо того чтобы
 * иметь по сценарию на карту.
 *
 * Виды задания:
 *   {вид:'еда',      сколько}          — накопить столько еды (у юнитов и в складах)
 *   {вид:'дома',     надо:[{вид,n}]}   — построить столько домов таких видов (виды суммируются, если
 *                                        в списке несколько — игре всё равно, какой из пары)
 *   {вид:'владелец', кого}             — истребить всех юнитов такого племени
 *   {вид:'артефакт', предмет}          — принести предмет с таким номером кому-нибудь в руки
 *   {вид:'захват',   цели:[id]}        — сделать своими эти здания (строителем с видом 0xe)
 *   {вид:'зверьё',   типы:[]}          — выбить всё зверьё этих видов
 *   {вид:'все'}                        — уничтожить всех чужих владельцев
 */
import { G } from '../mem.js';

const ЕДА = (сколько) => () => ({ вид: 'еда', сколько });
const ДОМА = (...надо) => () => ({ вид: 'дома', надо });
const ВЛАДЕЛЕЦ = (кого) => () => ({ вид: 'владелец', кого });
const ВСЕ = () => ({ вид: 'все' });
/** Один пункт списка «дома»: столько-то домов такого вида (или любого из перечисленных). */
const д = (n, ...виды) => ({ виды, n });

// Адрес обработчика → задание. Условия — те же, что в js/port/orders_ai.js: там счётчик домов
// лежит в 0x36bc6+тип, то есть 0x36be0+вид.
const ПО_АДРЕСУ = {
  0x17989: ЕДА(3000), 0x179d6: ЕДА(3000),          // вторая ещё требует добить владельца 0
  0x17a19: ДОМА(д(3, 1), д(3, 9)),
  0x17a3d: ДОМА(д(2, 1), д(2, 5)),
  0x17a61: ДОМА(д(2, 8), д(4, 4)),
  0x17a85: ДОМА(д(4, 2, 3), д(3, 1)),
  0x17aaf: ДОМА(д(3, 1), д(3, 6)),
  0x17ad3: ДОМА(д(3, 1), д(2, 2, 3)),
  0x17afd: ДОМА(д(3, 2, 3), д(4, 4)),
  0x17b27: ДОМА(д(3, 11)),
  0x17b42: ВЛАДЕЛЕЦ(1), 0x17b59: ВЛАДЕЛЕЦ(0), 0x17b70: ВЛАДЕЛЕЦ(3), 0x17b87: ВЛАДЕЛЕЦ(2),
  0x17b9e: ВЛАДЕЛЕЦ(5), 0x17bb5: ВЛАДЕЛЕЦ(4), 0x17bcc: ВЛАДЕЛЕЦ(7), 0x17be3: ВЛАДЕЛЕЦ(6),
  0x17bfa: (m, вл) => ({ вид: 'артефакт', предмет: m.u8(0x36c54 + вл) }),
  0x17c79: (m, вл) => ({ вид: 'захват', цели: [m.u32(0x36c5c + вл * 4)] }),
  0x17ca9: () => ({ вид: 'зверьё', типы: [14, 16, 17, 19] }),
  0x17cde: (m, вл) => ({ вид: 'захват', цели: [m.u32(0x36c7c + вл * 8), m.u32(0x36c80 + вл * 8)] }),
  0x17d28: ВСЕ, 0x17d26: ВСЕ, 0x17d59: ВСЕ, 0x17d5c: ВСЕ,
};
// Вторая миссия RaDumBa: еда И зачистка владельца 0. Еду добываем так же, поэтому отдельного вида
// задания не заводим — доносим это отдельным полем.
const ДОБАВКА = { 0x179d6: { плюсВладелец: 0 } };

/** Задание миссии для владельца вл (по умолчанию — для человека). null, если обработчик незнаком. */
export function задание(m, вл = m.u8(G.humanOwner)) {
  const адрес = m.u32(0x36a60 + ((m.u8(G.mission) * 8 + (вл & 7)) & 0xffff) * 4);
  const f = ПО_АДРЕСУ[адрес]; if (!f) return null;
  const з = f(m, вл & 7); з.адрес = адрес;
  return Object.assign(з, ДОБАВКА[адрес] || null);
}

/** Коротко словами — для трасс и стенда. */
export function словами(з) {
  if (!з) return 'неизвестно';
  if (з.вид === 'еда') return `накопить ${з.сколько} еды` + (з.плюсВладелец !== undefined ? ` и добить племя ${з.плюсВладелец}` : '');
  if (з.вид === 'дома') return 'построить ' + з.надо.map(п => `${п.n}×дом[${п.виды.join('/')}]`).join(' и ');
  if (з.вид === 'владелец') return `истребить племя ${з.кого}`;
  if (з.вид === 'артефакт') return `добыть предмет ${з.предмет}`;
  if (з.вид === 'захват') return `захватить ${з.цели.length === 1 ? 'святилище' : з.цели.length + ' святилища'}`;
  if (з.вид === 'зверьё') return `истребить зверьё видов ${з.типы.join(',')}`;
  return 'уничтожить всех';
}
