// Прогон одного эпизода: движок шагает, политика решает раз в N тиков (наше).
//
// Один и тот же прогон используется и в просмотрщике (по кадру за раз), и в headless-сборе
// датасета (целиком, без графики). Поэтому шаг вынесен отдельно: `шаг(эп)` делает ровно один
// тик движка и, если пришло время решения, спрашивает политику и кладёт приказы.
import { G, U, UNITS } from '../mem.js';
import { выполнить, жив, ЧИСЛО_ДЕЙСТВИЙ, враги, обмен, союзники, ОТОЙТИ, СТРЕЛЯТЬ, строитель, ПЕРЕВЕС } from './act.js';
import { ПОДСКАЗКИ } from './reward.js';
import { наблюдать, пустое } from './obs.js';
import { решение } from './policy_script.js';
import { U as _U } from '../mem.js';
import { замер, заШаг, итог, еда } from './reward.js';

export const ИНТЕРВАЛ = 8;        // тиков между решениями: 8 × 55 мс ≈ 0.45 с, темп живого игрока

/** Подготовить эпизод к прогону: память бойцов, первый замер, буферы наблюдений. */
export function начать(eng, эп) {
  эп.тик = 0;
  эп.решений = 0;
  эп.награда = 0;
  эп.память = new Map();
  эп.наблюдение = new Map();
  for (const i of эп.наши) {
    эп.память.set(i, { действие: -1, x: eng.m.u16(UNITS + i + U.X) >> 5, y: eng.m.u16(UNITS + i + U.Y) >> 5 });
    эп.наблюдение.set(i, пустое());
  }
  эп.было = замер(eng, эп);
  эп.нашиHP0 = эп.было.hp || 1;
  эп.нашиHPмакс = эп.было.hpмакс || эп.нашиHP0;
  эп.отвлечённостьСумма = 0; эп.отвлечённостьЧисло = 0;
  // Обмен на старте (по всем врагам сцены, не только в окне) — для штрафа за бессмысленную смерть.
  эп.обменСтарт = 0;
  for (const i of эп.наши) { const о = обмен(eng.m, i, враги(eng, i, 64), союзники(eng, i, 64)); эп.обменСтарт = Math.max(эп.обменСтарт, о.общий); }
  эп.врагиHP0 = эп.было.врагиHP || 1;
  эп.шаговЖив = 0;
  эп.история = [эп.было.позиции.slice()];
  эп.последние = new Map();       // юнит → {действие, текст} для показа
  эп.записи = [];                 // пары «наблюдение → действие → награда» для датасета
  эп.наградаУчтена = 0;           // сколько из эп.награда уже разнесено по записям
  эп.записиШага = [];             // записи последнего решения (по одной на живого бойца)
  // Опасность врагов для взвешенного «убито»: здоровье × атака на старте.
  эп.опасность = new Map();
  for (const i of эп.враги) эп.опасность.set(i, eng.m.u8(UNITS + i + U.HPMAX) * Math.max(1, eng.m.u8(UNITS + i + U.ATK)));
  // Скриптовый соперник: врагов ведёт учитель со своим «эпизодом» (роль — уничтожить наших).
  эп.эпВрага = эп.скриптВрага ? {
    роль: 'ATTACK_TO_DEATH', вес: 1, задание: { роль: 'ATTACK_TO_DEATH', вес: 1, точка: null, цель: 0 },
    наши: эп.враги, враги: эп.наши, охраняемый: 0, предметы: [], точка: null, память: new Map(),
  } : null;
  if (эп.эпВрага) for (const i of эп.враги) эп.эпВрага.память.set(i, { действие: -1, x: eng.m.u16(UNITS + i + U.X) >> 5, y: eng.m.u16(UNITS + i + U.Y) >> 5 });
  эп.еда0 = 0;
  for (const i of эп.наши) эп.еда0 += (eng.m.u16(UNITS + i + U.FOOD) << 16) >> 16;
  return эп;
}

/**
 * Один тик. Политика — функция (eng, боец, эп, наблюдение) → номер действия.
 * @param собирать — складывать ли пары «наблюдение → действие» в эп.записи.
 */
export function шаг(eng, эп, политика, собирать = false) {
  const m = eng.m;
  if (эп.тик % ИНТЕРВАЛ === 0) решить(eng, эп, политика, собирать);
  eng.timer = eng.timer + 1;
  eng.tick();
  эп.тик++;
  if (эп.охраняемый && жив(m, эп.охраняемый)) эп.шаговОбъект = эп.тик;
  if (эп.наши.some(i => жив(m, i))) эп.шаговЖив = эп.тик;
  if (эп.тик % ИНТЕРВАЛ === 0) {
    const стало = замер(eng, эп);
    if (стало.враговЖивых) { эп.отвлечённостьСумма += стало.наНас / стало.враговЖивых; эп.отвлечённостьЧисло++; }
    эп.награда += заШаг(eng, эп, эп.было, стало, эп.история);
    эп.история.push(стало.позиции.slice());
    if (эп.история.length > 8) эп.история.shift();
    эп.было = стало;
  }
  return готов(eng, эп);
}

/** Одно решение за всех живых бойцов сцены: наблюдение, действие политики, награда за промежуток. */
function решить(eng, эп, политика, собирать) {
  const m = eng.m;
  // Подсказки, накопленные с прошлого решения, — награда за прошлое решение: КАЖДОМУ бойцу,
  // решавшему в тот шаг (награда командная, цепочка записей у каждого бойца своя).
  if (собирать && эп.записиШага.length) {
    const r = эп.награда - эп.наградаУчтена;
    for (const з of эп.записиШага) з.награда += r;
    эп.наградаУчтена = эп.награда;
  }
  эп.записиШага = [];
  if (эп.эпВрага) {
    // Соперник под учителем: те же действия, тот же приказ через очередь, только владелец другой.
    const э = эп.эпВрага;
    for (const i of э.наши) {
      if (!жив(m, i)) continue;
      const пам = э.память.get(i);
      const д = решение(eng, i, э);
      выполнить(eng, i, д, э.задание);
      пам.действие = д; пам.x = m.u16(UNITS + i + U.X) >> 5; пам.y = m.u16(UNITS + i + U.Y) >> 5;
    }
  }
  for (const i of эп.наши) {
    if (!жив(m, i)) continue;
    const пам = эп.память.get(i);
    const наб = наблюдать(eng, i, эп.задание, пам, эп.наблюдение.get(i));
    const действие = политика(eng, i, эп, наб);
    const текст = выполнить(eng, i, действие, эп.задание);
    // Штраф за отход при явном перевесе (кроме роли отступления и строителя): «отойти» или
    // отскок макро «стрелять», когда врагов в окне мы кладём куда быстрее, чем они нас.
    if ((действие === ОТОЙТИ || (действие === СТРЕЛЯТЬ && текст.startsWith('отскочить'))) && эп.роль !== 'RETREAT' && !строитель(m, i)) {
      const в = враги(eng, i);
      if (в.length && обмен(m, i, в, союзники(eng, i)).общий <= ПЕРЕВЕС) эп.награда += ПОДСКАЗКИ.темп;
    }
    if (собирать) { const з = { окно: наб.окно.slice(), вектор: наб.вектор.slice(), действие, награда: 0, юнит: i, тик: эп.тик, конец: 0 }; эп.записи.push(з); эп.записиШага.push(з); }
    пам.действие = действие;
    пам.x = m.u16(UNITS + i + U.X) >> 5; пам.y = m.u16(UNITS + i + U.Y) >> 5;
    эп.последние.set(i, { действие, текст });
    эп.решений++;
  }
}

/** Условия конца: вышло время, все наши погибли, все враги погибли, объект разрушен. */
export function готов(eng, эп) {
  const m = eng.m;
  if (эп.тик >= эп.шаговВсего) return 'время вышло';
  // С охраняемым объектом смерть бойца эпизод не заканчивает: судьба дома решается дальше без
  // него, и «бить до последнего» получает по заслугам — дом рушится уже после гибели защитника.
  if (!эп.наши.some(i => жив(m, i))) { if (!эп.охраняемый) return 'отряд погиб'; }
  if (эп.охраняемый && !жив(m, эп.охраняемый)) return эп.наши.some(i => жив(m, i)) ? 'объект разрушен' : 'боец погиб, объект разрушен';
  if (эп.роль === 'GATHER' && эп.едыВсего && еда(m, эп) >= эп.едыВсего * 0.8) return 'собрано';   // часть еды уходит на лечение
  // Перебитые враги заканчивают эпизод только там, где они и были задачей: дойти до метки или
  // собрать еду после драки всё ещё надо.
  if (эп.враговВсего && эп.роль !== 'MOVE_TO' && эп.роль !== 'GATHER' && !эп.враги.some(i => жив(m, i))) return 'враги перебиты';
  if (эп.роль === 'MOVE_TO' && эп.точка) {
    for (const i of эп.наши) {
      if (!жив(m, i)) continue;
      if (Math.max(Math.abs((m.u16(UNITS + i + U.X) >> 5) - эп.точка.x),
                   Math.abs((m.u16(UNITS + i + U.Y) >> 5) - эп.точка.y)) <= 1) return 'дошёл';
    }
  }
  return null;
}

/** Досчитать итог: подсказки уже накоплены в эп.награда, здесь добавляется исход. */
export function завершить(eng, эп, причина) {
  эп.причина = причина || 'время вышло';
  эп.исход = итог(eng, эп);
  эп.итого = эп.награда + эп.исход;
  // Критерий владельца (§4л): потери своих, убитые чужие (с учётом опасности), остаток HP у
  // выживших врагов — и его свёртка F. Считается для любого эпизода, чтобы инструменты не лезли в память.
  { const m = eng.m; let опВ = 0, опУ = 0, hp = 0, mx = 0;
    for (const i of эп.враги) { const w = эп.опасность ? (эп.опасность.get(i) || 1) : 1; опВ += w; if (!жив(m, i)) опУ += w; mx += m.u8(UNITS + i + U.HPMAX); if (жив(m, i)) hp += m.u8(UNITS + i + U.HP); }
    эп.критерий = { убито: опВ ? опУ / опВ : 0, потери: эп.наши.length ? эп.наши.filter(i => !жив(m, i)).length / эп.наши.length : 0, hpВрагов: mx ? hp / mx : 0 };
    эп.критерий.F = 0.5 * эп.критерий.убито + 0.3 * (1 - эп.критерий.потери) + 0.2 * (1 - эп.критерий.hpВрагов); }
  // Остаток подсказок — записям последнего решения, исход — последней записи каждого бойца
  // (у погибшего раньше цепочка кончается его последним решением); там же ставится «конец».
  if (эп.записи.length) {
    const r = эп.награда - эп.наградаУчтена;
    for (const з of эп.записиШага) з.награда += r;
    эп.наградаУчтена = эп.награда;
    const были = new Set();
    for (let k = эп.записи.length - 1; k >= 0; k--) {
      const з = эп.записи[k];
      if (были.has(з.юнит)) continue;
      были.add(з.юнит); з.конец = 1; з.награда += эп.исход;
    }
  }
  return эп;
}

/** Прогнать эпизод целиком (headless). */
export function прогнать(eng, эп, политика, собирать = false) {
  начать(eng, эп);
  let причина = null;
  while (!(причина = шаг(eng, эп, политика, собирать))) { /* крутим */ }
  return завершить(eng, эп, причина);
}
