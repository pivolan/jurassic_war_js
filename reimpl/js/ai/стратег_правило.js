// Скриптовый стратег (наше): не сеть, а правила — но правила не «когда набралось семь бойцов»,
// а по укладу игры. Владелец описал его словами, здесь они переведены в состояния.
//
// Состояния и переходы (порядок проверки важен — сверху вниз, первое подошедшее и берём):
//
//   ОБОРОНА   — бьют базу или наших у базы. Идём всей толпой, вычищаем врага в радиусе и
//               возвращаемся. Как только по базе перестали бить и врага рядом нет — сразу назад
//               к зверю, не сторожим пустое место.
//   ВЫРУЧКА   — бьют кого-то из наших в поле. Все, кто рядом, бросаются на обидчика. Это не
//               состояние всей армии, а правило поверх любого другого: помогают только соседи.
//   МЯСО      — «одержимость сбором мяса»: бьём только тех зверей, кого валим быстро и без потерь.
//               Врагов, что проходят мимо, отгоняем, но не гонимся: важнее успеть набить мяса.
//   ПРОКАЧКА  — бьём по одному зверю всем отрядом, начиная со слабых поблизости и поднимаясь к
//               тем, кто покрепче. Цель — не мясо, а опыт в костяк.
//   ВОЛНА     — костяк дорос и мы сильнее видимого врага: идём и ломаем.
//
// Почему «мясо» и «прокачка» — разные состояния, хотя оба про охоту. Цели у них противоположные:
// за мясом выгодно разбегаться и бить слабых по всей округе, а за опытом — держаться кучей и
// валить одного, посильнее. Смешение этих двух и давало то самое «сумбурно бегают туда-сюда».
export const СОСТОЯНИЯ = ['оборона', 'выручка', 'мясо', 'прокачка', 'волна'];

/** Настройки состояний. Всё, что можно покрутить замером, собрано здесь. */
export const НАСТРОЙКИ = {
  голодно: 1500,          // еды меньше — значит пора за мясом, а не за опытом
  сыто: 4000,             // еды больше — можно позволить себе качаться
  радиусОбороны: 18,      // в этом круге вокруг базы врага добиваем
  остыть: 300,            // шагов «держим оборону» после последнего удара по дому
  // Радиус просьбы о помощи — ЭКРАН. Слова владельца: «сколько клеток в экран помещается, такой и
  // радиус». Окно карты в оригинале 512×480 точек при 32 точках на клетку, то есть 16×15 клеток;
  // берём 16. Прежние восемь были вдвое меньше экрана: боец звал на помощь, когда его уже добивали
  // в двух шагах от своих, а те и не знали.
  выручкаРадиус: 16,
  погоня: 90,             // ~5 секунд: не догнали за это время — берём другую цель
  слабыйЗверь: 0.35,      // зверь «слабый», если его сила меньше этой доли силы отряда
  посильнее: 0.8,         // на прокачке берём зверя покрупнее, но не сильнее этой доли
  волнаПеревес: 1.4,      // во сколько раз наш кулак должен быть ценнее видимого врага
  костякТигров: 1,        // каждый в кулаке должен валить столько тигров, чтобы идти в волну
  волнаБойцов: 8,         // без видимого врага в поход идём только таким составом
  // Держаться вместе. Слова владельца: «если кучка менее 5 человек — стараться двигаться вместе,
  // по умолчанию важно быть близко друг к другу, хотя бы до 5 клеток между ближайшими». Поэтому
  // два радиуса: маленькому отряду тесный, большому свободнее — иначе десяток бойцов толкается на
  // пятачке и мешает сам себе.
  вместеРадиус: 12,       // для отряда от пяти бойцов
  вместеМалый: 5,         // для отряда меньше пяти
  малыйОтряд: 5,          // с какого числа отряд считается большим
  мясоПодНогами: 3,       // клеток: мясо ближе этого подбирает любой боец, не только носильщик
  // Решение «кому помогаем» принимается раз в пять секунд и не пересматривается чаще (слова
  // владельца). Пять секунд — это 90 шагов движка. Дольше держать нельзя: цель успевает убежать
  // или умереть, и отряд бьёт воздух; чаще — отряд мечется между жертвами и никого не добивает.
  целиДержим: 90,
};

/**
 * Решить, в каком состоянии играем. Всё берётся из готового среза `осмотр()` — ничего из-под
 * тумана. Возвращает имя состояния и короткое объяснение (оно печатается в стенде сцен).
 *
 * @param в {едаНаша, бьютДом, шагПослеУдара, врагиУБазы, наширядом, ценностьКулака,
 *           ценностьВрага, костякДорос, зверейРядом}
 */
export function состояние(в, н = НАСТРОЙКИ) {
  if (в.бьютДом || в.врагиУБазы > 0) return { имя: 'оборона', почему: в.бьютДом ? 'бьют дом' : 'враг у базы' };
  if (в.шагПослеУдара >= 0 && в.шагПослеУдара < н.остыть) return { имя: 'оборона', почему: 'только что били дом, не расходимся' };
  // Волна. Тут легко ошибиться, и я ошибся: сравнение «мы ценнее врага в полтора раза» при
  // невидимом враге всегда истинно (его ценность ноль), и племя уходило штурмовать пустоту на
  // второй секунде партии. Поэтому два разных условия:
  //   • врага видим — сравниваем ценности честно;
  //   • не видим — идём только когда и костяк дорос, и бойцов набралось не меньше порога.
  if (в.костякДорос && в.ценностьКулака > 0) {
    const сильнее = в.видимВрага ? в.ценностьКулака >= в.ценностьВрага * н.волнаПеревес
                                 : в.бойцов >= н.волнаБойцов && в.знаемБазу;
    if (сильнее) return { имя: 'волна', почему: в.видимВрага ? 'костяк дорос и мы сильнее' : 'костяк дорос, идём искать' };
  }
  if (в.едаНаша < н.голодно) return { имя: 'мясо', почему: 'еды мало' };
  if (в.едаНаша > н.сыто && в.зверейРядом > 0) return { имя: 'прокачка', почему: 'еды хватает, растим костяк' };
  return { имя: 'мясо', почему: 'по умолчанию кормимся' };
}

/**
 * Кого бить из тех, кто бьёт наших. Правило владельца дословно: «бить надо того, у кого меньше
 * всех жизней, чтобы добить его быстрее».
 * @param цели [{id, hp, доля, далеко}]
 */
export function ктоПервый(цели) {
  let лучший = null;
  for (const ц of цели) {
    if (!лучший || ц.hp < лучший.hp || (ц.hp === лучший.hp && ц.далеко < лучший.далеко)) лучший = ц;
  }
  return лучший;
}

/**
 * Пора ли бросить цель. Два случая из описания владельца: погоня не удалась за несколько секунд,
 * или цель и так не опасна — тогда бросаем раньше.
 */
export function броситьЦель({ шаговВПогоне, уронаНанесли, цельОпасна }, н = НАСТРОЙКИ) {
  if (!цельОпасна && шаговВПогоне > н.погоня / 3) return true;
  return шаговВПогоне > н.погоня && !уронаНанесли;
}
