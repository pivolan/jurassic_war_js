// Партия целиком в грубой модели (наше): две стороны, пятисекундные отрезки, тот же интерфейс
// решений, что у комдива (js/ai/комдив.js).
//
// Зачем именно «тот же интерфейс». Учиться в модели имеет смысл только если найденные веса можно
// без переделок поставить в настоящую игру и там проверить. Поэтому здесь:
//   • признаки — те же 48 чисел и в том же порядке, что даёт Комдив.наблюдать по настоящей памяти
//     (первые 32 — сводка штаба, дальше по четыре на каждую из четырёх групп);
//   • решение — тот же Комдив.решение: задача каждой группе плюс стройка и производство.
// Значит чемпион модели — это готовый файл весов для `задать(…, { комдив })`.
//
// ЧЕГО В МОДЕЛИ НЕТ. Поиска пути, тумана, микроконтроля, цветов, вещей на земле, разной живности,
// рельефа. Расстояния — три числа (до пастбища, до врага, до дома), бой — усреднённый размен по
// формуле движка. Поэтому модель годится, чтобы за секунды отсеять безнадёжное и нащупать общий
// уклад игры, и НЕ годится, чтобы объявить победителя. Победителя объявляет движок.
import * as Комдив from './комдив.js';
import { отряд, бой, подрасти, урон, темп, ШАГ_С } from './модель.js';

/** Коэффициенты, подобранные по настоящим партиям (tools/ai_модель.mjs --подбор). */
export const КОЭФ = { мясо: 2.5, носка: 1, запас: 900, скорость: 1.6 };

/** Цены, как в игре: простолюдин 500, боец 800, дом примерно 2000-3500 (через строителя). */
export const ЦЕНЫ = { рабочий: 500, боец: 800, дом: 2500, железо: 350 };

/** Одна сторона в модельной партии. */
export function сторона(сид = 1) {
  return {
    еда: 2000, рабочие: 2, мясоНаЗемле: 0, принесено: 0,
    // Четыре группы, как у комдива. Вначале все бойцы в первой — дальше их растаскивают задачи.
    группы: [отряд(4, 30, 10, 60, 32), отряд(0), отряд(0), отряд(0)],
    // Где группа: 0 — дома, 1 — на пастбище, 2 — у врага, дробное между ними значит «в пути».
    где: [0, 0, 0, 0],
    дома: { святилище: 1, склад: 1, казарма: 0, оружейная: 0, военный: 0 },
    строится: 0, жив: true, сид,
  };
}

/** Мир вокруг: стадо и расстояния. Одинаков для обеих сторон — карта-то одна. */
export function мир() {
  return { стадо: { n: 10, атк: 40, деф: 8, hp: 90, спд: 24, мясо: 400 * КОЭФ.мясо }, доПастбища: 12, междуБазами: 60 };
}

const сумма = (гр) => гр.reduce((s, г) => s + г.n, 0);
const силаСтороны = (с) => с.группы.reduce((s, г) => s + г.n * (г.атк + г.деф + г.hp), 0);
const зажать = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

/**
 * Признаки для сети — та же раскладка, что у Комдив.наблюдать. Точных значений тут быть не может
 * (в модели нет ни карты, ни тумана), но смысл каждого числа тот же: сеть учится на тех же осях,
 * по которым потом будет играть в настоящей игре.
 */
export function признаки(с, враг, м, вых = new Float32Array(Комдив.ВХОД)) {
  вых.fill(0);
  // 0..31 — сводка: экономика, войско, враг, время. Заполняем то, что в модели есть.
  вых[0] = зажать(с.еда / 20000);
  вых[1] = 0.5;                                          // прирост за такт — в модели он ровный
  вых[2] = зажать(с.рабочие / 8);
  вых[3] = зажать(сумма(с.группы) / 20);
  вых[4] = зажать(силаСтороны(с) / 8000);
  вых[5] = зажать((с.дома.казарма + с.дома.оружейная + с.дома.военный) / 4);
  вых[6] = зажать(с.мясоНаЗемле / 5000);
  вых[7] = зажать(м.стадо.n / 20);
  вых[8] = зажать(сумма(враг.группы) / 20);
  вых[9] = зажать(силаСтороны(враг) / 8000);
  вых[10] = зажать(силаСтороны(с) / Math.max(1, силаСтороны(с) + силаСтороны(враг)));
  вых[11] = зажать(с.дома.святилище);
  вых[12] = зажать(с.строится);
  // 32.. — по четыре числа на группу: сколько в ней, какова сила, целость, как далеко от дома.
  for (let g = 0; g < Комдив.ГРУПП; g++) {
    const гр = с.группы[g], п = 32 + g * Комдив.НА_ГРУППУ;
    вых[п] = зажать(гр.n / 20);
    вых[п + 1] = зажать(гр.n * (гр.атк + гр.деф + гр.hp) / 4000);
    вых[п + 2] = гр.n ? 1 : 0;                           // раненых модель не различает
    вых[п + 3] = зажать(с.где[g] === 2 ? 1 : с.где[g] === 1 ? 0.3 : 0);
  }
  return вых;
}

/** Перекинуть бойцов между группами так, чтобы каждая непустая задача имела состав. */
function разложить(с, задачи) {
  const всего = сумма(с.группы);
  if (!всего) return;
  // Сливаем всё в первую и раздаём поровну тем группам, которым дана «активная» задача.
  const главная = с.группы[0];
  for (let g = 1; g < с.группы.length; g++) {
    const гр = с.группы[g];
    if (!гр.n) continue;
    // Средние статы сливаем по числу бойцов — грубо, но честно по силе.
    const N = главная.n + гр.n;
    главная.атк = (главная.атк * главная.n + гр.атк * гр.n) / N;
    главная.деф = (главная.деф * главная.n + гр.деф * гр.n) / N;
    главная.hp = (главная.hp * главная.n + гр.hp * гр.n) / N;
    главная.опыт += гр.опыт; главная.n = N; гр.n = 0; гр.опыт = 0;
  }
  const активные = задачи.map((з, g) => ({ з, g })).filter(({ з }) => з !== 'стоять');
  if (!активные.length) return;
  const доля = главная.n / активные.length;
  const шаблон = { атк: главная.атк, деф: главная.деф, hp: главная.hp, спд: главная.спд };
  const опыт = главная.опыт;
  главная.n = 0; главная.опыт = 0;
  активные.forEach(({ g }, k) => {
    const гр = с.группы[g];
    гр.n = доля; гр.атк = шаблон.атк; гр.деф = шаблон.деф; гр.hp = шаблон.hp; гр.спд = шаблон.спд;
    гр.опыт = k === 0 ? опыт : 0;
  });
}

/** Один отрезок партии для одной стороны: задачи групп уже назначены. */
function отрезок(с, враг, м, задачи, реш) {
  разложить(с, задачи);
  // 1. Перемещение: «дома» ↔ «пастбище» ↔ «враг». Скорость в долях пути за отрезок.
  const цельГде = (з) => (з === 'охота' || з === 'мясо' ? 1 : з === 'штурм' || з === 'враг' ? 2 : 0);
  for (let g = 0; g < с.группы.length; g++) {
    const цель = цельГде(задачи[g]);
    const путь = цель === 2 ? м.междуБазами : м.доПастбища;
    const шагДоли = (КОЭФ.скорость * ШАГ_С) / Math.max(1, путь);
    if (с.где[g] < цель) с.где[g] = Math.min(цель, с.где[g] + шагДоли);
    else if (с.где[g] > цель) с.где[g] = Math.max(цель, с.где[g] - шагДоли);
  }
  // 2. Охота: группы, которые дошли до пастбища.
  for (let g = 0; g < с.группы.length; g++) {
    if (задачи[g] !== 'охота' || с.где[g] < 1) continue;
    const гр = с.группы[g];
    if (!гр.n || !м.стадо.n) continue;
    const зверь = отряд(м.стадо.n, м.стадо.атк, м.стадо.деф, м.стадо.hp, м.стадо.спд);
    const было = зверь.n;
    бой(гр, зверь, ШАГ_С);
    м.стадо.n = зверь.n;
    с.мясоНаЗемле += (было - зверь.n) * м.стадо.мясо;
    подрасти(гр);
  }
  // 3. Сбор мяса: рабочие плюс группы с задачей «мясо».
  const носильщиков = с.рабочие + с.группы.reduce((s, г, g) => s + (задачи[g] === 'мясо' && с.где[g] >= 1 ? г.n : 0), 0);
  if (носильщиков && с.мясоНаЗемле) {
    const ходка = (2 * м.доПастбища) / КОЭФ.скорость;
    const донесли = Math.min(с.мясоНаЗемле, носильщиков * 1000 * КОЭФ.носка * (ШАГ_С / Math.max(1, ходка)));
    с.мясоНаЗемле -= донесли; с.еда += донесли; с.принесено += донесли;
  }
  // 4. Стройка и покупки — ровно те, что назвала сеть.
  if (реш.стройка !== 'ничего' && с.еда >= ЦЕНЫ.дом) {
    с.еда -= ЦЕНЫ.дом;
    const к = реш.стройка === 'склад' ? 'склад' : реш.стройка === 'казарма' ? 'казарма'
            : реш.стройка === 'оружейная' ? 'оружейная' : 'военный';
    с.дома[к] = (с.дома[к] || 0) + 1; с.построено = (с.построено || 0) + 1;
  }
  if (реш.производство === 'рабочий' && с.еда >= ЦЕНЫ.рабочий + КОЭФ.запас) { с.еда -= ЦЕНЫ.рабочий; с.рабочие++; }
  if (реш.производство === 'боец' && с.еда >= ЦЕНЫ.боец + КОЭФ.запас) {
    с.еда -= ЦЕНЫ.боец;
    const куда = с.группы.find(г => г.n > 0) || с.группы[0];
    // Новичок разбавляет средние статы группы — иначе покупка «усиливала» бы ветеранов.
    const N = куда.n + 1;
    куда.атк = (куда.атк * куда.n + 30) / N; куда.деф = (куда.деф * куда.n + 10) / N; куда.hp = (куда.hp * куда.n + 60) / N;
    куда.n = N;
  }
}

/** Бой между сторонами: дерутся те группы, которые дошли до чужой базы. */
function стычка(a, b, задачиA, задачиB) {
  const наступA = a.группы.filter((г, g) => г.n && a.где[g] >= 2);
  const наступB = b.группы.filter((г, g) => г.n && b.где[g] >= 2);
  // Защитники — только те, кто ДОМА. Раньше сюда попадали и охотники на пастбище, и получалось,
  // что базу всегда обороняет всё войско разом: ни одна партия не кончалась, все ничьи.
  const домаA = a.группы.filter((г, g) => г.n && a.где[g] < 0.5);
  const домаB = b.группы.filter((г, g) => г.n && b.где[g] < 0.5);
  const сложить = (сп) => { const n = сп.reduce((s, г) => s + г.n, 0); if (!n) return null;
    return { сп, о: отряд(n, сп.reduce((s, г) => s + г.атк * г.n, 0) / n, сп.reduce((s, г) => s + г.деф * г.n, 0) / n,
                          сп.reduce((s, г) => s + г.hp * г.n, 0) / n, 32) }; };
  const пары = [[сложить(наступA), сложить(домаB), b], [сложить(наступB), сложить(домаA), a]];
  for (const [ат, об, чей] of пары) {
    if (!ат) continue;
    if (об) {
      const былоА = ат.о.n, былоО = об.о.n;
      бой(ат.о, об.о, ШАГ_С);
      const долА = ат.о.n / Math.max(0.0001, былоА), долО = об.о.n / Math.max(0.0001, былоО);
      // Обрезаем хвосты: без этого от отряда остаётся «одна стотысячная бойца», которая живёт
      // вечно и не даёт партии кончиться.
      for (const г of ат.сп) { г.n *= долА; if (г.n < 0.05) г.n = 0; }
      for (const г of об.сп) { г.n *= долО; if (г.n < 0.05) г.n = 0; }
    } else {
      // Защитников нет — ломаем дома. Не по штуке за отрезок: дом в игре держится долго, и
      // мгновенный снос делал модель детским садом — случайная сеть выигрывала все партии
      // подряд, просто добежав до чужой базы. Копим урон: полный отряд сносит дом примерно за
      // полминуты.
      const всего = Object.values(чей.дома).reduce((s, v) => s + v, 0);
      if (всего > 0 && ат.о.n >= 1) {
        чей.уронПоДомам = (чей.уронПоДомам || 0) + ат.о.n * ат.о.атк * ШАГ_С;
        const ПОРОГ = 6000;                                // примерно полминуты работы шести бойцов
        while (чей.уронПоДомам >= ПОРОГ) {
          чей.уронПоДомам -= ПОРОГ;
          let снесли = false;
          for (const к of ['военный', 'оружейная', 'казарма', 'склад', 'святилище'])
            if (чей.дома[к] > 0) { чей.дома[к]--; снесли = true; break; }
          if (!снесли) break;
        }
      }
      if (Object.values(чей.дома).reduce((s, v) => s + v, 0) === 0 && чей.группы.every(г => г.n < 0.5)) чей.жив = false;
    }
    // Сторона без домов и без бойцов считается выбитой — партия кончилась.
    for (const с of [a, b]) {
      if (Object.values(с.дома).reduce((s, v) => s + v, 0) === 0 && с.группы.every(г => г.n < 0.5)) с.жив = false;
    }
  }
}

/**
 * Прогнать модельную партию: сеть против скриптового уклада (простое правило — охотиться, пока
 * мало сил, потом идти на врага). Возвращает исход и остатки.
 * @param сеть веса комдива (js/ai/комдив.js)
 */
export function партия(сеть, { минут = 15, сид = 1, соперник = null } = {}) {
  const A = сторона(сид), B = сторона(сид + 1), м = мир();
  const вх = new Float32Array(Комдив.ВХОД), вх2 = new Float32Array(Комдив.ВХОД);
  const отрезков = Math.round(минут * 60 / ШАГ_С);
  for (let k = 0; k < отрезков; k++) {
    if (!A.жив || !B.жив) break;
    // Наша сторона — сеть.
    признаки(A, B, м, вх);
    const решA = Комдив.решение(сеть, вх);
    // Соперник: либо такая же сеть (игра сама с собой — так сито не выродится в «обгони
    // рукописное правило»), либо, если её не дали, простое правило.
    let решB;
    if (соперник) { признаки(B, A, м, вх2); решB = Комдив.решение(соперник, вх2); }
    else {
      const силаA = силаСтороны(A), силаB = силаСтороны(B);
      const идём = силаB > силаA * 0.9 && сумма(B.группы) >= 8;
      решB = { задачи: идём ? ['штурм', 'штурм', 'охота', 'мясо'] : ['охота', 'охота', 'мясо', 'стоять'],
               стройка: B.дома.казарма ? 'ничего' : 'казарма',
               производство: B.рабочие < 4 ? 'рабочий' : 'боец' };
    }
    отрезок(A, B, м, решA.задачи, решA);
    отрезок(B, A, м, решB.задачи, решB);
    стычка(A, B, решA.задачи, решB.задачи);
    if (k % 6 === 0) м.стадо.n += 1;                     // зверьё возрождается
  }
  const итог = { победа: B.жив ? (A.жив ? null : 'B') : 'A',
                 силаA: силаСтороны(A), силаB: силаСтороны(B),
                 бойцовA: сумма(A.группы), бойцовB: сумма(B.группы),
                 принесеноA: A.принесено, домовA: Object.values(A.дома).reduce((s, v) => s + v, 0) };
  return итог;
}
