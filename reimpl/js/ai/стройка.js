// Клетка свободна под дом и для обхода: и рельеф проходим, и никакой дом её не занял (движок
// штампует владельца дома в сетку BI, 0x1dac2). Раньше смотрели только рельеф, и площадкой номер
// один оставалось место, где уже стоит наш загон: строитель шёл туда, не мог встать и по кругу
// бегал к запасным площадкам через выпас мамонтов (Тирано/2, зерно 5).
// Сетка BI помечает и юнитов тем же способом, что и дома, поэтому дома считаем сами — по списку
// юнитов-домов и их отпечаткам (раз за шаг движка): стоящий рядом боец площадку не портит.
let клеткиДомов = null, клеткиШаг = -1;
function домаНаКлетках(m) {
  const шаг = m.u32(G.step);
  if (клеткиДомов && клеткиШаг === шаг) return клеткиДомов;
  клеткиДомов = new Set(); клеткиШаг = шаг;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (т < 0x1a) continue;
    const bx = m.u16(UNITS + i + U.X), by = m.u16(UNITS + i + U.Y);
    const n = m.u32(0x3176c + (т - 0x1a) * 8); let p = m.u32(0x31770 + (т - 0x1a) * 8);
    for (let k = 0; k < Math.min(n, 64); k++, p += 8)
      клеткиДомов.add((((bx + m.u32(p)) & 0xffff) >> 5) + (((by + m.u32(p + 4)) & 0xffff) >> 5) * 256);
  }
  return клеткиДомов;
}
