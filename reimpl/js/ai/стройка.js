/** Точки рождения зверья и их прямоугольники выпаса — сюда дома не ставим. */
function логова(m) {
  const т = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!ЗВЕРЬ(m.u8(UNITS + i + U.TYPE))) continue;
    т.push({ x: m.u8(UNITS + i + 0x59), y: m.u8(UNITS + i + 0x5a),
             x0: m.u8(UNITS + i + 0x55), y0: m.u8(UNITS + i + 0x56),
             x1: m.u8(UNITS + i + 0x57), y1: m.u8(UNITS + i + 0x58) });
  }
  return т;
}

/** Наши дома по видам: сколько уже стоит (и сколько строится). */
function домаПоВидам(m, мой) {
  const есть = new Map(), строятся = new Map();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (!ДОМ_ЛИ(т) || m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const карта = (m.u8(UNITS + i + U.FLAGS50) & 2) ? строятся : есть;   // бит 2 — «ещё строится»
    const в = ВИД(т); карта.set(в, (карта.get(в) || 0) + 1);
  }
  return { есть, строятся };
}

/**
 * Что строить дальше: список видов по порядку.
 *   1. Святилище, если его нет (без него ничего не закажешь);
 *   2. мясное хранилище — владелец: «в главной стройке сразу же обязательно заказываем»;
 *   3. то, что требует задание миссии.
 * Возвращает первый вид, которого не хватает, с учётом уже строящихся и уже посланных конструкторов.
 */
function чегоНеХватает(m, с, мой) {
  const { есть, строятся } = домаПоВидам(m, мой);
  const идут = new Map();                                     // конструкторы в пути — тоже считаются
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.TYPE) !== КОНСТРУКТОР || m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const в = m.u8(UNITS + i + 0x59); идут.set(в, (идут.get(в) || 0) + 1);
  }
  const счёт = (в) => (есть.get(в) || 0) + (строятся.get(в) || 0) + (идут.get(в) || 0);
  const надо = [];
  if (счёт(0) < 1) надо.push(0);                              // Святилище
  if (счёт(4) < 1) надо.push(4);                              // мясное хранилище
  // План Тирано/2: второй склад за горлом — чтобы не носить мясо мимо мамонта обратно в карман.
  else if (ПЛАН_Т2 && Т2.этаКарта(m) && счёт(4) < 2) надо.push(4);
  const з = с.задание;
  if (з?.вид === 'дома') for (const п of з.надо) {
    let n = 0; for (const в of п.виды) n += счёт(в);
    for (let k = n; k < п.n; k++) надо.push(п.виды[0]);
  }
  return { надо, счёт };
}

/** Годится ли клетка под дом. `строгость`: 2 — и логова, и пастбища; 1 — только логова; 0 — лишь бы пройти. */
function местоГодно(m, x, y, лог, W, H, строгость) {
  if (x < 2 || y < 2 || x > W - 4 || y > H - 4) return false;
  for (let dy = 0; dy < 3; dy++) for (let dx = 0; dx < 3; dx++) if (!проходима(m, x + dx, y + dy)) return false;
  if (строгость === 0) return true;
  for (const л of лог) {
    if (Math.max(Math.abs(л.x - x), Math.abs(л.y - y)) < ОТ_ЛОГОВА) return false;
    if (строгость >= 2 && x >= л.x0 - 1 && x <= л.x1 + 1 && y >= л.y0 - 1 && y <= л.y1 + 1) return false;
  }
  return true;
}

/**
 * Выбрать место под дом: кольцами от якоря.
 *
 * Требования владельца: «место нужно выбирать там, где желательно не появляются звери — дело не в
 * том, что их там нет прямо сейчас, а лучше бы они там вообще не спавнились». Поэтому сперва ищем
 * место вне пастбищ и не ближе ОТ_ЛОГОВА к точкам рождения; если такого рядом нет — послабляем
 * требования по очереди, иначе конструктор просто не построит ничего (на карте второй миссии
 * Тирано двадцать три зверя, и их пастбища закрывают почти всё).
 *
 * `близко` — Святилище ставим у самого старта: гонять единственного конструктора через полкарты
 * мимо логов значит потерять его и миссию вместе с ним.
 */
/**
 * ПЛОЩАДКИ ПОД ДОМ С ЦИФРАМИ ОПАСНОСТИ. Место выбирает СКРИПТ — «это алгоритмически стабильное
 * решение», одни и те же цифры дают одно и то же место, и строитель не ходит кругами. Считаем
 * несколько разнесённых площадок и к каждой прикладываем то, чем место опасно: сколько логов
 * рядом, сколько зверья пасётся вокруг и кто там самый злой; берём лучшую, остальные показываем
 * в строке состояния — по ним видно, из чего выбирали.
 * Владелец о нынешней базе: «построена рядом, и там постоянно кто-то появляется из зверей; с
 * другой стороны, остальные места ещё опаснее — там вообще мамонты гуляют». Вот это и надо
 * показать числами, чтобы выбор был осознанным.
 */
export function отпечаток(m, вид) {
  // Клетки, которые займёт дом: таблица движка 0x3176c (сколько) и 0x31770 (список смещений в
  // пикселях) по виду дома — та же, которой он штампует владельца в сетку (combat.js, 0x1dac2).
  const n = m.u32(0x3176c + вид * 8);
  let p = m.u32(0x31770 + вид * 8);
  const клетки = [];
  for (let k = 0; k < Math.min(n, 64); k++, p += 8)
    клетки.push({ dx: m.u32(p) >> 5, dy: m.u32(p + 4) >> 5 });
  return клетки.length ? клетки : [{ dx: 0, dy: 0 }, { dx: 1, dy: 0 }, { dx: 0, dy: 1 }, { dx: 1, dy: 1 }];
}

/**
 * РАЗБОР ОДНОЙ ПЛОЩАДКИ. Возвращает всё, из чего потом складывается оценка, — и причины отказа,
 * чтобы в строке состояния было видно, почему место не подошло.
 *
 * Что считаем:
 *   • пятно — все клетки отпечатка должны быть проходимы;
 *   • кольцо — свободные клетки вокруг пятна: по ним дом обходят. Доля свободных = «обход»;
 *   • пробка — на сколько НЕСВЯЗНЫХ кусков распадается это кольцо. Один кусок значит, что дом
 *     стоит у края поляны и его можно обойти; два и больше — что он затыкает проход между ними,
 *     и после стройки обойти его будет негде. Владелец: «здание не должно загораживать выходы,
 *     должны быть свободные слоты, чтобы его можно было обойти спокойно»;
 *   • логова — расстояние до ближайшей точки рождения зверья и сколько их в круге;
 *   • зверьё — сколько живого рядом прямо сейчас и кто самый злой.
 */
export function разборМеста(m, x, y, лог, звери, отпеч, W, H) {
  const ст = статикаМеста(m, x, y, лог, отпеч, W, H);
  return ст.годно ? зверьёМеста(m, ст, x, y, звери) : ст;
}
// Статика площадки — рельеф, дома, кольцо, пробки, логова: меняется только со сменой домов, логов
// или рельефа. Живая часть — зверьё рядом — считается заново на каждый разбор.
function статикаМеста(m, x, y, лог, отпеч, W, H) {
  const занято = new Set();
  let пятноГодно = true;
  let x0 = 99, y0 = 99, x1 = -99, y1 = -99;
  for (const к of отпеч) {
    const cx = x + к.dx, cy = y + к.dy;
    занято.add(cx + cy * 256);
    x0 = Math.min(x0, cx); y0 = Math.min(y0, cy); x1 = Math.max(x1, cx); y1 = Math.max(y1, cy);
    if (cx < 2 || cy < 2 || cx > W - 3 || cy > H - 3 || !проходима(m, cx, cy)) пятноГодно = false;
  }
  if (!пятноГодно) return { годно: false, причина: 'пятно занято или у края' };

  // Кольцо вокруг пятна: обходим прямоугольник на клетку шире с каждой стороны.
  const кольцо = [];
  for (let cy = y0 - 1; cy <= y1 + 1; cy++) for (let cx = x0 - 1; cx <= x1 + 1; cx++) {
    if (занято.has(cx + cy * 256)) continue;
    if (cx > x0 - 1 && cx < x1 + 1 && cy > y0 - 1 && cy < y1 + 1) continue;    // внутренние — не кольцо
    кольцо.push({ x: cx, y: cy, свободна: cx >= 0 && cy >= 0 && cx < W && cy < H && проходима(m, cx, cy) });
  }
  const свободных = кольцо.filter(к => к.свободна);
  const свободна = (x2, y2) => !занято.has(x2 + y2 * 256) && x2 >= 0 && y2 >= 0 && x2 < W && y2 < H && проходима(m, x2, y2);
  const обход = кольцо.length ? свободных.length / кольцо.length : 0;

  // Сколько несвязных кусков образуют свободные клетки кольца (соседство по восьми направлениям).
  const ключ = (к) => к.x + к.y * 256;
  const остались = new Map(свободных.map(к => [ключ(к), к]));
  let кусков = 0;
  while (остались.size) {
    кусков++;
    const [, старт] = остались.entries().next().value;
    const очередь = [старт]; остались.delete(ключ(старт));
    while (очередь.length) {
      const т = очередь.pop();
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        if (!dx && !dy) continue;
        // По диагонали кусок кольца связан, только если движок пропустит по ней: угол между двумя
        // занятыми клетками юнит не срезает. Иначе загон в горле прохода (Тирано/2, 34,32)
        // считался «одним куском» через диагональ у стены, и проход запирался.
        if (dx && dy && !(свободна(т.x + dx, т.y) || свободна(т.x, т.y + dy))) continue;
        const k2 = (т.x + dx) + (т.y + dy) * 256;
        const с2 = остались.get(k2);
        if (с2) { остались.delete(k2); очередь.push(с2); }
      }
    }
  }

  let доЛогова = 99, логовРядом = 0, вПастбище = false;
  for (const л of лог) {
    const д = Math.max(Math.abs(л.x - x), Math.abs(л.y - y));
    доЛогова = Math.min(доЛогова, д);
    if (д <= КРУГ_ОПАСНОСТИ) логовРядом++;
    if (x >= л.x0 - 1 && x <= л.x1 + 1 && y >= л.y0 - 1 && y <= л.y1 + 1) вПастбище = true;
  }
  return { годно: true, x, y, обход: +обход.toFixed(2), свободных: свободных.length, кусков,
           доЛогова, логовРядом, вПастбище };
}
function зверьёМеста(m, ст, x, y, звери) {
  let зверейРядом = 0, самый = null;
  for (const з of звери) {
    const к = { x: m.u16(UNITS + з + U.X) >> 5, y: m.u16(UNITS + з + U.Y) >> 5 };
    if (далеко(к, { x, y }) > КРУГ_ОПАСНОСТИ) continue;
    зверейРядом++;
    const а = m.u8(UNITS + з + U.ATK);
    if (!самый || а > самый.атака) самый = { кто: ИМЯ_ЗВЕРЯ_[m.u8(UNITS + з + U.TYPE)] || '?', атака: а };
  }
  return { ...ст, зверейРядом, самый };
}
/** Подпись всего, от чего зависит статика площадок: дома, логова, рельеф. */
function подписьСтатики(m, лог, W, H) {
  let h = 0;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) h = (Math.imul(h, 31) + m.u16(BG + (y << 9) + x * 2)) | 0;
  let л = '';
  for (const о of лог) л += о.x + ',' + о.y + ',' + о.x0 + ',' + о.y0 + ',' + о.x1 + ',' + о.y1 + ';';
  return h + '|' + [...домаНаКлетках(m)].join(',') + '|' + л;
}
const кэшСтатики = new WeakMap();

/**
 * ВЫБОР МЕСТА ПОД ДОМ: набираем площадки кольцами от якоря, каждую разбираем и оцениваем, берём
 * лучшие. Правила владельца, переведённые в коэффициенты:
 *
 *   «здание не должно загораживать выходы куда-либо»          → штраф за каждый лишний кусок кольца
 *   «должны быть свободные слоты, чтобы его обойти спокойно»  → награда за долю свободного кольца,
 *                                                               и отказ, если свободного меньше трети
 *   «не строить рядом с местами, где появляются звери»        → награда за расстояние до логова,
 *                                                               штраф за каждое логово в круге и за
 *                                                               само пастбище
 *   «если только нет других мест»                             → три ступени строгости: сперва всё
 *                                                               сразу, потом послабления, и лишь в
 *                                                               конце «лишь бы пройти»
 *   «несколько мест, приоритеты по коэф, выбираем наилучший»  → возвращаем СПИСОК, отсортированный
 *                                                               по оценке, а не первое попавшееся
 */
// КЭШ ПЛОЩАДОК. Перебор площадок — 83% времени всей партии (профиль Тирано/2: ПРОРАБ звал его
// каждый тик для каждого строителя). Ответ держим КЭШ_МЕСТ тиков: карта за это время не меняется,
// а зверьё сдвигается меньше клетки. JW_СТР_КЭШ_МЕСТ=-1 — считать каждый тик, как раньше.
const КЭШ_МЕСТ = +(срд.JW_СТР_КЭШ_МЕСТ || 16);
const кэшМест = new WeakMap();
export function кандидаты(m, якорь, лог, близко = false, сколько = 4, вид = 1, безПробок = false) {
  if (КЭШ_МЕСТ <= 0) return кандидатыСчёт(m, якорь, лог, близко, сколько, вид, безПробок);
  let к = кэшМест.get(m); if (!к) кэшМест.set(m, к = new Map());
  const ключ = `${якорь.x},${якорь.y},${близко},${сколько},${вид},${безПробок}`, шаг = m.u32(G.step);
  const было = к.get(ключ);
  if (было && шаг >= было.шаг && шаг - было.шаг < КЭШ_МЕСТ) return было.ответ.slice();
  const ответ = кандидатыСчёт(m, якорь, лог, близко, сколько, вид, безПробок);
  if (к.size > 64) к.clear();
  к.set(ключ, { шаг, ответ });
  return ответ.slice();
}
function кандидатыСчёт(m, якорь, лог, близко, сколько, вид, безПробок) {
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const предел = близко ? БЛИЖНИЙ_КРУГ : ДАЛЬШЕ_БАЗЫ;
  const хочу = близко ? 2 : У_БАЗЫ;
  const отпеч = отпечаток(m, вид);
  const звери = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (ЗВЕРЬ(m.u8(UNITS + i + U.TYPE)) && жив(m, i)) звери.push(i);
  }
  // Три ступени: строго → терпимо → лишь бы построить. Владелец: «если только нет других мест».
  const СТУПЕНИ = [
    { обход: ОБХОД_НАДО, кусков: 1, доЛогова: ОТ_ЛОГОВА, пастбище: false },
    { обход: ОБХОД_НАДО / 2, кусков: 2, доЛогова: Math.round(ОТ_ЛОГОВА / 2), пастбище: true },
    // Проход не затыкаем до последнего: Тирано/2, зерно 3 — загон встал в горле единственного
    // прохода из кармана базы (34,33), и четверо строителей с отрядом так и остались запертыми.
    { обход: 0, кусков: 1, доЛогова: 0, пастбище: true },
    { обход: 0, кусков: 99, доЛогова: 0, пастбище: true },
  ];
  const разобрано = new Map();
  let кс = кэшСтатики.get(m); if (!кс) кэшСтатики.set(m, кс = new Map());
  const подпись = подписьСтатики(m, лог, W, H);
  let статика = кс.get(вид);
  if (!статика || статика.подпись !== подпись) { кс.set(вид, статика = new Map()); статика.подпись = подпись; }
  for (const треб of СТУПЕНИ) {
    const найдено = [];
    for (let r = 1; r <= предел; r++) {
      // Только клетки кольца радиуса r, в том же порядке, что и перебор всего квадрата.
      for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx += (dy === -r || dy === r) ? 1 : 2 * r) {
        const x = якорь.x + dx, y = якорь.y + dy;
        if (найдено.some(т => далеко(т, { x, y }) < РАЗНОС)) continue;     // площадки разносим
        let р = разобрано.get(x + y * 256);
        if (!р) {                                                              // от ступени не зависит
          let ст = статика.get(x + y * 256);
          if (!ст) статика.set(x + y * 256, ст = статикаМеста(m, x, y, лог, отпеч, W, H));
          разобрано.set(x + y * 256, р = ст.годно ? зверьёМеста(m, ст, x, y, звери) : ст);
        }
        if (!р.годно) continue;
        if (р.обход < треб.обход || р.кусков > треб.кусков) continue;
        if (безПробок && р.кусков > 1) continue;
        if (р.доЛогова < треб.доЛогова) continue;
        if (!треб.пастбище && р.вПастбище) continue;
        // Оценка: обход и удалённость от логов — в плюс, пробка, логова, зверьё и крюк — в минус.
        const оценка = р.обход * К_ОБХОД
                     - (р.кусков - 1) * К_ПРОБКА
                     + Math.min(р.доЛогова, 20) * К_ЛОГОВО
                     - р.логовРядом * К_ЛОГОВ_РЯДОМ
                     - (р.вПастбище ? К_ПАСТБИЩЕ : 0)
                     - р.зверейРядом * К_ЗВЕРЬ
                     - Math.abs(r - хочу) * К_КРЮК;
        найдено.push({ ...р, отЯкоря: r, оценка: Math.round(оценка) });
      }
    }
    if (найдено.length) return найдено.sort((a, b) => b.оценка - a.оценка).slice(0, сколько);
  }
  return [];
}

function выбратьМесто(m, якорь, лог, близко = false) {
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const предел = близко ? БЛИЖНИЙ_КРУГ : ДАЛЬШЕ_БАЗЫ;
  const хочу = близко ? 2 : У_БАЗЫ;
  for (const строгость of [2, 1, 0]) {
    let лучшее = null, лучшаяОценка = -1e9;
    for (let r = 1; r <= предел; r++) {
      for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue;
        const x = якорь.x + dx, y = якорь.y + dy;
        if (!местоГодно(m, x, y, лог, W, H, строгость)) continue;
        let доЛогова = 1e9;
        for (const л of лог) доЛогова = Math.min(доЛогова, Math.max(Math.abs(л.x - x), Math.abs(л.y - y)));
        // Чем дальше от точек рождения и чем ближе к желаемому кругу — тем лучше.
        const оценка = Math.min(доЛогова, 20) * 2 - Math.abs(r - хочу) * 3;
        if (оценка > лучшаяОценка) { лучшаяОценка = оценка; лучшее = { x, y }; }
      }
    }
    if (лучшее) return лучшее;
  }
  return null;
}

/**
 * Шаг слоя стройки.
 * @returns разбор для строки состояния: что заказано, куда послан конструктор, есть ли тревога.
 */
export function шаг(eng, с) {
  const m = eng.m;
  const мой = m.u8(G.humanOwner);
  const миссия = m.u8(G.mission);
  if (с.заданиеДля !== миссия) { с.заданиеДля = миссия; try { с.задание = Кампания.задание(m); } catch { с.задание = null; } }

  const дома = [], конструкторы = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (ДОМ_ЛИ(т)) дома.push({ н: i, т, стро: !!(m.u8(UNITS + i + U.FLAGS50) & 2),
                               занят: !!(m.u8(UNITS + i + U.FLAGS50) & 1) });
    else if (т === КОНСТРУКТОР && жив(m, i)) конструкторы.push(i);
  }

  // Эталонный зверь карты — самый частый: против него и меряем, чего стоит боец. Считаем один раз.
  if (с.эталонДля !== миссия) {
    с.эталонДля = миссия;
    const счётЗверей = new Map();
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
      const т = m.u8(UNITS + i + U.TYPE);
      if (ЗВЕРЬ(т)) счётЗверей.set(т, (счётЗверей.get(т) || 0) + 1);
    }
    const [т] = [...счётЗверей.entries()].sort((a, b) => b[1] - a[1])[0] || [];
    // Цифры берём у ЖИВОГО зверя, а не из таблицы типов: сложность миссии их поднимает (леопард
    // Тирано/2 на тяжёлой — 37/39/39/115 против табличных 22/24/24/100), и по таблице простолюдин
    // «побеждал» леопарда, которому на деле проигрывает.
    let живой = 0;
    for (let i = m.u32(G.unitHead); i && т; i = m.u32(UNITS + i + U.NEXT))
      if (!(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.TYPE) === т) { живой = i; break; }
    с.эталонЗверя = т ? { кто: ИМЯ_ЗВЕРЯ_[т] || ('зверь ' + т), ...статы(m, т),
                          ...(живой ? { жизни: m.u8(UNITS + живой + U.HPMAX), атака: m.u8(UNITS + живой + U.ATK),
                                        защита: m.u8(UNITS + живой + U.DEF), скорость: m.u8(UNITS + живой + U.SPD) } : {}) } : null;
  }

  const { надо, счёт } = чегоНеХватает(m, с, мой);
  const лог = логова(m);
  const святилище = дома.find(д => д.т === СВЯТИЛИЩЕ && !д.стро);
  const база = святилище ? кл(m, святилище.н)
             : (конструкторы.length ? кл(m, конструкторы[0]) : null);

  // ВОЙСКО ДЛЯ ДАЛЬНЕЙ СТРОЙКИ. Места у Святилища хватает на один-два дома, дальше площадки лежат
  // среди логов и выпасов. Замер Тирано/2: загон, поставленный за 12 клеток от базы при отряде из
  // простолюдинов (каждый проигрывает леопарду один на один), пёс снёс за полминуты, отряд полёг
  // его защищая, а следом звери разобрали и базу. Поэтому дом задания вдали от базы ставим, только
  // когда у нас есть КОНВОЙ_СИЛЬНЫХ бойцов, которые бьют эталонного зверя карты в дуэли по
  // калькулятору движка; до тех пор строим только рядом, а еда идёт на таких бойцов.
  let сильных = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (т >= 0x1a || т === КОНСТРУКТОР || !жив(m, i)) continue;
    const б = { тип: т, жизни: m.u8(UNITS + i + U.HPMAX), атака: m.u8(UNITS + i + U.ATK),
                защита: m.u8(UNITS + i + U.DEF), скорость: m.u8(UNITS + i + U.SPD) };
    if (!с.эталонЗверя || дуэль(б, с.эталонЗверя).победит) сильных++;
  }
  const войскоГотово = !КОНВОЙ_СИЛЬНЫХ || !база || сильных >= КОНВОЙ_СИЛЬНЫХ;
  const дальний = (вид) => вид !== 0 && вид !== 4;
  // С ТОЧНО дома задания не ставим туда, где они затыкают проход (кольцо распадается на куски):
  // лучше подождать. Тирано/2, зерно 13: загон на (34,37) — прямо в проходе из кармана — запер
  // и отряд, и строителей до конца партии при 15 тысячах еды в казне.
  const безПробок = (вид) => ДОВОДИТЬ_ТОЧНО && дальний(вид);
  const рядом = (вид) => кандидаты(m, база, лог, true, 6, вид, безПробок(вид));

  const ждалКонвоя = с.ждётКонвоя; с.ждётКонвоя = null;
  // 1. КОНСТРУКТОРЫ. Каждому, кто не в стройке, даём точку. Приказ не повторяем каждый тик:
  // движок при повторе бросает найденный путь и ищет заново — юнит топчется на месте.
  let посланы = 0;
  // План Тирано/2: площадки за горлом заняты кем — чтобы два строителя не шли на одну.
  const планЗанято = new Set();
  if ((ПЛАН_Т2 || ЗА_МОСТОМ) && Т2.этаКарта(m)) for (const [, т] of (с.планПлощадка ??= new Map())) планЗанято.add(т.x + ',' + т.y);
  for (const i of конструкторы) {
    const c = кл(m, i);
    // СТРОИТЕЛЬ В ДРАКЕ НЕ УЧАСТВУЕТ (владелец: «строитель убил первого зверя — это не хорошо, пусть
    // в драке не участвует совсем»). Зверь вплотную, держит его целью или сам строитель вцепился в
    // зверя — уводим на ближнюю клетку, дальнюю от всех зверей вокруг; стройка ждёт.
    (с.зачем ??= {})[i] = '?';
    // КОНСТРУКТОР ЗАХВАТА (вид 14) домов не строит: идёт за армией к нужному Святилищу врага и, когда
    // у цели нет чужих бойцов, получает «атаковать» здание — движок сам делает его нашим (0x1d9cd).
    if (m.u8(UNITS + i + 0x59) === 14) {
      const з = с.захват, п = с.послано.get(i), шаг = m.u32(G.step);
      if (з?.цель && !(m.u8(UNITS + з.цель + U.FLAGS5B) & 1)) {
        const т = кл(m, з.цель);
        let охрана = 0;
        for (let j = m.u32(G.unitHead); j; j = m.u32(UNITS + j + U.NEXT)) {
          const тj = m.u8(UNITS + j + U.TYPE), wj = m.u8(UNITS + j + U.OWNER);
          if ((m.u8(UNITS + j + U.FLAGS5B) & 1) || !m.u8(UNITS + j + U.HP) || тj >= 0x1a || wj === мой) continue;
          if (далеко(кл(m, j), т) <= 3) охрана++;
        }
        const куда = з.у && !охрана ? т : (с.отряд || т);
        if (з.у && !охрана) {
          if (!п || п.цель !== з.цель || шаг - п.шаг >= ПОВТОР) { приказ(eng, i, 0x1f, з.цель, m.u16(UNITS + з.цель + U.X), m.u16(UNITS + з.цель + U.Y)); с.послано.set(i, { цель: з.цель, шаг }); }
          с.зачем[i] = 'захват: иду в святилище ' + т.x + ',' + т.y;
        } else if (далеко(c, куда) > 2 && (!п || п.цx !== куда.x || п.цy !== куда.y || шаг - п.шаг >= ПОВТОР * 3)) {
          приказ(eng, i, 0x0f, 0, куда.x << 5, куда.y << 5); с.послано.set(i, { цx: куда.x, цy: куда.y, шаг });
          с.зачем[i] = 'захват: иду за армией';
        } else с.зачем[i] = 'захват: жду зачистки (' + охрана + ' у цели)';
      }
      посланы++; continue;
    }
    if (БЕЗ_ДРАКИ && отвестиОтДраки(eng, m, i, c, с)) { с.зачем[i] = 'бегство'; посланы++; continue; }
    const свой = m.u8(UNITS + i + 0x59);                        // вид будущего дома
    // У СТЕНЫ (любая карта): место в зоне базы выбирает местоУСтены; строим, только когда поиск щели
    // движка (0x1cd2d) от клетки строителя даёт ровно нашу клетку. Мест в зоне нет — дальше как раньше.
    if (У_СТЕНЫ) {
      if (с.центрДля !== миссия || !с.центрБазы) {
        с.центрДля = миссия; с.планУСтены = new Map(); с.плохиеЯкоря = new Set(); с.дошёлДоБазы = false;
        // Безопасная база — только пока Святилища нет (на Тирано/2 карман с логовами проверен победами — не трогаем).
        с.центрБазы = (!база || !святилище) && БЕЗОПАСНО && !Т2.этаКарта(m) ? безопаснаяБаза(m, база || c) : (база || c);
      }
      const планы = с.планУСтены;
      for (const [j] of планы) if (!конструкторы.includes(j)) планы.delete(j);
      let т = планы.get(i);
      if (т && m.u32(G.step) - т.с > 2200) { планы.delete(i); т = null; }     // не встал за 2 минуты — ищем заново
      if (!т) {
        const чужие = [];
        for (const [j, п] of планы) if (j !== i) for (const { dx, dy } of отпечаток(m, п.вид)) чужие.push(п.x + dx + (п.y + dy) * 256);
        // Зона базы полна — расширяем кольцами (Коака/2: третьему гнезду места не нашлось, строитель ушёл в
        // «дальняя стройка ждёт конвоя» и простоял 270 секунд при 16 тысячах еды).
        let место = null;
        for (const доп of [0, 4, 8, 12]) if ((место = местоУСтены(m, свой, с.центрБазы, лог, чужие, с.плохиеЯкоря, У_СТЕНЫ_Р + доп))) break;
        if (место) { т = { ...место, вид: свой, с: m.u32(G.step) }; планы.set(i, т); }
      }
      с.зачем[i] = т ? 'у стены ' + т.x + ',' + т.y : 'у стены: мест нет';
      if (т) {
        const п = с.послано.get(i);
        if (далеко(c, т) <= 0) {
          const своя = BI + c.x + (c.y << 8), было = m.u8(своя);
          m.w8(своя, было & 3);
          const м = F[0x1cd2d](eng, { eax: свой, esi: i });
          m.w8(своя, было);
          const совпало = ((м.edx & 0xffff) >> 5) === т.x && ((м.ebx & 0xffff) >> 5) === т.y;
          // ЗАПАСНОЙ ХОД (владелец, Коака/2: «завис при попытке построить; не может в лучшем месте — берём
          // следующее»). Стоим на месте, а движок 5 секунд подряд ставит дом не сюда — место вычёркиваем.
          if (!совпало) {
            с.зачем[i] += ' движок: ' + ((м.edx & 0xffff) >> 5) + ',' + ((м.ebx & 0xffff) >> 5);
            т.ждёт ??= m.u32(G.step);
            if (m.u32(G.step) - т.ждёт > 90) {
              (с.плохиеЯкоря ??= new Set()).add(т.x + т.y * 256);
              планы.delete(i); с.послано.delete(i);
            }
            посланы++; continue;
          }
          т.ждёт = null;
          if (!п || п.цx !== т.x || п.цy !== т.y || п.строй !== true || m.u32(G.step) - п.шаг >= ПОВТОР) {
            приказ(eng, i, 0xe0, 0, c.x << 5, c.y << 5);
            с.послано.set(i, { цx: т.x, цy: т.y, шаг: m.u32(G.step), x: c.x, y: c.y, строй: true });
          }
        } else {
          // Не дойти до места (стоит на одной клетке 10 секунд) — место тоже вычёркиваем.
          // Не приближается к месту 10 секунд (стоит или ходит туда-сюда) — место вычёркиваем.
          const дд = Math.hypot(c.x - т.x, c.y - т.y);
          if (!т.поз || дд < т.поз.д - 0.5) т.поз = { д: дд, с: m.u32(G.step) };
          else if (m.u32(G.step) - т.поз.с > 180) {
            (с.плохиеЯкоря ??= new Set()).add(т.x + т.y * 256);
            планы.delete(i); с.послано.delete(i); посланы++; continue;
          }
          // Далеко — идём по точкам безопасного пути (движок сам повёл бы напрямик, мимо логов).
          let цель = т;
          const точки = с.центрБазы?.точки;
          // по точкам пути — только пока не дошли до базы (Масаи/2, Коака/2: у базы строитель бегал туда-сюда
          // между соседними точками, а место дома лежало в стороне от пути)
          if (точки?.length && далеко(c, с.центрБазы) <= 3) с.дошёлДоБазы = true;
          if (точки?.length && !с.дошёлДоБазы && далеко(c, т) > 4) {
            let и = 0; for (let j = 1; j < точки.length; j++) if (далеко(точки[j], c) < далеко(точки[и], c)) и = j;
            цель = и + 1 < точки.length ? точки[и + 1] : т;           // дошли до конца пути — к самому месту дома
            if (далеко(цель, т) <= 4 || далеко(c, точки[точки.length - 1]) <= 1) цель = т;
          }
          if (!п || п.цx !== цель.x || п.цy !== цель.y || (п.x === c.x && п.y === c.y && m.u32(G.step) - п.шаг >= ПОВТОР * 5)) {
            приказ(eng, i, 0x0f, 0, цель.x << 5, цель.y << 5);
            с.послано.set(i, { цx: цель.x, цy: цель.y, шаг: m.u32(G.step), x: c.x, y: c.y });
          }
        }
        посланы++; continue;
      }
    }
    // ПЛАН ТИРАНО/2: второй склад и дома задания — на площадки за горлом (проверены: зверь туда не
    // подходит), строитель выходит из кармана только в окно мимо мамонта (Т2.можноВыходить).
    if ((ПЛАН_Т2 || ЗА_МОСТОМ) && Т2.этаКарта(m) && (свой !== 0 || ЗА_МОСТОМ) && (ЗА_МОСТОМ || свой !== 4 || счёт(4) >= 2)) {
      // Святилище (3×2) — в юго-восточный угол кармана: у старта оно вставало на 33,40 поперёк
      // кармана у самого моста и перегораживало выход (владелец: «путь перегородил»).
      let т = свой === 0 ? Т2.СВЯТИЛИЩЕ : с.планПлощадка.get(i);
      // В_КАРМАНЕ (владелец: «у края справа вполне можно построить оба здания, мешать не будут»):
      // первые два дома — в карман у правого края, рядом со Святилищем; строитель не выходит к мамонтам.
      if (!т && В_КАРМАНЕ && (с.домовВКармане ?? 0) < 2) {
        т = местоВКармане(m, свой);
        if (т) { с.планПлощадка.set(i, т); планЗанято.add(т.x + ',' + т.y); с.домовВКармане = (с.домовВКармане ?? 0) + 1; }
      }
      if (!т) {
        т = Т2.ПЛОЩАДКИ.find(п => !планЗанято.has(п.x + ',' + п.y)
                              && [[0,0],[1,0],[0,1],[1,1]].every(([dx, dy]) => проходима(m, п.x + dx, п.y + dy)));
        if (т) { с.планПлощадка.set(i, т); планЗанято.add(т.x + ',' + т.y); }
      }
      if (т) {
        const п = с.послано.get(i);
        const новый = !п || п.цx !== т.x || п.цy !== т.y || (п.x === c.x && п.y === c.y && m.u32(G.step) - п.шаг >= ПОВТОР * 5);
        // За мостом: выходим вслед за отрядом, когда он уже вышел из кармана (окно мимо мамонта почти не
        // открывается — мамонт стоит в 4–5 клетках от пути). Иначе — прежнее окно.
        const ждать = ЗА_МОСТОМ ? !(с.отряд && !Т2.вКармане(с.отряд)) : !Т2.можноВыходить(m);
        if (!Т2.вКармане(т) && Т2.вКармане(c) && ждать) {                                   // ждём на стоянке
          if (далеко(c, Т2.СТОЯНКА) > 1 && (!п || п.цx !== Т2.СТОЯНКА.x || п.цy !== Т2.СТОЯНКА.y)) {
            приказ(eng, i, 0x0f, 0, Т2.СТОЯНКА.x << 5, Т2.СТОЯНКА.y << 5);
            с.послано.set(i, { цx: Т2.СТОЯНКА.x, цy: Т2.СТОЯНКА.y, шаг: m.u32(G.step), x: c.x, y: c.y });
          }
          посланы++; continue;
        }
        // Святилище: пока на его клетках кто-то стоит (у старта там дерутся с леопардом), не строим —
        // движок сдвигает занятое место сам и ставил дом на 32,40, поперёк прохода к мосту.
        // Спрашиваем сам движок (0x1cd2d — тот поиск щели, что сработает по приказу), куда встанет дом, и
        // строим, только если ровно сюда: он ищет от клетки строителя и при занятых клетках сдвигал
        // Святилище на 32,40 и 34,40 — поперёк прохода и на место склада.
        if (Т2.вКармане(т) && далеко(c, т) <= 0) {
          const своя = BI + c.x + (c.y << 8), было = m.u8(своя);
          m.w8(своя, было & 3);
          const м = F[0x1cd2d](eng, { eax: свой, esi: i });
          m.w8(своя, было);
          if (((м.edx & 0xffff) >> 5) !== т.x || ((м.ebx & 0xffff) >> 5) !== т.y) { посланы++; continue; }
        }
        if (далеко(c, т) <= 0) { приказ(eng, i, 0xe0, 0, c.x << 5, c.y << 5); с.послано.set(i, { цx: т.x, цy: т.y, шаг: m.u32(G.step), x: c.x, y: c.y }); посланы++; continue; }
        if (новый) { приказ(eng, i, 0x0f, 0, т.x << 5, т.y << 5); с.послано.set(i, { цx: т.x, цy: т.y, шаг: m.u32(G.step), x: c.x, y: c.y }); }
        посланы++; continue;
      }
    }
    const якорь = свой === 0 ? c : (база || c);                 // Святилище — у самого старта
    // Площадки на выбор считаем всегда: их видит мозг штаба (и они же идут в строку состояния).
    const места = (!войскоГотово && дальний(свой)) ? рядом(свой)
                : кандидаты(m, якорь, лог, свой === 0, 6, свой, безПробок(свой));   // отпечаток у каждого дома свой
    с.места = места.map(({ x, y, доЛогова, логовРядом, зверейРядом, самый, обход, кусков, оценка }) =>
                        ({ x, y, доЛогова, логовРядом, зверейРядом, самый, обход, кусков, оценка }));
    с.местаВид = свой;

    // ЗАСТРЯЛ — МЕНЯЕМ ПЛОЩАДКУ. Считаем по КЛЕТКЕ И ВРЕМЕНИ, а не по состоянию: движок между
    // тиками переключает конструктора с «иду строиться» на «иду» и обратно, и по состоянию
    // застревание не поймать. Замер Moospell/2: конструктор казармы простоял в одной клетке 200
    // секунд — место к его приходу занял склад, а место под дом выбирает сам движок (0x1d1cf →
    // 0x1cd2d) от того, где стоит юнит. Поэтому мало повторить приказ: надо СДВИНУТЬ юнита на
    // другую площадку обычной ходьбой, и уже оттуда дать «строй».
    const з = (с.застряли ??= new Map()).get(i);
    if (!з || з.x !== c.x || з.y !== c.y) с.застряли.set(i, { x: c.x, y: c.y, шаг: m.u32(G.step), н: 0, ведём: null });
    const стоит = с.застряли.get(i);
    // Кто ждёт конвоя у базы, тот не застрял: стоит нарочно (иначе «застрявшего» уводили к запасной
    // площадке одного, без отряда, — прямо через выпас мамонтов).
    const долго = m.u32(G.step) - стоит.шаг >= ЗАСТРЯЛ && ждалКонвоя?.строитель !== i;
    if (долго) {
      const запас = места.filter(т => далеко(т, c) > 2);
      const т = запас[(стоит.н + 1) % Math.max(1, запас.length)];
      if (т) {
        приказ(eng, i, 0x0f, 0, т.x << 5, т.y << 5);            // сперва просто отойти туда
        с.застряли.set(i, { x: c.x, y: c.y, шаг: m.u32(G.step), н: стоит.н + 1, ведём: т });
        с.послано.set(i, { цx: т.x, цy: т.y, шаг: m.u32(G.step), x: c.x, y: c.y });
        посланы++; continue;
      }
    }
    // Дошёл до площадки, куда его увели, — можно строиться прямо здесь.
    if (стоит.ведём && далеко(c, стоит.ведём) <= 2) {
      // Дошёл «почти». Движок поставит дом в ближайшую к НЕМУ щель — проверяем, не затыкает ли
      // она проход; если да, доводим ровно на площадку (Тирано/2, зерно 1: цель (35,32) не мешала,
      // а дом встал на (34,32), откуда пришёл строитель, и запер карман базы).
      if (ДОВОДИТЬ_ТОЧНО && свой !== 0 && свой !== 4 && далеко(c, стоит.ведём) > 0) {
        const м = F[0x1cd2d](eng, { eax: свой, esi: i });
        const р = разборМеста(m, (м.edx & 0xffff) >> 5, (м.ebx & 0xffff) >> 5, лог, [], отпечаток(m, свой),
                              m.u32(G.mapW), m.u32(G.mapH));
        if (р.годно && р.кусков > 1 && (стоит.точно || 0) < 3) {
          приказ(eng, i, 0x0f, 0, стоит.ведём.x << 5, стоит.ведём.y << 5);
          с.застряли.set(i, { ...стоит, шаг: m.u32(G.step), точно: (стоит.точно || 0) + 1 });
          посланы++; continue;
        }
      }
      приказ(eng, i, 0xe0, 0, c.x << 5, c.y << 5);
      с.застряли.set(i, { x: c.x, y: c.y, шаг: m.u32(G.step), н: стоит.н, ведём: null });
      посланы++; continue;
    }
    if (стоит.ведём) { посланы++; continue; }                   // ещё идёт к новой площадке
    // СВЯТИЛИЩЕ — ПОСЛЕ ЗВЕРЕЙ. Площадка 3×2 посреди тесного кармана Тирано/2 (34,41) отнимает у
    // отряда место для ротации раненых, и пёс догрызает зажатого в углу (16-я секунда в 11 партиях
    // из 20). Пока в круге КРУГ_ЗВЕРЯ от строителя жив дикий зверь, Святилище не закладываем;
    // если за это время строителя оттеснили, сперва возвращаем его на стартовую клетку — иначе
    // движок поставит дом у горла прохода, и туда заходит мамонт.
    if (свой === 0) {
      const старт = (с.стартСтроителя ??= new Map());
      if (!старт.has(i)) старт.set(i, { x: c.x, y: c.y });
      let зверь = false;
      for (let з = m.u32(G.unitHead); з && !зверь; з = m.u32(UNITS + з + U.NEXT)) {
        const т = m.u8(UNITS + з + U.TYPE);
        if (т < 14 || т > 23 || (m.u8(UNITS + з + U.FLAGS5B) & 1) || !m.u8(UNITS + з + U.HP) || (m.u8(UNITS + з + U.STATE) & 0xf0) === 0x60) continue;
        зверь = далеко(кл(m, з), c) <= КРУГ_ЗВЕРЯ;
      }
      if (зверь && !СВЯТ_ТОЧКА) { с.ждалЗверя = true; посланы++; continue; }
      let с0 = СВЯТ_ТОЧКА || старт.get(i);
      // К точке Святилища строитель идёт за отрядом: пока отряд не дошёл до точки, держится у его
      // середины (одного его на 26-й секунде съел пёс у 25,23).
      if (СВЯТ_ТОЧКА && с.отряд && далеко(с.отряд, СВЯТ_ТОЧКА) > 2) {
        if (далеко(c, с.отряд) <= 1) { посланы++; continue; }
        с0 = { x: с.отряд.x, y: с.отряд.y };
      }
      if ((с.ждалЗверя || СВЯТ_ТОЧКА) && (c.x !== с0.x || c.y !== с0.y)) {
        const п0 = с.послано.get(i);
        if (!п0 || п0.цx !== с0.x || п0.цy !== с0.y || m.u32(G.step) - п0.шаг >= ПОВТОР) {
          приказ(eng, i, 0x0f, 0, с0.x << 5, с0.y << 5);
          с.послано.set(i, { цx: с0.x, цy: с0.y, шаг: m.u32(G.step), x: c.x, y: c.y });
        }
        посланы++; continue;
      }
    }

    const п = с.послано.get(i);
    if (п && m.u32(G.step) - п.шаг < ПОВТОР && (п.x !== c.x || п.y !== c.y)) { посланы++; continue; }
    // Берём лучшую по оценке — решение должно быть устойчивым: одни и те же цифры дают одно и то
    // же место. Владелец: «надо скриптом выбирать место строительства, это алгоритмически
    // стабильное решение».
    if (!места.length && (ДОВОДИТЬ_ТОЧНО || !войскоГотово) && дальний(свой)) continue;   // ждёт войска (или места) у базы
    // ПЛОЩАДКУ ДЕРЖИМ. Оценка площадок дрожит вместе со зверьём вокруг, и лучшая менялась, пока
    // строитель шёл: Тирано/2, зерно 7 — он двадцать минут бегал между (44,29) и (35,39) через
    // выпас мамонтов, пока его не съели. Выбранную площадку меняем, только если она перестала
    // годиться под дом или строитель на ней застрял (см. выше).
    const держим = (с.площадкаСтроителя ??= new Map()).get(i);
    let точка = null;
    if (держим && держим.вид === свой && места.some(т => т.x === держим.x && т.y === держим.y)) точка = держим;
    if (!точка) точка = места[0] || выбратьМесто(m, якорь, лог, свой === 0) || (п ? { x: п.цx, y: п.цy } : null);
    if (!точка) continue;
    с.площадкаСтроителя.set(i, { x: точка.x, y: точка.y, вид: свой });
    // СПЕРВА ДОВЕСТИ, ПОТОМ СТРОИТЬ. Точку в приказе 0xe0 движок не слушает: 0x1d1cf ищет площадку
    // (0x1cd2d) от клетки, где СТОИТ строитель. Замер Тирано/2: лучшая площадка (30,29), а загоны
    // выросли в логовах пса и леопарда у самой базы и на выпасе мамонтов — там, где строителя
    // застал приказ. Поэтому к далёкой площадке ведём обычной ходьбой, «строй» — на месте.
    // Святилище и склад — не трогаем: им место у старта, куда бойцы носят мясо.
    // Площадки у самой базы — по-старому, приказом «строй»: движок и так поставит дом рядом, а
    // ходьба у логова под боком у Святилища стоила строителей (зерно 9: пятеро съедены на месте).
    // КОНВОЙ ВПЕРЁД. Строитель стоит у базы, пока отряд не дошёл до площадки: мамонты Тирано/2 ели
    // строителей по дороге (четверо за партию, по 2000–2500 еды каждый), а отряд, прикрывавший
    // площадку, приходил туда позже строителя. Площадку при этом уже объявляем — штаб ведёт туда
    // отряд по ней.
    const дальняя = ДОВОДИТЬ && свой !== 0 && свой !== 4 && база && далеко(точка, база) > ДАЛЬНЯЯ;
    if (дальняя && КОНВОЙ_ВПЕРЁД && далеко(c, точка) > 2
        && (!с.отряд || далеко(с.отряд, точка) > КОНВОЙ_ВПЕРЁД)) {
      с.ждётКонвоя = { x: точка.x, y: точка.y, строитель: i }; с.зачем[i] = "ждёт конвоя " + точка.x + "," + точка.y;
      посланы++; continue;
    }
    // ДОВОДИТЬ_ВСЕ — опыт: и к ближней площадке ведём пешком. Иначе «строй» там, где стоит
    // строитель, и движок ставит дом в ближайшую щель — в том числе в горло прохода из кармана.
    if (ДОВОДИТЬ && свой !== 0 && свой !== 4 && далеко(c, точка) > (ДОВОДИТЬ_ВСЕ ? 0 : 2)
        && (ДОВОДИТЬ_ВСЕ || !база || далеко(точка, база) > ДАЛЬНЯЯ)) {
      приказ(eng, i, 0x0f, 0, точка.x << 5, точка.y << 5);
      с.застряли.set(i, { x: c.x, y: c.y, шаг: m.u32(G.step), н: стоит.н, ведём: точка });
      с.послано.set(i, { цx: точка.x, цy: точка.y, шаг: m.u32(G.step), x: c.x, y: c.y });
      посланы++; continue;
    }
    // ГДЕ ВСТАНЕТ НА САМОМ ДЕЛЕ. «Строй» ставит дом в ближайшую к строителю свободную площадку
    // (0x1cd2d), а не в нашу точку. Если та площадка затыкает проход (кольцо вокруг распадается на
    // куски) — ведём строителя к нашей точке пешком. Тирано/2, зерно 3: загон встал в горле
    // единственного прохода из кармана базы, и отряд со строителями оказался заперт.
    if ((НЕ_ЗАТЫКАТЬ || ДОВОДИТЬ_ТОЧНО)
        && свой !== 0 && свой !== 4 && далеко(c, точка) > 0) {
      // Движок сперва освобождает клетку самого строителя (0x1a42c) и лишь потом ищет щель, поэтому
      // если дом влезает прямо там, где он стоит, — там и встанет.
      const W2 = m.u32(G.mapW), H2 = m.u32(G.mapH);
      // Своя клетка в сетке BI помечена самим строителем (юниты штампуют её так же, как дома), —
      // на время разбора снимаем эту метку и сразу возвращаем.
      const своя = BI + c.x + (c.y << 8), было = m.u8(своя);
      m.w8(своя, было & 3);
      let р = разборМеста(m, c.x, c.y, лог, [], отпечаток(m, свой), W2, H2);
      m.w8(своя, было);
      if (!р.годно) {
        const м = F[0x1cd2d](eng, { eax: свой, esi: i });
        р = разборМеста(m, (м.edx & 0xffff) >> 5, (м.ebx & 0xffff) >> 5, лог, [], отпечаток(m, свой), W2, H2);
      }
      if (р.годно && р.кусков > 1) {
        приказ(eng, i, 0x0f, 0, точка.x << 5, точка.y << 5);
        с.застряли.set(i, { x: c.x, y: c.y, шаг: m.u32(G.step), н: стоит.н, ведём: точка });
        с.послано.set(i, { цx: точка.x, цy: точка.y, шаг: m.u32(G.step), x: c.x, y: c.y });
        посланы++; continue;
      }
    }
    // «Строй» не повторяем каждый тик: повтор бросает путь к площадке, и строитель, стоящий там,
    // где дом не влезает, навсегда застывает в 0xe0 (было: 816 приказов подряд, дом не встал).
    if (п && п.цx === точка.x && п.цy === точка.y && m.u32(G.step) - п.шаг < ПОВТОР) { посланы++; continue; }
    приказ(eng, i, 0xe0, 0, точка.x << 5, точка.y << 5);
    с.послано.set(i, { цx: точка.x, цy: точка.y, шаг: m.u32(G.step), x: c.x, y: c.y });
    посланы++;
  }

  // РЕЗЕРВ НА СКЛАД. Без склада мясо сдавать некуда и казна не растёт вовсе; если его сломали,
  // когда в казне меньше его цены, партия встаёт намертво (Тирано/2, зерно 2: 713 еды с 3600-й
  // секунды до конца). Поэтому, пока склад стоит, на бойцов и дома тратим только сверх его цены.
  const резерв = РЕЗЕРВ_НА_СКЛАД && дома.some(д => д.т === СКЛАД && !д.стро)
    ? (домаПлемени(m, мой, 0).find(п => п.вид === 4)?.цена ?? 1000) : 0;

  // 1б. СНЯТЬ ПАУЗУ. Когда заказ съедает еду до нуля, движок ставит производство на паузу (бит 4 в
  // +0x50, economy.js 0x18a81) — и сам её НЕ СНИМАЕТ: это делает игрок повторным нажатием (0x7f
  // занятому зданию снимает паузу, bldOrder). Мы этого не делали никогда, и на второй миссии Тирано
  // Святилище и загон простояли на паузе полчаса при казне в пять тысяч. Снимаем, как только еды
  // хватает хотя бы на ПАУЗА_ЗАПАС шагов заказа.
  for (const д of дома) {
    const ф = m.u8(UNITS + д.н + U.FLAGS50);
    if (!(ф & 1) || !(ф & 4)) continue;
    const заШаг = m.u32(UNITS + д.н + 0x1f);
    if (m.u32(0x31c28 + мой * 4) < заШаг * ПАУЗА_ЗАПАС + резерв) continue;
    if (m.u32(G.step) - ((с.паузаСнята ??= new Map()).get(д.н) ?? -1e9) < 36) continue;
    приказ(eng, д.н, 0x7f, m.u32(UNITS + д.н + U.TARGET) & 0xff);
    с.паузаСнята.set(д.н, m.u32(G.step));
  }

  // 2. ЗАКАЗ В СВЯТИЛИЩЕ. Одно занятое здание — один заказ за раз: очередь у нас есть, но пока
  // заказываем по одному, чтобы еду не съело наперёд.
  let заказ = null;
  const еда = m.u32(0x31c28 + мой * 4);
  // Что вообще можно заказать в Святилище и почём — читаем у движка, а не гадаем: у каждого
  // племени свой набор кнопок.
  let меню = [], менюБойцов = [];
  const слот = святилище ? m.u8(UNITS + святилище.н + U.SLOT) : (дома[0] ? m.u8(UNITS + дома[0].н + U.SLOT) : мой);
  if (святилище) меню = домаПлемени(m, слот, еда, счёт);
  // Кого можно заказать в уже построенных домах — это отдельный и чаще более нужный выбор:
  // «не всегда нам нужны все здания, часто нам нужны новые юниты для атаки, охоты».
  менюБойцов = бойцыВДомах(m, слот, дома, еда);
  с.меню = меню; с.менюБойцов = менюБойцов;

  // --- ЭКОНОМИКА И ПОРОГ «НУЖЕН ЛИ ЕЩЁ ДОМ»
  const шагСейчас = m.u32(G.step);
  if (с.замерШаг === undefined) { с.замерШаг = шагСейчас; с.замерЕда = еда; с.доход = 0; с.потрачено = 0; }
  if (шагСейчас - с.замерШаг >= ЗАМЕР_ДОХОДА) {
    const секунд = (шагСейчас - с.замерШаг) * 0.055;
    // Доход считаем по приходу, а не по разнице: заказы тратят из той же казны, поэтому к разнице
    // прибавляем всё, что за окно ушло на производство.
    с.доход = Math.max(0, Math.round(((еда - с.замерЕда) + с.потрачено) / секунд));
    с.замерШаг = шагСейчас; с.замерЕда = еда; с.потрачено = 0;
  }
  const производящих = дома.filter(д => !д.стро && д.занят).length;
  const могутПроизводить = дома.filter(д => !д.стро && (д.т - 0x1a) !== 4).length;   // склад ничего не делает
  if (производящих) с.потрачено += производящих * 10;                                 // 10 еды за шаг на дом
  const пропускная = Math.max(1, могутПроизводить) * 182;
  const переработка = Math.round(еда / пропускная);
  const экономика = {
    запас: еда, доход_в_секунду: с.доход || 0,
    домов_рабочих: могутПроизводить, из_них_заняты: производящих,
    пропускная_в_секунду: пропускная, запас_переработаем_за_секунд: переработка,
    // Решение скрипта: считаем, а не гадаем. Мозгу остаётся выбрать, КАКОЙ дом.
    нужен_ещё_дом: переработка > ГОРИЗОНТ || (с.доход || 0) > пропускная,
    почему: переработка > ГОРИЗОНТ
      ? `запаса на ${переработка} с работы домов, это дольше ${ГОРИЗОНТ} с`
      : ((с.доход || 0) > пропускная ? `доход ${с.доход} еды/с обгоняет пропускную ${пропускная}` : 'домов хватает'),
  };
  с.экономика = экономика;

  // ЗАКАЗ БОЙЦА в обычном доме. Кнопка та же (0x7f), только отдаётся не Святилищу, а дому.
  let заказанБоец = null;
  // Сколько у нас живых бойцов (строители не в счёт) и сколько домов ещё требует задание.
  let бойцовЕсть = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (т < 0x1a && т !== КОНСТРУКТОР && жив(m, i)) бойцовЕсть++;
  }
  // Сколько людей без оружия и без щита: вещи носят только типы 1–3.
  let безоружных = 0, безЩита = 0, готовоОружия = 0, готовоЩитов = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if (m.u8(UNITS + i + U.OWNER) !== мой || !жив(m, i)) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (т < 1 || т > 3) continue;
    if (m.u8(UNITS + i + U.WEAPON) === 0xff) безоружных++;
    if (m.u8(UNITS + i + U.SHIELD) === 0xff) безЩита++;
    // Уже выкованное, но ещё не надетое, тоже считается: иначе кузница лупит вещь за вещью,
    // пока их никто не подобрал (замер: тридцать «оружие #3» подряд за минуту).
    for (let k = 0; k < 6; k++) {
      const id = m.u8(UNITS + i + U.INV + k);
      if (!id || k === m.u8(UNITS + i + U.WEAPON) || k === m.u8(UNITS + i + U.SHIELD)) continue;
      const в = вещьСправка(m, id);
      if (в.оружие) готовоОружия++; else if (в.щит) готовоЩитов++;
    }
  }
  // И то, что валяется на земле. Владелец: «на земле не должно быть больше 4 единиц оружия; оружия на
  // земле должно быть меньше, чем безоружных». Стрелковое (4–7) рукопашники не берут — считаем отдельно.
  const безоружныхВсего = безоружных, безЩитаВсего = безЩита;
  let наЗемлеОружия = 0, наЗемлеЩитов = 0;
  for (let it = m.u32(0x31b7c), шагов = 0; it && шагов < 4096; it = m.u32(ITEMS + it + 0xc), шагов++) {
    const тип = m.u8(ITEMS + it);
    if (!тип || тип === 0x1e) continue;
    const в = вещьСправка(m, тип);
    if (в.оружие) { готовоОружия++; наЗемлеОружия++; } else if (в.щит) { готовоЩитов++; наЗемлеЩитов++; }
  }
  безоружных = Math.max(0, безоружных - готовоОружия);
  безЩита = Math.max(0, безЩита - готовоЩитов);
  const домаЖдут = надо.length > 0;
  // Сила: своя и сильнейшего чужого племени рядом. Считаем грубо — атака плюс жизни, как в штабе.
  let нашаСила = 0; const чужаяСила = new Map();
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const т = m.u8(UNITS + i + U.TYPE);
    if (т >= 0x1a || ЗВЕРЬ(т) || т === 24 || т === 25 || !жив(m, i)) continue;
    const сила = m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.HP);
    const хозяин = m.u8(UNITS + i + U.OWNER);
    if (хозяин === мой) нашаСила += сила;
    else if (хозяин <= 7) чужаяСила.set(хозяин, (чужаяСила.get(хозяин) || 0) + сила);
  }
  const сильнейшийЧужой = Math.max(0, ...чужаяСила.values());
  // Пока слабее соседа — набираем войско: «тогда он не станет нападать».
  const надоСилы = сильнейшийЧужой * ЗАПАС_СИЛЫ;
  const хватитНарода = бойцовЕсть >= ХВАТИТ_БОЙЦОВ && (!сильнейшийЧужой || нашаСила >= надоСилы);
  // СНАЧАЛА ОХОТНИКИ (владелец, Коака/2: «одним динозавром никого не убить — значит в начале строить
  // что-то другое»). Если нынешний отряд не бьёт эталонного зверя карты вместе, перебираем дома из
  // меню: сколько их бойцов добавить, чтобы отряд его бил, и во что это встанет (дом, если его нет, +
  // бойцы). Берём самый дешёвый план, что укладывается в казну (нет такого — самый дешёвый вообще):
  // его дом строим раньше домов задания, его бойцов и нанимаем.
  с.планОхоты = null;
  if (СНАЧАЛА_ОХОТНИКИ && с.эталонЗверя) {
    const отряд = [];
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || m.u8(UNITS + i + U.OWNER) !== мой) continue;
      const т = m.u8(UNITS + i + U.TYPE);
      if (т >= 0x1a || т === КОНСТРУКТОР || ЗВЕРЬ(т) || !жив(m, i)) continue;
      отряд.push({ тип: т, жизни: m.u8(UNITS + i + U.HPMAX), атака: m.u8(UNITS + i + U.ATK), защита: m.u8(UNITS + i + U.DEF), скорость: m.u8(UNITS + i + U.SPD) });
    }
    if (!отрядБьёт(отряд, с.эталонЗверя)) {
      let лучший = null;
      for (const п of меню) for (const б of (п.даёт || [])) {
        if (!б.жизни || !б.цена) continue;
        for (let n = 1; n <= 6; n++) {
          if (!отрядБьёт([...отряд, ...Array(n).fill(б)], с.эталонЗверя)) continue;
          const цена = (п.есть ? 0 : п.цена) + n * б.цена, влезает = цена <= еда;
          if (!лучший || (влезает && !лучший.влезает) || (влезает === лучший.влезает && цена < лучший.цена))
            лучший = { вид: п.вид, кто: б.кто, n, цена, влезает, домЕсть: !!п.есть };
          break;
        }
      }
      с.планОхоты = лучший;
    }
  }
  const ждёмЗаказ = m.u32(G.step) - (с.заказБойцаНа ?? -99) <= 18;
  if (!ждёмЗаказ) {
    let хочу = null;
    // 1) Слово мозга — что он назвал, то и заказываем.
    if (с.заказБоец) {
      хочу = менюБойцов.find(б => б.дом === с.заказБоец.дом && б.k === с.заказБоец.k);
      с.заказБоец = null;
    }
    // 1а) План «сначала охотники»: его бойцов — в первую очередь.
    if (!хочу && с.планОхоты) хочу = менюБойцов.find(б => б.кто === с.планОхоты.кто && б.хватает && !б.занят) || null;
    // 1б) ОРУЖИЕ И ЩИТЫ ТЕМ, КТО БЕЗ НИХ. Владелец: «чтобы заказалось оружие для построек» и
    // «щиты тоже обязательно надо строить, не только оружие». Куём по очереди: сперва оружие
    // безоружным (урон растёт сразу), потом щиты тем, у кого пустая вторая рука, — щит вычитается
    // из чужого удара по таблице оружия (0x37af4 + 0x28) и часто превращает единицу урона по нам
    // в единицу минимума, то есть продлевает жизнь бойцу вдвое.
    // Лишнего не куём (Радумба/2: оружейная клепала луки, рукопашники их не брали — пять луков и
    // четыре щита на земле): на земле меньше 4 и меньше, чем безоружных; рукопашное впереди стрелкового.
    const куётОружие = безоружных > 0 && наЗемлеОружия < Math.min(4, безоружныхВсего);
    const куётЩит = безЩита > 0 && наЗемлеЩитов < Math.min(4, безЩитаВсего);
    // Прошлая вещь ещё куётся (на землю не легла, в счёт не попала) — следующую не заказываем 30 с.
    if (!хочу && (куётОружие || куётЩит) && m.u32(G.step) - (с.вещьНа ?? -9999) > 550) {
      const нужноОружие = куётОружие;
      const стрелковое = (б) => б.id >= 4 && б.id <= 7;
      const вещи = менюБойцов
        .filter(б => б.вещь && б.хватает && !б.занят && (нужноОружие ? б.оружие : б.щит))
        .sort((a, b) => нужноОружие ? (стрелковое(a) - стрелковое(b)) || (b.атака || 0) - (a.атака || 0)
                                    : (b.защита || 0) - (a.защита || 0));
      if (вещи.length) хочу = вещи[0];
    }
    // 2) Запасное правило скрипта (когда мозга нет): самый сильный из тех, на кого хватает.
    //    Но только пока бойцов меньше, чем «хватит», и пока задание не ждёт домов: на вторых
    //    миссиях еда нужнее на постройки, а четырёх человек достаточно, чтобы кормить племя.
    // Четверых нанимаем ВСЕГДА, даже когда задание ждёт построек: без людей ни мяса, ни защиты, и
    // именно их отсутствие владелец и увидел («почему-то не построился второй рабочий»). Сверх
    // четырёх — только когда стройка уже не ждёт еды.
    // 2а) Дальняя стройка ждёт войска — нанимаем того, кто бьёт эталонного зверя, сверх четырёх.
    if (!хочу && !войскоГотово && КОНВОЙ_СИЛЬНЫХ) {
      const сильные = менюБойцов.filter(б => б.хватает && !б.занят && !б.вещь && б.жизни
                                             && (!с.эталонЗверя || дуэль(б, с.эталонЗверя).победит))
                                 .sort((a, b) => (b.атака + b.жизни) - (a.атака + a.жизни));
      хочу = сильные[0] || null;
    }
    // Пока копим на того, кто бьёт эталонного зверя, слабых не нанимаем: их 500 еды откладывают
    // сильного, а в бою они гибнут чаще, чем окупаются.
    const копимНаСильного = КОНВОЙ_СИЛЬНЫХ && !войскоГотово && менюБойцов.some(б => !б.вещь && б.жизни
                              && (!с.эталонЗверя || дуэль(б, с.эталонЗверя).победит));
    if (!хочу && !хватитНарода && !копимНаСильного) {
      // НАЁМ_ИЗ — из каких домов нанимать (по умолчанию из любых). Владелец про Тирано/2: «нет
      // необходимости строить больше двух юнитов вообще на этой карте» — только простолюдины из
      // казармы, раптор за 1400 не нужен.
      const можно = менюБойцов.filter(б => б.хватает && !б.занят && !б.вещь && (!НАЁМ_ИЗ || НАЁМ_ИЗ.includes(б.вид)))
                              .sort((a, b) => (b.атака + b.жизни) - (a.атака + a.жизни));
      хочу = можно[0] || null;
    }
    // Своих бойцов нет вовсе — запас на склад не держим: мясо носить некому, и казна сама не вырастет
    // (Коака/2: 2500 еды, рамфоринх 1800 + запас 1000 — не нанимали никогда, партия стояла).
    if (хочу && !хочу.занят && еда >= хочу.цена + (бойцовЕсть === 0 || с.планОхоты ? 0 : резерв)) {
      приказ(eng, хочу.дом, 0x7f, хочу.k);
      с.заказБойцаНа = m.u32(G.step);
      заказанБоец = { кто: хочу.кто, цена: хочу.цена };
      if (хочу.вещь) с.вещьНа = m.u32(G.step);
      (с.журналБойцов ??= []).push(Math.round(m.u32(G.step) * 0.055) + 'с:' + хочу.кто + (хочу.вещь ? ':вещь' : '') + ':безор' + безоружных + ':безщ' + безЩита);
    }
  }
  if (святилище) {
    const занято = (m.u8(UNITS + святилище.н + U.FLAGS50) & 1) !== 0;
    // 1) Обязательное — Святилище, склад, дома из задания.
    //    ИЗ ДОМОВ ЗАДАНИЯ ПЕРВЫМ — ТОТ, ЧЕЙ БОЕЦ ЛУЧШИЙ ОХОТНИК. Заданию всё равно, в каком порядке
    //    строить, а экономике нет: вторая миссия Тирано требует 3 казармы и 3 загона велоцирапторов,
    //    и если начать с казарм, отряд из простолюдинов, проигрывающих леопарду один на один, еды на
    //    остальное не добудет (замер: за 30 минут одна казарма и полное вымирание). Раптор за 1400
    //    побеждает леопарда в дуэли и даёт в 2.6 раза больше урона на 1000 еды. Склад и Святилище
    //    не трогаем — они идут первыми всегда.
    const пользаПамять = new Map();
    const польза = (вид) => {
      if (пользаПамять.has(вид)) return пользаПамять.get(вид);
      const д = меню.find(п => п.вид === вид);
      const лучший = (д?.даёт || []).map(б => боевыеЦифры(б, с.эталонЗверя)).filter(Boolean)
                                   .sort((a, b) => (b.заЕду || 0) - (a.заЕду || 0))[0];
      пользаПамять.set(вид, лучший?.заЕду || 0);
      return лучший?.заЕду || 0;
    };
    // Первым — ОДИН склад (без него мясо сдавать некуда); остальные склады, если их требует задание, —
    // наравне с домами задания (Радумба/2: задание просит четыре склада, ПРОРАБ ставил их все первыми и
    // проедал казну — на казарму и бойцов не осталось, партия встала без единого бойца).
    const первые = надо.includes(4) && счёт(4) < 1 ? [4] : [];
    const задания = надо.filter(в2 => в2 !== 0);
    if (первые.length) задания.splice(задания.indexOf(4), 1);
    if (ПОРЯДОК_ПО_ПОЛЬЗЕ) задания.sort((a, b) => польза(b) - польза(a));
    // Дом задания, которому рядом с базой места нет, ждёт войска: не заказываем, еда — на бойцов.
    // И строителей задания, пока войско слабое, — не больше одного: мест у базы на одного, а трое
    // строителей загона на Тирано/2 (зерно 7) встали друг другу поперёк и простояли в «строй»
    // до конца партии, пока леопарды не съели их всех — по 2500 еды за каждого.
    const строителейЗадания = конструкторы.filter(i => дальний(m.u8(UNITS + i + 0x59))).length;
    const можноСейчас = задания.filter(в2 => войскоГотово || (!строителейЗадания && рядом(в2).length));
    const домОхоты = с.планОхоты && !с.планОхоты.домЕсть && !(счёт(с.планОхоты.вид) > 0) ? [с.планОхоты.вид] : [];
    // Пока отряд не может охотиться (есть план охотников), дома задания ждут: еда — на охотников.
    let в = [...первые, ...домОхоты, ...(с.планОхоты ? [] : можноСейчас)][0];
    // Захват: армия пошла к Святилищу врага — заказываем конструктор захвата (вид 14, 2000 еды), если его нет.
    const захватчиков = конструкторы.filter(j => m.u8(UNITS + j + 0x59) === 14).length;
    let захватЗаказ = false;
    if (захватчиков) с.захватЗаказНа = null;                   // вышел из Святилища — заказ исполнен
    if (с.захват?.идём && !захватчиков && !первые.length && еда >= 2000 && с.захватЗаказНа == null) { в = 14; захватЗаказ = true; }
    else if (с.захватЗаказНа != null && m.u32(G.step) - с.захватЗаказНа > 2000) с.захватЗаказНа = null;   // не вышел за 2 минуты — можно снова
    let откуда = первые.length ? 'склад' : домОхоты.length ? 'охотники' : можноСейчас.length ? 'задание' : '';
    // 2) Слово мозга: он выбирает из того же меню.
    if (в === undefined && с.заказМозга !== null && с.заказМозга !== undefined) {
      const п = меню.find(п2 => п2.вид === с.заказМозга);
      // Дубликат по слову мозга ставим только если расчёт согласен, что домов не хватает:
      // владелец увидел, как ДЖЕВ поставил вторую оружейную при живой первой.
      const дубликат = п && п.есть > 0;
      if (п && п.хватает && (!дубликат || (экономика.нужен_ещё_дом && п.есть < ПРЕДЕЛ_ОДИНАКОВЫХ))) { в = п.вид; откуда = 'мозг'; }
      с.заказМозга = null;
    }
    // 3) ИЗЛИШЕК. Мозг молчит (или его нет), обязательное построено, а еды больше, чем полторы
    // цены дома, — ставим следующий дом сами: самый дешёвый из тех, которых ещё нет. Иначе казна
    // растёт, а племя не растёт вместе с ней.
    if (в === undefined && (экономика.нужен_ещё_дом || меню.some(п => п.вид !== 0 && п.есть === 0 && еда >= п.цена * ЗАПАС_НА_ДОМ))) {
      // Пока мозг молчит: берём дом, чей боец даёт больше урона на 1000 еды, а из равных — дешевле.
      const зверь = с.эталонЗверя || null;
      // ОДИНАКОВЫХ ДОМОВ НЕ ПЛОДИМ. Владелец про Koomba: «просто откуда-то взялось три барака,
      // хотя достаточно было одного». Второй дом того же вида имеет смысл только когда первый не
      // успевает тратить еду (экономика.нужен_ещё_дом) и одинаковых ещё меньше ПРЕДЕЛА; в остальных
      // случаях еда идёт в БОЙЦОВ, а не в стены.
      const можно = меню.filter(п => п.вид !== 0 && еда >= п.цена * ЗАПАС_НА_ДОМ
                                     && (п.есть === 0 || (экономика.нужен_ещё_дом && п.есть < ПРЕДЕЛ_ОДИНАКОВЫХ)))
        .map(п => {
          const лучший = (п.даёт || []).map(б => боевыеЦифры(б, зверь)).filter(Boolean)
                          .sort((a, b) => (b.заЕду || 0) - (a.заЕду || 0))[0];
          return { ...п, польза: лучший?.заЕду || 0 };
        })
        .sort((a, b) => (b.польза - a.польза) || (a.цена - b.цена));
      if (можно.length) { в = можно[0].вид; откуда = 'излишек'; }
    }
    if (в !== undefined && !занято && (захватЗаказ || еда >= (меню.find(п => п.вид === в)?.цена ?? ЦЕНА[в] ?? 0) + (в === 4 || в === 0 ? 0 : резерв))
        && m.u32(G.step) - с.заказаноНа > 18) {
      приказ(eng, святилище.н, 0x7f, в);
      if (захватЗаказ) с.захватЗаказНа = m.u32(G.step);
      (с.журналЗаказов ??= []).push(Math.round(m.u32(G.step) * 0.055) + 'с:' + в + ':' + откуда + ':надо' + надо.join('/'));
      с.заказаноНа = m.u32(G.step);
      заказ = в;
    }
  }

  // 3. ТРЕВОГА: кто ломает наши дома. Сам бой ведёт образец — он спросит это поле.
  //
  // ОБИДЧИК ДЕРЖИТСЯ ДО КОНЦА. Владелец: «если юнит атакует зданием, на него агрятся до тех пор,
  // пока тот не отойдёт сильно далеко — на ширину всего экрана от здания, которое было атаковано.
  // На момент агра мы не отвлекаемся на других, даже если они тоже атакуют здания. После убийства
  // переключаемся на следующего». Поэтому помним и обидчика, и ДОМ, который он бил: пока обидчик
  // жив и не ушёл дальше ЭКРАН клеток от того дома, новых не выбираем.
  let обидчик = 0;
  const прежний = с.обидчик;
  if (прежний && жив(m, прежний.кто) && далеко(кл(m, прежний.кто), прежний.где) <= ЭКРАН) {
    обидчик = прежний.кто;
  } else {
    с.обидчик = null;
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
      const т = m.u8(UNITS + i + U.TYPE);
      if (!ЗВЕРЬ(т) && (т >= 0x1a || m.u8(UNITS + i + U.OWNER) === мой)) continue;
      const ц = m.u32(UNITS + i + U.TARGET);
      if (!ц || m.u8(UNITS + ц + U.OWNER) !== мой || !ДОМ_ЛИ(m.u8(UNITS + ц + U.TYPE))) continue;
      if (!жив(m, i)) continue;
      обидчик = i; с.обидчик = { кто: i, где: кл(m, ц) }; break;
    }
  }
  с.тревога = обидчик;

  // ДАЛЬНЯЯ СТРОЙКА — её штаб прикрывает отрядом: строитель, которого ведём к площадке вдали от
  // базы, или наш дом, который там ещё строится (у недостроя жизни с нуля, пёс рушит его за
  // полминуты — замер Тирано/2, загон на (30,29) продержался 33 секунды).
  let площадка = null;
  const ждёт = с.ждётКонвоя;
  if (база && ждёт && конструкторы.includes(ждёт.строитель)) площадка = { x: ждёт.x, y: ждёт.y, строитель: ждёт.строитель };
  if (база && !площадка) {
    for (const i of конструкторы) {
      const т = с.застряли?.get(i)?.ведём;
      if (т && далеко(т, база) > ДАЛЬНЯЯ) { площадка = { x: т.x, y: т.y, строитель: i }; break; }
    }
    if (!площадка) for (const д of дома) {
      if (!д.стро) continue;
      const к = кл(m, д.н);
      if (далеко(к, база) > ДАЛЬНЯЯ) { площадка = { x: к.x, y: к.y, дом: д.н }; break; }
    }
  }

  return { домов: дома.length, надо: надо.slice(0, 4), конструкторов: конструкторы.length,
           посланы, заказ, тревога: обидчик, база, места: с.места, местаВид: с.местаВид,
           меню: с.меню, менюБойцов: с.менюБойцов, заказанБоец, еда, экономика: с.экономика,
           эталонЗверя: с.эталонЗверя, бойцов: бойцовЕсть, хватитНарода, домаЖдут,
           нашаСила, сильнейшийЧужой, надоСилы: Math.round(надоСилы), безоружных, безЩита,
           // Задание миссии нужно штабу: на «домашних» миссиях он держит отряд у стройки. Без этого
           // поля правило штаба не срабатывало никогда.
           задание: с.задание, площадка, сильных, войскоГотово,
           домаГде: дома.map(д => кл(m, д.н)) };
}
