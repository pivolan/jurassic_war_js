function отвестиОтДраки(eng, m, i, c, с) {
  const цель = m.u32(UNITS + i + U.TARGET);
  const звери = [];
  let угроза = !!цель && зверь(m, цель);
  for (let з = m.u32(G.unitHead); з; з = m.u32(UNITS + з + U.NEXT)) {
    if (!зверь(m, з)) continue;
    const к = кл(m, з), д = далеко(к, c);
    if (д <= 8) звери.push(к);
    // Угроза — только тот, кто нападает: держит строителя целью или стоит вплотную и дерётся. От мирно
    // стоящих рядом не бежим — бегство их и будило (Радумба/2: пёс в покое, строитель побежал, пёс за ним).
    const дерётся = (m.u8(UNITS + з + U.STATE) >> 4) === 1 || (m.u8(UNITS + з + U.STATE) & 0xf0) === 0x30 && m.u8(UNITS + з + U.STATE) !== 0x38;
    if (m.u32(UNITS + з + U.TARGET) === i || (д <= 1 && дерётся)) угроза = true;
  }
  const шаг = m.u32(G.step), б = (с.бегутОтДраки ??= new Map()), было = б.get(i);
  if (!угроза) { if (было && шаг - было.шаг < 18) return true; б.delete(i); return false; }
  // Убежать не выйдет (зверь быстрее), а жизни меньше 60% — строим дом прямо здесь: строитель сам
  // становится зданием, а у здания жизней много больше (Радумба/2: строителя догнал пёс на пути к
  // безопасному месту, на 21-й секунде). Место выберет движок рядом.
  // Строитель Святилища строится сразу, как только на него напали: без Святилища партии нет вовсе.
  if (m.u8(UNITS + i + 0x59) === 0 || m.u8(UNITS + i + U.HP) * 10 < m.u8(UNITS + i + U.HPMAX) * 6) {
    const бьют = [];
    for (let з = m.u32(G.unitHead); з; з = m.u32(UNITS + з + U.NEXT))
      if (зверь(m, з) && m.u32(UNITS + з + U.TARGET) === i && далеко(кл(m, з), c) <= 2) бьют.push(з);
    if (бьют.length && (!было || было.строй !== true || шаг - было.шаг > 36)) {
      приказ(eng, i, 0xe0, 0, c.x << 5, c.y << 5);
      б.set(i, { x: c.x, y: c.y, шаг, строй: true });
      return true;
    }
    if (было?.строй) return true;
  }
  let лучшее = null;
  for (let dy = -4; dy <= 4; dy++) for (let dx = -4; dx <= 4; dx++) {
    const x = c.x + dx, y = c.y + dy;
    if (!рельеф(m, x, y) || домаНаКлетках(m).has(x + y * 256)) continue;
    const мин = Math.min(99, ...звери.map(к => Math.hypot(к.x - x, к.y - y)));
    const оц = мин * 10 - Math.hypot(dx, dy);
    if (!лучшее || оц > лучшее.оц) лучшее = { x, y, оц };
  }
  if (!лучшее) return false;
  if (!было || было.x !== лучшее.x || было.y !== лучшее.y || шаг - было.шаг >= 18) {
    приказ(eng, i, 0x0f, 0, лучшее.x << 5, лучшее.y << 5);
    б.set(i, { x: лучшее.x, y: лучшее.y, шаг });
    с.послано.delete(i);                      // после бегства стройка даст приказ заново
  }
  return true;
}

/**
 * БЕЗОПАСНАЯ БАЗА (владелец, Масаи/2: «строитель мог бы выбрать безопасное место для строительства
 * сразу — там нет ни зверей, ни логовищ»). Опасность клетки — сумма по логовам карты: сила зверя
 * (жизни × атака) против простолюдина 30×20, на спад до нуля к 10 клеткам от его ВЫПАСА
 * (прямоугольник +0x55..0x58, а не только точка логова). Земли под дома должно хватать (в квадрате
 * 9×9 проходимо не меньше 40 клеток). Идти — по земле от старта, не дальше БАЗА_ДАЛЬ шагов. Если у
 * самого старта опасность меньше БАЗА_ТЕРПИМ (1 — примерно один простолюдин-зверь вплотную) — остаёмся;
 * переезжаем, только если опасность падает хотя бы вдвое.
 */
export function безопаснаяБаза(m, старт) {
  const логова = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || !ЗВЕРЬ(m.u8(UNITS + i + U.TYPE))) continue;
    логова.push({ x0: m.u8(UNITS + i + 0x55), y0: m.u8(UNITS + i + 0x56), x1: m.u8(UNITS + i + 0x57), y1: m.u8(UNITS + i + 0x58),
                  сила: m.u8(UNITS + i + U.HPMAX) * m.u8(UNITS + i + U.ATK) / 600 });
  }
  const опасность = (x, y) => { let о = 0;
    for (const л of логова) { const д = Math.max(л.x0 - x, x - л.x1, л.y0 - y, y - л.y1, 0); if (д < 10) о += л.сила * (1 - д / 10); }
    return о; };
  const оСтарта = опасность(старт.x, старт.y);
  if (оСтарта < БАЗА_ТЕРПИМ) return { ...старт, опасность: оСтарта, путь: 0, точки: [] };
  // Дорога тоже должна быть безопасной (Радумба/2: прямой путь к тихому месту шёл мимо логова пса —
  // строителя догнали на ходу). Дейкстра: шаг стоит 1 + опасность клетки × ОПАСНОСТЬ_ПУТИ.
  const W = m.u32(G.mapW), H = m.u32(G.mapH), ключ = (x, y) => x + y * 256;
  const цена = new Map([[ключ(старт.x, старт.y), 0]]), откуда = new Map(), шагов = new Map([[ключ(старт.x, старт.y), 0]]), пик = new Map([[ключ(старт.x, старт.y), 0]]);
  const оп = new Map(), опК = (k) => { let о = оп.get(k); if (о === undefined) { о = опасность(k % 256, k >> 8); оп.set(k, о); } return о; };
  const куча = [[0, ключ(старт.x, старт.y)]];
  const взять = () => { let и = 0; for (let j = 1; j < куча.length; j++) if (куча[j][0] < куча[и][0]) и = j; const r = куча[и]; куча[и] = куча[куча.length - 1]; куча.pop(); return r; };
  while (куча.length) {
    const [ц, k] = взять(); if (ц > цена.get(k)) continue;
    const a = k % 256, b = k >> 8, ш = шагов.get(k);
    if (ш >= БАЗА_ДАЛЬ) continue;
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const x = a + dx, y = b + dy;
      if ((!dx && !dy) || x < 0 || y < 0 || x >= W || y >= H || !рельеф(m, x, y)) continue;
      const н = ключ(x, y), нц = ц + Math.hypot(dx, dy) * (1 + опК(н) * ОПАСНОСТЬ_ПУТИ);
      if (нц < (цена.get(н) ?? Infinity)) { цена.set(н, нц); откуда.set(н, k); шагов.set(н, ш + 1); пик.set(н, Math.max(пик.get(k), ш >= 3 ? опК(н) : 0)); куча.push([нц, н]); } } }
  let лучшее = { ...старт, опасность: оСтарта, путь: 0, оц: оСтарта * 20 };
  for (const [k, ц] of цена) { const x = k % 256, y = k >> 8;
    if ((x + y) & 1) continue;
    // место: своя опасность, длина пути и самая опасная клетка пути (кроме первых шагов от старта — там опасно везде)
    const о = опК(k), оц = о * 20 + шагов.get(k) * 0.5 + пик.get(k) * 8;
    if (оц >= лучшее.оц) continue;
    let земли = 0; for (let yy = -4; yy <= 4; yy++) for (let xx = -4; xx <= 4; xx++) if (рельеф(m, x + xx, y + yy)) земли++;
    if (земли < 40) continue;
    лучшее = { x, y, опасность: о, путь: шагов.get(k), оц };
  }
  // точки пути — каждая 4-я клетка, от старта к базе
  const путь = []; for (let k = ключ(лучшее.x, лучшее.y); k !== undefined; k = откуда.get(k)) путь.push({ x: k % 256, y: k >> 8 });
  путь.reverse(); лучшее.точки = путь.filter((_, n) => n % 4 === 0 || n === путь.length - 1);
  // переезд того стоит, только если опасность падает хотя бы вдвое
  return лучшее.опасность <= оСтарта / 2 ? { ...лучшее, опасностьСтарта: оСтарта } : { ...старт, опасность: оСтарта, путь: 0, точки: [] };
}

/**
 * У СТЕНЫ — ОБЩЕЕ ПРАВИЛО ДЛЯ ЛЮБОЙ КАРТЫ (владелец про Тирано/2: «у края вполне можно построить,
 * мешать не будут»; потом — «сделай те правила универсальными, чтобы правильно распределять
 * строительство»). Зона базы — проходимые клетки, связные с центром базы, в квадрате радиуса
 * У_СТЕНЫ_Р. Выходы — клетки зоны на её краю, за которыми земля идёт дальше. Дом ставим так, чтобы:
 *   • все клетки дома — свободная земля зоны, не на самом логове зверя;
 *   • не лечь на ДОРОГУ — кратчайший путь от центра к каждому выходу шириной 3 клетки;
 *   • всё, что доходило до выходов, доходило и после (проход не рвётся).
 * Из годных — сильнее всего прижатую к стенам и домам, при равенстве ближе к центру.
 */
export function местоУСтены(m, вид, центр, лог, занятоЕщё = [], плохие = null, R = У_СТЕНЫ_Р) {
  const ключ = (x, y) => x + y * 256;
  const занято = new Set(занятоЕщё);
  for (const л of лог) занято.add(ключ(л.x, л.y));
  for (const k of домаНаКлетках(m)) занято.add(k);
  const вЗоне = new Set([ключ(центр.x, центр.y)]), оч = [[центр.x, центр.y]], родитель = new Map();
  for (let h = 0; h < оч.length; h++) { const [a, b] = оч[h];
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const x = a + dx, y = b + dy, k = ключ(x, y);
      if (вЗоне.has(k) || Math.max(Math.abs(x - центр.x), Math.abs(y - центр.y)) > R || !рельеф(m, x, y)) continue;
      вЗоне.add(k); родитель.set(k, ключ(a, b)); оч.push([x, y]); } }
  const выходы = [];
  for (const k of вЗоне) { const x = k % 256, y = k >> 8;
    if (Math.max(Math.abs(x - центр.x), Math.abs(y - центр.y)) !== R) continue;
    let наружу = false;
    for (let dy = -1; dy <= 1 && !наружу; dy++) for (let dx = -1; dx <= 1; dx++)
      if (Math.max(Math.abs(x + dx - центр.x), Math.abs(y + dy - центр.y)) > R && рельеф(m, x + dx, y + dy)) { наружу = true; break; }
    if (наружу) выходы.push(k); }
  // дорога: путь от центра к каждому выходу (кроме двух первых клеток у центра), расширенный на клетку
  // Выходы — сплошными участками (в чистом поле весь край зоны — один участок): дорога к середине
  // каждого участка, а не к каждой клетке края — иначе дороги закрывали всё вокруг центра.
  const участки = [], взят = new Set();
  for (const в of выходы) { if (взят.has(в)) continue;
    const уч = [в]; взят.add(в);
    for (let h = 0; h < уч.length; h++) for (const н of выходы)
      if (!взят.has(н) && Math.max(Math.abs(н % 256 - уч[h] % 256), Math.abs((н >> 8) - (уч[h] >> 8))) <= 1) { взят.add(н); уч.push(н); }
    участки.push(уч); }
  const дорога = new Set();
  for (const в of участки.map(уч => уч[уч.length >> 1])) { const путь = []; for (let k = в; k !== undefined; k = родитель.get(k)) путь.push(k);
    for (const k of путь.slice(0, Math.max(0, путь.length - 2)))
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) дорога.add(k + dx + dy * 256); }
  const свободна = (k, дом) => вЗоне.has(k) && !занято.has(k) && !дом.has(k);
  const доВыходов = (дом) => { const б = new Set(выходы.filter(k => свободна(k, дом))), о = [...б];
    while (о.length) { const k = о.pop(), a = k % 256, b = k >> 8;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const н = ключ(a + dx, b + dy);
        if (!б.has(н) && свободна(н, дом)) { б.add(н); о.push(н); } } }
    return б; };
  const до = доВыходов(new Set());
  // сколько шагов от клетки до ближнего выхода по земле зоны (глубина в базе)
  const путьДоВыхода = new Map(выходы.map(k => [k, 0])), о2 = [...выходы];
  for (let h = 0; h < о2.length; h++) { const k = о2[h], a = k % 256, b = k >> 8;
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const н = ключ(a + dx, b + dy);
      if (!путьДоВыхода.has(н) && вЗоне.has(н)) { путьДоВыхода.set(н, путьДоВыхода.get(k) + 1); о2.push(н); } } }
  const отп = отпечаток(m, вид);
  let лучшее = null;
  for (const k0 of вЗоне) { const x = k0 % 256, y = k0 >> 8;
    if (плохие?.has(k0)) continue;                              // тут движок строить не дал — следующее место
    const клетки = отп.map(({ dx, dy }) => ключ(x + dx, y + dy));
    if (!клетки.every(k => свободна(k, new Set()) && !дорога.has(k))) continue;
    const дом = new Set(клетки);
    const после = доВыходов(дом);
    if ([...до].some(k => !дом.has(k) && !после.has(k))) continue;
    let прижат = 0;
    for (const k of клетки) for (const d of [1, -1, 256, -256]) { const н = k + d;
      if (!дом.has(н) && (!рельеф(m, н % 256, н >> 8) || занято.has(н))) прижат++; }
    // у логова зверь рождается прямо у стены дома — штраф; даль от центра дорога (строителю и мясу ходить):
    // в чистом поле иначе уходили на край карты за 7 клеток ради «стены» — края карты
    const уЛогова = лог.filter(л => Math.max(Math.abs(л.x - x - 0.5), Math.abs(л.y - y - 0.5)) <= 2.5).length;
    // глубже в базе — лучше: дом у самого выхода встаёт на пути зверя, идущего внутрь (Тирано/2, браузер:
    // склад у устья моста — отряд погиб у моста; склад в глубине кармана — живы все)
    const доВыхода = Math.min(99, ...клетки.map(k => путьДоВыхода.get(k) ?? 99));
    const оц = прижат * 100 - Math.max(Math.abs(x - центр.x), Math.abs(y - центр.y)) * 60 - уЛогова * 150 + Math.min(доВыхода, 2 * R) * 60;
    if (!лучшее || оц > лучшее.оц) лучшее = { x, y, оц };
  }
  return лучшее && { x: лучшее.x, y: лучшее.y };
}

/**
 * МЕСТО В КАРМАНЕ (Тирано/2). Владелец: «у края справа вполне можно построить оба здания, мешать не
 * будут». Перебираем точки привязки в кармане (дом растёт вправо-вниз): все клетки дома — земля, не
 * дом, не логово и не устье моста (y ≥ 40); после постановки все свободные клетки кармана должны
 * по-прежнему доходить до моста (34,38). Из годных берём ту, что сильнее прижата к стене и домам,
 * при равенстве — правее и ниже.
 */
function местоВКармане(m, вид) {
  const К = Т2.КАРМАН, ключ = (x, y) => x + ',' + y;
  const занято = new Set(Т2.ЛОГОВА_КАРМАНА.map(л => ключ(л.x, л.y)));
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || m.u8(UNITS + i + U.TYPE) < 0x1a) continue;
    const x0 = m.u16(UNITS + i + U.X) >> 5, y0 = m.u16(UNITS + i + U.Y) >> 5;
    for (const { dx, dy } of отпечаток(m, m.u8(UNITS + i + U.TYPE) - 0x1a)) занято.add(ключ(x0 + dx, y0 + dy));
  }
  const земля = (x, y) => Т2.вКармане({ x, y }) && проходима(m, x, y);
  const свободна = (x, y, дом) => земля(x, y) && !занято.has(ключ(x, y)) && !дом.has(ключ(x, y));
  const отп = отпечаток(m, вид);
  const доМоста = (дом) => {
    const было = new Set([ключ(34, 38)]), оч = [[34, 38]];
    while (оч.length) { const [a, b] = оч.pop();
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const k = ключ(a + dx, b + dy);
        if (!было.has(k) && свободна(a + dx, b + dy, дом)) { было.add(k); оч.push([a + dx, b + dy]); } } }
    return было;
  };
  const доПостановки = доМоста(new Set());
  let лучшее = null;
  for (let y = 40; y <= К.y1; y++) for (let x = К.x0; x <= К.x1; x++) {
    const дом = new Set(отп.map(({ dx, dy }) => ключ(x + dx, y + dy)));
    if (!отп.every(({ dx, dy }) => свободна(x + dx, y + dy, new Set()))) continue;
    // связность: всё, что доходило до моста до постановки, должно доходить и после (8 соседей)
    const после = доМоста(дом);
    if ([...доПостановки].some(k => !дом.has(k) && !после.has(k))) continue;
    let прижат = 0;
    for (const { dx, dy } of отп) for (const [ex, ey] of [[1,0],[-1,0],[0,1],[0,-1]]) {
      const k = ключ(x + dx + ex, y + dy + ey); if (дом.has(k)) continue;
      if (!земля(x + dx + ex, y + dy + ey) || занято.has(k)) прижат++;
    }
    const оц = прижат * 100 + x * 2 + y;
    if (!лучшее || оц > лучшее.оц) лучшее = { x, y, оц };
  }
  return лучшее && { x: лучшее.x, y: лучшее.y };
}
