// ВОЖДЬ: компьютерный командующий на Haiku 5.5 + ДЖЕВ (владелец 08.10.2026).
//
// Вторая версия («не выбирать одну из четырёх кнопок, а командовать»): вождь сам делит войско на ОТРЯДЫ и
// даёт каждому ЗАДАЧУ и МЕСТО. Места называет движок — списком с короткими именами (наша база, пастбища, база
// врага, видимые группы врагов, стороны света для разведки); координат модель не видит (инструкция к jev:
// места только из списка). Исполняют готовые умения скриптового компьютера — уровень «комдива»
// (js/port/ai_script.js, вестиПоКомдиву): охота, дом, штурм, враг, отход, мясо, разведка, стоять.
//
//   • Haiku — раз в ТАКТ_ВОЖДЯ шагов (≈8 с игры; не больше одного запроса в полёте). В сводке: обстановка,
//     отряды (состав, здоровье, где стоят, что делают), места, ПАМЯТЬ — последние решения и что случилось после.
//   • ДЖЕВ — отбирает темы базы знаний под ситуацию (на сервере, RAG). Страховка отрядов им снята (08.10).
//   • Нет ответа или сервис молчит — отряды доигрывают последний приказ, а до первого приказа играет скрипт.
//
// Только для браузерной сцены ?duel=llm: решения приходят асинхронно, в локстеп они не годятся.
import { G, U, UNITS } from '../mem.js';
import { боеваяЦенность } from '../port/ai_script.js';

const ТАКТ_ВОЖДЯ = 150, ОТРЯДОВ = 4;
export const ЗАДАЧИ = ['охота', 'дом', 'штурм', 'враг', 'отход', 'мясо', 'разведка', 'стоять'];
const СТРОЙКА = ['ничего', 'склад', 'казарма', 'оружейная', 'военныйдом', 'ещёвоенный'];
const ПРОИЗВОДСТВО = ['ничего', 'рабочий', 'боец', 'строитель'];
const ИМЕНА_ДОМОВ = ['Святилище', 'казарма', 'оружейная', 'оружейная', 'склад', 'школа эльфов', 'школа волшебников',
  'школа колдунов', 'школа рейнджеров', 'загон рапторов', 'загон карнотавров', 'загон рамфоринхов', 'загон трицератопсов', 'загон дилофозавров'];
const ИМЯ = { 1: 'простолюдин', 2: 'силач', 3: 'воин', 5: 'эльф', 6: 'волшебник', 7: 'колдун', 8: 'рейнджер', 9: 'раптор', 10: 'карнотавр', 11: 'рамфоринх', 12: 'трицератопс', 13: 'дилофозавр' };

export function создать(цвет, адрес = '/jw/jev', подпись = '') {
  // имя партии для журнала на сервере (out/вождь/<партия>.jsonl)
  const партия = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14) + '_' + String(подпись).replace(/[^\w-]/g, '').slice(0, 30);
  return { цвет, адрес, партия, события: [], отряды: Array.from({ length: ОТРЯДОВ }, () => []), задачи: Array(ОТРЯДОВ).fill('охота'),
           куда: Array(ОТРЯДОВ).fill(null), новыхВ: 0, места: {}, приказ: null, ждёмВождя: false, вождьС: -1e9,
           журнал: [], ошибок: 0, вызовов: 0, джевВызовов: 0, мсВождя: 0, страховка: new Map(), былиБойцы: null,
           итогПрошлого: '' };
}

const жив = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.HP) > 0 && (m.u8(UNITS + i + U.STATE) & 0xf0) !== 0x60;
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
const рядом = (а, б) => Math.max(Math.abs(а.x - б.x), Math.abs(а.y - б.y));
// Сила — той же боевой мерой, что у скриптового компьютера (боеваяЦенность: урон в секунду с учётом защиты ×
// запас здоровья, в «стартовых бойцах»), с поправкой на текущее здоровье. Прежняя «здоровье × атака» не видела
// защиту врага: в журнале вождь с двумя бойцами против трёх читал «мы намного сильнее» и лез в бой.
function сила(m, список) { let s = 0; for (const i of список) s += боеваяЦенность(m, i) * (m.u8(UNITS + i + U.HP) / (m.u8(UNITS + i + U.HPMAX) || 1)); return s; }
function отношение(а, б) {
  if (!б) return а ? 'врага не видно' : 'никого';
  const r = а / б;
  if (r >= 2.5) return 'мы намного сильнее'; if (r >= 1.6) return 'мы примерно вдвое сильнее';
  if (r >= 1.15) return 'мы немного сильнее'; if (r > 0.87) return 'силы примерно равны';
  if (r > 0.6) return 'мы немного слабее'; if (r > 0.4) return 'мы примерно вдвое слабее'; return 'мы намного слабее';
}
function сторона(от, к) {
  const dx = к.x - от.x, dy = к.y - от.y, d = Math.max(Math.abs(dx), Math.abs(dy));
  if (d < 4) return 'прямо здесь';
  const у = Math.atan2(-dy, dx) * 180 / Math.PI;
  const ст = ['к востоку', 'к северо-востоку', 'к северу', 'к северо-западу', 'к западу', 'к юго-западу', 'к югу', 'к юго-востоку'][((Math.round(у / 45) % 8) + 8) % 8];
  return `${ст}, ${d < 20 ? 'близко' : d < 45 ? 'недалеко' : 'далеко'}`;
}
const центр = (m, сп) => { let x = 0, y = 0; for (const i of сп) { const п = кл(m, i); x += п.x; y += п.y; } return сп.length ? { x: Math.round(x / сп.length), y: Math.round(y / сп.length) } : null; };

/** Места, которые видит вождь: короткий id → { описание, точка }. Только из разведанного (о уже отфильтрован). */
function места(m, с, о) {
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const б = о.база || { x: W >> 1, y: H >> 1 };
  const м = {};
  const уБазы = о.база ? о.врагиВидимые.filter(е => рядом(кл(m, е), о.база) <= 12).length : 0;
  м.БАЗА = { описание: уБазы ? `наша база — ТАМ БОЙ, врагов ${уБазы}` : 'наша база', точка: б };
  if (с.вражБаза) м.ВРАГ_БАЗА = { описание: `база врага ${сторона(б, с.вражБаза)}`, точка: с.вражБаза };
  (с.пастбища || []).slice(0, 4).forEach((п, k) => {
    м['ПАСТБИЩЕ' + (k + 1)] = { описание: `пастбище ${сторона(б, п)}, зверей ${п.зверей || '?'}`, точка: { x: п.x, y: п.y } };
  });
  // видимые враги — грубые кучки по 10 клеток
  const кучки = [];
  for (const е of о.врагиВидимые) { const п = кл(m, е); const к = кучки.find(q => рядом(q.ц, п) <= 10); if (к) { к.сп.push(е); } else кучки.push({ ц: п, сп: [е] }); }
  кучки.sort((а, б2) => б2.сп.length - а.сп.length).slice(0, 3).forEach((к, k) => {
    const ц = центр(m, к.сп); м['ВРАГИ' + (k + 1)] = { описание: `враги ${сторона(б, ц)}: ${к.сп.length} бойцов`, точка: ц };
  });
  const края = { СЕВЕР: { x: W >> 1, y: 3 }, ЮГ: { x: W >> 1, y: H - 4 }, ЗАПАД: { x: 3, y: H >> 1 }, ВОСТОК: { x: W - 4, y: H >> 1 }, ЦЕНТР: { x: W >> 1, y: H >> 1 } };
  for (const [к, т] of Object.entries(края)) м[к] = { описание: `край карты: ${к.toLowerCase()} (для разведки)`, точка: т };
  return м;
}

/** Держим отряды постоянными: мёртвых убираем, новых бойцов — в отряд «куда новых». */
function обновитьОтряды(m, в, свои) {
  const есть = new Set(свои);
  for (let g = 0; g < ОТРЯДОВ; g++) в.отряды[g] = в.отряды[g].filter(i => есть.has(i) && жив(m, i));
  const заняты = new Set(в.отряды.flat());
  for (const i of свои) if (!заняты.has(i)) в.отряды[в.новыхВ].push(i);
}
/** Перекинуть бойцов под нужные численности: лишних забираем из отрядов, у которых сверх нормы. */
function переделить(m, в, сколько) {
  const надо = сколько.map(n => Math.max(0, n | 0));
  const лишние = [];
  for (let g = 0; g < ОТРЯДОВ; g++) while (в.отряды[g].length > надо[g]) лишние.push(в.отряды[g].pop());
  for (let g = 0; g < ОТРЯДОВ && лишние.length; g++) while (в.отряды[g].length < надо[g] && лишние.length) в.отряды[g].push(лишние.pop());
  for (const i of лишние) в.отряды[в.новыхВ].push(i);
}

function сводка(eng, с, о, в, свои) {
  const m = eng.m, шаг = m.u32(G.step);
  const наша = сила(m, свои), ихВидно = сила(m, о.врагиВидимые);
  const б = о.база;
  const уБазы = б ? о.врагиВидимые.filter(е => рядом(кл(m, е), б) <= 12).length : 0;
  const дома = []; for (const [вид, n] of о.домаГотовых || []) дома.push(`${ИМЕНА_ДОМОВ[вид] || 'дом'}${n > 1 ? ' ×' + n : ''}`);
  const сейчас = new Set(свои);
  const потеряно = в.былиБойцы ? [...в.былиБойцы].filter(i => !сейчас.has(i)).length : 0;
  в.былиБойцы = сейчас;
  const отряды = в.отряды.map((сп, g) => {
    if (!сп.length) return `${g + 1}: пусто`;
    const типы = new Map(); for (const i of сп) { const т = m.u8(UNITS + i + U.TYPE); типы.set(т, (типы.get(т) || 0) + 1); }
    let hp = 0, hpm = 0; for (const i of сп) { hp += m.u8(UNITS + i + U.HP); hpm += m.u8(UNITS + i + U.HPMAX) || 1; }
    const ц = центр(m, сп);
    const рядомВраги = о.врагиВидимые.filter(е => рядом(кл(m, е), ц) <= 8).length;
    return `${g + 1}: ${[...типы].map(([т, n]) => `${ИМЯ[т] || 'боец'} ×${n}`).join(', ')}; здоровье ${Math.round(100 * hp / hpm)}%; ` +
           `${б ? сторона(б, ц) + ' от базы' : ''}; задача «${в.задачи[g]}»${в.куда[g] ? ' → ' + в.куда[g] : ''}${рядомВраги ? `; рядом враги: ${рядомВраги}` : ''}`;
  });
  const м = места(m, с, о); в.места = м;
  const признаки = [];
  if (уБазы) признаки.push('оборона', 'база', 'святилище');
  if (о.еда < 800) признаки.push('еда', 'мясо', 'экономика');
  if (!о.склад) признаки.push('склад', 'еда', 'стройка');
  if (свои.length < 4) признаки.push('армия', 'казарма', 'бойцы');
  if (потеряно >= 2) признаки.push('потери', 'бой', 'отход');
  if (!о.врагиВидимые.length && !с.вражБаза) признаки.push('разведка');
  if (о.врагиВидимые.length && наша > ихВидно * 1.5) признаки.push('атака', 'снос');
  if (о.звери.length) признаки.push('звери', 'охота', 'прокачка');
  const минута = Math.floor(шаг / 1080);
  признаки.push(минута < 4 ? 'начало' : минута < 12 ? 'середина' : 'конец');
  в.признаки = признаки;
  return {
    время: `${минута}:${String(Math.floor(шаг / 18) % 60).padStart(2, '0')}`,
    еда: `${о.еда} (${о.еда >= 3000 ? 'хватает на дом или несколько бойцов' : о.еда >= 800 ? 'на бойца-другого' : 'почти нет'})`,
    склад: о.склад ? 'есть' : 'НЕТ — мясо некуда сдавать',
    наши_дома: дома.join(', ') || 'нет домов',
    рабочие_и_строители: `${о.рабочие.length} рабочих, ${о.строители.length} строителей`,
    бойцов_всего: свои.length, потеряли_бойцов_за_прошлый_ход: потеряно,
    враг: о.врагиВидимые.length ? `видно ${о.врагиВидимые.length} бойцов; ${отношение(наша, ихВидно)}` : 'вражеских бойцов не видно',
    дома_врага: о.вражДомаВидимые.length ? `видно ${о.вражДомаВидимые.length}` : (с.вражБаза ? 'видели раньше, знаем где' : 'не найдены'),
    у_нашей_базы: уБазы ? `ВРАГИ У БАЗЫ: ${уБазы} (отход к базе = отход в бой)` : 'спокойно',
    отряды, новые_бойцы_идут_в_отряд: в.новыхВ + 1,
    места: Object.fromEntries(Object.entries(м).map(([к, з]) => [к, з.описание])),
    прошлые_решения: в.журнал.slice(0, 4).map(ж => `${ж.время}: ${ж.замысел} — ${ж.кратко}`),
    что_вышло_с_прошлого_решения: в.итогПрошлого || 'первое решение',
  };
}

async function запрос(адрес, тело) {
  const о = await fetch(адрес, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(тело) });
  return о.json();
}

/** Принять ответ вождя: задачи и места отрядов, переделка, стройка, заказ. */
function принять(m, с, в, а, шаг, время) {
  const кратко = [];
  const сколько = в.отряды.map(сп => сп.length); let делим = false;
  for (const п of Array.isArray(а.отряды) ? а.отряды : []) {
    const g = (п.номер | 0) - 1; if (g < 0 || g >= ОТРЯДОВ) continue;
    if (ЗАДАЧИ.includes(п.задача)) в.задачи[g] = п.задача;
    в.куда[g] = п.куда && в.места[п.куда] ? п.куда : null;
    if (Number.isFinite(+п.сколько) && +п.сколько >= 0) { сколько[g] = +п.сколько; делим = true; }
    кратко.push(`${g + 1}:${в.задачи[g]}${в.куда[g] ? '→' + в.куда[g] : ''}`);
  }
  if (делим) переделить(m, в, сколько);
  if (Number.isFinite(+а.новых_в) && +а.новых_в >= 1 && +а.новых_в <= ОТРЯДОВ) в.новыхВ = (+а.новых_в) - 1;
  в.стройка = СТРОЙКА.includes(а.стройка) ? а.стройка : 'ничего';
  в.производство = ПРОИЗВОДСТВО.includes(а.производство) ? а.производство : 'ничего';
  в.страховка.clear();
  в.приказ = { замысел: String(а.замысел || '').slice(0, 70), реплика: String(а.реплика || '').slice(0, 100),
               почему: String(а.почему || '').slice(0, 200), шаг, время, кратко: кратко.join(' ') };
  в.журнал.unshift({ ...в.приказ }); в.журнал.length = Math.min(в.журнал.length, 12);
}

/**
 * Такт командования: держим отряды и раз в ТАКТ_ВОЖДЯ спрашиваем вождя.
 * Ставит с.комдивГруппы / с.комдивЗадачи / с.комдивЦели / с.хочетПроизводство / с.комдивСтройка.
 */
export function командовать(eng, с, о, свои) {
  const в = с.вождь, m = eng.m, шаг = m.u32(G.step);
  обновитьОтряды(m, в, свои);
  if (!в.ждёмВождя && шаг - в.вождьС >= ТАКТ_ВОЖДЯ) {
    в.ждёмВождя = true; в.вождьС = шаг; в.вызовов++;
    // что вышло с прошлого решения — словами, для последовательности
    if (в.приказ) {
      const было = в.снимок || {}; const наша = сила(m, свои);
      в.итогПрошлого = `бойцов было ${было.бойцов ?? '?'}, стало ${свои.length}; еда ${было.еда ?? '?'} → ${о.еда}; ` +
        `наша сила ${наша > (было.сила || 0) * 1.1 ? 'выросла' : наша < (было.сила || 0) * 0.9 ? 'упала' : 'та же'}`;
    }
    let домов = 0; for (const [, n] of о.домаN || []) домов += n;
    if (в.приказ && (в.снимок?.домов ?? домов) > домов) в.итогПрошлого += `; ПОТЕРЯЛИ ДОМОВ: ${в.снимок.домов - домов}`;
    в.снимок = { бойцов: свои.length, еда: о.еда, сила: сила(m, свои), домов };
    const св = сводка(eng, с, о, в, свои); в.последняяСводка = св;
    const время = св.время;
    const события = в.события.splice(0);              // что было между решениями
    запрос(в.адрес + '/llm', { сводка: св, признаки: в.признаки || [], партия: в.партия, события }).then(r => {
      в.ждёмВождя = false; в.мсВождя = r.мс || 0;
      if (r.ответ) { принять(m, с, в, r.ответ, шаг, время); в.приказ.темы = r.темы || []; в.приказ.мсОтбора = r.мсОтбора || 0; }
      else в.ошибок++;
    }).catch(() => { в.ждёмВождя = false; в.ошибок++; });
  }
  // Страховки ДЖЕВом больше нет (владелец 08.10: убрать) — в журнале она отвечала «отходить 0%» тающему отряду.
  // итог для исполнителя
  с.комдивГруппы = в.отряды;
  с.комдивЗадачи = в.задачи.slice();
  с.комдивЦели = в.куда.map(id => (id && в.места[id] ? в.места[id].точка : null));
  с.хочетПроизводство = !в.производство || в.производство === 'ничего' ? null : в.производство;
  с.комдивСтройка = в.стройка || 'ничего';
}
