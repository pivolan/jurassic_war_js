// Комдив (наше): ОДНА самостоятельная сеть, которая командует всем войском сразу.
//
// Замысел владельца дословно: «хочу одну нейронную сеть, которая не будет зависеть от других
// нейронок; она может быть сложной, из разных слоёв; тренировать её эволюционно, тупо за счёт
// огромного количества прогонов и случайного изменения весов; всё остальное пусть отрабатывает
// скриптово, чтобы можно было очень быстро всё загонять».
//
// Поэтому здесь ровно один мозг и никаких других. Ни боец (js/ai/net.js), ни тактик
// (js/ai/tactic.js), ни стратег (js/ai/strategy.js) в партии не участвуют: юнитами как управлял
// скриптовый конечный автомат, так и управляет. Сеть говорит только, ЧТО делает каждая группа и
// что строить с кем заказывать, — то есть занимает место командующего, а не место рук.
//
// Устройство. Два скрытых слоя (сложнее одного — по просьбе владельца; глубже пока незачем,
// эволюция тем труднее, чем больше весов):
//     вход 48 → 48 (ReLU) → 32 (ReLU) → 42 логита
// Выход разбит на независимые головы, каждая своим argmax:
//     4 группы × 8 задач = 32   — что делает каждая боевая группа;
//     6                          — что строить следующим;
//     4                          — кого заказывать в домах.
//
// Почему argmax, а не выбор по вероятности: в сетевой партии решение обязано быть однозначным,
// иначе локстеп у игроков разъедется.
//
// Признаки честные: всё берётся из `осмотр()` скриптового штаба, где чужие юниты и дома уже
// отфильтрованы по разведанному. Из-под тумана сеть не видит ничего.
import { U, UNITS } from '../mem.js';
import { наблюдать as сводка, ВХОД as СВОДКА } from './strategy.js';

/** Что может делать боевая группа. Каждая задача — уже написанное скриптовое умение. */
export const ЗАДАЧИ = ['охота', 'дом', 'штурм', 'враг', 'отход', 'мясо', 'разведка', 'стоять'];
export const ГРУПП = 4;                                   // на столько частей делится войско
export const СТРОЙКА = ['ничего', 'склад', 'казарма', 'оружейная', 'военныйдом', 'ещёвоенный'];
export const ПРОИЗВОДСТВО = ['ничего', 'рабочий', 'боец', 'строитель'];

// Вход: общая сводка (та же, по которой играет штаб) плюс по четыре числа на каждую группу.
export const НА_ГРУППУ = 4;
export const ВХОД = СВОДКА + ГРУПП * НА_ГРУППУ;           // 32 + 16 = 48
export const СЛОЙ1 = 48, СЛОЙ2 = 32;
export const ВЫХОД = ГРУПП * ЗАДАЧИ.length + СТРОЙКА.length + ПРОИЗВОДСТВО.length;   // 32 + 6 + 4 = 42

const зажать = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

/**
 * Признаки. Первые 32 — общая сводка штаба, дальше по группам: сколько в ней бойцов, какова её
 * сила, насколько она цела и далеко ли от дома. Больше группе знать не нужно: остальное она
 * добирает сама, когда ей поставили задачу.
 * @param группы массив массивов id бойцов (см. `разбить`).
 */
export function наблюдать(eng, с, о, группы, вых = new Float32Array(ВХОД)) {
  const m = eng.m;
  вых.fill(0);
  сводка(eng, с, о, вых.subarray(0, СВОДКА));
  const б = о.база;
  for (let g = 0; g < ГРУПП; g++) {
    const гр = группы[g] || [];
    let сила = 0, целых = 0, дальше = 0;
    for (const i of гр) {
      сила += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.HPMAX);
      const hp = m.u8(UNITS + i + U.HP), hpm = m.u8(UNITS + i + U.HPMAX) || 1;
      целых += hp / hpm;
      if (б) {
        const x = (m.u16(UNITS + i + U.X) >> 5) - б.x, y = (m.u16(UNITS + i + U.Y) >> 5) - б.y;
        дальше = Math.max(дальше, Math.max(Math.abs(x), Math.abs(y)));
      }
    }
    const п = СВОДКА + g * НА_ГРУППУ;
    вых[п] = зажать(гр.length / 20);
    вых[п + 1] = зажать(сила / 4000);
    вых[п + 2] = гр.length ? зажать(целых / гр.length) : 0;
    вых[п + 3] = зажать(дальше / 100);
  }
  return вых;
}

/** Случайные веса. Сида хватает, чтобы повторить любую особь: эволюции нужна воспроизводимость. */
export function случайная(сид = 1) {
  let s0 = сид >>> 0 || 1;
  const сл = () => { s0 = (s0 * 1103515245 + 12345) & 0x7fffffff; return s0 / 0x80000000 * 2 - 1; };
  const дай = (n, вх, вых2) => { const a = new Float32Array(n); const м = Math.sqrt(6 / (вх + вых2)); for (let i = 0; i < n; i++) a[i] = сл() * м; return a; };
  return {
    w1: дай(СЛОЙ1 * ВХОД, ВХОД, СЛОЙ1), b1: new Float32Array(СЛОЙ1),
    w2: дай(СЛОЙ2 * СЛОЙ1, СЛОЙ1, СЛОЙ2), b2: new Float32Array(СЛОЙ2),
    w3: дай(ВЫХОД * СЛОЙ2, СЛОЙ2, ВЫХОД), b3: new Float32Array(ВЫХОД),
  };
}
/** Пустая сеть: все веса нули. Это «всегда первая задача каждой группе» — осмысленная точка
 *  отсчёта, с которой честно сравнивать обученную. */
export const пустая = () => ({
  w1: new Float32Array(СЛОЙ1 * ВХОД), b1: new Float32Array(СЛОЙ1),
  w2: new Float32Array(СЛОЙ2 * СЛОЙ1), b2: new Float32Array(СЛОЙ2),
  w3: new Float32Array(ВЫХОД * СЛОЙ2), b3: new Float32Array(ВЫХОД),
});

const слой = (w, b, вх, n, m2, вых, relu) => {
  for (let o = 0; o < n; o++) {
    let s = b[o]; const база = o * m2;
    for (let i = 0; i < m2; i++) s += w[база + i] * вх[i];
    вых[o] = relu ? (s > 0 ? s : 0) : s;
  }
  return вых;
};

/** Прямой проход: 48 → 48 → 32 → 42. */
export function прогон(сеть, вх, п = прогон.буфер ??= { h1: new Float32Array(СЛОЙ1), h2: new Float32Array(СЛОЙ2), y: new Float32Array(ВЫХОД) }) {
  слой(сеть.w1, сеть.b1, вх, СЛОЙ1, ВХОД, п.h1, true);
  слой(сеть.w2, сеть.b2, п.h1, СЛОЙ2, СЛОЙ1, п.h2, true);
  слой(сеть.w3, сеть.b3, п.h2, ВЫХОД, СЛОЙ2, п.y, false);
  return п.y;
}

const лучший = (в, от, до) => { let k = от; for (let i = от + 1; i < до; i++) if (в[i] > в[k]) k = i; return k - от; };

/**
 * Решение командующего: задача каждой группе, что строить и кого заказывать.
 * @returns {задачи: string[], стройка: string, производство: string}
 */
export function решение(сеть, вх) {
  const в = прогон(сеть, вх);
  const задачи = [];
  let п = 0;
  for (let g = 0; g < ГРУПП; g++) { задачи.push(ЗАДАЧИ[лучший(в, п, п + ЗАДАЧИ.length)]); п += ЗАДАЧИ.length; }
  const стройка = СТРОЙКА[лучший(в, п, п + СТРОЙКА.length)]; п += СТРОЙКА.length;
  const производство = ПРОИЗВОДСТВО[лучший(в, п, п + ПРОИЗВОДСТВО.length)];
  return { задачи, стройка, производство };
}

/**
 * Разбить войско на группы. Делим по силе «змейкой» (сильнейший в первую, следующий во вторую и
 * так далее, потом обратно) — так группы получаются сопоставимыми, и сеть управляет четырьмя
 * сравнимыми кулаками, а не одним большим и тремя огрызками.
 */
export function разбить(m, бойцы, сила) {
  const с2 = [...бойцы].sort((a, b) => сила(b) - сила(a) || a - b);
  const группы = Array.from({ length: ГРУПП }, () => []);
  let g = 0, шаг = 1;
  for (const i of с2) {
    группы[g].push(i);
    g += шаг;
    if (g === ГРУПП) { g = ГРУПП - 1; шаг = -1; } else if (g < 0) { g = 0; шаг = 1; }
  }
  return группы;
}

export function вЗапись(сеть) {
  return { вид: 'комдив', вход: ВХОД, слои: [СЛОЙ1, СЛОЙ2], выход: ВЫХОД, групп: ГРУПП, задачи: ЗАДАЧИ,
           w1: [...сеть.w1], b1: [...сеть.b1], w2: [...сеть.w2], b2: [...сеть.b2], w3: [...сеть.w3], b3: [...сеть.b3] };
}
export function изЗаписи(з) {
  const f = (a) => Float32Array.from(a || []);
  return { w1: f(з.w1), b1: f(з.b1), w2: f(з.w2), b2: f(з.b2), w3: f(з.w3), b3: f(з.b3) };
}
