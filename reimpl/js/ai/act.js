// Чего стоит вражеская постройка. Не по здоровью, а по тому, что она даёт противнику: Святилище
// строит строителей (а значит и все дома), склад держит еду — единственный ресурс игры, казармы и
// школы дают поток бойцов, оружейная лишь доснаряжает готовых. Те же числа в награде за партии
// (tools/ai_game_rollout.mjs): цель и плата должны совпадать, иначе сеть учится не тому.
export const ЦЕНА_ДОМА = {
  0x1a: 1.0, 0x1e: 0.9, 0x1b: 0.7,
  0x1f: 0.7, 0x20: 0.7, 0x21: 0.7, 0x22: 0.7,
  0x23: 0.7, 0x24: 0.7, 0x25: 0.7, 0x26: 0.7, 0x27: 0.7,
  0x1c: 0.4, 0x1d: 0.4,
};
/** Чего стоит эта постройка (см. ЦЕНА_ДОМА); неизвестный тип — половина. */
export const ценаДома = (т) => ЦЕНА_ДОМА[т] ?? 0.5;

// ---------------------------------------------------------------- разбор обстановки
// Живой — не спрятан, здоровье больше нуля И состояние не 0x6x: умирающий юнит (0x6f → 0x60,
// обработчик 0x1886e держит его в списке ещё несколько тиков, а у зверей в 0x6x здоровье не
// обнулено вовсе) — уже труп, бить его бесполезно, целью и врагом он быть не должен.
export const жив = (m, i) => !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.HP) > 0
                             && (m.u8(UNITS + i + U.STATE) & 0xf0) !== 0x60;
/** Клетка юнита ({x, y} в тайлах). */
export const клетка = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });

const TILE_INF = 0x3183c;
/** Проходима ли клетка для ходьбы: внутри карты, тайл проходим, украшения (дерева) нет. Юниты не
 *  учитываются — они двигаются, а стоящих обойдёт автомат движка. */
export function проходима(m, x, y) {
  if (x < 0 || y < 0 || x >= m.u32(G.mapW) || y >= m.u32(G.mapH)) return false;
  const слово = m.u16(BG + (y << 9) + x * 2);
  return !(слово & 0xf800) && (m.b[TILE_INF + (слово & 0x7ff)] & 1) === 1;
}
/** Сколько клеток подряд проходимо от (x,y) в сторону (dx,dy), не считая саму клетку, до макс. */
export function луч(m, x, y, dx, dy, макс = ШАГ) {
  let n = 0;
  while (n < макс && проходима(m, x + dx * (n + 1), y + dy * (n + 1))) n++;
  return n;
}

/** Живые чужие юниты (не здания) в квадрате радиуса R вокруг бойца. */
export function враги(eng, боец, R = 7) {
  const m = eng.m, мой = m.u8(UNITS + боец + U.OWNER);
  const c = клетка(m, боец), список = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (i === боец || !жив(m, i)) continue;
    const t = m.u8(UNITS + i + U.TYPE);
    if (t >= 0x1a) continue;                          // здания — отдельно
    // Ядовитые растения (24 и 25) — не противник, а местность. Бить их бессмысленно: они
    // отрастают на том же месте (js/port/combat.js, 0x1d12e), а пока их бьёшь, стоишь в их
    // облаке и теряешь по единице здоровья за тик. В замере первой миссии Masai на ЛЁГКОЙ
    // сложности всё племя из четверых полегло у одного такого цветка за шестьсот шагов.
    if (t === 24 || t === 25) continue;
    if (m.u8(UNITS + i + U.OWNER) === мой) continue;
    const p = клетка(m, i);
    const dx = p.x - c.x, dy = p.y - c.y;
    if (Math.abs(dx) > R || Math.abs(dy) > R) continue;
    const цель = m.u32(UNITS + i + U.TARGET);
    список.push({ i, x: p.x, y: p.y, dx, dy, d: Math.max(Math.abs(dx), Math.abs(dy)),
                  hp: m.u8(UNITS + i + U.HP), доля: m.u8(UNITS + i + U.HP) / (m.u8(UNITS + i + U.HPMAX) || 1), тип: t,
                  маг: t >= 5 && t <= 8, мана: m.u8(UNITS + i + U.MANA), цель,
                  бьётСвоего: !!цель && цель !== боец && жив(m, цель) && m.u8(UNITS + цель + U.OWNER) === мой && m.u8(UNITS + цель + U.TYPE) < 0x1a });
  }
  return список;
}

/**
 * Вражеские постройки в окне бойца, самые ценные первыми (при равной цене — ближние).
 * Отдельно от враги(): там здания нарочно отброшены, они не участвуют в оценке угрозы и в магии.
 */
export function дома(eng, боец, R = 7) {
  const m = eng.m, мой = m.u8(UNITS + боец + U.OWNER);
  const c = клетка(m, боец), список = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (!жив(m, i)) continue;
    const t = m.u8(UNITS + i + U.TYPE); if (t < 0x1a) continue;
    if (m.u8(UNITS + i + U.OWNER) === мой) continue;
    const p = клетка(m, i);
    const dx = p.x - c.x, dy = p.y - c.y;
    if (Math.abs(dx) > R || Math.abs(dy) > R) continue;
    список.push({ i, x: p.x, y: p.y, dx, dy, d: Math.max(Math.abs(dx), Math.abs(dy)),
                  тип: t, цена: ценаДома(t), доля: m.u8(UNITS + i + U.HP) / (m.u8(UNITS + i + U.HPMAX) || 1) });
  }
  список.sort((a, b) => (b.цена - a.цена) || (a.d - b.d) || (a.i - b.i));
  return список;
}

/** Предметы на земле (список 0x31b7c), ближние первыми. По умолчанию — по всей карте: приказ
 *  «подобрать» — макро вроде «к цели», юнит сам дойдёт; в наблюдение попадают только те, что в окне. */
export function предметы(eng, боец, R = 255) {
  const m = eng.m, c = клетка(m, боец), список = [];
  for (let i = m.u32(0x31b7c); i; i = m.u32(ITEMS + i + 0xc)) {
    const x = m.u8(ITEMS + i + 1), y = m.u8(ITEMS + i + 2);
    const d = Math.max(Math.abs(x - c.x), Math.abs(y - c.y));
    if (d <= R) список.push({ i, x, y, d, тип: m.u8(ITEMS + i), кол: m.u16(ITEMS + i + 6) });
  }
  return список.sort((a, b) => a.d - b.d || a.i - b.i);
}

/**
 * Куда отходить от угрозы: веер кандидатов (8 направлений × дистанции ШАГ..1), каждый — конец
 * проходимого луча. Оценка: минимальная дистанция до ближайшего врага после хода (главное),
 * средняя дистанция до всех, штраф за край карты и за тупик (мало свободных лучей из точки:
 * из угла дальше не уйти). Раньше «отойти» было одним вектором от центра масс врагов, и у стены
 * или края карты давало приказ «идти в свою же клетку» — боец стоял и получал урон.
 */
export function кудаОтойти(m, c, в, любойЦеной = false) {
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  let лучший = null;
  const оценка = (x, y) => {
    let мин = Infinity, сум = 0;
    for (const е of в) { const d = Math.max(Math.abs(е.x - x), Math.abs(е.y - y)); if (d < мин) мин = d; сум += d; }
    const край = Math.min(x, y, W - 1 - x, H - 1 - y);
    let выходы = 0;
    for (const [dx, dy] of НАПРАВЛЕНИЯ) if (луч(m, x, y, dx, dy, 2) >= 2) выходы++;
    return П.отход_вес_ближний * Math.min(мин, 8) + сум / в.length - (край < 2 ? П.отход_штраф_край * (2 - край) : 0) - (выходы < 3 ? П.отход_штраф_тупик : 0) + выходы * П.отход_премия_выходы;
  };
  const своя = оценка(c.x, c.y);
  for (const [dx, dy] of НАПРАВЛЕНИЯ) {
    const n = луч(m, c.x, c.y, dx, dy);
    for (let k = n; k >= 1; k--) {
      const x = c.x + dx * k, y = c.y + dy * k;
      const о = оценка(x, y) + k * 0.05;          // при равной оценке — дальше
      if (!лучший || о > лучший.о) лучший = { x, y, о };
    }
  }
  // `любойЦеной` (строитель): любая проходимая клетка лучше, чем остаться и драться —
  // хоть вдоль стены, хоть мимо врага.
  return лучший && (любойЦеной || лучший.о > своя - 0.5) ? { x: лучший.x, y: лучший.y } : null;
}

// ---------------------------------------------------------------- дальний бой и оценка силы
const RNG = [64, 96, 128, 160, 192, 224, 256, 288];      // 0x3055e, по SPD>>5 (combat-spec §3)
/** Дальность атаки в клетках по центрам (0 — ближний бой): маги 5–8 всегда стреляют, дилофозавр
 *  (13) — 64 px, люди 1–4 — только с луком/бумерангом (в арене оружия нет). */
export function дальность(m, i) {
  const t = m.u8(UNITS + i + U.TYPE), spd = m.u8(UNITS + i + U.SPD);
  let R = -1;
  if (t >= 5 && t <= 8) R = RNG[Math.min(7, spd >> 5)];
  else if (t === 13) R = 64;
  else if (t >= 1 && t <= 4) {
    const w = m.u8(UNITS + i + U.WEAPON);
    if (w !== 0xff) { const id = m.u8(UNITS + i + U.INV + w); if (id === 4) R = RNG[Math.min(7, spd >> 6)]; else if (id >= 5 && id <= 7) R = RNG[Math.min(7, spd >> 5)]; }
  }
  return R < 0 ? 0 : (R >> 5) + 1;                        // 64 px → 3 клетки, 96 → 4
}
/** Урон за удар по формуле 0x1e934 без оружия и щита (в арене их нет), и удары в шаг с учётом
 *  перезарядки 16 − SPD>>4 (combat-spec). */
export const урон = (atk, def) => (Math.max(atk - def, 0) >> 4) + (atk >> 5) + 1;
/** Доля клетки за тик при такой скорости: по ней считается, успеет ли враг подойти. */
// Удары за шаг: человек (тип < 9) раз в 8 шагов, ящер и зверь раз в 6 — по замеру, от скорости не
// зависит (см. справочник.тиковНаУдар). Раньше тут стояла пауза после подхода, 16 − SPD>>4.
const темпТипа = (тип) => 1 / (тип < 9 ? 8 : 6);
/**
 * Оценка обмена: сколько шагов мне (и союзникам в окне) убивать врагов против того, сколько им
 * убивать меня. >1 — обмен против меня; 2 и выше — драться бессмысленно.
 * @returns {ближний, общий} — с ближайшим врагом один на один и со всеми в окне разом.
 */
export function обмен(m, я, в, союзники = []) {
  if (!в.length) return { ближний: 0, общий: 0 };
  const мойHP = m.u8(UNITS + я + U.HP), мойATK = m.u8(UNITS + я + U.ATK), мойDEF = m.u8(UNITS + я + U.DEF), мойSPD = m.u8(UNITS + я + U.SPD);
  const шаговМне = (е) => е.hp / (урон(мойATK, m.u8(UNITS + е.i + U.DEF)) * темпТипа(m.u8(UNITS + я + U.TYPE)));
  const уронМне = (е) => урон(m.u8(UNITS + е.i + U.ATK), мойDEF) * темпТипа(m.u8(UNITS + е.i + U.TYPE));
  const ближ = в.reduce((a, b) => a.d < b.d ? a : b);
  const ближний = шаговМне(ближ) / (мойHP / уронМне(ближ));
  let нашУрон = урон(мойATK, 0) * темпТипа(m.u8(UNITS + я + U.TYPE));            // грубо: урон стороны по «среднему» DEF врага
  let hpВрагов = 0, уронВрагов = 0, средDEF = 0;
  for (const е of в) { hpВрагов += е.hp; уронВрагов += уронМне(е); средDEF += m.u8(UNITS + е.i + U.DEF); }
  средDEF /= в.length;
  нашУрон = урон(мойATK, средDEF) * темпТипа(m.u8(UNITS + я + U.TYPE));
  // Сторона — это я и союзники в окне: их здоровье тоже надо выбить, иначе в отряде «три на
  // три» каждый считал бы обмен один против троих и убегал (так и было у учителя).
  let hpСтороны = мойHP;
  for (const s of союзники) { нашУрон += урон(m.u8(UNITS + s + U.ATK), средDEF) * темпТипа(m.u8(UNITS + s + U.TYPE)); hpСтороны += m.u8(UNITS + s + U.HP); }
  const общий = (hpВрагов / нашУрон) / (hpСтороны / уронВрагов);
  return { ближний, общий };
}
/** Порог явного перевеса: обмен ≤ 0.6 — мы кладём их больше чем вдвое быстрее, отходить незачем. */
export const ПЕРЕВЕС = 0.6;

/** Живые свои (не здания, не сам боец) в квадрате радиуса R. */
export function союзники(eng, боец, R = 7) {
  const m = eng.m, мой = m.u8(UNITS + боец + U.OWNER), c = клетка(m, боец), список = [];
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (i === боец || !жив(m, i) || m.u8(UNITS + i + U.TYPE) >= 0x1a || m.u8(UNITS + i + U.OWNER) !== мой) continue;
    const p = клетка(m, i);
    if (Math.abs(p.x - c.x) <= R && Math.abs(p.y - c.y) <= R) список.push(i);
  }
  return список;
}

/** Строитель (тип 4, Constructor) — дорогой и слабый, правило владельца: НИКОГДА не дерётся. */
export const СТРОИТЕЛЬ = 4;
/** Это строитель: он не дерётся вовсе. */
export const строитель = (m, i) => m.u8(UNITS + i + U.TYPE) === СТРОИТЕЛЬ;

/**
 * Выполнить действие: превратить его в приказ движка. Возвращает описание для показа.
 * `сдать` — куда класть приказ; по умолчанию общая очередь. Скриптовый ИИ подменяет её своей,
 * которая душит повторы: одинаковый приказ, отданный заново, сбрасывает замах, и юнит,
 * которому каждые восемь тиков повторяют «бей вот этого», не наносит ни одного удара.
 */
export function выполнить(eng, боец, действие, задание, сдать = приказ) {
  const m = eng.m, c = клетка(m, боец);
  // Жёсткое правило слоя действий: строителю при любой угрозе в окне «бить» и «держать»
  // заменяются на «отойти» (в охране автомат движка сам контратакует ударившего — этого тоже
  // не надо). Сеть может выбрать что угодно, но приказ атаки от строителя не уйдёт никогда.
  if ((действие === БЛИЖНИЙ || действие === СЛАБЕЙШИЙ || действие === ДЕРЖАТЬ) && строитель(m, боец) && враги(eng, боец).length)
    действие = ОТОЙТИ;
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const вточку = (x, y) => {
    x = Math.max(0, Math.min(W - 1, x)); y = Math.max(0, Math.min(H - 1, y));
    сдать(eng, боец, КОД.ИДТИ, 0, x << 5, y << 5);
    return { x, y };
  };
  if (действие < 8) {
    // Идти в сторону: насколько луч проходим — столько и идём; если упёрлись сразу — берём
    // соседнее направление (±45°), где есть куда шагнуть. Иначе боец кладёт приказ «идти в свою
    // же клетку» и стоит у стены под ударами.
    let лучший = null;
    for (const k of [0, 1, -1]) {
      const [dx, dy] = НАПРАВЛЕНИЯ[(действие + k + 8) % 8];
      const n = луч(m, c.x, c.y, dx, dy);
      if (n > 0 && (!лучший || n > лучший.n)) лучший = { n, dx, dy };
      if (лучший && лучший.n === ШАГ) break;
    }
    if (!лучший) { сдать(eng, боец, КОД.ОХРАНА); return 'идти некуда — стоп'; }
    const p = вточку(c.x + лучший.dx * лучший.n, c.y + лучший.dy * лучший.n);
    return `идти в ${p.x},${p.y}`;
  }
  if (действие === К_ЦЕЛИ) {
    const ц = задание && задание.точка;
    if (!ц) return 'к цели: цели нет';
    const p = вточку(ц.x, ц.y);
    return `к цели ${p.x},${p.y}`;
  }
  if (действие === БЛИЖНИЙ || действие === СЛАБЕЙШИЙ) {
    const в = враги(eng, боец);
    // Живых врагов нет — встать на пост: иначе автомат движка продолжит махать по трупу,
    // который он ещё считает своей целью.
    if (!в.length) { сдать(eng, боец, КОД.ОХРАНА); return 'бить некого — стоп'; }
    в.sort(действие === БЛИЖНИЙ ? (a, b) => a.d - b.d || a.i - b.i
                                : (a, b) => a.hp - b.hp || a.d - b.d || a.i - b.i);
    const ц = в[0];
    сдать(eng, боец, КОД.АТАКА, ц.i, ц.x << 5, ц.y << 5);
    return `бить ${ц.i.toString(16)} в ${ц.x},${ц.y}`;
  }
  if (действие === ОТОЙТИ) {
    const в = враги(eng, боец);
    if (!в.length) { сдать(eng, боец, КОД.ОХРАНА); return 'отходить не от кого'; }
    const p = кудаОтойти(m, c, в, строитель(m, боец));
    if (!p) {
      // Зажат у стены — драться, а не стоять под ударами: бьём ближайшего. Строитель сюда не
      // попадает: для него кудаОтойти отдаёт любую проходимую клетку, а совсем без них — стоп.
      if (строитель(m, боец)) { сдать(eng, боец, КОД.СТОП); return 'отойти некуда — строитель ждёт'; }
      в.sort((a, b) => a.d - b.d || a.i - b.i);
      сдать(eng, боец, КОД.АТАКА, в[0].i, в[0].x << 5, в[0].y << 5);
      return `отойти некуда — бить ${в[0].i.toString(16)}`;
    }
    const т = вточку(p.x, p.y);
    return `отойти в ${т.x},${т.y}`;
  }
  if (действие === ДЕРЖАТЬ) { сдать(eng, боец, КОД.ОХРАНА); return 'держать позицию'; }
  if (действие === ДОМ) {
    const д = дома(eng, боец);
    if (!д.length) return 'домов рядом нет';
    const ц = д[0];
    сдать(eng, боец, КОД.АТАКА, ц.i, ц.x << 5, ц.y << 5);
    return `бить дом ${ц.тип.toString(16)} в ${ц.x},${ц.y}`;
  }
  if (действие === ПОДОБРАТЬ) {
    // Приказ «добывать в точке» (0x4c): юнит идёт к клетке и забирает, что там лежит, —
    // проверено на еде (ai-spec §4.3, состояние 0x4x). Цель — ближайший видимый предмет.
    const п = предметы(eng, боец);
    if (!п.length) return 'подбирать нечего';
    сдать(eng, боец, КОД.ДОБЫЧА, 0, п[0].x << 5, п[0].y << 5);
    return `подобрать в ${п[0].x},${п[0].y}`;
  }
  if (действие === СТРЕЛЯТЬ) {
    // «Выстрелил — отошёл — выстрелил»: макро для дальнего боя. Враг дальше двух клеток —
    // приказ атаки (автомат движка сам подойдёт на дальность и выстрелит, маги 5–8 в упор не
    // бьют никогда); враг подошёл вплотную (≤ 2 клетки: его ход плюс запас) — отскочить веером
    // кандидатов; на следующем решении снова стрелять. Ближнему бойцу макро недоступно.
    const r = дальность(m, боец);
    if (!r) return 'стрелять нечем';
    let в = враги(eng, боец);
    if (!в.length) { сдать(eng, боец, КОД.ОХРАНА); return 'стрелять не в кого'; }
    в.sort((a, b) => a.d - b.d || a.i - b.i);
    // Назначенная цель (фокус отряда или уже подранённый) важнее ближнего: без этого стрелок,
    // отправленный валить зверя вместе со всеми, стрелял в того, кто просто ближе, и отряд
    // размазывал урон. Отскок при этом считаем от неё же — она и есть тот, кто нас достанет.
    const назн = задание && задание.цель && в.find(е => е.i === задание.цель);
    if (назн) в = [назн, ...в.filter(е => е !== назн)];
    // Отскакивать только когда обмен не в нашу пользу (уточнение владельца): при явном перевесе
    // отход — потеря темпа и лишний урон дому/своим, надо просто добивать.
    //
    // `задание.кайт` задаёт, когда отскок вообще разрешён:
    //   'всегда' (умолчание) — как училась сеть и как игралось раньше;
    //   'нет'    — отскока нет совсем. Тестер (Discord, 13.09) написал, что драться против
    //              кайтящего ИИ «really annoying», и владелец решил убрать раздражающий
    //              микроконтроль: пусть компьютер будет сложным, а не бешеным;
    //   'ранен'  — отскакивает только подбитый (меньше половины HP). Середина: размен лоб в лоб
    //              состоится, но добить отходящего стрелка всё ещё надо успеть.
    const режимКайта = задание?.кайт || (задание?.безОтскока ? 'нет' : 'всегда');
    const можноОтскок = режимКайта === 'всегда'
      || (режимКайта === 'ранен' && m.u8(UNITS + боец + U.HP) * 2 < m.u8(UNITS + боец + U.HPMAX));
    let ближайший = в[0].d; for (const е of в) if (е.d < ближайший) ближайший = е.d;
    if (можноОтскок && ближайший <= П.кайт_дистанция && обмен(m, боец, в, союзники(eng, боец)).общий > П.перевес) {
      const p = кудаОтойти(m, c, в, true);
      if (p) { const т = вточку(p.x, p.y); return `отскочить в ${т.x},${т.y}`; }
    }
    сдать(eng, боец, КОД.АТАКА, в[0].i, в[0].x << 5, в[0].y << 5);
    return `стрелять в ${в[0].i.toString(16)}`;
  }
  if (действие === РАНЕНЫЙ || действие === МАГ || действие === ЗАЩИТИТЬ) {
    // Выбор цели — дело юнита (поправка владельца к рамке): он видит окно и решает, кого бить
    // первым. Раненый — наименьшая доля HP; маг — типы 5–8, сначала с большей маной; защитить —
    // тот, кто бьёт союзника (не меня). Подходящих нет — ближайший.
    let в = враги(eng, боец);
    if (!в.length) { сдать(eng, боец, КОД.ОХРАНА); return 'бить некого — стоп'; }
    const п = действие === РАНЕНЫЙ ? в.slice().sort((a, b) => a.доля - b.доля || a.d - b.d || a.i - b.i)
            : действие === МАГ ? в.filter(е => е.маг).sort((a, b) => b.мана - a.мана || a.d - b.d || a.i - b.i)
            : в.filter(е => е.бьётСвоего).sort((a, b) => a.d - b.d || a.i - b.i);
    const ц = п[0] || в.slice().sort((a, b) => a.d - b.d || a.i - b.i)[0];
    сдать(eng, боец, КОД.АТАКА, ц.i, ц.x << 5, ц.y << 5);
    return `${ДЕЙСТВИЯ[действие]}: ${ц.i.toString(16)}${п[0] ? '' : ' (подходящих нет — ближайший)'}`;
  }
  if (действие === ЦЕЛЬ) {
    // Цель приказа сверху (AI-PLAN §2.3: цель — номер объекта): это крючок для тактика, который
    // раздаёт цели по отряду; сам юнит только исполняет.
    const ц = задание && задание.цель;
    if (!ц || !жив(m, ц)) return 'цели приказа нет';
    сдать(eng, боец, КОД.АТАКА, ц, m.u16(UNITS + ц + U.X), m.u16(UNITS + ц + U.Y));
    return `бить цель ${ц.toString(16)}`;
  }
  if (действие === УСНУТЬ) {
    // Спящий лечится сам; любой новый приказ его будит, поэтому «продолжать спать» — это
    // «ничего», а повторный «уснуть» спящему приказ не кладёт.
    if (спит(eng, боец)) return 'спит';
    // При враге в окне спать нельзя: ppo9 научился сыпать «уснуть» в бою (2730 приказов, из них
    // 560 при враге) — просыпание от удара делало это почти бесплатным. Теперь это пустое действие.
    if (враги(eng, боец).length) return 'уснуть при враге — нельзя';
    сдать(eng, боец, КОД.СТОП);            // 0x2f — та же команда, что кнопка zzz
    return 'уснуть';
  }
  return 'ничего';
}
