// Набор действий сети и превращение их в приказы движка (наше).
//
// Сеть не двигает юнита по кадрам: у юнита есть свой автомат состояний, он сам идёт, обходит
// препятствия и бьёт. Сеть встаёт туда, где сидит игрок, — раз в несколько тиков выдаёт бойцу
// обычный игровой приказ. Набор кодов снят с таблиц 0x141f8/0x14218 (см. notes/AI-UNIT-STAGE1.md).
//
// Приказы уходят в очередь движка через js/port/inject.js — общую точку для ИИ и сетевой игры.
//
// Приказ подхватывается юнитом только когда тот стоит ровно на границе клетки (0x18154), то есть
// до восьми тиков он ждёт в поле ORDER. Это задержка, а не потеря; «подхвачен ли» видно по
// ORDER == 0xff, и это отдельный признак во входе сети (js/ai/obs.js).
import { G, U, UNITS, ITEMS, BG } from '../mem.js';
import { приказ, КОД } from '../port/inject.js';
import { ПАРАМЕТРЫ as П } from './params.js';
// Сон в игре родной: приказ 0x2f (кнопка zzz), состояние 0x2x. Обработчик 0x18e0b (port/move.js)
// переводит 0x2f в 0x20 и раз в 32 такта добавляет спящему +1 HP и +1 маны сверх общей
// регенерации. Своего «быстрого сна» у сцен больше нет: тренировка должна идти по правилам игры,
// иначе сеть учится тому, чего в партии не бывает.
/** Юнит отдыхает (спит): состояние 0x2x. */
export const спит = (eng, i) => (eng.m.u8(UNITS + i + U.STATE) & 0xf0) === 0x20;

export { приказ, КОД };

// Восемь направлений в том же порядке, что у движка (0x30504): 1 — вверх, дальше по часовой.
