// Переключатель поведений (наше): стратег, который управляет не сырыми решениями, а ГОТОВЫМИ
// скриптовыми характерами.
//
// Замысел владельца дословно: «у нас есть скриптовое поведение — можно ли стратега на основе
// скриптов тренировать, чтобы он управлял скриптовыми вариантами на прогонах, а не другими
// нейронками уровнем ниже; так бы эмуляции проходили намного быстрее».
//
// Чем это отличается от js/ai/strategy.js. Тот стратег выдаёт четыре сырых решения (осанка,
// стройка, производство, поле) — 17 логитов, и каждое из них надо выучить с нуля; клон правила
// упёрся в паритет со скриптом, а отбор поверх клона встал на третьем поколении. Здесь выход
// другой: это выбор ОДНОГО из восьми характеров, каждый из которых уже написан, проверен и
// сам по себе играет. Сеть не переизобретает поведение, а решает, КОГДА какое включить:
// в начале партии кормиться охотником, при угрозе стать черепахой, набрав костяк — агрессором.
//
// Почему это быстро. Прогоны и так идут на скрипте: нижних сетей в них нет вовсе (боец и тактик
// подключаются только если их явно выбрали в лобби), поэтому партия 20 игровых минут считается
// за секунду-полторы. Дорогим обучение делала не скорость прогона, а размер задачи: 17 логитов
// против восьми. Здесь действий восемь, и любое из них — рабочее поведение, а не случайность.
//
// Честность. Признаки — те же 32, что у стратега (js/ai/strategy.js, `наблюдать`): всё из
// `осмотр()`, из-под тумана ничего.
import { ВХОД, наблюдать } from './strategy.js';

export { ВХОД, наблюдать };

/** Характеры штаба по порядку — это и есть действия сети (js/port/ai_script.js, ХАРАКТЕРЫ). */
export const ПОВЕДЕНИЯ = ['ровный', 'агрессор', 'экономист', 'черепаха', 'налётчик', 'защитник', 'костяк', 'охотник'];
export const ВЫХОД = ПОВЕДЕНИЯ.length;
export const СКРЫТЫХ = 16;
/** Как часто пересматривать поведение: 600 шагов ≈ 33 секунды. Чаще — штаб не успевает довести
 *  ни одного замысла до конца, реже — сеть перестаёт реагировать на то, что происходит. */
export const ТАКТ = 600;

/** Случайные веса (для старта отбора). */
export function случайная(сид = 1) {
  let s0 = сид >>> 0 || 1;
  const сл = () => { s0 = (s0 * 1103515245 + 12345) & 0x7fffffff; return s0 / 0x80000000 * 2 - 1; };
  const м1 = Math.sqrt(6 / (ВХОД + СКРЫТЫХ)), м2 = Math.sqrt(6 / (СКРЫТЫХ + ВЫХОД));
  const w1 = new Float32Array(СКРЫТЫХ * ВХОД), w2 = new Float32Array(ВЫХОД * СКРЫТЫХ);
  for (let i = 0; i < w1.length; i++) w1[i] = сл() * м1;
  for (let i = 0; i < w2.length; i++) w2[i] = сл() * м2;
  return { w1, b1: new Float32Array(СКРЫТЫХ), w2, b2: new Float32Array(ВЫХОД) };
}

/** Один прямой проход: 32 признака → скрытый слой (ReLU) → логит на каждое поведение. */
export function прогон(сеть, вх, скр = new Float32Array(СКРЫТЫХ), вых = new Float32Array(ВЫХОД)) {
  for (let h = 0; h < СКРЫТЫХ; h++) {
    let s = сеть.b1[h]; const б = h * ВХОД;
    for (let i = 0; i < ВХОД; i++) s += сеть.w1[б + i] * вх[i];
    скр[h] = s > 0 ? s : 0;
  }
  for (let o = 0; o < ВЫХОД; o++) {
    let s = сеть.b2[o]; const б = o * СКРЫТЫХ;
    for (let h = 0; h < СКРЫТЫХ; h++) s += сеть.w2[б + h] * скр[h];
    вых[o] = s;
  }
  return вых;
}

/** Какое поведение включить. Argmax, а не выбор по вероятности: в партии решение обязано быть
 *  однозначным, иначе локстеп у игроков разъедется. */
export function решение(сеть, вх, скр, буф) {
  const в = прогон(сеть, вх, скр, буф);
  let k = 0; for (let i = 1; i < ВЫХОД; i++) if (в[i] > в[k]) k = i;
  return ПОВЕДЕНИЯ[k];
}

/** Веса в JSON и обратно — тот же формат, что у остальных слоёв. */
export function вЗапись(сеть) {
  return { вид: 'поведенец', вход: ВХОД, скрытых: СКРЫТЫХ, выход: ВЫХОД, поведения: ПОВЕДЕНИЯ,
           w1: [...сеть.w1], b1: [...сеть.b1], w2: [...сеть.w2], b2: [...сеть.b2] };
}
export function изЗаписи(з) {
  return { w1: Float32Array.from(з.w1), b1: Float32Array.from(з.b1), w2: Float32Array.from(з.w2), b2: Float32Array.from(з.b2) };
}
