// Угодья карт: где на каждой карте постоянно пасётся зверьё.
//
// Замысел владельца дословно: «мы можем немножко сжульничать — ты читаешь все карты, знаешь точки
// респавна животных, помечаешь их как удобные пастбища, и тогда компьютер даже с закрытой картой
// знает, где кормиться, и выбирает ближайшее или самое выгодное».
//
// Почему это не жульничество на самом деле. Зверь возрождается ВСЕГДА на своей домашней клетке
// (js/port/combat.js, 0x1cfcb: координаты берутся из +0x59/+0x5a записи). Угодье — постоянная
// точка карты, а не то, что видно в тумане. Человек, сыгравший карту дважды, знает её так же.
//
// Таблицу считает tools/ai_пастбища.mjs и кладёт в data/пастбища.json: по каждой карте список
// кучек — середина, сколько зверья, сколько мяса даёт полный выпас и самый злой зверь кучки.
import { текущаяКарта } from '../loader.js';
let таблица = null;

/** Загрузить таблицу (в игре — fetch, в стендах — с диска). Зовётся один раз. */
export function задать(данные) { таблица = данные || null; }
/** Есть ли таблица вообще. */
export const естьТаблица = () => !!таблица;

/**
 * Угодья этой карты в том же виде, в каком их держит память штаба: {x, y, зверей, сила, шаг}.
 * `шаг` ставим отрицательным, чтобы «известное с рождения» не считалось свежей разведкой и
 * вытеснялось настоящими наблюдениями, когда те появятся.
 */
export function дляКарты(карта = текущаяКарта) {
  const з = таблица && таблица[карта];
  if (!з || !з.угодья) return [];
  return з.угодья.map(у => ({ x: у.x, y: у.y, зверей: у.зверей, сила: у.сила * у.зверей, шаг: -1, изТаблицы: 1 }));
}
