// Слой стратега (наше): третий, верхний этаж пирамиды из notes/AI-PLAN.md, часть 1.
//
// Место в схеме. Боец решает, как один юнит бьётся (js/ai/net.js), тактик — что делает главный
// отряд (js/ai/tactic.js). Оба уже играют и в турнире мозгов идут вровень со скриптом. Выше них
// до сих пор стоял целиком скриптовый штаб `js/port/ai_script.js`: жёсткие пороги из таблиц
// УРОВНИ и ХАРАКТЕРЫ. Отсюда и главная жалоба тестера — однообразие: при одном и том же уровне
// компьютер каждую партию разыгрывает одну и ту же последовательность, потому что решение
// «копить или идти», «что строить», «кого заказывать» — это сравнение с константой.
//
// Что решает стратег. Ровно те четыре вещи, которые сейчас решает штаб, и ничего сверх:
//   • ОСАНКА       — развитие / атака / оборона / копим;
//   • СТРОЙКА      — что заказать следующим (или ничего);
//   • ПРОИЗВОДСТВО — кого делать в домах (или никого);
//   • ПОЛЕ         — какую долю армии держать в кулаке, а не дома.
// Всё остальное — поиск цели, состав отрядов, маршруты, фокус огня — остаётся у скрипта и у
// нижних слоёв. Так выход остаётся коротким (17 логитов), а сеть учит выбор стратегии, а не
// переизобретает то, что уже написано и проверено.
//
// Почему именно так. Тот же приём, что дал работающего тактика: выход — макро-действия поверх
// готовых умений, обучение начинается с клонирования нынешнего правила (`метка()`), а дальше
// правило улучшается отбором на исходах партий. Учить с нуля верхний уровень над случайно
// ведущими себя нижними нельзя — AI-PLAN, подводный камень 10.
//
// Честность. Все признаки берутся из `осмотр()` — того же среза, по которому играет скриптовый
// штаб: чужие юниты и дома там уже отфильтрованы по разведанному, а зверьё, мясо и вещи — по
// памяти мест. Данных из-под тумана здесь не появляется (AI-PLAN §2.3, «категорически нельзя»).
import { G, U, UNITS } from '../mem.js';

// Виды построек в игре: 0 Святилище, 1 Казарма, 2/3 Оружейные, 4 Склад, 5..13 военные дома.
// Стратег называет не конкретный вид (их у каждого племени свой набор), а НАМЕРЕНИЕ: «поставить
// склад», «поставить второй военный дом». Во что это превратится, решает племя — так одна сеть
// годится всем восьми, и её не приходится переучивать под чужое дерево технологий.
export const ОСАНКИ = ['развитие', 'атака', 'оборона', 'копим'];
export const СТРОЙКА = ['ничего', 'склад', 'казарма', 'оружейная', 'военныйдом', 'ещёвоенный'];
export const ПРОИЗВОДСТВО = ['ничего', 'рабочий', 'боец', 'строитель'];
export const ПОЛЕ = ['мало', 'половина', 'все'];          // какая доля бойцов уходит в кулак

export const ВХОД = 32;
export const ВЫХОД = ОСАНКИ.length + СТРОЙКА.length + ПРОИЗВОДСТВО.length + ПОЛЕ.length;  // 4+6+4+3 = 17
export const СКРЫТЫХ = 24;

/** Клетка юнита. */
const кл = (m, i) => ({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
/** Сумма характеристик: грубая мера силы юнита (та же, что у тактика и у штаба). */
const сила = (m, i) => m.u8(UNITS + i + U.HPMAX) + m.u8(UNITS + i + U.MAG) + m.u8(UNITS + i + U.ATK)
                     + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.SPD);
/** Зажать в 0..1: сеть маленькая, разнобой масштабов ей вреден больше, чем потеря точности. */
const зажать = (x) => x < 0 ? 0 : x > 1 ? 1 : x;
/** Жив ли юнит (бит 0 байта +5b — «в свободном списке»). */
const жив = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1);

/**
 * Наблюдение стратега: 32 числа в 0..1.
 * @param eng движок, `с` — состояние ИИ цвета, `о` — срез `осмотр()`.
 */
export function наблюдать(eng, с, о, вых = new Float32Array(ВХОД)) {
  const m = eng.m; вых.fill(0);
  const шаг = m.u32(G.step);

  // ---- своя экономика
  вых[0] = зажать(о.еда / 20000);
  вых[1] = зажать((о.еда - (с.едаБыла ?? о.еда)) / 4000 + 0.5);      // прирост за такт штаба, 0.5 — ноль
  вых[2] = зажать(о.бойцы.length / 20);
  вых[3] = зажать(о.рабочие.length / 8);
  вых[4] = зажать(о.строители.length / 4);
  вых[5] = зажать(о.дома.size / 8);
  вых[6] = о.дома.has(4) ? 1 : 0;                                     // склад
  вых[7] = о.дома.has(1) ? 1 : 0;                                     // казарма

  // ---- технологии и целость базы
  вых[8] = (о.дома.has(2) || о.дома.has(3)) ? 1 : 0;                  // оружейная любая
  let военных = 0; for (const в of о.дома.keys()) if (в >= 5) военных++;
  вых[9] = военных ? 1 : 0;
  вых[10] = зажать(военных / 3);
  let домHP = 0, домМакс = 0;
  for (const [, з] of о.дома) { домHP += m.u8(UNITS + з + U.HP); домМакс += m.u8(UNITS + з + U.HPMAX); }
  вых[11] = домМакс ? домHP / домМакс : 0;

  // ---- своя армия
  const кулак = (с.отряды && с.отряды.кулак) ? с.отряды.кулак.filter(i => жив(m, i)) : [];
  вых[12] = зажать(кулак.length / 15);
  let силаКулака = 0, стрелков = 0;
  for (const i of кулак) {
    силаКулака += сила(m, i);
    const т = m.u8(UNITS + i + U.TYPE); if ((т >= 5 && т <= 8) || т === 13) стрелков++;
  }
  вых[13] = зажать(кулак.length ? силаКулака / кулак.length / 400 : 0);
  вых[14] = кулак.length ? стрелков / кулак.length : 0;
  const геройЖив = жив(m, с.герой);
  вых[15] = геройЖив ? 1 : 0;
  вых[16] = зажать(геройЖив && с.геройСтарт ? сила(m, с.герой) / (с.геройСтарт * 3) : 0);

  // ---- враг, только по разведанному
  вых[17] = зажать(о.врагиВидимые.length / 15);
  let ихСила = 0; for (const е of о.врагиВидимые) ихСила += сила(m, е);
  let нашаСила = 0; for (const i of о.бойцы) нашаСила += сила(m, i);
  вых[18] = зажать(нашаСила ? ихСила / нашаСила / 2 : (ихСила ? 1 : 0));
  вых[19] = зажать(о.вражДомаВидимые.length / 8);
  вых[20] = с.вражБаза ? 1 : 0;
  вых[21] = зажать(с.виделВрага >= 0 ? (шаг - с.виделВрага) / 3600 : 1);
  вых[22] = зажать(с.битС >= 0 ? (шаг - с.битС) / 1800 : 1);

  // ---- карта и время
  вых[23] = зажать(шаг / 40000);
  const клеток = Math.max(1, (о.клетокX || 1) * (о.клетокY || 1));
  вых[24] = зажать((с.разведано ? с.разведано.size : 0) / клеток);
  вых[25] = зажать(о.звери.length / 20);
  вых[26] = зажать(о.еденаЗемле.length / 10);
  вых[27] = зажать(о.вещи.length / 10);

  // ---- кем нас попросили быть. Уровень и характер остаются входом, а не отдельными весами:
  // одна сеть должна уметь и лёгкого, и зверского, иначе придётся держать четыре набора весов
  // и обучать каждый отдельно (AI-PLAN, этап 7, пункт 3).
  вых[28] = зажать((с.уровень ?? 1) / 3);
  вых[29] = зажать((с.порогАтаки ?? 5) / 12);                         // насколько поздно лезет в драку
  вых[30] = зажать((с.рабочихНадо ?? 2) / 4);                         // насколько экономичен
  вых[31] = с.приёмы && с.приёмы.has('оборона') ? 1 : 0;
  return вых;
}

/**
 * Случайные начальные веса (Xavier-подобные, с явным ГСЧ). Явный ГСЧ, а не Math.random: обучение
 * должно воспроизводиться по сиду — иначе сравнивать два прогона нельзя.
 */
export function случайная(сид = 1) {
  let s0 = сид >>> 0 || 1;
  const сл = () => { s0 = (s0 * 1103515245 + 12345) & 0x7fffffff; return s0 / 0x80000000 * 2 - 1; };
  const мас1 = Math.sqrt(6 / (ВХОД + СКРЫТЫХ)), мас2 = Math.sqrt(6 / (СКРЫТЫХ + ВЫХОД));
  const w1 = new Float32Array(СКРЫТЫХ * ВХОД), w2 = new Float32Array(ВЫХОД * СКРЫТЫХ);
  for (let i = 0; i < w1.length; i++) w1[i] = сл() * мас1;
  for (let i = 0; i < w2.length; i++) w2[i] = сл() * мас2;
  return { w1, b1: new Float32Array(СКРЫТЫХ), w2, b2: new Float32Array(ВЫХОД) };
}

/** Один прямой проход: вход → скрытый слой (ReLU) → 17 логитов. */
export function прогон(сеть, вх, скр = new Float32Array(СКРЫТЫХ), вых = new Float32Array(ВЫХОД)) {
  for (let h = 0; h < СКРЫТЫХ; h++) {
    let s = сеть.b1[h]; const б = h * ВХОД;
    for (let i = 0; i < ВХОД; i++) s += сеть.w1[б + i] * вх[i];
    скр[h] = s > 0 ? s : 0;
  }
  for (let o = 0; o < ВЫХОД; o++) {
    let s = сеть.b2[o]; const б = o * СКРЫТЫХ;
    for (let h = 0; h < СКРЫТЫХ; h++) s += сеть.w2[б + h] * скр[h];
    вых[o] = s;
  }
  return вых;
}

/** Индекс наибольшего в срезе [от, до). Argmax, а не сэмплирование: в партии решение обязано
 *  быть однозначным, иначе локстеп у игроков разъедется. */
function лучший(в, от, до) {
  let k = от, м = в[от];
  for (let i = от + 1; i < до; i++) if (в[i] > м) { м = в[i]; k = i; }
  return k - от;
}

/**
 * Решение стратега: четыре независимых выбора по своим группам логитов.
 * @returns {осанка, стройка, производство, поле} — строками из таблиц выше.
 */
export function решение(сеть, вх, скр, буф) {
  const в = прогон(сеть, вх, скр, буф);
  let п = 0;
  const осанка = ОСАНКИ[лучший(в, п, п += ОСАНКИ.length)];
  const стройка = СТРОЙКА[лучший(в, п, п += СТРОЙКА.length)];
  const производство = ПРОИЗВОДСТВО[лучший(в, п, п += ПРОИЗВОДСТВО.length)];
  const поле = ПОЛЕ[лучший(в, п, п += ПОЛЕ.length)];
  return { осанка, стройка, производство, поле };
}

/**
 * Что решил бы нынешний скриптовый штаб — метка для клонирования поведения. Это стартовая точка
 * стратега: сеть сперва повторяет правило, а дальше правило улучшает отбор на исходах партий.
 * Зовётся из `штаб()` уже ПОСЛЕ того, как он всё посчитал, поэтому читает готовые поля.
 * @returns номера в группах: [осанка, стройка, производство, поле].
 */
export function метка(с, о, надоВид, заказано) {
  const осанка = Math.max(0, ОСАНКИ.indexOf(с.осанка));
  let стройка = 0;
  if (надоВид !== null && надоВид !== undefined) {
    if (надоВид === 4) стройка = 1;
    else if (надоВид === 1) стройка = 2;
    else if (надоВид === 2 || надоВид === 3) стройка = 3;
    else стройка = [...о.дома.keys()].some(в => в >= 5) ? 5 : 4;
  }
  const производство = Math.max(0, ПРОИЗВОДСТВО.indexOf(заказано || 'ничего'));
  // Доля армии в поле: как её сейчас поделил `отряды()`.
  const всего = о.бойцы.length || 1;
  const вКулаке = (с.отряды && с.отряды.кулак) ? с.отряды.кулак.length : 0;
  const доля = вКулаке / всего;
  const поле = доля < 0.34 ? 0 : доля < 0.85 ? 1 : 2;
  return [осанка, стройка, производство, поле];
}

/** Размеры групп логитов — нужны обучению, чтобы считать softmax по каждой отдельно. */
export const ГРУППЫ = [ОСАНКИ.length, СТРОЙКА.length, ПРОИЗВОДСТВО.length, ПОЛЕ.length];
/** Границы групп в векторе логитов: [[от, до], …]. */
export const ГРАНИЦЫ = (() => { const г = []; let п = 0; for (const n of ГРУППЫ) { г.push([п, п + n]); п += n; } return г; })();
/** Имя слоя `вперёд` — как у тактика, чтобы обучающие скрипты были похожи. */
export const вперёд = прогон;
