// ПРЕСЕТЫ РУЧЕК ДЛЯ ССЫЛОК. Ручки ИИ названы по-русски (JW_ОБР_…), а в ссылках владельцу нужна одна
// латиница. Поэтому лучшие связки заводим здесь под короткими именами и включаем параметром p:
//   /jw/scene/tyrano/2?p=t2   — лучшая связка для второй миссии Тирано на hard (замер 24.09.2026:
//                               31/40 побед за 90 мин, медиана 69 мин, лучшая 40,5 мин без потерь).
// Явные JW_… в той же ссылке главнее пресета.
export const ПРЕСЕТЫ = {
  t2: { JW_ОБР_ШТАБ: '1', JW_ШТАБ_ДОМ: '6', JW_ОБР_РЕАКЦИЯ: '60', JW_ОБР_ОХРАНА_ЛОГОВА: '1', JW_ОБР_ОХРАНА: '1',
        JW_СТР_РЕЗЕРВ: '1', JW_СТР_ТОЧНО: '1', JW_ШТАБ_ДОМА_ВСЕ: '1', JW_СТР_КОНВОЙ: '2', JW_ОБР_ГОНЕЦ: '0',
        JW_ОБР_КАЖДЫЕ: '6', JW_ОБР_ОТНЕСТИ: '1800', JW_ОБР_ОТНЕСТИ_ОТРЯДОМ: '5000' },
};
/** Дописать в окружение ручки пресета из ссылки (?p=имя), не трогая заданные явно. */
export function сПресетом(е) {
  try {
    const п = new URLSearchParams(globalThis.location?.search || '').get('p');
    for (const [к, з] of Object.entries(ПРЕСЕТЫ[п] || {})) if (е[к] === undefined) е[к] = з;
  } catch {}
  return е;
}
