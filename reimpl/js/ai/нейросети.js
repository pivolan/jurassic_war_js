// Готовые нейросети для партии (наше): загрузка весов по имени файла и кэш.
//
// Зачем отдельный модуль. Веса лежат в `out/ai/weights` и отдаются как `/jw/ai/weights/…`. Их
// нужно и лобби (показать список), и слою партии (поставить сеть штабу), и просмотру записи
// (воспроизвести ровно ту же сеть). Загрузка асинхронная, а старт партии — нет, поэтому всё
// скачивается заранее, до первого шага, и дальше берётся из кэша.
//
// Два слоя, два вида файлов:
//   боец  — свёрточная сеть на ~80 тыс. весов (js/ai/net.js), решает за одного юнита;
//   тактик — маленькая сеть на 638 весов (js/ai/tactic.js), решает, что делает главный отряд.
// Различаем по полю «скрытых»: оно есть только у тактика.
//
// Детерминизм. Сеть в партии играет с нулевой температурой (argmax по логитам), то есть без
// случайности; одинаковые веса у всех участников — обязательное условие, поэтому имя файла едет
// в параметрах старта и в записи партии, а не выбирается на каждой машине отдельно.
import { политикаСети } from './policy_net.js';
import * as Тактик from './tactic.js';
import * as Комдив from './комдив.js';
import * as Отряд from './отряд.js';

// В игре доступна одна, лучшая версия каждого слоя. Все прогоны обучения остались в
// out/ai/weights и видны на стенде арены, но в лобби выбирать из десятка «ppo9t» и «bc4» незачем:
// это путает и ничего не даёт. Здесь — что считается лучшим на сегодня.
//   боец  — ppoДома: тот же ppoИгры, дообученный уже с действием «бить дом» (вектор 67, действий
//           22). Прежние веса ppoИгры остались под старый размер сети и в текущем коде просто не
//           грузятся — выбор «сеть бойца» в лобби молча откатывался на скрипт, см. ROADMAP.
//           Замер tools/ai_brains.mjs, 576 партий (6 карт × 8 племён × 2 места, предел 900 с):
//           скрипт — боец 26:26, скрипт — «обе» 22:30, боец — тактик 30:14. То есть сеть бойца
//           идёт со скриптом вровень, а связка обеих сетей его обыгрывает;
//   тактик — клонирование правила штаба; заменится победителем отбора, когда тот обгонит клон.
export const ЛУЧШИЕ = { боец: 'ppoДома-2026-09-13-1558.json', тактик: 'тактик-bc.json', комдив: 'комдив-комдив1.json' };

const кэш = new Map();          // имя файла → { вид, боец?, тактик? }
let корень = null;

/** Где искать веса. По умолчанию — рядом с игрой: /jw/ai/weights/. */
export function задатьКорень(п) { корень = п; }
/**
 * Адрес файла весов: заданный корень или каталог рядом с игрой.
 *
 * Страница лежит в <корень игры>/reimpl/web/, веса — в <корень игры>/ai/weights/, то есть ДВА
 * уровня вверх, а не три. Три было написано под старую раскладку сайта, и после переезда в /play/
 * каждый запрос весов уходил в /ai/weights/ и отвечал 404 — молча, потому что `подготовить`
 * глотает ошибку. Итог: в лобби можно было выбрать «компьютер: нейронка», а играл всё равно
 * скрипт, и никто этого не видел. Отсчитываем от самой страницы, чтобы не зависеть от префикса.
 */
function путь(файл) {
  if (корень) return корень.replace(/\/$/, '') + '/' + файл;
  const дом = location.pathname.replace(/\/reimpl\/web\/[^/]*$/, '/');
  return new URL(дом + 'ai/weights/' + файл, location.href).href;
}

/** Список доступных весов (index.json рядом с ними). */
export async function список() {
  try {
    const о = await fetch(путь('index.json'), { cache: 'no-store' });
    if (!о.ok) return [];
    const с = await о.json();
    // Слой пишет tools/ai_оглавление.mjs. У старых оглавлений его нет — тогда угадываем по записи.
    return с.map(з => ({ ...з, слой: з.слой || (з.вид ? String(з.вид) : ('скрытых' in з ? 'тактик' : 'боец')) }));
  } catch { return []; }
}

/**
 * Прогоны обучения, которые идут прямо сейчас (out/ai/data/живые.json пишет tools/ai_ppo.py).
 * Веса текущей итерации лежат рядом и обновляются каждые несколько минут — стенд показывает их
 * отдельной строкой, чтобы можно было посмотреть, чему сеть научилась к этому часу.
 */
export async function живые() {
  try {
    const о = await fetch(путь('../data/живые.json'), { cache: 'no-store' });
    if (!о.ok) return [];
    return (await о.json()).map(з => ({ ...з, файл: `../data/${з.папка}/текущие.json`, лучшие: `../data/${з.папка}/лучшие.json` }));
  } catch { return []; }
}

/**
 * Есть ли такой файл весов. Нужно для «последней удачной версии»: лучшие.json появляется только
 * после первой посчитанной итерации, и до того запрос отвечает 404 — молча откатываться на скрипт
 * из-за этого нельзя.
 */
export async function есть(файл) {
  try { const о = await fetch(путь(файл), { method: 'HEAD', cache: 'no-store' }); return о.ok; } catch { return false; }
}

/** Веса из идущего обучения: они меняются на диске, поэтому ни браузерный кэш, ни наш не годятся. */
const живойФайл = (файл) => файл.startsWith('../data/');

/** Скачать и разобрать веса. Возвращает { вид: 'боец'|'тактик', политика?|сеть? }. */
export async function загрузить(файл) {
  if (!файл) return null;
  if (кэш.has(файл) && !живойФайл(файл)) return кэш.get(файл);
  if (живойФайл(файл)) кэш.delete(файл);          // на диске уже следующая итерация — качаем заново
  const о = await fetch(путь(файл) + (живойФайл(файл) ? '?t=' + Date.now() : ''), { cache: живойФайл(файл) ? 'no-store' : 'force-cache' });
  if (!о.ok) throw new Error('веса не скачались: ' + файл);
  const j = await о.json();
  // Комдив — сеть ГРУПП (48 → 48 → 32 → 42), а не одного бойца: у неё свой вход и свой выход,
  // поэтому и грузится отдельно. Подписана в самой записи полем «вид».
  // Сеть ОТРЯДА: одна на четверых, свой вход (окно 24×24×6 плюс вектор 48) и свой выход
  // (четыре головы по 22 действия), поэтому и грузится отдельно. Подписана полем «вид».
  const готово = (j.вид === 'отряд')
    ? { вид: 'отряд', отряд: Отряд.политика(j, { температура: 0 }), имя: j.имя || файл }
    : (j.вид === 'комдив')
    ? { вид: 'комдив', комдив: Комдив.изЗаписи(j), имя: j.имя || файл }
    : ('скрытых' in j)
    ? { вид: 'тактик', сеть: { w1: Float32Array.from(j.w1), b1: Float32Array.from(j.b1), w2: Float32Array.from(j.w2), b2: Float32Array.from(j.b2) }, имя: j.имя || файл }
    : { вид: 'боец', политика: политикаСети(j, { температура: 0 }), имя: j.имя || файл };
  if (готово.вид === 'тактик' && (j.вход !== Тактик.ВХОД || j.выход !== Тактик.ВЫХОД))
    throw new Error(`веса тактика не под эту сеть: вход ${j.вход}/${Тактик.ВХОД}, выход ${j.выход}/${Тактик.ВЫХОД}`);
  // Живые веса кладём в кэш тоже — иначе `дляМеста` их не увидит, — но при следующем запросе
  // перекачиваем заново: на диске уже другая итерация.
  кэш.set(файл, готово);
  if (живойФайл(файл)) готово.живой = true;
  return готово;
}

/** Уже скачанные веса (без сети). */
export const изКэша = (файл) => кэш.get(файл) || null;

/**
 * Подготовить всё, что нужно местам партии: список вида [{ мозги, весаБойца, весаТактика }].
 * Зовётся до старта; после него `изКэша` отдаёт готовое синхронно.
 */
export async function подготовить(места) {
  const файлы = нужныеФайлы(места);
  const беда = [];
  for (const ф of файлы) {
    try { await загрузить(ф); }
    catch (e) { console.warn('нейросеть', ф, e.message); беда.push(`${ф}: ${e.message}`); }
  }
  return беда;
}

/** Какие файлы весов нужны этим местам. */
export function нужныеФайлы(места) {
  const файлы = new Set();
  for (const м of места || []) {
    const мозги = м?.мозги || 'скрипт';
    if (мозги === 'боец' || мозги === 'обе') файлы.add(м.весаБойца || ЛУЧШИЕ.боец);
    if (мозги === 'тактик' || мозги === 'обе') файлы.add(м.весаТактика || ЛУЧШИЕ.тактик);
    if (мозги === 'комдив') файлы.add(м.весаКомдива || ЛУЧШИЕ.комдив);
    if (мозги === 'отряд' && м.весаОтряда) файлы.add(м.весаОтряда);
  }
  return [...файлы];
}

/**
 * Чего не хватает этим местам: список человеческих объяснений, пустой — значит всё на месте.
 *
 * Просьба владельца дословно: «пусть ошибка выдаётся, если нейронка не подключается, вместо тихой
 * замены на скрипт». До этого так и было: адрес весов считался от старой раскладки сайта, каждый
 * запрос отвечал 404, `подготовить` ошибку глотала, а `дляМеста` просто не клала сеть — партия
 * молча шла на скрипте, и в лобби при этом честно было выбрано «компьютер: нейронка». Полгода
 * такую подмену можно не заметить: скрипт играет прилично.
 */
export function чегоНеХватает(места) {
  const нет = [];
  for (const м of места || []) {
    const мозги = м?.мозги || 'скрипт';
    if (мозги === 'скрипт' || мозги === 'стратег') continue;
    const п = дляМеста(м);
    if ((мозги === 'боец' || мозги === 'обе') && !п.бойСеть) нет.push(`сеть бойца (${м.весаБойца || ЛУЧШИЕ.боец})`);
    if ((мозги === 'тактик' || мозги === 'обе') && !п.тактик) нет.push(`сеть тактика (${м.весаТактика || ЛУЧШИЕ.тактик})`);
    if (мозги === 'комдив' && !п.комдив) нет.push(`сеть комдива (${м.весаКомдива || ЛУЧШИЕ.комдив})`);
    if (мозги === 'отряд' && !п.отряд) нет.push(`сеть отряда (${м.весаОтряда || 'не выбрана'})`);
  }
  return [...new Set(нет)];
}

/** Что поставить штабу этого места: { бойСеть, тактик } — то, что понимает Скрипт.задать. */
export function дляМеста(м) {
  const о = {};
  if (!м) return о;
  const мозги = м.мозги || 'скрипт';
  // Имя весов может не приехать (старая запись, старый клиент) — тогда берём лучшее по умолчанию.
  const бФайл = м.весаБойца || ЛУЧШИЕ.боец, тФайл = м.весаТактика || ЛУЧШИЕ.тактик;
  const кФайл = м.весаКомдива || ЛУЧШИЕ.комдив;
  о.мозгиИмя = мозги; о.весаБойцаИмя = м.весаБойца || null; о.весаТактикаИмя = м.весаТактика || null;
  о.весаКомдиваИмя = м.весаКомдива || null;
  if (мозги === 'боец' || мозги === 'обе') { const в = изКэша(бФайл); if (в?.политика) о.бойСеть = в.политика; }
  if (мозги === 'тактик' || мозги === 'обе') { const в = изКэша(тФайл); if (в?.сеть) о.тактик = в.сеть; }
  if (мозги === 'комдив') { const в = изКэша(кФайл); if (в?.комдив) о.комдив = в.комдив; }
  if (мозги === 'отряд') { const в = изКэша(м.весаОтряда || ''); if (в?.отряд) о.отряд = в.отряд; }
  return о;
}
