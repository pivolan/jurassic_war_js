// Кодировщик наблюдения для сети, ведущей одного юнита (наше).
//
// Вход сети — три части:
//   1. окно 16×16 клеток вокруг бойца, 8 слоёв (окно чётное, чтобы делилось пулингом);
//   2. вектор собственных признаков — что с самим бойцом;
//   3. задание сверху (роль, вес важности, цель) и короткая история.
//
// ЧЕСТНОСТЬ. Клетки, не разведанные владельцем бойца (бит 0 в BI), зануляются во всех слоях,
// кроме слоя «разведано». Иначе получится бот-экстрасенс: он выучится действовать по данным,
// которых в игре не видит, и заметить это почти невозможно. Туман у нас открывается навсегда,
// поэтому маска простая и памяти об устаревании не нужно.
import { G, U, UNITS, BI, BG, MO, ITEMS } from '../mem.js';
import { ЧИСЛО_ДЕЙСТВИЙ, НАПРАВЛЕНИЯ, луч, ШАГ, спит, дальность, враги, обмен, союзники } from './act.js';

export const R = 7;                       // радиус окна: смещения -7..+8
export const ОКНО = 16;
export const СЛОЁВ = 11;
// Три слоя про цели (поправка владельца: кого бить первым — решает юнит): мана врага (доля),
// «это маг» (типы 5–8) и «кого он бьёт» (1 — союзника, 0.5 — меня).
export const СЛОЙ = { ЗЕМЛЯ: 0, РАЗВЕДАНО: 1, СВОИ: 2, ЧУЖИЕ: 3, ЗВЕРИ: 4, СВОИ_ДОМА: 5, ЧУЖИЕ_ДОМА: 6, ПРЕДМЕТЫ: 7,
                      ЧУЖИЕ_МАНА: 8, ЧУЖИЕ_МАГИ: 9, ЧУЖИЕ_ЦЕЛЬ: 10 };
export const СВОИХ = 30;                  // собственные (16) + лучи (8) + «спит» + дальний бой (3) + обмен (2)
export const ЗАДАНИЯ = 13;                // роль (7) + вес важности (3) + точка задания (есть ли, dx, dy)
export const ИСТОРИИ = ЧИСЛО_ДЕЙСТВИЙ + 2;   // прошлое действие + куда сдвинулся с прошлого решения
export const ВЕКТОР = СВОИХ + ЗАДАНИЯ + ИСТОРИИ;

const TILE_INF = 0x3183c;
const П = ОКНО * ОКНО;

/** Роли: их набор общий для сети, наград и сценариев. */
export const РОЛИ = ['ATTACK_TO_DEATH', 'DEFEND_POINT', 'DISTRACT', 'RETREAT', 'HOLD', 'MOVE_TO', 'GATHER'];
export const ВЕСА = ['по возможности', 'обычный', 'любой ценой'];

/** Пустое наблюдение нужного размера: им заполняются места выбывших бойцов в батче. */
export function пустое() {
  return { окно: new Float32Array(СЛОЁВ * П), вектор: new Float32Array(ВЕКТОР) };
}

/**
 * Заполнить наблюдение для бойца.
 * @param задание {роль, вес, точка:{x,y}, цель} — то, что в бою придёт от тактика,
 *                а на первом этапе ставит сценарий.
 * @param память  {действие, x, y} — прошлое решение и позиция на нём.
 */
export function наблюдать(eng, боец, задание, память, вых = пустое()) {
  const m = eng.m, b = m.b;
  const окно = вых.окно, вектор = вых.вектор;
  окно.fill(0); вектор.fill(0);
  const мой = m.u8(UNITS + боец + U.OWNER);
  const cx = m.u16(UNITS + боец + U.X) >> 5, cy = m.u16(UNITS + боец + U.Y) >> 5;
  const W = m.u32(G.mapW), H = m.u32(G.mapH);
  const x0 = cx - R, y0 = cy - R;

  // ---- слои ландшафта и тумана
  for (let dy = 0; dy < ОКНО; dy++) {
    const y = y0 + dy;
    if (y < 0 || y >= H) continue;
    for (let dx = 0; dx < ОКНО; dx++) {
      const x = x0 + dx;
      if (x < 0 || x >= W) continue;
      const k = dy * ОКНО + dx, c = x + (y << 8);
      const разведано = b[BI + c] & 1;
      окно[СЛОЙ.РАЗВЕДАНО * П + k] = разведано;
      if (!разведано) continue;
      const слово = m.u16(BG + (y << 9) + x * 2);
      окно[СЛОЙ.ЗЕМЛЯ * П + k] = (слово & 0xf800) ? 0 : (b[TILE_INF + (слово & 0x7ff)] & 1);
    }
  }
  // ---- юниты и здания
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    if ((m.u8(UNITS + i + U.STATE) & 0xf0) === 0x60) continue;    // умирает / труп — не юнит
    const x = (m.u16(UNITS + i + U.X) >> 5) - x0, y = (m.u16(UNITS + i + U.Y) >> 5) - y0;
    if (x < 0 || y < 0 || x >= ОКНО || y >= ОКНО) continue;
    const k = y * ОКНО + x;
    if (!окно[СЛОЙ.РАЗВЕДАНО * П + k]) continue;
    const вл = m.u8(UNITS + i + U.OWNER), т = m.u8(UNITS + i + U.TYPE);
    const макс = m.u8(UNITS + i + U.HPMAX);
    const доля = макс ? m.u8(UNITS + i + U.HP) / макс : 1;
    let слой;
    if (т >= 0x1a) слой = вл === мой ? СЛОЙ.СВОИ_ДОМА : СЛОЙ.ЧУЖИЕ_ДОМА;
    else if (т >= 14) слой = СЛОЙ.ЗВЕРИ;             // дикая живность — среда, а не сторона
    else слой = вл === мой ? СЛОЙ.СВОИ : СЛОЙ.ЧУЖИЕ;
    окно[слой * П + k] = Math.max(окно[слой * П + k], доля || 0.05);
    if (т < 0x1a && вл !== мой) {
      const маг = m.u8(UNITS + i + U.MAG);
      окно[СЛОЙ.ЧУЖИЕ_МАНА * П + k] = Math.max(окно[СЛОЙ.ЧУЖИЕ_МАНА * П + k], маг ? m.u8(UNITS + i + U.MANA) / маг : 0);
      if (т >= 5 && т <= 8) окно[СЛОЙ.ЧУЖИЕ_МАГИ * П + k] = 1;
      const ц = m.u32(UNITS + i + U.TARGET);
      if (ц === боец) окно[СЛОЙ.ЧУЖИЕ_ЦЕЛЬ * П + k] = Math.max(окно[СЛОЙ.ЧУЖИЕ_ЦЕЛЬ * П + k], 0.5);
      else if (ц && !(m.u8(UNITS + ц + U.FLAGS5B) & 1) && m.u8(UNITS + ц + U.OWNER) === мой && m.u8(UNITS + ц + U.TYPE) < 0x1a) окно[СЛОЙ.ЧУЖИЕ_ЦЕЛЬ * П + k] = 1;
    }
  }
  // ---- предметы на земле (список 0x31b7c, поля +1/+2 — клетка)
  for (let i = m.u32(0x31b7c); i; i = m.u32(ITEMS + i + 0xc)) {
    const x = m.u8(ITEMS + i + 1) - x0, y = m.u8(ITEMS + i + 2) - y0;
    if (x < 0 || y < 0 || x >= ОКНО || y >= ОКНО) continue;
    const k = y * ОКНО + x;
    if (окно[СЛОЙ.РАЗВЕДАНО * П + k]) окно[СЛОЙ.ПРЕДМЕТЫ * П + k] = 1;
  }

  // ---- собственные признаки
  const макс = m.u8(UNITS + боец + U.HPMAX) || 1;
  const дир = m.u8(UNITS + боец + U.DIR);
  let v = 0;
  вектор[v++] = m.u8(UNITS + боец + U.HP) / макс;
  вектор[v++] = макс / 255;
  вектор[v++] = m.u8(UNITS + боец + U.ATK) / 255;
  вектор[v++] = m.u8(UNITS + боец + U.DEF) / 255;
  вектор[v++] = m.u8(UNITS + боец + U.SPD) / 255;
  вектор[v++] = m.u8(UNITS + боец + U.MANA) / 255;
  вектор[v++] = m.u8(UNITS + боец + U.TYPE) / 26;
  вектор[v++] = дир ? Math.sin((дир - 1) * Math.PI / 4) : 0;
  вектор[v++] = дир ? Math.cos((дир - 1) * Math.PI / 4) : 0;
  вектор[v++] = (m.u8(UNITS + боец + U.STATE) >> 4) / 7;      // группа состояния 0x0x..0x6x
  вектор[v++] = m.u8(UNITS + боец + U.ORDER) === 0xff ? 1 : 0; // прошлый приказ уже подхвачен
  вектор[v++] = Math.min(m.u8(UNITS + боец + 0x40), 12) / 12;  // сколько тиков упирается
  вектор[v++] = m.u32(UNITS + боец + U.TARGET) ? 1 : 0;
  вектор[v++] = Math.min(m.u16(UNITS + боец + U.FOOD), 200) / 200;
  вектор[v++] = cx / 64; вектор[v++] = cy / 64;                // где на карте (грубо)
  // Сколько клеток проходимо в каждую из восьми сторон (доля от ШАГ): край карты, скала, вода и
  // деревья — всё одинаково «стена». Окно это тоже показывает, но явный признак дешевле выучить,
  // и без него сеть упиралась в край, отступая.
  for (const [dx, dy] of НАПРАВЛЕНИЯ) вектор[v++] = луч(m, cx, cy, dx, dy) / ШАГ;
  вектор[v++] = спит(eng, боец) ? 1 : 0;                      // спит (родное состояние 0x2x); доля HP — первый признак
  // Дальний бой: есть ли он, дальность в клетках и дистанция до ближайшего врага в единицах
  // своей дальности (у ближнего бойца — в клетках/2). Оценка обмена — отступление от плана
  // (AI-PLAN §2.1 даёт в окне только HP врагов): сводка из статов врагов в окне, чтобы боец
  // видел, стоит ли ввязываться; см. заметку, §4ж.
  const r = дальность(m, боец), в = враги(eng, боец);
  const ближ = в.length ? в.reduce((a, b) => a.d < b.d ? a : b).d : 16;
  вектор[v++] = r ? 1 : 0;
  вектор[v++] = r / 8;
  вектор[v++] = Math.min(2, ближ / (r || 2)) / 2;
  const о = обмен(m, боец, в, союзники(eng, боец));
  вектор[v++] = Math.min(8, о.ближний) / 8;
  вектор[v++] = Math.min(8, о.общий) / 8;

  // ---- задание сверху
  const роль = задание ? РОЛИ.indexOf(задание.роль) : -1;
  if (роль >= 0) вектор[СВОИХ + роль] = 1;
  const вес = задание ? Math.max(0, Math.min(2, задание.вес | 0)) : 1;
  вектор[СВОИХ + РОЛИ.length + вес] = 1;
  // Точка задания относительно бойца, в долях от 16 клеток: без неё сеть не знает, далеко ли
  // до поста или до метки, и «держать» и «к цели» для неё неотличимы.
  if (задание && задание.точка) {
    const т = СВОИХ + РОЛИ.length + 3;
    вектор[т] = 1;
    вектор[т + 1] = Math.max(-1, Math.min(1, (задание.точка.x - cx) / 16));
    вектор[т + 2] = Math.max(-1, Math.min(1, (задание.точка.y - cy) / 16));
  }

  // ---- история
  const б = СВОИХ + ЗАДАНИЯ;
  if (память && память.действие >= 0) вектор[б + память.действие] = 1;
  if (память && память.x !== undefined) {
    вектор[б + ЧИСЛО_ДЕЙСТВИЙ] = Math.max(-1, Math.min(1, (cx - память.x) / 4));
    вектор[б + ЧИСЛО_ДЕЙСТВИЙ + 1] = Math.max(-1, Math.min(1, (cy - память.y) / 4));
  }
  return вых;
}
