  /** Хост: запустить. Все готовы — сразу; нет — отсчёт, который сбрасывает любое изменение в лобби. */
  запустить() {
    if (!this.яХост || this.фаза !== 'лобби') return;
    if (this.отсчёт) { this.сбросОтсчёта(true); return; }
    if (this.всеГотовы) return this.старт();
    this.канал.послать({ вид: 'отсчёт', сек: ОТСЧЁТ_СЕК });
    this.таймерЗапуска = setTimeout(() => { this.таймерЗапуска = null; if (this.фаза === 'лобби') this.старт(); }, ОТСЧЁТ_СЕК * 1000);
  }
  /** Хост: снять отсчёт (изменилось что-то в лобби или нажали ещё раз). */
  сбросОтсчёта(вслух = false) {
    if (this.таймерЗапуска) { clearTimeout(this.таймерЗапуска); this.таймерЗапуска = null; if (this.канал && this.яХост) this.канал.послать({ вид: 'отсчёт', отмена: true }); }
    else if (вслух && this.канал && this.яХост) this.канал.послать({ вид: 'отсчёт', отмена: true });
  }

  /** Хост в идущей партии: лобби вошедшим — миссия, кто за кого, свободные племена. */
  описатьПартию() {
    const л = this.лобби;
    this.канал.послать({ вид: 'лобби', идёт: true, миссия: this.параметры.миссия, сложность: this.параметры.сложность, племена: this.параметры.племена,
                         доступные: л.доступные, открытая: л.открытая, зрители: л.зрители, режим: this.параметры.режим, места: this.параметры.места, быстрый: this.параметры.быстрый,
                         состояние: this.состояниеПартии(), слотыЗрителей: (this.слотыЗрителей(), л.слотыЗрителей) });
  }
  /** Индикаторы идущей партии: ход, время, живые по цветам, кто под ИИ. */
  состояниеПартии() {
    const m = this.о.память(), лс = this.лс; if (!m || !лс) return null;
    const живые = {};
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
      const вл = m.u8(UNITS + i + U.OWNER), t = m.u8(UNITS + i + U.TYPE); if (вл > 7) continue;
      const з = живые[вл] ??= { бойцов: 0, зданий: 0 }; if (t >= 1 && t <= 13) з.бойцов++; else if (t >= 0x1a) з.зданий++;
    }
    return { ход: лс.ход, секунд: Math.round(лс.шаг * 0.055), живые, подИИ: [...this.подИИ] };
  }
