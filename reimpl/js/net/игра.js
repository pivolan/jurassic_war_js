// Сетевая партия в браузере (наше): лобби, старт, локстеп, снимки, выбывшие. Интерфейс — в
// web/game.js, здесь только состояние и протокол. Всё общение идёт через релей (tools/net_server.mjs),
// который рассылает каждое сообщение всем в комнате, включая отправителя — поэтому хост тоже
// «получает» свой старт и свой снимок и обрабатывает их как все.
//
// Сообщения (JSON, вид):
//   лобби   ← хост: { миссия, сложность, племена: {игрок: племя}, доступные: [племя...] }
//   выбор   → все:  { племя }              — хочу такое племя; хост проверяет и рассылает лобби
//   миссия  → хост: { миссия, сложность } — хост сменил карту; переигрывает доступные племена
//   старт   ← хост: { миссия, сложность, хост, племена }; следом двоичный снимок (ход 0)
//   ход     ↔ все:  пакет локстепа (js/net/lockstep.js)
//   нужен_снимок → хост: { ход } — разошлись, пришли состояние; хост шлёт снимок на границе хода
//   снимокJS ← хост: { кому, ход, данные } — JS-часть состояния (маршруты, цели магов, патрули), идёт перед двоичным снимком
//   пауза   ↔ все:  { вкл }
//   состав  ← релей: { хост, участники, ушёл?, вернулся? }
//
// Переподключение. Место в комнате привязано к ключу (случайная строка в localStorage браузера,
// её знает только релей). Вылетевшего ждут: у остальных окно с таймером (ЖДАТЬ_МС) и кнопкой
// «не ждать»; решение — когда все оставшиеся проголосовали (или у всех вышел таймер, голос уходит
// сам). Пока ждут — локстеп стоит сам собой. Вернувшийся приходит с тем же ключом, хост шлёт ему
// старт заново (повтор) и снимок на границе хода, и всем — «вернулся с хода N»: с этого хода его
// пакеты снова нужны, а свои пакеты за ходы от N остальные ему досылают. Никто не останавливается.
//   не_ждать → все: { кого }                — голос: играем без него
//   место   → хост: { номер, действие: сесть|встать|закрыть|открыть|компьютер|племя, племя? } — места-цвета (режим «наборы»)
//   готов   → хост: { вкл }                 — игрок в лобби готов / не готов; хост держит и рассылает в «лобби» (готовы)
//
// Два режима партии. «армии» — как на карте: каждый игрок берёт племя из тех, у кого на карте есть
// армия (кампания). «наборы» (сетевые карты, пак 13): у карты столько мест-цветов, сколько стартовых
// точек; место открыто, закрыто, за компьютером или за игроком; игрок сам выбирает племя (состав
// стартового набора и спрайты), а стороной в симуляции служит цвет (владелец). При старте хост
// сносит армии карты и расставляет наборы (js/port/skirmish.js). «быстрый» — 100k еды и два юнита.
//   выгнать → релей: { кого }               — хост выгоняет из лобби (релей закрывает соединение и забывает ключ)
//   сдаюсь  → все: { ход }                  — игрок сдаётся: на ходу `ход` его войска и постройки гибнут, он выходит из локстепа
//   чат     → все: { текст }                — чат комнаты; релей подписывает игрока и имя
//   отсчёт  ← хост: { сек } | { отмена }    — запуск через сек секунд; любое изменение в лобби сбрасывает
//   хочу_играть → хост: { племя? }          — из лобби идущей партии: вернуться на своё место или взять свободное племя
//   хочу_смотреть → хост: {}                — из лобби идущей партии: смотреть (роль наблюдателя у релея)
//   лобби с идёт:true ← хост                 — вошедшему в идущую партию: что за партия, кто за кого
//
// Наблюдатель: входит в любую комнату (роль «наблюдатель»), племени и пакетов у него нет, он не
// хост, приказы не отдаёт; получает снимок и крутит ту же симуляцию. Туман — на выбор: без тумана,
// за одно племя (движок открывает карту его юнитами) или за всех людей сразу (объединение).
//   вернулся ← хост: { игрок, сХода, применить } — игрок снова в строю с хода сХода; с хода «применить» его племя снова человек
//
// Встроенный ИИ (скриптовый компьютер оригинала) и выбывшие: когда все решили не ждать
// вылетевшего, его племя на ходу T+1 (T — последний ход, за который от него был пакет; он у всех
// один) перестаёт быть человеком и включается ИИ этого слота. Когда он вернулся — на ходу
// «применить» ИИ выключается и племя снова человек. Оба переключения — по плану локстепа,
// поэтому на всех машинах строго на одном ходу. Список «под ИИ» хост шлёт вернувшемуся со стартом.
