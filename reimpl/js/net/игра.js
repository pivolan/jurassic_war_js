  наСостав(с) {
    for (const у of с.участники) this.имена.set(у.игрок, у.имя);
    if (с.ушёл !== undefined) {
      if (this.активна && this.лс && this.лс.игроки.includes(с.ушёл) && this.лс.ушедшие.get(с.ушёл)?.с !== Infinity) this.отключился(с.ушёл);
      else this.статус(this.т('{p} вышел', { p: this.имя(с.ушёл) }));
    }
    if (с.роль !== undefined && с.роль !== this.я) {
      const у = this.участники.find(у => у.игрок === с.роль);
      if (у) this.статус(this.т(у.роль === 'наблюдатель' ? '{p} теперь зритель' : '{p} теперь играет', { p: this.имя(с.роль) }));
    }
    if (с.вернулся !== undefined && с.вернулся !== this.я) {
      this.статус(this.т('{p} вернулся', { p: this.имя(с.вернулся) }));
      this.снятьОжидание(с.вернулся);
    }
    // Хост в идущей партии: каждому вошедшему — что за партия и кто за кого; дальше он сам
    // попросит «хочу_играть» или «хочу_смотреть» из лобби
    if (this.активна && this.яХост && this.параметры) this.описатьПартию();
    if (this.фаза === 'лобби' && this.яХост) this.хостПересчитать();
    else if (this.активна && this.яХост && this.канал.хост !== this.былХост) this.опубликовать();   // хост сменился — новый публикует комнату
    this.былХост = this.канал?.хост;
    this.решитьВсех();
    this.о.наЛобби?.();
  }

  // ---------------------------------------------------------------- вылетевшие
  отключился(игрок) {
    if (this.ожидание.has(игрок)) return;
    const о = { с: Date.now(), голоса: new Set(), таймер: null };
    о.таймер = setTimeout(() => this.неЖдать(игрок), ЖДАТЬ_МС);   // вышло время — голос уходит сам
    this.ожидание.set(игрок, о);
    this.статус(this.т('{p} отключился — ждём его возвращения', { p: this.имя(игрок) }));
    this.о.наОжидание?.();
  }
  /** Мой голос: играем без него. Решение — когда так сказали все, кто остался. */
  неЖдать(игрок) {
    if (!this.ожидание.has(игрок)) return;
    this.канал?.послать({ вид: 'не_ждать', кого: игрок });
  }
  снятьОжидание(игрок) {
    const о = this.ожидание.get(игрок);
    if (!о) return;
    clearTimeout(о.таймер); this.ожидание.delete(игрок);
    this.о.наОжидание?.();
  }
  /** Все ли оставшиеся проголосовали не ждать. Считается по потоку сообщений релея — одинаково у всех. */
  решить(игрок) {
    const о = this.ожидание.get(игрок);
    if (!о) return;
    const оставшиеся = this.игрокиКомнаты.map(у => у.игрок).filter(и => и !== игрок && !this.ожидание.has(и) && this.лс.игроки.includes(и));
    if (!оставшиеся.every(и => о.голоса.has(и))) return;
    this.снятьОжидание(игрок);
    this.лс.выбыл(игрок);
    const т = this.племена[игрок];
    if (т !== undefined) { const ход = this.лс.ушедшие.get(игрок).до + 1; this.лс.наХоду(ход, () => this.передатьИИ(т)); }
    this.статус(this.т('{p} выбыл — его племя берёт ИИ', { p: this.имя(игрок) }));
  }

  /** Ход применения сдачи (одинаковый у всех): войска и постройки племени гибнут, игрок выходит из локстепа,
   *  остальные видят короткое сообщение. Племя остаётся «человеческим» без юнитов — так проверка конца
   *  партии засчитает победу последнему оставшемуся. */
  сдался(кто, т) {
    const eng = this.о.движок(), m = eng.m;
    let n = 0;
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      const b = UNITS + i; if (m.u8(b + U.FLAGS5B) & 1 || m.u8(b + U.OWNER) !== т) continue;
      const st = m.u8(b + U.STATE); if (st === 0x6f || st === 0x60) continue;
      m.w8(b + U.HP, 0); m.w8(b + U.STATE, 0x6f); n++;                   // как 0x1ebdc: дальше 0x19693 сам сделает труп
      Очередь.очистить(eng, i);
    }
    this.лс.выбыл(кто);
    const текст = this.т('{p} сдался', { p: this.имя(кто) });
    this.статус(текст); this.о.наСообщение?.(текст);
    if (кто === this.я) { this.конец = 'defeat'; this.о.наКонец?.('defeat'); setTimeout(() => this.выйти(), 2500); }
    return n;
  }
  /** Сказать в чат комнаты (релей подпишет отправителя и разошлёт всем в комнате). */
  сказать(текст) { if (this.канал && текст.trim()) this.канал.послать({ вид: 'чат', текст: текст.slice(0, 300) }); }
  /** Текущий список людей для симуляции: все племена партии, кроме тех, что под ИИ. */
  люди() { return [...new Set(Object.values(this.племена))].filter(т => !this.подИИ.has(т)); }
  передатьИИ(т) {
    this.подИИ.add(т); const m = this.о.память(); задатьЛюдей(this.люди(), m);
    for (let s = 0; s < 8; s++) if (m.u8(0x32ae4 + s) === т) включитьИИ(m, s);
    this.статус(this.т('ИИ взял {t}', { t: ПЛЕМЯ(т) }));
  }
  вернутьЧеловеку(т) {
    if (!this.подИИ.has(т)) return;
    this.подИИ.delete(т); const m = this.о.память(); задатьЛюдей(this.люди(), m);
    for (let s = 0; s < 8; s++) if (m.u8(0x32ae4 + s) === т) m.w8(0x32aec + s, 0);
    this.статус(this.т('{t} снова у человека', { t: ПЛЕМЯ(т) }));
  }
