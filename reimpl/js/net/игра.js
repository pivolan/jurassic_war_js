  выгнать(игрок) { if (this.яХост && this.фаза === 'лобби' && !this.лобби.идёт) this.канал?.послать({ вид: 'выгнать', кого: игрок }); }
  /** Сдаться: племя отдаётся ИИ у всех на одном ходу, сам выходим. */
  сдаться() { if (this.активна && !this.наблюдатель && this.лс) this.канал?.послать({ вид: 'сдаюсь', ход: this.лс.ход + this.лс.задержка + 1 }); }
