    к.наСлужебное = (об) => { if (this.канал === к) this.наСлужебное(об); };
    к.наХод = (п) => { if (this.лс) this.лс.принять(п); else if (this.фаза === 'игра') this.почта.push(п); };
    this.канал = к; this.фаза = 'лобби'; this.роль = 'игрок';
    this.статус(this.т('скирмиш: выберите карту и соперников'));
