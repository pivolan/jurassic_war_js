  async сестьИгроком(номер) {
    if (this.фаза !== 'лобби') return;
    if (this.наблюдатель) {
      await this.сменитьРоль('игрок');
      // хост пересчитывает места по новому составу (грузит карту, до секунды) — ждём, потом садимся на нужное
      for (let k = 0; k < 40 && !this.лобби.места.some(м => м.кто === 'игрок' && м.игрок === this.я); k++) await new Promise(r => setTimeout(r, 100));
    }
    if (номер !== undefined) this.место(номер, 'сесть');
  }
  /** Сменить роль (игрок ↔ наблюдатель): заново войти в ту же комнату с тем же ключом. */
  /** Игрок ⇄ наблюдатель на месте: релей меняет роль в том же соединении (номер игрока и ключ
   *  сохраняются), лобби приходит новым «составом». Раньше это делалось перезаходом в комнату —
   *  комната «перезагружалась», терялись чат и снимок. */
  async сменитьРоль(роль) {
    if (!this.канал || this.фаза !== 'лобби') return;
    if ((this.канал.роль || 'игрок') === роль) return;
    this.ролеваяОшибка = null;
    this.канал.ролью(роль);
    for (let k = 0; k < 60 && (this.канал?.роль || 'игрок') !== роль && !this.ролеваяОшибка; k++) await new Promise(r => setTimeout(r, 50));
    if (this.ролеваяОшибка) { const e = this.ролеваяОшибка; this.ролеваяОшибка = null; throw new Error(e); }
    this.роль = this.канал?.роль || 'игрок';
  }

