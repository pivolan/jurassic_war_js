  /**
   * @param о обвязка:
   *   загрузить(миссия, племя, сложность) → Promise<eng>  — загрузить миссию на этой машине (ресурсы + состояние)
   *   владельцы(миссия, племя) → Promise<number[]>          — какие племена на карте есть (с бойцами)
   *   движок() → eng, память() → Mem
   *   наЛобби(), наСтатус(текст), наНачало(), наСнимок(ход), наКонец('victory'|'defeat'), наПауза(вкл), наВыход(),
   *   наСообщение(текст) — короткое игровое уведомление всем, наЧат({игрок, имя, текст}) — чат комнаты
   *   наОжидание() — кого ждём, изменилось (this.ожидание); ключ — ключ игрока для релея (строка) или null
   */
  constructor(о) {
    this.о = о;
    this.канал = null; this.лс = null;
    this.фаза = 'нет';                 // нет | лобби | игра
    this.лобби = { миссия: МИССИЯ_ПО_УМОЛЧАНИЮ, сложность: 1, племена: {}, доступные: [], открытая: false, зрители: true, готовы: {}, режим: 'наборы', места: [], быстрый: false, украшения: true, слотыЗрителей: {} };
    this.расы = {};                    // на партию: игрок → племя (набор и спрайты); в режиме «армии» = племена
    this.сдавшиеся = new Set();        // кто сдался (их выход из комнаты — не обрыв)
    this.отсчёт = null;                // { до: время } — идёт отсчёт до старта
    this.таймерЗапуска = null;         // хост: setTimeout старта
    this.племена = {};                 // на партию: игрок → племя
    this.моёПлемя = null; this.хостПлемя = null;
    this.готова = false;               // снимок положен, можно крутить
    this.ожидающийСнимок = null;       // снимок пришёл раньше, чем загрузилась миссия
    this.запросы = new Set();          // хост: кому прислать снимок на границе хода
    this.запрошен = false;             // клиент: снимок уже запрошен
    this.конец = null;                 // victory | defeat — чтобы не сообщать дважды
    this.ждали = false;
    this.почта = [];                   // пакеты ходов, пришедшие пока грузилась миссия (локстепа ещё нет)
    this.снимокJS = null;              // JS-часть снимка, пришедшая перед двоичной
    this.ожидание = new Map();         // игрок → { с: время, голоса: Set, таймер } — вылетевшие, которых ждём
    this.имена = new Map();            // игрок → имя (участники приходят и уходят, имена помним)
    this.параметры = null;             // старт партии — хост повторяет его вернувшемуся
    this.вернувшиеся = new Set();      // хост: кому снимок уйдёт как вернувшемуся (всем — «снова в игре с хода N»)
    this.новички = new Map();          // хост: игрок → племя, вошёл в идущую партию, ещё не оформлен
    this.роль = 'игрок';               // игрок | наблюдатель
    this.подИИ = new Set();            // племена людей, которых сейчас ведёт встроенный ИИ (выбывшие)
    this.туман = { режим: 'все', племя: null };   // наблюдателю: нет | племя | все
    this.былХост = null;
    this.журнал = [];
  }

  get я() { return this.канал?.игрок ?? null; }
  get яХост() { return !!this.канал?.яХост; }
  get активна() { return this.фаза === 'игра'; }
  get участники() { return this.канал?.участники || []; }
  get игрокиКомнаты() { return this.участники.filter(у => у.роль !== 'наблюдатель'); }
