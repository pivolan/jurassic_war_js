    this.канал.послать({ вид: 'старт', миссия: л.миссия, сложность: л.сложность, хост: this.я, племена: л.племена, доступные: л.доступные, открытая: л.открытая, зрители: л.зрители,
                         режим: л.режим, места: л.места.filter(м => м.кто !== 'закрыто' && (л.режим !== 'наборы' || м.кто !== 'открыто')), быстрый: л.быстрый, расы, украшения: !!л.украшения, автоеда: !!л.автоеда });
