// Локальный канал (наше): та же игра, что по сети, но без релея и без сети вообще.
//
// Скирмиш — это сетевая партия, в которой участник ровно один: мы. Чтобы не писать второй
// путь запуска, подменяем канал заглушкой с тем же набором методов: всё, что «отправляется»,
// тут же возвращается нам самим — ровно так же ведёт себя релей, который шлёт сообщение всем
// в комнате, включая отправителя. Локстеп при этом крутится как обычно, просто ждать некого:
// пакеты хода приходят от единственного игрока, то есть от нас.
//
// Возврат делается через queueMicrotask: синхронный вызов обработчика прямо из послать()
// означал бы повторный вход в код, который ещё не закончил свою работу (например, «старт»
// внутри обработчика «лобби»).
export class ЛокальныйКанал {
  constructor(имя = 'игрок') {
    this.локальный = true;
    this.адрес = null; this.комната = 'скирмиш'; this.имя = имя;
    this.игрок = 0; this.хост = 0; this.яХост = true; this.роль = 'игрок'; this.вернулся = false; this.закрыт = false;
    this.участники = [{ игрок: 0, имя, роль: 'игрок' }];
    this.наХод = null; this.наСостав = null; this.наСнимок = null; this.наСлужебное = null;
  }
  /** Совместимость с Канал.подключиться: подключаться некуда, сразу готов. */
  async подключиться() { return this; }

  /** Роль в скирмише: игрок или наблюдатель (смотреть, как дерутся компьютеры). Релея нет,
   *  поэтому меняем у себя и тут же сообщаем «состав» — обвязка ждёт именно его. */
  ролью(роль) {
    if (this.закрыт) return;
    const р = роль === 'наблюдатель' ? 'наблюдатель' : 'игрок';
    if (this.роль === р) return;
    this.роль = р;
    this.участники = [{ игрок: 0, имя: this.имя, роль: р }];
    queueMicrotask(() => { if (!this.закрыт) this.наСостав?.({ вид: 'состав', участники: this.участники, хост: 0, роль: 0 }); });
  }
  /** Пакет хода отдаём сразу, без микрозадачи: локстеп кладёт его себе в таблицу и тут же
   *  исполняет этот ход, так что приказ доходит в тот же тик, как в кампании. Повторного входа
   *  тут нет — «принять» только раскладывает данные по таблицам. */
  ход(пакет) {
    if (this.закрыт) return;
    const копия = JSON.parse(JSON.stringify(пакет)); копия.игрок = 0;
    this.наХод?.(копия);
  }
  послать(об) {
    if (this.закрыт) return;
    const копия = JSON.parse(JSON.stringify(об));
    копия.игрок = 0;                           // отправителя проставляет сервер — здесь это мы
    queueMicrotask(() => {
      if (this.закрыт) return;
      if (копия.вид === 'ход') { this.наХод?.(копия); return; }
      if (копия.вид === 'состав') { this.наСостав?.(копия); return; }
      this.наСлужебное?.(копия);
    });
  }
  /** Снимок самому себе не нужен: память уже в нужном состоянии. */
  снимок() {}
  закрыть() { this.закрыт = true; this.наХод = this.наСостав = this.наСнимок = this.наСлужебное = null; }
}
