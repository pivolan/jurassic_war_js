export const ШАГОВ_В_ХОДЕ = 4;      // 4 × 55 мс = 220 мс на ход
export const ЗАДЕРЖКА = 2;          // ходов упреждения: приказ исполнится через 2 хода
export const СНИМОК = { от: 0x30000, до: 0x123000 };   // область симуляции (как у реплеев)

// Зрительское внутри области симуляции: при восстановлении снимка это остаётся своим.
// Туман (бит 0 сетки BI) — отдельно, см. восстановить().
export const ЗРИТЕЛЬ = [
  [0x30098, 0x300a0],   // скорость игры/прокрутки, чувствительность мыши (настройки)
  [0x30380, 0x30388],   // подсказка над кнопкой постройки: показанная и наведённая
  [0x30c4c, 0x30c4d],   // звук включён
  [0x31aca, 0x31af0],   // форма курсора, «ожидающий клик», выделение, флаги панели, камера
  [0x31b2c, 0x31b58],   // смещения миникарты, состояние кнопок панели
  [0x31b64, 0x31b66],   // моё племя
  [0x333c1, 0x333c9],   // таймеры строк чата
  [0x3886c, 0x38870],   // гашение повторов голоса
  [0x38870, 0x38be8],   // очередь заявок на звук (0x2000d: слот на каждый id по 8 байт) — что слышно, зависит от тумана
  [0x393a4, 0x393a8],   // второй ГСЧ: его двигают голоса и клики, на симуляцию не влияет
  [0x41910, 0x41928],   // сообщение внизу экрана и его таймер
  [0x427c0, 0x427cc],   // полосы и флажки панели выделенного юнита
  [0x488c0, 0x488f0],   // окно карты (вьюпорт)
];
// Байт +7 записи юнита: бит 0x80 — выделение, младшие биты — тоже интерфейс (economy.js 0x1c0fe
// снимает их вместе с выделением). Симуляция его только обнуляет при рождении и смерти.
export const F07_ЗРИТЕЛЬ = true;

// ---------------------------------------------------------------- контрольная сумма
// Хешируем только состояние симуляции. Что исключено и почему — notes/ROADMAP.md §7a:
// камера, курсор и выделение — это зритель; пул эффектов трогает отрисовка; состояние второго
// ГСЧ 0x393a4 зависит от звука и от того, сколько игрок кликал по своим юнитам; туман — свой.
export const ОБЛАСТИ = [                    // юниты и сетка BI считаются отдельно, см. хеш()
  [ITEMS, BG],                      // предметы на земле
  [BG, BI],                         // карта
  [MO, MO + 0xb000],                // направления и летающие
  [0x31ab0, 0x31aca],               // тик, шаг, сложность, миссия
  [0x31af0, 0x31b2c],               // размеры карты
  [0x31b58, 0x31b64],               // диапазон и seed ГСЧ: диапазон не всегда выставляют перед вызовом, он часть состояния
  [0x31b66, 0x31b68],               // младшие биты шага
  [0x31b6c, 0x31c28],               // головы списков
  [0x31c28, 0x31c68],               // еда и склады
  [0x32ae4, 0x32e00],               // владельцы и состояние ИИ по слотам
  [0x33358, 0x333c0],               // условия и счётчики партии
  [0x393a0, 0x393a4],               // счётчик вызовов основного ГСЧ — самый чуткий признак
];

/** FNV-1a по состоянию симуляции. Возвращает беззнаковое 32-битное. */
export function хеш(eng) {
  const b = eng.m.b;
  let h = 0x811c9dc5;
  const mix = (v) => { h ^= v; h = Math.imul(h, 0x01000193) >>> 0; };
  // Юниты: байт +7 (выделение и прочие пометки панели) — интерфейсный, в хеш не идёт; бит 0 байта
  // +0x42 — «нарисован в кадре», его ставит отрисовка (scene.js afterBlit), читают только звуки.
  // Здания (вид ≥ 0x1a): номер спрайта +0x2d/+0x2e и счётчики огня/анимации +0x27/+0x28 пишет
  // отрисовка (scene.js 0x2550f), и только пока здание на экране — у каждого своё, симуляция их не читает.
  for (let i = UNITS; i < UNITS + 600 * 96; i += 96) {
    const здание = b[i + U.TYPE] >= 0x1a;
    for (let k = 0; k < 96; k++) {
      if (k === U.F07) continue;
      if (здание && (k === 0x27 || k === 0x28 || k === 0x2d || k === 0x2e)) continue;
      mix(k === 0x42 ? b[i + k] & 0xfe : b[i + k]);
    }
  }
  for (const [от, до] of ОБЛАСТИ) for (let a = от; a < до; a++) mix(b[a]);
  // Занятость и разведка: бит 0 — туман, он у каждого свой.
  for (let a = BI; a < MO; a++) mix(b[a] & 0xfe);
  return h >>> 0;
}

/** Полный хеш всей области симуляции — для проверки двух движков в одном процессе. */
export function хешПолный(eng) {
  const b = eng.m.b;
  let h = 0x811c9dc5;
  for (let a = СНИМОК.от; a < СНИМОК.до; a++) { h ^= b[a]; h = Math.imul(h, 0x01000193) >>> 0; }
  return h >>> 0;
}

/** Снимок области симуляции: то, что уезжает подключившемуся игроку. */
export const снимок = (eng) => eng.m.b.slice(СНИМОК.от, СНИМОК.до);

/** Положить снимок хоста, сохранив своё зрительское: племя, камеру, выделение, туман, настройки. */
export function восстановить(eng, данные) {
  if (данные.length !== СНИМОК.до - СНИМОК.от) throw new Error(`снимок не того размера: ${данные.length} вместо ${СНИМОК.до - СНИМОК.от}`);
  const b = eng.m.b;
  const своё = ЗРИТЕЛЬ.map(([от, до]) => b.slice(от, до));
  const туман = new Uint8Array(0xb000);
  for (let k = 0; k < 0xb000; k++) туман[k] = b[BI + k] & 1;
  b.set(данные, СНИМОК.от);
  ЗРИТЕЛЬ.forEach(([от], k) => b.set(своё[k], от));
  for (let k = 0; k < 0xb000; k++) b[BI + k] = (b[BI + k] & 0xfe) | туман[k];
}

