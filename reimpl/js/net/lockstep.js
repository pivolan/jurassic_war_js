/** Зрительское ли это место (для сравнения памяти двух машин в проверках). */
export function зрительское(a) {
  for (const [от, до] of ЗРИТЕЛЬ) if (a >= от && a < до) return true;
  if (a >= UNITS && a < UNITS + 600 * 96 && [U.F07, 0x42].includes((a - UNITS) % 96)) return true;
  return false;
}

// ---------------------------------------------------------------- сам локстеп
export class Локстеп {
  /**
   * @param eng движок
   * @param {number} игрок  номер игрока в комнате (его проставил релей)
   * @param {number[]} игроки список всех номеров игроков в партии
   * @param настройки { шаговВХоде, задержка, шли(пакет) — как отправлять }
   */
  constructor(eng, игрок, игроки, настройки = {}) {
    this.eng = eng;
    this.игрок = игрок;
    this.игроки = игроки.slice().sort((a, b) => a - b);
    this.шаговВХоде = настройки.шаговВХоде ?? ШАГОВ_В_ХОДЕ;
    this.задержка = настройки.задержка ?? ЗАДЕРЖКА;
    // Сверять состояние не с кем, когда игрок один (скирмиш): хеш каждой ход — это лишние
    // сотни килобайт перебора на тик, и на плавность это видно.
    this.безХеша = !!настройки.безХеша;
    this.шли = настройки.шли ?? null;
    this.шаг = 0;                    // сколько тиков уже сделано
    this.ход = 0;                    // текущий ход
    this.мои = [];                   // приказы, набранные в этом ходу
    this.пакеты = new Map();         // «ход:игрок» → массив приказов
    this.хеши = new Map();           // ход → наш хеш после этого хода
    this.чужиеХеши = new Map();      // «ход:игрок» → хеш
    this.расхождение = null;         // { ход, игрок, свой, чужой }
    this.ждём = null;                // кого ждём, если стоим
    this.ушедшие = new Map();        // игрок → { до, с }: пакеты не нужны за ходы (до, с) — выбыл после `до`, вернулся с хода `с`
    this.отправлен = -1;             // до какого хода включительно мы уже разослали пакеты
    this.планы = new Map();          // ход → [fn]: сделать в начале хода до приказов, одинаково у всех (вход нового игрока)
    // Первые ходы пустые у всех: приказы из них ещё не могли появиться.
    for (let t = 0; t < this.задержка; t++)
      for (const и of this.игроки) this.пакеты.set(`${t}:${и}`, []);
    this.отправлен = this.задержка - 1;
  }

  /** Отдать приказ своему юниту. Исполнится через ЗАДЕРЖКА ходов. */
  прикажи(юнит, код, цель = 0, x = 0, y = 0) {
    this.мои.push({ юнит, код, цель, x, y });
  }

  /** Пакет на ход `ход` из набранных приказов (или пустой). Хеш — за последний сыгранный ход. */
  пакет(ход, приказы) {
    const сыгран = this.ход - 1;
    return { вид: 'ход', ход, игрок: this.игрок, приказы,
             хешХод: сыгран, хеш: сыгран >= 0 ? (this.хеши.get(сыгран) ?? null) : null };
  }

  /** Пакет своего хода — его надо разослать всем (включая себя через принять()). */
  собратьПакет() {
    const ход = this.ход + this.задержка;
    const п = this.пакет(ход, this.мои);
    this.мои = [];
    this.отправлен = Math.max(this.отправлен, ход);
    return п;
  }

  /** Разослать всё, что положено к этому моменту: пустые за пропущенные ходы и свой пакет. */
  отправитьХод() {
    if (!this.шли || this.отправлен >= this.ход + this.задержка) return;   // за этот ход уже отправлено (ход ждал пакетов)
    for (let t = this.отправлен + 1; t < this.ход + this.задержка; t++) this.шли(this.пакет(t, []));
    this.отправлен = Math.max(this.отправлен, this.ход + this.задержка - 1);
    this.шли(this.собратьПакет());
  }

  /** Принять пакет хода (свой или чужой). */
  принять(п) {
    if (п.вид !== 'ход') return;
    if (!this.пакеты.has(`${п.ход}:${п.игрок}`)) this.пакеты.set(`${п.ход}:${п.игрок}`, п.приказы || []);
    if (п.хеш !== null && п.хеш !== undefined && п.хешХод !== undefined) {
      this.чужиеХеши.set(`${п.хешХод}:${п.игрок}`, п.хеш);
      this.сверить(п.хешХод, п.игрок, п.хеш);
    }
  }

  сверить(ход, игрок, чужой) {
    if (игрок === this.игрок) return;
    const свой = this.хеши.get(ход);
    if (свой === undefined || this.расхождение) return;
    if (свой !== чужой) this.расхождение = { ход, игрок, свой, чужой };
  }

  /** Нужен ли пакет игрока на этот ход (выбывшего в его отсутствие не ждём). */
  нужен(и, ход) {
    const у = this.ушедшие.get(и);
    return !(у && ход > у.до && ход < у.с);
  }
  /** Есть ли все пакеты на ход. */
  готов(ход) { return this.игроки.every(и => this.пакеты.has(`${ход}:${и}`) || !this.нужен(и, ход)); }

  /** Решено играть без игрока: всё, что он успел прислать, доигрывается, дальше он не ждётся. */
  выбыл(игрок) {
    if (!this.игроки.includes(игрок)) return;
    const у = this.ушедшие.get(игрок);
    if (у && у.с === Infinity) return;
    let последний = -1;
    for (const ключ of this.пакеты.keys()) {
      const [t, и] = ключ.split(':').map(Number);
      if (и === игрок && t > последний) последний = t;
    }
    this.ушедшие.set(игрок, { до: последний, с: Infinity });
  }

  /** Запланировать на начало хода (если ход уже прошёл — на ближайший). */
  наХоду(ход, fn) { const t = Math.max(ход, this.ход); (this.планы.get(t) || this.планы.set(t, []).get(t)).push(fn); }
  /** Новый игрок в идущей партии: до `сХода` его пакеты не нужны. */
  добавить(игрок, сХода) {
    if (this.игроки.includes(игрок)) { this.вернулся(игрок, сХода); return; }
    this.игроки.push(игрок); this.игроки.sort((a, b) => a - b);
    this.ушедшие.set(игрок, { до: -1, с: сХода });
  }

  /** Игрок вернулся и получил снимок хода `сХода`: с этого хода его пакеты снова нужны. */
  вернулся(игрок, сХода) {
    const у = this.ушедшие.get(игрок);
    if (у && у.с === Infinity) у.с = сХода;
  }

  /** Свои пакеты, которые ещё лежат в почте (для повторной отправки вернувшемуся). */
  своиПакеты(сХода) {
    const из = [];
    for (const [ключ, приказы] of this.пакеты) {
      const [t, и] = ключ.split(':').map(Number);
      if (и === this.игрок && t >= сХода) из.push({ вид: 'ход', ход: t, игрок: и, приказы, хешХод: -1, хеш: null });
    }
    return из;
  }

  /**
   * Один тик. Возвращает 'ждём' (нет пакетов), 'расхождение' или null (сделан шаг).
   * На первом тике каждого хода в очередь движка уходят приказы этого хода — в жёстком порядке.
   */
  тик() {
    if (this.расхождение) return 'расхождение';
    if (this.шаг % this.шаговВХоде === 0) {
      if (!this.готов(this.ход)) {
        this.ждём = this.игроки.filter(и => !this.пакеты.has(`${this.ход}:${и}`) && this.нужен(и, this.ход));
        return 'ждём';
      }
      this.ждём = null;
      const план = this.планы.get(this.ход);
      if (план) { this.планы.delete(this.ход); for (const fn of план) fn(this); }
      for (const и of this.игроки)
        for (const з of this.пакеты.get(`${this.ход}:${и}`) || [])
          приказ(this.eng, з.юнит, з.код, з.цель, з.x, з.y);
    }
    this.eng.timer = this.eng.timer + 1;
    this.eng.tick();
    this.шаг++;
    if (this.шаг % this.шаговВХоде === 0) {
      const h = this.безХеша ? 0 : хеш(this.eng);
      if (!this.безХеша) this.хеши.set(this.ход, h);
      if (this.отладка) {                                   // снимки последних ходов — искать, где разошлось (tools/net_browser.mjs)
        (this.снимки ??= new Map()).set(this.ход, снимок(this.eng));
        this.снимки.delete(this.ход - 16);
      }
      for (const и of this.игроки) {
        const чужой = this.чужиеХеши.get(`${this.ход}:${и}`);
        if (чужой !== undefined) this.сверить(this.ход, и, чужой);
        this.пакеты.delete(`${this.ход - 1}:${и}`);
        this.чужиеХеши.delete(`${this.ход - 64}:${и}`);
      }
      this.хеши.delete(this.ход - 64);
      this.ход++;
    }
    return null;
  }

  /** Сколько ходов мы уже можем проиграть, не дожидаясь сети (запас на догон). */
  запас() {
    let n = 0;
    while (n < 32 && this.готов(this.ход + n)) n++;    // предел: когда все остальные выбыли, готов() верен на любой ход
    return n;
  }

  /**
   * Перескочить на ход `ход` после восстановления снимка хоста (снят в начале этого хода).
   * Старые пакеты и хеши выбрасываются, пропущенные свои пакеты досылаются пустыми.
   */
  перескочить(ход) {
    this.ход = ход; this.шаг = ход * this.шаговВХоде;
    this.расхождение = null; this.ждём = null; this.мои = [];
    for (const ключ of [...this.пакеты.keys()]) if (+ключ.split(':')[0] < ход) this.пакеты.delete(ключ);
    this.хеши.clear(); this.чужиеХеши.clear();
    // Пустые пакеты — только за ходы от снимка: всё, что раньше, остальные уже сыграли (или
    // решили играть без нас), а вернувшемуся с нуля иначе пришлось бы слать тысячи пустышек.
    if (this.шли) for (let t = Math.max(this.отправлен + 1, ход); t < ход + this.задержка; t++) this.шли(this.пакет(t, []));
    this.отправлен = Math.max(this.отправлен, ход + this.задержка - 1);
  }
}
