// Сетевая игра: детерминированный локстеп (наше).
//
// По сети не ходит состояние — ходят приказы. Все машины крутят один и тот же движок из одного
// и того же начального снимка и получают одинаковую память. Оригинал делал это же по нуль-модему
// 9-байтными пакетами (разбор — notes/MULTIPLAYER.md); мы берём ту же схему, но своим каналом
// и сразу на N игроков.
//
// Как считается время. Шаги движка режутся на «ходы» по ШАГОВ_В_ХОДЕ тиков. Приказ, отданный
// во время хода T, исполняется в ходе T + ЗАДЕРЖКА — это упреждение, оно и прячет пинг: пока
// идёт ход T, пакеты хода T+ЗАДЕРЖКА летят по сети. Ход исполняется, только когда пришли пакеты
// ОТ ВСЕХ игроков; иначе симуляция стоит.
//
// Порядок применения приказов задан жёстко: по номеру игрока, внутри игрока — по порядку выдачи.
// Оригинал добивался того же двумя ветками в 0x13f4c (сначала свои, потом чужие, и наоборот на
// той стороне) — это работало ровно для двоих. Явная сортировка работает для любого числа.
//
// Начальное состояние НЕ загружается миссией на каждой машине: хост делает снимок и рассылает
// его. Иначе разъедется уже на загрузке — 0x15da1 при старте миссии дёргает второй ГСЧ (0x204a6),
// а тот считается от таймера BIOS и выбирает строку таблицы врагов для ИИ.
//
// Сверка. В пакете хода T+ЗАДЕРЖКА едет хеш состояния после хода T-1 (последнего сыгранного).
// Кто получил чужой хеш за ход, который сам уже сыграл, сравнивает; кто ещё не дошёл — сравнит,
// когда дойдёт. Расхождение = стоп и запрос снимка у хоста (js/net/игра.js).
//
// Зритель и симуляция. У каждой машины своё племя [0x31b64], своя камера, выделение, туман —
// это в снимок не входит и в хеш не берётся (списки ЗРИТЕЛЬ и хеш ниже). Кто из владельцев
// человек — общий для всех список, см. js/port/humans.js.
