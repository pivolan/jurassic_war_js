// Турнир скриптовых компьютеров (наше): зеркальные пары по всем племенам, каждая сложность против
// каждой, оба посадочных места. Нужен, чтобы «сложнее» действительно значило «сильнее».
//
//   node tools/ai_balance.mjs [карта] [секунд] [уровни через запятую]
import { движок, прогнать, ТИК_МС } from './ai_duel.mjs';
import { loadMission } from '../reimpl/js/loader.js';
import { расставить, стартовыеПозиции } from '../reimpl/js/port/skirmish.js';
import * as Скрипт from '../reimpl/js/port/ai_script.js';

const карта = +(process.argv[2] || 100), сек = +(process.argv[3] || 1200);
const уровни = (process.argv[4] || '0,1,2,3').split(',').map(Number);
const ПЛЕМЁН = 8;

function партия(племя, урА, урБ) {
  const eng = движок();
  loadMission(eng.m, eng.files, карта, племя, 1);
  const точки = стартовыеПозиции(eng.m); const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
  const места = [{ цвет: цвета[0], племя, кто: 'компьютер' }, { цвет: цвета[1], племя, кто: 'компьютер' }];
  расставить(eng, места, {});
  eng.m.w8(0x32aec + места[0].цвет, 0); eng.m.w8(0x32aec + места[1].цвет, 0);
  Скрипт.задать(eng, места[0].цвет, { уровень: урА });
  Скрипт.задать(eng, места[1].цвет, { уровень: урБ });
  const r = прогнать(eng, Math.round(сек * 1000 / ТИК_МС));
  if (r.победитель === null) return null;
  return r.победитель === места[0].цвет ? урА : урБ;
}

const счёт = new Map(уровни.map(у => [у, { побед: 0, партий: 0 }]));
let ничьих = 0, всего = 0;
for (let i = 0; i < уровни.length; i++) for (let j = i + 1; j < уровни.length; j++) {
  for (let племя = 0; племя < ПЛЕМЁН; племя++) for (const [а, б] of [[уровни[i], уровни[j]], [уровни[j], уровни[i]]]) {
    всего++;
    const поб = партия(племя, а, б);
    счёт.get(а).партий++; счёт.get(б).партий++;
    if (поб === null) { ничьих++; continue; }
    счёт.get(поб).побед++;
  }
}
console.log(`карта ${карта}, предел ${сек} с игры, партий ${всего} (ничьих ${ничьих})`);
for (const у of уровни) {
  const с = счёт.get(у);
  console.log(`  уровень ${у} (${Скрипт.УРОВНИ[у].имя.padEnd(8)}): побед ${String(с.побед).padStart(3)} из ${с.партий}`);
}
