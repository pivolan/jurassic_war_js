// Доходят ли компьютеры до чужих построек (наше).
//
//   node tools/ai_bases.mjs [минут=15] [партий=6]
//
// Жалоба владельца: «компы очень мало внимания уделяют зданиям, легко отвлекаются». Считаем по
// партии скрипт-против-скрипта: сколько раз штаб выбирал целью чужой дом, видел ли он его вообще
// и сколько построек в итоге снесено с каждой стороны.
import { движок, прогнать, ТИК_МС } from './ai_duel.mjs';
import { loadMission } from '../reimpl/js/loader.js';
import { расставить, стартовыеПозиции } from '../reimpl/js/port/skirmish.js';
import * as Скрипт from '../reimpl/js/port/ai_script.js';
import { G, U, UNITS } from '../reimpl/js/mem.js';

const МИНУТ = +(process.argv[2] || 15), ПАРТИЙ = +(process.argv[3] || 6);
// Ген «домВажнее» — радиус, в котором чужой боец отвлекает армию от выбранного дома. Большое
// значение возвращает прежнее поведение («видим врага — идём на врага»), и по нему видно, что
// именно изменилось.
const ДОМВАЖНЕЕ = process.argv[4] !== undefined ? +process.argv[4] : undefined;
const КАРТЫ = [100, 101, 102, 103, 105, 110];
const ЗДАНИЕ = (т) => т >= 0x1a;
const домов = (m, вл) => { let n = 0;
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT))
    if (!(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.OWNER) === вл && ЗДАНИЕ(m.u8(UNITS + i + U.TYPE))) n++;
  return n; };

let сносовВсего = 0, виделиДома = 0, партийСоСносом = 0;
for (let k = 0; k < ПАРТИЙ; k++) {
  const eng = движок(); const m = eng.m;
  const карта = КАРТЫ[k % КАРТЫ.length];
  loadMission(m, eng.files, карта, 0, 1);
  const точки = стартовыеПозиции(m); const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
  const [A, B] = цвета;
  if (A === undefined || B === undefined) continue;
  расставить(eng, [{ цвет: A, племя: 0, кто: 'компьютер' }, { цвет: B, племя: 0, кто: 'компьютер' }], {});
  for (const ц of [A, B]) { m.w8(0x32aec + ц, 0); Скрипт.задать(eng, ц, { уровень: 3, характер: 'ровный', гены: ДОМВАЖНЕЕ === undefined ? undefined : { домВажнее: ДОМВАЖНЕЕ } }); }
  const домA0 = домов(m, A), домB0 = домов(m, B);
  let виделA = 0;
  const шагов = Math.round(МИНУТ * 60 * 1000 / ТИК_МС);
  const кусок = Math.round(шагов / 20);
  for (let ч = 0; ч < 20; ч++) {
    прогнать(eng, кусок);
    const с = Скрипт.состояние(eng, A);
    if (с && с.осанка === 'атака') виделA++;
  }
  const снесеноB = домB0 - домов(m, B), снесеноA = домA0 - домов(m, A);
  сносовВсего += снесеноA + снесеноB;
  if (снесеноA + снесеноB > 0) партийСоСносом++;
  виделиДома += виделA;
  console.log(`карта ${карта}: домов было ${домA0}/${домB0}, снесено ${снесеноA}/${снесеноB}, в атаке ${виделA}/20 замеров`);
}
console.log(`итого: партий со сносом ${партийСоСносом} из ${ПАРТИЙ}, снесено построек ${сносовВсего}`);
