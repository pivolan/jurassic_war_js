// Переподключение в сетевой партии — проверка настоящим контроллером (js/net/игра.js) в Node,
// без браузера: три игрока через релей, вылет, окно ожидания, возврат со снимком на лету,
// голосование «не ждать», возврат выбывшего.
//
//   node tools/net_rejoin.mjs [адрес релея]
import fs from 'node:fs'; import zlib from 'node:zlib'; import path from 'node:path'; import url from 'node:url';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..', 'reimpl') + '/';
import { Mem, G, U, UNITS } from '../reimpl/js/mem.js';
import { Engine } from '../reimpl/js/engine.js';
import { loadMission } from '../reimpl/js/loader.js';
import '../reimpl/js/modules.js';
const { setPathMode } = await import('../reimpl/js/port/path.js');
const { КОД } = await import('../reimpl/js/port/inject.js');
const { СетеваяИгра } = await import('../reimpl/js/net/игра.js');
const { люди } = await import('../reimpl/js/port/humans.js');
setPathMode('astar');
const АДРЕС = process.argv[2] || 'ws://127.0.0.1:8791/';

const образ = zlib.inflateSync(fs.readFileSync(КОРЕНЬ + 'data/boot_snap.bin.z'));
const files = {};
for (const f of ['_PWAR01.TRC', '_PWAR05.TRS', '_PWAR08.TRC', '_PWAR09.TRC', '_PWAR13.TRC']) files[f] = new Uint8Array(fs.readFileSync(КОРЕНЬ + '../PWAR/' + f));
const чистая = () => { const m = Mem.ofSize(); m.b.set(образ, 0x30000); m.w32(0x46c, 110); return m; };

const комната = 'возврат-' + Date.now();
const ключи = ['ключ-а-' + Date.now(), 'ключ-б-' + Date.now(), 'ключ-в-' + Date.now()];
let пауза = false;
const узлы = [];
function узел(k) {
  const у = { k, eng: null, журнал: [], игра: null };
  у.игра = new СетеваяИгра({
    ключ: ключи[k],
    движок: () => у.eng, память: () => у.eng.m,
    загрузить: async (миссия, племя, сложность) => { у.eng = loadMission(чистая(), files, миссия, племя, сложность); у.eng.files = files; return у.eng; },
    владельцы: async (миссия, племя) => { const m = чистая(); loadMission(m, files, миссия, племя, 1); const есть = new Set();
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) { const t = m.u8(UNITS + i + U.TYPE), вл = m.u8(UNITS + i + U.OWNER); if (t >= 1 && t <= 13 && вл < 8) есть.add(вл); } return [...есть].sort((a, b) => a - b); },
    наСтатус: (т) => { if (т) у.журнал.push(т); },
  });
  return у;
}
const жди = (мс) => new Promise(r => setTimeout(r, мс));
const состояние = (у) => { const л = у.игра.лс; return `${у.k}:${у.игра.фаза}${у.игра.готова ? '' : '(не готов)'} ход ${л?.ход ?? '-'}${л?.ждём?.length ? ' ждём ' + л.ждём : ''}${л?.расхождение ? ' РАСХОЖДЕНИЕ' : ''}${у.игра.ожидание.size ? ' ожидание ' + [...у.игра.ожидание.keys()] : ''}`; };
async function пока(усл, мс, что) { const t0 = Date.now(); while (Date.now() - t0 < мс) { if (усл()) return true; await жди(50); } console.log('НЕ ДОЖДАЛИСЬ:', что, '·', узлы.map(состояние).join(' | ')); return false; }
/** Хеши совпадают на общем ходу у всех живых узлов. */
function сверить(живые) {
  const общий = Math.min(...живые.map(у => у.игра.лс.ход)) - 1;
  const х = живые.map(у => у.игра.лс.хеши.get(общий));
  const ок = х.every(v => v !== undefined && v === х[0]);
  console.log(`  ход ${общий}: хеши ${х.map(v => v?.toString(16)).join('/')} — ${ок ? 'совпали' : 'РАЗНЫЕ'}`);
  return ок;
}
// ---- тикаем всех живых раз в 5 мс (в браузере 55 мс — здесь просто быстрее)
const тикер = setInterval(() => { for (const у of узлы) if (у.игра.активна) у.игра.тик(пауза); }, 5);
// приказ своим бойцам раз в ход у каждого — чтобы кэш маршрутов (JS-состояние) был непустой
const приказы = setInterval(() => { for (const у of узлы) { const л = у.игра.лс; if (!у.игра.активна || !у.игра.готова || !л) continue;
  const m = у.eng.m, мои = []; for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) { const t = m.u8(UNITS + i + U.TYPE); if (t >= 1 && t <= 13 && m.u8(UNITS + i + U.OWNER) === у.игра.моёПлемя && !(m.u8(UNITS + i + U.FLAGS5B) & 1)) мои.push(i); }
  if (мои.length) { const i = мои[(л.ход * 7 + у.k) % мои.length]; л.прикажи(i, КОД.ИДТИ, 0, ((m.u16(UNITS + i + U.X) >> 5) + (у.k + 1) * 3) % m.u32(G.mapW) << 5, m.u16(UNITS + i + U.Y)); } } }, 300);

let всёОк = true;
// ---- 1. лобби и старт
for (let k = 0; k < 3; k++) { узлы.push(узел(k)); await узлы[k].игра.войти(АДРЕС, комната, 'игрок' + k); await жди(300); }
await пока(() => узлы.every(у => у.игра.лобби.доступные.length), 15000, 'лобби');
узлы[0].игра.старт();
if (!await пока(() => узлы.every(у => у.игра.активна && у.игра.готова), 20000, 'старт')) process.exit(1);
console.log('старт:', узлы.map(состояние).join(' | '));
await пока(() => узлы.every(у => у.игра.лс.ход >= 40), 30000, '40 ходов');
всёОк &= сверить(узлы);

// ---- 2. вылет и возврат, пока остальные ждут
console.log('— игрок 2 вылетает');
узлы[2].игра.канал.ws.close();
await пока(() => узлы[0].игра.ожидание.has(2) && узлы[1].игра.ожидание.has(2), 5000, 'окно ожидания у 0 и 1');
console.log('  ждут:', узлы.slice(0, 2).map(состояние).join(' | '), '· статус хоста:', узлы[0].журнал.at(-1));
const ходСтоя = узлы[0].игра.лс.ход;
await жди(1500);
console.log(`  хост стоит: ход ${ходСтоя} → ${узлы[0].игра.лс.ход}`);
console.log('— игрок 2 возвращается с тем же ключом');
узлы[2] = узел(2); await узлы[2].игра.войти(АДРЕС, комната, 'игрок2-снова'); await жди(500); узлы[2].игра.хочуИграть();
if (!await пока(() => узлы[2].игра.активна && узлы[2].игра.готова, 20000, 'возврат 2')) всёОк = false;
console.log('  вернулся:', состояние(узлы[2]), '·', узлы[2].журнал.slice(-3).join(' / '));
if (!await пока(() => узлы.every(у => у.игра.лс.ход >= ходСтоя + 30), 30000, '30 ходов после возврата')) всёОк = false;
console.log('  ожидание снято:', узлы.map(у => у.игра.ожидание.size).join('/'), '·', узлы.map(состояние).join(' | '));
всёОк &= сверить(узлы);

// ---- 3. вылет, «не ждать», игра без него, потом возврат выбывшего
console.log('— игрок 1 вылетает, остальные голосуют «не ждать»');
узлы[1].игра.канал.ws.close();
await пока(() => узлы[0].игра.ожидание.has(1) && узлы[2].игра.ожидание.has(1), 5000, 'окно ожидания');
узлы[0].игра.неЖдать(1); await жди(300); узлы[2].игра.неЖдать(1);
if (!await пока(() => !узлы[0].игра.ожидание.has(1) && !узлы[2].игра.ожидание.has(1), 5000, 'решение')) всёОк = false;
console.log('  решили:', узлы[0].журнал.at(-1));
const ходБезНего = узлы[0].игра.лс.ход;
await жди(2500);
const слотИИ = (у, т) => { const m = у.eng.m; for (let s = 0; s < 8; s++) if (m.u8(0x32ae4 + s) === т) return m.u8(0x32aec + s); };
console.log('  после выбытия: люди', [узлы[0], узлы[2]].map(у => [...люди(у.eng.m)].join(',')).join(' | '), '· ИИ слота Ka-noo-se', [узлы[0], узлы[2]].map(у => слотИИ(у, 1)).join('/'));
всёОк &= [узлы[0], узлы[2]].every(у => !люди(у.eng.m).has(1) && слотИИ(у, 1) === 1);
if (!await пока(() => узлы[0].игра.лс.ход >= ходБезНего + 30 && узлы[2].игра.лс.ход >= ходБезНего + 30, 30000, '30 ходов без игрока 1')) всёОк = false;
всёОк &= сверить([узлы[0], узлы[2]]);
console.log('— игрок 1 возвращается');
узлы[1] = узел(1); await узлы[1].игра.войти(АДРЕС, комната, 'игрок1-снова'); await жди(500); узлы[1].игра.хочуИграть();
if (!await пока(() => узлы[1].игра.активна && узлы[1].игра.готова, 20000, 'возврат 1')) всёОк = false;
console.log('  вернулся:', состояние(узлы[1]), '·', узлы[1].журнал.slice(-2).join(' / '), '· хост:', узлы[0].журнал.at(-1));
const ходВозврата = узлы[1].игра.лс.ход;
if (!await пока(() => узлы.every(у => у.игра.лс.ход >= ходВозврата + 30), 30000, '30 ходов после возврата 1')) всёОк = false;
console.log('  после возврата: люди', узлы.map(у => [...люди(у.eng.m)].join(',')).join(' | '), '· ИИ слота Ka-noo-se', узлы.map(у => слотИИ(у, 1)).join('/'));
всёОк &= узлы.every(у => люди(у.eng.m).has(1) && слотИИ(у, 1) === 0);
всёОк &= сверить(узлы);
// его приказы снова доходят до всех?
const боец = (() => { const m = узлы[1].eng.m; for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) { const t = m.u8(UNITS + i + U.TYPE); if (t >= 1 && t <= 13 && m.u8(UNITS + i + U.OWNER) === узлы[1].игра.моёПлемя && !(m.u8(UNITS + i + U.FLAGS5B) & 1)) return i; } })();
const было0 = узлы[1].eng.m.u16(UNITS + боец + U.DSTX);
const цель = (узлы[1].eng.m.u16(UNITS + боец + U.X) + 256) & 0xffff;
узлы[1].игра.лс.прикажи(боец, КОД.ИДТИ, 0, цель, узлы[1].eng.m.u16(UNITS + боец + U.Y));
await жди(3000);
// цель приказа (DSTX) должна стоять у всех — значит, пакет вернувшегося дошёл до каждого
const dst = узлы.map(у => у.eng.m.u16(UNITS + боец + U.DSTX));
// у всех одинаково и не то, что было до приказа (маршрут A* может подменить цель ближайшей достижимой клеткой)
const дошёл = dst.every(v => v === dst[0]) && dst[0] !== было0;
console.log(`  приказ вернувшегося: боец ${боец.toString(16)} цель ${цель}, DSTX у всех ${dst.join('/')} —`, дошёл ? 'дошёл до всех' : 'НЕ ДОШЁЛ');
всёОк &= дошёл;
console.log(всёОк ? 'ПЕРЕПОДКЛЮЧЕНИЕ РАБОТАЕТ' : 'ЕСТЬ ПРОБЛЕМЫ');
clearInterval(тикер); clearInterval(приказы);
for (const у of узлы) у.игра.выйти();
process.exit(всёОк ? 0 : 1);
