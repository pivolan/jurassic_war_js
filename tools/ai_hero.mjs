// Работает ли стратегия «поднять героя» (наше). Гоняем партию и смотрим не только на счёт, а на
// то, во что вырос лучший боец каждой стороны: в этой игре опыт за убийство равен (сумма статов
// жертвы)² >> 2, поэтому весь вопрос в том, достаётся он одному или размазывается по отряду.
//
//   node tools/ai_hero.mjs [карта] [секунд] [характерA] [характерB] [уровень]
import { партия, прогнать, ТИК_МС } from './ai_duel.mjs';
import { G, U, UNITS } from '../reimpl/js/mem.js';
import { стартовыеПозиции } from '../reimpl/js/port/skirmish.js';
import * as Скрипт from '../reimpl/js/port/ai_script.js';

const КАРТА = +(process.argv[2] || 200), СЕК = +(process.argv[3] || 900);
const A = process.argv[4] || 'охотник', B = process.argv[5] || 'агрессор', УР = +(process.argv[6] || 2);

const статы = (m, i) => [U.HPMAX, U.MAG, U.ATK, U.DEF, U.SPD].map(f => m.u8(UNITS + i + f));
const сила = (m, i) => статы(m, i).reduce((a, b) => a + b, 0);
/** По каждому цвету: сколько бойцов, суммарная сила, лучший боец и его статы. */
function срез(m) {
  const из = {};
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const вл = m.u8(UNITS + i + U.OWNER), t = m.u8(UNITS + i + U.TYPE); if (вл > 7) continue;
    const з = из[вл] ??= { бойцов: 0, сумма: 0, лучший: 0, лучшСила: 0, зданий: 0 };
    if (t >= 0x1a) { з.зданий++; continue; }
    if (t < 1 || t > 13) continue;
    const с = сила(m, i); з.бойцов++; з.сумма += с;
    if (с > з.лучшСила) { з.лучшСила = с; з.лучший = i; }
  }
  return из;
}

const места = [{ цвет: 0, племя: 0, кто: 'компьютер', ии: 'скрипт', уровень: УР, характер: A },
               { цвет: 0, племя: 0, кто: 'компьютер', ии: 'скрипт', уровень: УР, характер: B }];
// Цвета берём те, что и правда есть на карте.
const пробный = партия(КАРТА, [{ цвет: 0, племя: 0 }, { цвет: 3, племя: 0 }]);
const цвета = Object.keys(стартовыеПозиции(пробный.m)).map(Number).sort((a, b) => a - b);
места[0].цвет = цвета[0]; места[1].цвет = цвета[1];
const eng = партия(КАРТА, места);
console.log(`карта ${КАРТА}: цвет ${места[0].цвет} «${A}» против цвета ${места[1].цвет} «${B}», уровень ${УР}`);
const ШАГ = Math.round(60000 / ТИК_МС);
const r = прогнать(eng, Math.round(СЕК * 1000 / ТИК_МС), { наШаге: (e, k) => {
  if (k % ШАГ) return;
  const с = срез(e.m);
  let зверья = 0; for (let i = e.m.u32(G.unitHead); i; i = e.m.u32(UNITS + i + U.NEXT)) {
    if (e.m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const t = e.m.u8(UNITS + i + U.TYPE); if (t >= 14 && t <= 23 && e.m.u8(UNITS + i + U.OWNER) === 8) зверья++;
  }
  const стр = места.map(м => {
    const з = с[м.цвет]; if (!з) return `${м.характер}: выбит`;
    const г = з.лучший ? статы(e.m, з.лучший).join('/') : '-';
    const ст = Скрипт.состояние(e, м.цвет);
    const герой = ст?.герой || 0;
    const гс = герой && !(e.m.u8(UNITS + герой + U.FLAGS5B) & 1) ? статы(e.m, герой).join('/') : '-';
    return `${м.характер}: ${з.бойцов}б ${з.зданий}д сила ${з.сумма} | лучший ${г} | герой ${гс} | ${ст?.осанка || '-'}`;
  }).join('   ||   ');
  console.log(`${String(Math.round(k * ТИК_МС / 1000)).padStart(4)} с  зверья ${String(зверья).padStart(3)}  ${стр}`);
} });
const с = срез(eng.m);
console.log(`итог: ${r.победитель === места[0].цвет ? A : r.победитель === места[1].цвет ? B : 'ничья'} за ${Math.round(r.шагов * ТИК_МС / 1000)} с`);
for (const м of места) {
  const з = с[м.цвет]; if (!з) { console.log(`  ${м.характер}: выбит`); continue; }
  console.log(`  ${м.характер}: бойцов ${з.бойцов}, суммарная сила ${з.сумма}, лучший ${з.лучший ? статы(eng.m, з.лучший).join('/') : '-'}`);
}
