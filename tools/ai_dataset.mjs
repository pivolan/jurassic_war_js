// Сбор датасета для behavior cloning: прогоны учителя и зашумлённых политик по всем учебным
// сценам, запись «наблюдение → метка учителя → выполненное действие → награда» (наше).
//
//   node tools/ai_dataset.mjs <имя> [вариаций=30] [потоков=16]
//
// Метка — ВСЕГДА решение учителя в этом состоянии, даже если выполнено случайное действие:
// так в датасет попадают состояния, куда учитель сам не заходит (после ошибок), и сеть учится
// из них выбираться (идея DAgger). Режимы: учитель; учитель с ε=0.2; с ε=0.5; чисто случайная.
//
// Формат: out/ai/data/<имя>/part-<k>.* — плоские массивы одной длины N:
//   окна.u8      [N, 8, 16, 16]  слои окна, доли ×255
//   векторы.f32  [N, ВЕКТОР]
//   учитель.u8   [N]  метка учителя
//   действие.u8  [N]  что было выполнено
//   награда.f32  [N]  награда за запись (подсказки до следующего решения; последней — плюс исход)
//   конец.u8     [N]  1 у последней записи эпизода
//   сцена.u16, вариация.u16, режим.u8 [N]
//   итог.f32     [N]  итог всего эпизода (одинаков у всех записей эпизода)
// Рядом — meta.json с размерами и списком сцен.
import fs from 'node:fs'; import path from 'node:path';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';   // потолок в 60% ядер и низкий приоритет

const РЕЖИМЫ = [
  { имя: 'учитель', ε: 0, доля: 1 },
  { имя: 'учитель ε=0.2', ε: 0.2, доля: 0.5 },
  { имя: 'учитель ε=0.5', ε: 0.5, доля: 0.35 },
  { имя: 'случайная', ε: 1, доля: 0.25 },
];

if (isMainThread) {
  const { КОРЕНЬ, СЦЕНЫ, УЧЕБНЫЕ, ОКНО, СЛОЁВ, ВЕКТОР, ЧИСЛО_ДЕЙСТВИЙ, ДЕЙСТВИЯ } = await import('./ai_lib.mjs');
  const имя = process.argv[2] || 'bc';
  const ВАРИАЦИЙ = +(process.argv[3] || 30), ПОТОКОВ = Ядра.потоков(process.argv[4], 16);
  const папка = path.join(КОРЕНЬ, 'out/ai/data', имя);
  fs.mkdirSync(папка, { recursive: true });
  // Задания: (сцена, вариация, режим); раздаём по потокам вперемешку, чтобы нагрузка была ровной.
  const задания = [];
  for (const сц of УЧЕБНЫЕ) {
    const номер = СЦЕНЫ.indexOf(сц);
    РЕЖИМЫ.forEach((р, k) => {
      const n = Math.max(1, Math.round(ВАРИАЦИЙ * р.доля));
      for (let в = 0; в < n; в++) задания.push([номер, в, k]);
    });
  }
  for (let i = задания.length - 1; i > 0; i--) { const j = (i * 7919 + 13) % (i + 1); [задания[i], задания[j]] = [задания[j], задания[i]]; }
  const t0 = Date.now();
  let готово = 0, записей = 0;
  const счёт = new Array(ЧИСЛО_ДЕЙСТВИЙ).fill(0);
  await Promise.all(Array.from({ length: ПОТОКОВ }, (_, k) => new Promise((ок, нет) => {
    const w = new Worker(new URL(import.meta.url), { workerData: { k, папка, задания: задания.filter((_, i) => i % ПОТОКОВ === k) } });
    w.on('message', (м) => { готово += м.эпизодов; записей += м.записей; м.счёт.forEach((n, a) => счёт[a] += n); });
    w.on('error', нет); w.on('exit', (c) => c ? нет(new Error('поток ' + k + ' упал: ' + c)) : ок());
  })));
  const с = Date.now() - t0;
  fs.writeFileSync(path.join(папка, 'meta.json'), JSON.stringify({
    имя, дата: new Date().toISOString(), окно: ОКНО, слоёв: СЛОЁВ, вектор: ВЕКТОР, действий: ЧИСЛО_ДЕЙСТВИЙ,
    вариаций: ВАРИАЦИЙ, режимы: РЕЖИМЫ, эпизодов: готово, записей,
    сцены: СЦЕНЫ.map((с, i) => ({ номер: i, имя: с.имя, роль: с.роль, проверочная: !!с.проверочная })),
    метки: Object.fromEntries(ДЕЙСТВИЯ.map((д, a) => [д, счёт[a]])),
  }, null, 1), 'utf8');
  console.log(`${готово} эпизодов, ${записей} записей за ${(с / 1000).toFixed(1)} с → ${папка}`);
  console.log('метки учителя: ' + ДЕЙСТВИЯ.map((д, a) => `${д} ${(счёт[a] / записей * 100).toFixed(1)}%`).join(', '));
} else {
  const { СЦЕНЫ, эпизод, решение, ЧИСЛО_ДЕЙСТВИЙ, ОКНО, СЛОЁВ, ВЕКТОР } = await import('./ai_lib.mjs');
  const { k, папка, задания } = workerData;
  const П = СЛОЁВ * ОКНО * ОКНО;
  const юнит = [], эпизодИд = [], окна = [], векторы = [], учитель = [], действие = [], награда = [], конец = [], сцена = [], вариация = [], режим = [], итог = [];
  const счёт = new Array(ЧИСЛО_ДЕЙСТВИЙ).fill(0);
  let s = (k + 1) * 2654435761 >>> 0;
  const сл = () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
  let эпизодов = 0, записей = 0;
  for (const [номер, в, р] of задания) {
    const ε = РЕЖИМЫ[р].ε;
    const метки = [];
    const эп = эпизод(СЦЕНЫ[номер], в, (e, i, э) => {
      const у = решение(e, i, э);
      метки.push(у);
      return сл() < ε ? Math.floor(сл() * ЧИСЛО_ДЕЙСТВИЙ) : у;
    }, true);
    эп.записи.forEach((з, j) => {
      const о = new Uint8Array(П);
      for (let i = 0; i < П; i++) о[i] = Math.round(з.окно[i] * 255);
      окна.push(о); векторы.push(з.вектор); учитель.push(метки[j]); действие.push(з.действие);
      награда.push(з.награда); конец.push(з.конец ? 1 : 0); юнит.push(з.юнит); эпизодИд.push(эпизодов);
      сцена.push(номер); вариация.push(в); режим.push(р); итог.push(эп.итого);
      счёт[метки[j]]++;
    });
    эпизодов++; записей += эп.записи.length;
  }
  const N = записей;
  const пиши = (имя, arr) => fs.writeFileSync(path.join(папка, `part-${k}.${имя}`), Buffer.from(arr.buffer, arr.byteOffset, arr.byteLength));
  const о = new Uint8Array(N * П); окна.forEach((x, i) => о.set(x, i * П)); пиши('окна.u8', о);
  const в = new Float32Array(N * ВЕКТОР); векторы.forEach((x, i) => в.set(x, i * ВЕКТОР)); пиши('векторы.f32', в);
  пиши('учитель.u8', Uint8Array.from(учитель)); пиши('действие.u8', Uint8Array.from(действие));
  пиши('награда.f32', Float32Array.from(награда)); пиши('конец.u8', Uint8Array.from(конец));
  пиши('сцена.u16', Uint16Array.from(сцена)); пиши('вариация.u16', Uint16Array.from(вариация));
  пиши('режим.u8', Uint8Array.from(режим)); пиши('итог.f32', Float32Array.from(итог)); пиши('юнит.u16', Uint16Array.from(юнит)); пиши('эпизод.u32', Uint32Array.from(эпизодИд));
  parentPort.postMessage({ эпизодов, записей, счёт });
}
