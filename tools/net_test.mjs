// Проверка локстепа без всякой сети: N движков в одном процессе (наше).
//
//   node tools/net_test.mjs [игроков] [шагов] [сид]
//
// Каждый «игрок» ведёт своих юнитов и время от времени отдаёт им случайные приказы. Пакеты ходов
// расходятся между всеми с задержкой, как по сети. После каждого тика память всех движков
// сверяется побайтово с памятью первого. Это самая строгая проверка: если расходится — видно
// сразу и с точным шагом.
//
// Плюс отдельно проверяется восстановление: одному движку нарочно портят состояние, ловится
// расхождение хешей, ему присылается снимок хоста — и партия продолжается сойдясь.
import fs from 'node:fs'; import zlib from 'node:zlib'; import path from 'node:path'; import url from 'node:url';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..', 'reimpl') + '/';
import { Mem, G, U, UNITS } from '../reimpl/js/mem.js';
import { Engine } from '../reimpl/js/engine.js';
import { loadMission } from '../reimpl/js/loader.js';
import '../reimpl/js/modules.js';
import { F } from '../reimpl/js/fn.js';
const { setPathMode } = await import('../reimpl/js/port/path.js');
await import('../reimpl/js/port/inject.js');          // обёртка 0x1419e — после modules.js
const { Локстеп, хеш, хешПолный, снимок, восстановить, СНИМОК, зрительское } = await import('../reimpl/js/net/lockstep.js');
const { КОД, счёт } = await import('../reimpl/js/port/inject.js');
const { задатьЛюдей } = await import('../reimpl/js/port/humans.js');
setPathMode('astar');

const ИГРОКОВ = +(process.argv[2] || 2);
const ШАГОВ = +(process.argv[3] || 3000);
const СИД = +(process.argv[4] || 1);
// По умолчанию — шестая миссия: 197 юнитов, много владельцев, нагрузка честная. Все «игроки»
// делят юнитов одного племени. TRIBES=0,1,2 — у каждого узла своё племя (и своё [0x31b64], своя
// камера и выделение): проверка, что зрительское не просачивается в симуляцию. Миссия — MISSION
// (с нуля), для племён удобна 12-я: восемь племён с похожими армиями.
const ПЛЕМЕНА = process.env.TRIBES ? process.env.TRIBES.split(',').map(Number) : null;
const МИССИЯ = process.env.MISSION !== undefined ? +process.env.MISSION : (ПЛЕМЕНА ? 11 : 5), ПЛЕМЯ = ПЛЕМЕНА ? ПЛЕМЕНА[0] : 0;
if (ПЛЕМЕНА && ПЛЕМЕНА.length !== ИГРОКОВ) { console.log('TRIBES: нужно столько племён, сколько игроков'); process.exit(2); }
if (ПЛЕМЕНА) задатьЛюдей(ПЛЕМЕНА);

const образ = zlib.inflateSync(fs.readFileSync(КОРЕНЬ + 'data/boot_snap.bin.z'));
const files = {};
for (const f of ['_PWAR01.TRC', '_PWAR05.TRS', '_PWAR08.TRC', '_PWAR09.TRC'])
  files[f] = new Uint8Array(fs.readFileSync(КОРЕНЬ + '../PWAR/' + f));

// ---- хост готовит начальное состояние ОДИН раз и раздаёт снимком.
// Загружать миссию на каждой машине нельзя: 0x15da1 дёргает второй ГСЧ от таймера BIOS.
const хост = новыйДвижок();
loadMission(хост.m, files, МИССИЯ, ПЛЕМЯ, 1);
// ИИ слотов людей выключается на хосте до снимка — как в сетевой игре (js/net/игра.js)
if (ПЛЕМЕНА) for (let s = 0; s < 8; s++) if (ПЛЕМЕНА.includes(хост.m.u8(0x32ae4 + s))) хост.m.w8(0x32aec + s, 0);
const начальный = снимок(хост);

function новыйДвижок() {
  const m = Mem.ofSize(); m.b.set(образ, 0x30000); m.w32(0x46c, 110);
  const eng = new Engine(m); eng.files = files;
  return eng;
}

// ---- у кого какие юниты: делим живых бойцов поровну, каждый «игрок» ведёт свою пачку
const отряды = [];
{
  // Берём только юнитов человека. Юнитов ИИ-слотов трогать бессмысленно: встроенный ИИ пишет
  // им приказ прямо в поле +0x46 каждый шаг и наш приказ затирает — проверялось, юнит стоял на
  // месте при любом числе приказов. В настоящей сетевой игре у каждого человека свои слоты.
  const m = хост.m;
  const бойцы = (вл) => { const из = []; for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    const t = m.u8(UNITS + i + U.TYPE); if (t >= 1 && t <= 13 && m.u8(UNITS + i + U.OWNER) === вл) из.push(i); } return из; };
  if (ПЛЕМЕНА) for (let p = 0; p < ИГРОКОВ; p++) отряды.push(бойцы(ПЛЕМЕНА[p]).slice(0, 12));
  else { const все = бойцы(m.u8(G.humanOwner)); for (let p = 0; p < ИГРОКОВ; p++) отряды.push(все.filter((_, k) => k % ИГРОКОВ === p).slice(0, 12)); }
  console.log('  отряды', отряды.map(o => o.length).join('/'), ПЛЕМЕНА ? '· племена ' + ПЛЕМЕНА.join(',') : '');
}

// ---- движки игроков: все стартуют с одного снимка
const узлы = [];
for (let p = 0; p < ИГРОКОВ; p++) {
  const eng = новыйДвижок();
  восстановить(eng, начальный);
  if (ПЛЕМЕНА) {                       // своё племя, своя камера и выделение — как у живого игрока
    eng.m.w8(G.humanOwner, ПЛЕМЕНА[p]); eng.m.w32(0x31ae8, p * 64); eng.m.w32(0x31aec, p * 32);
    const мои = отряды[p]; if (мои.length) { eng.m.w32(0x31adc, мои[0]); eng.m.w8(UNITS + мои[0] + U.F07, eng.m.u8(UNITS + мои[0] + U.F07) | 0x80); }
    F[0x244c3](eng);                   // туман заново — вокруг своих
  }
  узлы.push({ eng, лс: new Локстеп(eng, p, [...Array(ИГРОКОВ).keys()]), почта: [] });
}

// ---- «сеть»: пакет доходит до всех через ЛАГ ходов очереди
const ЛАГ = 1;
function разослать(от, пакет) {
  for (const у of узлы) у.почта.push({ доставить: у.лс.ход + ЛАГ, пакет });
}
function доставить(у) {
  for (const п of у.почта) if (п.доставить <= у.лс.ход) у.лс.принять(п.пакет);
  у.почта = у.почта.filter(п => п.доставить > у.лс.ход);
}

// ---- случайные, но воспроизводимые приказы
let сид = СИД >>> 0, отдано = 0;
const сл = (n) => { сид = (Math.imul(сид, 1103515245) + 12345) & 0x7fffffff; return сид % n; };

const W = хост.m.u32(G.mapW), H = хост.m.u32(G.mapH);
function приказыИгрока(p) {
  const из = [];
  if (process.env.NOORDERS) return из;
  if (сл(3) !== 0) return из;                       // не каждый ход
  const отряд = отряды[p];
  for (let k = 0, n = 1 + сл(3); k < n; k++) {
    const юнит = отряд[сл(отряд.length)];
    if (юнит === undefined) break;
    const x = сл(W), y = сл(H);
    отдано++;
    из.push({ юнит, код: сл(4) === 0 ? КОД.ОХРАНА : КОД.ИДТИ, цель: 0, x: x << 5, y: y << 5 });
  }
  return из;
}

/** Первый байт, где память двух узлов разошлась; зрительское, туман и бит выделения не в счёт. */
function первоеРасхождение(эталон, свой) {
  for (let a = 0; a < эталон.length; a++) {
    if (эталон[a] === свой[a]) continue;
    const адр = СНИМОК.от + a;
    if (зрительское(адр)) continue;
    if (адр >= 0x10ce74 && адр < 0x117e74 && ((эталон[a] ^ свой[a]) & 0xfe) === 0) continue;       // туман
    return a;
  }
  return -1;
}
/** Все расходящиеся места списком диапазонов — чтобы понять, что именно зрительское. */
function расхожденияСписком(эталон, свой) {
  const из = []; let от = -1;
  for (let a = 0; a <= эталон.length; a++) {
    const есть = a < эталон.length && эталон[a] !== свой[a];
    if (есть && от < 0) от = a;
    if (!есть && от >= 0) { из.push(`0x${(СНИМОК.от + от).toString(16)}..0x${(СНИМОК.от + a).toString(16)}`); от = -1; }
  }
  return из;
}

// ---- прогон
console.log(`локстеп: ${ИГРОКОВ} игрока, миссия ${МИССИЯ + 1}, ${ШАГОВ} шагов, сид ${СИД}`);
let расхождение = null, порча = ШАГОВ >= 1200 ? 903 : -1, чинили = false;   // не кратно 50: пусть поймает ближайшая сверка
const t0 = process.hrtime.bigint();
for (let шаг = 0; шаг < ШАГОВ && !расхождение; шаг++) {
  for (const у of узлы) доставить(у);
  // на границе хода каждый собирает и рассылает свой пакет
  for (const у of узлы) {
    if (у.лс.шаг % у.лс.шаговВХоде === 0) {
      for (const з of приказыИгрока(у.лс.игрок)) у.лс.прикажи(з.юнит, з.код, з.цель, з.x, з.y);
      разослать(у.лс.игрок, у.лс.собратьПакет());
    }
  }
  for (const у of узлы) доставить(у);
  let стоим = 0;
  for (const у of узлы) { const r = у.лс.тик(); if (r === 'ждём') стоим++; }
  if (process.env.TRACE && шаг % 100 === 99) {
    const m = узлы[0].eng.m, i = отряды[0][0];
    console.log(`   след шаг ${шаг}: юнит ${i.toString(16)} ord=${m.u8(UNITS + i + U.ORDER).toString(16)} ` +
                `xy=${m.u16(UNITS + i + U.X) >> 5},${m.u16(UNITS + i + U.Y) >> 5} dst=${m.u16(UNITS + i + U.DSTX) >> 5},${m.u16(UNITS + i + U.DSTY) >> 5} st=${m.u8(UNITS + i + U.STATE).toString(16)}`);
  }
  if (стоим === узлы.length) { console.log(`ВСЕ ВСТАЛИ на шаге ${шаг}, ждём`, узлы[0].лс.ждём); break; }
  // порча состояния — проверка, что расхождение ловится и лечится снимком
  if (шаг === порча) {
    const жертва = узлы[узлы.length - 1];
    жертва.eng.m.b[UNITS + отряды[узлы.length - 1][0] + U.HP] ^= 0x20;
    console.log(`  шаг ${шаг}: нарочно испортили состояние у игрока ${узлы.length - 1}`);
  }
  // сверка: побайтово со всеми
  if (шаг % 50 === 0 || шаг === порча + 1) {
    const эталон = узлы[0].eng.m.b.subarray(СНИМОК.от, СНИМОК.до);
    for (let p = 1; p < узлы.length; p++) {
      const свой = узлы[p].eng.m.b.subarray(СНИМОК.от, СНИМОК.до);
      const плохо = первоеРасхождение(эталон, свой);
      if (плохо >= 0) {
        if (!чинили && порча > 0 && шаг > порча) {
          console.log(`  шаг ${шаг}: расхождение у игрока ${p} по адресу 0x${(СНИМОК.от + плохо).toString(16)}` +
                      ` — шлём снимок хоста`);
          восстановить(узлы[p].eng, снимок(узлы[0].eng));
          чинили = true;
        } else {
          расхождение = { шаг, игрок: p, адрес: СНИМОК.от + плохо };
          console.log('  все расхождения:', расхожденияСписком(эталон, свой).slice(0, 40).join(' '));
        }
      }
    }
  }
}
const мс = Number(process.hrtime.bigint() - t0) / 1e6;
const л = узлы[0].лс;
if (расхождение) {
  console.log(`РАСХОЖДЕНИЕ на шаге ${расхождение.шаг}, игрок ${расхождение.игрок}, ` +
              `адрес 0x${расхождение.адрес.toString(16)}`);
  process.exit(1);
}
console.log(`  inject: положено ${счёт.положено}, отдано в очередь ${счёт.отдано}`);
console.log(`сошлось: ${л.шаг} шагов, ${л.ход} ходов, хеш ${л.хеши.get(л.ход - 1)?.toString(16)}, приказов отдано ${отдано}`);
for (const у of узлы) console.log(`  игрок ${у.лс.игрок}: шаг ${у.лс.шаг}, хеш ${у.лс.хеши.get(у.лс.ход - 1)?.toString(16)}` + (у.лс.расхождение ? ` САМ ПОЙМАЛ расхождение на ходу ${у.лс.расхождение.ход}` : ''));
if (чинили) console.log('  восстановление снимком сработало: после порчи все снова сошлись');
console.log(`${мс.toFixed(0)} мс на ${ИГРОКОВ} движка × ${л.шаг} шагов`);
