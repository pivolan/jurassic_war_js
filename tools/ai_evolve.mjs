// Эволюция констант скриптового учителя (наше). Параметров два десятка — там эволюция уместна.
//
//   node tools/ai_evolve.mjs [--минут=45] [--потоков=6] [--популяция=24] [--вариаций=3] [--имя=teacher]
//
// Стратегия: (μ, λ) с зеркальными гауссовыми возмущениями — для каждой пары детей θ ± σ·шаг·ε,
// элита (лучшие 2) переносится без изменений, адаптивная сигма: лучший ребёнок обошёл родителя —
// σ ×1.15, нет — ×0.85 (в пределах [0.05, 1]). Каждый кандидат считается на одном и том же наборе
// сцен и вариаций (одинаковые сиды) — сравнение честное.
//
// Приспособленность — ровно критерий владельца, свёрнутый в одно число на эпизод:
//   F = 0.5·(доля убитых чужих, с учётом опасности) + 0.3·(1 − доля потерянных своих)
//     + 0.2·(1 − остаток HP у выживших врагов, доля от их запаса)
// Максимум 1 — «убить всех, никого не потерять, добить в ноль». Среднее по эпизодам набора.
import fs from 'node:fs'; import path from 'node:path';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';   // потолок в 60% ядер и низкий приоритет

const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const [k, v] = a.slice(2).split('='); return [k, v ?? '1']; }));
const СЦЕНЫ_НАБОРА = ['три на три (ИИ)', 'три на три (скрипт)', 'стычка: равные', 'стычка: у врага маг', 'стычка: нас меньше',
                      'стычка: нас больше', 'один против двоих', 'дилофозавр против бегунов', 'два пса', 'оборона дома', 'отвлечь двоих'];

if (isMainThread) {
  const { КОРЕНЬ, СЦЕНЫ, СПЕК, поУмолчанию } = await import('./ai_lib.mjs');
  const МИНУТ = +(арг.минут || 45), ПОТОКОВ = Ядра.потоков(арг.потоков, 6), ПОП = +(арг.популяция || 24), ВАР = +(арг.вариаций || 3);
  const имя = арг.имя || 'teacher';
  const ключи = Object.keys(СПЕК);
  const сцены = СЦЕНЫ_НАБОРА.map(н => СЦЕНЫ.findIndex(s => s.имя === н)).filter(i => i >= 0);
  const задачиЭпизодов = []; for (const с of сцены) for (let v = 0; v < ВАР; v++) задачиЭпизодов.push([с, v]);
  const лог = fs.createWriteStream(path.join(КОРЕНЬ, 'out/ai/logs', `evolve-${имя}.log`), { flags: 'a' });
  const скажи = (s) => { console.log(s); лог.write(s + '\n'); };
  let seed = 12345; const сл = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x80000000; };
  const гаусс = () => { const u = Math.max(1e-9, сл()), v = сл(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
  const зажать = (k, x) => Math.max(СПЕК[k].от, Math.min(СПЕК[k].до, x));

  // Оценить список кандидатов: задачи (кандидат, сцена, вариация) раздаются потокам.
  async function оценить(кандидаты) {
    const задачи = [];
    кандидаты.forEach((к, i) => { for (const [с, v] of задачиЭпизодов) задачи.push([i, с, v]); });
    const суммы = кандидаты.map(() => ({ f: 0, n: 0, убито: 0, потери: 0, hp: 0 }));
    await Promise.all(Array.from({ length: ПОТОКОВ }, (_, k) => new Promise((ок, нет) => {
      const w = new Worker(new URL(import.meta.url), { workerData: { кандидаты, задачи: задачи.filter((_, i) => i % ПОТОКОВ === k) } });
      w.on('message', (м) => { for (const [i, f, у, п, h] of м) { const s = суммы[i]; s.f += f; s.n++; s.убито += у; s.потери += п; s.hp += h; } });
      w.on('error', нет); w.on('exit', (c) => c ? нет(new Error('поток ' + c)) : ок());
    })));
    return суммы.map(s => ({ f: s.f / s.n, убито: s.убито / s.n, потери: s.потери / s.n, hp: s.hp / s.n }));
  }

  const t0 = Date.now();
  let родитель = поУмолчанию();
  let [оц0] = await оценить([родитель]);
  скажи(`# старт: учитель по умолчанию F=${оц0.f.toFixed(4)} (убито ${(оц0.убито*100).toFixed(0)}%, потери ${(оц0.потери*100).toFixed(0)}%, HP врагов ${(оц0.hp*100).toFixed(0)}%); набор ${сцены.length} сцен × ${ВАР} вариаций, популяция ${ПОП}, потоков ${ПОТОКОВ}`);
  let лучший = { п: родитель, оц: оц0 }, σ = 0.5, элита = [{ п: родитель, оц: оц0 }];
  let поколение = 0;
  while ((Date.now() - t0) / 60000 < МИНУТ) {
    поколение++;
    const дети = [];
    const пар = Math.floor((ПОП - элита.length) / 2);
    for (let p = 0; p < пар; p++) {
      const ε = ключи.map(() => гаусс());
      const плюс = {}, минус = {};
      ключи.forEach((k, j) => { плюс[k] = зажать(k, лучший.п[k] + σ * СПЕК[k].шаг * ε[j]); минус[k] = зажать(k, лучший.п[k] - σ * СПЕК[k].шаг * ε[j]); });
      дети.push(плюс, минус);
    }
    const оц = await оценить(дети);
    const все = [...элита, ...дети.map((п, i) => ({ п, оц: оц[i] }))].sort((a, b) => b.оц.f - a.оц.f);
    const лучшийРебёнок = дети.map((п, i) => ({ п, оц: оц[i] })).sort((a, b) => b.оц.f - a.оц.f)[0];
    const обошёл = лучшийРебёнок.оц.f > лучший.оц.f;
    σ = Math.max(0.05, Math.min(1, σ * (обошёл ? 1.15 : 0.85)));
    if (обошёл) лучший = лучшийРебёнок;
    элита = все.slice(0, 2);
    скажи(`поколение ${поколение}: лучший F=${лучший.оц.f.toFixed(4)} (убито ${(лучший.оц.убито*100).toFixed(0)}%, потери ${(лучший.оц.потери*100).toFixed(0)}%, HP врагов ${(лучший.оц.hp*100).toFixed(0)}%), лучший ребёнок ${лучшийРебёнок.оц.f.toFixed(4)}, σ=${σ.toFixed(3)}, ${((Date.now() - t0) / 60000).toFixed(1)} мин`);
  }
  const дата = new Date().toISOString().slice(0, 16).replace('T', '-').replace(':', '');
  const путь = path.join(КОРЕНЬ, 'out/ai', `${имя}-${дата}.json`);
  const изменения = ключи.filter(k => Math.abs(лучший.п[k] - СПЕК[k].по) > 1e-9).map(k => `${k}: ${СПЕК[k].по} → ${+лучший.п[k].toFixed(3)}`);
  fs.writeFileSync(путь, JSON.stringify({
    имя: `${имя}-${дата}`, описание: `эволюция констант учителя: ${поколение} поколений, F ${оц0.f.toFixed(4)} → ${лучший.оц.f.toFixed(4)} на ${сцены.length} сценах × ${ВАР} вариаций`,
    дата: new Date().toISOString(), свёртка: 'F = 0.5·убито + 0.3·(1 − потери) + 0.2·(1 − HP выживших врагов)',
    набор: сцены.map(i => СЦЕНЫ[i].имя), вариаций: ВАР, поколений: поколение, популяция: ПОП,
    приспособленность: { старт: оц0, лучший: лучший.оц }, изменения, параметры: лучший.п,
  }, null, 1), 'utf8');
  скажи(`лучший набор → ${путь}\nизменения: ${изменения.join('; ') || 'нет'}`);
} else {
  const { СЦЕНЫ, эпизод, решение, задать } = await import('./ai_lib.mjs');
  const { кандидаты, задачи } = workerData;
  const out = [];
  for (const [i, с, v] of задачи) {
    задать(кандидаты[i]);
    const эп = эпизод(СЦЕНЫ[с], v, (e, б, э) => решение(e, б, э));
    const к = эп.критерий;
    out.push([i, к.F, к.убито, к.потери, к.hpВрагов]);
  }
  parentPort.postMessage(out);
}
