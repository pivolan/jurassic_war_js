// Стенд для отладки добычи мяса: ОДИН компьютер на карте, соперников нет вовсе.
//
//   node tools/ai_курьер.mjs [--карта=101] [--племя=0] [--секунд=1200] [--курьер=1] [--шаг=60]
//   node tools/ai_курьер.mjs --пастбища            # где на картах пастбища: сколько зверья и кучек
//
// Зачем отдельный стенд (просьба владельца): в дуэли всё смешано — бой, разведка, оборона, — и
// понять, доходит ли мясо до склада, невозможно. Здесь никто не мешает: племя охотится, курьер
// бегает за мясом, а мы каждую минуту печатаем, сколько еды в казне, сколько мяса гниёт на земле
// и сколько его в руках. Если казна не растёт, а на земле копится — механика не работает.
