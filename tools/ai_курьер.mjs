const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));
const ПЛЕМЕНА = ['Tyrano', 'Ka-noo-se', 'Romack', 'Masai', 'Moospell', 'Koomba', 'RaDumBa', 'Koaka'];

const { движок, ТИК_МС } = await import('./ai_duel.mjs');
const { loadMission } = await import('../reimpl/js/loader.js');
const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
const Скрипт = await import('../reimpl/js/port/ai_script.js');
const { G, U, UNITS, ITEMS } = await import('../reimpl/js/mem.js');
const ГОЛОВА_ПРЕДМЕТОВ = 0x31b68, ЕДА_НА_ЗЕМЛЕ = 0x1e;
const ЗВЕРЬ = (t) => t >= 14 && t <= 23;

/** Всё мясо на земле: сколько кусков и сколько в них еды. */
function мясоНаЗемле(m) {
  let кусков = 0, всего = 0;
  for (let it = m.u32(ГОЛОВА_ПРЕДМЕТОВ); it; it = m.u32(ITEMS + it + 0xc))
    if (m.u8(ITEMS + it) === ЕДА_НА_ЗЕМЛЕ) { кусков++; всего += m.u16(ITEMS + it + 6); }
  return { кусков, всего };
}

const ЗДАНИЕ = 0x1a;
// Виды домов: 0..4 — святилище, казарма, две оружейные и склад, 5 и дальше — военные дома
// (у каждого племени свои). Раньше отчёт показывал только первые пять, и построенные военные
// дома в него не попадали вовсе — казалось, что компьютер не строит ничего.
const КРАТКО = ['Св', 'Кз', 'Ор', 'О2', 'Ск'];
const кратко = (вид) => КРАТКО[вид] || 'В' + вид;

/**
 * Наши: бойцы, их вооружение и выучка, дома по видам, мясо в руках, звери на карте.
 * Всё, что владелец просил видеть: «выгуливает ли группы, тренирует ли, собирает ли мясо,
 * достраивает ли и экипирует ли армию».
 */
function срез(m, цвет) {
  let бойцов = 0, вРуках = 0, сила = 0, зверей = 0, сОружием = 0, сЩитом = 0, людей = 0, лучший = 0, строится = 0;
  const дома = new Array(16).fill(0);
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
    if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
    const t = m.u8(UNITS + i + U.TYPE);
    if (ЗВЕРЬ(t)) { зверей++; continue; }
    if (m.u8(UNITS + i + U.OWNER) !== цвет) continue;
    if (t >= ЗДАНИЕ) {
      const вид = t - ЗДАНИЕ; if (вид >= 0 && вид < дома.length) дома[вид]++;
      if (m.u8(UNITS + i + U.STATE) === 0x60) строится++;
      continue;
    }
    if (t < 1 || t > 13) continue;
    бойцов++; вРуках += m.u16(UNITS + i + U.FOOD);
    const с1 = m.u8(UNITS + i + U.HPMAX) + m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.SPD);
    сила += с1; if (с1 > лучший) лучший = с1;
    if (t >= 1 && t <= 3) {                                             // вещи носят только люди
      людей++;
      if (m.u8(UNITS + i + U.WEAPON) !== 0xff) сОружием++;
      if (m.u8(UNITS + i + U.SHIELD) !== 0xff) сЩитом++;
    }
  }
  return { бойцов, дома, строится, вРуках, сила, лучший, зверей, людей, сОружием, сЩитом, казна: m.u32(G.food + цвет * 4) };
}

/** Строка про дома: только те, что есть. */
const домаКратко = (дома, строится) => (дома.map((n, k) => n ? `${кратко(k)}${n}` : '').filter(Boolean).join(' ') || '—') + (строится ? `+${строится}стр` : '');

/** Кто чем занят: размеры отрядов у скриптового штаба. */
function отряды(с) {
  const о = с.отряды || {};
  const n = (к) => (о[к] || []).length;
  return `раб ${n('рабочие')} охот ${n('охотники')}+${n('охота')} кулак ${n('кулак')} дом ${n('дома')} охр ${n('охрана')} разв ${n('разведка')} лечь ${n('лечение')}`;
}

// ---------------------------------------------------------------- где пастбища
if (арг.пастбища) {
  const карты = (арг.карты || '100,101,102,103,104,105,106,107,108,109,110,111,112,113,114,115,116,117,118,119').split(',').map(Number);
  console.log('карта  зверья  кучек(≥3 зверей в 8 клетках)  самая большая кучка');
  for (const карта of карты) {
    try {
      const eng = движок(); const m = eng.m;
      loadMission(m, eng.files, карта, 0, 1);
      const звери = [];
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
        if (ЗВЕРЬ(m.u8(UNITS + i + U.TYPE))) звери.push({ x: m.u16(UNITS + i + U.X) >> 5, y: m.u16(UNITS + i + U.Y) >> 5 });
      }
      // Кучки: простая склейка по расстоянию 8 клеток.
      const свои = звери.map(() => -1); const кучки = [];
      for (let a = 0; a < звери.length; a++) {
        if (свои[a] >= 0) continue;
        const к = [a]; свои[a] = кучки.length;
        for (let q = 0; q < к.length; q++) for (let b = 0; b < звери.length; b++) {
          if (свои[b] >= 0) continue;
          const d = Math.max(Math.abs(звери[к[q]].x - звери[b].x), Math.abs(звери[к[q]].y - звери[b].y));
          if (d <= 8) { свои[b] = кучки.length; к.push(b); }
        }
        кучки.push(к);
      }
      const большие = кучки.filter(к => к.length >= 3).sort((a, b) => b.length - a.length);
      console.log(`${String(карта).padEnd(6)} ${String(звери.length).padStart(6)}  ${String(большие.length).padStart(26)}  ${большие[0]?.length ?? 0}`);
    } catch (e) { console.log(`${карта}: ${String(e.message).slice(0, 60)}`); }
  }
  process.exit(0);
}

// ---------------------------------------------------------------- одиночный прогон
const карта = +(арг.карта || 101), племя = +(арг.племя || 0);
const секунд = +(арг.секунд || 1200), шагПечати = +(арг.шаг || 60);
const курьер = арг.курьер !== '0';

const eng = движок(); const m = eng.m;
loadMission(m, eng.files, карта, племя, 1);
const точки = стартовыеПозиции(m); const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
const цвет = цвета[0];
// Соперников по умолчанию нет вовсе: на карте только наше племя и живность — видно ровно
// хозяйство. С --соперник=1 ставим второе племя БЕЗ управления (ни встроенного ИИ, ни нашего):
// оно стоит на месте со своими домами и юнитами. Так видно волну: куда пошла, что снесла, и
// вернулась ли собираться заново, если не дожала.
