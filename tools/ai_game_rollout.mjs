// Прогон ПАРТИЙ нейронкой для RL (наше): то же, что tools/ai_rollout.mjs, только вместо сцен
// арены — настоящие скирмиш-партии против скриптового штаба.
//
//   node tools/ai_game_rollout.mjs <веса.json> <папка> [партий=64] [потоков=16] [seed=1] [температура=1]
//
// Порядок доводов совпадает с ai_rollout.mjs нарочно: tools/ai_ppo.py зовёт прогон именно так,
// и подменить арену на партии можно одним ключом `--прогон`.
//
// Награда. На арене её считает episode.js по ролям; в партии ролей нет — есть племя, экономика и
// исход. Берём то, что боец может изменить своими руками:
//   + добытая еда между решениями (охота и переноска — это вся экономика игры),
//   − потерянное здоровье (за размен собой платит племя),
//   + урон по вражескому зданию, которое боец сейчас бьёт, с весом по важности здания,
//   − смерть (разово),
//   ± исход партии и счёт по зданиям в последней записи цепочки.
// Числа мелкие: подсказки не должны перевешивать исход, иначе сеть учится копить мясо и не воевать.
//
// Зачем отдельно платить за здания. Наблюдение владельца: компьютеры дерутся с юнитами и почти не
// трогают постройки, хотя в этой игре постройки и есть вся партия. Святилище выдаёт строителя,
// склад держит еду (а еда тут единственный ресурс), казармы и школы делают новых бойцов. Снёс
// склад — противник остался без запаса; снёс школы — новых юнитов не будет вовсе. Без явной платы
// сеть этого не выучит: юнит рядом бьётся и даёт быструю отдачу, а стена молчит и не отвечает.
//
// Цепочки. У каждого бойца своя цепочка записей (поля «эпизод» и «юнит»), GAE в ai_ppo.py идёт
// по ним — как и на арене, где по одной сцене ходили несколько бойцов.
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';   // потолок в 60% ядер и низкий приоритет
const ЭТОТ = url.fileURLToPath(import.meta.url);

// Карты и племена прогона. По умолчанию — весь набор вперемешку, чтобы сеть не заучивала одну
// обстановку. Переопределяются окружением, когда нужно натаскать сеть на конкретную дуэль
// (владелец: «потренируй нейронку против скрипта на этой карте, один на один, тираны против
// телепортеров»). Имена переменных латиницей: bash не принимает кириллицу в именах окружения.
//   JW_MAPS=100 JW_NET_TRIBE=2 JW_SCRIPT_TRIBE=0 JW_SCRIPT_CHAR=костяк
const среда = globalThis.process?.env || {};
const КАРТЫ = (среда.JW_MAPS ? среда.JW_MAPS.split(',').map(Number) : [100, 101, 102, 103, 104, 105, 107, 110, 112, 115]);
// Чего стоит каждое здание. Числа — не HP, а «сколько партии в нём»: Святилище делает строителей,
// то есть все остальные дома; склад держит единственный ресурс; казармы и школы — поток бойцов;
// оружейная только доснаряжает уже готовых. Всё остальное (по типу не найдено) считаем за 0.5.
const ЦЕНА_ЗДАНИЯ = {
  0x1a: 1.0,   // Sanctuary — главный дом, из него строители
  0x1e: 0.9,   // Food-storage — весь запас еды
  0x1b: 0.7,   // Barracks
  0x1f: 0.7, 0x20: 0.7, 0x21: 0.7, 0x22: 0.7,          // школы магов
  0x23: 0.7, 0x24: 0.7, 0x25: 0.7, 0x26: 0.7, 0x27: 0.7, // загоны динозавров
  0x1c: 0.4, 0x1d: 0.4,                                  // оружейные
};
const ЦЕНА = (т) => ЦЕНА_ЗДАНИЯ[т] ?? 0.5;
const ЗДАНИЕ = (т) => т >= 0x1a;
const УРОН_ЗДАНИЮ = 0.5;      // за полностью снесённое здание ценой 1.0, размазано по ударам
const СЧЁТ_ЗДАНИЙ = 0.5;      // вес разницы «снесли у них / потеряли у себя» в конце партии

const ПЛЕМЕНА = (среда.JW_TRIBES ? среда.JW_TRIBES.split(',').map(Number) : [0, 1, 2, 4, 5, 6]);
// Дуэль: у сети и у скрипта могут быть РАЗНЫЕ племена. Если задано племя сети, оно и стоит на
// её месте, а скрипт играет своим; иначе оба берут племя задания, как было.
const ПЛЕМЯ_СЕТИ = среда.JW_NET_TRIBE !== undefined ? +среда.JW_NET_TRIBE : null;
const ПЛЕМЯ_СКРИПТА = среда.JW_SCRIPT_TRIBE !== undefined ? +среда.JW_SCRIPT_TRIBE : null;
const ХАРАКТЕР_СКРИПТА = среда.JW_SCRIPT_CHAR || 'ровный';
const ХАРАКТЕР_СЕТИ = среда.JW_NET_CHAR || 'ровный';
// Длина партии. За десять минут отряды до чужой базы обычно не доходят: замер показал, что дом
// оказывается в окне бойца лишь в 3 % решений, и учить его ломать постройки просто не на чем.
// Переопределяется JW_ИГРА_СЕК, чтобы это можно было проверить, не трогая код.
const СЕКУНД = +(globalThis.process?.env?.JW_GAME_SEC || globalThis.process?.env?.JW_ИГРА_СЕК || 600);

if (isMainThread) {
  const [веса, папка] = process.argv.slice(2);
  const ПАРТИЙ = +(process.argv[4] || 64), ПОТОКОВ = Ядра.потоков(process.argv[5], 16), SEED = +(process.argv[6] || 1), T = +(process.argv[7] || 1);
  fs.mkdirSync(папка, { recursive: true });
  for (const f of fs.readdirSync(папка)) if (f.startsWith('part-')) fs.unlinkSync(path.join(папка, f));
  // Задания раскладываем по кругу: карта × племя × место, сдвиг по сиду — каждая итерация PPO
  // получает свой набор партий, и сеть не заучивает одну карту.
  const задания = [];
  for (let k = 0; k < ПАРТИЙ; k++) {
    const i = SEED * 7919 + k * 104729;
    задания.push({ карта: КАРТЫ[i % КАРТЫ.length], племя: ПЛЕМЕНА[(i / КАРТЫ.length | 0) % ПЛЕМЕНА.length],
                   место: (i / (КАРТЫ.length * ПЛЕМЕНА.length) | 0) % 2, секунд: СЕКУНД });
  }
  const t0 = Date.now();
  let записей = 0; const итоги = []; const зд = { решений: 0, урон: 0, счёт: 0, партий: 0, вОкне: 0 };
  await Promise.all(Array.from({ length: ПОТОКОВ }, (_, k) => new Promise((ок, нет) => {
    const w = new Worker(ЭТОТ, { workerData: { k, веса, папка, T, seed: SEED * 131 + k, задания: задания.filter((_, i) => i % ПОТОКОВ === k) } });
    w.on('message', (м) => { записей += м.записей; итоги.push(...м.итоги);
      зд.решений += м.решенийПоЗданиям || 0; зд.урон += м.уронЗданий || 0; зд.счёт += м.счётаЗданий || 0;
      зд.партий += м.партий || 0; зд.вОкне += м.решенийСДомомВОкне || 0; });
    w.on('error', нет); w.on('exit', (c) => c ? нет(new Error('поток упал ' + c)) : ок());
  })));
  const { ОКНО, СЛОЁВ, ВЕКТОР } = await import('../reimpl/js/ai/obs.js');
  const { ЧИСЛО_ДЕЙСТВИЙ } = await import('../reimpl/js/ai/act.js');
  const средн = (a) => a.length ? a.reduce((s, x) => s + x, 0) / a.length : 0;
  const побед = итоги.filter(и => и[1] > 0.6).length, поражений = итоги.filter(и => и[1] < 0.4).length;
  const сводка = { эпизодов: итоги.length, записей, итог: средн(итоги.map(x => x[1])), побед, поражений,
                   ничьих: итоги.length - побед - поражений,
                   // Здания: доля решений, отданных по постройке, суммарная плата за урон и средний
                   // счёт «снесли минус потеряли». По ним видно, учится ли сеть трогать дома вообще.
                   поЗданиям: записей ? +(зд.решений / записей).toFixed(3) : 0,
                   домВОкне: записей ? +(зд.вОкне / записей).toFixed(3) : 0,
                   уронЗданий: +зд.урон.toFixed(1),
                   счётЗданий: зд.партий ? +(зд.счёт / зд.партий).toFixed(3) : 0,
                   секунд: (Date.now() - t0) / 1000 };
  fs.writeFileSync(path.join(папка, 'meta.json'), JSON.stringify({ окно: ОКНО, слоёв: СЛОЁВ, вектор: ВЕКТОР,
    действий: ЧИСЛО_ДЕЙСТВИЙ, источник: 'партии', ...сводка }), 'utf8');
  console.log(JSON.stringify(сводка));
} else {
  const { k, веса, папка, T, seed, задания } = workerData;
  const { движок, прогнать, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  const { политикаСети } = await import('../reimpl/js/ai/policy_net.js');
  const { решение } = await import('../reimpl/js/ai/policy_script.js');
  const Действия = await import('../reimpl/js/ai/act.js');
  const { ОКНО, СЛОЁВ, ВЕКТОР } = await import('../reimpl/js/ai/obs.js');
  const { U, UNITS } = await import('../reimpl/js/mem.js');
  /** Сумма ценностей живых зданий владельца: по ней считается счёт в конце партии. */
  const ценаЗданий = (m, владелец) => {
    let s = 0;
    for (let i = m.u32(0x31b6c); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
      if (m.u8(UNITS + i + U.OWNER) !== владелец) continue;
      const т = m.u8(UNITS + i + U.TYPE); if (!ЗДАНИЕ(т)) continue;
      s += ЦЕНА(т);
    }
    return s;
  };
  /** Вражеское здание, которое боец сейчас бьёт (или 0). Цель в +0x47 бывает мусорной — проверяем. */
  const битоеЗдание = (m, i, мой) => {
    const ц = m.u32(UNITS + i + U.TARGET) >>> 0;
    if (!ц || ц >= 600 * 96) return 0;
    if (m.u8(UNITS + ц + U.FLAGS5B) & 1) return 0;
    if (!ЗДАНИЕ(m.u8(UNITS + ц + U.TYPE))) return 0;
    return m.u8(UNITS + ц + U.OWNER) === мой ? 0 : ц;
  };
  const сеть = политикаСети(fs.readFileSync(веса, 'utf8'), { температура: T, seed });
  const П = СЛОЁВ * ОКНО * ОКНО;

  const окна = [], векторы = [], учитель = [], действие = [], награда = [], конец = [], сцена = [], вариация = [],
        итог = [], юнит = [], эпизодИд = [], logp = [], ценность = [];
  const итоги = []; let партий = 0;
  // Счётчики для сводки: видно ли вообще, что сеть бьёт здания, и сколько за это капает.
  let решенийПоЗданиям = 0, уронЗданий = 0, счётаЗданий = 0;
  // Отдельно считаем, сколько раз у бойца дом вообще БЫЛ в окне. Без этого числа нельзя отличить
  // «сеть игнорирует постройки» от «постройки ей ни разу не попадались» — а лечится это в разных
  // местах: первое наградой, второе стратегом, который не доводит армию до чужой базы.
  let решенийСДомомВОкне = 0;

  for (const з of задания) {
    const eng = движок(); const m = eng.m;
    loadMission(m, eng.files, з.карта, з.племя, 1);
    const точки = стартовыеПозиции(m); const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
    const A = цвета[з.место], B = цвета[1 - з.место];
    if (A === undefined || B === undefined) continue;
    const племяA = ПЛЕМЯ_СЕТИ ?? з.племя, племяB = ПЛЕМЯ_СКРИПТА ?? з.племя;
    расставить(eng, [{ цвет: A, племя: племяA, кто: 'компьютер' }, { цвет: B, племя: племяB, кто: 'компьютер' }], {});
    const прошлое = new Map();          // юнит → { hp, еда, индексЗаписи }
    const мои = [];
    const политика = (e, i, эп, наб) => {
      const у = решение(e, i, эп);
      const a = сеть(e, i, эп, наб);
      const hp = m.u8(UNITS + i + U.HP), еда = m.u16(UNITS + i + U.FOOD) | 0;
      const п = прошлое.get(i);
      if (п) {                                        // награда за промежуток идёт ПРЕДЫДУЩЕЙ записи
        // Урон по зданию считаем только по той цели, которую боец бил на прошлом решении: так
        // платим ему за его работу, а не за то, что где-то на карте кто-то ломает стену.
        let здания = 0;
        if (п.здание) {
          const мёртво = (m.u8(UNITS + п.здание + U.FLAGS5B) & 1) !== 0;
          const стало = мёртво ? 0 : m.u8(UNITS + п.здание + U.HP);
          if (стало < п.зданиеHP) { здания = УРОН_ЗДАНИЮ * ЦЕНА(п.зданиеТип) * (п.зданиеHP - стало) / п.зданиеМакс; уронЗданий += здания; }
        }
        const р = Math.max(-1, Math.min(1, (еда - п.еда) / 400 - (п.hp - hp) / 50 + здания));
        награда[п.индекс] = р;
      }
      const цельЗдание = битоеЗдание(m, i, A);
      if (цельЗдание) решенийПоЗданиям++;
      if (Действия.дома(e, i).length) решенийСДомомВОкне++;
      const о = new Uint8Array(П);
      for (let t = 0; t < П; t++) о[t] = Math.round(наб.окно[t] * 255);
      прошлое.set(i, { hp, еда, индекс: окна.length, здание: цельЗдание,
        зданиеHP: цельЗдание ? m.u8(UNITS + цельЗдание + U.HP) : 0,
        зданиеМакс: цельЗдание ? (m.u8(UNITS + цельЗдание + U.HPMAX) || 1) : 1,
        зданиеТип: цельЗдание ? m.u8(UNITS + цельЗдание + U.TYPE) : 0 });
      мои.push(окна.length);
      окна.push(о); векторы.push(Float32Array.from(наб.вектор));
      учитель.push(у); действие.push(a); награда.push(0); конец.push(0);
      сцена.push(з.карта); вариация.push(з.племя * 2 + з.место); итог.push(0);
      юнит.push(i & 0xffff); эпизодИд.push(партий);
      logp.push(Math.log(Math.max(1e-8, сеть.последнее.вер[a]))); ценность.push(сеть.последнее.ценность);
      return a;
    };
    for (const [ц, п] of [[A, политика], [B, null]]) {
      m.w8(0x32aec + ц, 0);
      Скрипт.задать(eng, ц, { уровень: 3, характер: п ? ХАРАКТЕР_СЕТИ : ХАРАКТЕР_СКРИПТА, бойСеть: п });
    }
    const зданияA0 = ценаЗданий(m, A), зданияB0 = ценаЗданий(m, B);
    const r = прогнать(eng, Math.round(з.секунд * 1000 / ТИК_МС));
    const исход = r.победитель === A ? 1 : r.победитель === B ? 0 : 0.5;
    // Счёт по зданиям: сколько ценности снесли у противника минус сколько потеряли своей. Это и
    // есть «важно не только ломать, но и беречь»: за потерянный склад платит вся сторона.
    const снесли = (зданияB0 - ценаЗданий(m, B)) / (зданияB0 || 1);
    const потеряли = (зданияA0 - ценаЗданий(m, A)) / (зданияA0 || 1);
    const счётЗданий = снесли - потеряли;
    // Конец цепочки у каждого бойца: последняя его запись получает исход партии и штраф за смерть.
    const последняя = new Map();
    for (const idx of мои) { итог[idx] = исход; последняя.set(юнит[idx], idx); }
    for (const [i, idx] of последняя) {
      конец[idx] = 1;
      const мёртв = (m.u8(UNITS + i + U.FLAGS5B) & 1) !== 0;
      награда[idx] += (исход - 0.5) + СЧЁТ_ЗДАНИЙ * счётЗданий + (мёртв ? -0.3 : 0);
    }
    счётаЗданий += счётЗданий;
    итоги.push([з.карта, исход]); партий++;
  }

  const N = окна.length;
  const пиши = (имя, arr) => fs.writeFileSync(path.join(папка, `part-${k}.${имя}`), Buffer.from(arr.buffer, arr.byteOffset, arr.byteLength));
  const о = new Uint8Array(N * П); окна.forEach((x, i) => о.set(x, i * П)); пиши('окна.u8', о);
  const в = new Float32Array(N * ВЕКТОР); векторы.forEach((x, i) => в.set(x, i * ВЕКТОР)); пиши('векторы.f32', в);
  пиши('учитель.u8', Uint8Array.from(учитель)); пиши('действие.u8', Uint8Array.from(действие));
  пиши('награда.f32', Float32Array.from(награда)); пиши('конец.u8', Uint8Array.from(конец));
  пиши('сцена.u16', Uint16Array.from(сцена)); пиши('вариация.u16', Uint16Array.from(вариация));
  пиши('режим.u8', new Uint8Array(N).fill(9)); пиши('итог.f32', Float32Array.from(итог));
  пиши('юнит.u16', Uint16Array.from(юнит)); пиши('эпизод.u32', Uint32Array.from(эпизодИд));
  пиши('logp.f32', Float32Array.from(logp)); пиши('ценность.f32', Float32Array.from(ценность));
  parentPort.postMessage({ записей: N, итоги, решенийПоЗданиям, уронЗданий, счётаЗданий, партий, решенийСДомомВОкне });
}
