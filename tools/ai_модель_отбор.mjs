// Отбор комдива В ГРУБОЙ МОДЕЛИ (js/ai/модель_партия.js): сотни партий в секунду на ядро вместо
// одной. Веса на выходе — те же, что понимает настоящая игра, поэтому чемпиона можно сразу
// проверить движком (tools/ai_сцены.mjs --комдив=… или tools/ai_эволюция.mjs --старт=…).
//
//   node tools/ai_модель_отбор.mjs [--часов=8] [--популяция=60] [--партий=200] [--минут=20]
//                                  [--имя=мод1] [--старт=веса.json]
//
// Правило, которое здесь нельзя нарушать: модель — это сито, а не судья. Она в сто раз быстрее и
// на четверть врёт (сверка tools/ai_модель.mjs). Поэтому чемпион модели — не «лучший ИИ», а
// «кандидат, которого стоит прогнать в движке».
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
import { Worker, isMainThread, parentPort } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';
const ЭТОТ = url.fileURLToPath(import.meta.url);
const КОРЕНЬ = path.join(path.dirname(ЭТОТ), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));

if (!isMainThread) {
  const Комдив = await import('../reimpl/js/ai/комдив.js');
  const Модель = await import('../reimpl/js/ai/модель_партия.js');
  parentPort.on('message', (з) => {
    if (з === 'стоп') return process.exit(0);
    const сеть = Комдив.изЗаписи(з.веса);
    const кэш = new Map();                                 // разбирать одного и того же соперника по многу раз незачем
    let побед = 0, ничьих = 0, очки = 0;
    for (const { сид, соперник: сопВеса } of з.задания) {
      let соперник = null;
      if (сопВеса) { const ключ = сопВеса.метка ?? JSON.stringify(сопВеса).length;
        соперник = кэш.get(ключ) || (кэш.set(ключ, Комдив.изЗаписи(сопВеса)), кэш.get(ключ)); }
      const и = Модель.партия(сеть, { минут: з.минут, сид, соперник });
      if (и.победа === 'A') { побед++; очки += 1; continue; }
      if (и.победа === 'B') continue;                      // поражение — ноль
      ничьих++;
      // Ничья — это не «ничего не случилось». Двадцать минут ровного счёта и двадцать минут, где
      // мы вдвое сильнее, — совсем разные ничьи, и отбору нужна именно эта разница: без неё все
      // особи получают ровно 0.5, сравнивать нечего и обучение стоит на месте.
      const п = (и.силаA - и.силаB) / Math.max(1, и.силаA + и.силаB);
      очки += 0.5 + 0.25 * Math.max(-1, Math.min(1, п)) + 0.05 * Math.max(-1, Math.min(1, (и.домовA - 2) / 4));
    }
    parentPort.postMessage({ побед, ничьих, всего: з.задания.length, очки });
  });
}

if (isMainThread) {
  const Комдив = await import('../reimpl/js/ai/комдив.js');
  const потоков = Ядра.потоков(арг.потоков, 8);
  const ЧАСОВ = +(арг.часов || 8), ПОП = +(арг.популяция || 60), ПАРТИЙ = +(арг.партий || 200);
  const МИНУТ = +(арг.минут || 20), имя = арг.имя || 'мод1', МУТ = +(арг.мутация || 0.25);
  const ЭЛИТА = Math.max(2, Math.round(ПОП * 0.2));

  const потоки = Array.from({ length: потоков }, () => new Worker(ЭТОТ));
  const занять = (w, п) => new Promise((ок) => { w.once('message', ок); w.postMessage(п); });
  // Соперники в модели — «зал славы»: несколько прошлых чемпионов РАЗНЫХ поколений плюс простое
  // правило. Одного чемпиона мало: когда соперником стоит ровно тот же набор весов, что и у
  // оцениваемого, партия симметрична, всегда ничья с нулевым перевесом — и пригодность у всех
  // ровно 0.5. Первый прогон так и встал: 470 поколений подряд «0 побед, 240 ничьих».
  const зал = [null];                                     // null — рукописное правило
  const оценить = async (веса, сиды) => {
    // Сиды делим между соперниками: каждый кандидат играет со всеми и в одинаковых условиях.
    const задания = [];
    сиды.forEach((сид, i) => задания.push({ сид, соперник: зал[i % зал.length] }));
    const куски = Array.from({ length: потоков }, (_, k) => задания.filter((_, i) => i % потоков === k));
    const части = await Promise.all(потоки.map((w, k) => занять(w, { веса, задания: куски[k], минут: МИНУТ })));
    const побед = части.reduce((s, ч) => s + ч.побед, 0), ничьих = части.reduce((s, ч) => s + ч.ничьих, 0);
    const всего = части.reduce((s, ч) => s + ч.всего, 0), очки = части.reduce((s, ч) => s + ч.очки, 0);
    return { F: очки / Math.max(1, всего), побед, ничьих, всего };
  };

  let сид = 1;
  const сл = () => { сид = (сид * 1103515245 + 12345) & 0x7fffffff; return сид / 0x80000000; };
  const шум = () => (сл() + сл() + сл() - 1.5) * 1.33;
  const КЛЮЧИ = ['w1', 'b1', 'w2', 'b2', 'w3', 'b3'];
  const копия = (с) => Object.fromEntries(КЛЮЧИ.map(к => [к, Float32Array.from(с[к])]));
  const скрестить = (a, b) => Object.fromEntries(КЛЮЧИ.map(к => { const н = new Float32Array(a[к].length);
    for (let i = 0; i < н.length; i++) н[i] = сл() < 0.5 ? a[к][i] : b[к][i]; return [к, н]; }));
  const мутировать = (с, σ) => { const н = копия(с);
    for (const к of КЛЮЧИ) for (let i = 0; i < н[к].length; i++) if (сл() < 0.3) н[к][i] += шум() * σ; return н; };
  // Набор сидов поколения: общий для всех особей, свой у каждого поколения.
  const сиды = (п) => Array.from({ length: ПАРТИЙ }, (_, i) => (п * 7919 + i * 104729) % 100000);

  let население = [Комдив.пустая(), ...Array.from({ length: ПОП - 1 }, (_, k) => Комдив.случайная(k * 7919 + 13))];
  if (арг.старт) {
    const родитель = Комдив.изЗаписи(JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, арг.старт), 'utf8')));
    население = [родитель, ...Array.from({ length: ПОП - 1 }, () => мутировать(родитель, МУТ))];
  }
  console.log(`отбор в модели «${имя}»: население ${ПОП} (элита ${ЭЛИТА}), партий на особь ${ПАРТИЙ} по ${МИНУТ} мин, потоков ${потоков}`);
  console.log('модель — сито, а не судья: чемпиона потом гонять в движке');
  const t0 = Date.now();
  fs.mkdirSync(path.join(КОРЕНЬ, 'out/ai/weights'), { recursive: true });
  for (let п = 0; (Date.now() - t0) / 3600000 < ЧАСОВ; п++) {
    const набор = сиды(п);
    const оценки = [];
    for (const особь of население) {
      оценки.push({ особь, оц: await оценить(Комдив.вЗапись(особь), набор) });
      if ((Date.now() - t0) / 3600000 >= ЧАСОВ) break;
    }
    оценки.sort((a, b) => b.оц.F - a.оц.F);
    const родители = оценки.slice(0, ЭЛИТА), л = родители[0];
    fs.writeFileSync(path.join(КОРЕНЬ, `out/ai/weights/комдив-${имя}.json`), JSON.stringify(Комдив.вЗапись(л.особь)));
    const сред = оценки.reduce((s, о) => s + о.оц.F, 0) / оценки.length;
    console.log(`поколение ${п}: лучший F=${л.оц.F.toFixed(4)} (побед ${л.оц.побед}/${л.оц.всего}, ничьих ${л.оц.ничьих}), среднее ${сред.toFixed(4)}, ${((Date.now() - t0) / 60000).toFixed(1)} мин`);
    // В зал славы чемпион попадает не каждое поколение: соперники должны быть РАЗНЫМИ, иначе зал
    // заполнится копиями одного и того же и вырождение вернётся.
    if (п % 3 === 0) { const з2 = Комдив.вЗапись(л.особь); з2.метка = 'п' + п; зал.push(з2); if (зал.length > 5) зал.splice(1, 1); }
    const новое = родители.map(р => р.особь);
    while (новое.length < ПОП) {
      const a = родители[Math.floor(сл() * родители.length)].особь, b = родители[Math.floor(сл() * родители.length)].особь;
      новое.push(мутировать(скрестить(a, b), МУТ));
    }
    население = новое;
  }
  for (const w of потоки) w.postMessage('стоп');
  process.exit(0);
}
