const ПОСЕКУНДНО = арг.includes('--from');
let прошлыйРежим = '', прошлаяЦель = 0, прошлыеЖивые = new Set(свои()), последнийСнимок = -1e9;
const имяЦели = (ц) => ц ? (ИМЯ_ЗВЕРЯ[m.u8(UNITS + ц + U.TYPE)] || (m.u8(UNITS + ц + U.OWNER) !== мой ? 'чужой' : '?')) : 'нет';
const видео = [];
const ТИКОВ = Math.round(СЕКУНД * 1000 / ТИК_МС);
for (let т = 0; т < ТИКОВ; т++) {
  const п = Обр.шаг(eng, свои(), с); eng.timer++; eng.tick();
  // Условия миссии — как в кадре игры, раз в 32 шага (game.js, 0x17728): сам движок их не зовёт.
  if ((m.u32(G.step) & 0x1f) === 0) { try { call(eng, 0x17728, {}); } catch { /* на следующем */ } }
  // Конец партии движок пишет в endcode: 2 — победа по заданию, 1 — у нас не осталось никого.
  const конец = m.u8(G.endcode);
  if (конец && !итог) { итог = конец === 2 ? 'ПОБЕДА' : 'ПОРАЖЕНИЕ'; }
  if (т % 9 === 0) for (const i of свои()) {                  // хвосты
    const путь = хвосты.get(i) || []; путь.push(кл(i)); if (путь.length > ХВОСТ) путь.shift(); хвосты.set(i, путь);
  }
  const сек = +(т * ТИК_МС / 1000).toFixed(1);
  const что = [];
  const режим = `${п?.режим || '—'}${п?.подрежим ? '/' + п.подрежим : ''}`;
  if (режим !== прошлыйРежим) { что.push(режим); прошлыйРежим = режим; }
  if (с.цель !== прошлаяЦель) { что.push(`цель: ${имяЦели(с.цель)}`); прошлаяЦель = с.цель; }
  const живые = new Set(свои());
  for (const i of прошлыеЖивые) {
    if (живые.has(i)) continue;
    // Строитель, превратившийся в дом, из списка бойцов уходит — но это стройка, а не смерть.
    if (m.u8(UNITS + i + U.TYPE) >= 0x1a && !(m.u8(UNITS + i + U.FLAGS5B) & 1)) { что.push('строитель стал домом'); continue; }
    // Кто его убил: тот, кто держал его целью на прошлом шаге, и сколько ещё врагов его грызло.
    const убийцы = (ктоБилПрошлый.get(i) || []).map(з => ИМЯ_ЗВЕРЯ[m.u8(UNITS + з + U.TYPE)] || 'чужой');
    что.push('ПОГИБ БОЕЦ' + (убийцы.length ? ` (били: ${убийцы.join(', ')})` : ''));
  }
  // Запоминаем, кто кого из наших держит целью, — для следующего шага.
  ктоБилПрошлый.clear();
  for (let з = m.u32(G.unitHead); з; з = m.u32(UNITS + з + U.NEXT)) {
    if (!жив(з) || m.u8(UNITS + з + U.OWNER) === мой) continue;
    const ц = m.u32(UNITS + з + U.TARGET);
    if (ц && живые.has(ц)) { const сп = ктоБилПрошлый.get(ц) || []; сп.push(з); ктоБилПрошлый.set(ц, сп); }
  }
  прошлыеЖивые = живые;
  // ОТБИЛСЯ ОТ ГРУППЫ: боец дальше ОТБИЛСЯ клеток от середины остальных. Причину берём из того,
  // что ВОЖАК про него помнит: личный отход, несёт мясо, идёт за вещью, в гарнизоне, свой приказ
  // «иди» (с.бегут), — и из состояния движка. Отмечаем раз на эпизод, а не каждый тик.
  {
    const бойцы = [...живые].filter(i => m.u8(UNITS + i + U.TYPE) !== 4);
    for (const i of бойцы) {
      const прочие = бойцы.filter(j => j !== i);
      if (!прочие.length) continue;
      const цx = прочие.reduce((a, j) => a + кл(j).x, 0) / прочие.length, цy = прочие.reduce((a, j) => a + кл(j).y, 0) / прочие.length;
      const д = Math.max(Math.abs(кл(i).x - цx), Math.abs(кл(i).y - цy));
      const был = отбились.get(i);
      if (д > ОТБИЛСЯ && !был) {
        const причины = [];
        if (с.отходят?.has(i)) причины.push(`личный отход${с.отходят.get(i).далеко ? ' дальний' : ''}`);
        if (с.несут?.has(i)) причины.push('несёт мясо');
        if (с.заВещью?.has(i)) причины.push('идёт за вещью');
        if (с.бегут?.has(i)) { const б = с.бегут.get(i); причины.push(`послан в ${б.цx},${б.цy}`); }
        const ц = m.u32(UNITS + i + U.TARGET);
        if (ц && жив(ц)) причины.push(`цель ${имяЦели(ц)}`);
        причины.push(`сост ${m.u8(UNITS + i + U.STATE).toString(16)} приказ ${m.u8(UNITS + i + U.ORDER).toString(16)}`);
        что.push(`ОТБИЛСЯ #${i} на ${д.toFixed(0)} кл (${причины.join(', ')})`);
        отбились.set(i, true);
      } else if (д <= ОТБИЛСЯ - 2 && был) отбились.delete(i);
    }
  }
  if (п?.стройка?.заказ != null) что.push(`заказан дом ${п.стройка.заказ}`);
  if (п?.стройка?.заказанБоец) что.push(`заказан ${п.стройка.заказанБоец.кто}`);
  if (п?.стройка?.тревога && !с._тревогаБыла) { что.push('ТРЕВОГА: ломают дом'); }
  с._тревогаБыла = !!п?.стройка?.тревога;
  if (итог && !события.some(е => е.что.startsWith(итог))) что.push(итог);
  if (что.length) события.push({ т, сек, что: что.join(' · '), смерть: что.some(х => х.startsWith('ПОГИБ БОЕЦ')) || !!итог });
  // Снимок: на событие, но не чаще раза в секунду (кроме гибели), плюс раз в 15 секунд на всякий случай.
  const важно = что.some(х => х.startsWith('ПОГИБ БОЕЦ')) || что.some(х => х.startsWith('ОТБИЛСЯ'));
  // Режим «посекундно на отрезке»: --from 628 --to 684 --every 4 — кадр строго по часам.
  if (ПОСЕКУНДНО) {
    if (сек >= ОТРЕЗОК_С && сек <= ОТРЕЗОК_ДО && т % Math.max(1, Math.round(КАЖДЫЕ * 1000 / ТИК_МС)) === 0)
      снимки.push({ т, сек, что: что.join(' · ') || прошлыйРежим, смерть: false, кадр: схема(32, 24, 8), живых: живые.size, режим });
    if (сек > ОТРЕЗОК_ДО) break;
    continue;
  }
  const надо = (что.length && (т - последнийСнимок >= 18 || важно)) || т - последнийСнимок >= 270;
  if (надо) {
    const к = схема(48, 36, 5);
    снимки.push({ т, сек, что: что.join(' · ') || 'обзор', смерть: что.some(х => х.startsWith('ПОГИБ БОЕЦ')) || что.some(х => х.startsWith('ОТБИЛСЯ')), кадр: к,
                  живых: живые.size, режим });
    последнийСнимок = т;
  }
  if (ВИДЕО && т % ШАГ_ВИДЕО === 0) видео.push({ сек, режим, живых: живые.size, кадр: схема(ОКНО_В, Math.round(ОКНО_В * 0.75), Math.round(640 / ОКНО_В)) });
  if (итог) { снимки.push({ т, сек, что: итог, смерть: true, кадр: схема(48, 36, 5), живых: живые.size, режим }); break; }
}

// ---------------------------------------------------------------- раскадровка
// Выбор кадров: первый, последний, все гибели, остальное — равномерно по времени.
let выбор = new Set(ПОСЕКУНДНО ? снимки.map((_, н) => н) : [0, снимки.length - 1]);
снимки.forEach((к, н) => { if (к.смерть && выбор.size < КАДРОВ) выбор.add(н); });
for (let н = 1; выбор.size < Math.min(КАДРОВ, снимки.length); н++) {
  const шаг = снимки.length / (КАДРОВ - 1);
  for (let k = 0; k < КАДРОВ && выбор.size < КАДРОВ; k++) выбор.add(Math.min(снимки.length - 1, Math.round(k * шаг)));
  if (н > 3) break;
}
выбор = [...выбор].sort((a, b) => a - b);
const файлы = [];
for (const н of выбор) {
  const к = снимки[н], ф = `${ПАПКА}/кадры/${String(к.т).padStart(5, '0')}.png`;
  fs.writeFileSync(ф, png(к.кадр.w, к.кадр.h, к.кадр.rgba));
  const мин = `${Math.floor(к.сек / 60)}:${String(Math.floor(к.сек % 60)).padStart(2, '0')}`;
  файлы.push(['-label', `${мин} ${к.что}`.slice(0, 46), ф]);
}
const лист = `${ПАПКА}/раскадровка.png`;
execFileSync('montage', [...файлы.flat(), '-font', ШРИФТ, '-pointsize', '11', '-fill', '#eee', '-background', '#111',
  '-tile', ПОСЕКУНДНО ? '4x' : '3x', '-geometry', '+3+3', лист]);
// Легенда под раскадровкой: без неё цвета приходится помнить.
const ЛЕГЕНДА = [['#46ff46', 'наши, полоска — жизни'], ['#96c8ff', 'строитель'], ['#ffaf46', 'зверь по зубам'],
  ['#ff2d23', 'зверь на грани'], ['#78001e', 'не по зубам, обведён'], ['#ff50ff', 'цветок/гриб'],
  ['#28e1cd', 'чужое племя'], ['#3c8cff', 'наш дом'], ['#148278', 'чужой дом'], ['#c8823c', 'мясо']];
const легенда = `${ПАПКА}/легенда.png`;
execFileSync('convert', ['-size', '738x64', 'xc:#111', '-font', ШРИФТ, '-pointsize', '11',
  ...ЛЕГЕНДА.flatMap(([ц, подпись], н) => { const x = 6 + (н % 4) * 183, y = 4 + Math.floor(н / 4) * 20;
    return ['-fill', ц, '-draw', `rectangle ${x},${y + 2} ${x + 10},${y + 12}`, '-fill', '#ddd', '-annotate', `+${x + 15}+${y + 12}`, подпись]; }),
  легенда]);
execFileSync('convert', [лист, легенда, '-gravity', 'west', '-background', '#111', '-append', лист]);
const текст = [`${ИМЕНА_ПЛЕМЁН[ПЛЕМЯ]}, миссия ${МИССИЯ + 1}, ${СЕКУНД} с, штаб ${process.env.JW_ОБР_ШТАБ === '1' ? 'вкл' : 'выкл'}, итог: ${итог || 'не решено'}`,
  `дома: ${(() => { const c = new Map(); for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if ((m.u8(UNITS + i + U.FLAGS5B) & 1) || m.u8(UNITS + i + U.OWNER) !== мой) continue;
      const т = m.u8(UNITS + i + U.TYPE); if (т >= 0x1a) c.set(т - 0x1a, (c.get(т - 0x1a) || 0) + 1); }
    return [...c.entries()].map(([в, n]) => `${в}×${n}`).join(', ') || 'нет'; })()}`,
  `живых в конце: ${свои().length}, еда: ${m.u32(0x31c28 + мой * 4)}, событий ${события.length}`, '',
  ...события.map(е => `${String(е.сек).padStart(6)} с  ${е.что}`)].join('\n');
fs.writeFileSync(`${ПАПКА}/события.txt`, текст);
console.log(`раскадровка: ${лист}`);
console.log(`события: ${ПАПКА}/события.txt (${события.length})`);

// ---------------------------------------------------------------- ролик для владельца
let ролик = null;
if (ВИДЕО && видео.length) {
  const вк = `${ПАПКА}/видео`; fs.mkdirSync(вк, { recursive: true });
  // Подпись в каждый кадр: игровое время, режим отряда, сколько живых и последнее событие.
  let последнее = '';
  видео.forEach((к, н) => {
    const ф = `${вк}/${String(н).padStart(5, '0')}.png`;
    fs.writeFileSync(ф, png(к.кадр.w, к.кадр.h, к.кадр.rgba));
    const было = события.filter(е => е.сек <= к.сек).pop();
    if (было) последнее = было.что;
    const мин = `${Math.floor(к.сек / 60)}:${String(Math.floor(к.сек % 60)).padStart(2, '0')}`;
    execFileSync('convert', [ф, '-font', ШРИФТ, '-pointsize', '15', '-fill', '#fff', '-undercolor', '#000a',
      '-gravity', 'northwest', '-annotate', '+6+4', надпись(`${мин}  ${к.режим}  живых ${к.живых}`),
      ...(ЗАГОЛОВОК ? ['-gravity', 'northeast', '-annotate', '+6+4', ЗАГОЛОВОК] : []),
      '-gravity', 'southwest', '-annotate', '+6+4', надпись(последнее).slice(0, 70), ф]);
  });
  ролик = `${ПАПКА}/ролик.mp4`;
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-framerate', '10', '-i', `${вк}/%05d.png`,
    '-vf', 'pad=ceil(iw/2)*2:ceil(ih/2)*2', '-pix_fmt', 'yuv420p', '-c:v', 'libx264', '-crf', '23', ролик]);
  console.log(`ролик: ${ролик} (${видео.length} кадров, ×${Math.round(ШАГ_ВИДЕО / 2)} к игровому времени)`);
}

if (ТЕЛЕГРАМ) {
  const подпись = `${ИМЕНА_ПЛЕМЁН[ПЛЕМЯ]} м${МИССИЯ + 1}: живых ${свои().length}, еда ${m.u32(0x31c28 + мой * 4)}, событий ${события.length}`;
  execFileSync('tools/tg.sh', ['photo', лист, `Раскадровка · ${подпись}`], { stdio: 'inherit' });
  if (ролик) execFileSync('tools/tg.sh', ['video', ролик, `Схема боя · ${подпись}`], { stdio: 'inherit' });
}
