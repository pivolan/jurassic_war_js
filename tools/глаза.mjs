const CRC = new Uint32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc32 = (buf) => { let c = 0xffffffff; for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
function кусок(тип, данные) {
  const д = Buffer.alloc(4); д.writeUInt32BE(данные.length);
  const т = Buffer.concat([Buffer.from(тип, 'ascii'), данные]);
  const к = Buffer.alloc(4); к.writeUInt32BE(crc32(т));
  return Buffer.concat([д, т, к]);
}
function png(w, h, rgba) {
  const сырое = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) { сырое[y * (w * 4 + 1)] = 0; rgba.copy(сырое, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4); }
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), кусок('IHDR', ihdr),
                        кусок('IDAT', zlib.deflateSync(сырое)), кусок('IEND', Buffer.alloc(0))]);
}

