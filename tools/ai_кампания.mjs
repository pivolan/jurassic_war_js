  const дайТактика = () => сеть.тактик ??= (() => { const т = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, ЛУЧШИЕ.тактик), 'utf8'));
    return { w1: Float32Array.from(т.w1), b1: Float32Array.from(т.b1), w2: Float32Array.from(т.w2), b2: Float32Array.from(т.b2) }; })();
