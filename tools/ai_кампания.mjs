// Проходит ли наш компьютер КАМПАНИЮ (наше).
//
//   node tools/ai_кампания.mjs [--племена=0..7] [--миссии=0..11] [--сложность=2|--сложности=0,1,2]
//   node tools/ai_кампания.mjs --стейдж=1        — одна миссия, все расы × все сложности, таблица
//                              [--минут=30] [--мозги=скрипт|стратег|комдив:файл] [--потоков=…]
//
// Замысел владельца: «главный смысл — пройти кампанию. У неё чёткие критерии прохождения, и она
// вынуждает игрока сперва растить юнитов, потом копить, и только потом аккуратно побеждать.
// Общий скрипт, проходящий всю кампанию целиком, и решил бы задачу интересного противника».
//
// Чем кампания хороша как полигон. У каждой миссии СВОЙ тип цели, и под них не подгонишь одну
// тактику (разбор целей — js/port/orders_ai.js):
//   • набрать 3000 еды;                       • построить столько-то домов такого-то вида;
//   • истребить конкретное племя;             • истребить зверьё определённых видов;
//   • донести артефакт племени до своих;      • захватить чужое святилище (и вариант с двумя);
//   • уничтожить всех чужих владельцев.
// Плюс восемь племён — восемь разных наборов юнитов и домов. Итого 96 готовых проверок.
//
// Стенд НЕ учит и ничего не подгоняет: он только честно говорит, какие миссии проходятся сейчас.
