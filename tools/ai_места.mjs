// Выбор стартовых мест для замеров: две стороны и как можно дальше друг от друга.
//
// Просьба владельца (15.09.2026): «сделай по два племени и чтобы далеко были друг от друга, даже
// на больших картах». Стенды раньше брали просто первые два цвета из списка — а на восьмиместных
// картах это часто соседние углы: стороны встречаются на второй минуте, и замер получается не про
// стратегию, а про то, кто первым добежал. На 256×176 это особенно обидно: половина смысла
// большой карты в том, что до врага надо ещё дойти.
//
// Здесь выбирается ПАРА самых далёких мест. Расстояние берём в клетках по прямой (точный путь
// считать незачем: нам нужно «далеко», а не «сколько шагов»).
export function параПодальше(точки) {
  const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
  if (цвета.length < 2) return цвета;
  let лучшая = [цвета[0], цвета[1]], дальше = -1;
  for (let i = 0; i < цвета.length; i++)
    for (let j = i + 1; j < цвета.length; j++) {
      const a = точки[цвета[i]], b = точки[цвета[j]];
      const d = Math.hypot((a.x - b.x) / 32, (a.y - b.y) / 32);
      if (d > дальше) { дальше = d; лучшая = [цвета[i], цвета[j]]; }
    }
  return лучшая;
}

/** То же, но сразу с расстоянием — стендам удобно печатать, насколько далеко развели стороны. */
export function параПодальшеСДистанцией(точки) {
  const [a, b] = параПодальше(точки);
  const п1 = точки[a], п2 = точки[b];
  return { цвета: [a, b], клеток: п1 && п2 ? Math.round(Math.hypot((п1.x - п2.x) / 32, (п1.y - п2.y) / 32)) : 0 };
}
