// Сколько стоит прокачанный боец в стартовых: измеряем боями, а не рассуждениями.
//
//   node tools/ai_сила.mjs [--повторов=5] [--макс=16] [--тип=2] [--подробно]
//
// Вопрос владельца: «есть ли коэффициент, который однозначно скажет, кто сильнее — один юнит с
// такими-то характеристиками или много слабых? Можно это экспериментами проверить и таблицу
// соответствия сделать; разница может быть нелинейной».
//
// Ответ рассуждением тут не годится: в бою работает не только урон, но и то, сколько врагов
// физически могут достать одного (вокруг клетки их помещается восемь), и порядок ударов, и
// перезарядка. Поэтому здесь ЭКСПЕРИМЕНТ: на пустой площадке ставим одного прокачанного против
// N стартовых, стравливаем и смотрим, кто остался. N подбираем двоичным поиском — получается
// «цена» бойца в стартовых. Дальше по этой таблице видно, линейна ли прокачка (спойлер: нет).
//
// Бойцы обеих сторон дерутся сами: приказ «атаковать» им ставит движок, микроконтроля нет ни у
// кого — меряем голую силу, а не умение.
import path from 'node:path'; import url from 'node:url';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));

const { движок, ТИК_МС } = await import('./ai_duel.mjs');
const { loadMission } = await import('../reimpl/js/loader.js');
const { G, U, UNITS } = await import('../reimpl/js/mem.js');
const { F } = await import('../reimpl/js/fn.js');
const { поставить } = await import('../reimpl/js/ui/scenebuild.js');
const { приказ, КОД } = await import('../reimpl/js/port/inject.js');
const { проходима } = await import('../reimpl/js/ai/act.js');

const ТИП = +(арг.тип || 2);                              // 2 — воин, обычный человек с оружием
/** Стартовые характеристики этого вида прямо из таблицы движка. */
function базовые(m, тип) {
  const ст = m.u32(0x30a9e + тип * 4);
  return { hp: m.u8(ст + 0x37654), атк: m.u8(ст + 0x37657), деф: m.u8(ст + 0x37658), спд: m.u8(ст + 0x37659) };
}

/** Убрать с карты всё живое: меряем в чистом поле. */
function очистить(m) {
  for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) | 1);
}
/** Свободная запись юнита. */
function свободная(m) {
  for (let i = 96; i < 0xe000; i += 96) if (m.u8(UNITS + i + U.FLAGS5B) & 1) return i;
  return 0;
}
/** Поставить бойца с заданными характеристиками. */
function боец(eng, { тип, владелец, x, y, hp, атк, деф, спд }) {
  const m = eng.m, i = свободная(m); if (!i) return 0;
  m.w8(UNITS + i + U.TYPE, тип); m.w8(UNITS + i + U.OWNER, владелец);
  m.w8(UNITS + i + U.HPMAX, hp); m.w8(UNITS + i + U.HP, hp);
  m.w8(UNITS + i + U.ATK, атк); m.w8(UNITS + i + U.DEF, деф); m.w8(UNITS + i + U.SPD, спд);
  m.w8(UNITS + i + U.XP, 0); m.w8(UNITS + i + U.WEAPON, 0xff); m.w8(UNITS + i + U.SHIELD, 0xff);
  m.w16(UNITS + i + U.FOOD, 0); m.w8(UNITS + i + U.ORDER, 0xff);
  for (let k = 0; k < 9; k++) m.w8(UNITS + i + U.INV + k, 0);
  поставить(eng, i, x, y);
  return i;
}
const жив = (m, i) => i && !(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.HP) > 0;

/**
 * Один бой: герой с характеристиками `г` против `n` стартовых. Возвращает true, если герой выжил.
 * Расстановка: герой в середине, стартовые кольцом вокруг — так их бьёт не по одному, а сколько
 * влезет, и это честная проверка «сколько слабых стоят одного сильного».
 */
/**
 * Чистая площадка: квадрат проходимых клеток. Арена — угол настоящей карты, и без этой проверки
 * половина расстановок попадала в воду и скалы: бойцы не доходили друг до друга, бой не начинался,
 * а стенд честно записывал это в «не победил». Так и появились нули у прокачанных.
 */
function площадка(m, r = 6) {
  for (let y = 12; y < m.u32(G.mapH) - 12; y += 3)
    for (let x = 12; x < m.u32(G.mapW) - 12; x += 3) {
      let чисто = true;
      for (let dy = -r; dy <= r && чисто; dy++) for (let dx = -r; dx <= r; dx++)
        if (!проходима(m, x + dx, y + dy)) { чисто = false; break; }
      if (чисто) return { x, y };
    }
  return { x: 40, y: 40 };
}
let ПЛОЩАДКА = null;

function бой(_игнор, г, n, база, сдвиг) {
  // Свежий движок на каждый бой. Раньше все сотни боёв шли на одном: трупы, списки и счётчики
  // копились, и с какого-то момента бойцы переставали сходиться вовсе — стенд писал прокачанному
  // «ноль стартовых» там, где отдельной проверкой он убивал противника за двести шагов.
  const eng = движок(); const m = eng.m;
  loadMission(m, eng.files, 110, 0, 1);
  очистить(m);
  ПЛОЩАДКА ??= площадка(m);
  const цx = ПЛОЩАДКА.x + (сдвиг % 2), цy = ПЛОЩАДКА.y + ((сдвиг / 2) | 0);
  const герой = боец(eng, { тип: ТИП, владелец: 0, x: цx, y: цy, ...г });
  const толпа = [];
  const кольцо = [[2, 0], [-2, 0], [0, 2], [0, -2], [2, 2], [-2, -2], [2, -2], [-2, 2],
                  [3, 1], [-3, -1], [1, 3], [-1, -3], [3, -1], [-3, 1], [1, -3], [-1, 3],
                  [4, 0], [-4, 0], [0, 4], [0, -4], [4, 2], [-4, -2], [2, 4], [-2, -4]];
  for (let k = 0; k < n; k++) {
    const [dx, dy] = кольцо[k % кольцо.length];
    const м = Math.floor(k / кольцо.length) + 1;
    толпа.push(боец(eng, { тип: ТИП, владелец: 1, x: цx + dx * м, y: цy + dy * м, ...база }));
  }
  // Приказ драться: обеим сторонам, иначе они просто стоят.
  for (const i of толпа) приказ(eng, i, КОД.АТАКА, герой, цx << 5, цy << 5);
  if (толпа[0]) приказ(eng, герой, КОД.АТАКА, толпа[0], 0, 0);
  const ЖИЗНЬ = 40000;                                     // ~37 игровых минут: у прокачанных бои долгие
  for (let k = 0; k < ЖИЗНЬ; k++) {
    eng.timer++; eng.tick();
    if (k % 32 === 0) {
      const живГерой = жив(m, герой), живТолпа = толпа.some(i => жив(m, i));
      if (!живГерой || !живТолпа) return живГерой;
      // Подгоняем: если кто-то потерял приказ, ставим снова — иначе бой затухает.
      if (k % 256 === 0) {
        const цель = толпа.find(i => жив(m, i));
        for (const i of толпа) if (жив(m, i) && m.u8(UNITS + i + U.ORDER) === 0xff) приказ(eng, i, КОД.АТАКА, герой, 0, 0);
        if (цель && m.u8(UNITS + герой + U.ORDER) === 0xff) приказ(eng, герой, КОД.АТАКА, цель, 0, 0);
      }
    }
  }
  // Время вышло, а бой не кончился — засчитываем НЕ победу. Критерий однозначный: герой должен
  // добить толпу. Попытка судить по остаткам здоровья вышла боком: у прокачанного защита выше
  // чужой атаки, толпа бьёт по единице, и «он же целее» давало ему победу там, где он просто
  // стоял столбом. А обратный перегиб («не добил — проиграл, даже если убил половину») занижает
  // сильных. Из двух перегибов берём тот, что занижает: лучше недооценить прокачку, чем пойти в
  // атаку с отрядом, который на деле слабее.
  return false;
}

/** Сколько стартовых одолевает такой герой: двоичный поиск по числу противников. */
function ценаВСтартовых(eng, г, база, повторов, макс) {
  const побеждает = (n) => {
    let побед = 0;
    for (let п = 0; п < повторов; п++) if (бой(eng, г, n, база, п)) побед++;
    return побед * 2 > повторов;                          // большинство боёв
  };
  if (!побеждает(1)) return 0;
  let низ = 1, верх = 2;
  while (верх <= макс && побеждает(верх)) { низ = верх; верх *= 2; }
  if (верх > макс) return макс;
  while (верх - низ > 1) { const с = (низ + верх) >> 1; if (побеждает(с)) низ = с; else верх = с; }
  return низ;
}

