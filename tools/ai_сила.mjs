const eng = движок(); const m = eng.m;
loadMission(m, eng.files, 110, 0, 1);
const база = базовые(m, ТИП);
const повторов = +(арг.повторов || 5), макс = +(арг.макс || 16);
console.log(`тип ${ТИП}: стартовый боец hp ${база.hp}, атака ${база.атк}, защита ${база.деф}, скорость ${база.спд}`);
console.log(`бой в чистом поле, по ${повторов} повторов, потолок ${макс} противников\n`);
console.log('уровень | hp  атк деф | стоит стартовых | сумма статов | dps×ehp (в разах к базе)');

// Рост по уровням примерно такой, как даёт опыт в игре: очко то в атаку, то в защиту, то в жизнь.
const урон = (атк, деф) => Math.max(1, ((атк - деф) >> 4) + (атк >> 5) + 1);
const темп = (спд) => 1 / Math.max(1, 16 - (спд >> 4));
const базДпс = урон(база.атк, база.деф) * темп(база.спд), базЕхп = база.hp;
const таблица = [];
for (const L of [0, 5, 10, 20, 30, 40, 60, 80]) {
  const г = { hp: Math.min(250, база.hp + L * 4), атк: Math.min(250, база.атк + L * 2), деф: Math.min(250, база.деф + L), спд: база.спд };
  const n = ценаВСтартовых(eng, г, база, повторов, макс);
  const сумма = (г.hp + г.атк + г.деф) / (база.hp + база.атк + база.деф);
  const дпс = урон(г.атк, база.деф) * темп(г.спд), ехп = г.hp * (урон(база.атк, база.деф) ? урон(база.атк, база.деф) : 1);
  const произв = (дпс * г.hp) / (базДпс * базЕхп);
  таблица.push({ L, г, n, сумма, произв });
  console.log(`${String(L).padStart(7)} | ${String(г.hp).padStart(3)} ${String(г.атк).padStart(3)} ${String(г.деф).padStart(3)} | ${String(n).padStart(15)} | ${сумма.toFixed(2).padStart(12)} | ${произв.toFixed(2).padStart(12)}`);
}
console.log('\nчто это значит:');
const посл = таблица[таблица.length - 1];
console.log(`  боец ${посл.L}-го уровня стоит ${посл.n} стартовых, при этом сумма его статов выше базовой всего в ${посл.сумма.toFixed(1)} раза`);
console.log('  то есть прокачка нелинейна: сумма характеристик растёт в разы, а боевая ценность — в десятки раз');
