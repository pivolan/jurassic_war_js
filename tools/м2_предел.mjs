// ТЕОРЕТИЧЕСКИЙ ПРЕДЕЛ Тирано/2 (hard) — модель владельца: звери стоят, отряд всегда добивает,
// последний удар по очереди у слабейшего (прокачка ровная), опыт — сперва в атаку до потолка,
// потом в жизни и защиту. Возрождения, носка мяса на склад и очередь Святилища учтены.
//
//   node tools/м2_предел.mjs [нас=3] [реал=1] [носить=3000] [нанять=0] [делить=0] [подробно=1]
//
//   нас      — сколько бойцов на старте (на карте их 4);
//   реал=1   — зверь по силам, только если его урон не больше 70% жизней группы, и после боя группа
//              стоит, пока не залечится (+1,14 жизни/с на каждого); без него — «всегда добивают»;
//   нанять=N — первой строим казарму и нанимаем N простолюдинов (по 500), они вливаются в группу 0,
//              когда та приходит на склад;
//   носить=N  — идти сдавать, когда у группы N мяса (но не больше, чем влезет: жизни·64 на бойца);
//   делить=A — когда у всех в группе атака ≥ A (и в ней не меньше 2), группа делится пополам.
// Выбор цели у каждой группы — наименьшее (дойти + дождаться возрождения + убить + залечиться) на
// единицу мяса; чужую цель другая группа не берёт. Расстояния — волной по проходимости, ход 2,4 кл/с.
