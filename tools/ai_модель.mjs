// Сверка грубой модели (js/ai/модель.js) с настоящим движком и подбор её коэффициентов.
//
//   node tools/ai_модель.mjs [--карта=110] [--минут=15] [--скорость]
//
// Учить стратега в модели можно только тогда, когда модель хотя бы примерно повторяет настоящую
// партию. Здесь мы гоняем одно и то же начало двумя способами — настоящим движком и моделью — и
// печатаем обе кривые рядом: сколько еды принесено, сколько бойцов, какая сила. Врёт модель или
// нет, видно сразу, а не через неделю обучения.
//
// --скорость: сколько партий в секунду даёт модель против движка.
import path from 'node:path'; import url from 'node:url';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));
const М = await import('../reimpl/js/ai/модель.js');
// Коэффициенты модели: подбираются по настоящим партиям (--подбор) и живут здесь.
const КОЭФ = { мясо: 1, носка: 1, вПоле: 0.6, запас: 500 };

// ---------------------------------------------------------------- модель
/**
 * Прогнать модель: одинокое племя охотится и растёт, как в одиночном стенде ai_курьер.
 * `к` — подбираемые коэффициенты: во сколько раз быстрее идёт охота и носка, чем даёт голая
 * формула. Они и есть та самая «интерполяция»: в настоящей игре отряд бьёт зверя не в чистом
 * поле, ходит не по прямой и не один, и всё это сворачивается в два числа.
 */
function модельПрогон(минут, печать, к = КОЭФ) {
  const с = М.сторона({ еда: 2000, бойцы: М.отряд(4, 30, 10, 60, 32), рабочие: 2 });
  // Стадо на карте: десяток зверей среднего размера, возрождаются (в игре собака за 40 с, тигр за 100).
  const стадо = { n: 10, атк: 40, деф: 8, hp: 90, спд: 24, мясо: 400 * к.мясо };
  const отрезков = Math.round(минут * 60 / М.ШАГ_С);
  for (let k = 1; k <= отрезков; k++) {
    // Охота: часть бойцов в поле — сколько именно, тоже подбираем.
    const охотники = { ...с.бойцы, n: Math.max(1, с.бойцы.n * к.вПоле) };
    с.мясоНаЗемле += М.охота(охотники, стадо);
    с.бойцы.опыт = охотники.опыт; с.бойцы.n = Math.min(с.бойцы.n, охотники.n + с.бойцы.n * 0.4);
    М.подрасти(с.бойцы);
    М.НОСКА.груз = 1000 * к.носка;
    М.доставка(с);
    // Возрождение зверья: примерно один зверь в полминуты, как в игре.
    if (k % 6 === 0) стадо.n += 1;
    // Покупки: простолюдин 500, боец 800 — берём, пока есть на что, оставляя запас.
    while (с.еда >= к.запас + 800) { с.еда -= 800; с.бойцы.n += 1; }
    if (k % 12 === 0) печать?.(k * М.ШАГ_С / 60, { принесено: с.принесено, еда: с.еда, бойцы: { ...с.бойцы } });
  }
  return с;
}

// ---------------------------------------------------------------- движок
async function движокПрогон(минут, карта, печать) {
  const { движок, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  const { G, U, UNITS } = await import('../reimpl/js/mem.js');
  const eng = движок(); const m = eng.m;
  loadMission(m, eng.files, карта, 0, 1);
  const цвет = Object.keys(стартовыеПозиции(m)).map(Number).sort((a, b) => a - b)[0];
  расставить(eng, [{ цвет, племя: 0, кто: 'компьютер' }], {});
  m.w8(0x32aec + цвет, 0); Скрипт.задать(eng, цвет, { уровень: 3, характер: 'костяк' });
  const шагов = Math.round(минут * 60 * 1000 / ТИК_МС);
  let казнаБыла = m.u32(G.food + цвет * 4), принесено = 0;
  for (let k = 1; k <= шагов; k++) {
    eng.timer++; eng.tick();
    const к = m.u32(G.food + цвет * 4); if (к > казнаБыла) принесено += к - казнаБыла; казнаБыла = к;
    if (k % Math.round(60000 / ТИК_МС) === 0) {
      let бойцов = 0, сила = 0;
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (m.u8(UNITS + i + U.FLAGS5B) & 1 || m.u8(UNITS + i + U.OWNER) !== цвет) continue;
        const t = m.u8(UNITS + i + U.TYPE); if (t < 1 || t > 13) continue;
        бойцов++; сила += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.HPMAX);
      }
      печать?.(k * ТИК_МС / 60000, { бойцов, сила, принесено, еда: к });
    }
  }
}

// ---------------------------------------------------------------- запуск
const минут = +(арг.минут || 15), карта = +(арг.карта || 110);
if (арг.скорость) {
  const t1 = Date.now(); let n = 0;
  while (Date.now() - t1 < 2000) { модельПрогон(минут); n++; }
  const вСекунду = n / ((Date.now() - t1) / 1000);
  console.log(`модель: ${вСекунду.toFixed(0)} партий по ${минут} мин в секунду на одном ядре`);
  const t2 = Date.now(); await движокПрогон(минут, карта); const мс = Date.now() - t2;
  console.log(`движок: ${(1000 / мс).toFixed(2)} партий в секунду на одном ядре (${мс} мс на партию)`);
  console.log(`разница: ${(вСекунду * мс / 1000).toFixed(0)}×`);
  process.exit(0);
}
if (арг.подбор) {
  // Снимаем настоящую кривую один раз, дальше крутим только модель — она дешёвая.
  const ряд = new Map();
  await движокПрогон(минут, карта, (мин, с) => ряд.set(Math.round(мин), с));
  const ошибка = (к) => {
    const мод = new Map();
    модельПрогон(минут, (мин, с) => мод.set(Math.round(мин), с), к);
    let e = 0, n = 0;
    for (const [мин, д] of ряд) {
      const м = мод.get(мин); if (!м) continue;
      const дп = Math.max(1, д.принесено), дб = Math.max(1, д.бойцов);
      e += Math.abs(м.принесено - д.принесено) / дп + Math.abs(м.бойцы.n - д.бойцов) / дб;
      n += 2;
    }
    return e / Math.max(1, n);
  };
  let лучшее = null;
  for (const мясо of [1, 1.5, 2, 2.5, 3])
    for (const носка of [1, 1.5, 2, 3])
      for (const вПоле of [0.5, 0.7, 0.9])
        for (const запас of [200, 500, 900]) {
          const к = { мясо, носка, вПоле, запас }; const e = ошибка(к);
          if (!лучшее || e < лучшее.e) лучшее = { к, e };
        }
  console.log('подобранные коэффициенты:', JSON.stringify(лучшее.к), 'средняя ошибка', (лучшее.e * 100).toFixed(0) + '%');
  console.log('\nминута | движок: бойцов принесено | модель: бойцов принесено');
  const мод = new Map(); модельПрогон(минут, (мин, с) => мод.set(Math.round(мин), с), лучшее.к);
  for (const [мин, д] of ряд) { const м = мод.get(мин); if (!м) continue;
    console.log(`${String(мин).padStart(6)} | ${String(д.бойцов).padStart(7)} ${String(Math.round(д.принесено)).padStart(9)} | ${String(Math.round(м.бойцы.n)).padStart(7)} ${String(Math.round(м.принесено)).padStart(9)}`); }
  process.exit(0);
}
console.log(`сверка модели и движка: карта ${карта}, ${минут} минут\n`);
console.log('минута | движок: бойцов сила принесено | модель: бойцов сила принесено');
const движокРяд = new Map();
await движокПрогон(минут, карта, (мин, с) => движокРяд.set(Math.round(мин), с));
модельПрогон(минут, (мин, с) => {
  const д = движокРяд.get(Math.round(мин)); if (!д) return;
  console.log(`${String(Math.round(мин)).padStart(6)} | ${String(д.бойцов).padStart(7)} ${String(д.сила).padStart(5)} ${String(Math.round(д.принесено)).padStart(9)} | ${String(Math.round(с.бойцы.n)).padStart(7)} ${String(Math.round(М.силаОтряда(с.бойцы))).padStart(5)} ${String(Math.round(с.принесено)).padStart(9)}`);
});
process.exit(0);
