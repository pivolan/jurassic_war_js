#!/usr/bin/env python3
"""Собрать кнопку меню с новой надписью: текстура своя, буквы от нейросети (наше).

  python3 tools/menu_compose.py <исход.png> <ответ_сети.png> <готово.png>

Почему так. Нейросеть перерисовывает всю картинку, и если взять её целиком, у кнопки поедут и
камень, и кольцо, и фон (замер: треть пикселей). Здесь от сети берутся ТОЛЬКО жёлтые буквы, а всё
остальное — исходные пиксели:

  1. место старой надписи затирается текстурой самой кнопки (медиана соседей, не тронутых буквами),
     поэтому под новой надписью нет призрака старой;
  2. буквы сети вырезаются по жёлтому, при необходимости ужимаются, чтобы влезть в круг с полями,
     и ставятся по центру;
  3. итог загоняется в палитру игры и получает исходную маску прозрачности.

В результате меняется только надпись, а кнопка остаётся кнопкой оригинала.
"""
import sys, os
# В tools/ лежит dis.py, который затеняет стандартный модуль dis (его тянет numpy через inspect):
# убираем свой каталог из начала пути, как это делают ai_train_bc.py и ai_ppo.py.
_свои = os.path.dirname(os.path.abspath(__file__))
sys.path = [p for p in sys.path if os.path.abspath(p or '.') != _свои] + [_свои]
import numpy as np
from PIL import Image

исход, сеть, готово = sys.argv[1:4]
о = Image.open(исход).convert('RGBA')
ш, в = о.size
О = np.asarray(о.convert('RGB'), int)
С = np.asarray(Image.open(сеть).convert('RGB').resize((ш, в), Image.LANCZOS), int)

жёлтый = lambda A: (A[:, :, 0] > 150) & (A[:, :, 1] > 120) & (A[:, :, 2] < 110)
старые, новые = жёлтый(О), жёлтый(С)

# 1. Затираем старую надпись текстурой кнопки: для каждого пикселя буквы берём медиану чистых
#    пикселей вокруг, расширяя окно, пока чистые не найдутся.
чисто = О.copy()
ys, xs = np.where(старые)
for y, x in zip(ys, xs):
    for r in (3, 5, 8, 12):
        y0, y1, x0, x1 = max(0, y - r), min(в, y + r + 1), max(0, x - r), min(ш, x + r + 1)
        окно = О[y0:y1, x0:x1]
        маска = ~старые[y0:y1, x0:x1]
        if маска.sum() >= 6:
            чисто[y, x] = np.median(окно[маска], axis=0)
            break

# 2. Буквы сети: вырезаем, при необходимости ужимаем под круг и ставим по центру.
if новые.any():
    # Сеть иногда оставляет призрак старой надписи: редкие жёлтые точки над и под новой строкой.
    # Берём только плотную строку текста — по профилю строк оставляем полосу вокруг максимума.
    профиль = новые.sum(1)
    пик = int(профиль.argmax()); порог = max(2, профиль[пик] * 0.18)
    верх = пик
    while верх > 0 and профиль[верх - 1] >= порог: верх -= 1
    низ = пик
    while низ < len(профиль) - 1 and профиль[низ + 1] >= порог: низ += 1
    полоса = np.zeros_like(новые); полоса[верх:низ + 1] = True
    новые = новые & полоса
    ys, xs = np.where(новые)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    буквы = Image.fromarray((новые[y0:y1, x0:x1] * 255).astype('uint8'))
    цвета = Image.fromarray(С[y0:y1, x0:x1].astype('uint8'))
    предел = int(min(ш, в) * 0.66)                      # надпись не должна лезть на кольцо
    if буквы.width > предел:
        k = предел / буквы.width
        нов = (max(1, int(буквы.width * k)), max(1, int(буквы.height * k)))
        буквы = буквы.resize(нов, Image.LANCZOS); цвета = цвета.resize(нов, Image.LANCZOS)
    м = np.asarray(буквы) > 110
    ц = np.asarray(цвета, int)
    сдвx, сдвy = (ш - м.shape[1]) // 2, (в - м.shape[0]) // 2
    поле = np.zeros((в, ш), bool)
    поле[сдвy:сдвy + м.shape[0], сдвx:сдвx + м.shape[1]] = м
    краски = np.zeros_like(О)
    краски[сдвy:сдвy + м.shape[0], сдвx:сдвx + м.shape[1]] = ц
    чисто[поле] = краски[поле]

# Палитра берётся из САМОЙ кнопки, а не из общей MAIN.PAL: у кнопки своих 30-40 цветов, и если
# гнать через общую палитру, ближайший цвет находится не тот и меняется вся картинка (проверено:
# 68,0,0 превращалось в 51,0,0 на каждом пикселе). Со своей палитрой нетронутые места остаются
# нетронутыми, а буквы садятся на ближайший из уже имеющихся цветов.
цвета = np.unique(О.reshape(-1, 3), axis=0)
пал = Image.new('P', (1, 1))
плоско = [int(v) for c in цвета for v in c][:768]
пал.putpalette(плоско + [0] * (768 - len(плоско)))
итог = Image.fromarray(чисто.astype('uint8')).quantize(palette=пал, dither=Image.NONE).convert('RGBA')
итог.putalpha(о.getchannel('A'))
итог.save(готово)
изм = (np.asarray(итог.convert('RGB'), int) != О).any(2).sum()
print(f'{готово}: изменено {изм} пикселей из {ш * в} ({100 * изм / (ш * в):.1f} %)')
