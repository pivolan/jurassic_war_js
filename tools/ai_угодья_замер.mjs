// Стоят ли угодья карт чего-нибудь: одно и то же племя на всех картах с таблицей и без.
//
//   node tools/ai_угодья_замер.mjs [--карты=100,…] [--племена=0,5] [--секунд=600] [--потоков=…]
//
// Зачем отдельный замер. На карте 101 зверьё и так всё время на глазах, и таблица там не нужна —
// цифры не двигаются ни на единицу. Разница должна быть там, где стада ДАЛЕКО: пока племя не
// дошло до первого зверя, оно кормится вслепую. Поэтому гоняем все карты подряд и смотрим, что
// таблица даёт в сумме, а не на одной удобной карте.
//
// Меряем через tools/ai_курьер.mjs (одно племя, соперника нет — чистая экономика): последняя
// строка даёт казну, сдано, армию и её силу.
import { spawn } from 'node:child_process'; import path from 'node:path'; import url from 'node:url';
import * as Ядра from './ai_ядра.mjs';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));

const карты = (арг.карты || Array.from({ length: 20 }, (_, k) => 100 + k).join(',')).split(',').map(Number);
const племена = (арг.племена || '0,5').split(',').map(Number);
const СЕКУНД = +(арг.секунд || 600);
const ПОТОКОВ = Ядра.потоков(арг.потоков, 8);

/** Один прогон: карта, племя, таблица вкл/выкл → {сдано, сила, бойцов}. */
function прогон(карта, племя, таблица) {
  return new Promise((ок) => {
    const п = spawn(process.execPath, [path.join(КОРЕНЬ, 'tools/ai_курьер.mjs'),
      // Печать раз в минуту: с шагом во весь прогон стенд успевал напечатать только нулевую
      // минуту, и замер честно сравнивал стартовые числа сам с собой (везде «поровну»).
      `--карта=${карта}`, `--племя=${племя}`, `--секунд=${СЕКУНД}`, '--шаг=60'],
      { env: { ...process.env, JW_PASTURES: таблица ? '1' : '0' }, stdio: ['ignore', 'pipe', 'ignore'] });
    let буфер = '';
    п.stdout.on('data', (д) => { буфер += д; });
    п.on('close', () => {
      const строки = буфер.trim().split('\n').filter(с => /^\s*\d+ \|/.test(с));
      const п2 = строки[строки.length - 1];
      if (!п2) return ок(null);
      const ч = п2.split('|').map(с => с.trim());
      const [казна, сдано] = ч[1].split(/\s+/).map(Number);
      const [бойцов, сила] = ч[2].split(/\s+/).map(Number);
      ок({ казна, сдано, бойцов, сила });
    });
  });
}

const задания = [];
for (const к of карты) for (const п of племена) for (const т of [true, false]) задания.push([к, п, т]);
const итоги = new Map();
let сделано = 0;
const t0 = Date.now();
async function очередь() {
  while (задания.length) {
    const [к, п, т] = задания.shift();
    const р = await прогон(к, п, т);
    итоги.set(`${к}|${п}|${т ? 1 : 0}`, р);
    сделано++;
    if (сделано % 10 === 0) process.stderr.write(`  ${сделано} прогонов, ${((Date.now() - t0) / 60000).toFixed(1)} мин\n`);
  }
}
await Promise.all(Array.from({ length: ПОТОКОВ }, очередь));

console.log(`карт ${карты.length} × племён ${племена.length}, по ${СЕКУНД} с, ${((Date.now() - t0) / 60000).toFixed(1)} мин\n`);
console.log('карта | племя | сдано с таблицей : без | сила с : без');
let сТ = 0, безТ = 0, силаС = 0, силаБ = 0, лучше = 0, хуже = 0;
for (const к of карты) for (const п of племена) {
  const a = итоги.get(`${к}|${п}|1`), b = итоги.get(`${к}|${п}|0`);
  if (!a || !b) { console.log(`${String(к).padEnd(5)} | ${п} | прогон не удался`); continue; }
  сТ += a.сдано; безТ += b.сдано; силаС += a.сила; силаБ += b.сила;
  if (a.сдано > b.сдано) лучше++; else if (a.сдано < b.сдано) хуже++;
  const знак = a.сдано === b.сдано ? '=' : (a.сдано > b.сдано ? '+' : '−');
  console.log(`${String(к).padEnd(5)} | ${п}     | ${String(a.сдано).padStart(6)} : ${String(b.сдано).padStart(6)} ${знак} | ${String(a.сила).padStart(5)} : ${String(b.сила).padStart(5)}`);
}
const n = лучше + хуже;
console.log(`\nвсего сдано: ${сТ} с таблицей против ${безТ} без — ${безТ ? ((сТ / безТ - 1) * 100).toFixed(1) : '—'} %`);
console.log(`сила армий:  ${силаС} против ${силаБ} — ${силаБ ? ((силаС / силаБ - 1) * 100).toFixed(1) : '—'} %`);
console.log(`карт, где с таблицей лучше: ${лучше}, хуже: ${хуже}, поровну: ${карты.length * племена.length - n}`);
