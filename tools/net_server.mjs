function кадр(данные, двоичный) {
  const тело = двоичный ? данные : Buffer.from(данные, 'utf8');
  const n = тело.length;
  let шапка;
  if (n < 126) { шапка = Buffer.alloc(2); шапка[1] = n; }
  else if (n < 65536) { шапка = Buffer.alloc(4); шапка[1] = 126; шапка.writeUInt16BE(n, 2); }
  else { шапка = Buffer.alloc(10); шапка[1] = 127; шапка.writeBigUInt64BE(BigInt(n), 2); }
  шапка[0] = 0x80 | (двоичный ? 2 : 1);
  return Buffer.concat([шапка, тело]);
}

class Соединение {
  constructor(сокет) {
    this.сокет = сокет; this.буфер = Buffer.alloc(0); this.живой = true;
    this.комната = null; this.игрок = null; this.имя = '';
    this.куски = null; this.кусокДвоичный = false;     // недособранное фрагментированное сообщение
  }
  шли(данные, двоичный = false) { if (this.живой) this.сокет.write(кадр(данные, двоичный)); }
  шлиJSON(об) { this.шли(JSON.stringify(об)); }
  закрой() { if (this.живой) { this.живой = false; try { this.сокет.destroy(); } catch {} } }
}

// Браузер режет большие сообщения (снимок ~970 КБ) на фрагменты: первый кадр с кодом 1/2 и
// FIN=0, дальше кадры-продолжения с кодом 0, последний — с FIN=1. Склеиваем.
function разобрать(с, наСообщение) {
  let b = с.буфер;
  for (;;) {
    if (b.length < 2) break;
    const код = b[0] & 0x0f, маска = (b[1] & 0x80) !== 0, конец = (b[0] & 0x80) !== 0;
    let n = b[1] & 0x7f, сдвиг = 2;
    if (n === 126) { if (b.length < 4) break; n = b.readUInt16BE(2); сдвиг = 4; }
    else if (n === 127) { if (b.length < 10) break; n = Number(b.readBigUInt64BE(2)); сдвиг = 10; }
    if (n > ПРЕДЕЛ) { с.закрой(); return; }
    const ключ = сдвиг + (маска ? 4 : 0);
    if (b.length < ключ + n) break;
    let тело = b.subarray(ключ, ключ + n);
    if (маска) {
      const м = b.subarray(сдвиг, сдвиг + 4);
      тело = Buffer.from(тело);
      for (let i = 0; i < тело.length; i++) тело[i] ^= м[i & 3];
    }
    b = b.subarray(ключ + n);
    if (код === 8) { с.закрой(); с.буфер = b; return; }
    if (код === 9) { с.сокет.write(Buffer.concat([Buffer.from([0x8a, тело.length]), тело])); continue; }
    if (код === 10) { с.ждётПонг = false; continue; }                  // понг на наш пинг
    if (код === 1 || код === 2 || код === 0) {
      if (код !== 0) { с.куски = []; с.кусокДвоичный = код === 2; }
      else if (!с.куски) continue;                                  // продолжение без начала — мусор
      с.куски.push(Buffer.from(тело));
      if (с.куски.reduce((n, к) => n + к.length, 0) > ПРЕДЕЛ) { с.закрой(); return; }
      if (конец) { const всё = с.куски.length === 1 ? с.куски[0] : Buffer.concat(с.куски); с.куски = null; наСообщение(всё, с.кусокДвоичный); }
    }
  }
  с.буфер = b;
}

// Сведения о комнате для списка (лобби): их публикует хост сообщением «комната»
// { миссия, сложность, открытая, мест, статус: 'ожидание' | 'игра', племена }. Релей их только хранит.
function описание(имя, к) {
  const и = к.инфо || {};
  const живые = new Set([...к.участники].map(у => у.игрок));
  const места = [...к.места.values()].filter(м => м.роль !== 'наблюдатель').map(м => ({ игрок: м.игрок, имя: м.имя, живой: живые.has(м.игрок), племя: и.племена?.[м.игрок] }));
  for (const у of к.участники) if (у.роль !== 'наблюдатель' && !места.some(м => м.игрок === у.игрок)) места.push({ игрок: у.игрок, имя: у.имя, живой: true, племя: и.племена?.[у.игрок] });
  const наблюдателей = [...к.участники].filter(у => у.роль === 'наблюдатель').length;
  return { имя, статус: и.статус || 'ожидание', миссия: и.миссия ?? null, сложность: и.сложность ?? 1, открытая: !!и.открытая, зрители: и.зрители !== false, состояние: и.состояние || null,
           мест: и.мест ?? null, игроков: места.filter(м => м.живой).length, наблюдателей, вылетевших: места.filter(м => !м.живой).length, места, создана: к.создана, хост: к.хост?.игрок ?? null };
}

/** Можно ли войти: своё место — всегда; наблюдатель — всегда; в ожидание — если есть свободные;
 *  в игру — только в открытую и при свободных местах. */
function пускать(к, ключ, роль) {
  if (ключ && к.места.has(ключ)) return null;
  const и = к.инфо || {};
  if (роль === 'наблюдатель') {
    if (и.статус === 'игра' && и.зрители === false) return 'хост не пускает зрителей во время матча';
    if ([...к.участники].filter(у => у.роль === 'наблюдатель').length >= ЗРИТЕЛЕЙ_МАКС) return 'мест для зрителей нет';
    return null;
  }
  const занято = [...к.места.values()].filter(м => м.роль !== 'наблюдатель').length;
  if (и.мест != null && занято >= и.мест) return 'в комнате нет свободных мест';
  if (и.статус === 'игра' && !и.открытая) return 'партия уже идёт, и хост не пускает в неё посторонних';
  return null;
}

function войти(с, имяКомнаты, имяИгрока, ключ, роль) {
  let к = комнаты.get(имяКомнаты);
  if (!к) комнаты.set(имяКомнаты, к = { участники: new Set(), хост: null, следующий: 0, места: new Map(), инфо: null, создана: Date.now() });
  const отказ = пускать(к, ключ, роль);
  if (отказ) { с.шлиJSON({ вид: 'отказ', текст: отказ }); if (к.участники.size === 0) комнаты.delete(имяКомнаты); return null; }
  с.комната = имяКомнаты;
  const место = ключ ? к.места.get(ключ) : null;
  let вернулся = false;
  if (место) {
    // Своё место. Если старое соединение ещё числится живым (обрыв, который сервер не заметил),
    // новое его вытесняет: настоящий владелец ключа — тот, кто пришёл сейчас.
    if (место.с && место.с.живой && место.с !== с) { const старое = место.с; старое.вытеснен = true; старое.закрой(); к.участники.delete(старое); }
    // Место игрока возвращается игроку, какую бы роль ни попросил клиент: из нового окна он не
    // знает, что ключ подойдёт, и просит «наблюдателя» — а хост потом ждал бы его в партии вечно.
    // Наблюдательское место роль не навязывает: из него можно войти игроком.
    с.игрок = место.игрок; вернулся = true; с.роль = место.роль === 'наблюдатель' ? (роль === 'наблюдатель' ? 'наблюдатель' : 'игрок') : 'игрок';
  } else {
    с.игрок = к.следующий++; с.роль = роль === 'наблюдатель' ? 'наблюдатель' : 'игрок';
  }
  с.имя = имяИгрока || ('игрок ' + с.игрок);
  if (ключ) к.места.set(ключ, { игрок: с.игрок, с, имя: с.имя, роль: с.роль });
  к.участники.add(с);
  // Хост — только игрок; наблюдатель хостом не становится
  if (!к.хост || !к.хост.живой || !к.участники.has(к.хост)) к.хост = [...к.участники].find(у => у.роль !== 'наблюдатель') || с;
  разослать(имяКомнаты, { вид: 'состав', хост: к.хост.игрок, вернулся: вернулся ? с.игрок : undefined,
                          участники: [...к.участники].map(у => ({ игрок: у.игрок, имя: у.имя, роль: у.роль })) });
  console.log(`[${имяКомнаты}] ${вернулся ? 'вернулся' : 'вошёл'} ${с.имя} (игрок ${с.игрок}), всего ${к.участники.size}`);
  return вернулся;
}

function разослать(имяКомнаты, об, двоичное) {
  const к = комнаты.get(имяКомнаты);
  if (!к) return;
  const пакет = двоичное ? кадр(об, true) : кадр(JSON.stringify(об), false);
  for (const у of к.участники) if (у.живой) у.сокет.write(пакет);
}

function выйти(с) {
  const к = комнаты.get(с.комната);
  if (!к || !к.участники.has(с)) return;              // вытесненное соединение уже убрано
  к.участники.delete(с);
  for (const м of к.места.values()) if (м.с === с) м.ушёл = Date.now();   // место держим МЕСТО_МИН минут, потом забываем
  console.log(`[${с.комната}] вышел ${с.имя}, осталось ${к.участники.size}`);
  // Игроков не осталось (даже если партия шла) — комната закрывается; зрителей, если были, выставляем
  if (![...к.участники].some(у => у.роль !== 'наблюдатель')) {
    for (const у of [...к.участники]) { у.шлиJSON({ вид: 'выгнан', причина: 'комната закрыта' }); у.закрой(); }
    комнаты.delete(с.комната); console.log(`[${с.комната}] закрыта: игроков нет`); return;
  }
  if (к.хост === с) к.хост = [...к.участники].find(у => у.роль !== 'наблюдатель') || [...к.участники][0];
  разослать(с.комната, { вид: 'состав', хост: к.хост.игрок, ушёл: с.игрок,
                          участники: [...к.участники].map(у => ({ игрок: у.игрок, имя: у.имя, роль: у.роль })) });
}

