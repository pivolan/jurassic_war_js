// Точка сбора для сетевой игры (наше). Маленький релей на веб-сокетах, без зависимостей.
//
//   node tools/net_server.mjs [порт]         (по умолчанию 8791, слушает 127.0.0.1; в бою крутится в supervisor как jw_net, снаружи ws://127.0.0.1:8791/)
//
// Зачем он нужен. Браузер не умеет слушать входящие соединения, поэтому напрямую клиент с
// клиентом не свяжется — нужна общая точка. Релей ничего не знает про игру: он держит комнаты и
// пересылает сообщения всем участникам комнаты, включая отправителя. Это важно: все получают один
// и тот же поток в одном и том же порядке, и ни у кого нет «своей» истории.
//
// Первый вошедший в комнату становится хостом. Место в комнате привязано к ключу игрока (случайная
// строка, которую браузер хранит у себя): кто пришёл с тем же ключом — тот же игрок, ему отдаётся
// его номер. Так вылетевший возвращается в свою партию, а посторонний с улицы занять чужое место
// не может — ключ никому, кроме релея, не показывается.
//
// Первый вошедший в комнату становится хостом. Хост нужен для двух вещей: он раздаёт начальный
// снимок памяти (загружать миссию на каждой машине нельзя — 0x15da1 дёргает второй ГСЧ от таймера
// BIOS) и он же присылает снимок при рассинхроне. Симуляцию все считают сами.
//
// Реализация веб-сокета своя: рукопожатие по RFC 6455 и разбор кадров — сотня строк, зато в
// проекте по-прежнему ни одной внешней зависимости.
