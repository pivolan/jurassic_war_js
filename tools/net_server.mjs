/** Заголовок .jwr: MAGIC(4) + u32 длина + JSON. Возвращает объект или null. */
function заголовокРеплея(буф) {
  if (буф.length < 12 || буф.toString('latin1', 0, 4) !== 'JWR1') return null;
  const n = буф.readUInt32LE(4);
  if (n < 2 || n > 65536 || 8 + n > буф.length) return null;
  try { return JSON.parse(буф.toString('utf8', 8, 8 + n)); } catch { return null; }
}
