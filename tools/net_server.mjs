const ЗАГОЛОВКИ = { 'cache-control': 'no-store', 'access-control-allow-origin': '*',
                    'access-control-allow-methods': 'GET, POST, OPTIONS', 'access-control-allow-headers': 'content-type, x-replay-id' };
const сервер = http.createServer((req, res) => {
  const путь = req.url.replace(/^\/+/, '/');
  if (req.method === 'OPTIONS') { res.writeHead(204, ЗАГОЛОВКИ); res.end(); return; }
  if (путь.startsWith('/rooms')) {   // список комнат для лобби (снаружи /jw/net/rooms nginx отдаёт как //rooms)
    res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
    res.end(JSON.stringify([...комнаты].map(([и, к]) => описание(и, к)))); return;
  }
  // ---- реплеи: список, скачивание, приём
  if (путь.startsWith('/replays')) {
    const хвост = путь.slice('/replays'.length).replace(/^\/+/, '').split('?')[0];
    if (req.method === 'GET' && !хвост) {
      const список = [...описьРеплеев.values()].sort((a, b) => (b.date || 0) - (a.date || 0)).slice(0, 200);
      res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
      res.end(JSON.stringify(список)); return;
    }
    if (req.method === 'GET' && /^[\w.-]+$/.test(хвост)) {
      const файл = path.join(РЕПЛЕИ, хвост.endsWith('.jwr') ? хвост : хвост + '.jwr');
      if (!fs.existsSync(файл)) { res.writeHead(404, ЗАГОЛОВКИ); res.end('нет такого реплея'); return; }
      res.writeHead(200, { 'content-type': 'application/octet-stream', ...ЗАГОЛОВКИ });
      fs.createReadStream(файл).pipe(res); return;
    }
    if (req.method === 'POST') {
      const куски = []; let всего = 0, оборвали = false;
      req.on('data', (к) => {
        всего += к.length;
        if (всего > РЕПЛЕЙ_ПРЕДЕЛ) { оборвали = true; req.destroy(); return; }
        куски.push(к);
      });
      req.on('end', () => {
        if (оборвали) { res.writeHead(413, ЗАГОЛОВКИ); res.end('слишком большой'); return; }
        const тело = Buffer.concat(куски);
        const h = заголовокРеплея(тело);
        if (!h) { res.writeHead(400, ЗАГОЛОВКИ); res.end('это не реплей'); return; }
        // Заголовок «x-replay-id» позволяет перезаписать уже принятую запись: браузер шлёт партию
        // не только в конце, но и по ходу (раз в минуту), чтобы она не пропала вместе с закрытой
        // вкладкой. Идентификатор чистим до безопасного вида — он становится именем файла.
        const свой = String(req.headers['x-replay-id'] || '').replace(/[^A-Za-z0-9_.-]/g, '').slice(0, 64);
        const id = свой || (String(Date.now()) + '-' + crypto.randomBytes(4).toString('hex'));
        try { fs.writeFileSync(path.join(РЕПЛЕИ, id + '.jwr'), тело); } catch (e) {
          res.writeHead(500, ЗАГОЛОВКИ); res.end('не записалось'); return; }
        описьРеплеев.set(id, { id, ...h, bytes: тело.length });
        подрезатьРеплеи();
        console.log(`реплей ${свой ? 'обновлён' : 'принят'}: ${h.name || id}, ${(тело.length / 1024) | 0} КБ, всего ${описьРеплеев.size}`);
        res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
        res.end(JSON.stringify({ id }));
      });
      req.on('error', () => {});
      return;
    }
    res.writeHead(405, ЗАГОЛОВКИ); res.end('нельзя'); return;
  }
  // ---- сохранения: список, скачивание, приём
  if (путь.startsWith('/saves')) {
    const хвост = путь.slice('/saves'.length).replace(/^\/+/, '').split('?')[0];
    if (req.method === 'GET' && !хвост) {
      const список = fs.readdirSync(СЕЙВЫ).filter(f => f.endsWith('.meta.json')).map(f => {
        try { return JSON.parse(fs.readFileSync(path.join(СЕЙВЫ, f), 'utf8')); } catch { return null; } })
        .filter(Boolean).sort((a, b) => (b.date || 0) - (a.date || 0)).slice(0, 200);
      res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
      res.end(JSON.stringify(список)); return;
    }
    if (req.method === 'GET' && /^[\w-]+$/.test(хвост)) {
      const файл = path.join(СЕЙВЫ, хвост + '.json');
      if (!fs.existsSync(файл)) { res.writeHead(404, ЗАГОЛОВКИ); res.end('нет такого сохранения'); return; }
      res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
      fs.createReadStream(файл).pipe(res); return;
    }
    if (req.method === 'POST') {
      const куски = []; let всего = 0, оборвали = false;
      req.on('data', (к) => { всего += к.length; if (всего > СЕЙВ_ПРЕДЕЛ) { оборвали = true; req.destroy(); return; } куски.push(к); });
      req.on('end', () => {
        if (оборвали) { res.writeHead(413, ЗАГОЛОВКИ); res.end('слишком большой'); return; }
        let об; try { об = JSON.parse(Buffer.concat(куски).toString('utf8')); } catch { об = null; }
        if (!об || typeof об.data !== 'string' || !об.meta) { res.writeHead(400, ЗАГОЛОВКИ); res.end('это не сохранение'); return; }
        const id = new Date().toISOString().replace(/[-:]/g, '').replace('T', '-').slice(0, 15) + '-' + crypto.randomBytes(3).toString('hex');
        const м = об.meta;
        const опись = { id, date: Date.now(), mission: м.mission, tribe: м.tribe, difficulty: м.difficulty, step: м.step, build: м.build, bytes: всего };
        try {
          fs.writeFileSync(path.join(СЕЙВЫ, id + '.json'), JSON.stringify(об));
          fs.writeFileSync(path.join(СЕЙВЫ, id + '.meta.json'), JSON.stringify(опись));
          const старые = fs.readdirSync(СЕЙВЫ).filter(f => f.endsWith('.meta.json')).sort();
          for (const f of старые.slice(0, Math.max(0, старые.length - СЕЙВОВ_МАКС))) {
            fs.rmSync(path.join(СЕЙВЫ, f), { force: true }); fs.rmSync(path.join(СЕЙВЫ, f.replace('.meta.json', '.json')), { force: true });
          }
        } catch { res.writeHead(500, ЗАГОЛОВКИ); res.end('не записалось'); return; }
        console.log(`сохранение принято: ${id}, стадия ${(м.mission ?? 0) + 1}, племя ${м.tribe}, ${(всего / 1024) | 0} КБ`);
        res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ });
        res.end(JSON.stringify({ id }));
      });
      req.on('error', () => {});
      return;
    }
    res.writeHead(405, ЗАГОЛОВКИ); res.end('нельзя'); return;
  }
  res.writeHead(200, { 'content-type': 'text/plain; charset=utf-8' });
  res.end(`релей сетевой игры Jurassic War\nкомнат: ${комнаты.size}, реплеев: ${описьРеплеев.size}\n` +
          [...комнаты].map(([и, к]) => `  ${и}: ${к.участники.size}`).join('\n') + '\n');
});

сервер.on('upgrade', (req, сокет) => {
  const ключ = req.headers['sec-websocket-key'];
  if (!ключ) { сокет.destroy(); return; }
  const ответ = crypto.createHash('sha1').update(ключ + МАГИЯ).digest('base64');
  сокет.write('HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n' +
              `Sec-WebSocket-Accept: ${ответ}\r\n\r\n`);
  сокет.setNoDelay(true);
  const с = new Соединение(сокет);
  сокет.on('data', (кусок) => {
    с.буфер = Buffer.concat([с.буфер, кусок]);
    разобрать(с, (тело, двоичное) => {
      if (двоичное) {
        // Двоичное — это снимок: первым байтом номер получателя (0xff — всем).
        if (с.комната) разослать(с.комната, тело, true);
        return;
      }
      let об;
      try { об = JSON.parse(тело.toString('utf8')); } catch { return; }
      if (об.вид === 'войти') { const в = войти(с, String(об.комната || 'общая').slice(0, 40), String(об.имя || '').slice(0, 24), typeof об.ключ === 'string' ? об.ключ.slice(0, 64) : null, об.роль); if (в !== null) с.шлиJSON({ вид: 'ты', игрок: с.игрок, вернулся: в, роль: с.роль }); return; }
      if (об.вид === 'привет') {           // холл: имя и где сейчас (комната или null)
        с.имя = String(об.имя || '').slice(0, 24) || 'гость'; с.где = об.комната ? String(об.комната).slice(0, 40) : null;
        холл.add(с); рассылатьОнлайн(); return;
      }
      if (об.вид === 'чат') {              // текст режем и подписываем сами; в комнате — всем в комнате, из холла — всему холлу
        const текст = String(об.текст || '').slice(0, ЧАТ_МАКС).trim(); if (!текст || !чатМожно(с)) return;
        if (с.комната) { разослать(с.комната, { вид: 'чат', игрок: с.игрок, имя: с.имя, текст, t: Date.now() }); return; }
        if (холл.has(с)) { const об2 = JSON.stringify({ вид: 'чат', общий: true, имя: с.имя, текст, t: Date.now() }); for (const у of кроме()) у.шли(об2); }
        return;
      }
      if (!с.комната) return;
      if (об.вид === 'роль') {            // смена роли на месте: без переподключения, номер игрока и ключ сохраняются
        const к = комнаты.get(с.комната); if (!к) return;
        const хочет = об.роль === 'наблюдатель' ? 'наблюдатель' : 'игрок';
        if (с.роль === хочет) return;
        const прочие = [...к.участники].filter(у => у !== с);
        if (хочет === 'наблюдатель') {
          if (прочие.filter(у => у.роль === 'наблюдатель').length >= ЗРИТЕЛЕЙ_МАКС) return с.шлиJSON({ вид: 'роль_отказ', текст: 'мест для зрителей нет' });
          if (!прочие.some(у => у.роль !== 'наблюдатель')) return с.шлиJSON({ вид: 'роль_отказ', текст: 'в комнате должен остаться хотя бы один игрок' });
        } else {
          const и = к.инфо || {}; const занято = прочие.filter(у => у.роль !== 'наблюдатель').length;
          if (и.мест != null && занято >= и.мест) return с.шлиJSON({ вид: 'роль_отказ', текст: 'в комнате нет свободных мест' });
        }
        с.роль = хочет;
        for (const м of к.места.values()) if (м.с === с) м.роль = хочет;
        if (к.хост === с && хочет === 'наблюдатель') к.хост = прочие.find(у => у.роль !== 'наблюдатель') || с;
        разослать(с.комната, { вид: 'состав', хост: к.хост.игрок, роль: с.игрок,
                                участники: [...к.участники].map(у => ({ игрок: у.игрок, имя: у.имя, роль: у.роль })) });
        return;
      }
      if (об.вид === 'выгнать') {          // хост выгоняет из лобби (во время партии нельзя); место освобождается, ключ забывается
        const к = комнаты.get(с.комната); if (!к || к.хост !== с || (к.инфо && к.инфо.статус === 'игра')) return;
        const кого = [...к.участники].find(у => у.игрок === об.кого); if (!кого || кого === с) return;
        for (const [ключ, м] of к.места) if (м.игрок === кого.игрок) к.места.delete(ключ);
        кого.шлиJSON({ вид: 'выгнан' }); кого.закрой(); return;
      }
      if (об.вид === 'комната') {          // сведения о комнате — только от хоста
        const к = комнаты.get(с.комната); if (к && к.хост === с) { к.инфо = { миссия: об.миссия, сложность: об.сложность, открытая: !!об.открытая, зрители: об.зрители !== false, мест: об.мест, статус: об.статус, племена: об.племена || {}, состояние: об.состояние || null }; }
        return;
      }
      об.игрок = с.игрок;                 // отправителя проставляет сервер, а не клиент
      разослать(с.комната, об);
    });
  });
  // Сокет после upgrade у http-сервера полуоткрытый (allowHalfOpen): когда та сторона закрылась,
  // приходит только «end», а «close» — нет, и соединение висло в CLOSE-WAIT, а место в комнате
  // считалось живым. Закрываем сами. Плюс пинг раз в 30 с: кто не ответил понгом — обрыв.
  сокет.on('end', () => с.закрой());
  const ушёл = () => { с.живой = false; clearInterval(с.пинг); выйти(с); if (холл.delete(с)) рассылатьОнлайн(); };
  сокет.on('close', ушёл);
  сокет.on('error', ушёл);
  с.ждётПонг = false;
  с.пинг = setInterval(() => {
    if (!с.живой) return clearInterval(с.пинг);
    if (с.ждётПонг) { с.закрой(); return; }
    с.ждётПонг = true; try { с.сокет.write(Buffer.from([0x89, 0])); } catch { с.закрой(); }
  }, 30000);
});

