// Прогон всех сцен скриптовым учителем без графики: проверка стыковки с движком и наград.
//   node tools/ai_smoke.mjs [вариаций] [подстрока имени сцены]
import { СЦЕНЫ, эпизод, решение, ДЕЙСТВИЯ, среднее } from './ai_lib.mjs';

const ВАРИАЦИЙ = +(process.argv[2] || 5);
const ФИЛЬТР = process.argv[3] || '';
let всегоШагов = 0, всегоЭпизодов = 0;
const t0 = process.hrtime.bigint();
for (const сц of СЦЕНЫ) {
  if (ФИЛЬТР && !сц.имя.includes(ФИЛЬТР)) continue;
  const счёт = new Array(ДЕЙСТВИЯ.length).fill(0);
  const итоги = [], подсказки = [], исходы = [], причины = new Map();
  for (let в = 0; в < ВАРИАЦИЙ; в++) {
    const эп = эпизод(сц, в, (e, i, э) => { const d = решение(e, i, э); счёт[d]++; return d; });
    итоги.push(эп.итого); подсказки.push(эп.награда); исходы.push(эп.исход);
    причины.set(эп.причина, (причины.get(эп.причина) || 0) + 1);
    всегоШагов += эп.тик; всегоЭпизодов++;
    if (эп.ошибки) console.log('  ОШИБКИ ДВИЖКА:', эп.ошибки);
  }
  const ср = среднее(итоги), сп = среднее(подсказки), си = среднее(исходы);
  const топ = счёт.map((n, k) => [n, ДЕЙСТВИЯ[k]]).filter(([n]) => n).sort((x, y) => y[0] - x[0])
                  .slice(0, 4).map(([n, им]) => `${им} ${n}`).join(', ');
  console.log(`${(сц.проверочная ? '· ' : '  ') + сц.имя.padEnd(28)} ${сц.роль.padEnd(16)} ` +
              `итог ${ср >= 0 ? '+' : ''}${ср.toFixed(2)} (исход ${си >= 0 ? '+' : ''}${си.toFixed(2)}, подсказки ${сп >= 0 ? '+' : ''}${сп.toFixed(2)})  [${[...причины].map(([п, n]) => `${п}×${n}`).join(', ')}]  ${топ}`);
}
const мс = Number(process.hrtime.bigint() - t0) / 1e6;
console.log(`\n${всегоЭпизодов} эпизодов, ${всегоШагов} шагов за ${мс.toFixed(0)} мс = ` +
            `${(всегоШагов / мс).toFixed(0)} тыс. шагов/с, ${(мс / всегоЭпизодов).toFixed(1)} мс на эпизод`);
