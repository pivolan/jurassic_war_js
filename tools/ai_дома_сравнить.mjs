// Сравнить двое весов по вниманию к постройкам (наше).
//
//   node tools/ai_дома_сравнить.mjs <было.json> <стало.json> [партий=24]
//
// Гоняет одинаковые партии против скриптового штаба и печатает три числа на каждые веса:
//   поЗданиям  — доля решений, отданных по вражескому дому (было ноль: действия просто не было);
//   уронЗданий — суммарная плата за урон постройкам (сколько сеть их реально ломает);
//   счётЗданий — «снесли у них минус потеряли у себя» по ценности, в среднем за партию.
// Плюс обычный итог, чтобы видеть, не разменяли ли мы победы на увлечение стенами.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
const [было, стало] = process.argv.slice(2);
const ПАРТИЙ = +(process.argv[4] || 24);
if (!было || !стало) { console.error('нужны два файла весов'); process.exit(1); }
const прогон = (веса, метка) => {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'дома-'));
  const из = execFileSync('node', ['tools/ai_game_rollout.mjs', веса, папка, String(ПАРТИЙ), '16', '7', '1'],
                          { encoding: 'utf8', maxBuffer: 1 << 26 });
  fs.rmSync(папка, { recursive: true, force: true });
  const с = JSON.parse(из.trim().split('\n').pop());
  console.log(`${метка}: итог ${с.итог.toFixed(3)} [побед ${с.побед} поражений ${с.поражений}] · ` +
              `поЗданиям ${с.поЗданиям} · уронЗданий ${с.уронЗданий} · счётЗданий ${с.счётЗданий}`);
  return с;
};
const a = прогон(было, 'было '), b = прогон(стало, 'стало');
console.log(`\nразница: итог ${(b.итог - a.итог >= 0 ? '+' : '') + (b.итог - a.итог).toFixed(3)}, ` +
            `решений по домам ${(b.поЗданиям - a.поЗданиям).toFixed(3)}, ` +
            `плата за урон ${(b.уронЗданий - a.уронЗданий).toFixed(1)}, ` +
            `счёт по зданиям ${(b.счётЗданий - a.счётЗданий).toFixed(3)}`);
