#!/usr/bin/env python3
"""Наложить на кнопку меню надпись, нарисованную нейросетью отдельно (наше).

  python3 tools/menu_letters.py <кнопка.png> <буквы.png> <готово.png> [--ширина=0.62] [--строки=1]

Зачем отдельно. Надписи на круглых кнопках оригинала — не шрифт: в паке лежат только FE0808RD.FNT
и FE0816RD.FNT (8×8 и 8×16), а буквы на кнопках крупнее и нарисованы от руки. Печать нашим
шрифтом с увеличением похожей не выходит. Поэтому просим сеть нарисовать ТОЛЬКО слово тем же
почерком на пустом фоне, а всё остальное делаем сами и локально:
  1) из ответа берём маску букв (заливка + её обводка — обводка у сети толстая, у оригинала её нет,
     поэтому она идёт в тело буквы, а не в контур);
  2) ужимаем маску с усреднением площади → карта покрытия 0..1, это и есть мягкие края;
  3) старую надпись затираем медианой соседей кнопки (как в menu_paint.py);
  4) покрытие раскладываем по тем оттенкам жёлтого, которые уже есть на этой кнопке: полное
     покрытие — тело буквы, частичное — те же ступени, что и в родном шрифте;
  5) квантуем в собственные цвета кнопки и возвращаем исходную альфу.
Кольцо, текстура и прозрачность остаются побайтово родными, меняется только середина.
"""
import sys, os
_свои = os.path.dirname(os.path.abspath(__file__))
sys.path = [p for p in sys.path if os.path.abspath(p or '.') != _свои] + [_свои]
import numpy as np
from PIL import Image, ImageFilter

кнопка, буквы, готово = sys.argv[1:4]
арг = dict(a[2:].split('=') for a in sys.argv[4:] if a.startswith('--') and '=' in a)
ДОЛЯ = float(арг.get('ширина', 0.62))       # ширина надписи от ширины кнопки
СТРОК = int(арг.get('строки', 1))

о = Image.open(кнопка).convert('RGBA'); ш, в = о.size
О = np.asarray(о.convert('RGB'), int)

# --- 1. Маска букв из картинки сети -------------------------------------------------------
Б = np.asarray(Image.open(буквы).convert('RGB'), int)
# Сеть рисует буквы с толстой чёрной обводкой, а в оригинале обводки нет. Если брать «всё, что не
# фон», обводка уходит в тело буквы, штрих толстеет вдвое и на 15 пикселях высоты слово слипается
# в кляксу (проверено). Поэтому по умолчанию берём только жёлтую заливку.
часть = арг.get('часть', 'заливка')
if часть == 'заливка':
    маска = (Б[:, :, 0] > 140) & (Б[:, :, 1] > 100) & (Б[:, :, 2] < 140) & (Б[:, :, 0] > Б[:, :, 2] + 60)
else:
    фон = np.median(np.concatenate([Б[0], Б[-1], Б[:, 0], Б[:, -1]]), axis=0)
    маска = (np.abs(Б - фон[None, None, :]).sum(2) > 90)
# дырки внутри букв (сеть иногда оставляет светлую сердцевину) закрываем замыканием
маска = np.asarray(Image.fromarray((маска * 255).astype('uint8')).filter(ImageFilter.MaxFilter(3))
                   .filter(ImageFilter.MinFilter(3))) > 0
ys, xs = np.where(маска)
if not len(ys): sys.exit('на картинке сети не нашлось букв')
М = Image.fromarray((маска[ys.min():ys.max() + 1, xs.min():xs.max() + 1] * 255).astype('uint8'))

# --- 2. Покрытие в нужном размере ----------------------------------------------------------
# Масштаб. По ширине слова его брать нельзя: у «Back» четыре буквы, у «Skirmish» восемь, и при
# равной ширине буквы выходят разного кегля. Поэтому меряем высоту ПЕРВОЙ буквы (она везде
# заглавная и без выносных) и подгоняем её под нужный кегль; ширина только ограничивается.
КЕГЛЬ = float(арг.get('кегль', 0))
if КЕГЛЬ:
    м2 = np.asarray(М) > 0
    столбцы = м2.any(0)
    к = np.argmax(~столбцы[np.argmax(столбцы):]) + np.argmax(столбцы) if (~столбцы).any() else м2.shape[1]
    первая = м2[:, :max(2, k := int(к))]
    ряды = np.where(первая.any(1))[0]
    кегль_ист = (ряды.max() - ряды.min() + 1) if len(ряды) else М.height
    масштаб = КЕГЛЬ / кегль_ист
    цель_ш = max(1, int(round(М.width * масштаб)))
    предел = int(ш * 0.78)
    if цель_ш > предел: цель_ш = предел
else:
    цель_ш = max(1, int(round(ш * ДОЛЯ)))
цель_в = max(1, int(round(М.height * цель_ш / М.width)))
покрытие = np.asarray(М.resize((цель_ш, цель_в), Image.BOX), float) / 255.0

# --- 3. Затираем старую надпись ------------------------------------------------------------
строго = (О[:, :, 0] > 150) & (О[:, :, 1] > 120) & (О[:, :, 2] < 120) & (О[:, :, 0] > О[:, :, 2] + 80)
широко = (О[:, :, 0] > 120) & (О[:, :, 1] > 80) & (О[:, :, 2] < 120) & (О[:, :, 0] > О[:, :, 2] + 60)
жёлтый = np.asarray(Image.fromarray((широко * 255).astype('uint8')).filter(ImageFilter.MaxFilter(5))) > 0
# Заливаем не одним махом, а слоями от края дыры внутрь: каждый следующий пиксель считается по
# уже восстановленным соседям. Один общий медианный проход оставлял на месте старой строки
# заметное ровное пятно — текстура вокруг слишком контрастная.
чисто = О.astype(float).copy()
дыра = жёлтый.copy()
while дыра.any():
    кайма = дыра & ~(np.asarray(Image.fromarray((дыра * 255).astype('uint8')).filter(ImageFilter.MinFilter(3))) > 0)
    if not кайма.any(): кайма = дыра
    новые = {}
    for y, x in zip(*np.where(кайма)):
        y0, y1, x0, x1 = max(0, y - 2), min(в, y + 3), max(0, x - 2), min(ш, x + 3)
        м = ~дыра[y0:y1, x0:x1]
        if м.sum() >= 3: новые[(y, x)] = np.median(чисто[y0:y1, x0:x1][м], axis=0)
    if not новые:
        for y, x in zip(*np.where(кайма)): чисто[y, x] = np.median(чисто[~дыра], axis=0)
        break
    for (y, x), v in новые.items(): чисто[y, x] = v
    for (y, x) in новые: дыра[y, x] = False

# --- 4. Оттенки самой кнопки ---------------------------------------------------------------
from collections import Counter
сч = Counter(map(tuple, О[строго]))
по_частоте = [np.array(c, float) for c, _ in сч.most_common(6)]
тело = по_частоте[0] if по_частоте else np.array([252.0, 252.0, 0.0])
края = по_частоте[1:] or [тело * 0.75]
ступени = [тело] + [края[min(k, len(края) - 1)] for k in range(3)]

поле = np.zeros((в, ш), float)
сдx, сдy = (ш - цель_ш) // 2, (в - цель_в) // 2
поле[сдy:сдy + цель_в, сдx:сдx + цель_ш] = покрытие
# те же четыре ступени, что у родного шрифта: тело — края — глубже — самый край
уровень = np.zeros((в, ш), np.uint8)
uровни = [(0.80, 1), (0.50, 2), (0.28, 3), (0.12, 4)]
for порог, к in uровни:
    uст = (поле >= порог) & (уровень == 0)
    уровень[uст] = к
for к in (1, 2, 3, 4):
    где = уровень == к
    if где.any(): чисто[где] = ступени[к - 1]

# --- 5. Обратно в цвета кнопки -------------------------------------------------------------
свои = np.unique(О.reshape(-1, 3), axis=0)
пал = Image.new('P', (1, 1))
плоско = [int(v) for c in свои for v in c][:768]
пал.putpalette(плоско + [0] * (768 - len(плоско)))
итог = Image.fromarray(np.clip(чисто, 0, 255).astype('uint8')).quantize(palette=пал, dither=Image.NONE).convert('RGBA')
итог.putalpha(о.getchannel('A'))
итог.save(готово)
изм = (np.asarray(итог.convert('RGB'), int) != О).any(2).sum()
print(f'{готово}: буквы {цель_ш}×{цель_в}, изменено {изм} из {ш*в} ({100*изм/(ш*в):.1f} %)')
