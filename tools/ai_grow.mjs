// Расширить веса сети под новый размер входа и выхода (наше).
//
//   node tools/ai_grow.mjs <старые.json> <новые.json>
//
// Зачем. Когда у бойца появляется новое действие («бить дом»), меняются два размера: выход
// политики (действий стало на одно больше) и вектор признаков (в него входит one-hot прошлого
// действия). Учить с нуля из-за этого расточительно — всё, что сеть уже умеет, лежит в свёртках и
// в скрытом слое. Поэтому веса не выбрасываем, а доращиваем нулями:
//   f1w — в каждую строку скрытого слоя вставляем нулевой столбец на месте нового признака;
//   pw  — добавляем нулевую строку логита нового действия;
//   pb  — добавляем смещение НАЧАЛЬНОЕ_СМЕЩЕНИЕ (немного меньше нуля), чтобы на первых шагах
//         новое действие не выбиралось наравне с выученными, но и не было закрыто совсем.
// Всё остальное переносится байт в байт: сеть после доращивания ведёт себя как прежняя.
import fs from 'node:fs';
const [вход, выход] = process.argv.slice(2);
if (!вход || !выход) { console.error('нужны старый и новый файл весов'); process.exit(1); }
const { ОКНО, СЛОЁВ, ВЕКТОР } = await import('../reimpl/js/ai/obs.js');
const { ЧИСЛО_ДЕЙСТВИЙ, ДЕЙСТВИЯ } = await import('../reimpl/js/ai/act.js');
const НАЧАЛЬНОЕ_СМЕЩЕНИЕ = -1;

const w = JSON.parse(fs.readFileSync(вход, 'utf8'));
if (w.окно !== ОКНО || w.слоёв !== СЛОЁВ) throw new Error('окно или число слоёв не совпадают — это другая сеть');
const дД = ЧИСЛО_ДЕЙСТВИЙ - w.действий, дВ = ВЕКТОР - w.вектор;
console.log(`было: вектор ${w.вектор}, действий ${w.действий}; стало: ${ВЕКТОР}, ${ЧИСЛО_ДЕЙСТВИЙ} (+${дВ} признаков, +${дД} действий)`);
if (дД < 0 || дВ < 0) throw new Error('сеть можно только доращивать, урезать нельзя');
if (дД === 0 && дВ === 0) { fs.copyFileSync(вход, выход); console.log('размеры совпадают — просто скопировал'); process.exit(0); }

const с = w.слои;
const С = с.f1b.length;                       // скрытых нейронов
const КОНВ = с.f1w.length / С - w.вектор;     // сколько входов приходит от свёрток
if (!Number.isInteger(КОНВ)) throw new Error('не сходится размер f1w');
// Вектор устроен так: [свои признаки | задания | one-hot прошлого действия | сдвиг]. Новое
// действие добавляется В КОНЕЦ списка действий, то есть его столбец встаёт сразу после последнего
// действия — перед двумя числами сдвига. Считаем эту позицию от конца, не завися от того, сколько
// признаков впереди.
const позицияНового = w.вектор - 2;
const f1w = [];
for (let h = 0; h < С; h++) {
  const строка = с.f1w.slice(h * (КОНВ + w.вектор), (h + 1) * (КОНВ + w.вектор));
  const конв = строка.slice(0, КОНВ), вект = строка.slice(КОНВ);
  const новый = вект.slice(0, позицияНового).concat(new Array(дВ).fill(0), вект.slice(позицияНового));
  f1w.push(...конв, ...новый);
}
const pw = с.pw.concat(new Array(дД * С).fill(0));
const pb = с.pb.concat(new Array(дД).fill(НАЧАЛЬНОЕ_СМЕЩЕНИЕ));
const итог = { ...w, вектор: ВЕКТОР, действий: ЧИСЛО_ДЕЙСТВИЙ,
  имя: (w.имя || 'веса') + '-рост',
  описание: `${w.описание || ''} · доращено до ${ЧИСЛО_ДЕЙСТВИЙ} действий (новое: ${ДЕЙСТВИЯ.slice(w.действий).join(', ')})`.trim(),
  слои: { ...с, f1w, pw, pb } };
fs.writeFileSync(выход, JSON.stringify(итог));
console.log(`f1w ${с.f1w.length} → ${f1w.length}, pw ${с.pw.length} → ${pw.length}, pb ${с.pb.length} → ${pb.length}`);
console.log('записано:', выход);
