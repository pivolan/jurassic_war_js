// Прогоны по картам (наше): кто где выигрывает и какое место кому лучше.
//
//   node tools/ai_maps.mjs опись                          — что за карты: размер, места, племена
//   node tools/ai_maps.mjs все     [сек] [проц]           — все скирмиш-карты, армии карты, зверский ИИ
//   node tools/ai_maps.mjs зеркало <карты> [сек] [проц]   — по прогону на племя, все места одним племенем
//   node tools/ai_maps.mjs пары    <карты> [сек] [проц]   — только два компа, все пары мест
//   node tools/ai_maps.mjs наборы  <карты> [сек] [проц]   — армии карты против стартовых наборов
//   node tools/ai_maps.mjs места   <карта> [сек] [проц]   — таблица «племя × место»: дуэли против эталона
//   node tools/ai_maps.mjs лучшие  <карты> [сек] [проц]   — каждому племени его лучшее место (файл best.json)
//
// «карты» — список id через запятую (id как в лобби: <100 кампания, 100+ скирмиш, 200+ демо).
// Уровень везде зверский (3), характер ровный: нас интересует карта, а не настройки ИИ.
import { fork } from 'node:child_process';
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const ЭТОТ = url.fileURLToPath(import.meta.url);
const КОРЕНЬ = path.join(path.dirname(ЭТОТ), '..') + '/';
export const ПЛЕМЕНА = ['Tyrano', 'Ka-noo-se', 'Romack', 'Masai', 'Moospell', 'Koomba', 'RaDumBa', 'Koaka'];
const СКИРМИШ = [...Array(20)].map((_, k) => 100 + k);

// ------------------------------------------------------------------ рабочий
async function рабочий() {
  const { движок, прогнать, ТИК_МС, сводка } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  const { G, U, UNITS } = await import('../reimpl/js/mem.js');

  /** Что стоит на карте: размер, места (цвета) и племя каждого места (слот его юнитов). */
  function опись(eng) {
    const m = eng.m;
    const места = {}, размер = { w: m.u32(G.mapW), h: m.u32(G.mapH) };
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
      const o = m.u8(UNITS + i + U.OWNER); if (o > 7) continue;
      const з = места[o] ??= { юнитов: 0, зданий: 0, племя: m.u8(UNITS + i + U.SLOT) };
      if (m.u8(UNITS + i + U.TYPE) >= 0x1a) з.зданий++; else з.юнитов++;
    }
    return { размер, места };
  }

  process.on('message', (з) => {
    if (з === 'стоп') return process.exit(0);
    const eng = движок(); const m = eng.m;
    loadMission(m, eng.files, з.карта, з.места?.[0]?.племя ?? 0, 1);
    if (з.вид === 'опись') { process.send({ ...з, итог: опись(eng) }); return; }
    const точки = стартовыеПозиции(m);
    const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
    let места = з.места;
    // Карты кампании грузятся вариантом под племя: у карты 3 при племени 0 места 0 и 1, при
    // племени 5 — уже 4 и 5. Поэтому для зеркальных прогонов места берём не из общей описи,
    // а из того, что на самом деле оказалось на карте после загрузки.
    if (з.всеМеста || !места) места = цвета.map(ц => ({ цвет: ц, племя: з.племя ?? 0 }));
    места = места.filter(мес => цвета.includes(мес.цвет));
    if (!места.length) { process.send({ ...з, итог: null, ошибка: 'нет таких мест' }); return; }
    if (з.режим === 'набор') расставить(eng, места.map(мес => ({ ...мес, кто: 'компьютер' })), {});
    else {
      // Армии карты остаются как есть; лишние цвета (не в списке мест) просто играют сами за себя.
      for (const ц of цвета) if (!места.some(мес => мес.цвет === ц)) убрать(m, ц);
    }
    for (const мес of места) {
      m.w8(0x32aec + мес.цвет, 0);                                               // встроенный ИИ выключен
      Скрипт.задать(eng, мес.цвет, { уровень: з.уровень ?? 3, характер: мес.характер || 'ровный' });
    }
    const r = прогнать(eng, Math.round(з.сек * 1000 / ТИК_МС));
    const с = сводка(m);
    process.send({ ...з, места, победитель: r.победитель, секунд: Math.round(r.шагов * ТИК_МС / 1000),
                   живые: Object.entries(с).filter(([, з2]) => з2.бойцов + з2.зданий > 0).map(([ц]) => +ц) });
  });

  /** Снести армию цвета — так на карте остаются только нужные места. */
  function убрать(m, ц) {
    const F = globalThis.__F;
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT))
      if (!(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.OWNER) === ц) m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) | 1);
  }
  process.send('готов');
}

// ------------------------------------------------------------------ хозяин
function пул(задачи, процессов, наГотово) {
  return new Promise((всё) => {
    const итоги = []; let выдано = 0, готово = 0;
    for (let k = 0; k < Math.min(процессов, Math.max(1, задачи.length)); k++) {
      const п = fork(ЭТОТ, ['рабочий'], { cwd: path.dirname(ЭТОТ) });
      п.on('message', (м) => {
        if (м !== 'готов') { итоги.push(м); готово++; наГотово?.(готово, задачи.length); }
        if (выдано < задачи.length) п.send(задачи[выдано++]); else { п.send('стоп'); if (готово >= задачи.length) всё(итоги); }
      });
    }
  });
}
const шумок = (готово, всего) => { if (готово % 25 === 0) process.stdout.write(`  ${готово}/${всего}\n`); };
const имена = JSON.parse(fs.readFileSync(КОРЕНЬ + 'reimpl/data/maps.json', 'utf8')).maps;
const имяКарты = (id) => (имена.find(к => к.id === id)?.name) || ('карта ' + id);

async function описьВсех(карты, проц) {
  const итоги = await пул(карты.map(к => ({ вид: 'опись', карта: к, сек: 1 })), проц);
  итоги.sort((a, b) => a.карта - b.карта);
  const из = new Map();
  for (const и of итоги) {
    const мест = Object.keys(и.итог.места).map(Number).sort((a, b) => a - b);
    из.set(и.карта, { ...и.итог, мест });
  }
  return из;
}

