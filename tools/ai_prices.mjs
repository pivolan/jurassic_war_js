// Что почём (наше): сколько стоит юнит и сколько за эти деньги достаётся статов — и во сколько
// обошлось бы то же самое прокачкой. Нужен, чтобы видеть перекосы баланса: если племя с порога
// покупает бойца, до которого другому надо доедать полкарты зверья, это не стратегия, а прайс.
//
//   node tools/ai_prices.mjs [карта]
import { партия } from './ai_duel.mjs';
import { G } from '../reimpl/js/mem.js';

const КАРТА = +(process.argv[2] || 101);
const ПЛЕМЕНА = ['Tyrano', 'Ka-noo-se', 'Romack', 'Masai', 'Moospell', 'Koomba', 'RaDumBa', 'Koaka'];
const ТИПЫ = { 1: 'Commoner', 2: 'Muscle-man', 3: 'Warrior', 4: 'Constructor', 5: 'Elf', 6: 'Wizard',
               7: 'Warlock', 8: 'Ranger', 9: 'Velociraptor', 10: 'Carnotaurus', 11: 'Rhamphorhynchus',
               12: 'Triceratops', 13: 'Dilophosaurus' };
const ВИДЫ = { 1: 'казарма', 5: 'дом эльфов', 6: 'дом магов', 7: 'дом колдунов', 8: 'дом рейнджеров',
               9: 'дом велоцирапторов', 10: 'дом карнотавров', 11: 'дом рамфоринхов', 12: 'дом трицератопсов', 13: 'дом дилофозавров' };

const eng = партия(КАРТА, [{ цвет: 0, племя: 0, кто: 'компьютер' }, { цвет: 1, племя: 1, кто: 'компьютер' }]);
const m = eng.m;
const СТОИМОСТЬ = (вид, k) => m.u8(0x315ac + (вид << 5) + k) * m.u32(0x30eac + ((вид << 5) + k) * 4);
const доступно = (слот, вид, k) => (m.u32(m.u32(0x30e88 + слот * 4) + вид * 4) >>> k) & 1;
const БОНУС = { 5: 0x375a4, 6: 0x375c4, 7: 0x375dc, 8: 0x375f4, 9: 0x37604, 10: 0x37614, 11: 0x37624, 12: 0x37634, 13: 0x37644 };
/** Статы юнита с учётом пакета бонусов портрета: тренировочный дом выдаёт по портрету k
 *  прибавку из таблицы (0x1db5e: HP, MAG, ATK и DEF поровну, SPD). */
const статы = (тип, k = 0) => { const st = m.u32(0x30a9e + тип * 4);
  const с = { hp: m.u8(st + 0x37654), mag: m.u8(st + 0x37656), atk: m.u8(st + 0x37657), def: m.u8(st + 0x37658), spd: m.u8(st + 0x37659) };
  const b = БОНУС[тип]; if (b === undefined || !k) return с;
  const п = b + k * 8;
  return { hp: с.hp + m.u8(п), mag: с.mag + m.u8(п + 1), atk: с.atk + m.u8(п + 2), def: с.def + m.u8(п + 2), spd: с.spd + m.u8(п + 3) };
};
const сумма = (с) => с.hp + с.mag + с.atk + с.def + с.spd;
/** Сколько опыта надо, чтобы догнать эти статы прокачкой от простолюдина (цена +1 = стат²/2 + 10). */
const опытДо = (цель) => { let xp = 0; const от = статы(1);
  for (const [поле, к] of [['hp', цель.hp], ['atk', цель.atk], ['def', цель.def], ['spd', цель.spd]])
    for (let s = от[поле]; s < к; s++) xp += ((s * s) >>> 1) + 10;
  return xp; };
// Опыт за убийство зверя: (сумма статов)² >> 2. Возьмём леопарда — самая обычная дичь.
const леопард = (sum => (sum * sum) >>> 2)(сумма(статы(22)));

const строки = [];
for (let слот = 0; слот < 8; слот++) {
  for (const вид of Object.keys(ВИДЫ).map(Number)) {
    for (let k = 0; k < 4; k++) {
      if (!доступно(слот, вид, k)) continue;
      const тип = вид >= 5 ? вид : k + 1;
      if (!ТИПЫ[тип] || тип === 4) continue;
      const ц = СТОИМОСТЬ(вид, k); if (!ц) continue;
      const с = статы(тип, вид >= 5 ? k : 0), сум = сумма(с);
      строки.push({ племя: ПЛЕМЕНА[слот], юнит: ТИПЫ[тип] + (вид >= 5 && k ? ' +' + k : ''), дом: ВИДЫ[вид], цена: ц, сум,
                    заЕду: +(сум / ц * 100).toFixed(1), опыт: опытДо(с), зверей: Math.round(опытДо(с) / леопард) });
    }
  }
}
строки.sort((a, b) => b.заЕду - a.заЕду);
console.log(`карта ${КАРТА}. «за 100 еды» — сколько очков статов даёт сотня еды; «зверей» — сколько леопардов`);
console.log('надо съесть простолюдину, чтобы дорасти до тех же статов прокачкой.\n');
console.log('племя      юнит              дом                    цена  статов  за 100 еды  зверей');
for (const с of строки)
  console.log(`${с.племя.padEnd(10)} ${с.юнит.padEnd(17)} ${с.дом.padEnd(20)} ${String(с.цена).padStart(6)} ${String(с.сум).padStart(6)} ${String(с.заЕду).padStart(10)} ${String(с.зверей).padStart(7)}`);
console.log(`\nдля справки: леопард даёт ${леопард} опыта, тигр ${(s => (s * s) >>> 2)(сумма(статы(21)))}, T-Rex ${(s => (s * s) >>> 2)(сумма(статы(14)))}.`);
