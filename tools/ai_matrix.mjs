// Перебор конфигураций компьютеров на одной карте (наше). Гоняем партии пачками в отдельных
// процессах и смотрим, при каком раскладе выигрывает нужная сторона.
//
//   node tools/ai_matrix.mjs [карта] [вариант] [цветНаш] [цветВраг] [секунд] [процессов] [форы%]
//
// Фора — сколько процентов стартовых бойцов убрать у врага: так меряется, чего стоит перевес.
//
// Задумано под Twin Hills: это кампанейская карта, у неё восемь вариантов (по одному на племя),
// и в варианте 5 зелёный (цвет 5) стоит против красного (цвет 4) с четырёхкратным перевесом у
// красного — 11 бойцов против 40 и 4000 еды против 100000.
import { fork } from 'node:child_process';
import path from 'node:path'; import url from 'node:url';
const ЭТОТ = url.fileURLToPath(import.meta.url);

const КАРТА = +(process.argv[2] || 2), ВАРИАНТ = +(process.argv[3] || 5);
const НАШ = +(process.argv[4] || 5), ВРАГ = +(process.argv[5] || 4);
const СЕК = +(process.argv[6] || 1800), ПРОЦЕССОВ = +(process.argv[7] || 8);
const УРОВНИ = ['лёгкий', 'обычный', 'сложный', 'зверский'];

async function рабочий() {
  const { движок, прогнать, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  process.on('message', async (з) => {
    if (з === 'стоп') return process.exit(0);
    const eng = движок(); const m = eng.m;
    loadMission(m, eng.files, з.карта, з.вариант, з.сложность);
    const поставить = (цвет, к) => {
      if (к.вид === 'встроенный') return;                            // как карта задала, ничего не трогаем
      m.w8(0x32aec + цвет, 0);
      Скрипт.задать(eng, цвет, { уровень: к.уровень, характер: к.характер });
    };
    // Стороне, которой правит наш скрипт, встроенный ИИ выключаем; чужой оставляем как есть.
    поставить(з.наш.цвет, з.наш); поставить(з.враг.цвет, з.враг);
    // Фора: убираем у врага долю стартовых бойцов. Так меряется не «кто хитрее», а сколько
    // материала стоит перевес: поведением четырёхкратную разницу в армии не отыграть.
    if (з.фора) {
      const { G, U, UNITS } = await import('../reimpl/js/mem.js');
      const { F } = await import('../reimpl/js/fn.js');
      const чужие = [];
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
        if (m.u8(UNITS + i + U.OWNER) !== з.враг.цвет) continue;
        const t = m.u8(UNITS + i + U.TYPE); if (t >= 1 && t <= 13) чужие.push(i);
      }
      const убрать = Math.round(чужие.length * з.фора / 100);
      for (let k = 0; k < убрать; k++) F[0x1aaf7](eng, { esi: чужие[k] });   // из живых — в свободный список
    }
    const r = прогнать(eng, Math.round(з.сек * 1000 / ТИК_МС));
    process.send({ ...з, победитель: r.победитель, секунд: Math.round(r.шагов * ТИК_МС / 1000) });
  });
  process.send('готов');
}

async function главный() {
  const задачи = [];
  const наши = [], враги = [{ вид: 'встроенный', цвет: ВРАГ }];
  for (let у = 0; у < 4; у++) for (const х of ['ровный', 'агрессор', 'экономист', 'черепаха', 'налётчик']) {
    наши.push({ вид: 'скрипт', цвет: НАШ, уровень: у, характер: х });
    враги.push({ вид: 'скрипт', цвет: ВРАГ, уровень: у, характер: х });
  }
  const форы = (process.argv[8] || '0').split(',').map(Number);
  for (const фора of форы) for (const сложность of [0, 1, 2]) for (const наш of наши) for (const враг of враги)
    задачи.push({ карта: КАРТА, вариант: ВАРИАНТ, сложность, сек: СЕК, наш, враг, фора });
  console.log(`карта ${КАРТА}, вариант ${ВАРИАНТ}: наш цвет ${НАШ}, враг ${ВРАГ}; партий ${задачи.length}, процессов ${ПРОЦЕССОВ}, предел ${СЕК} с игры`);

  const итоги = []; let выдано = 0, готово = 0;
  await new Promise((всё) => {
    for (let k = 0; k < ПРОЦЕССОВ; k++) {
      const п = fork(ЭТОТ, ['рабочий'], { cwd: path.dirname(ЭТОТ) });
      п.on('message', (м) => {
        if (м !== 'готов') { итоги.push(м); готово++; if (готово % 50 === 0) process.stdout.write(`  ${готово}/${задачи.length}\n`); }
        if (выдано < задачи.length) п.send(задачи[выдано++]);
        else { п.send('стоп'); if (готово >= задачи.length) всё(); }
      });
    }
  });

  const побед = итоги.filter(и => и.победитель === НАШ);
  console.log(`\nнаших побед: ${побед.length} из ${итоги.length}; побед врага ${итоги.filter(и => и.победитель === ВРАГ).length}; не доиграли ${итоги.filter(и => и.победитель === null).length}`);
  const имя = (к) => к.вид === 'встроенный' ? 'встроенный' : `${УРОВНИ[к.уровень]}/${к.характер}`;
  if (побед.length) {
    console.log('\nгде выиграли (наш ← враг, фора врагу, сложность, время):');
    for (const и of побед.sort((a, b) => a.фора - b.фора || a.секунд - b.секунд).slice(0, 40))
      console.log(`  ${имя(и.наш).padEnd(20)} ← ${имя(и.враг).padEnd(20)} фора -${и.фора}%  сл.${и.сложность}  ${и.секунд} с`);
    const мин = Math.min(...побед.map(и => и.фора));
    console.log(`\nнаименьшая фора, при которой мы выигрываем: у врага убрано ${мин}% стартовых бойцов`);
  }
  // Сводка по уровням: сколько побед у каждой пары «наш уровень ← вражий уровень»
  console.log('\nпобеды по парам уровней (строки — наш, столбцы — враг; «вст» — встроенный):');
  const шапка = ['вст', ...УРОВНИ.map(у => у.slice(0, 4))];
  console.log('            ' + шапка.map(с => с.padStart(6)).join(''));
  for (let у = 0; у < 4; у++) {
    const строка = [null, 0, 1, 2, 3].map(в => {
      const п = итоги.filter(и => и.наш.уровень === у && (в === null ? и.враг.вид === 'встроенный' : и.враг.уровень === в));
      return `${п.filter(и => и.победитель === НАШ).length}/${п.length}`;
    });
    console.log(УРОВНИ[у].padEnd(12) + строка.map(с => с.padStart(6)).join(''));
  }
}

if (process.argv[2] === 'рабочий') рабочий(); else главный();
