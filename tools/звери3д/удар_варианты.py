# ---------------- бронтозавр (Tripo: Root, Head_0..2 шея, передние 0_*, задние 1_*, хвост Tail_*)
T = lambda n: 'tripo::' + n
def шея(вверх):            # + голова вверх
    for n in ('Head_0', 'Head_1', 'Head_2'): крутить(T(n), 'Y', -вверх / 3)
def передняя(сторона, вперёд, сгиб):   # + лапа вперёд; сгиб в локте
    крутить(T(f'0_{сторона}_Limb_0'), 'Y', -вперёд); крутить(T(f'0_{сторона}_Limb_1'), 'Y', сгиб)
def хвост(вбок):
    for n in ('Tail_0', 'Tail_1', 'Tail_2'): крутить(T(n), 'Z', вбок / 3)
ХВОСТ = ['bone_18', 'bone_19', T('Tail_0'), T('Tail_1'), T('Tail_2')]
def дыбы(угол):
    """Подъём передней части: 60% корнем, остальное — изгиб позвонков (спина выгибается, а не поворачивается доской)."""
    крутить(T('Root'), 'Y', -угол * 0.6)
    for n in ('Spine_0', 'Spine_1', 'Spine_2', 'Spine_3'): крутить(T(n), 'Y', -угол * 0.1)
    for s in ('Left', 'Right'): крутить(T(f'1_{s}_Limb_0'), 'Y', угол * 0.6)
    # хвост: основание гасит наклон корня, чтобы хвост не задирался/не втыкался в землю рычагом
    крутить(ХВОСТ[0], 'Y', угол * 0.45)
def хвост_дуга(вверх, вбок=0.0):
    """Изгиб хвоста дугой: к кончику доля растёт (кончик отстаёт сильнее). + вверх."""
    доли = (0.10, 0.15, 0.20, 0.25, 0.30)
    for n, д in zip(ХВОСТ, доли):
        крутить(n, 'Y', вверх * д)          # хвост смотрит на −X: плюс вокруг +Y поднимает его
        if вбок: крутить(n, 'Z', вбок * д)
