    [dict(к=(10, 0), р=((-0.2, -0.5, -0.8), (-0.3, -0.2, -0.9))), dict(к=(-5, 0), р=((-0.3, -0.5, -0.8), (-0.4, -0.2, -0.9))), dict(к=(40, 0), р=((-0.5, -0.4, -0.7), (-0.6, -0.2, -0.7)), с=0.05, г=25)],
