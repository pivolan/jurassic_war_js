# Пять вариантов короткого удара (владелец 05.10: «атака у других юнитов сильно меньше, три кадра — слишком
# длинное действие, дёргано»). Кадры каждого варианта — 3 позы от стойки, силуэт меняется немного.
#   blender -b клип.blend -P удар_варианты.py -- демон|бронто выход.blend
# Варианты пишутся в кадры 500 + 10·в + (1, 2, 3), в = 0..4; урон у движка на третьем кадре.
import bpy, sys, math
from mathutils import Vector, Matrix, Quaternion
арг = sys.argv[sys.argv.index('--') + 1:]
КТО, ВЫХ = арг[0], арг[1]
SC = bpy.context.scene
ARM = [o for o in SC.objects if o.type == 'ARMATURE'][0]
P = ARM.pose.bones
for pb in P: pb.rotation_mode = 'QUATERNION'
порядок = [b.name for b in ARM.data.bones]

if КТО == 'демон':
    x = lambda n: P[n].head.x
    стойка = min(range(SC.frame_start, SC.frame_end + 1), key=lambda f: (SC.frame_set(f), abs(x('left_ankle') - x('right_ankle')))[1])
else:
    стойка = 1
SC.frame_set(стойка)
база = {pb.name: pb.matrix.copy() for pb in P}
корень = 'pelvis' if КТО == 'демон' else 'tripo::Root'
H = max(ARM.dimensions) if КТО == 'бронто' else (P['head'].head - P['left_ankle'].head).length * 1.15

def сброс():
    for n in порядок: P[n].matrix = база[n]; bpy.context.view_layer.update()
def навести(n, ребёнок, куда):
    M = P[n].matrix.copy(); h = M.translation.copy()
    d = (P[ребёнок].head - P[n].head).normalized()
    q = d.rotation_difference(Vector(куда).normalized())
    P[n].matrix = Matrix.Translation(h) @ q.to_matrix().to_4x4() @ Matrix.Translation(-h) @ M
    bpy.context.view_layer.update()
def крутить(n, ось, градусы):
    """Повернуть кость (со всеми детьми) вокруг мировой оси через её голову."""
    M = P[n].matrix.copy(); h = M.translation.copy()
    P[n].matrix = Matrix.Translation(h) @ Matrix.Rotation(math.radians(градусы), 4, ось) @ Matrix.Translation(-h) @ M
    bpy.context.view_layer.update()
def сдвиг(вперёд=0.0, вверх=0.0):
    M = P[корень].matrix.copy(); P[корень].matrix = Matrix.Translation(Vector((вперёд * H, 0, вверх * H))) @ M
    bpy.context.view_layer.update()
def ключ(f):
    for n in порядок:
        P[n].keyframe_insert('rotation_quaternion', frame=f)
        if not ARM.data.bones[n].parent: P[n].keyframe_insert('location', frame=f)

# ---------------- демон (оси: вперёд +X, влево +Y, вверх +Z)
def руки(пл, лк, сторона='обе'):
    for s, зн in (('right', 1), ('left', -1)):
        if сторона != 'обе' and сторона != s: continue
        навести(f'{s}_shoulder', f'{s}_elbow', (пл[0], пл[1] * зн, пл[2]))
        навести(f'{s}_elbow', f'{s}_wrist', (лк[0], лк[1] * зн, лк[2]))
def корпус(наклон=0, поворот=0):
    for n in ('spine2', 'spine3'):
        крутить(n, 'Y', наклон / 2); крутить(n, 'Z', поворот / 2)
