            # хвост с запаздыванием: на подъёме провисает, на пике тянется вниз, на ударе хлёстко вверх
            # ПРОТИВОВЕС (владелец: «хвост — как противовес»): перед вверх → хвост вниз, к земле; удар вперёд →
