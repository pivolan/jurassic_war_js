ВАРИАНТЫ = ДЕМОН if КТО == 'демон' else БРОНТО
import os, json
if os.environ.get('VARIANTS'): ВАРИАНТЫ = json.load(open(os.environ['VARIANTS']))   # свой набор (список из трёх поз)
for в, позы in enumerate(ВАРИАНТЫ):
    for k, п in enumerate(позы):
        сброс()
        if КТО == 'демон':
            if п.get('с'): сдвиг(п['с'], -0.01)
            наклон, поворот = п['к']; корпус(наклон, поворот)
            if п.get('г'): крутить('neck', 'Y', п['г'])
            пл, лк = п['р']; руки(пл, лк, п.get('с_', ('обе',))[0])
        else:
            if п.get('д'): дыбы(п['д'])
            if п.get('с'): сдвиг(п['с'])
            if п.get('ш'): шея(п['ш'])
            if п.get('вверх'): сдвиг(0, п['вверх'])
            if п.get('п'): передняя(*п['п'])
            if п.get('п2'):
                for s in ('Left', 'Right'): передняя(s, *п['п2'])
