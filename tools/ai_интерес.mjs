// Насколько партия ИНТЕРЕСНАЯ, а не выигранная (наше).
//
//   node tools/ai_интерес.mjs [--слева=скрипт] [--справа=скрипт] [--карт=20] [--племён=8]
//                             [--секунд=1200] [--потоков=…] [--подробно]
//     мозги: скрипт | стратег | родной | комдив:<файл весов>
//
// Зачем. Все прежние мерки спрашивали «кто победил», и обучение честно выучивало то, что в
// коротких сценах побеждает: собрать армию побыстрее и снести всё разом. Владелец хочет другого:
// «сделать комп интересным, а не выигрышным» — и сам говорит, что непонятно, на какие оценки
// тренировать. Этот стенд и есть попытка такую оценку выписать числом.
//
// Что считаем интересным. Партию, где:
//   • ПЕРЕВЕС ХОДИЛ ИЗ РУК В РУКИ — лидер менялся, а не был ясен с первой минуты;
//   • стороны ДОЛГО ДЕРЖАЛИСЬ близко друг к другу, а не разошлись в разнос;
//   • был ОТЫГРЫШ — кто-то просел и вернулся (отстроился, пережил волну);
//   • при этом ЧТО-ТО ПРОИСХОДИЛО: юниты гибли и строились, а не два компьютера стояли по углам.
// Каждая часть считается по срезам партии раз в ЗАМЕР секунд и сводится в одно число 0..1.
//
// Никакой «правильной» формулы тут быть не может — это вкус. Поэтому все веса вынесены в ВЕСА и
// печатаются вместе с итогом: если окажется, что число не совпадает с ощущением от просмотра,
// крутить надо их, а не подгонять партии.
import path from 'node:path'; import url from 'node:url'; import fs from 'node:fs';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';
const ЭТОТ = url.fileURLToPath(import.meta.url);
const КОРЕНЬ = path.join(path.dirname(ЭТОТ), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));

export const ЗАМЕР = 15;                 // секунд игры между срезами
export const ВЕСА = { смены: 0.30, равновесие: 0.25, отыгрыш: 0.25, событийность: 0.20 };
const ПОРОГ_РАВНО = 0.15;                // |перевес| меньше этого — «идут вровень»
const ПОРОГ_СМЕНЫ = 0.10;                // гистерезис: лидер сменился, только если ушёл за этот предел
const ПРОСАДКА = 0.25;                   // на столько надо просесть, чтобы возвращение считалось отыгрышем

/** Перевес стороны A в долях: армия, дома и казна, сведённые к −1…+1. */
export function перевес(a, b) {
  const сила = (a.сила - b.сила) / 4000, дома = (a.домов - b.домов) / 8, еда = (a.еда - b.еда) / 6000;
  return Math.max(-1, Math.min(1, сила + дома * 0.5 + еда * 0.3));
}

/** Свести ряд срезов в оценку интересности. */
export function интерес(ряд) {
  if (ряд.length < 3) return { итог: 0, смены: 0, равновесие: 0, отыгрыш: 0, событийность: 0 };
  const п = ряд.map(с => с.перевес);
  // 1. Смены лидера с гистерезисом: считаем только уверенные переходы через ноль.
  let смен = 0, лидер = 0;
  for (const v of п) {
    const л = v > ПОРОГ_СМЕНЫ ? 1 : v < -ПОРОГ_СМЕНЫ ? -1 : лидер;
    if (лидер && л && л !== лидер) смен++;
    лидер = л;
  }
  // 2. Доля времени, когда шли вровень.
  const равно = п.filter(v => Math.abs(v) < ПОРОГ_РАВНО).length / п.length;
  // 3. Отыгрыш: самый большой подъём после самой глубокой ямы, по каждой стороне.
  const подъём = (знак) => {
    let дно = 0, лучший = 0;
    for (const v of п) { const x = v * знак; if (x < дно) дно = x;
      if (дно <= -ПРОСАДКА) лучший = Math.max(лучший, x - дно); }
    return Math.min(1, лучший);
  };
  const отыгрыш = Math.max(подъём(1), подъём(-1));
  // 4. Событийность: сколько всего рождалось и гибло за партию, на минуту игры.
  const минут = (ряд.length * ЗАМЕР) / 60;
  const шевеление = ряд.reduce((s, с) => s + с.дельта, 0) / Math.max(1, минут);
  const событийность = Math.min(1, шевеление / 6);          // шесть изменений состава в минуту — уже живо
  const смены = Math.min(1, смен / 4);                      // четыре смены лидера — потолок
  const итог = смены * ВЕСА.смены + равно * ВЕСА.равновесие + отыгрыш * ВЕСА.отыгрыш + событийность * ВЕСА.событийность;
  return { итог, смены: смен, равновесие: равно, отыгрыш, событийность: шевеление };
}

// Ветку воркера включаем ТОЛЬКО когда воркер запущен этим же стендом. Иначе, если модуль просто
// импортировать внутрь чужого воркера (эволюция берёт отсюда формулы), он перехватит его
// сообщения и стенд-хозяин перестанет получать ответы.
if (!isMainThread && workerData?.стенд === 'интерес') {
  const { движок, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции, включитьИИ } = await import('../reimpl/js/port/skirmish.js');
  const { параПодальше } = await import('./ai_места.mjs');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  const Комдив = await import('../reimpl/js/ai/комдив.js');
  const { G, U, UNITS } = await import('../reimpl/js/mem.js');
  const ХАРАКТЕР = ['охотник', 'агрессор', 'агрессор', 'ровный', 'ровный', 'охотник', 'агрессор', 'охотник'];
  const срез = (m, ц) => { let бойцов = 0, домов = 0, сила = 0;
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
      if (m.u8(UNITS + i + U.FLAGS5B) & 1 || m.u8(UNITS + i + U.OWNER) !== ц) continue;
      const t = m.u8(UNITS + i + U.TYPE);
      if (t >= 0x1a) домов++;
      else if (t >= 1 && t <= 13) { бойцов++; сила += m.u8(UNITS + i + U.ATK) + m.u8(UNITS + i + U.DEF) + m.u8(UNITS + i + U.HPMAX); }
    }
    return { бойцов, домов, сила, еда: m.u32(G.food + ц * 4) }; };
  /** Поставить мозги стороне. */
  const мозги = (eng, цвет, вид, племя) => {
    const m = eng.m;
    if (вид === 'родной') { включитьИИ(m, цвет); return; }
    m.w8(0x32aec + цвет, 0);
    const общ = { уровень: 3, характер: ХАРАКТЕР[племя & 7] || 'ровный' };
    if (вид === 'стратег') return void Скрипт.задать(eng, цвет, { ...общ, стратегПравило: true });
    if (вид.startsWith('комдив:')) {
      const веса = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, вид.slice(7)), 'utf8'));
      return void Скрипт.задать(eng, цвет, { ...общ, комдив: Комдив.изЗаписи(веса) });
    }
    Скрипт.задать(eng, цвет, общ);
  };
  parentPort.on('message', (задачи) => {
    const из = [];
    for (const t of задачи) {
      try {
        const eng = движок(); const m = eng.m;
        loadMission(m, eng.files, t.карта, t.племя, 1);
        const цвета = параПодальше(стартовыеПозиции(m));
        const A = цвета[0], B = цвета[1];
        if (A === undefined || B === undefined) { из.push({ ...t, нет: 1 }); continue; }
        расставить(eng, [{ цвет: A, племя: t.племя, кто: 'компьютер' }, { цвет: B, племя: t.племя, кто: 'компьютер' }], {});
        мозги(eng, A, t.слева, t.племя); мозги(eng, B, t.справа, t.племя);
        const шагов = Math.round(t.секунд * 1000 / ТИК_МС), вЗамере = Math.round(ЗАМЕР * 1000 / ТИК_МС);
        const ряд = []; let прошлый = null;
        for (let k = 0; k < шагов; k++) {
          eng.timer++; eng.tick();
          if (k % вЗамере) continue;
          const a = срез(m, A), b = срез(m, B);
          const состав = a.бойцов + b.бойцов + a.домов + b.домов;
          ряд.push({ перевес: перевес(a, b), дельта: прошлый === null ? 0 : Math.abs(состав - прошлый) });
          прошлый = состав;
          if (!a.бойцов && !a.домов) break; if (!b.бойцов && !b.домов) break;
        }
        из.push({ ...t, ряд });
      } catch (e) { из.push({ ...t, ошибка: String(e.message).slice(0, 120) }); }
    }
    parentPort.postMessage(из);
  });
  parentPort.postMessage('готов');
} else if (isMainThread) {
  const СЛЕВА = арг.слева || 'скрипт', СПРАВА = арг.справа || 'скрипт';
  const КАРТ = +(арг.карт || 20), ПЛЕМЁН = +(арг.племён || 8), СЕКУНД = +(арг.секунд || 1200);
  const ПОТОКОВ = Ядра.потоков(арг.потоков, 16);
  const задачи = [];
  for (let к = 0; к < КАРТ; к++) for (let п = 0; п < ПЛЕМЁН; п++)
    задачи.push({ карта: 100 + к, племя: п, слева: СЛЕВА, справа: СПРАВА, секунд: СЕКУНД });
  console.log(`интерес: ${СЛЕВА} против ${СПРАВА}, карт ${КАРТ} × племён ${ПЛЕМЁН} = ${задачи.length} партий по ${СЕКУНД} с, срез раз в ${ЗАМЕР} с`);
  const t0 = Date.now();
  const итоги = [];
  await Promise.all(Array.from({ length: ПОТОКОВ }, (_, k) => new Promise((ок, нет) => {
    const w = new Worker(ЭТОТ, { workerData: { k, стенд: 'интерес' } });
    const мои = задачи.filter((_, i) => i % ПОТОКОВ === k);
    let готов = false;
    w.on('message', (м) => { if (!готов) { готов = true; w.postMessage(мои); return; } итоги.push(...м); w.terminate(); ок(); });
    w.on('error', нет);
  })));
  const хорошие = итоги.filter(и => и.ряд && и.ряд.length >= 3);
  const оценки = хорошие.map(и => ({ ...и, о: интерес(и.ряд) }));
  оценки.sort((a, b) => b.о.итог - a.о.итог);
  const ср = (f) => оценки.reduce((s, о) => s + f(о), 0) / Math.max(1, оценки.length);
  console.log(`\nпартий зачтено ${оценки.length} из ${итоги.length}, ${((Date.now() - t0) / 60000).toFixed(1)} мин\n`);
  // Разброс МЕЖДУ партиями. Он важнее среднего: если от партии к партии интерес пляшет сильнее,
  // чем отличаются мозги, то отбирать по нему бессмысленно — будем отбирать везение, а не сеть.
  const среднее = ср(о => о.о.итог);
  const разброс = Math.sqrt(ср(о => (о.о.итог - среднее) ** 2));
  console.log('ИНТЕРЕС (0..1):', среднее.toFixed(3), `± ${разброс.toFixed(3)} (разброс между партиями)`);
  console.log(`  смен лидера за партию: ${ср(о => о.о.смены).toFixed(2)}`);
  console.log(`  доля времени вровень:  ${(ср(о => о.о.равновесие) * 100).toFixed(0)} %`);
  console.log(`  отыгрыш после просадки: ${ср(о => о.о.отыгрыш).toFixed(2)}`);
  console.log(`  событийность, смен состава в минуту: ${ср(о => о.о.событийность).toFixed(1)}`);
  console.log(`  веса: ${Object.entries(ВЕСА).map(([к, в]) => `${к} ${в}`).join(', ')}`);
  if (арг.подробно) {
    console.log('\nсамые интересные партии:');
    for (const о of оценки.slice(0, 8)) console.log(`  карта ${о.карта} племя ${о.племя}: ${о.о.итог.toFixed(3)} (смен ${о.о.смены}, вровень ${(о.о.равновесие * 100) | 0} %, отыгрыш ${о.о.отыгрыш.toFixed(2)})`);
    console.log('самые скучные:');
    for (const о of оценки.slice(-5)) console.log(`  карта ${о.карта} племя ${о.племя}: ${о.о.итог.toFixed(3)} (смен ${о.о.смены}, вровень ${(о.о.равновесие * 100) | 0} %, отыгрыш ${о.о.отыгрыш.toFixed(2)})`);
  }
  const пусто = итоги.filter(и => и.ошибка); if (пусто.length) console.log(`\nошибок: ${пусто.length}, первая: ${пусто[0].ошибка}`);
  // --база=файл: записать интерес по каждой паре (карта, племя) как ОПОРУ. Дальше отбор считает не
  // сырой интерес, а прибавку к этой опоре: карта и племя сокращаются, остаётся вклад мозгов.
  // Партия у нас воспроизводима (один и тот же посев на одной и той же расстановке), поэтому опора
  // точная, а не усреднённая.
  if (арг.база) {
    const таб = {};
    for (const о of оценки) таб[`${о.карта}|${о.племя}`] = +о.о.итог.toFixed(4);
    const файл = path.isAbsolute(арг.база) ? арг.база : path.join(КОРЕНЬ, арг.база);
    fs.mkdirSync(path.dirname(файл), { recursive: true });
    fs.writeFileSync(файл, JSON.stringify(таб), 'utf8');
    console.log(`\nопора записана: ${path.relative(КОРЕНЬ, файл)}, ${Object.keys(таб).length} пар (карта, племя)`);
  }
  process.exit(0);
}
