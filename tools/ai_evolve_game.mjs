/** Разложить набор (гены/ручки/приёмы) в плоский вектор, как его видит эволюция. */
export function вВектор(н) {
  const v = КЛЮЧИ.map(k => (н.гены?.[k] ?? н.ручки?.[k] ?? ПОУМОЛЧАНИЮ[k]));
  const п0 = н.приёмы || ПРИЁМЫ_ЗВЕРСКОГО;
  return v.concat(ПРИЁМЫ.map(п => п0.includes(п) ? 1 : 0));
}
/** И обратно: вектор → то, что понимает Скрипт.задать. */
export function изВектора(v) {
  const гены = {}, ручки = {};
  КЛЮЧИ.forEach((k, i) => {
    const с = СПЕК[k]; let x = Math.max(с.от, Math.min(с.до, v[i]));
    if (с.цел) x = Math.round(x);
    (с.ручка ? ручки : гены)[k] = x;
  });
  const приёмы = ПРИЁМЫ.filter((_, i) => v[КЛЮЧИ.length + i] >= 0.5);
  return { гены, ручки, приёмы };
}

