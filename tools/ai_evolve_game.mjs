// Эволюция штаба на полных партиях (наше).
//
//   node tools/ai_evolve_game.mjs [--минут=60] [--потоков=18] [--популяция=24] [--имя=штаб]
//                                 [--карты=100,101,…] [--племена=0,4] [--секунд=600]
//                                 [--соперник=out/ai/штаб-….json] [--от=out/ai/штаб-….json]
//
// Зачем это, если есть PPO. У бойца награда густая: за каждый шаг видно, попал он или получил,
// подошёл к цели или отошёл — там градиент есть, и PPO работает. У штаба награда одна на всю
// партию: выиграл или нет. Между решением «строить оружейную» и победой лежат десять минут игры
// и тысяча чужих решений; сигнала, за какое из них хвалить, нет. Такое ищут эволюцией: она не
// требует градиента, терпит шум и делится по ядрам без остатка. Партия у нас считается за
// полсекунды-две, значит поколение из двух с половиной сотен партий — это полминуты на 18 потоках.
//
// Что ищем — три вида генов:
//   1. числа из `ГЕНЫ` (js/port/ai_script.js): радиусы, сроки, пороги — то, что я ставил на глаз;
//   2. «ручки» состояния: частота размышлений штаба и отрядов, порог атаки, сколько рабочих,
//      сколько охраны, осторожность, решимость, сколько разведчиков, радиус охоты;
//   3. приёмы — двоичные: включён приём или нет (13 штук).
//
// Как считается приспособленность. Кандидат играет партию против соперника (по умолчанию —
// нынешний зверский уровень) на наборе задач: карта × племя × кто где стоит. Племена в задаче
// одинаковые у обеих сторон — иначе мерилось бы не умение штаба, а перекос племён; места
// меняются местами, чтобы не выиграть за счёт удобного угла карты. Очко за партию:
//   победа        0.75 + 0.25·(сколько времени осталось)   — быстрая победа лучше долгой;
//   поражение     0.25·(сколько продержался)               — умереть позже лучше, чем сразу;
//   ничья         0.5 + 0.25·перевес по армии и домам      — ничьи у нас частые, и без этого
//                                                            почти все кандидаты неразличимы.
// Набор задач фиксирован на весь прогон (одни и те же карты и места), поэтому сравнение честное;
// проверочный набор (`--проверка`) в отбор не входит и печатается отдельно — по нему видно,
// не подогнался ли чемпион под свои карты.
//
// Стратегия отбора — та же (μ, λ) с зеркальными возмущениями, что и в tools/ai_evolve.mjs:
// пара детей θ ± σ·ε, две лучшие особи переносятся без изменений, σ растёт при удаче и падает
