// Проверка разведчика (наше): помогает ли отдельный боец-разведчик найти врага раньше и остаться
// живым. Слева сторона с приёмом «разведка», справа — без него, всё остальное одинаковое.
//
//   node tools/ai_scout.mjs [карта] [секунд] [уровень]
import { партия, прогнать, ТИК_МС } from './ai_duel.mjs';
import { G, U, UNITS } from '../reimpl/js/mem.js';
import { стартовыеПозиции } from '../reimpl/js/port/skirmish.js';
import * as Скрипт from '../reimpl/js/port/ai_script.js';

const КАРТА = +(process.argv[2] || 100), СЕК = +(process.argv[3] || 600), УР = +(process.argv[4] || 2);
const пробный = партия(КАРТА, [{ цвет: 0, племя: 0 }, { цвет: 3, племя: 0 }]);
const цвета = Object.keys(стартовыеПозиции(пробный.m)).map(Number).sort((a, b) => a - b);
const места = [{ цвет: цвета[0], племя: 0, кто: 'компьютер', ии: 'скрипт', уровень: УР },
               { цвет: цвета[1], племя: 0, кто: 'компьютер', ии: 'скрипт', уровень: УР }];
const eng = партия(КАРТА, места);
// Правому разведку запрещаем — сравниваем с ним.
Скрипт.состояние(eng, места[1].цвет).приёмы.delete('разведка');
const нашли = {}, потери = {};
прогнать(eng, Math.round(СЕК * 1000 / ТИК_МС), { наШаге: (e, k) => {
  for (const м of места) {
    const с = Скрипт.состояние(e, м.цвет); if (!с) continue;
    if (с.вражБаза && !(м.цвет in нашли)) нашли[м.цвет] = Math.round(k * ТИК_МС / 1000);
    const р = с.отряды.разведка[0];
    if (р && (e.m.u8(UNITS + р + U.FLAGS5B) & 1)) потери[м.цвет] = (потери[м.цвет] || 0) + 1;
  }
  if (k % Math.round(120000 / ТИК_МС)) return;
  const стр = места.map((м, j) => {
    const с = Скрипт.состояние(e, м.цвет);
    return `${j === 0 ? 'с разведкой' : 'без разведки'}: клеток осмотрено ${с.разведано.size}, база врага ${с.вражБаза ? 'найдена' : 'нет'}, разведчик ${с.отряды.разведка.length ? '#' + с.отряды.разведка[0] : '—'}`;
  }).join(' | ');
  console.log(`${String(Math.round(k * ТИК_МС / 1000)).padStart(4)} с  ${стр}`);
} });
for (const [j, м] of места.entries()) {
  const с = Скрипт.состояние(eng, м.цвет);
  console.log(`${j === 0 ? 'с разведкой ' : 'без разведки'}: осмотрено ${с.разведано.size} клеток, базу врага нашли ${нашли[м.цвет] ?? '—'} с, разведчиков потеряно ${потери[м.цвет] || 0}`);
}
