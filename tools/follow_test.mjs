// Проверка приказа «следовать за юнитом» (наше): ведомый идёт за ведущим, а когда тот встал и
// ведомый дошёл — указка снимается через три секунды.
//   node tools/follow_test.mjs
import { движок } from './ai_duel.mjs';
import { loadMission } from '../reimpl/js/loader.js';
import { расставить } from '../reimpl/js/port/skirmish.js';
import { G, U, UNITS } from '../reimpl/js/mem.js';
const Следом = await import('../reimpl/js/port/follow.js');
const { приказ, КОД, установить } = await import('../reimpl/js/port/inject.js');
globalThis.__следДебаг = process.argv.includes('--дебаг');
const eng = движок(); const m = eng.m; установить();
loadMission(m, eng.files, 100, 0, 1);
расставить(eng, [{ цвет: 0, племя: 0, кто: 'компьютер' }], {});
m.w8(0x32aec, 0);
const свои = [];
for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
  if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
  const t = m.u8(UNITS + i + U.TYPE);
  if (t >= 1 && t <= 13 && m.u8(UNITS + i + U.OWNER) === 0) свои.push(i);
}
const [ведущий, ведомый] = свои;
const тик = (n) => { for (let k = 0; k < n; k++) { eng.timer++; eng.tick(); } };
const кл = (i) => `${m.u16(UNITS + i + U.X) >> 5},${m.u16(UNITS + i + U.Y) >> 5}`;
console.log(`ведущий ${ведущий} в ${кл(ведущий)}, ведомый ${ведомый} в ${кл(ведомый)}`);
// В браузере приказ идёт через 0x14895 (его перехватывает сетевая обвязка); здесь обвязки нет,
// поэтому кладём наш код прямо в очередь inject — это тот же путь, что и в одиночной игре.
приказ(eng, ведомый, Следом.СЛЕДОВАТЬ, ведущий, 0, 0); тик(4);
console.log('указка есть:', Следом.ведомые(eng).has(ведомый));
// уводим ведущего далеко
const цx = (m.u16(UNITS + ведущий + U.X) >> 5) + 14, цy = m.u16(UNITS + ведущий + U.Y) >> 5;
приказ(eng, ведущий, КОД.ИДТИ, 0, цx << 5, цy << 5);
for (let k = 0; k < 6; k++) { тик(100); const с = Следом.ведомые(eng).get(ведомый); console.log(`  +${(k + 1) * 100}: ведущий ${кл(ведущий)} ведомый ${кл(ведомый)} сост${m.u8(UNITS+ведомый+U.STATE)} прик${m.u8(UNITS+ведомый+U.ORDER)} dst ${m.u16(UNITS+ведомый+U.DSTX)>>5},${m.u16(UNITS+ведомый+U.DSTY)>>5} указка ${с ? 'есть, дал '+с.далX+','+с.далY : 'снята'}`); }
// ведущий стоит — через три секунды указка должна сняться
тик(200);
console.log(`после остановки: ведущий ${кл(ведущий)} ведомый ${кл(ведомый)} указка ${Следом.ведомые(eng).has(ведомый) ? 'ЕСТЬ (плохо)' : 'снята (верно)'}`);

// Приказ игрока должен снять указку: сон, «идти», что угодно.
приказ(eng, ведомый, Следом.СЛЕДОВАТЬ, ведущий, 0, 0); тик(4);
console.log('снова назначили:', Следом.ведомые(eng).has(ведомый));
приказ(eng, ведомый, 0x3a, 0, 0, 0); тик(8);            // 0x3a — наш приказ «спать»
console.log('после приказа игрока «спать»:', Следом.ведомые(eng).has(ведомый) ? 'указка ЕСТЬ (плохо)' : 'указка снята (верно)');
приказ(eng, ведомый, Следом.СЛЕДОВАТЬ, ведущий, 0, 0); тик(4);
const цx2 = (m.u16(UNITS + ведомый + U.X) >> 5) + 3;
приказ(eng, ведомый, КОД.ИДТИ, 0, цx2 << 5, m.u16(UNITS + ведомый + U.Y)); тик(8);
console.log('после приказа игрока «идти»:', Следом.ведомые(eng).has(ведомый) ? 'указка ЕСТЬ (плохо)' : 'указка снята (верно)');
