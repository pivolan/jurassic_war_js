const ШТРАФ_ЗА_СМЕРТЬ = +(среда.JW_CUT_DEATH || 3);
// СКОЛЬКО МОЖНО ПОТЕРЯТЬ. Владелец: «надо, чтобы хоть пару убийств он успел сделать; давай чуть
// поправим потери, пусть там чуть-чуть потеряет, одного бойца можно». Раньше попытка обрывалась на
// ПЕРВОЙ смерти, и это само по себе резало добычу: погиб один на десятой секунде — и всё, сколько
// бы зверей ни оставалось. Теперь допускается один убитый: попытка идёт дальше втроём, и заработок
// сохраняется (смерть всё равно стоит своих очков). Второй убитый — провал, попытка обрывается и
// заработок обнуляется целиком.
