//
// Что за сцена. Владелец выбрал её сам, глядя на десяток нарезок карты (tools/ai_сцена_снимок.mjs):
// квадрат 32×32 клетки, от (1,12) до (32,43) — стартовый пятачок Тирано, увеличенный примерно
// в полтора раза от игрового кадра. Вода и правое озеро в него не попадают, зато попадают все
// соседи: четыре тигра, пять леопардов и три пса. Всё, что вне квадрата, с карты убирается.
//
// Задача (дословно): «за 25 секунд должно быть уничтожено максимум зверей и не должно быть
// смертей». Поэтому:
//   • эпизод длится 25 игровых секунд и обрывается СРАЗУ, как только погиб хоть кто-то из наших;
//   • в зачёт идёт число убитых зверей, а смерть — тяжёлый штраф;
//   • своё здоровье не штрафуется вовсе: «жизни можно тратить как угодно, главное не умереть».
//
// Тигров (т21) из сцены НЕ вырезаю: они стоят рядом со стартом, и «ноль смертей» здесь означает
// в том числе «не лезть к тем, кого не взять». Это часть задачи, а не помеха ей.
