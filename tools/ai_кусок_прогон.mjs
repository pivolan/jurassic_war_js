const ПЛАТА_ЗА_ВРЕМЯ = +(среда.JW_CUT_TIME || 1.5);
// Норма владельца: «первый зверь должен быть убит за 8 секунд максимум». Отдельной наградой,
// потому что через одно только дисконтирование она выражается слишком слабо: сеть охотно
// соглашается убить того же зверя на двадцатой секунде.
const НОРМА_ПЕРВОГО = +(среда.JW_CUT_FIRST || 8);
// И вторая ступень, тоже дословно: «после того как натренишь на убийство первого зверя, дальше
// лимит на второго зверя 20 секунд» — суммарно за раунд, а не сверх первых восьми. В 25-секундную
// сцену эта норма влезает целиком, так что обе премии живут здесь же.
const НОРМА_ВТОРОГО = +(среда.JW_CUT_SECOND || 20);
// Премия убывающая, а не «да/нет». Замер физики (tools/замер_убийства.mjs): наш урон по зверю —
// ровно 1 очко за удар, темп удара 0.83 с, у ближайшего зверя 37 здоровья; четверо в контакте
