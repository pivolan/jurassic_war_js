const КУСОК = (среда.JW_CUT_RECT ? среда.JW_CUT_RECT.split(',').map(Number) : [1, 12, 32, 43]);
const СЕКУНД = +(среда.JW_CUT_SEC || 30);   // окно попытки
// Цена зверя выше цены осторожности — см. пояснение в tools/ai_отряд_прогон.mjs.
