// СКОЛЬКО И КАК БЫСТРО. Премии за нормы убраны по указанию владельца: ступенька «успел к восьмой
// секунде» — это подпорка, а нужно, чтобы сеть сама рвалась убить как можно больше и как можно
// раньше. Поэтому две вещи вместо премий:
//
//  1) СРОЧНОСТЬ считается в секундах, а не в долях попытки: зверь, убитый в начале, стоит вдвое
//     дороже, дальше цена падает и упирается в половину. Так «быстрее» выгодно независимо от того,
//     какой длины попытка.
//  2) ЦЕПОЧКА: каждый следующий зверь дороже предыдущего на ПРИБАВКУ. Это не выдумка, а то, как
//     устроена сама игра: за убийство даётся опыт, характеристики растут, и владелец говорит об
//     этом прямо — «после третьего зверя, особенно если кто-то один наносит последний удар,
//     убийства будут простыми». Растущая цена толкает сеть держать разгон, а не останавливаться
//     после первого. Кайт при этом не награждается отдельно: он и так единственный способ убивать
//     быстро и не терять людей, а смерть обнуляет весь заработок за бой.
