// остальные разбегаются во все стороны». Правило-то у нас есть и оно верное — «отводишь на
// полшага ТОГО, КОГО БЬЮТ, остальными продолжаешь бить», — но живёт оно в скриптовом слое, а
// действие выбирает сеть, и она уводит тех, кого никто не трогает. Поэтому: кого бьют — отходи
// сколько нужно, это смена туши и она бесплатна; кого не бьют — за каждую клетку, на которую он
// отошёл от ближайшего зверя, снимаем. Симметрично плате за сближение и того же размера.
