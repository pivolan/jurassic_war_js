// теряется ПОДХОД. Платим за каждую клетку, на которую боец сократил расстояние до ближайшего
// живого зверя. Только за сокращение: отход на полшага — это смена туши, за неё штрафовать нельзя.
// Потолок за бой, чтобы не выгодно было топтаться туда-сюда.
