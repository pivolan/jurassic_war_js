// ЛАСТХИТ НА ИСКУССТВЕННЫХ СЦЕНАХ. Владелец: «реализовать точную логику прокачки конкретных юнитов
// прямо во время драки и отладить на искусственных сценах с небольшим количеством клеток».
//
//   node tools/ластхит_сцены.mjs            — вся таблица: сцены × звери × состав × кто назначен
//   node tools/ластхит_сцены.mjs подробно   — плюс ход каждого боя
//
// Сцена: на открытом месте карты Тирано/2 вырезаем арену 11×11 (края — стена), снимаем всех
// лишних; зверь стоит в середине и не уходит с выпаса (выпас — одна клетка), наши — в 3 клетках.
// Виды арены:  открытая — подойти со всех сторон;
//              угол      — зверь в тупике у стены, подойти можно с 2–3 сторон;
//              деревья   — вокруг разбросаны деревья, их приходится обходить.
// Каждый бой — дважды: без назначения (кто добьёт, тот добьёт) и с назначенным ластхитом. Меряем
// шаг смерти зверя и кто получил опыт. Разница по времени — цена ластхита.
// Наши по умолчанию «живучие» (250 жизней): меряем механику удара, а не то, кто умрёт первым.
const { бой, СОСТАВЫ, ИМЯ } = await import('./ластхит_бой.mjs');
const ПОДРОБНО = process.argv.includes('подробно');
if (process.env.ЛХ_ОДИН) { const [вид, тип, имя, назн] = process.env.ЛХ_ОДИН.split('|'); console.log(JSON.stringify(бой(вид, +тип, СОСТАВЫ[имя], +назн))); process.exit(0); }
const строки = [];
for (const вид of ['открытая', 'угол', 'деревья']) for (const тип of [23, 22, 21, 19, 15]) for (const [имя, состав] of Object.entries(СОСТАВЫ)) {
  const без = бой(вид, тип, состав, -1);
  const слабейший = состав.reduce((b, с, k) => (с.atk < состав[b].atk ? k : b), состав.length - 1);
  const с = бой(вид, тип, состав, слабейший);
  строки.push({ вид, зверь: ИМЯ[тип], состав: имя, мест: без.мест, без: без.шаг, кто_без: без.кто, назначен: слабейший, с: с.шаг, кто_с: с.кто, разница: с.шаг - без.шаг, стопов: с.стопов, отказ: с.отказ });
}
console.log('вид       зверь        состав                мест  без: шаг кто | назначен → шаг кто  разница  стопов');
for (const r of строки) console.log(`${r.вид.padEnd(9)} ${r.зверь.padEnd(12)} ${r.состав.padEnd(21)} ${String(r.мест).padStart(3)}  ${String(r.без).padStart(8)} ${String(r.кто_без).padStart(3)} | ${String(r.назначен).padStart(8)} → ${String(r.с).padStart(4)} ${String(r.кто_с).padStart(3)}  ${String(r.разница).padStart(7)} ${String(r.стопов).padStart(6)}${r.кто_с !== r.назначен ? '  ✗ не он' + (r.отказ ? ' (отказ по допуску)' : '') : ''}`);
const удач = строки.filter(r => r.кто_с === r.назначен).length;
console.log(`\nназначенный добил: ${удач}/${строки.length}; разница по времени: медиана ${строки.map(r => r.разница).sort((a, b) => a - b)[строки.length >> 1]} шагов, максимум ${Math.max(...строки.map(r => r.разница))}`);
