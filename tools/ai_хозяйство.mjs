// Что даёт починка хозяйства скриптового компьютера (наше).
//
//   node tools/ai_хозяйство.mjs [--карты=100,…] [--племена=0,…] [--секунд=900] [--потоков=18]
//
// Две правки меряются вместе, потому что лечат одну болезнь — нулевой доход:
//   • носильщик из бойцов, когда простолюдины кончились (мясо в игре носит кто угодно);
//   • накопление на постройку: строитель стоит как дом, и казна до его цены не доходила никогда.
// Лоб в лоб: одно племя, одна карта, оба места, починенное хозяйство против прежнего.
import path from 'node:path'; import url from 'node:url';
import { Worker, isMainThread, parentPort } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';   // потолок в 60% ядер и низкий приоритет
const ЭТОТ = url.fileURLToPath(import.meta.url);
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));
const КОРЕНЬ2 = new URL('..', import.meta.url).pathname;
const ПЛЕМЕНА = ['Tyrano', 'Ka-noo-se', 'Romack', 'Masai', 'Moospell', 'Koomba', 'RaDumBa', 'Koaka'];

if (!isMainThread) {
  const { движок, прогнать, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const { параПодальше } = await import('./ai_места.mjs');
  const Комдив = await import('../reimpl/js/ai/комдив.js');
  const fs2 = await import('node:fs'); const path2 = await import('node:path');
  // Кэш весов ПО ИМЕНИ ФАЙЛА. Сначала кэш был одной переменной на поток — и второй проверяемый
  // файл молча получал веса первого: два разных чемпиона дали в отчёте одинаковые 61:38 до
  // последней цифры. Совпадение числа в число — верный признак, что замер меряет одно и то же.
  const кэшВесов = new Map();
  const новыеВеса = (ф) => { if (!кэшВесов.has(ф)) кэшВесов.set(ф, Комдив.изЗаписи(JSON.parse(fs2.readFileSync(path2.join(КОРЕНЬ2, ф), 'utf8')))); return кэшВесов.get(ф); };
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  parentPort.on('message', async (з) => {
    if (з === 'стоп') return process.exit(0);
    const итоги = [];
    for (const t of з.задачи) итоги.push(await (async () => {
      try {
        const eng = движок(); const m = eng.m;
        loadMission(m, eng.files, t.карта, t.племя, 1);
        // Две стороны и как можно дальше друг от друга (просьба владельца): на восьмиместных
        // картах соседние места сводят партию к «кто первым добежал», а не к стратегии.
        const точки = стартовыеПозиции(m); const цвета = параПодальше(точки);
        const A = цвета[t.местоA], B = цвета[t.местоB];
        if (A === undefined || B === undefined) return { ...t, исход: 'нет' };
        расставить(eng, [{ цвет: A, племя: t.племя, кто: 'компьютер' }, { цвет: B, племя: t.племя, кто: 'компьютер' }], {});
        const порог = +String(t.что).split(':')[1] || null;
        // Проверка обученной сети: «комдив:файл» ставит стороне A веса комдива, сторона B —
        // обычный скрипт. Это и есть тот самый суд движком, без которого веса в игру не идут.
        const комдивФайл = String(t.что).startsWith('комдив:') ? String(t.что).slice('комдив:'.length) : null;
        const вид = комдивФайл ? 'комдив' : String(t.что).split(':')[0];
        // «пусто» — контрольный прогон: обеим сторонам одно и то же. Если он даёт перекос,
        // виноват стенд или сама игра, а не правка, и остальным числам верить нельзя.
        const нас = (вкл) => вид === 'пусто' ? { носильщикИзБойцов: false, копитьНаДом: false, мясоБойцами: false }
                          : вид === 'носильщик' ? { носильщикИзБойцов: вкл, копитьНаДом: false, мясоБойцами: false }
                          : вид === 'копить'      ? { носильщикИзБойцов: false, копитьНаДом: вкл, копитьОт: порог, мясоБойцами: false }
                          : вид === 'рабочих'     ? { мясоБойцами: false }
                          // «мясобойцами»: мясо носят все, а не только простолюдины. Остальное
                          // хозяйство у обеих сторон одинаковое — меряем ровно эту правку.
                          : вид === 'мясобойцами' ? { носильщикИзБойцов: true, копитьНаДом: true, мясоБойцами: вкл, мясоСдавать: порог || undefined }
                          // «курьер»: мясо у охотников забирает один курьер и носит на склад сам.
                          : вид === 'курьер'      ? { носильщикИзБойцов: true, копитьНаДом: true, мясоБойцами: true, курьерМяса: вкл, курьерСдаёт: порог || undefined }
                          // «мясовсё»: вся новая добыча целиком (подбор бойцами + курьер) против
                          // прежнего порядка, когда мясо носили только простолюдины.
                          : вид === 'мясовсё'     ? { носильщикИзБойцов: true, копитьНаДом: true, мясоБойцами: вкл, курьерМяса: вкл }
                          // «курьерсам»: бойцы мясо не трогают вовсе, всё собирает и носит курьер.
                          : вид === 'курьерсам'   ? { носильщикИзБойцов: true, копитьНаДом: true, мясоБойцами: false, курьерМяса: вкл }
                          // «волна»: откат после неудавшейся волны и растущий порог следующей.
                          // Выключено — прежнее поведение: атака не прекращается, порог не растёт.
                          // «стратег»: новый скриптовый ИИ (состояния мясо/прокачка/оборона/волна,
                          // взаимовыручка, добивание) против нынешнего скрипта.
                          : вид === 'комдив'      ? {}
                          : вид === 'стратег'     ? { стратегПравило: вкл }
                          // «скопления»: память о том, где зверья много, против «иду туда, где
                          // видел последнего зверя».
                          : вид === 'скопления'   ? { скопления: вкл }
                          : вид === 'волна'       ? { гены: вкл ? (порог ? { волнаПотеря: порог } : undefined) : { волнаПотеря: 0, волнаРост: 0, волнаОстыть: 0 } }
                          // «остыть»: сколько шагов сидеть дома после неудавшейся волны (порог × 600 ≈ 33 с).
                          : вид === 'остыть'      ? { гены: вкл ? { волнаОстыть: (порог || 6) * 600 } : { волнаПотеря: 0, волнаРост: 0, волнаОстыть: 0 } }
                                                  : { носильщикИзБойцов: вкл, копитьНаДом: вкл, копитьОт: порог, мясоБойцами: false };
        // Веса комдива читаем один раз на поток и кладём стороне A.
        let комдив = null;
        if (комдивФайл) комдив = новыеВеса(комдивФайл);
        m.w8(0x32aec + A, 0); const сA = Скрипт.задать(eng, A, { уровень: 3, характер: 'костяк', комдив, ...нас(t.A) });
        m.w8(0x32aec + B, 0); const сB = Скрипт.задать(eng, B, { уровень: 3, характер: 'костяк', ...нас(t.B) });
        // Ручка «сколько рабочих»: порог ставим ВСЕГДА стороне A — она и есть «включённая»
        // (места меняются полем местоA, но сторона A всегда та, у которой правка).
        if (вид === 'рабочих' && сA) сA.рабочихНадо = порог;
        const r = прогнать(eng, Math.round(t.секунд * 1000 / ТИК_МС));
        const { G, U, UNITS } = await import('../reimpl/js/mem.js');
        const срез = (ц) => { let домов = 0, бойцов = 0;
          for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
            if (m.u8(UNITS + i + U.FLAGS5B) & 1 || m.u8(UNITS + i + U.OWNER) !== ц) continue;
            if (m.u8(UNITS + i + U.TYPE) >= 0x1a) домов++; else бойцов++; }
          return { домов, бойцов, еда: m.u32(G.food + ц * 4) }; };
        // Правка всегда у стороны A (местоA меняет только её стартовую точку), поэтому и снимаем
        // с A. Раньше здесь стояло `местоA === 0 ? A : B` — это мерило цвет 0 против цвета 1,
        // а не включённое против выключенного, и все средние по концу партии были враньём:
        // контрольный прогон с одинаковыми настройками у обеих сторон давал «4 бойца против 10».
        const вкл = срез(A), выкл = срез(B);
        return { ...t, исход: r.победитель === A ? 'A' : r.победитель === B ? 'B' : '-',
                 домовВкл: вкл.домов, бойцовВкл: вкл.бойцов, едаВкл: вкл.еда,
                 домовВыкл: выкл.домов, бойцовВыкл: выкл.бойцов, едаВыкл: выкл.еда };
      } catch (e) { return { ...t, исход: 'ошибка', ошибка: String(e.message).slice(0, 120) }; }
    })());
    parentPort.postMessage(итоги);
  });
}

if (isMainThread) {
  const карты = (арг.карты || '100,101,102,105,110,112').split(',').map(Number);
  const племена = (арг.племена || '0,1,2,3,4,5,6,7').split(',').map(Number);
  const секунд = +(арг.секунд || 900), потоков = Ядра.потоков(арг.потоков, 18);
  const что = (арг.что || 'носильщик,копить,обе').split(',');
  const задачи = [];
  for (const ч of что) for (const карта of карты) for (const племя of племена) for (const [a, b] of [[0, 1], [1, 0]])
    задачи.push({ что: ч, A: true, B: false, карта, племя, местоA: a, местоB: b, секунд });
  const потоки = Array.from({ length: потоков }, () => new Worker(ЭТОТ));
  const куски = Array.from({ length: потоков }, (_, k) => задачи.filter((_, i) => i % потоков === k));
  const занять = (w, п) => new Promise((ок) => { w.once('message', ок); w.postMessage(п); });
  const t0 = Date.now();
  const итоги = (await Promise.all(потоки.map((w, k) => занять(w, { задачи: куски[k] })))).flat();
  for (const w of потоки) w.postMessage('стоп');
  console.log(`партий ${итоги.length}, ${((Date.now() - t0) / 1000).toFixed(0)} с`);
  for (const ч of что) {
    const в = итоги.filter(и => и.что === ч && и.исход !== 'ошибка' && и.исход !== 'нет');
    const a = в.filter(и => и.исход === 'A').length, b = в.filter(и => и.исход === 'B').length;
    const ср = (поле) => (в.reduce((s2, и) => s2 + (и[поле] || 0), 0) / Math.max(1, в.length)).toFixed(1);
    console.log(`\n${ч}: включено — выключено  ${a} : ${b}  ничьих ${в.length - a - b}`);
    console.log(`  к концу: домов ${ср('домовВкл')} против ${ср('домовВыкл')}, бойцов ${ср('бойцовВкл')} против ${ср('бойцовВыкл')}, еда ${ср('едаВкл')} против ${ср('едаВыкл')}`);
    // Очки. С дальними стартами три четверти партий кончаются ничьёй, и одними победами мерить
    // уже нечего: ±7 побед на 320 партий — это шум. Поэтому к победам добавляем перевес по тому,
    // что осталось к концу: армия и дома. Победа по-прежнему решает (вес 1), перевес только
    // разводит ничьи.
    const очки = в.reduce((s2, и) => {
      if (и.исход === 'A') return s2 + 1;
      if (и.исход === 'B') return s2;
      const б = (и.бойцовВкл - и.бойцовВыкл) / Math.max(1, и.бойцовВкл + и.бойцовВыкл);
      const д = (и.домовВкл - и.домовВыкл) / Math.max(1, и.домовВкл + и.домовВыкл);
      return s2 + 0.5 + 0.3 * б + 0.2 * д;
    }, 0) / Math.max(1, в.length);
    console.log(`  очки (победа 1, ничья по перевесу): ${очки.toFixed(3)} — ровно 0.5 значит «никакой разницы»`);
    console.log('  по племенам:');
    for (const п of племена) {
      const свои = в.filter(и => и.племя === п);
      const ка = свои.filter(и => и.исход === 'A').length, кб = свои.filter(и => и.исход === 'B').length;
      console.log(`    ${ПЛЕМЕНА[п].padEnd(10)} ${String(ка).padStart(3)} : ${String(кб).padEnd(3)} ничьих ${свои.length - ка - кб}`);
    }
  }
  const ош = итоги.filter(и => и.исход === 'ошибка'); if (ош.length) console.log('\nошибок:', ош.length, ош[0].ошибка);
  process.exit(0);
}
