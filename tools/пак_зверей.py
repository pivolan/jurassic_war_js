#!/usr/bin/env python3
"""Пак кадров новых зверей для порта: reimpl/data/beasts.bin.

  python3 tools/пак_зверей.py брахио=out/новые_звери/брахио_видео/кадры [демон=...]

Кадры — PNG в палитре игры (индекс 0 — прозрачно), имена как у out/новые_звери/нарезка.py:
стойка_{д}_0, ход_{д}_{0..3}, удар_{д}_{0..2}, смерть_{0|4}_{0|1} (д: 0 север … 4 юг).

Куда кладём. Блок зверя в паке 04 — 40 кадров от базы стойки (movement-spec §7): 0..4 стойка,
5 + д·4 + фаза ходьба, 25 + д·3 + фаза удар. Смерть, фаза A — 4 кадра от базы 0x36f10[тип]:
+0/+1 для направлений 1, 2, 7, 8 («север»), +2/+3 для 3..6 («юг»). Фаза B (лежит) у всех общая.

Точка привязки (4 × i16 записи слота): у каждого нашего кадра — как у кадра тираннозавра с тем же
номером в блоке, со сдвигом так, чтобы совпали центры. Для зеркального блиттера (направления
6–8) у всех кадров игры выполняется x2 = 32 − w − x0, y2 = y0 — так и считаем.

Формат: 'JWNZ', u16 число записей; запись — u16 слот, u16 w, u16 h, 4 × i16 привязка, w·h байт.
"""
import sys, struct, os
# папка tools/ стоит первой в путях, а в ней свой dis.py — он ломает импорт numpy (inspect → dis)
_тут = os.path.dirname(os.path.abspath(__file__)); sys.path = [п for п in sys.path if os.path.abspath(п or '.') != _тут]
import numpy as np
from PIL import Image
ТЕНЬ = os.environ.get('SHADOW', '1') == '1'
ЦЕНТР_Y = 18                            # центр лежащего тела (смерть) по вертикали относительно клетки
НОГИ_Y = int(os.environ.get('FEET_Y', '24'))   # где в клетке 32×32 стоят ноги демона (рамка выделения — вся клетка)
ТЕНЬ_DX = int(os.environ.get('SHADOW_DX', '3')); ТЕНЬ_DY = int(os.environ.get('SHADOW_DY', '4'))
ТЕНЬ_СВЕРХУ = int(os.environ.get('SHADOW_TOP', '14'))
НАКЛОН = float(os.environ.get('SHADOW_LEAN', '0.5')); СПЛЮЩ = float(os.environ.get('SHADOW_FLAT', '0.35'))
sys.path.append(os.path.join(os.path.dirname(__file__)))
import trc

ЗВЕРИ = {'брахио': {'база': 1925, 'смерть': 2353}, 'демон': {'база': 2045, 'смерть': 2365}}
РЕКС = {'база': 1885, 'смерть': 2349}

КОРЕНЬ = os.path.join(os.path.dirname(__file__), '..')
_, es = trc.load(os.path.join(КОРЕНЬ, 'PWAR/_PWAR04.TRS'))

def тень(а, направление):
    """Тень как у зверей игры (3D-рендер со светом сверху-справа): проекция силуэта на землю, цветом 1.
    Вид сбоку (СВ, В, ЮВ, смерть): точка на высоте h над линией ног ложится на землю в
    (x − h·НАКЛОН, ноги − h·СПЛЮЩ) + сдвиг — шея и хвост отбрасывают тень вниз-влево, прижатую к ногам.
    Вид с севера/юга (сверху): силуэт просто уходит вниз на ТЕНЬ_DY (так у тираннозавра). Тело рисуется поверх."""
    тело = а > 0; H, W = а.shape
    ys, xs = np.where(тело)
    # Как у тираннозавра: виды сверху — сдвиг вниз; диагонали — сдвиг влево-вниз (верх картинки там —
    # глубина, а не высота, проекция уводила тень хвоста далеко влево); лежащий труп — чуть-чуть;
    # проекция на землю — только для вида сбоку (восток), где верх картинки и есть высота.
    сдвиги = {0: (0, ТЕНЬ_СВЕРХУ), 4: (0, ТЕНЬ_СВЕРХУ), 1: (-8, 12), 3: (-8, 12), 5: (-4, 5), 'вниз': (0, 5)}
    if направление in сдвиги:
        dx, dy = сдвиги[направление]
        пары = [(x + dx, y + dy) for y, x in zip(ys, xs)]
    else:
        ноги = ys.max()
        выс = ноги - ys
        пары = list(zip(np.round(xs - выс * НАКЛОН - ТЕНЬ_DX).astype(int), np.round(ноги - выс * СПЛЮЩ + ТЕНЬ_DY).astype(int)))
    tx = np.array([p[0] for p in пары]); ty = np.array([p[1] for p in пары])
    лев = min(0, tx.min()); верх = min(0, ty.min())
    cw = max(W, tx.max() + 1) - лев; ch = max(H, ty.max() + 1) - верх
    холст = np.zeros((ch, cw), np.uint8)
    холст[ty - верх, tx - лев] = 1
    # дырки проекции (точки ложатся с шагом) заливаем закрытием
    from scipy import ndimage
    м = ndimage.binary_closing(холст == 1, iterations=2); холст[м] = 1
    кусок = холст[-верх:-верх + H, -лев:-лев + W]; кусок[тело] = а[тело]
    return Image.fromarray(холст, 'P'), cw, ch, -лев

def записи(имя, кат):
    global ЯКОРЯ
    import json
    ЯКОРЯ = json.load(open(os.path.join(кат, 'якоря.json'))) if os.path.exists(os.path.join(кат, 'якоря.json')) else {}
    з = ЗВЕРИ[имя]; сп = []
    def добавить(файл, смещ, база, база_рекс, направление):
        путь = os.path.join(кат, файл + '.png')
        if not os.path.exists(путь): print('нет', путь); return
        im = Image.open(путь)
        assert im.mode == 'P', путь
        w, h = im.size
        р = es[база_рекс + смещ]; rx0, ry0 = р['x'][0], р['x'][1]
        x0 = round(rx0 + р['w'] / 2 - w / 2); y0 = round(ry0 + р['h'] / 2 - h / 2)
        # ЯКОРЯ (якоря.json рядом с кадрами): точка земли под тазом в каждом кадре. Тогда все кадры направления
        # ставим так, чтобы эта точка была там же, где у стойки (стойка — по центру кадра тираннозавра, как раньше).
        # Без этого кадры центровались по своей рамке: вынесенная вперёд лапа сдвигала рамку, и тело уезжало назад.
        # Точку земли ставим туда же, где ноги у людей: по центру клетки 32×32 и на 42 px ниже её верха (воин:
        # x0 4, y0 −2, 24×46 — ноги у y≈44). По кадру тираннозавра нельзя: он крупный, и демон уезжал из рамки
        # выделения вправо-вниз (владелец, снимок 04.10). Кадры смерти без якоря — центр тела в центр клетки.
        я = ЯКОРЯ.get(файл)
        # Владелец (снимки 04.10): у людей и тираннозавра тело стоит в рамке выделения ПО ЦЕНТРУ. Поэтому стойку
        # каждого направления ставим центром кадра в центр клетки (16, ЦЕНТР_Y), а остальные кадры направления —
        # так, чтобы точка земли под тазом совпала со стойкой (иначе тело дёргается вслед за рамкой кадра).
        if ЯКОРЯ:
            if я is not None and not файл.startswith('смерть'):
                д_ = файл.split('_')[1]; ст = f'стойка_{д_}_0'
                wс, hс = Image.open(os.path.join(кат, ст + '.png')).size
                # по горизонтали — центр кадра в центр клетки; по вертикали — точка земли под тазом на НОГИ_Y,
                # чтобы копыта стояли внутри рамки, как у всех юнитов (владелец, 04.10)
                # по горизонтали центрируем ТЕЛО (точка под тазом в x=16), а не кадр: кадр с тенью шире влево
                xs = 16 - ЯКОРЯ[ст][0]; ys = НОГИ_Y - ЯКОРЯ[ст][1]
                x0 = round(xs + ЯКОРЯ[ст][0] - я[0]); y0 = round(ys + ЯКОРЯ[ст][1] - я[1])
            elif файл.startswith('смерть'):
                x0 = round(16 - w / 2); y0 = round(ЦЕНТР_Y - h / 2)
        # ТЕНЬ, как у зверей игры: силуэт самого кадра, сдвинутый влево-вниз (свет сверху справа), цветом 1 —
        # блиттер затемняет под ним землю (0x2c1df). Замер по тираннозавру: ~10 px влево, 10–20 вниз.
        if ТЕНЬ:
            # Наши 3D-кадры: тень прямо вниз под ноги во всех направлениях. Зеркальные направления (6–8) игра
            # рисует отражённым кадром ВМЕСТЕ с тенью — тень со сдвигом влево там уходила вправо (снимок владельца).
            # Наши 3D-кадры несут тень сами (индекс 1, настоящая проекция от копыт) — свою не добавляем.
            if not (np.array(im) == 1).any():
                im, w, h, сдвиг_x = тень(np.array(im), 'вниз' if ЯКОРЯ else направление)
                x0 -= сдвиг_x
        пикс = im.tobytes()
        сп.append((база + смещ, w, h, (x0, y0, 32 - w - x0, y0), пикс))
    for д in range(5):
        добавить(f'стойка_{д}_0', д, з['база'], РЕКС['база'], д)
        for ф in range(4): добавить(f'ход_{д}_{ф}', 5 + д * 4 + ф, з['база'], РЕКС['база'], д)
        for ф in range(3): добавить(f'удар_{д}_{ф}', 25 + д * 3 + ф, з['база'], РЕКС['база'], д)
    for д, смещ in ((0, 0), (4, 2)):
        for c in range(2): добавить(f'смерть_{д}_{c}', смещ + c, з['смерть'], РЕКС['смерть'], 5)
    return сп

if __name__ == '__main__':
    все = []
    for арг in sys.argv[1:]:
        имя, кат = арг.split('=', 1); все += записи(имя, кат)
    выход = os.path.join(КОРЕНЬ, 'reimpl/data/beasts.bin')
    with open(выход, 'wb') as f:
        f.write(b'JWNZ' + struct.pack('<H', len(все)))
        for слот, w, h, xs, пикс in все:
            f.write(struct.pack('<HHH4h', слот, w, h, *xs)); f.write(пикс)
    print('записей', len(все), 'байт', os.path.getsize(выход), '→', выход)
