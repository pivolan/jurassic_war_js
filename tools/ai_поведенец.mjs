// Отбор переключателя поведений (js/ai/поведенец.js): сеть решает, каким СКРИПТОВЫМ характером
// играть дальше, а сами партии считаются чистым скриптом — без нижних сетей.
//
//   node tools/ai_поведенец.mjs [--минут=30] [--популяция=16] [--карты=…] [--племена=…]
//                               [--секунд=900] [--старт=веса.json] [--имя=пов1]
//
// Зачем так (замысел владельца): «есть скриптовое поведение — пусть стратег управляет
// скриптовыми вариантами на прогонах, а не другими нейронками уровнем ниже, так эмуляции
// проходят намного быстрее». Здесь ровно это: действий восемь (характеры), каждое уже написано
// и проверено, и сеть учит не поведение, а момент переключения.
//
// Как считается пригодность. Каждая особь играет одни и те же партии против ФИКСИРОВАННОГО
// соперника — того же скрипта с характером племени по умолчанию (js/net/игра.js). Оба места
// пробуются по очереди, чтобы стартовая точка не решала. Пригодность = (победы + 0.5×ничьи)/партии.
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
import { Worker, isMainThread, parentPort } from 'node:worker_threads';
import * as Ядра from './ai_ядра.mjs';   // потолок в 60% ядер и низкий приоритет
const ЭТОТ = url.fileURLToPath(import.meta.url);
const КОРЕНЬ = path.join(path.dirname(ЭТОТ), '..');
const арг = Object.fromEntries(process.argv.slice(2).filter(a => a.startsWith('--')).map(a => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), '1'] : [a.slice(2, i), a.slice(i + 1)]; }));
// Характер соперника по племени — тот же, что стоит в лобби у обычного компьютера.
const ХАРАКТЕР_ПЛЕМЕНИ = ['охотник', 'агрессор', 'агрессор', 'ровный', 'ровный', 'охотник', 'агрессор', 'охотник'];

if (!isMainThread) {
  const { движок, прогнать, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const { параПодальше } = await import('./ai_места.mjs');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  const Поведенец = await import('../reimpl/js/ai/поведенец.js');
  parentPort.on('message', async (з) => {
    if (з === 'стоп') return process.exit(0);
    const итоги = [];
    for (const t of з.задачи) итоги.push(await (async () => {
      try {
        const eng = движок(); const m = eng.m;
        loadMission(m, eng.files, t.карта, t.племя, 1);
        // Две стороны и как можно дальше друг от друга (просьба владельца): на восьмиместных
        // картах соседние места сводят партию к «кто первым добежал», а не к стратегии.
        const точки = стартовыеПозиции(m); const цвета = параПодальше(точки);
        const A = цвета[t.местоA], B = цвета[t.местоB];
        if (A === undefined || B === undefined) return { ...t, исход: 'нет' };
        расставить(eng, [{ цвет: A, племя: t.племя, кто: 'компьютер' }, { цвет: B, племя: t.племя, кто: 'компьютер' }], {});
        const сам = ХАРАКТЕР_ПЛЕМЕНИ[t.племя & 7] || 'ровный';
        m.w8(0x32aec + A, 0); Скрипт.задать(eng, A, { уровень: 3, характер: сам, поведенец: Поведенец.изЗаписи(з.веса) });
        m.w8(0x32aec + B, 0); Скрипт.задать(eng, B, { уровень: 3, характер: сам });
        const r = прогнать(eng, Math.round(t.секунд * 1000 / ТИК_МС));
        return { ...t, исход: r.победитель === A ? 'A' : r.победитель === B ? 'B' : '-' };
      } catch (e) { return { ...t, исход: 'ошибка', ошибка: String(e.message).slice(0, 120) }; }
    })());
    parentPort.postMessage(итоги);
  });
}

if (isMainThread) {
  const Поведенец = await import('../reimpl/js/ai/поведенец.js');
  const карты = (арг.карты || '100,101,102,105,110,113').split(',').map(Number);
  const племена = (арг.племена || '0,3,5,7').split(',').map(Number);
  const секунд = +(арг.секунд || 900), потоков = Ядра.потоков(арг.потоков, 16);
  const МИНУТ = +(арг.минут || 30), ПОП = +(арг.популяция || 16), имя = арг.имя || 'пов1';
  const все = [];
  for (const карта of карты) for (const племя of племена) for (const [a, b] of [[0, 1], [1, 0]])
    все.push({ карта, племя, местоA: a, местоB: b, секунд });
  // Сколько партий на одну оценку. Мало партий — разброс больше шага улучшения, и восхождение
  // лезет по шуму: первый отбор так и вышел (на своих картах 0.66, на отложенных 0.50 против
  // 0.55 без сети вовсе). Поэтому по умолчанию берём ВСЕ задачи, а --подвыборка=N оставляет N
  // штук, но тогда набор МЕНЯЕТСЯ каждое поколение, и чемпион переигрывается на том же наборе,
  // что и кандидаты, — иначе сравнение нечестное.
  const подвыборка = +(арг.подвыборка || 0);
  let задачи = все;
  const набор = (поколение) => {
    if (!подвыборка || подвыборка >= все.length) return все;
    const п = [...все];
    let с2 = (поколение * 2654435761) >>> 0;                          // свой генератор: набор воспроизводим
    for (let i = п.length - 1; i > 0; i--) { с2 = (с2 * 1103515245 + 12345) & 0x7fffffff; const j = с2 % (i + 1); [п[i], п[j]] = [п[j], п[i]]; }
    return п.slice(0, подвыборка);
  };

  const потоки = Array.from({ length: потоков }, () => new Worker(ЭТОТ));
  const занять = (w, п) => new Promise((ок) => { w.once('message', ок); w.postMessage(п); });
  /** Прогнать одну особь по всем задачам. */
  const оценить = async (веса) => {
    const куски = Array.from({ length: потоков }, (_, k) => задачи.filter((_, i) => i % потоков === k));
    const итоги = (await Promise.all(потоки.map((w, k) => занять(w, { веса, задачи: куски[k] })))).flat();
    const в = итоги.filter(и => и.исход !== 'ошибка' && и.исход !== 'нет');
    const побед = в.filter(и => и.исход === 'A').length, ничьих = в.filter(и => и.исход === '-').length;
    return { F: в.length ? (побед + ничьих * 0.5) / в.length : 0, побед, ничьих, партий: в.length,
             ошибка: итоги.find(и => и.исход === 'ошибка')?.ошибка };
  };

  // Проверка готовых весов на отложенных картах: обучению верить нельзя, пока не сыграно там,
  // чего сеть не видела.
  if (арг.проверка) {
    const веса = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, арг.проверка), 'utf8'));
    const оц = await оценить(веса);
    console.log(`проверка ${арг.проверка}: F=${оц.F.toFixed(4)} (побед ${оц.побед}/${оц.партий}, ничьих ${оц.ничьих})`);
    const пусто = { w1: new Float32Array(Поведенец.СКРЫТЫХ * Поведенец.ВХОД), b1: new Float32Array(Поведенец.СКРЫТЫХ),
                    w2: new Float32Array(Поведенец.ВЫХОД * Поведенец.СКРЫТЫХ), b2: new Float32Array(Поведенец.ВЫХОД) };
    const б = await оценить(Поведенец.вЗапись(пусто));
    console.log(`для сравнения, без переключателя: F=${б.F.toFixed(4)} (побед ${б.побед}/${б.партий}, ничьих ${б.ничьих})`);
    for (const w of потоки) w.postMessage('стоп');
    process.exit(0);
  }

  // Старт: либо продолжаем с готовых весов, либо с нулевых. Нулевые — это «всегда первое
  // поведение» (ровный), то есть заведомо осмысленная точка, а не шум.
  let лучшие = арг.старт ? Поведенец.изЗаписи(JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, арг.старт), 'utf8')))
                         : { w1: new Float32Array(Поведенец.СКРЫТЫХ * Поведенец.ВХОД), b1: new Float32Array(Поведенец.СКРЫТЫХ),
                             w2: new Float32Array(Поведенец.ВЫХОД * Поведенец.СКРЫТЫХ), b2: new Float32Array(Поведенец.ВЫХОД) };
  const копия = (с) => ({ w1: Float32Array.from(с.w1), b1: Float32Array.from(с.b1), w2: Float32Array.from(с.w2), b2: Float32Array.from(с.b2) });
  let сид = 1;
  const сл = () => { сид = (сид * 1103515245 + 12345) & 0x7fffffff; return сид / 0x80000000 * 2 - 1; };
  /** Гауссов шум через сумму равномерных — нам хватает, зато воспроизводимо. */
  const шум = () => (сл() + сл() + сл()) / 1.5;
  const мутировать = (с, σ) => { const н = копия(с);
    for (const ключ of ['w1', 'b1', 'w2', 'b2']) for (let i = 0; i < н[ключ].length; i++) н[ключ][i] += шум() * σ;
    return н; };

  console.log(`отбор переключателя поведений «${имя}»: популяция ${ПОП}, задач на особь ${задачи.length} (карты ${карты.join(',')}, племена ${племена.join(',')}, по ${секунд} с), потоков ${потоков}`);
  console.log(`соперник: тот же скрипт с характером племени; действия сети: ${Поведенец.ПОВЕДЕНИЯ.join(', ')}`);
  const t0 = Date.now();
  let база = await оценить(Поведенец.вЗапись(лучшие));
  if (база.ошибка) console.log('ошибка в прогоне:', база.ошибка);
  console.log(`поколение 0: старт F=${база.F.toFixed(4)} (побед ${база.побед}/${база.партий}, ничьих ${база.ничьих})`);
  let σ = 0.3;
  for (let п = 1; (Date.now() - t0) / 60000 < МИНУТ; п++) {
    задачи = набор(п);                                                 // набор поколения — общий для всех
    // Чемпиона переигрываем на этом же наборе: иначе он остаётся с удачным числом со старого
    // набора и его уже не обогнать ничем, кроме такой же удачи.
    const чемп = await оценить(Поведенец.вЗапись(лучшие));
    let лучшийШаг = null;
    for (let k = 0; k < ПОП; k++) {
      const кандидат = мутировать(лучшие, σ);
      const оц = await оценить(Поведенец.вЗапись(кандидат));
      if (!лучшийШаг || оц.F > лучшийШаг.оц.F) лучшийШаг = { кандидат, оц };
      if ((Date.now() - t0) / 60000 >= МИНУТ) break;
    }
    if (лучшийШаг && лучшийШаг.оц.F > чемп.F) { лучшие = лучшийШаг.кандидат; база = лучшийШаг.оц; σ = Math.max(0.05, σ * 0.9); }
    else { база = чемп; σ = Math.min(0.6, σ * 1.1); }                  // не растём — шагаем шире
    console.log(`поколение ${п}: лучший F=${база.F.toFixed(4)} (побед ${база.побед}/${база.партий}, ничьих ${база.ничьих})  σ=${σ.toFixed(3)}  ${((Date.now() - t0) / 60000).toFixed(1)} мин`);
    fs.mkdirSync(path.join(КОРЕНЬ, 'out/ai/weights'), { recursive: true });
    fs.writeFileSync(path.join(КОРЕНЬ, `out/ai/weights/поведенец-${имя}.json`), JSON.stringify(Поведенец.вЗапись(лучшие)));
  }
  for (const w of потоки) w.postMessage('стоп');
  console.log(`готово: out/ai/weights/поведенец-${имя}.json, F=${база.F.toFixed(4)}`);
  process.exit(0);
}
