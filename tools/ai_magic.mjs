// Доходят ли маги до своих заклинаний (наше). Магия открывается по «магической силе» MAG
// (0x1f475): Elf 30/50/70/90/110, Wizard 30/45/65/90, Warlock 30/50/90/100, Ranger 30/50/70.
// Маг рождается с MAG 30, то есть с первым заклинанием; дальше MAG растёт только с опытом.
//
//   node tools/ai_magic.mjs [карты через запятую] [секунд] [уровень] [характер]
import { партия, прогнать, ТИК_МС } from './ai_duel.mjs';
import { G, U, UNITS } from '../reimpl/js/mem.js';
import { стартовыеПозиции } from '../reimpl/js/port/skirmish.js';

const КАРТЫ = (process.argv[2] || '100,101,102').split(',').map(Number);
const СЕК = +(process.argv[3] || 2700), УР = +(process.argv[4] || 3), ХАР = process.argv[5] || 'ровный';
// класс → [имя, [пороги MAG], биты SKILLS]
const КЛАССЫ = {
  5: ['Elf',     [30, 50, 70, 90, 110], [8, 9, 10, 11, 12]],
  6: ['Wizard',  [30, 45, 65, 90],      [14, 15, 16, 17]],
  7: ['Warlock', [30, 50, 90, 100],     [19, 20, 21, 22]],
  8: ['Ranger',  [30, 50, 70],          [24, 25, 26]],
};
const ПЛЕМЯ_МАГА = { 5: 1, 6: 4, 7: 4, 8: 2 };      // кем играть, чтобы этот класс вообще был

const лучшее = {};
for (const карта of КАРТЫ) {
  for (const племя of [1, 2, 4]) {                   // Ka-noo-se (эльфы), Romack (рейнджеры), Moospell (маги)
    const пробный = партия(карта, [{ цвет: 0, племя: 0 }, { цвет: 3, племя: 0 }]);
    const цвета = Object.keys(стартовыеПозиции(пробный.m)).map(Number).sort((a, b) => a - b);
    const места = [{ цвет: цвета[0], племя, кто: 'компьютер', ии: 'скрипт', уровень: УР, характер: ХАР },
                   { цвет: цвета[1], племя, кто: 'компьютер', ии: 'скрипт', уровень: УР, характер: ХАР }];
    const eng = партия(карта, места); const m = eng.m;
    // Следим за максимумом по ходу партии: маг может дорасти и погибнуть.
    const смотреть = () => {
      for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
        if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
        const t = m.u8(UNITS + i + U.TYPE); const к = КЛАССЫ[t]; if (!к) continue;
        const mag = m.u8(UNITS + i + U.MAG), sk = m.u32(UNITS + i + U.SKILLS);
        const открыто = к[2].filter(б => (sk >>> б) & 1).length;
        const з = лучшее[t] ??= { mag: 0, открыто: 0, карта: 0 };
        if (mag > з.mag) { з.mag = mag; з.карта = карта; }
        if (открыто > з.открыто) з.открыто = открыто;
      }
    };
    прогнать(eng, Math.round(СЕК * 1000 / ТИК_МС), { наШаге: (e, k) => { if ((k & 0xff) === 0) смотреть(); } });
    смотреть();
  }
  console.log(`карта ${карта} отыграна`);
}
console.log('\nкласс     всего заклинаний  лучший MAG  открыто  пороги');
for (const t of [5, 6, 7, 8]) {
  const [имя, пороги] = КЛАССЫ[t]; const з = лучшее[t] || { mag: 0, открыто: 0 };
  console.log(`${имя.padEnd(9)} ${String(пороги.length).padStart(9)}  ${String(з.mag).padStart(11)}  ${String(з.открыто).padStart(7)}  ${пороги.join('/')}`);
}

// ---------------------------------------------------------------- сколько опыта стоит заклинание
// Растим мага настоящей функцией движка (0x1ec47) и смотрим, на каком суммарном опыте
// открывается каждое заклинание. Это и есть ответ на вопрос «а дойдёт ли он вообще».
import { call } from '../reimpl/js/fn.js';
{
  const eng = партия(КАРТЫ[0], [{ цвет: 0, племя: 1, кто: 'компьютер' }, { цвет: 3, племя: 1, кто: 'компьютер' }]);
  const m = eng.m;
  const леопард = (s => (s * s) >>> 2)(60 + 0 + 60 + 50 + 100);           // Leopard 60/0/60/50/100
  console.log('\nсколько опыта нужно магу на каждое заклинание (растим движком, порциями по леопарду):');
  for (const тип of [5, 6, 7, 8]) {
    let маг = 0;
    for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT))
      if (!(m.u8(UNITS + i + U.FLAGS5B) & 1) && m.u8(UNITS + i + U.TYPE) === 1) { маг = i; break; }
    if (!маг) break;
    const st = m.u32(0x30a9e + тип * 4);
    m.w8(UNITS + маг + U.TYPE, тип);
    m.w8(UNITS + маг + U.HPMAX, m.u8(st + 0x37654)); m.w8(UNITS + маг + U.MAG, m.u8(st + 0x37656));
    m.w8(UNITS + маг + U.ATK, m.u8(st + 0x37657)); m.w8(UNITS + маг + U.DEF, m.u8(st + 0x37658));
    m.w8(UNITS + маг + U.SPD, m.u8(st + 0x37659)); m.w32(UNITS + маг + U.XP, 0);
    m.w8(UNITS + маг + U.STAT0B, 0x0b);        // маска роста мага: HP + ATK + MAG (у простолюдина её нет)
    const [имя, пороги] = КЛАССЫ[тип];
    const где = []; let дано = 0;
    for (let k = 0; k < 400 && где.length < пороги.length; k++) {
      m.w32(UNITS + маг + U.XP, m.u32(UNITS + маг + U.XP) + леопард); дано += леопард;
      call(eng, 0x1ec47, { esi: маг });
      while (где.length < пороги.length && m.u8(UNITS + маг + U.MAG) >= пороги[где.length]) где.push({ n: где.length + 1, xp: дано, зверей: Math.round(дано / леопард) });
    }
    console.log(`  ${имя.padEnd(8)} ${где.map(з => `${з.n}-е: ${з.зверей} леопардов`).join(', ')}${где.length < пороги.length ? `, дальше ${пороги.length - где.length} не добрали за 400` : ''}`);
  }
}
