// Оглавление весов для браузера: out/ai/weights/index.json.
//
//   node tools/ai_оглавление.mjs
//
// Раньше его писал побочным делом tools/ai_evolve_head.mjs, и слой в записи не указывался вовсе —
// игра угадывала его по полю «скрытых», то есть все веса, кроме тактика, считались бойцовскими.
// Комдива (сеть групп) в оглавлении не было совсем, поэтому выбрать его ни в лобби, ни на стенде
// было нельзя: файл лежит, а браузер про него не знает.
//
// Слой определяем по самой записи: комдив подписан полем «вид», тактик узнаётся по «скрытых»,
// поведенец — по «повадки», остальное — сеть бойца.
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const КОРЕНЬ = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const папка = path.join(КОРЕНЬ, 'out/ai/weights');

// Какие веса рабочие. Остальные 38 файлов — это след обучения: заготовки-клоны bc*, цепочка
// ppo1…ppo12b (интересен только её конец), переносы в новую форму входа, тупиковая ветка es-head,
// пятнадцатиминутные пробы и чемпионы вырожденного отбора в модели. Удалять их незачем — по ним
// видно, что откуда выросло, — но в списках игры им делать нечего: владелец попросил спрятать.
// Рабочие берём из самой игры (js/ai/нейросети.js, ЛУЧШИЕ), чтобы список не разъезжался с ней.
const { ЛУЧШИЕ } = await import('../reimpl/js/ai/нейросети.js');
const РАБОЧИЕ = new Set([...Object.values(ЛУЧШИЕ), 'поведенец-пов2.json']);

/** Какой слой описывают эти веса. */
function слой(j) {
  if (j.вид) return String(j.вид);
  if ('повадки' in j) return 'поведенец';
  if ('скрытых' in j) return 'тактик';
  return 'боец';
}

const список = fs.readdirSync(папка).filter(f => f.endsWith('.json') && f !== 'index.json').sort().map(f => {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(папка, f), 'utf8'));
    return { файл: f, имя: j.имя || f.slice(0, -5), слой: слой(j), основной: РАБОЧИЕ.has(f),
             описание: j.описание || '', дата: j.дата || '', вектор: j.вектор ?? null, действий: j.действий ?? null };
  } catch { return null; }
}).filter(Boolean);
fs.writeFileSync(path.join(папка, 'index.json'), JSON.stringify(список, null, 1), 'utf8');
const по = {};
for (const з of список) по[з.слой] = (по[з.слой] || 0) + 1;
console.log(`оглавление: ${список.length} файлов —`, Object.entries(по).map(([к, v]) => `${к} ${v}`).join(', '));
console.log(`рабочих: ${список.filter(з => з.основной).map(з => з.имя).join(', ') || '—'}`);
for (const ф of РАБОЧИЕ) if (!список.some(з => з.файл === ф)) console.log(`ВНИМАНИЕ: рабочих весов нет на месте — ${ф}`);
