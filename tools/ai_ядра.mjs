// Сколько ядер можно занять замерами и обучением — и как не мешать остальным.
//
// Просьба владельца: «ограничь нагрузку, не более 60% от всех ядер, чтобы остальные процессы
// колом не вставали». Стенды гоняют партии в worker_threads, и сколько потоков попросили —
// столько ядер и съедается; на 20-ядерной машине 18 потоков это практически вся машина.
//
// Правило владельца (уточнено 14.09.2026): «каждое ядро можно использовать на 100%, но два ядра
// всегда оставляй свободными — чтобы не надо было троттлить внутри ядра». То есть бюджет мы
// режем по ЧИСЛУ ядер, а не по доле мощности каждого:
//   • ЯДЕР_НАМ = все ядра минус одно (владелец, 14.09.2026: «одно ядро только оставь свободным»).
//     На двадцатиядерной машине это девятнадцать;
//   • nice остаётся, но он не троттлинг: пока свободные ядра есть, мы работаем в полную силу, а
//     если владелец что-то запустит, планировщик отдаст ему время сразу же.
//
// Переопределить (имена латиницей: переменную с кириллицей из bash не задать):
//   JW_FREE=4        — оставлять свободными не одно ядро, а четыре
//   JW_THREADS=4     — жёстко столько потоков
//   JW_NICE=0        — не понижать приоритет
// Если нужна совсем жёсткая гарантия (не «столько потоков», а «только эти ядра»), запускать
// через taskset: taskset -c 0-11 node tools/ai_хозяйство.mjs …
import os from 'node:os';

export const ЯДЕР = os.cpus().length || 1;
/** Сколько ядер оставляем машине: по умолчанию одно. */
export const СВОБОДНЫХ = Math.max(0, +(process.env.JW_FREE ?? 1) | 0);
/** Сколько ядер наши. */
export const ЯДЕР_НАМ = Math.max(1, ЯДЕР - СВОБОДНЫХ);
/**
 * Потолок рабочих потоков — на один меньше, чем ядер нам позволено: главный поток тоже работает
 * (раздаёт задания, считает пригодность), плюс служебные потоки V8. Без этого вычета замер
 * занимал на треть больше машины, чем обещал.
 */
export const ПОТОЛОК = Math.max(1, ЯДЕР_НАМ - 1);

/**
 * Сколько потоков брать: что попросили (или сколько по умолчанию), но не выше потолка.
 * Печатает предупреждение, когда обрезает, — иначе непонятно, почему замер идёт дольше.
 */
export function потоков(запрошено, поУмолчанию = ПОТОЛОК) {
  if (process.env.JW_THREADS) return Math.max(1, +process.env.JW_THREADS | 0);
  const хочет = Math.max(1, (+запрошено || +поУмолчанию || ПОТОЛОК) | 0);
  if (хочет > ПОТОЛОК) {
    console.log(`потоков ${хочет} → ${ПОТОЛОК} (не больше ${ЯДЕР_НАМ} из ${ЯДЕР} ядер: ${СВОБОДНЫХ} оставляем машине; JW_FREE/JW_THREADS переопределяют)`);
    return ПОТОЛОК;
  }
  return хочет;
}

/** Уйти в низкий приоритет, чтобы не мешать ничему интерактивному. */
export function неМешать(уровень = +(process.env.JW_NICE ?? 10)) {
  if (!уровень) return;
  try { os.setPriority(0, уровень); } catch { /* без прав на nice — не беда, потолок ядер всё равно стоит */ }
}

// Понижаем приоритет сразу при импорте: модуль подключают ровно те инструменты, которые грузят
// машину надолго, и забыть вызов было бы легко.
неМешать();
