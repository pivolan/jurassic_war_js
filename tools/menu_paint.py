#!/usr/bin/env python3
"""Затереть старую надпись на кнопке и напечатать новую, готовую от движка (наше).

  python3 tools/menu_paint.py <кнопка.png> <надпись.json> <готово.png> [--обводка]

Надпись приходит из tools/menu_label.mjs: список точек с индексами палитры игры. Старый текст
затирается медианой соседних пикселей самой кнопки, поэтому под новой надписью не остаётся
призрака старой, а текстура, кольцо и прозрачность кнопки не меняются вовсе.
"""
import sys, os, json
_свои = os.path.dirname(os.path.abspath(__file__))
sys.path = [p for p in sys.path if os.path.abspath(p or '.') != _свои] + [_свои]
import numpy as np
from PIL import Image, ImageFilter

кнопка, слой, готово = sys.argv[1:4]
обводка_нужна = '--обводка' in sys.argv[4:]     # по умолчанию буквы без тёмной рамки
о = Image.open(кнопка).convert('RGBA'); ш, в = о.size
О = np.asarray(о.convert('RGB'), int)
д = json.load(open(слой))
пал = д['палитра']

# Старую надпись ищем шире, чем «чистый жёлтый»: у букв есть тёмная обводка и сглаженные края,
# и если их не захватить, по кнопке остаются крапины от прежнего текста (так и вышло в первый раз).
# Две маски, и путать их нельзя. Строгая — сами буквы, по ней берутся цвета надписи. Широкая
# (строгая, расширенная на два пикселя) — что стирать: у букв есть сглаженные края, без них на
# кнопке остаются крапины. Раньше цвета брались по широкой, в неё попадала тёмная текстура, и
# новая надпись красилась тёмным — её было не видно.
строго = (О[:, :, 0] > 150) & (О[:, :, 1] > 120) & (О[:, :, 2] < 120) & (О[:, :, 0] > О[:, :, 2] + 80)
широко = (О[:, :, 0] > 120) & (О[:, :, 1] > 80) & (О[:, :, 2] < 120) & (О[:, :, 0] > О[:, :, 2] + 60)
жёлтый = np.asarray(Image.fromarray((широко * 255).astype('uint8')).filter(ImageFilter.MaxFilter(5))) > 0
чисто = О.copy()
ys, xs = np.where(жёлтый)
for y, x in zip(ys, xs):
    for r in (3, 5, 8, 12):
        y0, y1, x0, x1 = max(0, y - r), min(в, y + r + 1), max(0, x - r), min(ш, x + r + 1)
        окно, маска = О[y0:y1, x0:x1], ~жёлтый[y0:y1, x0:x1]
        if маска.sum() >= 6:
            чисто[y, x] = np.median(окно[маска], axis=0); break

# Буквы. Оригинальная надпись напечатана тем же шрифтом, и её «выпуклость» — это не размытие,
# а четыре уровня яркости самого шрифта: тело буквы (252,252,0), затем (224,204,28), (192,180,0),
# (140,104,8) по краям. Поэтому правильнее не размывать маску, а разложить уровни по тем же
# оттенкам, какие уже есть в надписи на кнопке. Способ выбирается ключом:
#   уровни   — как в оригинале: уровень шрифта → свой оттенок (по умолчанию);
#   обводка  — то же плюс тёмный контур на пиксель (глубже рельеф);
#   размытие — сглаживание по покрытию (мягко, но «мылит» мелкий шрифт);
#   жир      — уровни, но маска расширена на пиксель;
#   фаска    — ручной рельеф: светлая кромка сверху-слева, тёмная снизу-справа.
масштаб = float(next((a.split('=')[1] for a in sys.argv[4:] if a.startswith('--масштаб=')), 1.2))
способ = next((a.split('=')[1] for a in sys.argv[4:] if a.startswith('--способ=')), 'уровни')

база = д.get('рампа', 0)
карта = np.zeros((в, ш), np.uint8)                      # уровень шрифта в каждой точке, 1..4
for x, y, индекс in д['буквы']:
    if 0 <= x < ш and 0 <= y < в: карта[y, x] = min(4, max(1, индекс - база + 1))
ys, xs = np.where(карта > 0)
if len(ys):
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    кусок = Image.fromarray(карта[y0:y1, x0:x1])
    нов = (max(1, int(round(кусок.width * масштаб))), max(1, int(round(кусок.height * масштаб))))
    предел = int(ш * 0.72)
    if нов[0] > предел: нов = (предел, max(1, int(кусок.height * предел / кусок.width)))
    кусок = кусок.resize(нов, Image.NEAREST)
    поле = np.zeros((в, ш), np.uint8)
    сдx, сдy = (ш - кусок.width) // 2, (в - кусок.height) // 2
    поле[сдy:сдy + кусок.height, сдx:сдx + кусок.width] = np.asarray(кусок)

    # Оттенки берём из самой надписи кнопки: сколько разных, столько ступеней рельефа.
    from collections import Counter
    сч = Counter(map(tuple, О[строго]))
    по_частоте = [np.array(c, float) for c, _ in сч.most_common(6)]
    тело = по_частоте[0] if по_частоте else np.array([252.0, 252.0, 0.0])
    края = по_частоте[1:] or [тело * 0.75]
    ступени = [тело] + [края[min(k, len(края) - 1)] for k in range(3)]
    тёмный = min(по_частоте, key=lambda c: c.sum()) if по_частоте else тело * 0.5

    есть = поле > 0
    if способ == 'жир':
        расш = np.asarray(Image.fromarray((есть * 255).astype('uint8')).filter(ImageFilter.MaxFilter(3))) > 0
        поле[расш & ~есть] = 2; есть = поле > 0
    if способ == 'размытие':
        покрытие = np.asarray(Image.fromarray((есть * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(0.6)), float) / 255.0
        покрытие = np.clip(покрытие * 1.3, 0, 1)
        чисто = чисто * (1 - покрытие[:, :, None]) + тело[None, None, :] * покрытие[:, :, None]
    else:
        for уровень in (1, 2, 3, 4):
            где = поле == уровень
            if где.any(): чисто[где] = ступени[уровень - 1]
        if способ == 'обводка':
            контур = np.asarray(Image.fromarray((есть * 255).astype('uint8')).filter(ImageFilter.MaxFilter(3))) > 0
            чисто[контур & ~есть] = тёмный
        if способ == 'фаска':
            сдвиг = np.zeros_like(есть)
            сдвиг[1:, 1:] = есть[:-1, :-1]                   # тень снизу-справа
            чисто[сдвиг & ~есть] = тёмный
            блик = np.zeros_like(есть)
            блик[:-1, :-1] = есть[1:, 1:]                    # светлая кромка сверху-слева
            чисто[блик & ~есть] = ступени[1]
# Возвращаем в палитру самой кнопки: смешивание породило промежуточные цвета, а спрайт обязан
# остаться в своих 30-40 индексах.
свои = np.unique(О.reshape(-1, 3), axis=0)
пал = Image.new('P', (1, 1))
плоско = [int(v) for c in свои for v in c][:768]
пал.putpalette(плоско + [0] * (768 - len(плоско)))
итог = Image.fromarray(np.clip(чисто, 0, 255).astype('uint8')).quantize(palette=пал, dither=Image.NONE).convert('RGBA')
итог.putalpha(о.getchannel('A'))
итог.save(готово)
изм = (np.asarray(итог.convert('RGB'), int) != О).any(2).sum()
print(f'{готово}: изменено {изм} пикселей из {ш * в} ({100 * изм / (ш * в):.1f} %)')
