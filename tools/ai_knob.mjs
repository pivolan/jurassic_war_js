// Что на самом деле делает уровень сложности сильнее (наше). Уровень — это несколько ручек сразу
// (частота размышлений штаба, длина памяти, набор приёмов), и по итогу партии не видно, какая из
// них помогла, а какая помешала. Здесь крутим ровно одну ручку, всё прочее одинаковое.
//
//   node tools/ai_knob.mjs такт|память [карты через запятую] [секунд] [процессов]
import { fork } from 'node:child_process';
import path from 'node:path'; import url from 'node:url';
const ЭТОТ = url.fileURLToPath(import.meta.url);
const ТАКТЫ = [[96, 48], [48, 24], [24, 16], [16, 8]];      // как в лестнице уровней
const ПАМЯТИ = [0, 600, 3600, 1e9];
const ПОРОГИ = [3, 5, 7, 10];                               // при скольких бойцах штаб идёт в атаку
const РАБОЧИЕ = [1, 2, 3, 4];

async function рабочий() {
  const { движок, прогнать, ТИК_МС } = await import('./ai_duel.mjs');
  const { loadMission } = await import('../reimpl/js/loader.js');
  const { расставить, стартовыеПозиции } = await import('../reimpl/js/port/skirmish.js');
  const Скрипт = await import('../reimpl/js/port/ai_script.js');
  process.on('message', (з) => {
    if (з === 'стоп') return process.exit(0);
    const eng = движок(); const m = eng.m;
    loadMission(m, eng.files, з.карта, з.племя, 1);
    const точки = стартовыеПозиции(m); const цвета = Object.keys(точки).map(Number).sort((a, b) => a - b);
    const места = [{ цвет: цвета[0], племя: з.племя, кто: 'компьютер' }, { цвет: цвета[1], племя: з.племя, кто: 'компьютер' }];
    расставить(eng, места, {});
    for (const [k, мес] of места.entries()) {
      m.w8(0x32aec + мес.цвет, 0);
      const с = Скрипт.задать(eng, мес.цвет, { уровень: 1 });
      с.приёмы = new Set();                                  // приёмы выключены у обоих
      const v = k === 0 ? з.A : з.B;
      с.тактШтаба = 48; с.тактОтрядов = 24; с.память = 600;
      if (з.что === 'такт') { с.тактШтаба = ТАКТЫ[v][0]; с.тактОтрядов = ТАКТЫ[v][1]; }
      else if (з.что === 'память') с.память = ПАМЯТИ[v];
      else if (з.что === 'порог') с.порогАтаки = ПОРОГИ[v];
      else if (з.что === 'рабочие') с.рабочихНадо = РАБОЧИЕ[v];
    }
    const r = прогнать(eng, Math.round(з.сек * 1000 / ТИК_МС));
    const итог = r.победитель === места[0].цвет ? 'A' : r.победитель === места[1].цвет ? 'B' : '-';
    process.send({ ...з, итог });
  });
  process.send('готов');
}

async function главный() {
  const ЧТО = process.argv[3] || 'такт';
  const КАРТЫ = (process.argv[4] || '100,101,102,200,202,206').split(',').map(Number);
  const СЕК = +(process.argv[5] || 1800), ПРОЦЕССОВ = +(process.argv[6] || 12);
  const НАБОР = { такт: ТАКТЫ, память: ПАМЯТИ, порог: ПОРОГИ, рабочие: РАБОЧИЕ }[ЧТО];
  const N = НАБОР.length;
  const задачи = [];
  for (let a = 0; a < N; a++) for (let b = 0; b < N; b++) { if (a === b) continue;
    for (const карта of КАРТЫ) for (let племя = 0; племя < 8; племя++)
      задачи.push({ что: ЧТО, карта, сек: СЕК, племя, A: a, B: b }); }
  console.log(`ручка «${ЧТО}», карты ${КАРТЫ.join(',')}, партий ${задачи.length}`);
  const итоги = []; let выдано = 0, готово = 0;
  await new Promise((всё) => {
    for (let k = 0; k < ПРОЦЕССОВ; k++) {
      const п = fork(ЭТОТ, ['рабочий'], { cwd: path.dirname(ЭТОТ) });
      п.on('message', (м) => {
        if (м !== 'готов') { итоги.push(м); готово++; if (готово % 200 === 0) process.stdout.write(`  ${готово}/${задачи.length}\n`); }
        if (выдано < задачи.length) п.send(задачи[выдано++]); else { п.send('стоп'); if (готово >= задачи.length) всё(); }
      });
    }
  });
  const ничьих = итоги.filter(и => и.итог === '-').length;
  console.log(`\nсыграно ${итоги.length}, ничьих ${ничьих} (${Math.round(ничьих * 100 / итоги.length)}%)`);
  for (let v = 0; v < N; v++) {
    const свои = итоги.filter(и => и.A === v || и.B === v);
    const побед = свои.filter(и => (и.A === v && и.итог === 'A') || (и.B === v && и.итог === 'B')).length;
    const имя = ЧТО === 'такт' ? `штаб раз в ${ТАКТЫ[v][0]}, отряды раз в ${ТАКТЫ[v][1]}`
              : ЧТО === 'память' ? `память ${ПАМЯТИ[v] > 1e8 ? 'вечная' : ПАМЯТИ[v]}`
              : ЧТО === 'порог' ? `в атаку от ${ПОРОГИ[v]} бойцов` : `рабочих ${РАБОЧИЕ[v]}`;
    console.log(`  ${имя.padEnd(34)} побед ${String(побед).padStart(4)} из ${свои.length}  (${Math.round(побед * 100 / свои.length)}%)`);
  }
}
if (process.argv[2] === 'рабочий') рабочий(); else главный();
