// ПЕРЕБОР РУЧЕК ИИ на одной миссии — без картинок, параллельно, случайным поиском.
//
//   node tools/м2_перебор.mjs [комбинаций=120] [зёрен=3] [потоков=12] [секунд=1800]
//
// Каждая комбинация — набор значений СУЩЕСТВУЮЩИХ ручек ВОЖАКА и ПРОРАБА (новой логики не
// добавляем: задача владельца — «при минимальных изменениях добиться прохождения, не ломая
// текущее поведение»). Каждая гоняется на нескольких зёрнах случайности движка через
// tools/м2_опыт.mjs. Счёт: победа ≫ дома из задания ≫ казна ≫ выживание.
// Результаты дописываются в out/перебор/м2.jsonl, лучшие печатаются в конце.
import { spawn } from 'node:child_process';
import fs from 'node:fs';

const КОМБИНАЦИЙ = +(process.argv[2] ?? 120), ЗЁРЕН = +(process.argv[3] ?? 3);
const ПОТОКОВ = +(process.argv[4] ?? 12), СЕКУНД = +(process.argv[5] ?? 1800);
const ПЛЕМЯ = +(process.env.JW_ПЕРЕБОР_ПЛЕМЯ ?? 0), МИССИЯ = +(process.env.JW_ПЕРЕБОР_МИССИЯ ?? 2);

const ПРОСТРАНСТВО = {
  JW_ОБР_УДАРОВ: [3, 4, 5, 6, 8],
  JW_ОБР_ЗА_СПИНЫ: [0, 1],
  JW_ОБР_ЗАПАС_АТАКИ: [1.0, 1.2, 1.5, 2.0],
  JW_ОБР_ДИСТАНЦИЯ: [0, 1],
  JW_ОБР_ДИСТ_УБИЙЦЫ: [0, 1, 2, 3, 4],
  JW_ОБР_ВМЕСТЕ: [0, 1],
  JW_ОБР_АГРОВ: [2, 3, 4],
  JW_ОБР_ГУЩА: [2, 3, 4, 99],
  JW_ОБР_СОБРАВШИСЬ: [0, 1],
  JW_ОБР_ДЕРЖАТЬ: [0, 54],
  JW_ОБР_ПОЗАДИ: [2, 3, 5],
  JW_ОБР_ИЗ_ЗОН: [0, 1],
  JW_СТР_ПО_ПОЛЬЗЕ: [0, 1],
  JW_СТР_ХВАТИТ: [4, 6, 8],
};
const случ = (сп) => сп[Math.floor(Math.random() * сп.length)];
const набор = () => Object.fromEntries(Object.entries(ПРОСТРАНСТВО).map(([к, в]) => [к, случ(в)]));

// Нулевая комбинация — текущие умолчания: с ней сравниваем всё остальное.
const комбинации = [{}];
for (let н = 1; н < КОМБИНАЦИЙ; н++) комбинации.push(набор());

function прогон(ручки, зерно) {
  return new Promise((ok) => {
    const env = { ...process.env };
    for (const [к, в] of Object.entries(ручки)) env[к] = String(в);
    const п = spawn('nice', ['-n', '10', 'node', 'tools/м2_опыт.mjs', String(ПЛЕМЯ), String(МИССИЯ), String(СЕКУНД), String(зерно)], { env });
    let вывод = '';
    п.stdout.on('data', (к) => вывод += к);
    п.on('close', () => { try { ok(JSON.parse(вывод.trim().split('\n').pop())); } catch { ok(null); } });
  });
}

// Счёт одной партии: победа — 100, дом из задания — 10 (не больше трёх каждого вида),
// казна — по единице на тысячу, выживание — доля живых к концу.
function счёт(р) {
  if (!р) return -1;
  const д = р.вехи || {};
  const сколько = (вид) => Object.keys(д).filter(к => к.startsWith(вид + '#')).length;
  return (р.итог === 'ПОБЕДА' ? 100 + (1800 - р.секИтога) / 60 : 0)
       + 10 * (Math.min(3, сколько(1)) + Math.min(3, сколько(9)))
       + р.максКазна / 1000 + (р.живых > 0 ? 2 : 0);
}

fs.mkdirSync('out/перебор', { recursive: true });
const журнал = fs.createWriteStream(`out/перебор/м${МИССИЯ}-племя${ПЛЕМЯ}.jsonl`, { flags: 'a' });
const задачи = [];
комбинации.forEach((р, н) => { for (let з = 0; з < ЗЁРЕН; з++) задачи.push({ н, р, з }); });
const итоги = комбинации.map(() => []);
let сделано = 0;
async function работник() {
  while (задачи.length) {
    const { н, р, з } = задачи.shift();
    const res = await прогон(р, з);
    итоги[н].push({ з, res, счёт: счёт(res) });
    журнал.write(JSON.stringify({ н, ручки: р, зерно: з, счёт: счёт(res), res }) + '\n');
    if (++сделано % 30 === 0) process.stderr.write(`  ${сделано}/${комбинации.length * ЗЁРЕН}\n`);
  }
}
await Promise.all(Array.from({ length: ПОТОКОВ }, работник));
журнал.end();

const сводка = комбинации.map((р, н) => {
  const с = итоги[н]; const ср = с.reduce((a, x) => a + x.счёт, 0) / с.length;
  return { н, ср: +ср.toFixed(2), побед: с.filter(x => x.res?.итог === 'ПОБЕДА').length, ручки: р,
           казна: Math.round(с.reduce((a, x) => a + (x.res?.максКазна || 0), 0) / с.length),
           вехи: с.map(x => Object.keys(x.res?.вехи || {}).filter(к => /^(1|9)#/.test(к)).length) };
}).sort((a, b) => b.ср - a.ср);
console.log('умолчания:', JSON.stringify(сводка.find(с => с.н === 0)));
for (const с of сводка.slice(0, 8)) console.log(JSON.stringify(с));
