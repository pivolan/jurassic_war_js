// Замер ЭТАЛОНА: за сколько четвёрка валит первую гиену, действуя строго по сценарию владельца
// (js/ai/образец.js). Печатает игровое время до убийства, потери и то же самое по второй жертве —
// чтобы было с чем сравнивать обученную сеть.
//
//   node tools/образец_прогон.mjs [секунд=30] [ударовНаОтход=3]
import { движок, ТИК_МС } from './ai_duel.mjs';
const { loadMission } = await import('../reimpl/js/loader.js');
const { G, U, UNITS } = await import('../reimpl/js/mem.js');
const Обр = await import('../reimpl/js/ai/образец.js');
const СЕКУНД = +(process.argv[2] || 30);
const УДАРОВ = +(process.argv[3] || 3);
const КУСОК = [1, 12, 32, 43];

const eng = движок(); const m = eng.m;
loadMission(m, eng.files, 0, 0, 2);
const мой = m.u8(G.humanOwner); m.w8(0x32aec + мой, 0);
const [x0, y0, x1, y1] = КУСОК; const наши = [], звери = [];
for (let i = m.u32(G.unitHead); i; i = m.u32(UNITS + i + U.NEXT)) {
  if (m.u8(UNITS + i + U.FLAGS5B) & 1) continue;
  const x = m.u16(UNITS + i + U.X) >> 5, y = m.u16(UNITS + i + U.Y) >> 5, т = m.u8(UNITS + i + U.TYPE);
  const внутри = x >= x0 && x <= x1 && y >= y0 && y <= y1;
  if (m.u8(UNITS + i + U.OWNER) === мой && т < 0x1a) { if (внутри) наши.push(i); continue; }
  if (!(т >= 14 && т <= 23)) continue;
  if (внутри) звери.push(i);
  else { m.w8(UNITS + i + U.FLAGS5B, m.u8(UNITS + i + U.FLAGS5B) | 1); m.w16(UNITS + i + U.ANIM, 0xffff); }
}
const с = Обр.новое(); с.ударовНаОтход = УДАРОВ;
const предел = Math.round(СЕКУНД * 1000 / ТИК_МС);
const убиты = [];
let перваяЦель = 0, отходов = 0, пикАгра = 0, тиковОтрыва = 0, тиковСна = 0, пикАгра2 = 0, тиковНаТигре = 0; const смерти = [];
const t0 = process.hrtime.bigint();
// Образец детерминирован, и на одной сцене у него ровно одна траектория — сравнивать настройки
// по одному прогону нельзя. Разнообразие даём задержкой старта: несколько тиков зверьё живёт
// само по себе, и дальше расстановка уже другая. JW_ОБР_ЗАДЕРЖКА=тиков.
const ЗАДЕРЖКА = +(process.env.JW_ОБР_ЗАДЕРЖКА || 0);
for (let тик = 0; тик < предел; тик++) {
  const r = тик < ЗАДЕРЖКА ? {} : Обр.шаг(eng, наши, с);
  if (!перваяЦель && r.цель) перваяЦель = r.цель;
  отходов += r.отходят;
  if (r.отрыв) тиковОтрыва++;
  if (r.спят) тиковСна++;
  if (r.агров > пикАгра2) пикАгра2 = r.агров;
  // Сколько времени целью был тигр (тип 21) — он не по зубам четвёрке, и лезть на него нельзя.
  if (r.цель && m.u8(UNITS + r.цель + U.TYPE) === 21) тиковНаТигре++;
  eng.timer++; eng.tick();
  const мертво = звери.filter(з => !Обр.жив(m, з)).length;
  while (убиты.length < мертво) убиты.push(тик * ТИК_МС / 1000);
  const своиМертвы = наши.filter(i => !Обр.жив(m, i)).length;
  while (смерти.length < своиМертвы) смерти.push(тик * ТИК_МС / 1000);
  // Сколько зверья вообще вцепилось в нашу четвёрку прямо сейчас — по этому видно, когда
  // сценарий «бей одного» перестаёт работать: к нам сбегаются соседи.
  let вцепились = 0;
  for (const з of звери) if (Обр.жив(m, з) && наши.includes(m.u32(UNITS + з + U.TARGET))) вцепились++;
  if (вцепились > пикАгра) пикАгра = вцепились;
  if (своиМертвы > 1) break;
}
const потери = наши.filter(i => !Обр.жив(m, i)).length;
const счёт = Number(process.hrtime.bigint() - t0) / 1e6;
console.log(JSON.stringify({
  перваяЦель, типПервой: перваяЦель ? m.u8(UNITS + перваяЦель + U.TYPE) : null,
  перваяУбитаНаСек: убиты[0] ?? null, втораяНаСек: убиты[1] ?? null, третьяНаСек: убиты[2] ?? null,
  убитоВсего: убиты.length, потери, смертиНаСек: смерти, максЗверейНаНас: пикАгра,
  секундОтрыва: +(тиковОтрыва * ТИК_МС / 1000).toFixed(1), секундСна: +(тиковСна * ТИК_МС / 1000).toFixed(1),
  секундНаТигре: +(тиковНаТигре * ТИК_МС / 1000).toFixed(1),
  здоровьеВКонце: наши.map(i => Обр.жив(m, i) ? m.u8(UNITS + i + U.HP) + '/' + m.u8(UNITS + i + U.HPMAX) : 'труп').join(' '),
  ношаВКонце: наши.map(i => Обр.жив(m, i) ? m.u16(UNITS + i + U.FOOD) : 0).reduce((a, b) => a + b, 0),
  отходовСделано: отходов, выходыИзОтрыва: с.выходы || {},
  ударовНаОтход: УДАРОВ, счётМс: +счёт.toFixed(1),
}));
