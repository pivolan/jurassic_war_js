#!/usr/bin/env python3
"""Обучение сети ОТРЯДА (наше): одна сеть ведёт всех четверых сразу.

    python3 tools/ai_отряд_учить.py [--старт веса.json] [--имя отряд1] [--итераций 400]
                                    [--эпизодов 1500] [--потоков-прогона 18]

Цикл тот же, что у tools/ai_ppo.py: node гоняет сцену текущими весами → PPO правит веса → повтор.
Отличие одно, зато принципиальное: в записи ОДНО наблюдение и ЧЕТЫРЕ действия (по голове на
бойца). Поэтому логарифм вероятности хода — это СУММА по четырём головам, и энтропия тоже:
сеть выбирает не «действие», а расстановку сразу всем, и учится ей целиком.

Замысел владельца: «нейронка должна на выходе отдавать команду для четырёх этих юнитов… не четыре
отдельных, а одна, но которая сразу всем управляет».
"""
import sys, os
# Каталог инструментов убираем из НАЧАЛА пути и ставим в конец: рядом лежит свой tools/dis.py
# (дизассемблер образа), а стандартной библиотеке нужен её собственный `dis` — torch тянет его
# через inspect. Тот же приём, что и в tools/ai_ppo.py.
_tools = os.path.dirname(os.path.abspath(__file__))
sys.path = [p for p in sys.path if os.path.abspath(p or '.') != _tools] + [_tools]
import json, time, argparse, datetime, subprocess
import numpy as np
import torch, torch.nn.functional as F
import ai_net

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def прочитать(папка):
    """Собрать части прогона в один набор."""
    мета = json.load(open(os.path.join(папка, 'meta.json')))
    П = мета['слоёв'] * мета['окно'] ** 2
    части = sorted({f.split('.')[0] for f in os.listdir(папка) if f.startswith('part-')})
    куски = {'окна': [], 'векторы': [], 'действия': [], 'награда': [], 'конец': [], 'итог': [], 'эпизод': [], 'logp': [], 'ценность': []}
    for ч in части:
        чит = lambda имя, тип: np.fromfile(os.path.join(папка, f'{ч}.{имя}'), dtype=тип)
        куски['окна'].append(чит('окна.u8', np.uint8).reshape(-1, П))
        куски['векторы'].append(чит('векторы.f32', np.float32).reshape(-1, мета['вектор']))
        куски['действия'].append(чит('действия.u8', np.uint8).reshape(-1, мета['мест']))
        for имя, тип in [('награда', np.float32), ('конец', np.uint8), ('итог', np.float32), ('эпизод', np.uint32), ('logp', np.float32), ('ценность', np.float32)]:
            расш = {'награда': 'награда.f32', 'конец': 'конец.u8', 'итог': 'итог.f32', 'эпизод': 'эпизод.u32', 'logp': 'logp.f32', 'ценность': 'ценность.f32'}[имя]
            куски[имя].append(чит(расш, тип))
    д = {k: np.concatenate(v) for k, v in куски.items() if v}
    д['мета'] = мета
    return д


def выгоды(д, γ, λ):
    """GAE по цепочкам: записи одного эпизода идут подряд, конец помечен единицей."""
    n = len(д['награда'])
    adv = np.zeros(n, dtype=np.float32)
    посл = 0.0
    for i in range(n - 1, -1, -1):
        конец = д['конец'][i] == 1
        следц = 0.0 if конец else д['ценность'][i + 1] if i + 1 < n and д['эпизод'][i + 1] == д['эпизод'][i] else 0.0
        δ = д['награда'][i] + γ * следц - д['ценность'][i]
        посл = δ + γ * λ * (0.0 if конец else посл)
        adv[i] = посл
    return adv


def главное(арг):
    раб = os.path.join(КОРЕНЬ, 'out/ai/data', 'отряд-' + арг.имя)
    os.makedirs(раб, exist_ok=True)
    текущие = os.path.join(раб, 'текущие.json')
    if арг.старт and os.path.exists(арг.старт):
        сеть = ai_net.отряд_загрузить(арг.старт)
    else:
        сеть = ai_net.Отряд()
    ai_net.отряд_сохранить(сеть, текущие, арг.имя, 'старт')
    # Живые прогоны — чтобы веса этой минуты были видны в стенде мозгов прямо в игре.
    живые_путь = os.path.join(КОРЕНЬ, 'out/ai/data', 'живые.json')
    try:
        живые = json.load(open(живые_путь)) if os.path.exists(живые_путь) else []
    except Exception:
        живые = []
    живые = [з for з in живые if з.get('имя') != арг.имя]
    живые.append({'имя': арг.имя, 'папка': 'отряд-' + арг.имя, 'вид': 'отряд',
                  'начат': datetime.datetime.now().isoformat(timespec='seconds'), 'прогон': арг.прогон})
    json.dump(живые, open(живые_путь, 'w'), ensure_ascii=False, indent=1)

    опт = torch.optim.Adam(сеть.parameters(), lr=арг.lr)
    лог = open(os.path.join(КОРЕНЬ, 'out/ai/logs', f'отряд-{арг.имя}.log'), 'a')
    t0 = time.time()
    лучший = (-1e9, 0); прошлая_подпись = None
    for ит in range(1, арг.итераций + 1):
        вывод = subprocess.run(['node', os.path.join(КОРЕНЬ, арг.прогон), текущие, раб,
                                str(арг.эпизодов), str(арг.потоков_прогона), str(арг.seed * 100 + ит), str(арг.температура)],
                               capture_output=True, text=True, cwd=КОРЕНЬ)
        if вывод.returncode != 0:
            print('прогон упал:', вывод.stderr[-2000:]); return
        сводка = json.loads(вывод.stdout.strip().splitlines()[-1])
        д = прочитать(раб)
        мета = д['мета']
        окна = torch.tensor(д['окна'], dtype=torch.float32).div_(255).view(-1, мета['слоёв'], мета['окно'], мета['окно'])
        векторы = torch.tensor(д['векторы'])
        действия = torch.tensor(д['действия'], dtype=torch.long)
        adv = torch.tensor(выгоды(д, арг.γ, арг.λ))
        цель_v = adv + torch.tensor(д['ценность'])
        adv = (adv - adv.mean()) / (adv.std() + 1e-6)
        стар_logp = torch.tensor(д['logp'])
        N = len(окна)
        клип_доля = kl = энтропия = 0.0; шагов = 0
        for _ in range(арг.эпох):
            порядок = torch.randperm(N)
            for н in range(0, N, арг.батч):
                б = порядок[н:н + арг.батч]
                логиты, v = сеть(окна[б], векторы[б])
                lp_все = F.log_softmax(логиты, dim=-1)                      # [B, мест, действий]
                lp = lp_все.gather(2, действия[б].unsqueeze(2)).squeeze(2).sum(1)   # сумма по головам
                энт = -(lp_все.exp() * lp_все).sum(-1).sum(-1).mean()
                отн = (lp - стар_logp[б]).exp()
                п1 = отн * adv[б]; п2 = torch.clamp(отн, 1 - арг.клип, 1 + арг.клип) * adv[б]
                потеря = -torch.min(п1, п2).mean() + арг.vf * F.mse_loss(v, цель_v[б]) - арг.энтропия * энт
                опт.zero_grad(); потеря.backward()
                torch.nn.utils.clip_grad_norm_(сеть.parameters(), 0.5); опт.step()
                with torch.no_grad():
                    клип_доля += ((отн - 1).abs() > арг.клип).float().mean().item()
                    kl += (стар_logp[б] - lp).mean().item(); энтропия += энт.item(); шагов += 1
        ai_net.отряд_сохранить(сеть, текущие, арг.имя, f'итерация {ит}')
        # СМЕНА ЗАДАЧИ ОБНУЛЯЕТ РЕКОРД. Сцена и плата правятся прямо во время прогона — так и идёт
        # работа: посмотрели на поведение, поправили награду. Итог после правки считается уже по
        # другой задаче и со старым рекордом несравним: когда окно попытки выросло с 25 до 60
        # секунд, итог просел с 0.069 до 0.048, побить прежний рекорд стало нечем, и файл «лучшие»
        # навсегда застрял на весах ДО правки — а страница игры по умолчанию берёт именно его.
        # Владелец заметил это сам: «кажется, там не последняя версия даётся по умолчанию».
        # Поэтому сверяем подпись задачи и при её смене начинаем отсчёт рекорда заново.
        мета_путь = os.path.join(раб, 'meta.json')
        try:
            м = json.load(open(мета_путь))
            # именно секундСцены: ключ «секунд» в сводке — это время прогона в реальных секундах,
            # он меняется каждую итерацию и подписью задачи быть не может.
            подпись = (м.get('секундСцены'), str(м.get('кусок')), арг.прогон)
        except Exception:
            подпись = None
        if подпись and прошлая_подпись and подпись != прошлая_подпись:
            строка_смены = f'задача изменилась: {прошлая_подпись} → {подпись}; рекорд обнулён'
            print(строка_смены, flush=True); лог.write(строка_смены + chr(10)); лог.flush()
            лучший = (-1e9, 0)
        if подпись: прошлая_подпись = подпись
        if сводка['итог'] > лучший[0]:
            лучший = (сводка['итог'], ит)
            ai_net.отряд_сохранить(сеть, os.path.join(раб, 'лучшие.json'), арг.имя, f'лучшие, итерация {ит}')
        строка = (f"ит {ит:3d}: итог {сводка['итог']:+.3f} без потерь {сводка['безПотерь']:.3f} "
                  f"зверей {сводка['зверейЗаБой']:.2f} потерь {сводка['своихПотеряно']:.2f} | "
                  f"kl {kl/max(1,шагов):.4f} клип {клип_доля/max(1,шагов):.2f} энтропия {энтропия/max(1,шагов):.2f} | "
                  f"записей {N}, прогон {сводка['секунд']:.0f} с, всего {(time.time()-t0)/60:.1f} мин")
        print(строка, flush=True); лог.write(строка + '\n'); лог.flush()
    print(f'лучшее {лучший[0]:+.3f} на итерации {лучший[1]}; веса → {раб}')


if __name__ == '__main__':
    п = argparse.ArgumentParser()
    п.add_argument('--старт', default=''); п.add_argument('--имя', default='отряд1')
    п.add_argument('--итераций', type=int, default=400); п.add_argument('--эпизодов', type=int, default=1500)
    п.add_argument('--lr', type=float, default=3e-4); п.add_argument('--γ', type=float, default=0.99); п.add_argument('--λ', type=float, default=0.95)
    п.add_argument('--клип', type=float, default=0.2); п.add_argument('--эпох', type=int, default=3); п.add_argument('--батч', type=int, default=1024)
    п.add_argument('--энтропия', type=float, default=0.02); п.add_argument('--vf', type=float, default=0.5)
    п.add_argument('--температура', type=float, default=1.0); п.add_argument('--seed', type=int, default=1)
    п.add_argument('--потоков-прогона', dest='потоков_прогона', type=int, default=18)
    п.add_argument('--прогон', default='tools/ai_отряд_прогон.mjs')
    главное(п.parse_args())
