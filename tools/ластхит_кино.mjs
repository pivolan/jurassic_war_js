// РОЛИК ЛАСТХИТА: один и тот же бой дважды, бок о бок — слева без назначения (добивает кто придётся),
// справа с назначенным слабейшим (★). Видно, кто бьёт (белая черта к зверю), кого ластхит остановил
// «стопом» (красная обводка), кто уступил место (синяя), кто добил и за сколько шагов.
//
//   node tools/ластхит_кино.mjs [--телеграм]
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const { бой, СОСТАВЫ, ИМЯ } = await import('./ластхит_бой.mjs');

const СЦЕНЫ = [
  ['открытая', 23, '3: сильный+2 слабых', 'открытое место, пёс: сильный (атака 90) и двое слабых (20)'],
  ['открытая', 22, '4: 3 сильных+слабый', 'открытое место, леопард: трое сильных и один слабый'],
  ['деревья', 21, '4 новичка', 'деревья вокруг, тигр: четверо одинаковых новичков'],
  ['угол', 23, '4: 3 сильных+слабый', 'тупик у стены, пёс: два свободных бока, слабому уступают место'],
  ['открытая', 19, '3: сильный+2 слабых', 'открытое место, мамонт: сильный и двое слабых'],
];
const К = 34, ПОЛЕ = 11 * К, ОТСТУП = 30, ШИР = ПОЛЕ * 2 + ОТСТУП * 3, ВЫС = ПОЛЕ + 150;
const ПАПКА = `out/ластхит/${new Date().toISOString().slice(5, 16).replace(/[-:T]/g, '')}`;
fs.mkdirSync(ПАПКА, { recursive: true });
const ЦВ = { фон: [24, 28, 24], земля: [52, 78, 46], стена: [18, 22, 18], наш: [90, 210, 90], назн: [255, 214, 60], зверь: [200, 60, 50],
             бел: [245, 245, 245], красн: [240, 60, 60], син: [80, 150, 255], серый: [110, 110, 110] };

function кадрРисовать(панели) {
  const b = Buffer.alloc(ШИР * ВЫС * 3);
  const px = (x, y, c) => { if (x < 0 || y < 0 || x >= ШИР || y >= ВЫС) return; const o = (y * ШИР + x) * 3; b[o] = c[0]; b[o + 1] = c[1]; b[o + 2] = c[2]; };
  const прям = (x0, y0, w, h, c) => { for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) px(x, y, c); };
  const круг = (cx, cy, r, c, толщ = 0) => { for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) { const d = Math.hypot(x, y); if (толщ ? (d <= r && d > r - толщ) : d <= r) px(Math.round(cx + x), Math.round(cy + y), c); } };
  const линия = (x0, y0, x1, y1, c) => { const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 1); for (let k = 0; k <= n; k++) { const x = Math.round(x0 + (x1 - x0) * k / n), y = Math.round(y0 + (y1 - y0) * k / n); px(x, y, c); px(x + 1, y, c); } };
  прям(0, 0, ШИР, ВЫС, ЦВ.фон);
  панели.forEach((п, n) => {
    const ox = ОТСТУП + n * (ПОЛЕ + ОТСТУП), oy = 70;
    прям(ox, oy, ПОЛЕ, ПОЛЕ, ЦВ.земля);
    for (const [x, y] of п.стены) if (x >= 0 && y >= 0 && x < 11 && y < 11) прям(ox + x * К + 1, oy + y * К + 1, К - 2, К - 2, ЦВ.стена);
    const к = п.кадр; if (!к) return;
    const зx = ox + (к.зверь.x + 0.5) * К, зy = oy + (к.зверь.y + 0.5) * К;
    const живой = к.зверь.hp > 0;
    прям(Math.round(зx - К * 0.42), Math.round(зy - К * 0.42), Math.round(К * 0.84), Math.round(К * 0.84), живой ? ЦВ.зверь : ЦВ.серый);
    // полоска жизней зверя
    прям(Math.round(зx - К / 2), Math.round(зy - К * 0.62), К, 4, ЦВ.стена);
    прям(Math.round(зx - К / 2), Math.round(зy - К * 0.62), Math.round(К * к.зверь.hp / Math.max(1, к.зверь.max)), 4, ЦВ.красн);
    к.наши.forEach((u, k) => {
      const x = ox + (u.x + 0.5) * К, y = oy + (u.y + 0.5) * К;
      if (u.ударил) линия(x, y, зx, зy, ЦВ.бел);
      круг(x, y, К * 0.33, k === п.назначен ? ЦВ.назн : ЦВ.наш);
      if (u.стоп) круг(x, y, К * 0.46, ЦВ.красн, 3);
      if (u.уступил) круг(x, y, К * 0.46, ЦВ.син, 3);
      if (u.добил) круг(x, y, К * 0.5, ЦВ.бел, 4);
    });
  });
  return b;
}

// ASS-подписи: по строке на панель и на шаг.
const ass = (с) => { const t = Math.max(0, с); const h = Math.floor(t / 3600), mm = Math.floor(t % 3600 / 60), ss = (t % 60).toFixed(2).padStart(5, '0'); return `${h}:${String(mm).padStart(2, '0')}:${ss}`; };
const события = [];
const КАДР_С = 0.1;   // шаг движка на экране — 0,1 с (игра идёт в ~0,55 скорости: медленнее, чтобы видеть удары)
let время = 0, номер = 0;
const путьКадров = `${ПАПКА}/сырьё.rgb`; const поток = fs.openSync(путьКадров, 'w');
for (const [вид, тип, состав, подпись] of СЦЕНЫ) {
  const сост = СОСТАВЫ[состав];
  const слабейший = сост.reduce((b, с, k) => (с.atk < сост[b].atk ? k : b), сост.length - 1);
  const зл = {}, зп = {};
  const рл = бой(вид, тип, сост, -1, 0, зл), рп = бой(вид, тип, сост, слабейший, 0, зп);
  const длина = Math.max(зл.кадры.length, зп.кадры.length) + 25;
  const т0 = время;
  for (let f = 0; f < длина; f++) {
    const пан = [{ стены: зл.стены, кадр: зл.кадры[Math.min(f, зл.кадры.length - 1)], назначен: -1 },
                 { стены: зп.стены, кадр: зп.кадры[Math.min(f, зп.кадры.length - 1)], назначен: слабейший }];
    fs.writeSync(поток, кадрРисовать(пан));
    время += КАДР_С; номер++;
  }
  const добилЛ = рл.кто >= 0 ? `добил №${рл.кто + 1}` : 'не убит', добилП = рп.кто >= 0 ? `добил №${рп.кто + 1}${рп.кто === слабейший ? ' ★' : ''}` : 'не убит';
  события.push({ с: т0, по: время, текст: подпись, x: ШИР / 2, y: 22, размер: 22 });
  события.push({ с: т0, по: время, текст: 'без назначения', x: ОТСТУП + ПОЛЕ / 2, y: 52, размер: 18 });
  события.push({ с: т0, по: время, текст: `последний удар — слабейшему (★ №${слабейший + 1})`, x: ОТСТУП * 2 + ПОЛЕ * 1.5, y: 52, размер: 18 });
  // счётчики по шагам
  for (let f = 0; f < длина; f++) {
    const кл = зл.кадры[Math.min(f, зл.кадры.length - 1)], кп = зп.кадры[Math.min(f, зп.кадры.length - 1)];
    const с = т0 + f * КАДР_С, по = с + КАДР_С;
    события.push({ с, по, текст: `шаг ${кл.t} · зверь ${кл.зверь.hp}/${кл.зверь.max}${f >= зл.кадры.length - 1 ? ` · убит на ${рл.шаг}, ${добилЛ}` : ''}`, x: ОТСТУП + ПОЛЕ / 2, y: 70 + ПОЛЕ + 26, размер: 17 });
    события.push({ с, по, текст: `шаг ${кп.t} · зверь ${кп.зверь.hp}/${кп.зверь.max}${f >= зп.кадры.length - 1 ? ` · убит на ${рп.шаг}, ${добилП}` : ''}`, x: ОТСТУП * 2 + ПОЛЕ * 1.5, y: 70 + ПОЛЕ + 26, размер: 17 });
  }
  события.push({ с: т0 + (зп.кадры.length - 1) * КАДР_С, по: время, текст: `разница: ${рп.шаг - рл.шаг} шагов (${((рп.шаг - рл.шаг) * 0.055).toFixed(2)} с)`, x: ШИР / 2, y: 70 + ПОЛЕ + 60, размер: 20 });
  console.log(`${подпись}: без — шаг ${рл.шаг} (${добилЛ}); с назначенным — шаг ${рп.шаг} (${добилП}); разница ${рп.шаг - рл.шаг}`);
}
fs.closeSync(поток);
события.push({ с: 0, по: время, текст: 'зелёные — наши · ★ жёлтый — назначенный · белая черта — удар · красная обводка — «стоп» ластхита · синяя — уступил место · белое кольцо — добил', x: ШИР / 2, y: ВЫС - 22, размер: 13 });
const стиль = `[Script Info]\nScriptType: v4.00+\nPlayResX: ${ШИР}\nPlayResY: ${ВЫС}\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, OutlineColour, BackColour, Bold, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV\nStyle: Default,Noto Sans,18,&H00FFFFFF,&H00000000,&H80000000,0,1,2,0,5,0,0,0\n\n[Events]\nFormat: Layer, Start, End, Style, Text\n`;
const строки = события.map(е => `Dialogue: 0,${ass(е.с)},${ass(е.по)},Default,{\\pos(${Math.round(е.x)},${Math.round(е.y)})\\fs${е.размер}}${е.текст}`);
fs.writeFileSync(`${ПАПКА}/подписи.ass`, стиль + строки.join('\n') + '\n');
const ролик = `${ПАПКА}/ластхит.mp4`;
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', `${ШИР}x${ВЫС}`, '-r', String(1 / КАДР_С), '-i', путьКадров,
  '-vf', `ass=${ПАПКА}/подписи.ass`, '-pix_fmt', 'yuv420p', '-c:v', 'libx264', '-crf', '24', ролик]);
fs.unlinkSync(путьКадров);
console.log(`ролик: ${ролик} (${номер} кадров, ${время.toFixed(0)} с)`);
if (process.argv.includes('--телеграм')) execFileSync('tools/tg.sh', ['video', ролик, 'Ластхит: слева бой без назначения, справа последний удар отдан слабейшему (★). Красная обводка — «стоп» ластхита, синяя — уступил место.'], { stdio: 'inherit' });
